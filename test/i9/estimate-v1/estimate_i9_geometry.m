function [C,curvelen,diagnostic] = estimate_i9_geometry(ntot,a,R,model)
%ESTIMATE_I9_GEOMETRY Analytic CCW radial trilobe in the global coordinate frame.
% Based on: I9.1 search_i9_geometry; no formula changes.
% Source formula: design-9-1a radial formula; layout matches geom.construct_cont.
% Output: C=[x;x';x'';y;y';y'']; derivatives are analytic, never differenced.
  t=(0:ntot-1)*(2*pi/ntot); c=R/sqrt(1+a*a/2);
  r=c*(1+a*cos(3*t)); rp=-3*c*a*sin(3*t); rpp=-9*c*a*cos(3*t);
  C=[r.*cos(t);rp.*cos(t)-r.*sin(t);(rpp-r).*cos(t)-2*rp.*sin(t); ...
    r.*sin(t);rp.*sin(t)+r.*cos(t);(rpp-r).*sin(t)+2*rp.*cos(t)];
  curvelen=2*pi;
  u=[0,2*pi]; ru=c*(1+a*cos(3*u)); du=-3*c*a*sin(3*u); ddu=-9*c*a*cos(3*u);
  ends=[ru.*cos(u);du.*cos(u)-ru.*sin(u);(ddu-ru).*cos(u)-2*du.*sin(u); ...
    ru.*sin(u);du.*sin(u)+ru.*cos(u);(ddu-ru).*sin(u)+2*du.*cos(u)];
  diagnostic=struct('a',a,'endpoint_six_row_absolute_difference',abs(ends(:,2)-ends(:,1)),'area',sum(C(1,:).*C(5,:)-C(4,:).*C(2,:))*pi/ntot, ...
    'exact_area',pi*R^2,'minimum_radius',min(r),'minimum_speed',min(hypot(C(2,:),C(5,:))), ...
    'minimum_orientation',min(C(1,:).*C(5,:)-C(4,:).*C(2,:)), ...
    'wall_clearance',min(model.X_R-max(C(1,:)),min(C(1,:))-model.X_L), ...
    'vertical_clearance',model.d/2-max(abs(C(4,:))), ...
    'analytic_periodicity_roundoff_bound',32*eps*max(1,max(abs(C),[],'all')), ...
    'simple_curve_reason','positive single-valued periodic radial graph', ...
    'orientation','CCW','global_mirroring',false);
  assert(diagnostic.minimum_radius>0 && diagnostic.minimum_speed>0 && ...
    diagnostic.minimum_orientation>0 && diagnostic.wall_clearance>0 && diagnostic.vertical_clearance>0);
end
