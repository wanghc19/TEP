    'a_negative',0.12,'a_positive',0.20,'rho_center',2,'rho_lead',17,'rho_exterior',1, ...
    'star_scale',sqrt(0.04/0.0618),'X_L',-0.5,'X_R',0.5, ...
    'H',1.1,'proxy_dist',0.2);
  config.common = struct('nside',160,'ntop',160,'nproxy',80, ...
    'mpw',32,'M',48,'K',97);
