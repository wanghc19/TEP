function audit = audit_i7_resolvent(result,evidence)
%AUDIT_I7_RESOLVENT Independently audit the fresh I7.4 matrix evidence.
% Purpose:
%   Reassemble the frozen matching, propagation, material-action, wall, and
%   component identities without solving another physical problem.
% Input:
%   result   - Fresh compact output from estimate_i7_resolvent.
%   evidence - Fresh full evidence from the same MATLAB process.
% Output:
%   audit - Scalar relative defects and a fail-closed all_pass flag.
% Main algorithm:
%   Rebuild Adef, Aphys, the selected physical q, the raw-coordinate
%   boundary actions, the propagated lead sums, and every final component.
% Based on:
%   The frozen I7.1 matching blocks and I7.4 raw-coordinate conventions.
% Main changes:
%   This function performs no scattering, QZ, or layer-potential solve and
%   reads no historical output.
% Numerical goal:
%   Require every independently reconstructed identity to agree within
%   1e-11 in the same fresh process that creates the formal artifacts.

  if nargin ~= 2 || ~isstruct(result) || ~isstruct(evidence)
    error('i74audit:Arguments','Fresh result and evidence structs are required.');
  end
  tolerance = 1e-11;
  cfg = evidence.config; K = cfg.K;
  center = evidence.center_cellmap;
  gamma = evidence.gamma(:); beta_m = evidence.beta_m(:);
  Zp = evidence.Zplus; Zm = evidence.Zminus;
  Ap = Zp(1:K,:); Bp = Zp(K+1:end,:);
  Am = Zm(1:K,:); Bm = Zm(K+1:end,:);
  G = diag(gamma); I = eye(K);
  Lp = evidence.matching.Lp; Lm = evidence.matching.Lm;
  T = [I+center.R_L,center.T_RL;center.T_LR,I+center.R_R];
  Adef = [(1i*G-Lm)*center.R_L-(1i*G+Lm), ...
    (1i*G-Lm)*center.T_RL; ...
    (1i*G-Lp)*center.T_LR, ...
    (1i*G-Lp)*center.R_R-(1i*G+Lp)];
  b = sqrt(1+abs(beta_m).^2);
  row_weight = repmat(sqrt(1./b),2,1);
  amplitude_weight = b+abs(gamma).^2./b;
  column_weight = repmat(1./sqrt(amplitude_weight),2,1);
  Aphys = row_weight.*Adef.*column_weight.';
  [~,S,V] = svd(Aphys,'econ'); sphys = diag(S);
  q = column_weight.*V(:,end); q = q/norm(q);
  [~,anchor] = max(abs(q)); q = q*exp(-1i*angle(q(anchor)));
  if real(q(anchor)) < 0, q = -q; end
  sdef = svd(Adef,'econ');
  scalar_rebuilt = [sdef(end),sdef(end)/sdef(1), ...
    sphys(end),sphys(end)/sphys(1)];
  scalar_saved = [result.matching.adef_sigma,result.matching.adef_ratio, ...
    result.matching.aphys_sigma,result.matching.aphys_ratio];

  trace = T*q;
  Dplus = Ap+Bp; Dminus = Am+Bm;
  propagation = evidence.propagation;
  Gplus = [Ap;Bp*propagation.Pplus];
  Gminus = [Am*propagation.Pminus;Bm];
  center_density = [center.H_L,center.H_R]*q;
  lead = evidence.lead_cellmap;
  lead_density_map = [lead.H_L,lead.H_R];

  [center_action_defect,center_value,center_normal] = ...
    LOCAL_action_audit(evidence.center_material_fine,q);
  [lead_action_defect,lead_value,lead_normal] = ...
    LOCAL_lead_audit(evidence.lead_material_fine,propagation, ...
      evidence.evaluation.lead_cell_max);
  wall = evidence.wall;
  wall_weight = result.model.d/wall.nodes;
  wall_value = wall_weight*(sum(abs(wall.center_lead_value_left).^2)+ ...
    sum(abs(wall.center_lead_value_right).^2))+ ...
    sum([wall.internal_rows.value_squared])+wall.tail_value_squared_candidate;
  wall_normal = wall_weight*(sum(abs(wall.center_lead_dx_left).^2)+ ...
    sum(abs(wall.center_lead_dx_right).^2))+ ...
    sum([wall.internal_rows.normal_squared])+wall.tail_normal_squared_candidate;
  value_squared = center_value+lead_value+wall_value;
  normal_squared = center_normal+lead_normal+wall_normal;
  epsilon = sqrt(max(0,normal_squared+value_squared/result.model.d^2));

  input = evidence.numerical_input;
  wall_input = input.wall_tail_data;
  input_q = LOCAL_from_parts(input.q);
  input_Pplus = LOCAL_from_parts(input.propagation.plus);
  input_Pminus = LOCAL_from_parts(input.propagation.minus);
  input_center_density = LOCAL_from_parts(wall_input.center_density);
  input_lead_density = LOCAL_from_parts(wall_input.lead_density_map);
  input_Gplus = LOCAL_from_parts(wall_input.Gplus);
  input_Gminus = LOCAL_from_parts(wall_input.Gminus);
  input_cplus = LOCAL_from_parts(wall_input.cplus);
  input_cminus = LOCAL_from_parts(wall_input.cminus);

  audit = struct('schema','EPOST_I7_RESOLVENT_V1_INDEPENDENT_AUDIT', ...
    'tolerance',tolerance, ...
    'T_defect',LOCAL_defect(T,evidence.matching.T), ...
    'Adef_defect',LOCAL_defect(Adef,evidence.matching.Adef), ...
    'Aphys_defect',LOCAL_defect(Aphys,evidence.matching.Aphys), ...
    'row_weight_defect',LOCAL_defect(row_weight,evidence.matching.row_weight), ...
    'column_weight_defect',LOCAL_defect( ...
      column_weight,evidence.matching.column_weight), ...
    'matching_scalar_defect',LOCAL_defect(scalar_rebuilt,scalar_saved), ...
    'q_defect',LOCAL_defect(q,evidence.q), ...
    'center_density_defect',LOCAL_defect( ...
      center_density,evidence.center_density), ...
    'plus_trace_defect',LOCAL_defect( ...
      Dplus*propagation.cplus,trace(K+1:end)), ...
    'minus_trace_defect',LOCAL_defect( ...
      Dminus*propagation.cminus,trace(1:K)), ...
    'Gplus_defect',LOCAL_defect(Gplus,propagation.Gplus), ...
    'Gminus_defect',LOCAL_defect(Gminus,propagation.Gminus), ...
    'plus_recurrence_defect',LOCAL_residual( ...
      evidence.pencil.A*Zp,evidence.pencil.B*Zp*propagation.Pplus), ...
    'minus_recurrence_defect',LOCAL_residual( ...
      evidence.pencil.B*Zm,evidence.pencil.A*Zm*propagation.Pminus), ...
    'center_action_defect',center_action_defect, ...
    'lead_action_defect',lead_action_defect, ...
    'center_value_defect',LOCAL_scalar_defect( ...
      center_value,evidence.center_jump.value_squared), ...
    'center_normal_defect',LOCAL_scalar_defect( ...
      center_normal,evidence.center_jump.normal_squared), ...
    'lead_value_defect',LOCAL_scalar_defect( ...
      lead_value,evidence.lead_jump_sum.value_squared), ...
    'lead_normal_defect',LOCAL_scalar_defect( ...
      lead_normal,evidence.lead_jump_sum.normal_squared), ...
    'wall_value_defect',LOCAL_scalar_defect(wall_value,wall.value_squared), ...
    'wall_normal_defect',LOCAL_scalar_defect( ...
      wall_normal,wall.normal_squared), ...
    'component_value_defect',LOCAL_scalar_defect( ...
      value_squared,result.components.value_squared), ...
    'component_normal_defect',LOCAL_scalar_defect( ...
      normal_squared,result.components.normal_squared), ...
    'epsilon_defect',LOCAL_scalar_defect(epsilon,result.epsilon_boundary), ...
    'input_q_defect',LOCAL_defect(input_q,evidence.q), ...
    'input_Pplus_defect',LOCAL_defect(input_Pplus,propagation.Pplus), ...
    'input_Pminus_defect',LOCAL_defect(input_Pminus,propagation.Pminus), ...
    'input_center_density_defect',LOCAL_defect( ...
      input_center_density,evidence.center_density), ...
    'input_lead_density_defect',LOCAL_defect( ...
      input_lead_density,lead_density_map), ...
    'input_Gplus_defect',LOCAL_defect(input_Gplus,propagation.Gplus), ...
    'input_Gminus_defect',LOCAL_defect(input_Gminus,propagation.Gminus), ...
    'input_cplus_defect',LOCAL_defect(input_cplus,propagation.cplus), ...
    'input_cminus_defect',LOCAL_defect(input_cminus,propagation.cminus));
  names = fieldnames(audit); defects = [];
  for j = 1:numel(names)
    value = audit.(names{j});
    if isnumeric(value) && isscalar(value) && ...
        ~strcmp(names{j},'tolerance')
      defects(end+1) = value; %#ok<AGROW>
    end
  end
  audit.maximum_defect = max(defects);
  audit.all_finite = all(isfinite(defects));
  audit.all_pass = audit.all_finite && audit.maximum_defect <= tolerance;
end

function [action_defect,value_squared,normal_squared] = ...
    LOCAL_action_audit(action,state)
  N = action.target_nodes; scale = action.density_scale;
  Araw = (action.A_scaled.*scale.')./scale;
  residual = Araw*action.density_map+action.B;
  action_defect = max(LOCAL_defect( ...
    residual(1:N,:),action.signed_value_action),LOCAL_defect( ...
    -residual(N+1:end,:),action.signed_normal_action));
  value = residual(1:N,:)*state;
  normal = -residual(N+1:end,:)*state;
  value_squared = real(sum(action.weights.*abs(value).^2));
  normal_squared = real(sum(action.weights.*abs(normal).^2));
end

function [action_defect,value_squared,normal_squared] = ...
    LOCAL_lead_audit(action,propagation,max_cells)
  action_defect = LOCAL_action_audit(action,propagation.Gplus*propagation.cplus);
  plus = propagation.cplus; minus = propagation.cminus;
  value_squared = 0; normal_squared = 0;
  last_value = NaN; last_normal = NaN;
  for n = 0:max_cells-1
    [~,vp,np] = LOCAL_action_audit(action,propagation.Gplus*plus);
    [~,vm,nm] = LOCAL_action_audit(action,propagation.Gminus*minus);
    last_value = vp+vm; last_normal = np+nm;
    value_squared = value_squared+last_value;
    normal_squared = normal_squared+last_normal;
    plus = propagation.Pplus*plus;
    minus = propagation.Pminus*minus;
  end
  [~,vp,np] = LOCAL_action_audit(action,propagation.Gplus*plus);
  [~,vm,nm] = LOCAL_action_audit(action,propagation.Gminus*minus);
  next_value = vp+vm; next_normal = np+nm;
  value_ratio = next_value/max(realmin,last_value);
  normal_ratio = next_normal/max(realmin,last_normal);
  if ~(value_ratio >= 0 && value_ratio < 1 && ...
      normal_ratio >= 0 && normal_ratio < 1)
    error('i74audit:LeadTail','Fresh lead tail is unavailable.');
  end
  value_squared = value_squared+next_value/(1-value_ratio);
  normal_squared = normal_squared+next_normal/(1-normal_ratio);
end

function value = LOCAL_from_parts(parts)
  value = complex(parts.real,parts.imag);
end

function value = LOCAL_scalar_defect(actual,reference)
  value = abs(actual-reference)/max([1,abs(actual),abs(reference)]);
end

function value = LOCAL_defect(actual,reference)
  value = norm(actual-reference,'fro')/max(1,norm(reference,'fro'));
end

function value = LOCAL_residual(left,right)
  value = norm(left-right,'fro')/max(1,norm(left,'fro')+norm(right,'fro'));
end
