function LOCAL_write_json(path,value)
  text = jsonencode(value,'PrettyPrint',true);
  fid = fopen(path,'w');
  if fid < 0, error('i74:OutputWrite','Cannot create %s.',path); end
  cleanup = onCleanup(@() fclose(fid));
  fprintf(fid,'%s\n',text);
  clear cleanup;
end

function LOCAL_write_components(path,c)
  names = fieldnames(c); fid = fopen(path,'w');
  if fid < 0, error('i74:OutputWrite','Cannot create %s.',path); end
  cleanup = onCleanup(@() fclose(fid));
  fprintf(fid,'name,value\n');
  for j = 1:numel(names)
    value = c.(names{j});
    if isnumeric(value) && isscalar(value)
      fprintf(fid,'%s,%.17g\n',names{j},value);
    end
  end
  clear cleanup;
end

function value = LOCAL_relative_scalar(a,b)
  value = abs(a-b)/max([realmin,abs(a),abs(b)]);
end

