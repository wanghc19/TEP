function [result,evidence] = estimate_i7_resolvent(output_dir)
%ESTIMATE_I7_RESOLVENT Estimate the corrected-density I7.4 raw-field terms.
% Purpose:
%   Build the frozen I7 ellipse-center candidate and estimate its complete
%   material-interface, artificial-wall, and local mass terms in physical
%   density coordinates.
% Input:
%   output_dir - Existing empty run directory for create-once artifacts.
% Output:
%   result   - Compact numerical component and status structure.
%   evidence - Full finite matrices, densities, signed jumps, and gates.
% Main algorithm:
%   Form the fine/M48 matching null vector, retain the qualified lead QZ
%   propagation maps, apply the public raw boundary operator to the same
%   frozen trigonometric density at two node counts, sample both artificial-
%   wall jumps in physical space, and estimate the same field on a safe disk.
% Based on:
%   test/i7/refine-v1/check_i7_refinement.m and the I6 resolvent-v3 raw-field
%   conventions.
% Main changes:
%   Use the corrected public physical densities for an ellipse center,
%   replace circle Parseval material rows by physical arclength quadrature,
%   and keep every unclosed continuous-remainder obligation explicit.
% Numerical goal:
%   Supply all ordinary-double inputs for the conditional I7.4 F14 scalar
%   calculation without claiming a continuous spectral certificate.

  if nargin ~= 1 || ~(ischar(output_dir) || ...
      (isstring(output_dir) && isscalar(output_dir)))
    error('i74:Arguments','output_dir must be a character vector or string.');
  end
  output_dir = char(output_dir);
  if ~isfolder(output_dir)
    error('i74:OutputDirectory','The explicit output directory must exist.');
  end
  artifacts = {'stage-1-checkpoint.mat','scientific.mat', ...
    'numerical-input.json','result.json','audit.json', ...
    'component-summary.csv'};
  for j = 1:numel(artifacts)
    if isfile(fullfile(output_dir,artifacts{j})) || ...
        isfolder(fullfile(output_dir,artifacts{j}))
      error('i74:OutputExists','Refusing to overwrite %s.',artifacts{j});
    end
  end

  timer = tic;
  model = struct('khat',1.755995740875,'beta',0.5,'d',1,'L',1, ...
    'R',0.2,'rho_exterior',1,'rho_center',2,'rho_lead',17, ...
    'axes',[0.25,0.16],'X_L',-0.5,'X_R',0.5, ...
    'H',1.1,'proxy_dist',0.2,'delta_c',0.04,'delta_w',0.04);
  cfg = struct('ntot',256,'nside',160,'ntop',160, ...
    'nproxy',80,'mpw',32,'M',48,'K',97);
  evaluation = struct('target_nodes_coarse',256, ...
    'source_nodes_coarse',256,'target_nodes_fine',512, ...
    'source_nodes_fine',512,'material_boundary_nodes',[256,512], ...
    'wall_nodes',[256,512],'disk_radial_nodes',16,'disk_angular_nodes',16, ...
    'lead_cell_max',40);

  fprintf(1,'I7.4 stage 1: corrected center and lead objects\n');
  warning_guard = LOCAL_solver_warning_guard(); %#ok<NASGU>
  [lead,Zplus,Zminus,pencil,beta_m,gamma,phase,qz] = ...
    LOCAL_lead(model,cfg);
  center = LOCAL_center(model,cfg);
  [matching,q] = LOCAL_matching(center,Zplus,Zminus,beta_m,gamma);
  propagation = LOCAL_propagation( ...
    pencil,Zplus,Zminus,q,matching.T,cfg.K);
  clear warning_guard;
  center_density = center.H_L*q(1:cfg.K)+center.H_R*q(cfg.K+1:end);
  lead_density_plus = [lead.H_L,lead.H_R]*propagation.Gplus;
  lead_density_minus = [lead.H_L,lead.H_R]*propagation.Gminus;
  save(fullfile(output_dir,'stage-1-checkpoint.mat'),'model','cfg', ...
    'evaluation','lead','center','Zplus','Zminus','pencil','beta_m', ...
    'gamma','phase','qz','matching','q','propagation', ...
    'center_density','lead_density_plus','lead_density_minus','-v7.3');

  fprintf(1,'I7.4 stage 2: signed raw boundary-operator jump actions\n');
  center_coarse = LOCAL_material_action(center,'ellipse',model.axes, ...
    sqrt(model.rho_center)*model.khat,model, ...
    evaluation.material_boundary_nodes(1));
  center_fine = LOCAL_material_action(center,'ellipse',model.axes, ...
    sqrt(model.rho_center)*model.khat,model, ...
    evaluation.material_boundary_nodes(2));
  lead_coarse = LOCAL_material_action(lead,'circle',[model.R,model.R], ...
    sqrt(model.rho_lead)*model.khat,model, ...
    evaluation.material_boundary_nodes(1));
  lead_fine = LOCAL_material_action(lead,'circle',[model.R,model.R], ...
    sqrt(model.rho_lead)*model.khat,model, ...
    evaluation.material_boundary_nodes(2));

  center_jump = LOCAL_apply_jump(center_fine,q);
  center_jump_coarse = LOCAL_apply_jump(center_coarse,q);
  lead_sum = LOCAL_lead_jump_sum(lead_fine,propagation, ...
    evaluation.lead_cell_max);
  lead_sum_coarse = LOCAL_lead_jump_sum(lead_coarse,propagation, ...
    evaluation.lead_cell_max);
  material_value_squared = center_jump.value_squared+lead_sum.value_squared;
  material_normal_squared = center_jump.normal_squared+lead_sum.normal_squared;

  fprintf(1,'I7.4 stage 3: non-Fourier wall and safe-disk mass samples\n');
  wall = LOCAL_wall_jump(center,lead,q,propagation,model, ...
    evaluation.wall_nodes,evaluation.lead_cell_max);
  mass = LOCAL_mass_diagnostic(center,center_density,q,beta_m,gamma, ...
    model,evaluation.disk_radial_nodes,evaluation.disk_angular_nodes, ...
    evaluation.source_nodes_fine);

  components_complete = lead_sum.tail_candidate_available && ...
    wall.tail_candidate_available;
  value_squared = material_value_squared+wall.value_squared;
  normal_squared = material_normal_squared+wall.normal_squared;
  if components_complete
    epsilon_boundary = sqrt(max(0,normal_squared+value_squared/model.d^2));
  else
    epsilon_boundary = NaN;
  end
  U_lower_candidate = mass.cone_candidate;
  if ~(isfinite(U_lower_candidate) && U_lower_candidate >= 0)
    error('i74:NonfiniteComponents', ...
      'The numerical mass candidate is unavailable.');
  end

  curvature_max = model.axes(1)/model.axes(2)^2;
  reach_lower = model.axes(2)^2/model.axes(1);
  geometry = struct('curvature_max',curvature_max, ...
    'reach_lower',reach_lower, ...
    'collar_theta',1-model.delta_c*curvature_max, ...
    'ellipse_speed_min',model.axes(2), ...
    'ellipse_speed_max',model.axes(1), ...
    'ellipse_normal_tube_pass',model.delta_c<reach_lower);
  native_to_cross_grid_change = struct( ...
    'center_value_relative_change',LOCAL_relative_scalar( ...
      center_jump_coarse.value_squared,center_jump.value_squared), ...
    'center_normal_relative_change',LOCAL_relative_scalar( ...
      center_jump_coarse.normal_squared,center_jump.normal_squared), ...
    'lead_value_relative_change',LOCAL_relative_scalar( ...
      lead_sum_coarse.value_squared,lead_sum.value_squared), ...
    'lead_normal_relative_change',LOCAL_relative_scalar( ...
      lead_sum_coarse.normal_squared,lead_sum.normal_squared));
  square_integrable_candidate = ...
    norm(propagation.Pplus,'fro') < 1 && norm(propagation.Pminus,'fro') < 1;
  structure = struct('piecewise_pde_exact',true, ...
    'quasiperiodic_exact',true, ...
    'square_integrable',square_integrable_candidate, ...
    'numerical_qp_evaluator_enclosed',false, ...
    'propagation_tail_one_sided',false);
  unresolved = { ...
    'ellipse continuous boundary-operator quadrature remainder is not one-sided', ...
    'the raw field is defined with the exact QP kernel but its MFS numerical evaluation error is not enclosed', ...
    'safe-disk point lower and gradient upper are sampled rather than certified', ...
    'lead propagation and omitted-cell tails use observed geometric estimates rather than one-sided bounds', ...
    'artificial-wall physical quadrature and source interpolation remainders are not enclosed'};
  components = struct( ...
    'material_center_value_squared',center_jump.value_squared, ...
    'material_center_normal_squared',center_jump.normal_squared, ...
    'material_lead_value_squared',lead_sum.value_squared, ...
    'material_lead_normal_squared',lead_sum.normal_squared, ...
    'material_value_squared',material_value_squared, ...
    'material_normal_squared',material_normal_squared, ...
    'wall_value_squared',wall.value_squared, ...
    'wall_normal_squared',wall.normal_squared, ...
    'value_squared',value_squared,'normal_squared',normal_squared, ...
    'mass_disk_quadrature',mass.quadrature_norm, ...
    'mass_cone_candidate',mass.cone_candidate, ...
    'native_to_cross_grid_change',native_to_cross_grid_change, ...
    'native_to_cross_grid_note',[ ...
      'N=256 is the solve collocation grid; N=512 applies the same fixed ' ...
      'trigonometric density and is not a two-solve convergence test.']);
  K = cfg.K;
  Ap = Zplus(1:K,:); Bp = Zplus(K+1:end,:);
  Am = Zminus(1:K,:); Bm = Zminus(K+1:end,:);
  audit = struct( ...
    'schema','EPOST_I7_RESOLVENT_V1_AUDIT', ...
    'material_scale_roundtrip_max',max([ ...
      center_coarse.scale_roundtrip_defect, ...
      center_fine.scale_roundtrip_defect, ...
      lead_coarse.scale_roundtrip_defect, ...
      lead_fine.scale_roundtrip_defect]), ...
    'material_raw_matrix_identity_max',max([ ...
      center_coarse.raw_matrix_identity_defect, ...
      center_fine.raw_matrix_identity_defect, ...
      lead_coarse.raw_matrix_identity_defect, ...
      lead_fine.raw_matrix_identity_defect]), ...
    'fixed_density_interpolation_roundtrip_max',max([ ...
      center_coarse.interpolation_roundtrip_defect, ...
      center_fine.interpolation_roundtrip_defect, ...
      lead_coarse.interpolation_roundtrip_defect, ...
      lead_fine.interpolation_roundtrip_defect]), ...
    'center_density_identity_defect',norm(center_density- ...
      [center.H_L,center.H_R]*q)/max(1,norm(center_density)), ...
    'lead_plus_density_identity_defect',norm(lead_density_plus- ...
      [lead.H_L,lead.H_R]*propagation.Gplus,'fro')/ ...
      max(1,norm(lead_density_plus,'fro')), ...
    'lead_minus_density_identity_defect',norm(lead_density_minus- ...
      [lead.H_L,lead.H_R]*propagation.Gminus,'fro')/ ...
      max(1,norm(lead_density_minus,'fro')), ...
    'Gplus_block_formula_defect',norm(propagation.Gplus- ...
      [Ap;Bp*propagation.Pplus],'fro')/ ...
      max(1,norm(propagation.Gplus,'fro')), ...
    'Gminus_block_formula_defect',norm(propagation.Gminus- ...
      [Am*propagation.Pminus;Bm],'fro')/ ...
      max(1,norm(propagation.Gminus,'fro')), ...
    'plus_trace_residual',propagation.plus_coordinate_residual, ...
    'minus_trace_residual',propagation.minus_coordinate_residual, ...
    'center_coarse_value_squared',center_jump_coarse.value_squared, ...
    'center_fine_value_squared',center_jump.value_squared, ...
    'center_coarse_normal_squared',center_jump_coarse.normal_squared, ...
    'center_fine_normal_squared',center_jump.normal_squared, ...
    'lead_coarse_value_squared',lead_sum_coarse.value_squared, ...
    'lead_fine_value_squared',lead_sum.value_squared, ...
    'lead_coarse_normal_squared',lead_sum_coarse.normal_squared, ...
    'lead_fine_normal_squared',lead_sum.normal_squared, ...
    'center_fine_normalized_action_frobenius', ...
      center_fine.normalized_action_frobenius, ...
    'lead_fine_normalized_action_frobenius', ...
      lead_fine.normalized_action_frobenius, ...
    'material_value_sum_defect',abs(material_value_squared- ...
      center_jump.value_squared-lead_sum.value_squared), ...
    'material_normal_sum_defect',abs(material_normal_squared- ...
      center_jump.normal_squared-lead_sum.normal_squared), ...
    'epsilon_component_identity_defect',abs(epsilon_boundary^2- ...
      normal_squared-value_squared/model.d^2));
  scale_factor = 2.5;
  scale_invariance_available = isfinite(epsilon_boundary) && ...
    isfinite(U_lower_candidate) && U_lower_candidate > 0;
  if scale_invariance_available
    scale_invariance_defect = abs( ...
      (scale_factor*epsilon_boundary)/(scale_factor*U_lower_candidate)- ...
      epsilon_boundary/U_lower_candidate)/ ...
      max(realmin,epsilon_boundary/U_lower_candidate);
  else
    scale_invariance_defect = NaN;
  end
  numerical_input = struct('schema','EPOST_I7_RESOLVENT_V1_NUMERICAL_INPUT', ...
    'model',model,'epsilon_boundary',epsilon_boundary, ...
    'U_lower_candidate',U_lower_candidate,'components',components, ...
    'unresolved_certification',{unresolved},'structure',structure, ...
    'q',LOCAL_complex_parts(q), ...
    'propagation',struct( ...
      'plus',struct('real',real(propagation.Pplus), ...
        'imag',imag(propagation.Pplus)), ...
      'minus',struct('real',real(propagation.Pminus), ...
        'imag',imag(propagation.Pminus))), ...
    'wall_tail_data',struct( ...
      'center_density',LOCAL_complex_parts(center_density), ...
      'lead_density_map',LOCAL_complex_parts([lead.H_L,lead.H_R]), ...
      'Gplus',LOCAL_complex_parts(propagation.Gplus), ...
      'Gminus',LOCAL_complex_parts(propagation.Gminus), ...
      'cplus',LOCAL_complex_parts(propagation.cplus), ...
      'cminus',LOCAL_complex_parts(propagation.cminus)));

  if components_complete
    status = 'FINITE_DIAGNOSTIC_ONLY';
  else
    status = 'FINITE_PREFIX_DIAGNOSTIC_TAIL_UNAVAILABLE';
  end
  result = struct('schema','EPOST_I7_RESOLVENT_V1_RESULT', ...
    'status',status,'model',model,'config',cfg,'evaluation',evaluation, ...
    'matching',matching.summary,'qz',qz,'geometry',geometry, ...
    'components',components,'epsilon_boundary',epsilon_boundary, ...
    'U_lower_candidate',U_lower_candidate, ...
    'complete_component_candidate',components_complete, ...
    'structure',structure, ...
    'scale_invariance',struct('factor',scale_factor, ...
      'available',scale_invariance_available, ...
      'epsilon_over_U_relative_defect',scale_invariance_defect), ...
    'unresolved_certification',{unresolved}, ...
    'elapsed_seconds_matlab',toc(timer));
  evidence = struct('model',model,'config',cfg,'evaluation',evaluation, ...
    'beta_m',beta_m,'gamma',gamma,'phase',phase,'q',q, ...
    'matching',matching,'center_cellmap',center,'lead_cellmap',lead, ...
    'pencil',pencil,'Zplus',Zplus,'Zminus',Zminus, ...
    'propagation',propagation,'center_density',center_density, ...
    'lead_density_plus_unit',lead_density_plus, ...
    'lead_density_minus_unit',lead_density_minus, ...
    'center_material_fine',center_fine,'center_material_coarse',center_coarse, ...
    'lead_material_fine',lead_fine,'lead_material_coarse',lead_coarse, ...
    'center_jump',center_jump,'lead_jump_sum',lead_sum, ...
    'wall',wall,'mass',mass,'audit',audit, ...
    'numerical_input',numerical_input);

  save(fullfile(output_dir,'scientific.mat'),'result','evidence','-v7.3');
  LOCAL_write_json(fullfile(output_dir,'numerical-input.json'),numerical_input);
  LOCAL_write_json(fullfile(output_dir,'result.json'),result);
  LOCAL_write_json(fullfile(output_dir,'audit.json'),audit);
  LOCAL_write_components(fullfile(output_dir,'component-summary.csv'),components);
  fprintf(1,['I7.4 complete status=%s epsilon=%.17g Ucandidate=%.17g ' ...
    'seconds=%.3f\n'],status,epsilon_boundary,U_lower_candidate, ...
    result.elapsed_seconds_matlab);
end

%% ==================== Frozen matching objects ====================
% These helpers preserve the reviewed I7 port, QZ, and density conventions.

function [lead,Zp,Zm,pencil,beta_m,gamma,phase,diagnostic] = ...
    LOCAL_lead(model,cfg)
  [lead,~,chans] = LOCAL_cellmap('circle',[model.R,model.R], ...
    model.rho_lead,model,cfg);
  K = chans.K;
  A = [-lead.R_L,eye(K);lead.T_LR,zeros(K)];
  B = [zeros(K),lead.T_RL;eye(K),-lead.R_R];
  [Zp,plus] = LOCAL_qzsub(A,B,K);
  [Zm,minus] = LOCAL_qzsub(B,A,K);
  pencil = struct('A',A,'B',B);
  beta_m = chans.beta_m(:);
  gamma = chans.gamma_m(:);
  phase = chans.phase(:);
  diagnostic = struct('plus',plus,'minus',minus);
end

function center = LOCAL_center(model,cfg)
  center = LOCAL_cellmap('ellipse',model.axes,model.rho_center,model,cfg);
end

function [cellmap,C,chans,pars,proxy] = ...
    LOCAL_cellmap(flag_geom,axes,rho,model,cfg)
  pars = struct('k',model.khat,'beta',model.beta,'d',model.d, ...
    'periodic_axis','y','h2d_evaluator',@LOCAL_h2d_chunked_public);
  chans = bloch.rayleigh_channels(model.khat,model.beta,model.d, ...
    cfg.M,model.X_R-model.X_L);
  if strcmp(flag_geom,'circle')
    [C,curvelen] = geom.construct_cont(cfg.ntot,'circle',0,0,axes(1));
  else
    [C,curvelen] = geom.construct_cont(cfg.ntot,'ellipse',0,0,axes);
  end
  mfscfg = struct('H',model.H,'proxy_dist',model.proxy_dist, ...
    'N_side',cfg.nside,'N_top',cfg.ntop, ...
    'N_proxy_edge',cfg.nproxy,'M_pw',cfg.mpw);
  proxy = kernel.precomp_proxy(pars,mfscfg);
  cellmap = bloch.construct_S(C,model.khat,sqrt(rho)*model.khat, ...
    pars,proxy,curvelen,chans,model.X_L,model.X_R);
  cellmap.i74_geometry = C;
  cellmap.i74_pars = pars;
  cellmap.i74_proxy = proxy;
  cellmap.i74_shape = flag_geom;
  cellmap.i74_axes = axes;
end

function [out,q] = LOCAL_matching(cellmap,Zp,Zm,beta_m,gamma)
  K = numel(gamma); G = diag(gamma); I = eye(K);
  [Lp,Lm] = LOCAL_dtn(Zp,Zm,gamma);
  T = [I+cellmap.R_L,cellmap.T_RL;cellmap.T_LR,I+cellmap.R_R];
  Adef = [(1i*G-Lm)*cellmap.R_L-(1i*G+Lm), ...
    (1i*G-Lm)*cellmap.T_RL; ...
    (1i*G-Lp)*cellmap.T_LR, ...
    (1i*G-Lp)*cellmap.R_R-(1i*G+Lp)];
  b = sqrt(1+abs(beta_m).^2);
  rowwt = repmat(sqrt(1./b),2,1);
  ampwt = b+abs(gamma).^2./b;
  colwt = repmat(1./sqrt(ampwt),2,1);
  Aphys = rowwt.*Adef.*colwt.';
  [~,S,V] = svd(Aphys,'econ'); singular = diag(S);
  q = colwt.*V(:,end); q = q/norm(q);
  [~,phase_anchor] = max(abs(q));
  q = q*exp(-1i*angle(q(phase_anchor)));
  if real(q(phase_anchor)) < 0, q = -q; end
  residual = Adef*q;
  summary = struct('adef_sigma',min(svd(Adef,'econ')), ...
    'adef_ratio',min(svd(Adef,'econ'))/max(svd(Adef,'econ')), ...
    'aphys_sigma',singular(end),'aphys_ratio',singular(end)/singular(1), ...
    'q_norm',norm(q),'phase_anchor_index',phase_anchor, ...
    'phase_anchor_value',real(q(phase_anchor)), ...
    'residual_norm',norm(residual));
  out = struct('Adef',Adef,'Aphys',Aphys,'T',T,'Lp',Lp,'Lm',Lm, ...
    'row_weight',rowwt,'column_weight',colwt,'singular_values',singular, ...
    'residual',residual,'summary',summary);
end

function out = LOCAL_propagation(pencil,Zp,Zm,q,center_trace,K)
  plus = LOCAL_action(pencil.A,pencil.B,Zp,false,K);
  minus = LOCAL_action(pencil.A,pencil.B,Zm,true,K);
  Ap = Zp(1:K,:); Bp = Zp(K+1:end,:);
  Am = Zm(1:K,:); Bm = Zm(K+1:end,:);
  Dplus = Ap+Bp; Dminus = Am+Bm;
  trace = center_trace*q;
  left_trace = trace(1:K); right_trace = trace(K+1:end);
  cplus = Dplus\right_trace;
  cminus = Dminus\left_trace;
  plus_coordinate_residual = norm(Dplus*cplus-right_trace)/ ...
    max(1,norm(right_trace));
  minus_coordinate_residual = norm(Dminus*cminus-left_trace)/ ...
    max(1,norm(left_trace));
  Gplus = [Ap;Bp*plus.P];
  Gminus = [Am*minus.P;Bm];
  plus_recurrence_residual = norm( ...
    pencil.A*Zp-pencil.B*Zp*plus.P,'fro')/ ...
    max(1,norm(pencil.A*Zp,'fro')+norm(pencil.B*Zp*plus.P,'fro'));
  minus_recurrence_residual = norm( ...
    pencil.B*Zm-pencil.A*Zm*minus.P,'fro')/ ...
    max(1,norm(pencil.B*Zm,'fro')+norm(pencil.A*Zm*minus.P,'fro'));
  out = struct('Pplus',plus.P,'Pminus',minus.P, ...
    'Dplus',Dplus,'Dminus',Dminus, ...
    'Gplus',Gplus,'Gminus',Gminus, ...
    'cplus',cplus,'cminus',cminus, ...
    'plus_coordinate_residual',plus_coordinate_residual, ...
    'minus_coordinate_residual',minus_coordinate_residual, ...
    'plus_recurrence_residual',plus_recurrence_residual, ...
    'minus_recurrence_residual',minus_recurrence_residual, ...
    'plus_diagnostic',rmfield(plus,'P'), ...
    'minus_diagnostic',rmfield(minus,'P'));
end

function out = LOCAL_action(A,B,Z,reversed,K)
  if reversed, C=A*Z; rhs=B*Z; else, C=B*Z; rhs=A*Z; end
  [~,R] = qr(C,0); rc = rcond(R); P = C\rhs;
  residual = norm(C*P-rhs,'fro')/max(1, ...
    norm(C,'fro')*norm(P,2)+norm(rhs,'fro'));
  if rank(R) ~= K || rc < 1e-8 || residual > 1e-10
    error('i74:Propagation','A lead propagation map failed qualification.');
  end
  out = struct('P',P,'thin_qr_rcond',rc,'solve_residual',residual, ...
    'frobenius_norm',norm(P,'fro'),'spectral_norm',norm(P,2));
end

function [Zs,diagnostic] = LOCAL_qzsub(A,B,K)
  rho = hypot(norm(A,'fro'),norm(B,'fro'));
  if ~isfinite(rho) || rho == 0
    error('i7:QZScale','The QZ pencil scale is zero or nonfinite.');
  end
  A = A/rho; B = B/rho;
  [S,T,Q,Z] = qz(A,B,'complex');
  res = hypot(norm(A-Q'*S*Z','fro'),norm(B-Q'*T*Z','fro'));
  tol = max(100*eps,10*res);
  alpha = diag(S); theta = diag(T); scale = hypot(abs(alpha),abs(theta));
  indet = scale <= tol; scale(indet) = 1;
  an = abs(alpha)./scale; tn = abs(theta)./scale;
  infinite = ~indet & tn <= tol & an > tol;
  neutral = ~indet & ~infinite & abs(an-tn) <= tol;
  stable = ~indet & ~infinite & ~neutral & an < tn-tol;
  unstable = infinite | (~indet & ~neutral & an > tn+tol);
  if sum(stable) ~= K || sum(unstable) ~= K || any(indet) || any(neutral)
    error('i7:QZClassification', ...
      'stable=%d unstable=%d neutral=%d indet=%d expected=%d.', ...
      sum(stable),sum(unstable),sum(neutral),sum(indet),K);
  end
  [~,~,~,Zo] = ordqz(S,T,Q,Z,stable); Zs = Zo(:,1:K);
  diagnostic = struct('stable',sum(stable),'unstable',sum(unstable), ...
    'neutral',sum(neutral),'indeterminate',sum(indet), ...
    'residual',res,'tolerance',tol);
end

function [Lp,Lm] = LOCAL_dtn(Zp,Zm,gamma)
  K = numel(gamma); G = diag(gamma);
  Ap = Zp(1:K,:); Bp = Zp(K+1:end,:);
  Am = Zm(1:K,:); Bm = Zm(K+1:end,:);
  Dp = Ap+Bp; Np = 1i*G*(Ap-Bp);
  Dm = Am+Bm; Nm = -1i*G*(Am-Bm);
  Lp = (Dp.'\Np.').'; Lm = (Dm.'\Nm.').';
end

%% ==================== Physical material jumps ====================
% Signed value and ordinary-normal jumps are evaluated before their moduli.

function out = LOCAL_material_action(cellmap,flag_geom,axes,kint,model,N)
  if strcmp(flag_geom,'circle')
    [C,curvelen] = geom.construct_cont(N,'circle',0,0,axes(1));
  else
    [C,curvelen] = geom.construct_cont(N,'ellipse',0,0,axes);
  end
  curve = LOCAL_curve(flag_geom,axes,N);
  boundary_speed = hypot(C(2,:),C(5,:)).';
  boundary_weights = (curvelen/N)*boundary_speed;
  original_density_map = [cellmap.H_L,cellmap.H_R];
  density_map = LOCAL_interp_density_map(original_density_map,N);
  A_scaled = op.construct_A_QP(C,model.khat,kint, ...
    cellmap.i74_pars,cellmap.i74_proxy,curvelen);
  [B_L,B_R] = bloch.incident_rhs(C,cellmap.channels, ...
    model.X_L,model.X_R);
  B = [B_L,B_R];
  density_scale = sqrt(repmat(boundary_weights,2,1));
  scaled_density_map = density_scale.*density_map;
  scaled_residual_action = A_scaled*scaled_density_map+density_scale.*B;
  raw_residual_action = scaled_residual_action./density_scale;
  A_raw = (A_scaled.*density_scale.')./density_scale;
  raw_from_matrix = A_raw*density_map+B;
  signed_value_action = raw_residual_action(1:N,:);
  signed_normal_action = -raw_residual_action(N+1:end,:);
  out = struct('shape',flag_geom,'axes',axes,'source_nodes',N, ...
    'target_nodes',N,'weights',boundary_weights, ...
    'signed_value_action',signed_value_action, ...
    'signed_normal_action',signed_normal_action, ...
    'density_map',density_map,'density_scale',density_scale, ...
    'A_scaled',A_scaled,'B',B, ...
    'scale_roundtrip_defect',norm( ...
      scaled_density_map./density_scale-density_map,'fro')/ ...
      max(1,norm(density_map,'fro')), ...
    'raw_matrix_identity_defect',norm( ...
      raw_from_matrix-raw_residual_action,'fro')/ ...
      max(1,norm(raw_residual_action,'fro')), ...
    'normalized_action_frobenius',norm(raw_residual_action,'fro')/ ...
      max(1,norm(B,'fro')+norm(A_raw,'fro')*norm(density_map,'fro')), ...
    'interpolation_roundtrip_defect',norm( ...
      LOCAL_interp_density_map(density_map,size(original_density_map,1)/2)- ...
      original_density_map,'fro')/max(1,norm(original_density_map,'fro')), ...
    'physical_arclength_sum',sum(boundary_weights), ...
    'normal_unit_defect',max(abs(hypot(curve.nx,curve.ny)-1)));
end

function out = LOCAL_apply_jump(action,state)
  value = action.signed_value_action*state;
  normal = action.signed_normal_action*state;
  out = struct('value',value,'normal',normal, ...
    'value_squared',real(sum(action.weights.*abs(value).^2)), ...
    'normal_squared',real(sum(action.weights.*abs(normal).^2)));
end

function out = LOCAL_lead_jump_sum(action,propagation,max_cells)
  plus = propagation.cplus; minus = propagation.cminus;
  rows = repmat(struct('index',0,'plus_state_norm',0, ...
    'minus_state_norm',0,'value_squared',0,'normal_squared',0), ...
    max_cells,1);
  value_squared = 0; normal_squared = 0;
  for n = 0:max_cells-1
    xp = propagation.Gplus*plus; xm = propagation.Gminus*minus;
    jp = LOCAL_apply_jump(action,xp); jm = LOCAL_apply_jump(action,xm);
    rows(n+1) = struct('index',n,'plus_state_norm',norm(xp), ...
      'minus_state_norm',norm(xm), ...
      'value_squared',jp.value_squared+jm.value_squared, ...
      'normal_squared',jp.normal_squared+jm.normal_squared);
    value_squared = value_squared+rows(n+1).value_squared;
    normal_squared = normal_squared+rows(n+1).normal_squared;
    plus = propagation.Pplus*plus;
    minus = propagation.Pminus*minus;
  end
  xp = propagation.Gplus*plus; xm = propagation.Gminus*minus;
  next_plus = LOCAL_apply_jump(action,xp);
  next_minus = LOCAL_apply_jump(action,xm);
  next_value = next_plus.value_squared+next_minus.value_squared;
  next_normal = next_plus.normal_squared+next_minus.normal_squared;
  value_ratio = next_value/max(realmin,rows(end).value_squared);
  normal_ratio = next_normal/max(realmin,rows(end).normal_squared);
  [value_tail,value_tail_available] = ...
    LOCAL_geometric_tail(next_value,value_ratio);
  [normal_tail,normal_tail_available] = ...
    LOCAL_geometric_tail(next_normal,normal_ratio);
  tail_candidate_available = value_tail_available && normal_tail_available;
  out = struct('value_squared',value_squared+value_tail, ...
    'normal_squared',normal_squared+normal_tail, ...
    'finite_value_squared',value_squared, ...
    'finite_normal_squared',normal_squared, ...
    'tail_value_squared_candidate',value_tail, ...
    'tail_normal_squared_candidate',normal_tail, ...
    'tail_value_ratio',value_ratio,'tail_normal_ratio',normal_ratio, ...
    'cells',rows, ...
    'next_plus_coordinate_norm',norm(plus), ...
    'next_minus_coordinate_norm',norm(minus), ...
    'finite_cell_count_each_side',max_cells, ...
    'tail_candidate_available',tail_candidate_available, ...
    'omitted_tail_certified',false);
end

function [value,available] = LOCAL_geometric_tail(next_term,ratio)
  if isfinite(next_term) && isfinite(ratio) && ratio >= 0 && ratio < 1
    value = next_term/(1-ratio);
    available = true;
  else
    value = NaN;
    available = false;
  end
end

function layer = LOCAL_qp_layer(source,target,pars,proxy)
  nt = numel(target.x); ns = numel(source.x);
  value = zeros(nt,2*ns); normal = zeros(nt,2*ns);
  batch = 64;
  src = [source.x.';source.y.'];
  for first = 1:batch:nt
    index = first:min(first+batch-1,nt);
    trg = [target.x(index).';target.y(index).'];
    [P,Gx,Gy,Hxx,Hxy,Hyy] = ...
      kernel.qpgreen_mfs_pairmat(src,trg,pars,proxy);
    wt = source.weights.'; sx = source.nx.'; sy = source.ny.';
    D = -(LOCAL_row_scale(Gx,sx)+LOCAL_row_scale(Gy,sy)).*wt;
    S = -P.*wt;
    nx = target.nx(index); ny = target.ny(index);
    Ttau = -(nx.*(Hxx.*sx+Hxy.*sy)+ ...
      ny.*(Hxy.*sx+Hyy.*sy)).*wt;
    Nzeta = -(nx.*Gx+ny.*Gy).*wt;
    value(index,:) = [D,S];
    normal(index,:) = [Ttau,Nzeta];
  end
  layer = struct('value',value,'normal',normal);
end

function out = LOCAL_row_scale(matrix,row)
  out = matrix.*row;
end

function curve = LOCAL_curve(flag_geom,axes,N)
  t = (0:N-1)'*2*pi/N;
  a = axes(1); b = axes(2);
  if strcmp(flag_geom,'circle'), b = a; end
  x = a*cos(t); y = b*sin(t);
  xt = -a*sin(t); yt = b*cos(t); speed = hypot(xt,yt);
  nx = yt./speed; ny = -xt./speed;
  weights = (2*pi/N)*speed;
  curve = struct('t',t,'x',x,'y',y,'xt',xt,'yt',yt, ...
    'speed',speed,'nx',nx,'ny',ny,'weights',weights);
end

function H = LOCAL_interp_density_map(H0,N)
  n0 = size(H0,1)/2;
  H = [interpft(H0(1:n0,:),N,1);interpft(H0(n0+1:end,:),N,1)];
end

%% ==================== Walls and local mass ====================
% These helpers use physical samples rather than a target Fourier norm.

function out = LOCAL_wall_jump(center,lead,q,propagation,model,levels,max_cells)
  records = cell(numel(levels),1);
  for j = 1:numel(levels)
    N = levels(j);
    center_maps = LOCAL_cell_wall_maps(center,model,N,N);
    lead_maps = LOCAL_cell_wall_maps(lead,model,N,N);
    records{j} = LOCAL_wall_level( ...
      center_maps,lead_maps,q,propagation,model,max_cells);
  end
  coarse = records{1}; fine = records{end};
  out = fine;
  out.levels = records;
  out.value_relative_change = LOCAL_relative_scalar( ...
    coarse.value_squared,fine.value_squared);
  out.normal_relative_change = LOCAL_relative_scalar( ...
    coarse.normal_squared,fine.normal_squared);
  out.physical_quadrature_remainder_certified = false;
end

function out = LOCAL_cell_wall_maps(cellmap,model,Nsource,Ntarget)
  shape = cellmap.i74_shape; axes = cellmap.i74_axes;
  source = LOCAL_curve(shape,axes,Nsource);
  H = LOCAL_interp_density_map([cellmap.H_L,cellmap.H_R],Nsource);
  y = -model.d/2+(0:Ntarget-1)'*model.d/Ntarget;
  left = struct('x',model.X_L*ones(Ntarget,1),'y',y, ...
    'nx',ones(Ntarget,1),'ny',zeros(Ntarget,1));
  right = struct('x',model.X_R*ones(Ntarget,1),'y',y, ...
    'nx',ones(Ntarget,1),'ny',zeros(Ntarget,1));
  layer_left = LOCAL_qp_layer(source,left,cellmap.i74_pars,cellmap.i74_proxy);
  layer_right = LOCAL_qp_layer(source,right,cellmap.i74_pars,cellmap.i74_proxy);
  geometry_left = struct('x',left.x,'y',left.y,'nx',left.nx,'ny',left.ny);
  geometry_right = struct('x',right.x,'y',right.y, ...
    'nx',right.nx,'ny',right.ny);
  [BLL,BLR] = bloch.incident_rhs(geometry_left,cellmap.channels, ...
    model.X_L,model.X_R);
  [BRL,BRR] = bloch.incident_rhs(geometry_right,cellmap.channels, ...
    model.X_L,model.X_R);
  Bleft = [BLL,BLR]; Bright = [BRL,BRR];
  out = struct('nodes',Ntarget,'y',y, ...
    'left_value',Bleft(1:Ntarget,:)+layer_left.value*H, ...
    'left_dx',Bleft(Ntarget+1:end,:)+layer_left.normal*H, ...
    'right_value',Bright(1:Ntarget,:)+layer_right.value*H, ...
    'right_dx',Bright(Ntarget+1:end,:)+layer_right.normal*H);
end

function out = LOCAL_wall_level(center,lead,q,propagation,model,max_cells)
  weight = model.d/center.nodes;
  input_plus = propagation.Gplus*propagation.cplus;
  input_minus = propagation.Gminus*propagation.cminus;
  value_left = lead.right_value*input_minus-center.left_value*q;
  value_right = lead.left_value*input_plus-center.right_value*q;
  normal_left = lead.right_dx*input_minus-center.left_dx*q;
  normal_right = center.right_dx*q-lead.left_dx*input_plus;
  interface_value = weight*(sum(abs(value_left).^2)+sum(abs(value_right).^2));
  interface_normal = weight*(sum(abs(normal_left).^2)+sum(abs(normal_right).^2));
  plus = propagation.cplus; minus = propagation.cminus;
  rows = repmat(struct('index',0,'value_squared',0,'normal_squared',0), ...
    max_cells,1);
  internal_value = 0; internal_normal = 0;
  for n = 0:max_cells-1
    plus_next = propagation.Pplus*plus;
    minus_next = propagation.Pminus*minus;
    current_plus = propagation.Gplus*plus;
    next_plus = propagation.Gplus*plus_next;
    current_minus = propagation.Gminus*minus;
    next_minus = propagation.Gminus*minus_next;
    vp = lead.left_value*next_plus-lead.right_value*current_plus;
    np = lead.right_dx*current_plus-lead.left_dx*next_plus;
    vm = lead.right_value*next_minus-lead.left_value*current_minus;
    nm = lead.right_dx*next_minus-lead.left_dx*current_minus;
    rows(n+1) = struct('index',n, ...
      'value_squared',real(weight*(sum(abs(vp).^2)+sum(abs(vm).^2))), ...
      'normal_squared',real(weight*(sum(abs(np).^2)+sum(abs(nm).^2))));
    internal_value = internal_value+rows(n+1).value_squared;
    internal_normal = internal_normal+rows(n+1).normal_squared;
    plus = plus_next; minus = minus_next;
  end
  plus_next = propagation.Pplus*plus;
  minus_next = propagation.Pminus*minus;
  vp = lead.left_value*(propagation.Gplus*plus_next)- ...
    lead.right_value*(propagation.Gplus*plus);
  np = lead.right_dx*(propagation.Gplus*plus)- ...
    lead.left_dx*(propagation.Gplus*plus_next);
  vm = lead.right_value*(propagation.Gminus*minus_next)- ...
    lead.left_value*(propagation.Gminus*minus);
  nm = lead.right_dx*(propagation.Gminus*minus_next)- ...
    lead.left_dx*(propagation.Gminus*minus);
  next_value = real(weight*(sum(abs(vp).^2)+sum(abs(vm).^2)));
  next_normal = real(weight*(sum(abs(np).^2)+sum(abs(nm).^2)));
  value_ratio = next_value/max(realmin,rows(end).value_squared);
  normal_ratio = next_normal/max(realmin,rows(end).normal_squared);
  [tail_value,value_tail_available] = ...
    LOCAL_geometric_tail(next_value,value_ratio);
  [tail_normal,normal_tail_available] = ...
    LOCAL_geometric_tail(next_normal,normal_ratio);
  out = struct('nodes',center.nodes,'y',center.y, ...
    'center_lead_value_left',value_left, ...
    'center_lead_value_right',value_right, ...
    'center_lead_dx_left',normal_left, ...
    'center_lead_dx_right',normal_right, ...
    'center_lead_value_squared',real(interface_value), ...
    'center_lead_normal_squared',real(interface_normal), ...
    'internal_rows',rows,'internal_value_squared',internal_value, ...
    'internal_normal_squared',internal_normal, ...
    'tail_value_squared_candidate',tail_value, ...
    'tail_normal_squared_candidate',tail_normal, ...
    'tail_value_ratio',value_ratio,'tail_normal_ratio',normal_ratio, ...
    'value_squared',real(interface_value)+internal_value+tail_value, ...
    'normal_squared',real(interface_normal)+internal_normal+tail_normal, ...
    'tail_candidate_available', ...
      value_tail_available && normal_tail_available, ...
    'tail_certified',false);
end

function out = LOCAL_mass_diagnostic(center,density,q,beta_m,gamma, ...
    model,Nr,Ntheta,Nsource)
  disk_center = [3/8;0]; radius = 1/16;
  radial = radius*sqrt(((1:Nr)-0.5)/Nr);
  theta = (0:Ntheta-1)*2*pi/Ntheta;
  [rr,tt] = ndgrid(radial,theta);
  targets = disk_center+[rr(:).'.*cos(tt(:).');rr(:).'.*sin(tt(:).')];
  [value,grad] = LOCAL_center_field(center,density,q,beta_m,gamma, ...
    model,targets,Nsource);
  area = pi*radius^2;
  quadrature_norm = sqrt(area*mean(abs(value).^2));
  center_target = disk_center;
  [value_center,~] = LOCAL_center_field(center,density,q,beta_m,gamma, ...
    model,center_target,Nsource);
  gradient_samples = sqrt(sum(abs(grad).^2,1));
  sampled_gradient_max = max(gradient_samples);
  cone_point_margin = max(abs(value_center)-radius*sampled_gradient_max,0);
  cone_candidate = sqrt(pi)*radius*cone_point_margin;
  out = struct('center',disk_center,'radius',radius, ...
    'radial_nodes',Nr,'angular_nodes',Ntheta, ...
    'quadrature_norm',quadrature_norm, ...
    'center_value_abs',abs(value_center), ...
    'sampled_gradient_max',sampled_gradient_max, ...
    'cone_point_margin',cone_point_margin, ...
    'cone_candidate',cone_candidate, ...
    'one_sided_certified',false,'sample_values',value, ...
    'sample_gradient',grad);
end

function [value,grad] = LOCAL_center_field(center,density,q,beta_m,gamma, ...
    model,targets,Nsource)
  source = LOCAL_curve('ellipse',model.axes,Nsource);
  n0 = numel(density)/2;
  eta = [interpft(density(1:n0),Nsource); ...
    interpft(density(n0+1:end),Nsource)];
  tau = eta(1:Nsource); zeta = eta(Nsource+1:end);
  value = zeros(1,size(targets,2)); grad = zeros(2,size(targets,2));
  batch = 32;
  src = [source.x.';source.y.'];
  for first = 1:batch:size(targets,2)
    index = first:min(first+batch-1,size(targets,2));
    trg = targets(:,index);
    [P,Gx,Gy,Hxx,Hxy,Hyy] = ...
      kernel.qpgreen_mfs_pairmat(src,trg,center.i74_pars,center.i74_proxy);
    wt = source.weights; nx = source.nx; ny = source.ny;
    charge_x = nx.*wt.*tau; charge_y = ny.*wt.*tau;
    charge_z = wt.*zeta;
    layer_value = -(Gx*charge_x+Gy*charge_y)-P*charge_z;
    layer_x = -(Hxx*charge_x+Hxy*charge_y)-Gx*charge_z;
    layer_y = -(Hxy*charge_x+Hyy*charge_y)-Gy*charge_z;
    [incident,incident_grad] = LOCAL_incident(q,beta_m,gamma,model,trg);
    value(index) = incident+layer_value.';
    grad(:,index) = incident_grad+[layer_x.';layer_y.'];
  end
end

function [value,grad] = LOCAL_incident(q,beta_m,gamma,model,target)
  K = numel(gamma); qL = q(1:K); qR = q(K+1:end);
  x = target(1,:).'; y = target(2,:).';
  psi = exp(1i*y*beta_m.')/sqrt(model.d);
  left = exp(1i*(x-model.X_L)*gamma.').*psi;
  right = exp(-1i*(x-model.X_R)*gamma.').*psi;
  value = (left*qL+right*qR).';
  gradx = (left*(1i*gamma.*qL)+right*(-1i*gamma.*qR)).';
  grady = ((left+0).* (1i*beta_m.'))*qL+ ...
    ((right+0).* (1i*beta_m.'))*qR;
  grad = [gradx;grady.'];
end

