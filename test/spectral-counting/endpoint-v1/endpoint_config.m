function config = endpoint_config(p)
%ENDPOINT_CONFIG Fixed g12 geometry and two-endpoint inertia parameters.
% Purpose: Freeze the current physical model and two quadrature rules.
% Based on: refine_i102_config.m, model, g12 mesh, location and DtN gates.
% Main changes: one order, mu endpoints, no root or field recovery, 2 GiB cap.
% Input: p is 2 (minimum run) or 3 (optional order comparison).
% Output: explicit scientific and runtime configuration; no external reads.
  assert(isscalar(p) && any(p==[2,3]),'endpoint:Order','Use P2 or P3.');
  config.schema = 'ENDPOINT_INERTIA_V1';
  config.mode = 'formal'; config.group = 'g12'; config.orders = p;
  % Spectral parameters are mu=k^2, not wavenumbers.
  config.mu = [2.40,2.46];
  config.model = struct('beta',0.5,'d',1,'L',1,'star_scale',1, ...
    'rho_center',4,'rho_negative',17,'rho_positive',17,'rho_background',1, ...
    'a_negative',0.12,'a_positive',0.20,'radius',0.2);
  config.mesh = struct('subdivisions',12,'interface_segments',80);
  config.mesh_rules = struct('ring_scale',0.15,'coordinate_tolerance',1e-11, ...
    'interface_clearance_fraction',0.30,'ring_clearance_fraction',0.10, ...
    'det_ratio_max',20,'repair_rounds',3,'curve_samples',33,'repair_seconds',30);
  config.mesh_rules.flip = struct('max_checks',32,'max_flips',16, ...
    'convex_factor',1e-12,'crossing_tolerance',1e-9);
  config.rules = struct('name',{'primary','check'},'volume_order',{12,16}, ...
    'band_subsegments',{2,4},'band_points',{8,12});
  config.edge_tol = 1e-10;
  config.location = struct('newton_steps',30,'halvings',8,'residual',1e-12, ...
    'barycentric_min',-1e-10,'aabb_pad',1e-12,'batch',20000);
  config.gates = struct('cell_backward',1e-10,'cell_condest',1e12, ...
    'qz_degenerate_factor',100,'unit_gap',1e-6,'z0_rcond',1e-10, ...
    'invariance',1e-8,'riccati',1e-8,'dtn_hermitian',1e-8, ...
    'dtn_consistency',1e-8,'consistency_rcond',1e-12,'pairing_band',1e6, ...
    'matrix_hermitian',1e-10,'qp_defect',1e-12,'h_hermitian',1e-8);
  config.solver = struct('rhs_block',32,'lu_fill_allowance',4);
  % A pivot within tolerance is unresolved, not an asserted exact zero.
  config.inertia = struct('pivot_relative',1e-10,'factor_residual',1e-10, ...
    'near_eigenvalues',6,'eigs_tol',1e-10,'eigs_maxit',300);
  config.resources = struct('threads',4,'rss_bytes',2^31, ...
    'internal_gate_bytes',2.0e9,'soft_seconds',1800,'hard_seconds',2400);
end
