function out = LOCAL_audit(model,cfg,point,ev,prop,density, ...
    lead_plus,lead_minus,center_actions,lead_actions,center_jumps, ...
    lead_sums,walls,mass,components,epsilon_num,node_ledger)
  config = pipeline_i8_config();
  K = cfg.K; q = ev.q;
  q_density = ev.center.H_L*q(1:K)+ev.center.H_R*q(K+1:end);
  metric = ev.matching.summary;
  defects = struct( ...
    'point_metric',max(abs([point.adef_sigma-metric.adef_sigma, ...
      point.adef_ratio-metric.adef_ratio, ...
      point.aphys_sigma-metric.aphys_sigma, ...
      point.aphys_ratio-metric.aphys_ratio])), ...
    'q_norm',abs(norm(q)-1), ...
    'center_density',norm(density-q_density)/max(1,norm(density)), ...
    'lead_plus',norm(lead_plus- ...
      [ev.lead.H_L,ev.lead.H_R]*prop.Gplus,'fro')/ ...
      max(1,norm(lead_plus,'fro')), ...
    'lead_minus',norm(lead_minus- ...
      [ev.lead.H_L,ev.lead.H_R]*prop.Gminus,'fro')/ ...
      max(1,norm(lead_minus,'fro')), ...
    'plus_trace',prop.plus_coordinate_residual, ...
    'minus_trace',prop.minus_coordinate_residual, ...
    'plus_recurrence',prop.plus_recurrence_residual, ...
    'minus_recurrence',prop.minus_recurrence_residual, ...
    'center_density_solve',LOCAL_density_residual(ev.center), ...
    'lead_density_solve',LOCAL_density_residual(ev.lead), ...
    'center_scale',center_actions{1}.scale_roundtrip_defect, ...
    'lead_scale',lead_actions{1}.scale_roundtrip_defect, ...
    'lead_raw',lead_actions{1}.raw_matrix_identity_defect, ...
    'node_dimensions',double(~node_ledger.pass), ...
    'native_flags',max(double([ ...
      center_actions{1}.native_grid,lead_actions{1}.native_grid] ~= [ ...
      config.evaluation.material_nodes==cfg.ntot_center, ...
      config.evaluation.material_nodes==cfg.ntot_lead])), ...
    'center_jump_value',LOCAL_relative( ...
      center_jumps{1}.value,center_actions{1}.signed_value), ...
    'center_jump_normal',LOCAL_relative( ...
      center_jumps{1}.normal,center_actions{1}.signed_normal), ...
    'epsilon_identity',abs(epsilon_num^2-(components.normal_squared+ ...
      components.value_squared/model.d^2)));
  numeric = cell2mat(struct2cell(defects)).';
  finite_components = all(cellfun(@(x) ...
    (isnumeric(x) || islogical(x)) && isscalar(x) && isfinite(double(x)), ...
    struct2cell(components)));
  out = struct('schema','EPOST_I8_EST_V1_AUDIT','defects',defects, ...
    'maximum_defect',max(numeric),'tolerance',config.evaluation.audit_tolerance, ...
    'finite_components',finite_components, ...
    'mass_positive',mass{1}.quadrature_norm>0, ...
    'material_nodes',center_actions{1}.source_nodes, ...
    'wall_nodes',walls{1}.nodes, ...
    'disk_nodes',[mass{1}.radial_nodes,mass{1}.angular_nodes], ...
    'lead_tail_available',lead_sums{1}.tail_candidate_available, ...
    'wall_tail_available',walls{1}.tail_candidate_available, ...
    'all_pass',max(numeric)<=config.evaluation.audit_tolerance && finite_components && ...
      mass{1}.quadrature_norm>0);
end

%% ==================== Resource-safe kernel helpers ====================
% These helpers preserve the reviewed I8 raw-field conventions.

function value = LOCAL_relative(a,b)
  value=norm(a-b,'fro')/max(1,norm(b,'fro'));
end

function value = LOCAL_rel(a,b)
  value=abs(a-b)/max([realmin,abs(a),abs(b)]);
end

function [pot,grad,hess] = LOCAL_h2d_chunked_public( ...
    wavek,sources,charge,targ)
  callback_timer = tic;
  nt = size(targ,2); pot = zeros(1,nt); grad = zeros(2,nt); hess = zeros(3,nt);
  config = pipeline_i8_config(); target_batch = config.backend.direct_target_batch;
  for first = 1:target_batch:nt
    index = first:min(first+target_batch-1,nt);
    [pot(:,index),grad(:,index),hess(:,index)] = ...
      kernel.h2d_directch(wavek,sources,charge,targ(:,index));
  end
  LOCAL_proxy_ledger('append',struct('method','direct', ...
    'ns',size(sources,2),'nt',nt,'batches',ceil(nt/target_batch), ...
    'ier',0,'seconds',toc(callback_timer)));
end

