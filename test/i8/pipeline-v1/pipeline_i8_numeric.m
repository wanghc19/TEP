%% ==================== Evaluator comparison and coverage ====================
% These helpers assemble identical scalar formulas and record smooth-proxy use.

function out = LOCAL_level_result(center,lead,wall,mass,model,geometry, ...
    mu_num,Cnum,N,center_native,lead_native)
  components = LOCAL_components(center,lead,wall,mass);
  epsilon_num = NaN; Q = NaN; denominator = NaN; Rnum = NaN;
  status = 'FINITE_PREFIX_DIAGNOSTIC';
  if components.complete && geometry.pass
    epsilon_num = sqrt(max(0,components.normal_squared+ ...
      components.value_squared/model.d^2));
    Q = Cnum*epsilon_num;
    denominator = mass.quadrature_norm-Q;
    status = 'NO_FINITE_RNUM';
    if isfinite(denominator) && denominator > 0
      Rnum = 2*mu_num*Q/denominator;
      if isfinite(Rnum), status = 'UNCERTIFIED_RNUM'; end
    end
  end
  out = struct('nodes',N,'center_material_native',center_native, ...
    'lead_material_native',lead_native,'components',components, ...
    'epsilon_num',epsilon_num,'U_num',mass.quadrature_norm,'Cnum',Cnum, ...
    'Q',Q,'denominator',denominator,'Rnum',Rnum,'status',status);
end

function [pot,grad,hess] = LOCAL_h2d_fmm(wavek,sources,charge,targ)
%LOCAL_H2D_FMM The reviewed fmm-v1 charge-only proxy convention, unchanged.
  callback_timer = tic; nt = size(targ,2);
  srcinfo = struct('sources',sources,'charges',reshape(charge,1,[]));
  config = pipeline_i8_config();
  [U,ier] = hfmm2d(config.backend.fmm_eps,wavek,srcinfo,0,targ,3);
  if ~isscalar(ier) || ier ~= 0
    error('i84b:FMMError','FMM2D returned ier=%g.',ier);
  end
  pot = reshape(U.pottarg,1,nt);
  grad = reshape(U.gradtarg,2,nt);
  hess = reshape(U.hesstarg,3,nt);
  if any(~isfinite(pot),'all') || any(~isfinite(grad),'all') || any(~isfinite(hess),'all')
    error('i84b:FMMNonfinite','FMM2D returned nonfinite smooth-proxy fields.');
  end
  LOCAL_proxy_ledger('append',struct('method','fmm','ns',size(sources,2), ...
    'nt',nt,'batches',1,'ier',ier,'seconds',toc(callback_timer)));
end

function value = LOCAL_proxy_ledger(action,varargin)
  persistent records stage
  value = [];
  switch action
    case 'reset'
      records = struct('method',{},'ns',{},'nt',{},'batches',{}, ...
        'ier',{},'seconds',{},'stage',{}); stage = '';
    case 'stage'
      stage = varargin{1};
    case 'append'
      record = varargin{1}; record.stage = stage;
      records(end+1,1) = record;
    case 'get'
      value = records;
  end
end

function LOCAL_write_json(filename,value)
  fid = fopen(filename,'w');
  if fid < 0, error('i84b:Output','Cannot write %s.',filename); end
  closer = onCleanup(@() fclose(fid)); %#ok<NASGU>
  fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));
end
