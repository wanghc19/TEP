function audit = audit_i8(result,evidence)
%AUDIT_I8 Independently recompose the fresh I8.3 frozen-field estimate.
% Purpose:
%   Audit one fresh estimate_i8 result from saved primitive matrices, density
%   coordinates, sampled wall maps, and disk values without another BIE solve.
% Input:
%   result   - Fresh estimate_i8 result structure.
%   evidence - Fresh estimate_i8 primitive-evidence structure.
% Output:
%   audit - Coverage, normalized defects, and an independent pass verdict.
% Main algorithm:
%   Rebuild matching and propagation from scattering/QZ blocks, recover the
%   physical center density, apply each saved scaled material matrix in raw
%   density coordinates, reconstruct all finite-cell and tail terms, assemble
%   the physical wall jumps, and recompute mass, Cnum, denominator, and Rnum.
% Notes:
%   This checks the actual saved finite matrices and samples. It is neither a
%   fresh field evaluation nor a certified quadrature or spectral bound.

  tolerance = 1e-10;
  defects = struct;
  model = result.model;
  cfg = result.config;
  ev = evidence.base;
  K = cfg.K;
  warning_guard = LOCAL_warning_guard(); %#ok<NASGU>

  contract = result.model.khat == 1.7562818500073463 && ...
    result.point.k == result.model.khat && ismember(cfg.ntot,[256,384]) && ...
    cfg.nside == 160 && cfg.ntop == 160 && cfg.nproxy == 80 && ...
    cfg.mpw == 32 && cfg.M == 48 && cfg.K == 97 && ...
    isequal(result.evaluation.material_nodes,[512,768]) && ...
    isequal(result.evaluation.wall_nodes,[512,768]) && ...
    isequal(result.evaluation.disk_grid,[16,32;32,64]) && ...
    isequal(result.evaluation.disk_shift,[0,0.5]) && ...
    result.evaluation.lead_cells == 40 && model.beta == 0.5 && ...
    model.d == 1 && model.R == 0.2 && model.rho_center == 2 && ...
    model.rho_lead == 17 && model.X_L == -0.5 && model.X_R == 0.5 && ...
    model.star_scale == sqrt(0.04/0.0618);

  % --- stage 1: rebuild matching and the frozen physical density ---
  Ap = ev.Zplus(1:K,:); Bp = ev.Zplus(K+1:end,:);
  Am = ev.Zminus(1:K,:); Bm = ev.Zminus(K+1:end,:);
  G = diag(ev.gamma); I = eye(K);
  Lp = ((Ap+Bp).'\(1i*G*(Ap-Bp)).').';
  Lm = ((Am+Bm).'\(-1i*G*(Am-Bm)).').';
  T = [I+ev.center.R_L,ev.center.T_RL; ...
    ev.center.T_LR,I+ev.center.R_R];
  N0 = [1i*G*(ev.center.R_L-I),1i*G*ev.center.T_RL; ...
    1i*G*ev.center.T_LR,1i*G*(ev.center.R_R-I)];
  L = blkdiag(Lm,Lp);
  Adef = [(1i*G-Lm)*ev.center.R_L-(1i*G+Lm), ...
    (1i*G-Lm)*ev.center.T_RL; ...
    (1i*G-Lp)*ev.center.T_LR, ...
    (1i*G-Lp)*ev.center.R_R-(1i*G+Lp)];
  b = sqrt(1+abs(ev.beta_m).^2);
  rowwt = repmat(1./sqrt(b),2,1);
  colwt = repmat(1./sqrt(b+abs(ev.gamma).^2./b),2,1);
  Aphys = rowwt.*Adef.*colwt.';
  [~,~,V] = svd(Aphys,'econ');
  q_audit = colwt.*V(:,end); q_audit = q_audit/norm(q_audit);
  q = ev.q;
  center_density = ev.center.H_L*q(1:K)+ev.center.H_R*q(K+1:end);
  adef_s = svd(Adef,'econ'); aphys_s = svd(Aphys,'econ');
  metrics = [adef_s(end),adef_s(end)/adef_s(1), ...
    aphys_s(end),aphys_s(end)/aphys_s(1)];
  saved_metrics = [result.point.adef_sigma,result.point.adef_ratio, ...
    result.point.aphys_sigma,result.point.aphys_ratio];
  defects.T = LOCAL_diff(T,ev.matching.T);
  defects.N0 = LOCAL_diff(N0,ev.matching.N0);
  defects.L = LOCAL_diff(L,ev.matching.L);
  defects.Adef = LOCAL_diff(Adef,ev.matching.Adef);
  defects.Adef_identity = LOCAL_diff(Adef,N0-L*T);
  defects.Aphys = LOCAL_diff(Aphys,ev.matching.Aphys);
  defects.weights = max(LOCAL_diff(rowwt,ev.matching.row_weight), ...
    LOCAL_diff(colwt,ev.matching.column_weight));
  defects.q_subspace = abs(1-LOCAL_overlap(q_audit,q));
  defects.q_norm = abs(norm(q)-1);
  defects.metrics = max(abs(metrics-saved_metrics));
  defects.center_density = LOCAL_diff(center_density,evidence.center_density);
  defects.center_density_solve = LOCAL_density_solve(ev.center);
  defects.lead_density_solve = LOCAL_density_solve(ev.lead);

  % --- stage 2: rebuild both lead propagation maps and coordinates ---
  Pplus = (ev.pencil.B*ev.Zplus)\(ev.pencil.A*ev.Zplus);
  Pminus = (ev.pencil.A*ev.Zminus)\(ev.pencil.B*ev.Zminus);
  trace = T*q;
  cplus = (Ap+Bp)\trace(K+1:end);
  cminus = (Am+Bm)\trace(1:K);
  Gplus = [Ap;Bp*Pplus];
  Gminus = [Am*Pminus;Bm];
  prop = evidence.propagation;
  defects.Pplus = LOCAL_diff(Pplus,prop.Pplus);
  defects.Pminus = LOCAL_diff(Pminus,prop.Pminus);
  defects.cplus = LOCAL_diff(cplus,prop.cplus);
  defects.cminus = LOCAL_diff(cminus,prop.cminus);
  defects.Gplus = LOCAL_diff(Gplus,prop.Gplus);
  defects.Gminus = LOCAL_diff(Gminus,prop.Gminus);
  defects.lead_plus_density = LOCAL_diff( ...
    [ev.lead.H_L,ev.lead.H_R]*Gplus,evidence.lead_plus);
  defects.lead_minus_density = LOCAL_diff( ...
    [ev.lead.H_L,ev.lead.H_R]*Gminus,evidence.lead_minus);
  defects.plus_pencil = LOCAL_diff(ev.pencil.A*ev.Zplus, ...
    ev.pencil.B*ev.Zplus*Pplus);
  defects.minus_pencil = LOCAL_diff(ev.pencil.B*ev.Zminus, ...
    ev.pencil.A*ev.Zminus*Pminus);
  defects.plus_trace = LOCAL_diff((Ap+Bp)*cplus,trace(K+1:end));
  defects.minus_trace = LOCAL_diff((Am+Bm)*cminus,trace(1:K));

  % --- stage 3: apply saved raw material matrices on both grids ---
  nlevels = numel(evidence.center_actions);
  reconstructed = repmat(struct('components',struct(), ...
    'epsilon_num',NaN,'U_num',NaN,'Cnum',NaN, ...
    'denominator',NaN,'Rnum',NaN),nlevels,1);
  for level = 1:nlevels
    ca = evidence.center_actions{level};
    la = evidence.lead_actions{level};
    N = ca.source_nodes;
    eta = LOCAL_interp_density(evidence.center_density,N);
    raw_center = (ca.A_scaled*(ca.density_scale.*eta))./ ...
      ca.density_scale+ca.Bq;
    center_value = raw_center(1:N);
    center_normal = -raw_center(N+1:end);
    center_value_sq = real(sum(ca.weights.*abs(center_value).^2));
    center_normal_sq = real(sum(ca.weights.*abs(center_normal).^2));
    defects.(sprintf('center_density_%d',level)) = ...
      LOCAL_diff(eta,ca.density);
    defects.(sprintf('center_raw_%d',level)) = ...
      LOCAL_diff(raw_center,ca.raw_action);
    defects.(sprintf('center_sign_%d',level)) = max( ...
      LOCAL_diff(center_value,ca.signed_value), ...
      LOCAL_diff(center_normal,ca.signed_normal));

    density_map = LOCAL_interp_density( ...
      [ev.lead.H_L,ev.lead.H_R],la.source_nodes);
    raw_lead = (la.A_scaled*(la.density_scale.*density_map))./ ...
      la.density_scale+la.B;
    lead_value_action = raw_lead(1:la.source_nodes,:);
    lead_normal_action = -raw_lead(la.source_nodes+1:end,:);
    defects.(sprintf('lead_density_%d',level)) = ...
      LOCAL_diff(density_map,la.density_map);
    defects.(sprintf('lead_value_action_%d',level)) = ...
      LOCAL_diff(lead_value_action,la.signed_value_action);
    defects.(sprintf('lead_normal_action_%d',level)) = ...
      LOCAL_diff(lead_normal_action,la.signed_normal_action);

    [lead_rebuilt,lead_rows] = LOCAL_lead_sum( ...
      lead_value_action,lead_normal_action,la.weights, ...
      Gplus,Gminus,Pplus,Pminus,cplus,cminus, ...
      result.evaluation.lead_cells);
    saved_lead = evidence.lead_sums{level};
    defects.(sprintf('lead_rows_%d',level)) = ...
      LOCAL_rows_diff(lead_rows,saved_lead.cells);
    defects.(sprintf('lead_sum_%d',level)) = max([ ...
      LOCAL_nan_diff(lead_rebuilt.finite_value, ...
        saved_lead.finite_value_squared), ...
      LOCAL_nan_diff(lead_rebuilt.finite_normal, ...
        saved_lead.finite_normal_squared), ...
      LOCAL_nan_diff(lead_rebuilt.tail_value, ...
        saved_lead.tail_value_squared_candidate), ...
      LOCAL_nan_diff(lead_rebuilt.tail_normal, ...
        saved_lead.tail_normal_squared_candidate), ...
      LOCAL_nan_diff(lead_rebuilt.value,saved_lead.value_squared), ...
      LOCAL_nan_diff(lead_rebuilt.normal,saved_lead.normal_squared)]);
    defects.(sprintf('lead_tail_%d',level)) = max(abs([ ...
      lead_rebuilt.value_ratio-saved_lead.tail_value_ratio, ...
      lead_rebuilt.normal_ratio-saved_lead.tail_normal_ratio]));

    % --- stage 4: rebuild every center/lead and internal wall pair ---
    cm = evidence.center_maps{level}; lm = evidence.lead_maps{level};
    [wall_rebuilt,wall_rows,wall_vectors] = LOCAL_wall_sum( ...
      cm,lm,Gplus,Gminus,Pplus,Pminus,cplus,cminus,model, ...
      result.evaluation.lead_cells);
    saved_wall = evidence.wall_levels{level};
    defects.(sprintf('wall_vectors_%d',level)) = max([ ...
      LOCAL_diff(wall_vectors.value_left, ...
        saved_wall.center_lead_value_left), ...
      LOCAL_diff(wall_vectors.value_right, ...
        saved_wall.center_lead_value_right), ...
      LOCAL_diff(wall_vectors.normal_left, ...
        saved_wall.center_lead_dx_left), ...
      LOCAL_diff(wall_vectors.normal_right, ...
        saved_wall.center_lead_dx_right)]);
    defects.(sprintf('wall_rows_%d',level)) = ...
      LOCAL_rows_diff(wall_rows,saved_wall.internal_rows);
    defects.(sprintf('wall_sum_%d',level)) = max([ ...
      LOCAL_nan_diff(wall_rebuilt.center_value, ...
        saved_wall.center_lead_value_squared), ...
      LOCAL_nan_diff(wall_rebuilt.center_normal, ...
        saved_wall.center_lead_normal_squared), ...
      LOCAL_nan_diff(wall_rebuilt.internal_value, ...
        saved_wall.internal_value_squared), ...
      LOCAL_nan_diff(wall_rebuilt.internal_normal, ...
        saved_wall.internal_normal_squared), ...
      LOCAL_nan_diff(wall_rebuilt.tail_value, ...
        saved_wall.tail_value_squared_candidate), ...
      LOCAL_nan_diff(wall_rebuilt.tail_normal, ...
        saved_wall.tail_normal_squared_candidate), ...
      LOCAL_nan_diff(wall_rebuilt.value,saved_wall.value_squared), ...
      LOCAL_nan_diff(wall_rebuilt.normal,saved_wall.normal_squared)]);
    defects.(sprintf('wall_tail_%d',level)) = max(abs([ ...
      wall_rebuilt.value_ratio-saved_wall.tail_value_ratio, ...
      wall_rebuilt.normal_ratio-saved_wall.tail_normal_ratio]));

    % --- stage 5: recompose mass, components, and scalar estimate ---
    mass = evidence.mass{level};
    U = sqrt(pi*mass.radius^2*mean(abs(mass.sample_values).^2));
    components = LOCAL_components(center_value_sq,center_normal_sq, ...
      lead_rebuilt,wall_rebuilt,U);
    epsilon_num = sqrt(max(0,components.normal_squared+ ...
      components.value_squared/model.d^2));
    mu = model.khat*model.khat;
    h = model.collar_h; theta = result.geometry.theta;
    c0 = 1/(theta*h); c1 = h/(2*theta);
    Cnum = sqrt(c0/(model.rho_exterior*mu^2)+ ...
      (c1+c0)/(4*mu)+c1*model.rho_lead);
    denominator = U-Cnum*epsilon_num;
    Rnum = NaN;
    if components.complete && denominator>0
      Rnum = 2*mu*Cnum*epsilon_num/denominator;
    end
    reconstructed(level) = struct('components',components, ...
      'epsilon_num',epsilon_num,'U_num',U,'Cnum',Cnum, ...
      'denominator',denominator,'Rnum',Rnum);
    saved_level = result.levels(level);
    defects.(sprintf('mass_%d',level)) = abs(U-saved_level.U_num);
    defects.(sprintf('components_%d',level)) = ...
      LOCAL_component_diff(components,saved_level.components);
    defects.(sprintf('scalars_%d',level)) = max([ ...
      LOCAL_nan_diff(epsilon_num,saved_level.epsilon_num), ...
      LOCAL_nan_diff(Cnum,saved_level.Cnum), ...
      LOCAL_nan_diff(denominator,saved_level.denominator), ...
      LOCAL_nan_diff(Rnum,saved_level.Rnum)]);
  end

  fine = reconstructed(end);
  defects.final_scalars = max([ ...
    LOCAL_nan_diff(fine.epsilon_num,result.epsilon_num), ...
    LOCAL_nan_diff(fine.U_num,result.U_num), ...
    LOCAL_nan_diff(fine.Cnum,result.Cnum), ...
    LOCAL_nan_diff(fine.denominator,result.denominator), ...
    LOCAL_nan_diff(fine.Rnum,result.Rnum)]);
  expected_status = LOCAL_status(fine.components,evidence.audit.all_pass, ...
    result.geometry.pass,fine.denominator);
  status_consistent = strcmp(expected_status,result.status);
  values = cell2mat(struct2cell(defects));
  coverage = struct('levels',nlevels,'center_actions',nlevels, ...
    'lead_cells',2*nlevels*result.evaluation.lead_cells, ...
    'internal_walls',2*nlevels*result.evaluation.lead_cells, ...
    'tail_pairs',4*nlevels,'mass_grids',nlevels);
  clear warning_guard;
  audit = struct('schema','EPOST_I8_EST_V1_INDEPENDENT_AUDIT', ...
    'ntot',cfg.ntot,'baseline_contract',cfg.ntot==256, ...
    'contract_pass',contract,'status_expected',expected_status, ...
    'status_consistent',status_consistent,'defects',defects, ...
    'maximum_defect',max(values),'tolerance',tolerance, ...
    'coverage',coverage,'reconstructed',{reconstructed}, ...
    'all_pass',contract && status_consistent && ...
      all(isfinite(values)) && all(values<=tolerance), ...
    'certified',false);
end

%% ==================== Frozen-density interpolation ====================
% These helpers rebuild stored physical density maps without a new solve.

function H = LOCAL_interp_density(H0,N)
  n0 = size(H0,1)/2;
  H = [interpft(H0(1:n0,:),N,1);interpft(H0(n0+1:end,:),N,1)];
end

%% ==================== Material and wall ledgers ====================
% These helpers independently propagate and sum every retained physical term.

function [out,rows] = LOCAL_lead_sum(Av,An,w,Gp,Gm,Pp,Pm,cp,cm,ncells)
  rows = zeros(ncells,2); finite_value = 0; finite_normal = 0;
  for n = 1:ncells
    xp = Gp*cp; xm = Gm*cm;
    v = Av*xp; vn = Av*xm; j = An*xp; jn = An*xm;
    rows(n,:) = [real(sum(w.*(abs(v).^2+abs(vn).^2))), ...
      real(sum(w.*(abs(j).^2+abs(jn).^2)))];
    finite_value = finite_value+rows(n,1);
    finite_normal = finite_normal+rows(n,2);
    cp = Pp*cp; cm = Pm*cm;
  end
  xp = Gp*cp; xm = Gm*cm;
  next_value = real(sum(w.*(abs(Av*xp).^2+abs(Av*xm).^2)));
  next_normal = real(sum(w.*(abs(An*xp).^2+abs(An*xm).^2)));
  value_ratio = next_value/max(realmin,rows(end,1));
  normal_ratio = next_normal/max(realmin,rows(end,2));
  [tail_value,vok] = LOCAL_tail(next_value,value_ratio);
  [tail_normal,nok] = LOCAL_tail(next_normal,normal_ratio);
  out = struct('finite_value',finite_value,'finite_normal',finite_normal, ...
    'tail_value',tail_value,'tail_normal',tail_normal, ...
    'value_ratio',value_ratio,'normal_ratio',normal_ratio, ...
    'value',finite_value+tail_value,'normal',finite_normal+tail_normal, ...
    'complete',vok && nok);
end

function [out,rows,vectors] = LOCAL_wall_sum( ...
    center,lead,Gp,Gm,Pp,Pm,cp,cm,model,ncells)
  weight = model.d/center.nodes;
  xp = Gp*cp; xm = Gm*cm;
  value_left = lead.right_value*xm-center.left_value;
  value_right = lead.left_value*xp-center.right_value;
  normal_left = lead.right_dx*xm-center.left_dx;
  normal_right = center.right_dx-lead.left_dx*xp;
  center_value = real(weight*(sum(abs(value_left).^2)+ ...
    sum(abs(value_right).^2)));
  center_normal = real(weight*(sum(abs(normal_left).^2)+ ...
    sum(abs(normal_right).^2)));
  rows = zeros(ncells,2); internal_value = 0; internal_normal = 0;
  for n = 1:ncells
    cp_next = Pp*cp; cm_next = Pm*cm;
    xp = Gp*cp; xp_next = Gp*cp_next;
    xm = Gm*cm; xm_next = Gm*cm_next;
    vp = lead.left_value*xp_next-lead.right_value*xp;
    np = lead.right_dx*xp-lead.left_dx*xp_next;
    vm = lead.right_value*xm_next-lead.left_value*xm;
    nm = lead.right_dx*xm_next-lead.left_dx*xm;
    rows(n,:) = real(weight*[sum(abs(vp).^2)+sum(abs(vm).^2), ...
      sum(abs(np).^2)+sum(abs(nm).^2)]);
    internal_value = internal_value+rows(n,1);
    internal_normal = internal_normal+rows(n,2);
    cp = cp_next; cm = cm_next;
  end
  cp_next = Pp*cp; cm_next = Pm*cm;
  xp = Gp*cp; xp_next = Gp*cp_next;
  xm = Gm*cm; xm_next = Gm*cm_next;
  next_value = real(weight*(sum(abs(lead.left_value*xp_next- ...
    lead.right_value*xp).^2)+sum(abs(lead.right_value*xm_next- ...
    lead.left_value*xm).^2)));
  next_normal = real(weight*(sum(abs(lead.right_dx*xp- ...
    lead.left_dx*xp_next).^2)+sum(abs(lead.right_dx*xm_next- ...
    lead.left_dx*xm).^2)));
  value_ratio = next_value/max(realmin,rows(end,1));
  normal_ratio = next_normal/max(realmin,rows(end,2));
  [tail_value,vok] = LOCAL_tail(next_value,value_ratio);
  [tail_normal,nok] = LOCAL_tail(next_normal,normal_ratio);
  out = struct('center_value',center_value,'center_normal',center_normal, ...
    'internal_value',internal_value,'internal_normal',internal_normal, ...
    'tail_value',tail_value,'tail_normal',tail_normal, ...
    'value_ratio',value_ratio,'normal_ratio',normal_ratio, ...
    'value',center_value+internal_value+tail_value, ...
    'normal',center_normal+internal_normal+tail_normal, ...
    'complete',vok && nok);
  vectors = struct('value_left',value_left,'value_right',value_right, ...
    'normal_left',normal_left,'normal_right',normal_right);
end

function [value,available] = LOCAL_tail(next,ratio)
  available = isfinite(next) && isfinite(ratio) && ratio>=0 && ratio<1;
  if available, value = next/(1-ratio); else, value = NaN; end
end

function c = LOCAL_components(cv,cn,lead,wall,U)
  c = struct('center_value_squared',cv,'center_normal_squared',cn, ...
    'lead_finite_value_squared',lead.finite_value, ...
    'lead_finite_normal_squared',lead.finite_normal, ...
    'lead_tail_value_squared',lead.tail_value, ...
    'lead_tail_normal_squared',lead.tail_normal, ...
    'lead_tail_value_ratio',lead.value_ratio, ...
    'lead_tail_normal_ratio',lead.normal_ratio, ...
    'wall_center_value_squared',wall.center_value, ...
    'wall_center_normal_squared',wall.center_normal, ...
    'wall_internal_value_squared',wall.internal_value, ...
    'wall_internal_normal_squared',wall.internal_normal, ...
    'wall_tail_value_squared',wall.tail_value, ...
    'wall_tail_normal_squared',wall.tail_normal, ...
    'wall_tail_value_ratio',wall.value_ratio, ...
    'wall_tail_normal_ratio',wall.normal_ratio, ...
    'material_value_squared',cv+lead.value, ...
    'material_normal_squared',cn+lead.normal, ...
    'wall_value_squared',wall.value,'wall_normal_squared',wall.normal, ...
    'value_squared',cv+lead.value+wall.value, ...
    'normal_squared',cn+lead.normal+wall.normal, ...
    'mass_squared',U^2,'complete',lead.complete && wall.complete);
end

%% ==================== Comparison and status ====================
% These helpers reduce saved primitive discrepancies to scalar audit defects.

function value = LOCAL_rows_diff(rows,saved)
  expected = [[saved.value_squared].',[saved.normal_squared].'];
  value = LOCAL_diff(rows,expected);
end

function value = LOCAL_component_diff(a,b)
  names = fieldnames(a); value = 0;
  for j = 1:numel(names)
    name = names{j};
    if islogical(a.(name))
      value = max(value,double(a.(name)~=b.(name)));
    else
      value = max(value,LOCAL_nan_diff(a.(name),b.(name)));
    end
  end
end

function value = LOCAL_density_solve(cellmap)
  scale = sqrt(repmat(cellmap.far_aux.weights(:),2,1));
  H = [cellmap.H_L,cellmap.H_R];
  B = [cellmap.B_L,cellmap.B_R];
  value = norm(cellmap.A_QP*(scale.*H)+scale.*B,'fro')/ ...
    max(1,norm(scale.*B,'fro'));
end

function value = LOCAL_nan_diff(a,b)
  if isnan(a) && isnan(b), value = 0;
  elseif isfinite(a) && isfinite(b), value = abs(a-b);
  else, value = Inf;
  end
end

function status = LOCAL_status(components,audit_pass,geometry_pass,denominator)
  if ~components.complete, status = 'FINITE_PREFIX_DIAGNOSTIC';
  elseif ~audit_pass, status = 'PARTIAL_AUDIT_FAILED';
  elseif ~geometry_pass, status = 'PARTIAL_GEOMETRY_FAILED';
  elseif ~(isfinite(denominator) && denominator>0)
    status = 'NO_FINITE_RNUM';
  else, status = 'UNCERTIFIED_RNUM';
  end
end

function value = LOCAL_overlap(a,b)
  value = abs(a'*b)/(norm(a)*norm(b));
end

function value = LOCAL_diff(a,b)
  value = norm(a-b,'fro')/max(1,norm(b,'fro'));
end

function cleanup = LOCAL_warning_guard()
  state = warning; cleanup = onCleanup(@() warning(state));
  warning('error','MATLAB:singularMatrix');
  warning('error','MATLAB:nearlySingularMatrix');
  warning('error','MATLAB:illConditionedMatrix');
  warning('error','MATLAB:rankDeficientMatrix');
end
