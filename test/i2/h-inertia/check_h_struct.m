function result = check_h_struct(attempt)
%CHECK_H_STRUCT Run the compact I2.2 two-endpoint structure diagnostic.
% Purpose:
%   Reproduce the I2.2 endpoint objects with the reviewed I2.1 evaluator and
%   stop before inertia because the exact Hermitian and interval-continuity
%   proofs remain unavailable.
% Input:
%   attempt - New append-only output tag, for example 'compact-a1'.
% Output:
%   result  - Configuration, endpoint objects, diagnostics, and verdict.
% Main algorithm:
%   Seed the frozen fine-M48 evaluator at the I1.3 center, evaluate only the
%   two registered L14 shoulder points, construct T, N0, L, H=A/T and C0,
%   check the unchanged numerical gates, and record unavailable inertia.
% Based on:
%   The historical cfg_i22, eval_i22, and run_i22 files archived below the
%   experiment output directory.
% Main changes:
%   One portable numerical entry point; no repository discovery, provenance
%   manifests, history reads, scan, root solve, symmetrization, or inertia.
% Numerical goal:
%   Preserve the reviewed finite-dimensional endpoint calculation while
%   making the theory-gate stop explicit and inexpensive to reproduce.

  attempt = LOCAL_attempt(attempt);
  here = fileparts(mfilename('fullpath'));
  output = fullfile(here,'output',attempt);
  if exist(output,'dir') || exist(output,'file')
    error('i22:OutputExists','Output already exists: %s.',output);
  end
  LOCAL_runtime();

  c = LOCAL_config();
  timer = tic;
  peak_active_mib = 0;
  selectors = LOCAL_selectors();
  [seed,frame] = eval_i21('seed',c,selectors);
  LOCAL_seed_gate(seed,frame,c);
  peak_active_mib = LOCAL_budget(timer,c,peak_active_mib,{seed,frame});

  labels = {'L','R'};
  kvals = [c.k_left,c.k_right];
  nodes = repmat(LOCAL_empty_endpoint(),2,1);
  for j = 1:2
    node = eval_i21('point',kvals(j),c,frame);
    LOCAL_node_gate(node,kvals(j),frame,c);
    [objects,diagnostics] = LOCAL_objects(node,c);
    nodes(j) = LOCAL_endpoint(labels{j},node,objects,diagnostics,c);
    peak_active_mib = LOCAL_budget(timer,c,peak_active_mib, ...
      {node,frame,objects,diagnostics,nodes});
  end

  gates = LOCAL_gates(nodes,c);
  if ~gates.branch_qz_chart
    error('i22:BranchQZChart','The inherited branch, QZ, or chart gate failed.');
  end
  if ~gates.factor_health
    error('i22:FactorHealth','An inherited factor gate failed.');
  end
  if ~gates.T_invertible
    error('i22:TNotInvertible','A shoulder failed the registered T gate.');
  end
  if ~gates.object_equivalence
    error('i22:ObjectEquivalence','A registered A/H identity gate failed.');
  end
  if ~gates.structure_finite
    error('i22:StructureNonfinite','A raw structure diagnostic is nonfinite.');
  end

  inertia = repmat(struct('endpoint','','available',false, ...
    'n_pos',NaN,'n_neg',NaN,'n_zero',NaN,'min_abs_eig',NaN, ...
    'algorithm','NOT_RUN_EXACT_HERMITIAN_GATE'),2,1);
  inertia(1).endpoint = 'L';
  inertia(2).endpoint = 'R';
  result = struct( ...
    'experiment_id','I2-H-STRUCTURE-DIAGNOSTIC-V1', ...
    'attempt',attempt, ...
    'status','I2_2_STOP_THEORY_GATE', ...
    'pass',false, ...
    'first_unmet_condition','EXACT_HERMITIAN_NOT_ESTABLISHED', ...
    'claim_boundary','FROZEN_FINE_M48_FINITE_DIMENSIONAL_OBJECT', ...
    'elapsed_seconds',toc(timer), ...
    'peak_active_mib',peak_active_mib, ...
    'configuration',c, ...
    'seed',LOCAL_seed_summary(seed,frame), ...
    'endpoints',nodes, ...
    'gates',gates, ...
    'exact_finite_hermitian_proof',false, ...
    'continuous_same_family_interval_proof',false, ...
    'inertia_available',false, ...
    'inertia',inertia, ...
    'inertia_jump','UNAVAILABLE', ...
    'conclusion',['Both frozen endpoints were evaluated, but inertia is ' ...
      'not mathematically available because both structure proofs are open.']);

  mkdir(output);
  save(fullfile(output,'result.mat'),'result','-v7');
  LOCAL_report(fullfile(output,'report.md'),result);
end

