function attempt = LOCAL_attempt(value)
  if nargin ~= 1 || ~(ischar(value) || (isstring(value) && isscalar(value)))
    error('i22:Attempt','Supply one explicit attempt name.');
  end
  attempt = char(value);
  if isempty(regexp(attempt,'^[a-z0-9][a-z0-9-]*$','once'))
    error('i22:Attempt','Attempt names use lowercase letters, digits, and hyphens.');
  end
end

function LOCAL_runtime()
  matches = which('eval_i21','-all');
  if ischar(matches), matches = cellstr(matches); end
  solver = which('lsqminnorm');
  if exist('OCTAVE_VERSION','builtin') ~= 0 || isempty(solver) || ...
      ~startsWith(solver,matlabroot)
    error('i22:MATLABRequired','MATLAB with lsqminnorm is required.');
  end
  if numel(matches) ~= 1
    error('i22:EvaluatorPath','Exactly one eval_i21 must be on the MATLAB path.');
  end
end

function peak = LOCAL_budget(timer,c,peak,values)
  info = whos('values');
  peak = max(peak,sum([info.bytes])/2^20);
  if toc(timer) > c.hard_seconds || peak > c.memory_mib_max
    error('i22:Resource','The registered time or active-memory gate failed.');
  end
end

%% ==================== Same-object construction ====================
% These helpers preserve the historical A, T, N0, L, H, and C0 formulas.

function [o,d] = LOCAL_objects(node,c)
  K = c.K;
  LOCAL_shape(node.AdefD,2*K,2*K,'AdefD');
  LOCAL_shape(node.pair.A,2*K,2*K,'pencil A');
  LOCAL_shape(node.pair.B,2*K,2*K,'pencil B');
  LOCAL_shape(node.Dm,K,K,'Dm'); LOCAL_shape(node.Nm,K,K,'Nm');
  LOCAL_shape(node.Dp,K,K,'Dp'); LOCAL_shape(node.Np,K,K,'Np');
  LOCAL_shape(node.cm.Lambda,K,K,'Lambda minus');
  LOCAL_shape(node.cp.Lambda,K,K,'Lambda plus');
  if numel(node.gamma) ~= K || numel(node.phase) ~= K
    error('i22:ObjectShape','Channel dimensions drifted.');
  end
  I = eye(K); Gamma = diag(node.gamma(:)); E = diag(node.phase(:));
  T = [I,E;E,I];
  N0 = [-1i*Gamma,1i*Gamma*E;1i*Gamma*E,-1i*Gamma];
  L = blkdiag(node.cm.Lambda,node.cp.Lambda);
  A = node.AdefD; H = A/T; C0 = N0/T;
  d = struct( ...
    'T_rcond',rcond(T), ...
    'T_sigma_min',min(svd(T,'econ')), ...
    'min_abs_1_minus_E2',min(abs(1-node.phase(:).^2)), ...
    'H_right_solve_residual',LOCAL_product(A,H,T), ...
    'C0_right_solve_residual',LOCAL_product(N0,C0,T), ...
    'block_identity_defect',LOCAL_sum(A,N0,L,T), ...
    'A_HT_defect',LOCAL_product(A,H,T), ...
    'C0_hermitian_defect',LOCAL_hermitian(C0), ...
    'Lambda_minus_hermitian_defect',LOCAL_hermitian(node.cm.Lambda), ...
    'Lambda_plus_hermitian_defect',LOCAL_hermitian(node.cp.Lambda), ...
    'graph_minus_lagrangian_defect',LOCAL_graph(node.Dm,node.Nm), ...
    'graph_plus_lagrangian_defect',LOCAL_graph(node.Dp,node.Np), ...
    'H_hermitian_defect',LOCAL_hermitian(H), ...
    'block_model_direct_defect',norm(A-(N0-L*T),'fro')/ ...
      max(1,norm(A,'fro')+norm(N0-L*T,'fro')));
  values = struct2cell(d);
  d.all_finite = all(cellfun(@(x) isscalar(x) && isfinite(x),values));
  o = struct('k',node.k,'A',A,'Gamma',Gamma,'E',E,'T',T,'N0',N0, ...
    'L',L,'H',H,'C0',C0,'D_minus',node.Dm,'N_minus',node.Nm, ...
    'D_plus',node.Dp,'N_plus',node.Np, ...
    'Lambda_minus',node.cm.Lambda,'Lambda_plus',node.cp.Lambda, ...
    'pencil_A',node.pair.A,'pencil_B',node.pair.B);
end

function LOCAL_shape(A,m,n,name)
  if ~isequal(size(A),[m,n]) || ~all(isfinite(A(:)))
    error('i22:ObjectShape','%s shape or finite-value gate failed.',name);
  end
end

function value = LOCAL_hermitian(X)
  value = norm(X-X','fro')/max(1,norm(X,'fro'));
end

function value = LOCAL_graph(D,N)
  X = D'*N;
  value = norm(X-X','fro')/max(1,norm(X,'fro'));
end

function value = LOCAL_product(A,B,C)
  value = norm(A-B*C,'fro')/max(1, ...
    norm(A,'fro')+norm(B,'fro')*norm(C,'fro'));
end

function value = LOCAL_sum(A,N0,L,T)
  value = norm(A-(N0-L*T),'fro')/max(1, ...
    norm(A,'fro')+norm(N0,'fro')+norm(L,'fro')*norm(T,'fro'));
end

%% ==================== Endpoint gates and compact result ====================
% These helpers retain the reviewed numerical predicates without ledgers.

function LOCAL_seed_gate(seed,frame,c)
  ok = seed.k == c.kstar && seed.pass && all([seed.factors.pass]) && ...
    isequal(size(seed.R),[c.expected.proxy_rank,c.expected.proxy_rank]) && ...
    isequal(seed.proxy_shape,[c.expected.proxy_rows, ...
      c.expected.proxy_columns]) && ...
    isequal(seed.proxy_shifted_shape,[c.expected.proxy_shifted_rows, ...
      c.expected.proxy_shifted_columns]) && ...
    isequal(size(seed.Aqp),[c.expected.bie_order,c.expected.bie_order]) && ...
    isequal(size(seed.AdefD),[2*c.K,2*c.K]) && ...
    isequal(size(seed.pair.A),[2*c.K,2*c.K]) && ...
    isequal(size(seed.pair.B),[2*c.K,2*c.K]) && ...
    isequal(size(frame.Z0_plus),[2*c.K,c.K]) && ...
    isequal(size(frame.Z0_minus),[2*c.K,c.K]) && ...
    numel(frame.rows_plus) == c.K && numel(frame.rows_minus) == c.K && ...
    frame.proxy_chart.r == c.expected.proxy_rank;
  if ~ok, error('i22:SeedGate','The frozen seed/frame gate failed.'); end
end

function LOCAL_node_gate(node,k,frame,c)
  ok = node.k == k && strcmp(node.name,'fine') && node.pass && ...
    node.plus.pass && node.minus.pass && node.branch_port.pass && ...
    node.branch_proxy.pass && node.cp.safe && node.cm.safe && ...
    all([node.factors.pass]) && ...
    strcmp(node.branch_port.fingerprint,frame.port_anchor.fingerprint) && ...
    strcmp(node.branch_proxy.fingerprint, ...
      frame.proxy_chart.anchor.fingerprint) && ...
    strcmp(node.proxy_chart.fingerprint,frame.proxy_chart.fingerprint) && ...
    isequal(node.H_plus_rows,frame.rows_plus) && ...
    isequal(node.H_minus_rows,frame.rows_minus) && ...
    isequal(size(node.AdefD),[2*c.K,2*c.K]) && ...
    isequal(size(node.AdefG),[4*c.K,4*c.K]) && ...
    k > c.i21_real_diameter(1) && k < c.i21_real_diameter(2);
  if ~ok, error('i22:EndpointGate','An endpoint inherited gate failed.'); end
end

function out = LOCAL_endpoint(label,node,objects,diagnostics,c)
  out = LOCAL_empty_endpoint();
  out.label = label; out.k = node.k; out.inside_i21_disk = ...
    node.k > c.i21_real_diameter(1) && node.k < c.i21_real_diameter(2);
  out.branch_pass = node.branch_port.pass && node.branch_proxy.pass;
  out.qz_pass = node.plus.pass && node.minus.pass;
  out.chart_pass = node.cp.safe && node.cm.safe;
  out.factor_pass = all([node.factors.pass]);
  out.factors = node.factors;
  out.qz = struct('plus',LOCAL_qz(node.plus),'minus',LOCAL_qz(node.minus));
  out.fixed_rows = node.row;
  out.safe_dtn = struct('minus',node.cm,'plus',node.cp);
  out.schur_defect = node.schur;
  out.diagnostics = diagnostics;
  out.objects = objects;
end

function out = LOCAL_empty_endpoint()
  out = struct('label','','k',NaN,'inside_i21_disk',false, ...
    'branch_pass',false,'qz_pass',false,'chart_pass',false, ...
    'factor_pass',false,'factors',struct([]),'qz',struct(), ...
    'fixed_rows',struct(),'safe_dtn',struct(),'schur_defect',NaN, ...
    'diagnostics',struct(),'objects',struct());
end

function out = LOCAL_qz(q)
  out = struct('stable',q.stable_diagnostic,'unstable',q.unstable_diagnostic, ...
    'neutral',q.neutral_count,'infinite',q.infinite_count, ...
    'indeterminate',q.indeterminate_count,'unit_gap',q.unit_gap, ...
    'chordal_separation',q.chordal_separation,'overlap',q.overlap, ...
    'score_gap',q.score_gap,'classification_gap',q.classification_gap, ...
    'cluster_tau',q.cluster_tau, ...
    'raw_residual',q.raw_residual,'ordered_residual',q.residual, ...
    'match_pass',q.match_pass,'pass',q.pass);
end

function out = LOCAL_seed_summary(seed,frame)
  out = struct('k',seed.k,'pass',seed.pass,'factor_pass', ...
    all([seed.factors.pass]),'proxy_rank',frame.proxy_chart.r, ...
    'row_count_plus',numel(frame.rows_plus), ...
    'row_count_minus',numel(frame.rows_minus));
end

function g = LOCAL_gates(nodes,c)
  d = [nodes.diagnostics];
  g = struct( ...
    'branch_qz_chart',all([nodes.branch_pass]) && all([nodes.qz_pass]) && ...
      all([nodes.chart_pass]), ...
    'factor_health',all([nodes.factor_pass]), ...
    'T_invertible',all([d.T_rcond] >= c.T_rcond_min) && ...
      all([d.min_abs_1_minus_E2] >= c.phase_square_separation_min), ...
    'object_equivalence',all([d.block_identity_defect] <= ...
      c.identity_residual_max) && all([d.A_HT_defect] <= ...
      c.identity_residual_max) && all([d.H_right_solve_residual] <= ...
      c.identity_residual_max) && all([d.C0_right_solve_residual] <= ...
      c.identity_residual_max), ...
    'structure_finite',all([d.all_finite]), ...
    'exact_finite_hermitian_proof',false, ...
    'continuous_same_family_interval_proof',false, ...
    'endpoint_separation','NOT_REACHED', ...
    'inertia_jump','UNAVAILABLE');
end

%% ==================== Compact report ====================
% The report summarizes only the numerical result stored in result.mat.

function LOCAL_report(path,r)
  fid = fopen(path,'w');
  if fid < 0, error('i22:Report','Cannot create report.md.'); end
  cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
  fprintf(fid,'# I2.2 compact endpoint diagnostic\n\n');
  fprintf(fid,'- Attempt: `%s`\n',r.attempt);
  fprintf(fid,'- Status: `%s`\n',r.status);
  fprintf(fid,'- First unmet condition: `%s`\n',r.first_unmet_condition);
  fprintf(fid,'- Runtime / active-object peak: `%.3f s` / `%.3f MiB`\n', ...
    r.elapsed_seconds,r.peak_active_mib);
  fprintf(fid,'- Scientific endpoints: `%.17g`, `%.17g`\n', ...
    r.endpoints(1).k,r.endpoints(2).k);
  fprintf(fid,'- Inertia: `UNAVAILABLE`; positive, negative, and zero counts are `NaN`.\n\n');
  fprintf(fid,'| endpoint | rcond(T) | min abs(1-E^2) | A=N0-LT defect | A=HT defect | H Hermitian defect |\n');
  fprintf(fid,'|---|---:|---:|---:|---:|---:|\n');
  for j = 1:2
    d = r.endpoints(j).diagnostics;
    fprintf(fid,'| %s | %.6e | %.6e | %.6e | %.6e | %.6e |\n', ...
      r.endpoints(j).label,d.T_rcond,d.min_abs_1_minus_E2, ...
      d.block_identity_defect,d.A_HT_defect,d.H_hermitian_defect);
  end
  fprintf(fid,['\nThe same frozen fine-M48 evaluator completed both endpoints and the ' ...
    'registered numerical equivalence gates. The exact finite Hermitian and ' ...
    'whole-interval same-family proofs remain false, so this attempt does not ' ...
    'compute inertia, locate a root, or support a real-root conclusion.\n']);
end
