function out = LOCAL_center_mass(z)
K = double(z.K);
q_left = double(z.q_center(1:K));
q_right = double(z.q_center(K + 1:end));
orders = (-double(z.M):double(z.M)).';
beta_modes = double(z.beta) + 2 * pi * orders / double(z.d);
gamma_modes = sqrt(complex(double(z.khat)^2 - beta_modes.^2));
length_x = double(z.X_R) - double(z.X_L);
A = zeros(K, 1);
B = zeros(K, 1);
propagating = abs(imag(gamma_modes)) < 1e-13;
g = real(gamma_modes(propagating));
A(propagating) = length_x;
B(propagating) = length_x * sinc(g * length_x / pi);
kappa = imag(gamma_modes(~propagating));
A(~propagating) = -expm1(-2 * kappa * length_x) ./ (2 * kappa);
B(~propagating) = length_x * exp(-kappa * length_x);
lambda_plus = A + B;
lambda_minus = A - B;
assert(min([lambda_plus; lambda_minus]) >= -1e-13);
per_mode = 0.5 * lambda_plus .* abs(q_left + q_right).^2 + ...
  0.5 * lambda_minus .* abs(q_left - q_right).^2;
mass_squared = sum(per_mode);
x = linspace(0, length_x, 4001);
samples = q_left .* exp(1i * gamma_modes * x) + ...
  q_right .* exp(1i * gamma_modes * (length_x - x));
quadrature_squared = trapz(x, sum(abs(samples).^2, 1));
out = struct('method', 'exact empty-center Rayleigh Gram in rho=1', ...
  'rho_center', 1, 'analytic_squared', mass_squared, ...
  'analytic_norm', sqrt(mass_squared), ...
  'quadrature_squared_diagnostic', quadrature_squared, ...
  'relative_quadrature_difference', ...
  abs(quadrature_squared - mass_squared) / mass_squared, ...
  'minimum_gram_eigenvalue', min([lambda_plus; lambda_minus]), ...
  'per_mode_squared', per_mode);
end

