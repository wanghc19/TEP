function density = LOCAL_density(z)
source_node_count = size(z.eta_unit_256, 1) / 2;
orders = (-source_node_count / 2:source_node_count / 2 - 1).';
eta = double(z.eta_unit_256);
density = struct('orders', orders, ...
  'tau_coeff', fftshift(fft(eta(1:source_node_count, :), [], 1), 1) / ...
    source_node_count, ...
  'zeta_coeff', fftshift(fft(eta(source_node_count + 1:end, :), [], 1), 1) / ...
    source_node_count, ...
  'source_node_count', source_node_count, ...
  'maximum_order', max(abs(orders)), ...
  'coordinate', '[tau;zeta], zeta=-sigma');
end

function g = LOCAL_circle_geometry(z, configuration)
R = double(z.R);
N = double(configuration.evaluation_node_count);
a = double(configuration.parameter_strip_width);
P = 2 * pi * R;
t = (0:N - 1).' * (2 * pi / N);
s_nodes = (0:N - 1).' * (P / N);
[contour, period] = geom.construct_cont(N, 'circle', 0, 0, R);
assert(period == 2 * pi && isequal(size(contour), [6, N]));
position = [double(contour(1, :).'), double(contour(4, :).')];
derivative = [double(contour(2, :).'), double(contour(5, :).')];
speed = vecnorm(derivative, 2, 2);
normal = [derivative(:, 2), -derivative(:, 1)] ./ speed;
h = double(z.delta_c);
theta = 1 - h / R;
material_plus = struct('label', 'material-plus-exterior', ...
  'width', h, 'rho_upper', 1, 'curvature_upper', 1 / R, ...
  'theta_lower', theta, 'Theta_upper', 1 + h / R, ...
  'zero_rim', theta > 0, 'pass', theta > 0);
material_minus = material_plus;
material_minus.label = 'material-minus-interior';
material_minus.rho_upper = double(z.rho_disk);
wall_plus = struct('label', 'wall-plus-neighbour-side', ...
  'width', double(z.delta_w), 'rho_upper', 1, ...
  'curvature_upper', 0, 'theta_lower', 1, 'Theta_upper', 1, ...
  'zero_rim', true, 'pass', true);
wall_minus = wall_plus;
wall_minus.label = 'wall-minus-central-side';
material_wall_disjoint = h + double(z.delta_w) <= ...
  min(abs(double(z.X_L)) - R, abs(double(z.X_R)) - R);
material_cell_copy_disjoint = 2 * (R + h) <= double(z.L);
material_transverse_copy_disjoint = 2 * (R + h) <= double(z.d);
wall_pair_disjoint = 2 * double(z.delta_w) <= double(z.L);
lift_gates = struct('material_wall_disjoint', material_wall_disjoint, ...
  'material_cell_copies_disjoint', material_cell_copy_disjoint, ...
  'material_transverse_periodic_copies_disjoint', ...
    material_transverse_copy_disjoint, ...
  'wall_pair_disjoint', wall_pair_disjoint, ...
  'all_rims_zero', true, ...
  'all_collars_disjoint', material_wall_disjoint && ...
    material_cell_copy_disjoint && material_transverse_copy_disjoint && ...
    wall_pair_disjoint);
position_abs = R * cosh(a);
g = struct('boundary_length', P, 'curvature_upper', 1 / R, ...
  'speed_lower', R, 'speed_upper', R, 'mu_shift', double(z.mu_h), ...
  'constant_speed_parameterization', true, ...
  'constant_speed_certificate_pass', P == 2 * pi * R, ...
  'parameter_nodes', t, 'arclength_nodes', s_nodes, ...
  'arclength_origin', 0, 'arclength_step', P / N, ...
  'constant_arclength_grid_pass', true, ...
  'arclength_partition_pass', true, 'position', position, ...
  'normal', normal, 'speed_nodes', speed, ...
  'material_lift_collars', struct('plus', material_plus, ...
    'minus', material_minus), ...
  'wall_lift_collars', struct('plus', wall_plus, 'minus', wall_minus), ...
  'lift_geometry_gates', lift_gates, ...
  'parameter_strip_width', a, 'arclength_strip_width', R * a, ...
  'strip_speed_upper', R, 'strip_position_abs_upper', position_abs, ...
  'strip_position_imag_upper', R * sinh(a), ...
  'real_displacement_abs_upper', [2 * R, 2 * R], ...
  'displacement_abs_upper', [2 * position_abs, 2 * position_abs], ...
  'displacement_real_upper', [2 * position_abs, 2 * position_abs], ...
  'displacement_imag_upper', [2 * R * sinh(a), 2 * R * sinh(a)], ...
  'target_normal_component_upper', cosh(a) * [1, 1], ...
  'source_normal_component_upper', cosh(a) * [1, 1], ...
  'left_clearance_lower', abs(double(z.X_L)) - R, ...
  'right_clearance_lower', abs(double(z.X_R)) - R, ...
  'strip_left_clearance_lower', abs(double(z.X_L)) - position_abs, ...
  'strip_right_clearance_lower', abs(double(z.X_R)) - position_abs, ...
  'strip_certificate_pass', abs(double(z.X_L)) > position_abs && ...
    abs(double(z.X_R)) > position_abs, ...
  'source_strip_certificate_pass', abs(double(z.X_L)) > position_abs && ...
    abs(double(z.X_R)) > position_abs, ...
  'target_strip_certificate_pass', abs(double(z.X_L)) > position_abs && ...
    abs(double(z.X_R)) > position_abs, ...
  'outward_normal_contract_pass', all(sum(position .* normal, 2) > 0), ...
  'parameter_grid_contract_pass', ...
    isequal(t, (0:N - 1).' * (2 * pi / N)));
assert(g.strip_certificate_pass && g.outward_normal_contract_pass && ...
  g.lift_geometry_gates.all_collars_disjoint);
end

function LOCAL_create_once(path)
assert(~isfile(path) && ~isfolder(path), 'I6:CreateOnce', ...
  'Every run artifact path must be new.');
assert(isfolder(fileparts(path)), 'I6:Parent', ...
  'Every run artifact parent directory must exist.');
end

function out = LOCAL_block(P, block_length)
power = eye(size(P));
power_norms = zeros(block_length, 1);
for index = 1:block_length
  power_norms(index) = norm(power, 'fro');
  power = P * power;
end
block_norm = norm(power, 'fro');
out = struct('block_length', block_length, 'block_norm', block_norm, ...
  'power_norms', power_norms, ...
  'sum_power_squared_upper', sum(power_norms.^2) / (1 - block_norm^2), ...
  'pass', isfinite(block_norm) && block_norm < 1);
end

%% ==================== Material-interface direct L2 accounting ====================
% Empty-center material is excluded; both lead sequences start at n=0.

function [value, normal, audit] = LOCAL_material( ...
    z, geometry, cfg, propagation, local, regular, off_surface)
assert(local.gates.pass && regular.gates.pass && off_surface.gates.pass);
assert(local.retained_source_exactness.pass);
Cv = double(local.nodes.val) + double(regular.nodes.val) + ...
  double(off_surface.nodes.val);
Cn = double(local.nodes.nor) - double(regular.nodes.nor) - ...
  double(off_surface.nodes.nor);
N = double(cfg.evaluation_node_count);
Pcurve = double(geometry.boundary_length);
ds = Pcurve / N;
a = double(cfg.parameter_strip_width);
target_remainder_factor = 2 * Pcurve / expm1(a * N);
rv = repmat(double(local.continuous_node_radius.val), N, 1) + ...
  repmat(double(regular.radius.val.total), N, 1) + ...
  double(off_surface.radius.val.total(:));
rn = repmat(double(local.continuous_node_radius.nor), N, 1) + ...
  repmat(double(regular.radius.nor.total), N, 1) + ...
  double(off_surface.radius.nor.total(:));
Mv = double(local.strip_action_upper.val) + ...
  double(regular.value_strip_upper) + double(off_surface.value_action_upper);
Mn = double(local.strip_action_upper.nor) + ...
  double(regular.normal_strip_upper) + ...
  double(off_surface.first_arclength_derivative_upper);
[value, value_ledger] = LOCAL_direct_sequence( ...
  z, cfg, propagation, Cv, rv, Mv, ds, target_remainder_factor, 'value');
[normal, normal_ledger] = LOCAL_direct_sequence( ...
  z, cfg, propagation, Cn, rn, Mn, ds, target_remainder_factor, 'normal');
audit = struct('node_count', N, 'curve_length', Pcurve, ...
  'arclength_weight', ds, 'parameter_strip_width', a, ...
  'target_remainder_factor', target_remainder_factor, ...
  'value_node_radius', rv(1), 'normal_node_radius', rn(1), ...
  'local_value_continuous_radius', ...
    local.continuous_node_radius.val, ...
  'local_normal_continuous_radius', ...
    local.continuous_node_radius.nor, ...
  'regular_value_radius', regular.radius.val.total, ...
  'regular_normal_radius', regular.radius.nor.total, ...
  'regular_radius_components', struct('value', regular.radius.val, ...
    'normal', regular.radius.nor), ...
  'local_superseded_radius_diagnostic', struct( ...
    'active', false, ...
    'value_source_max', max(local.radius.val.source), ...
    'value_discrete_series_max', max(local.radius.val.series), ...
    'value_total_max', max(local.radius.val.total), ...
    'normal_source_max', max(local.radius.nor.source), ...
    'normal_discrete_series_max', max(local.radius.nor.series), ...
    'normal_total_max', max(local.radius.nor.total)), ...
  'value_strip_action_upper', Mv, 'normal_strip_action_upper', Mn, ...
  'strip_action_components', struct( ...
    'local_value', local.strip_action_upper.val, ...
    'regular_value', regular.value_strip_upper, ...
    'off_surface_value', off_surface.value_action_upper, ...
    'local_normal', local.strip_action_upper.nor, ...
    'regular_normal', regular.normal_strip_upper, ...
    'off_surface_normal', ...
      off_surface.first_arclength_derivative_upper), ...
  'local_superseded_radius_inactive', true, ...
  'physical_value_sign', isequal(Cv, double(local.nodes.val) + ...
    double(regular.nodes.val) + double(off_surface.nodes.val)), ...
  'physical_normal_sign', isequal(Cn, double(local.nodes.nor) - ...
    double(regular.nodes.nor) - double(off_surface.nodes.nor)), ...
  'source_exactness', local.retained_source_exactness, ...
  'value_ledger', value_ledger, 'normal_ledger', normal_ledger, ...
  'pass', local.retained_source_exactness.pass && ...
    all(isfinite([rv; rn; Mv; Mn; target_remainder_factor])) && ...
    all([rv; rn; Mv; Mn; target_remainder_factor] >= 0));
assert(audit.pass && audit.physical_value_sign && audit.physical_normal_sign);
end

function [out, ledger] = LOCAL_direct_sequence( ...
    z, cfg, propagation, C, r, Mstrip, ds, remainder_factor, label)
sides = {'minus', 'plus'};
finite_sample = zeros(2, 1);
finite_center = zeros(2, 1);
finite_contour = zeros(2, 1);
cell_sample = zeros(2, 1);
cell_center = zeros(2, 1);
cell_contour = zeros(2, 1);
state_entries = repmat(struct('side', '', 'cell_index', 0, ...
  'sample_with_radius_squared', 0, 'target_remainder_squared', 0, ...
  'signed_center_squared', 0, 'node_radius_increment_squared', 0, ...
  'total_squared', 0), 2 * cfg.cell_cutoff, 1);
entry_index = 0;
tail_ledger = cell(2, 1);
for side_index = 1:2
  side = sides{side_index};
  G = double(z.(['G', side]));
  P = double(z.(['P', side]));
  state = double(z.(['c', side]));
  for n = 0:cfg.cell_cutoff - 1
    field_state = G * state;
    state_norm = norm(field_state, 2);
    sample_squared = ds * sum((abs(C * field_state) + ...
      r * state_norm).^2);
    center_squared = ds * sum(abs(C * field_state).^2);
    contour_squared = remainder_factor * Mstrip^2 * state_norm^2;
    finite_sample(side_index) = finite_sample(side_index) + sample_squared;
    finite_center(side_index) = finite_center(side_index) + center_squared;
    finite_contour(side_index) = finite_contour(side_index) + contour_squared;
    entry_index = entry_index + 1;
    state_entries(entry_index) = struct('side', side, 'cell_index', n, ...
      'sample_with_radius_squared', sample_squared, ...
      'target_remainder_squared', contour_squared, ...
      'signed_center_squared', center_squared, ...
      'node_radius_increment_squared', sample_squared - center_squared, ...
      'total_squared', sample_squared + contour_squared);
    state = P * state;
  end
  G_upper = norm(G, 'fro');
  operator_sample = ds * sum((vecnorm(C * G, 2, 2) + ...
    r * G_upper).^2);
  operator_center = ds * sum(vecnorm(C * G, 2, 2).^2);
  operator_contour = remainder_factor * Mstrip^2 * G_upper^2;
  tail_state_factor = propagation.(side).sum_power_squared_upper * ...
    norm(state, 2)^2;
  cell_sample(side_index) = operator_sample * tail_state_factor;
  cell_center(side_index) = operator_center * tail_state_factor;
  cell_contour(side_index) = operator_contour * tail_state_factor;
  tail_ledger{side_index} = struct('side', side, ...
    'G_frobenius_upper', G_upper, ...
    'operator_sample_with_radius_squared', operator_sample, ...
    'operator_signed_center_squared', operator_center, ...
    'operator_node_radius_increment_squared', ...
      operator_sample - operator_center, ...
    'operator_target_remainder_squared', operator_contour, ...
    'tail_state_norm', norm(state, 2), ...
    'sum_power_squared_upper', ...
      propagation.(side).sum_power_squared_upper, ...
    'sample_tail_squared', cell_sample(side_index), ...
    'signed_center_tail_squared', cell_center(side_index), ...
    'node_radius_increment_tail_squared', ...
      cell_sample(side_index) - cell_center(side_index), ...
    'target_remainder_tail_squared', cell_contour(side_index));
end
finite_squared = sum(finite_sample) + sum(finite_contour);
cell_tail_squared = sum(cell_sample) + sum(cell_contour);
out = struct('method', ...
  'direct signed physical-node analytic trapezoid L2 upper', ...
  'action_label', label, 'singleton_squared', 0, ...
  'finite_minus_squared', finite_sample(1) + finite_contour(1), ...
  'finite_plus_squared', finite_sample(2) + finite_contour(2), ...
  'finite_sample_with_radius_squared', sum(finite_sample), ...
  'finite_signed_center_squared', sum(finite_center), ...
  'finite_node_radius_increment_squared', ...
    sum(finite_sample) - sum(finite_center), ...
  'finite_target_remainder_squared', sum(finite_contour), ...
  'finite_squared', finite_squared, ...
  'cell_tail_minus_squared', cell_sample(1) + cell_contour(1), ...
  'cell_tail_plus_squared', cell_sample(2) + cell_contour(2), ...
  'cell_tail_sample_with_radius_squared', sum(cell_sample), ...
  'cell_tail_signed_center_squared', sum(cell_center), ...
  'cell_tail_node_radius_increment_squared', ...
    sum(cell_sample) - sum(cell_center), ...
  'cell_tail_target_remainder_squared', sum(cell_contour), ...
  'cell_tail_squared', cell_tail_squared, 'high_mode_squared', 0, ...
  'material_high_mode_applicable', false, ...
  'high_mode_note', ...
    'complete direct curve bound plus contour remainder; no target-mode truncation', ...
  'total_squared', finite_squared + cell_tail_squared);
ledger = struct('state_entries', state_entries, ...
  'side_tail', {tail_ledger}, 'empty_center_excluded', true, ...
  'full_P_tail_once', true, 'G_frobenius_upper_used', true);
end

