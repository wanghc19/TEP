function result = resolvent_nonfourier_v1(candidate_path, curve_path, ...
    snapshot_path, output_path, json_path)
%RESOLVENT_NONFOURIER_V1 Evaluate direct physical-curve jump norms.
% Purpose:
%   Evaluate T9--T10 and F14 for the frozen I3 raw field, with material
%   value and ordinary-normal jumps combined before direct curve integration.
% Input:
%   candidate_path - Frozen I3 certificate MAT file.
%   curve_path - Frozen circle-geometry contract MAT file.
%   snapshot_path, output_path, json_path - Create-once run artifacts.
% Output:
%   result - Ordinary floating-point, non-certified formula evaluation.
% Main algorithm:
%   Form signed material rows at physical curve nodes without a target DFT,
%   add source and analytic-trapezoid remainders, retain full propagation
%   matrices, evaluate the empty-center mass, and apply F14.
% Based on:
%   resolvent-bound T9--T10, F14, N1--N9; I5.1g signed local/Ewald/Rayleigh
%   physical-node formulas; periodic analytic trapezoid remainder.
% Main changes:
%   Replaces material target-Fourier rows and high-mode tails by direct signed
%   physical rows plus a continuous curve-integration remainder.
% Numerical goal:
%   Produce a reproducible ordinary-floating-point spectral-distance estimate.

timer = tic;
LOCAL_create_once(snapshot_path);
LOCAL_create_once(output_path);
LOCAL_create_once(json_path);

% --- stage 1: load and cross-check the frozen scientific object ---
candidate = load(candidate_path, 'staged');
curve_data = load(curve_path, 'curve_contract');
assert(isfield(candidate, 'staged') && isfield(candidate.staged, 'certificate'));
assert(isfield(curve_data, 'curve_contract'));
z = candidate.staged.certificate;
LOCAL_validate(z, curve_data.curve_contract);
configuration = LOCAL_configuration(z);
density = LOCAL_density(z);
geometry_direct = LOCAL_circle_geometry(z, configuration);
scientific_input = struct('schema', ...
  'EPOST_I6_RESOLVENT_NONFOURIER_V1_INPUT', 'candidate', z, ...
  'curve_contract', curve_data.curve_contract, ...
  'configuration', configuration, 'density', density, ...
  'geometry', geometry_direct);
save(snapshot_path, 'scientific_input', '-v7.3');

% --- stage 2: point-frequency trace constant ---
mu = double(z.khat)^2;
rho_min = min(1, double(z.rho_disk));
rho_max = max(1, double(z.rho_disk));
h = min(double(z.delta_c), double(z.delta_w));
kappa_max = 1 / double(z.R);
theta = 1 - h * kappa_max;
overlap = 1;
ell_ref = configuration.reference_length;
c0 = overlap / (theta * h);
c1 = overlap * h / (2 * theta);
trace_constant_squared = c0 / (rho_min * mu^2) + ...
  (c1 + ell_ref^2 * c0) / (4 * mu) + ...
  ell_ref^2 * c1 * rho_max;
trace_constant = sqrt(trace_constant_squared);
fprintf('STAGE trace C=%.17g C2=%.17g h=%.17g theta=%.17g\n', ...
  trace_constant, trace_constant_squared, h, theta);

% --- stage 3: full-matrix propagation certificates ---
propagation.minus = LOCAL_block(double(z.Pminus), ...
  configuration.propagation_block_length);
propagation.plus = LOCAL_block(double(z.Pplus), ...
  configuration.propagation_block_length);
assert(propagation.minus.pass && propagation.plus.pass);

% --- stage 4: material value and ordinary-normal L2 defects ---
local = signed_local_center_nonfourier_v1( ...
  z, geometry_direct, configuration, density);
regular = signed_regular_image_nonfourier_v1( ...
  z, geometry_direct, configuration, density);
off_surface = signed_off_surface_nonfourier_v1( ...
  z, geometry_direct, configuration);
[material_value, material_normal, direct_audit] = LOCAL_material( ...
  z, geometry_direct, configuration, propagation, ...
  local, regular, off_surface);
fprintf('STAGE material value2=%.17g normal2=%.17g\n', ...
  material_value.total_squared, material_normal.total_squared);

% --- stage 5: artificial-wall paired L2 defects ---
wall_raw = signed_wall_l2_nonfourier_v1( ...
  z, geometry_direct, configuration);
wall_value = LOCAL_wall_parts(wall_raw.value);
wall_normal = LOCAL_wall_parts(wall_raw.normal);
fprintf(['STAGE wall value2=%.17g normal2=%.17g primitiveFloor=%d ' ...
  'aggregateFloor=%d\n'], ...
  wall_value.total_squared, wall_normal.total_squared, ...
  wall_raw.tail_primitive_floor_applied, ...
  wall_raw.tail_aggregate_floor_applied);

value_squared = material_value.total_squared + wall_value.total_squared;
normal_squared = material_normal.total_squared + wall_normal.total_squared;
epsilon_boundary_squared = normal_squared + value_squared / ell_ref^2;
epsilon_boundary = sqrt(epsilon_boundary_squared);

% --- stage 6: empty-center raw mass lower evaluation ---
mass = LOCAL_center_mass(z);
U_lower = mass.analytic_norm;
Q_bar = trace_constant * epsilon_boundary;
denominator = U_lower - Q_bar;
epsilon_volume = 0;
if denominator > 0
  spectral_distance_bound = (2 * mu * Q_bar + epsilon_volume) / denominator;
  spectral_interval = [mu - spectral_distance_bound, ...
    mu + spectral_distance_bound];
  finite_bound = true;
else
  spectral_distance_bound = Inf;
  spectral_interval = [-Inf, Inf];
  finite_bound = false;
end
fprintf('STAGE mass U=%.17g quad_rel=%.17g eps=%.17g Q=%.17g den=%.17g\n', ...
  U_lower, mass.relative_quadrature_difference, epsilon_boundary, ...
  Q_bar, denominator);
checkpoint = struct('trace_constant', trace_constant, ...
  'material_value', material_value, 'material_normal', material_normal, ...
  'material_direct_audit', direct_audit, ...
  'wall_value', wall_value, 'wall_normal', wall_normal, 'mass', mass, ...
  'epsilon_boundary', epsilon_boundary, 'Q_bar', Q_bar, ...
  'denominator', denominator, 'spectral_distance_bound', spectral_distance_bound);
save(snapshot_path, 'checkpoint', '-append');

% --- stage 7: audit, persist, and emit a light JSON summary ---
geometry = struct('period_x', double(z.L), 'period_y', double(z.d), ...
  'inclusion_radius', double(z.R), 'collar_half_width', h, ...
  'curvature_upper', kappa_max, 'theta', theta, ...
  'overlap_multiplicity', overlap, 'material_wall_disjoint', ...
  logical(geometry_direct.lift_geometry_gates.material_wall_disjoint), ...
  'material_cell_copy_disjoint', ...
  logical(geometry_direct.lift_geometry_gates.material_cell_copies_disjoint), ...
  'material_transverse_copy_disjoint', ...
  logical(geometry_direct.lift_geometry_gates.material_transverse_periodic_copies_disjoint), ...
  'wall_pair_disjoint', ...
  logical(geometry_direct.lift_geometry_gates.wall_pair_disjoint), ...
  'material_node_count', configuration.evaluation_node_count, ...
  'material_parameter_strip_width', configuration.parameter_strip_width);
gates = struct('same_candidate_mu', mu == double(z.mu_h), ...
  'point_frequency_window', true, 'center_material_present', false, ...
  'material_singleton_count', 0, 'lead_material_n0_count', 2, ...
  'center_first_wall_count', 2, 'ordinary_normal_L2', true, ...
  'paired_value_L2', true, 'full_propagation_matrices', true, ...
  'material_target_fourier_absent', true, ...
  'material_direct_curve_bound', direct_audit.pass, ...
  'material_source_exactness', ...
    local.retained_source_exactness.pass, ...
  'propagation_factor_once', true, ...
  'analytic_exact_kernel_pde_assumption', true, ...
  'analytic_exact_quasiperiodic_assumption', true, ...
  'volume_defect_zero_in_ideal_model', true, ...
  'finite_nonnegative', all(isfinite([trace_constant, epsilon_boundary, ...
    U_lower, Q_bar])) && all([trace_constant, epsilon_boundary, U_lower, Q_bar] >= 0), ...
  'mass_quadrature_agreement', mass.relative_quadrature_difference < 2e-6, ...
  'denominator_positive', denominator > 0);
result = struct('schema', 'EPOST_I6_RESOLVENT_NONFOURIER_V1_RESULT', ...
  'status', 'NON_CERTIFIED_FORMULA_EVALUATION', ...
  'candidate', struct('khat', double(z.khat), 'mu', mu, ...
    'beta', double(z.beta)), ...
  'material', struct('rho_min', rho_min, 'rho_max', rho_max, ...
    'rho_disk', double(z.rho_disk)), ...
  'geometry', geometry, 'reference_length', ell_ref, ...
  'trace_constant_squared', trace_constant_squared, ...
  'trace_constant', trace_constant, ...
  'defect', struct('material_value', material_value, ...
    'material_normal', material_normal, 'wall_value', wall_value, ...
    'wall_normal', wall_normal, 'value_squared', value_squared, ...
    'normal_squared', normal_squared, ...
    'epsilon_boundary_squared', epsilon_boundary_squared, ...
    'epsilon_boundary', epsilon_boundary), ...
  'mass', mass, 'mass_is_certified_lower', false, ...
  'U_lower', U_lower, 'Q_bar', Q_bar, ...
  'normalized_defect_ratio', Q_bar / U_lower, ...
  'denominator', denominator, 'epsilon_volume', epsilon_volume, ...
  'spectral_distance_bound', spectral_distance_bound, ...
  'spectral_interval', spectral_interval, 'finite_bound', finite_bound, ...
  'propagation', propagation, 'gates', gates, ...
  'material_direct_audit', direct_audit, ...
  'reliability', struct('level', 'ordinary floating-point non-certified', ...
    'special_function_enclosure', false, 'outward_rounding', false, ...
    'mass_single_sided_rounding', false, ...
    'analytic_infinite_cell_tails_included', true, ...
    'analytic_material_target_remainder_included', true, ...
    'continuous_material_source_tail_included', true, ...
    'wall_tail_floor_policy', wall_raw.tail_floor_policy, ...
    'wall_tail_primitive_floor_applied', ...
      wall_raw.tail_primitive_floor_applied, ...
    'wall_tail_aggregate_floor_applied', ...
      wall_raw.tail_aggregate_floor_applied, ...
    'candidate_search_repeated', false, 'pde_strategy', ...
    'ideal exact-kernel raw field; epsilon_volume=0', ...
    'quasiperiodic_strategy', ...
    'Rayleigh and quasi-periodic kernel definitions; seam defect=0', ...
    'material_evaluation', ...
    'direct signed physical nodes; no material target Fourier expansion', ...
    'input_binding', ...
    'explicit frozen candidate and explicit circle contract; no runtime hash'), ...
  'resource', struct('matlab_elapsed_seconds_before_save', toc(timer)));
save(output_path, 'result', '-v7.3');
summary = LOCAL_summary(result);
fid = fopen(json_path, 'w');
assert(fid >= 0, 'I6:JsonOpen', 'Could not create JSON output.');
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '%s\n', jsonencode(summary, 'PrettyPrint', true));
fprintf(['I6_RESULT mu=%.17g C=%.17g eps=%.17g U=%.17g Q=%.17g ' ...
  'den=%.17g R=%.17g finite=%d\n'], mu, trace_constant, ...
  epsilon_boundary, U_lower, Q_bar, denominator, spectral_distance_bound, ...
  finite_bound);
end

%% ==================== Validation and finite certificates ====================
% These helpers map the frozen I5 scientific object to T9--T10 and N6--N9.

function LOCAL_validate(z, contract)
required = {'khat','gamma','mu_h','beta','d','R','rho_disk', ...
  'delta_c','delta_w','X_L','X_R','L','M','K','q_center', ...
  'Dplus','Dminus','Gplus','Gminus','Pplus','Pminus','cplus','cminus', ...
  'eta_unit_256','density_coordinate','xi_left_unit_512', ...
  'xi_right_unit_512','wall_input_unit_512','wall_orders_512'};
assert(all(isfield(z, required)));
K = double(z.K);
M = double(z.M);
assert(K == 2 * M + 1 && isequal(size(z.q_center), [2 * K, 1]));
assert(isequal(size(z.Gplus), [2 * K, K]) && ...
  isequal(size(z.Gminus), [2 * K, K]));
assert(isequal(size(z.Pplus), [K, K]) && ...
  isequal(size(z.Pminus), [K, K]));
assert(isequal(size(z.cplus), [K, 1]) && ...
  isequal(size(z.cminus), [K, 1]));
assert(isequal(size(z.eta_unit_256), [512, 2 * K]));
assert(strcmp(strtrim(char(z.density_coordinate)), ...
  '[tau;zeta], zeta=-sigma'));
assert(z.gamma == z.mu_h && z.mu_h == z.khat^2 && z.d == 1 && z.L == 1);
required_curve = {'schema','parameter_period','source_node_count', ...
  'density_coordinate','orientation','node_rule','adapter_metadata', ...
  'wall_left_x','wall_right_x'};
assert(all(isfield(contract, required_curve)));
assert(strcmp(char(contract.schema), 'TEP_I5_WALL_CURVE_CONTRACT_V1'));
assert(contract.parameter_period == 2 * pi && contract.source_node_count == 256);
assert(strcmp(char(contract.orientation), ...
  'counter-clockwise; outward normal=(dy_dt,-dx_dt)/speed'));
assert(strcmp(char(contract.node_rule), ...
  't_j=2*pi*j/N, j=0,...,N-1; no midpoint shift'));
assert(strcmp(strtrim(char(contract.density_coordinate)), ...
  strtrim(char(z.density_coordinate))));
assert(contract.adapter_metadata.radius == z.R && ...
  isequal(double(contract.adapter_metadata.center(:).'), [0, 0]));
assert(contract.wall_left_x == z.X_L && contract.wall_right_x == z.X_R);
end

