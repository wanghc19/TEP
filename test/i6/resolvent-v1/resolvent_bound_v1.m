function result = resolvent_bound_v1(candidate_path, v7_path, ...
    snapshot_path, output_path, json_path)
%RESOLVENT_BOUND_V1 Evaluate the first raw-jump resolvent distance estimate.
% Purpose:
%   Evaluate T9--T10 and F14 for the frozen I3 raw field using actual paired
%   material and artificial-wall value/ordinary-normal jumps.
% Input:
%   candidate_path - Frozen I3 certificate MAT file.
%   v7_path - Frozen signed-row evaluation bundle for normal and wall rows.
%   snapshot_path, output_path, json_path - Create-once run artifacts.
% Output:
%   result - Ordinary floating-point, non-certified formula evaluation.
% Main algorithm:
%   Reweight signed rows in ordinary L2, retain full propagation matrices,
%   bound infinite lead sequences by block powers, evaluate the exact empty-
%   center Rayleigh mass, and apply F14 when its denominator is positive.
% Based on:
%   resolvent-bound T9--T10, F14, N1--N9 and frozen I5 signed-row formulas.
% Main changes:
%   Removes lift and negative-order weights; the empty center has no material
%   interface, while its two center/first-cell walls remain singletons.
% Numerical goal:
%   Produce a reproducible non-certified spectral-distance estimate.

timer = tic;
LOCAL_create_once(snapshot_path);
LOCAL_create_once(output_path);
LOCAL_create_once(json_path);

% --- stage 1: load and cross-check the frozen scientific object ---
candidate = load(candidate_path, 'staged');
rows7 = load(v7_path, 'experiment_input');
assert(isfield(candidate, 'staged') && isfield(candidate.staged, 'certificate'));
assert(isfield(rows7, 'experiment_input'));
z = candidate.staged.certificate;
i5v7 = rows7.experiment_input;
LOCAL_validate(z, i5v7);
configuration = struct('cell_cutoff', 16, 'wall_mode_cutoff', 256, ...
  'propagation_block_length', 32, 'material_mode_cutoff', 1024, ...
  'reference_length', double(z.d));
scientific_input = struct('schema', 'EPOST_I6_RESOLVENT_V1_INPUT', ...
  'candidate', z, 'configuration', configuration, ...
  'v7_signed_rows', i5v7);
save(snapshot_path, 'scientific_input', '-v7.3');

% --- stage 2: point-frequency trace constant ---
mu = double(z.khat)^2;
rho_min = min(1, double(z.rho_disk));
rho_max = max(1, double(z.rho_disk));
h = min(double(z.delta_c), double(z.delta_w));
kappa_max = 1 / double(z.R);
theta = 1 - h * kappa_max;
overlap = 1;
ell_ref = configuration.reference_length;
c0 = overlap / (theta * h);
c1 = overlap * h / (2 * theta);
trace_constant_squared = c0 / (rho_min * mu^2) + ...
  (c1 + ell_ref^2 * c0) / (4 * mu) + ...
  ell_ref^2 * c1 * rho_max;
trace_constant = sqrt(trace_constant_squared);
fprintf('STAGE trace C=%.17g C2=%.17g h=%.17g theta=%.17g\n', ...
  trace_constant, trace_constant_squared, h, theta);

% --- stage 3: full-matrix propagation certificates ---
propagation.minus = LOCAL_block(double(z.Pminus), ...
  configuration.propagation_block_length);
propagation.plus = LOCAL_block(double(z.Pplus), ...
  configuration.propagation_block_length);
assert(propagation.minus.pass && propagation.plus.pass);

% --- stage 4: material value and ordinary-normal L2 defects ---
[material_value, material_normal] = LOCAL_material( ...
  z, i5v7, configuration, propagation);
fprintf('STAGE material value2=%.17g normal2=%.17g\n', ...
  material_value.total_squared, material_normal.total_squared);

% --- stage 5: artificial-wall paired L2 defects ---
wall_raw = signed_wall_l2_v1(z, i5v7.geometry, configuration);
wall_value = LOCAL_wall_parts(wall_raw.value);
wall_normal = LOCAL_wall_parts(wall_raw.normal);
fprintf(['STAGE wall value2=%.17g normal2=%.17g primitiveFloor=%d ' ...
  'aggregateFloor=%d\n'], ...
  wall_value.total_squared, wall_normal.total_squared, ...
  wall_raw.tail_primitive_floor_applied, ...
  wall_raw.tail_aggregate_floor_applied);

value_squared = material_value.total_squared + wall_value.total_squared;
normal_squared = material_normal.total_squared + wall_normal.total_squared;
epsilon_boundary_squared = normal_squared + value_squared / ell_ref^2;
epsilon_boundary = sqrt(epsilon_boundary_squared);

% --- stage 6: empty-center raw mass lower evaluation ---
mass = LOCAL_center_mass(z);
U_lower = mass.analytic_norm;
Q_bar = trace_constant * epsilon_boundary;
denominator = U_lower - Q_bar;
epsilon_volume = 0;
if denominator > 0
  spectral_distance_bound = (2 * mu * Q_bar + epsilon_volume) / denominator;
  spectral_interval = [mu - spectral_distance_bound, ...
    mu + spectral_distance_bound];
  finite_bound = true;
else
  spectral_distance_bound = Inf;
  spectral_interval = [-Inf, Inf];
  finite_bound = false;
end
fprintf('STAGE mass U=%.17g quad_rel=%.17g eps=%.17g Q=%.17g den=%.17g\n', ...
  U_lower, mass.relative_quadrature_difference, epsilon_boundary, ...
  Q_bar, denominator);
checkpoint = struct('trace_constant', trace_constant, ...
  'material_value', material_value, 'material_normal', material_normal, ...
  'wall_value', wall_value, 'wall_normal', wall_normal, 'mass', mass, ...
  'epsilon_boundary', epsilon_boundary, 'Q_bar', Q_bar, ...
  'denominator', denominator, 'spectral_distance_bound', spectral_distance_bound);
save(snapshot_path, 'checkpoint', '-append');

% --- stage 7: audit, persist, and emit a light JSON summary ---
geometry = struct('period_x', double(z.L), 'period_y', double(z.d), ...
  'inclusion_radius', double(z.R), 'collar_half_width', h, ...
  'curvature_upper', kappa_max, 'theta', theta, ...
  'overlap_multiplicity', overlap, 'material_wall_disjoint', ...
  logical(i5v7.geometry.lift_geometry_gates.material_wall_disjoint), ...
  'material_cell_copy_disjoint', ...
  logical(i5v7.geometry.lift_geometry_gates.material_cell_copies_disjoint), ...
  'material_transverse_copy_disjoint', ...
  logical(i5v7.geometry.lift_geometry_gates.material_transverse_periodic_copies_disjoint), ...
  'wall_pair_disjoint', ...
  logical(i5v7.geometry.lift_geometry_gates.wall_pair_disjoint));
gates = struct('same_candidate_mu', mu == double(z.mu_h), ...
  'point_frequency_window', true, 'center_material_present', false, ...
  'material_singleton_count', 0, 'lead_material_n0_count', 2, ...
  'center_first_wall_count', 2, 'ordinary_normal_L2', true, ...
  'paired_value_L2', true, 'full_propagation_matrices', true, ...
  'propagation_factor_once', true, ...
  'analytic_exact_kernel_pde_assumption', true, ...
  'analytic_exact_quasiperiodic_assumption', true, ...
  'volume_defect_zero_in_ideal_model', true, ...
  'finite_nonnegative', all(isfinite([trace_constant, epsilon_boundary, ...
    U_lower, Q_bar])) && all([trace_constant, epsilon_boundary, U_lower, Q_bar] >= 0), ...
  'mass_quadrature_agreement', mass.relative_quadrature_difference < 2e-6, ...
  'denominator_positive', denominator > 0);
result = struct('schema', 'EPOST_I6_RESOLVENT_V1_RESULT', ...
  'status', 'NON_CERTIFIED_FORMULA_EVALUATION', ...
  'candidate', struct('khat', double(z.khat), 'mu', mu, ...
    'beta', double(z.beta)), ...
  'material', struct('rho_min', rho_min, 'rho_max', rho_max, ...
    'rho_disk', double(z.rho_disk)), ...
  'geometry', geometry, 'reference_length', ell_ref, ...
  'trace_constant_squared', trace_constant_squared, ...
  'trace_constant', trace_constant, ...
  'defect', struct('material_value', material_value, ...
    'material_normal', material_normal, 'wall_value', wall_value, ...
    'wall_normal', wall_normal, 'value_squared', value_squared, ...
    'normal_squared', normal_squared, ...
    'epsilon_boundary_squared', epsilon_boundary_squared, ...
    'epsilon_boundary', epsilon_boundary), ...
  'mass', mass, 'mass_is_certified_lower', false, ...
  'U_lower', U_lower, 'Q_bar', Q_bar, ...
  'normalized_defect_ratio', Q_bar / U_lower, ...
  'denominator', denominator, 'epsilon_volume', epsilon_volume, ...
  'spectral_distance_bound', spectral_distance_bound, ...
  'spectral_interval', spectral_interval, 'finite_bound', finite_bound, ...
  'propagation', propagation, 'gates', gates, ...
  'reliability', struct('level', 'ordinary floating-point non-certified', ...
    'special_function_enclosure', false, 'outward_rounding', false, ...
    'mass_single_sided_rounding', false, ...
    'analytic_infinite_cell_tails_included', true, ...
    'analytic_high_mode_tails_included', true, ...
    'wall_tail_floor_policy', wall_raw.tail_floor_policy, ...
    'wall_tail_primitive_floor_applied', ...
      wall_raw.tail_primitive_floor_applied, ...
    'wall_tail_aggregate_floor_applied', ...
      wall_raw.tail_aggregate_floor_applied, ...
    'candidate_search_repeated', false, 'pde_strategy', ...
    'ideal exact-kernel raw field; epsilon_volume=0', ...
    'quasiperiodic_strategy', ...
    'Rayleigh and quasi-periodic kernel definitions; seam defect=0', ...
    'row_bundle_binding_caveat', ...
    'same mu, geometry, density FFT, cutoffs and P certificates checked; no runtime hash'), ...
  'resource', struct('matlab_elapsed_seconds_before_save', toc(timer)));
save(output_path, 'result', '-v7.3');
summary = LOCAL_summary(result);
fid = fopen(json_path, 'w');
assert(fid >= 0, 'I6:JsonOpen', 'Could not create JSON output.');
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '%s\n', jsonencode(summary, 'PrettyPrint', true));
fprintf(['I6_RESULT mu=%.17g C=%.17g eps=%.17g U=%.17g Q=%.17g ' ...
  'den=%.17g R=%.17g finite=%d\n'], mu, trace_constant, ...
  epsilon_boundary, U_lower, Q_bar, denominator, spectral_distance_bound, ...
  finite_bound);
end

%% ==================== Validation and finite certificates ====================
% These helpers map the frozen I5 scientific object to T9--T10 and N6--N9.

function LOCAL_validate(z, i5v7)
required = {'khat','mu_h','beta','d','L','R','rho_disk','delta_c', ...
  'delta_w','K','M','q_center','Gplus','Gminus','Pplus','Pminus', ...
  'cplus','cminus'};
assert(all(isfield(z, required)));
assert(strcmp(i5v7.schema, 'EPOST_I5_1H_INPUT_V7'));
assert(i5v7.structural_pass);
assert(z.mu_h == z.khat^2 && z.d == 1 && z.L == 1);
assert(i5v7.geometry.curvature_upper == 1 / z.R);
assert(i5v7.geometry.lift_geometry_gates.all_collars_disjoint);
assert(i5v7.material.gates.value_sign && i5v7.material.gates.normal_sign);
assert(i5v7.geometry.mu_shift == z.mu_h);
assert(i5v7.geometry.boundary_length == 2 * pi * z.R);
assert(i5v7.geometry.speed_lower == z.R && ...
  i5v7.geometry.speed_upper == z.R);
assert(i5v7.configuration.cell_cutoff == 16 && ...
  i5v7.configuration.wall_mode_cutoff == 256 && ...
  i5v7.configuration.residual_mode_cutoff == 1024);
assert(i5v7.density.source_node_count == size(z.eta_unit_256, 1) / 2);
native_count = i5v7.density.source_node_count;
eta = double(z.eta_unit_256);
tau = fftshift(fft(eta(1:native_count, :), [], 1), 1) / native_count;
zeta = fftshift(fft(eta(native_count + 1:end, :), [], 1), 1) / native_count;
assert(isequal(tau, i5v7.density.tau_coeff) && ...
  isequal(zeta, i5v7.density.zeta_coeff));
assert(isequal(i5v7.material.mode_orders, (-1023:1023).'));
assert(isequal(size(i5v7.material.physical_center.val), [2047, 2 * z.K]) && ...
  isequal(size(i5v7.material.physical_center.nor), [2047, 2 * z.K]) && ...
  isequal(size(i5v7.material.analytic_radius.val), [2047, 1]) && ...
  isequal(size(i5v7.material.analytic_radius.nor), [2047, 1]));
wall_orders = (-256:256).';
beta_modes = double(z.beta) + 2 * pi * wall_orders / double(z.d);
gamma_modes = sqrt(complex(double(z.khat)^2 - beta_modes.^2));
assert(isequal([min(abs(gamma_modes)), max(abs(gamma_modes))], ...
  i5v7.wall.sf_ledger.gamma_abs_range));
for side_cell = {'minus', 'plus'}
  side = side_cell{1};
  certificate = LOCAL_block(double(z.(['P', side])), 32);
  assert(certificate.pass && ...
    certificate.block_norm == i5v7.propagation.(side).block_norm_upper && ...
    certificate.sum_power_squared_upper == ...
      i5v7.propagation.(side).sum_power_squared_upper);
end
end

function LOCAL_create_once(path)
assert(~isfile(path) && ~isfolder(path), 'I6:CreateOnce', ...
  'Every run artifact path must be new.');
assert(isfolder(fileparts(path)), 'I6:Parent', ...
  'Every run artifact parent directory must exist.');
end

function out = LOCAL_block(P, block_length)
power = eye(size(P));
power_norms = zeros(block_length, 1);
for index = 1:block_length
  power_norms(index) = norm(power, 'fro');
  power = P * power;
end
block_norm = norm(power, 'fro');
out = struct('block_length', block_length, 'block_norm', block_norm, ...
  'power_norms', power_norms, ...
  'sum_power_squared_upper', sum(power_norms.^2) / (1 - block_norm^2), ...
  'pass', isfinite(block_norm) && block_norm < 1);
end

%% ==================== Material-interface L2 accounting ====================
% Empty-center material is excluded; both lead sequences start at n=0.

function [value, normal] = LOCAL_material(z, v7, cfg, propagation)
J = cfg.cell_cutoff;
sides = {'minus', 'plus'};
Cv = double(v7.material.physical_center.val);
rv = double(v7.material.analytic_radius.val(:));
Cn = double(v7.material.physical_center.nor);
rn = double(v7.material.analytic_radius.nor(:));
value_finite = zeros(2, 1);
normal_finite = zeros(2, 1);
value_cell = zeros(2, 1);
normal_cell = zeros(2, 1);
for side_index = 1:2
  side = sides{side_index};
  G = double(z.(['G', side]));
  P = double(z.(['P', side]));
  state = double(z.(['c', side]));
  for n = 0:J - 1 %#ok<NASGU>
    field_state = G * state;
    value_finite(side_index) = value_finite(side_index) + ...
      sum((abs(Cv * field_state) + rv * norm(field_state)) .^ 2);
    normal_finite(side_index) = normal_finite(side_index) + ...
      sum((abs(Cn * field_state) + rn * norm(field_state)) .^ 2);
    state = P * state;
  end
  value_operator_squared = sum((vecnorm(Cv * G, 2, 2) + ...
    rv * norm(G, 'fro')) .^ 2);
  value_cell(side_index) = value_operator_squared * ...
    propagation.(side).sum_power_squared_upper * norm(state)^2;
  normal_operator_squared = sum((vecnorm(Cn * G, 2, 2) + ...
    rn * norm(G, 'fro')) .^ 2);
  normal_cell(side_index) = normal_operator_squared * ...
    propagation.(side).sum_power_squared_upper * norm(state)^2;
end
material_high = LOCAL_material_high(z, v7, cfg, propagation);
value = struct('method', 'v7 signed physical Fourier rows with unit L2 weight', ...
  'singleton_squared', 0, 'finite_minus_squared', value_finite(1), ...
  'finite_plus_squared', value_finite(2), ...
  'finite_squared', sum(value_finite), ...
  'cell_tail_minus_squared', value_cell(1), ...
  'cell_tail_plus_squared', value_cell(2), ...
  'cell_tail_squared', sum(value_cell), ...
  'high_mode_squared', material_high.value.total_squared, ...
  'high_mode_components', material_high.value, ...
  'total_squared', sum(value_finite) + sum(value_cell) + ...
    material_high.value.total_squared);
normal = struct('method', 'v7 signed physical Fourier rows with unit L2 weight', ...
  'singleton_squared', 0, 'finite_minus_squared', normal_finite(1), ...
  'finite_plus_squared', normal_finite(2), ...
  'finite_squared', sum(normal_finite), ...
  'cell_tail_minus_squared', normal_cell(1), ...
  'cell_tail_plus_squared', normal_cell(2), ...
  'cell_tail_squared', sum(normal_cell), ...
  'high_mode_squared', material_high.normal.total_squared, ...
  'high_mode_components', material_high.normal, ...
  'total_squared', sum(normal_finite) + sum(normal_cell) + ...
    material_high.normal.total_squared);
end

function out = LOCAL_material_high(z, v7, cfg, propagation)
Pcurve = double(v7.geometry.boundary_length);
Lcut = cfg.material_mode_cutoff;
normal_certificate = v7.local.derivative_certificate.nor;
value_certificate = v7.local.derivative_certificate.val;
local2 = 2 * double(normal_certificate.Q2)^2 / Pcurve * ...
  (Pcurve / (2 * pi))^4 * ...
  (Lcut^(-4) + Lcut^(-3) / 3);
local4 = 2 * double(normal_certificate.Q4)^2 / Pcurve * ...
  (Pcurve / (2 * pi))^8 * ...
  (Lcut^(-8) + Lcut^(-7) / 7);
local_normal = min(local2, local4);
local_value = 2 * double(value_certificate.Q4)^2 / Pcurve * ...
  (Pcurve / (2 * pi))^8 * ...
  (Lcut^(-8) + Lcut^(-7) / 7);
strip_width = double(v7.geometry.arclength_strip_width);
strip_ratio = exp(-4 * pi * strip_width / Pcurve);
regular_normal = 2 * Pcurve * double(v7.regular.normal_strip_upper)^2 * ...
  strip_ratio^Lcut / (1 - strip_ratio);
off_normal = 2 * Pcurve * double(v7.off_surface.normal_strip_upper)^2 * ...
  strip_ratio^Lcut / (1 - strip_ratio);
regular_value = 2 * Pcurve * double(v7.regular.value_strip_upper)^2 * ...
  strip_ratio^Lcut / (1 - strip_ratio);
off_value = 2 * Pcurve * double(v7.off_surface.value_strip_upper)^2 * ...
  strip_ratio^Lcut / (1 - strip_ratio);
state_energy = 0;
for side_cell = {'minus', 'plus'}
  side = side_cell{1};
  G = double(z.(['G', side]));
  c = double(z.(['c', side]));
  state_energy = state_energy + norm(G, 'fro')^2 * ...
    propagation.(side).sum_power_squared_upper * norm(c)^2;
end
common = struct('state_energy', state_energy, ...
  'parameter_strip_width', double(v7.geometry.parameter_strip_width), ...
  'arclength_strip_width', strip_width, 'geometric_ratio', strip_ratio, ...
  'cutoff', Lcut);
out.normal = common;
out.normal.local_p2_squared = local2;
out.normal.local_p4_squared = local4;
out.normal.local_selected_squared = local_normal;
out.normal.regular_squared = regular_normal;
out.normal.off_surface_squared = off_normal;
out.normal.total_squared = state_energy * ...
  (sqrt(local_normal) + sqrt(regular_normal) + sqrt(off_normal))^2;
out.value = common;
out.value.local_p4_squared = local_value;
out.value.regular_squared = regular_value;
out.value.off_surface_squared = off_value;
out.value.total_squared = state_energy * ...
  (sqrt(local_value) + sqrt(regular_value) + sqrt(off_value))^2;
end

%% ==================== Wall and raw-mass accounting ====================
% The wall helper has two singleton columns followed by paired lead walls.

function out = LOCAL_wall_parts(raw)
finite_terms = (abs(raw.row_center) + raw.row_radius) .^ 2;
singleton = sum(finite_terms(:, 1:2), 'all');
finite = sum(finite_terms(:, 3:end), 'all');
out = struct('singleton_squared', singleton, 'finite_squared', finite, ...
  'cell_tail_squared', raw.propagation_tail_squared, ...
  'high_mode_squared', raw.high_mode_tail_squared, ...
  'total_squared', singleton + finite + raw.propagation_tail_squared + ...
    raw.high_mode_tail_squared, 'state_labels', {raw.state_labels});
end

function out = LOCAL_center_mass(z)
K = double(z.K);
q_left = double(z.q_center(1:K));
q_right = double(z.q_center(K + 1:end));
orders = (-double(z.M):double(z.M)).';
beta_modes = double(z.beta) + 2 * pi * orders / double(z.d);
gamma_modes = sqrt(complex(double(z.khat)^2 - beta_modes.^2));
length_x = double(z.X_R) - double(z.X_L);
A = zeros(K, 1);
B = zeros(K, 1);
propagating = abs(imag(gamma_modes)) < 1e-13;
g = real(gamma_modes(propagating));
A(propagating) = length_x;
B(propagating) = length_x * sinc(g * length_x / pi);
kappa = imag(gamma_modes(~propagating));
A(~propagating) = -expm1(-2 * kappa * length_x) ./ (2 * kappa);
B(~propagating) = length_x * exp(-kappa * length_x);
lambda_plus = A + B;
lambda_minus = A - B;
assert(min([lambda_plus; lambda_minus]) >= -1e-13);
per_mode = 0.5 * lambda_plus .* abs(q_left + q_right).^2 + ...
  0.5 * lambda_minus .* abs(q_left - q_right).^2;
mass_squared = sum(per_mode);
x = linspace(0, length_x, 4001);
samples = q_left .* exp(1i * gamma_modes * x) + ...
  q_right .* exp(1i * gamma_modes * (length_x - x));
quadrature_squared = trapz(x, sum(abs(samples).^2, 1));
out = struct('method', 'exact empty-center Rayleigh Gram in rho=1', ...
  'rho_center', 1, 'analytic_squared', mass_squared, ...
  'analytic_norm', sqrt(mass_squared), ...
  'quadrature_squared_diagnostic', quadrature_squared, ...
  'relative_quadrature_difference', ...
  abs(quadrature_squared - mass_squared) / mass_squared, ...
  'minimum_gram_eigenvalue', min([lambda_plus; lambda_minus]), ...
  'per_mode_squared', per_mode);
end

