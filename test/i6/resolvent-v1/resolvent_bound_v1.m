    {'method', 'high_mode_components'}), ...
  'material_normal', rmfield(result.defect.material_normal, ...
    {'method', 'high_mode_components'}), ...
  'wall_value', rmfield(result.defect.wall_value, 'state_labels'), ...
  'wall_normal', rmfield(result.defect.wall_normal, 'state_labels'), ...
  'U_lower', result.U_lower, 'Q_bar', result.Q_bar, ...
  'normalized_defect_ratio', result.normalized_defect_ratio, ...
