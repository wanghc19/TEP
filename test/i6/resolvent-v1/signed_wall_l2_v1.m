function out = signed_wall_l2_v1(z, geometry, configuration)
%SIGNED_WALL_L2_V1 Evaluate actual paired wall jumps in ordinary L2.
% Purpose:
%   Evaluate general-curve Rayleigh rows, with explicit source quadrature and
%   positive-distance/whole-matrix tails. No historical residual rows are read.
% Input:
%   z - Frozen certificate; geometry - real nodes and analytic strip bounds;
%   configuration - cell_cutoff and propagation_block_length (optional).
% Output:
%   out.normal/out.value contain finite, cell-tail and high-mode L2 squares.
% Main algorithm:
%   Form each actual wall value and ordinary-normal jump before applying unit
%   Parseval weights, and use one block certificate for each paired sequence.
% Based on:
%   s-wall-tail.md, s-lift-tail.md (ME-21)--(ME-30), and design-5-1g.md.
% Main changes:
%   Replaces the old weighted residual modules by unit-weight L2 value and
%   ordinary-normal jumps for two central and two paired side sequences.
% Numerical goal:
%   Ordinary floating-point L2 evaluation; sf/fp remain UNRESOLVED.

geometry_pass = LOCAL_geometry_gate(geometry);
assert(geometry_pass,'I5v7Wall:Geometry','The general-curve certificate failed.');
assert(isfield(configuration,'wall_mode_cutoff') && ...
  isequal(double(configuration.wall_mode_cutoff),256), ...
  'I5v7Wall:Cutoff','The reviewed wall cutoff must be 256.');
orders = (-256:256).';
beta_m = double(z.beta) + 2*pi*orders/double(z.d);
gamma_m = sqrt(complex(double(z.khat)^2-beta_m.^2));
assert(all(abs(gamma_m)>0), 'I5v7Wall:Wood', 'A retained Wood mode exists.');
assert(all(real(gamma_m)>=0 & imag(gamma_m)>=0), ...
  'I5v7Wall:Branch', 'The outgoing branch failed.');
native_N = size(z.eta_unit_256,1)/2;
assert(mod(native_N,2)==0 && native_N==256);
density_orders = (-native_N/2:native_N/2-1).';
tau = fftshift(fft(double(z.eta_unit_256(1:native_N,:)),[],1),1)/native_N;
zeta = fftshift(fft(double(z.eta_unit_256(native_N+1:end,:)),[],1),1)/native_N;
t = geometry.parameter_nodes(:);
N = numel(t);
assert(max(abs(t-(0:N-1).'*2*pi/N)) < 1e-12);
basis = exp(1i*t*density_orders.');
tau_nodes = basis*tau;
zeta_nodes = basis*zeta;
[curve_left,eps_left,ledger_left] = LOCAL_curve_rows( ...
  z,geometry,-1,double(z.X_L),beta_m,gamma_m, ...
  tau_nodes,zeta_nodes,tau,zeta,density_orders);
[curve_right,eps_right,ledger_right] = LOCAL_curve_rows( ...
  z,geometry,1,double(z.X_R),beta_m,gamma_m, ...
  tau_nodes,zeta_nodes,tau,zeta,density_orders);

old_orders = double(z.wall_orders_512(:));
assert(isequal(old_orders,(-256:255).'));
xi_left = LOCAL_embed(double(z.xi_left_unit_512),old_orders,orders);
xi_right = LOCAL_embed(double(z.xi_right_unit_512),old_orders,orders);
input = double(z.wall_input_unit_512);
input_left = LOCAL_embed(input(1:512,:),old_orders,orders);
input_right = LOCAL_embed(input(513:end,:),old_orders,orders);
K = double(z.K);
state_orders = (-double(z.M):double(z.M)).';
selector = LOCAL_embed(eye(K),state_orders,orders);
assert(isequal(input_left,[selector,zeros(size(selector))]) && ...
  isequal(input_right,[zeros(size(selector)),selector]));
phase = exp(1i*gamma_m*(double(z.X_R)-double(z.X_L)));
flat_left = .5*(xi_left-phase.*xi_right);
flat_right = .5*(-phase.*xi_left+xi_right);
QL = flat_left+curve_left;
QR = flat_right+curve_right;
flat_value_left = 1i./(2*gamma_m).*(xi_left+phase.*xi_right);
flat_value_right = 1i./(2*gamma_m).*(phase.*xi_left+xi_right);
curve_value_left = curve_left./(1i*gamma_m);
curve_value_right = curve_right./(1i*gamma_m);
VL = input_left-flat_value_left-curve_value_left;
VR = input_right-flat_value_right-curve_value_right;
eps_VL = eps_left./abs(gamma_m);
eps_VR = eps_right./abs(gamma_m);
q_left = LOCAL_embed(double(z.q_center(1:K)),state_orders,orders);
q_right = LOCAL_embed(double(z.q_center(K+1:end)),state_orders,orders);
d_left = 1i*gamma_m.*(q_left-phase.*q_right);
d_right = 1i*gamma_m.*(phase.*q_left-q_right);
hc_left = LOCAL_embed(double(z.Dminus)*double(z.cminus), ...
  state_orders,orders)-(q_left+phase.*q_right);
hc_right = LOCAL_embed(double(z.Dplus)*double(z.cplus), ...
  state_orders,orders)-(phase.*q_left+q_right);

block_length = 32;
if isfield(configuration,'propagation_block_length')
  block_length = configuration.propagation_block_length;
end
assert(isscalar(block_length) && isfinite(block_length) && ...
  block_length>=1 && block_length==fix(block_length));
pp = LOCAL_block(double(z.Pplus),block_length);
pm = LOCAL_block(double(z.Pminus),block_length);
Gp = double(z.Gplus); Gm = double(z.Gminus);
Pp = double(z.Pplus); Pm = double(z.Pminus);
cp = double(z.cplus(:)); cm = double(z.cminus(:));
J = double(configuration.cell_cutoff);
assert(isscalar(J) && isfinite(J) && J>=0 && J==fix(J));
normal_weight = ones(size(beta_m));
lift_weight = ones(size(beta_m));
lift_weight_certificate = struct('ordinary_L2_weight', true, 'pass', true);
normal = LOCAL_empty;
lifting = LOCAL_empty;
normal = LOCAL_add(normal,d_right+QL*(Gp*cp), ...
  eps_left*norm(Gp*cp),abs(d_right)+abs(flat_left*(Gp*cp))+ ...
  abs(curve_left*(Gp*cp)),normal_weight,'center-first-plus');
normal = LOCAL_add(normal,-d_left+QR*(Gm*cm), ...
  eps_right*norm(Gm*cm),abs(d_left)+abs(flat_right*(Gm*cm))+ ...
  abs(curve_right*(Gm*cm)),normal_weight,'center-first-minus');
rp = QR*Gp+QL*Gp*Pp;
rm = QL*Gm+QR*Gm*Pm;
ep = eps_right*norm(Gp,'fro')+eps_left*norm(Gp*Pp,'fro');
em = eps_left*norm(Gm,'fro')+eps_right*norm(Gm*Pm,'fro');
center_minus = hc_left - VR*(Gm*cm);
center_plus = hc_right - VL*(Gp*cp);
center_minus_radius = eps_VR*norm(Gm*cm,2);
center_plus_radius = eps_VL*norm(Gp*cp,2);
center_minus_triangle = abs(LOCAL_embed(double(z.Dminus)*cm, ...
  state_orders,orders))+abs(q_left)+abs(phase.*q_right)+ ...
  abs(input_right*(Gm*cm))+abs(flat_value_right*(Gm*cm))+ ...
  abs(curve_value_right*(Gm*cm));
center_plus_triangle = abs(LOCAL_embed(double(z.Dplus)*cp, ...
  state_orders,orders))+abs(phase.*q_left)+abs(q_right)+ ...
  abs(input_left*(Gp*cp))+abs(flat_value_left*(Gp*cp))+ ...
  abs(curve_value_left*(Gp*cp));
lifting = LOCAL_add(lifting,center_minus,center_minus_radius, ...
  center_minus_triangle,lift_weight,'actual-center-first-minus');
lifting = LOCAL_add(lifting,center_plus,center_plus_radius, ...
  center_plus_triangle,lift_weight,'actual-center-first-plus');
Wp = VR*Gp - VL*Gp*Pp;
Wm = VL*Gm - VR*Gm*Pm;
Wp_radius = eps_VR*norm(Gp,'fro') + eps_VL*norm(Gp*Pp,'fro');
Wm_radius = eps_VL*norm(Gm,'fro') + eps_VR*norm(Gm*Pm,'fro');
xp=cp; xm=cm;
for n=0:J-1
  yp=Gp*xp; yp_next=Gp*(Pp*xp);
  ym=Gm*xm; ym_next=Gm*(Pm*xm);
  normal = LOCAL_add(normal,rp*xp,ep*norm(xp), ...
    abs(flat_right*yp)+abs(curve_right*yp)+ ...
    abs(flat_left*yp_next)+abs(curve_left*yp_next), ...
    normal_weight,sprintf('plus-%d',n));
  normal = LOCAL_add(normal,rm*xm,em*norm(xm), ...
    abs(flat_left*ym)+abs(curve_left*ym)+ ...
    abs(flat_right*ym_next)+abs(curve_right*ym_next), ...
    normal_weight,sprintf('minus-%d',n));
  lifting = LOCAL_add(lifting,Wp*xp,Wp_radius*norm(xp,2), ...
    abs(input_right*yp)+abs(flat_value_right*yp)+abs(curve_value_right*yp)+ ...
    abs(input_left*yp_next)+abs(flat_value_left*yp_next)+ ...
    abs(curve_value_left*yp_next),lift_weight,sprintf('actual-plus-%d',n));
  lifting = LOCAL_add(lifting,Wm*xm,Wm_radius*norm(xm,2), ...
    abs(input_left*ym)+abs(flat_value_left*ym)+abs(curve_value_left*ym)+ ...
    abs(input_right*ym_next)+abs(flat_value_right*ym_next)+ ...
    abs(curve_value_right*ym_next),lift_weight,sprintf('actual-minus-%d',n));
  xp=Pp*xp; xm=Pm*xm;
end
normal.propagation_tail_squared = ...
  LOCAL_omega(rp,ep,normal_weight)*pp.sum_power_squared_upper*norm(xp)^2+ ...
  LOCAL_omega(rm,em,normal_weight)*pm.sum_power_squared_upper*norm(xm)^2;
lifting.propagation_tail_squared = ...
  LOCAL_omega(Wp,Wp_radius,lift_weight)* ...
    pp.sum_power_squared_upper*norm(xp)^2+ ...
  LOCAL_omega(Wm,Wm_radius,lift_weight)* ...
    pm.sum_power_squared_upper*norm(xm)^2;
delta = min(geometry.left_clearance_lower,geometry.right_clearance_lower);
Pcurve = geometry.boundary_length;
[normal_plus_sequence,normal_primitive_1,normal_aggregate_1] = ...
  LOCAL_normal_high(z,delta,Pcurve,tau,zeta,{Gp,Gp*Pp});
[normal_minus_sequence,normal_primitive_2,normal_aggregate_2] = ...
  LOCAL_normal_high(z,delta,Pcurve,tau,zeta,{Gm,Gm*Pm});
[normal_plus_singleton,normal_primitive_3,normal_aggregate_3] = ...
  LOCAL_normal_high(z,delta,Pcurve,tau,zeta,{Gp*cp});
[normal_minus_singleton,normal_primitive_4,normal_aggregate_4] = ...
  LOCAL_normal_high(z,delta,Pcurve,tau,zeta,{Gm*cm});
normal.high_mode_tail_squared = ...
  normal_plus_sequence* ...
    pp.sum_power_squared_upper*norm(cp)^2+ ...
  normal_minus_sequence* ...
    pm.sum_power_squared_upper*norm(cm)^2+ ...
  normal_plus_singleton+normal_minus_singleton;
[lifting.high_mode_tail_squared, lifting_high_ledger] = ...
  LOCAL_paired_value_high(z,geometry,Pcurve,tau,zeta,Gp,Gm,Pp,Pm, ...
    cp,cm,pp,pm);
normal = LOCAL_finish(normal);
lifting = LOCAL_finish(lifting);
collar_count_pass = size(lifting.row_center,2)==2+2*J && ...
  numel(unique(lifting.state_labels))==2+2*J && ...
  size(normal.row_center,2)==2+2*J && ...
  numel(unique(normal.state_labels))==2+2*J;
index_partition = isequal(orders,(-256:256).') && ...
  isequal(old_orders,(-256:255).') && max(orders)+1==257;
governing_sources = {'eta_unit_256','xi_left_unit_512','xi_right_unit_512', ...
  'wall_input_unit_512','q_center','Dplus','Dminus','Gplus','Gminus', ...
  'Pplus','Pminus','cplus','cminus'};
forbidden_sources = {'Jplus','Jminus','center_wall_jumps', ...
  'center_left_value_mismatch','center_right_value_mismatch'};
stored_residuals_used = ~isempty(intersect(governing_sources,forbidden_sources));
global_lift_owner = 'ordinary L2 value jump; reference-length weight in caller';
all_squares = [normal.finite_squared,normal.signed_center_squared, ...
  normal.quadrature_radius_squared,normal.propagation_tail_squared, ...
  normal.high_mode_tail_squared,lifting.finite_squared, ...
  lifting.signed_center_squared,lifting.quadrature_radius_squared, ...
  lifting.propagation_tail_squared,lifting.high_mode_tail_squared, ...
  normal.bound_squared,lifting.bound_squared, ...
  normal.triangle_component_squared,lifting.triangle_component_squared];
gates = struct('outgoing_nonwood',all(abs(gamma_m)>0), ...
  'density_sign',strcmp(strtrim(z.density_coordinate),'[tau;zeta], zeta=-sigma'), ...
  'positive_clearance',delta>0, ...
  'high_evanescent_margin',2*pi*257/double(z.d)-abs(double(z.beta))>2*double(z.khat), ...
  'half_open_zero_extension',all(xi_left(end,:)==0)&all(xi_right(end,:)==0), ...
  'index_partition',index_partition,'actual_jump_count',collar_count_pass, ...
  'actual_jumps_paired',collar_count_pass && ...
    size(lifting.row_center,2)==2+2*J, ...
  'actual_jump_owner_complete',collar_count_pass && ...
    size(lifting.row_center,2)==2+2*J && ...
    lifting_high_ledger.pass && lifting_high_ledger.owner_count==1, ...
  'shared_identity_audited',isequal(input_left,[selector,zeros(size(selector))]) && ...
    isequal(input_right,[zeros(size(selector)),selector]), ...
  'both_raw_traces_formed_before_subtraction', ...
    isequal(Wp,VR*Gp-VL*Gp*Pp) && isequal(Wm,VL*Gm-VR*Gm*Pm), ...
  'ordinary_value_L2_weight',strcmp(global_lift_owner, ...
    'ordinary L2 value jump; reference-length weight in caller'), ...
  'ordinary_normal_L2_weight',all(normal_weight==1), ...
  'all_collars_disjoint',geometry.lift_geometry_gates.all_collars_disjoint, ...
  'all_rims_zero',geometry.lift_geometry_gates.all_rims_zero, ...
  'tail_map_specific_complete',lifting_high_ledger.pass, ...
  'tail_ownership_once',lifting_high_ledger.owner_count==1, ...
  'wall_cutoff_analytic',index_partition && ...
    lifting_high_ledger.first_omitted_absolute_order==257 && ...
    isfinite(lifting.high_mode_tail_squared) && ...
    lifting.high_mode_tail_squared>=0, ...
  'stored_residuals_used',stored_residuals_used,'geometry_certificate',geometry_pass, ...
  'propagation_plus',pp.pass,'propagation_minus',pm.pass, ...
  'trace_collars',1<=double(z.L) && 1<=double(z.X_R)-double(z.X_L), ...
  'lifting_collars',2*double(z.delta_w)<=double(z.L), ...
  'exterior_model',double(z.mu_h)==double(z.khat)^2, ...
  'finite',isreal(all_squares) && all(isfinite(all_squares)) && ...
    all(all_squares>=0) && isreal(normal_weight) && isreal(lift_weight) && ...
    all(isfinite([normal_weight;lift_weight])) && ...
    all([normal_weight;lift_weight]>0) && ...
    all(isfinite([normal.row_center(:);normal.row_radius(:); ...
      lifting.row_center(:);lifting.row_radius(:)])) && ...
    isreal(normal.row_radius) && isreal(lifting.row_radius) && ...
    all([normal.row_radius(:);lifting.row_radius(:)]>=0));
gates.pass=all([gates.outgoing_nonwood,gates.density_sign, ...
  gates.positive_clearance,gates.high_evanescent_margin, ...
  gates.half_open_zero_extension,gates.propagation_plus,gates.propagation_minus, ...
  gates.trace_collars,gates.lifting_collars,gates.exterior_model,gates.finite, ...
  gates.index_partition,gates.actual_jump_count,gates.actual_jumps_paired, ...
  gates.actual_jump_owner_complete, ...
  gates.shared_identity_audited,gates.both_raw_traces_formed_before_subtraction, ...
  gates.ordinary_value_L2_weight,gates.ordinary_normal_L2_weight, ...
  gates.all_collars_disjoint,gates.all_rims_zero, ...
  gates.tail_map_specific_complete,gates.tail_ownership_once, ...
  gates.wall_cutoff_analytic, ...
  ~gates.stored_residuals_used,geometry_pass]);
out=struct('normal',normal,'value',lifting,'mode_orders',orders, ...
  'cell_cutoff',J,'quadrature_nodes',N,'propagation_plus',pp, ...
  'propagation_minus',pm,'gates',gates,'delta_sf','UNRESOLVED', ...
  'delta_fp','UNRESOLVED','minimum_energy_factor',1, ...
  'minimum_energy_factor_included',false, ...
  'tail_floor_policy','positive geometric tails use a realmin floor', ...
  'tail_primitive_floor_applied',any([normal_primitive_1, ...
    normal_primitive_2,normal_primitive_3,normal_primitive_4, ...
    lifting_high_ledger.primitive_floor_applied]), ...
  'tail_aggregate_floor_applied',any([normal_aggregate_1, ...
    normal_aggregate_2,normal_aggregate_3,normal_aggregate_4, ...
    lifting_high_ledger.aggregate_floor_applied]), ...
  'tail_floor_applied',any([normal_primitive_1,normal_primitive_2, ...
    normal_primitive_3,normal_primitive_4,normal_aggregate_1, ...
    normal_aggregate_2,normal_aggregate_3,normal_aggregate_4, ...
    lifting_high_ledger.floor_applied]), ...
  'global_lift_owner',global_lift_owner,'governing_sources',{governing_sources}, ...
  'minimum_energy',struct('weight_certificate',lift_weight_certificate, ...
    'paired_plus_center',Wp,'paired_minus_center',Wm, ...
    'paired_plus_radius',Wp_radius,'paired_minus_radius',Wm_radius, ...
    'central_minus_center',center_minus,'central_plus_center',center_plus, ...
    'central_minus_radius',center_minus_radius, ...
    'central_plus_radius',center_plus_radius, ...
    'high_tail_ledger',lifting_high_ledger), ...
  'cutoff_selection',struct('retained_absolute_order',256, ...
    'first_omitted_absolute_order',257, ...
    'selection_owner','exact flat support plus explicit ME-28 tail', ...
    'center_drift_used',false,'pass',gates.wall_cutoff_analytic), ...
  'sf_ledger',struct('left',ledger_left,'right',ledger_right, ...
    'erfc_expint_bessel_hankel_qpgreen_calls',0, ...
    'finite_primitive_calls_present',true, ...
    'oracle_primitive_families',{{'exp','log','log1p','sqrt','tanh'}}, ...
    'finite_phase_exp_scalar_count',numel(basis)+numel(phase)+ ...
      ledger_left.exp_scalar_count+ledger_right.exp_scalar_count, ...
    'rayleigh_sqrt_scalar_count',numel(gamma_m), ...
    'gamma_abs_range',[min(abs(gamma_m)),max(abs(gamma_m))], ...
    'kernel','exact finite Rayleigh representation'));
assert(gates.pass,'I5v7Wall:Gate','A signed-wall structural gate failed.');
end

function [squared, ledger] = LOCAL_paired_value_high( ...
    z,g,Pcurve,tau,zeta,Gp,Gm,Pp,Pm,cp,cm,pp,pm)
collars = g.wall_lift_collars;
b = abs(double(z.beta));
mu = double(z.mu_h);
assert(collars.plus.pass && collars.minus.pass && mu > 0 && b >= 0);
[plus_sequence,plus_ledger] = LOCAL_paired_value_high_for_maps( ...
  z,g,Pcurve,tau,zeta,{Gp,Gp*Pp});
[minus_sequence,minus_ledger] = LOCAL_paired_value_high_for_maps( ...
  z,g,Pcurve,tau,zeta,{Gm,Gm*Pm});
[plus_central,plus_central_ledger] = LOCAL_paired_value_high_for_maps( ...
  z,g,Pcurve,tau,zeta,{Gp*cp});
[minus_central,minus_central_ledger] = LOCAL_paired_value_high_for_maps( ...
  z,g,Pcurve,tau,zeta,{Gm*cm});
squared = plus_sequence*pp.sum_power_squared_upper*norm(cp,2)^2+ ...
  minus_sequence*pm.sum_power_squared_upper*norm(cm,2)^2+ ...
  plus_central+minus_central;
parts = [plus_sequence,minus_sequence,plus_central,minus_central,squared];
ledger = struct('owner','ME-25--ME-28 complete paired actual-jump tail', ...
  'owner_count',1,'first_omitted_absolute_order',257, ...
  'plus_sequence',plus_ledger,'minus_sequence',minus_ledger, ...
  'plus_central',plus_central_ledger, ...
  'minus_central',minus_central_ledger,'ordinary_L2_weight',1, ...
  'primitive_floor_applied',any([plus_ledger.primitive_floor_applied, ...
    minus_ledger.primitive_floor_applied, ...
    plus_central_ledger.primitive_floor_applied, ...
    minus_central_ledger.primitive_floor_applied]), ...
  'aggregate_floor_applied',any([plus_ledger.aggregate_floor_applied, ...
    minus_ledger.aggregate_floor_applied, ...
    plus_central_ledger.aggregate_floor_applied, ...
    minus_central_ledger.aggregate_floor_applied]), ...
  'floor_applied',any([plus_ledger.underflow_floor_applied, ...
    minus_ledger.underflow_floor_applied, ...
    plus_central_ledger.underflow_floor_applied, ...
    minus_central_ledger.underflow_floor_applied]), ...
  'all_state_maps_included',numel(plus_ledger.map_labels)==2 && ...
    numel(minus_ledger.map_labels)==2 && ...
    numel(plus_central_ledger.map_labels)==1 && ...
    numel(minus_central_ledger.map_labels)==1, ...
  'pass',all(isfinite(parts)) && all(parts>=0) && ...
    plus_ledger.pass && minus_ledger.pass && ...
    plus_central_ledger.pass && minus_central_ledger.pass);
end

function [squared,ledger] = LOCAL_paired_value_high_for_maps( ...
    z,g,Pcurve,tau,zeta,maps)
At=0;
Az=0;
map_labels=cell(numel(maps),1);
for j=1:numel(maps)
  At=At+Pcurve*sum(vecnorm(tau*maps{j},2,2));
  Az=Az+Pcurve*sum(vecnorm(zeta*maps{j},2,2));
  map_labels{j}=sprintf('paired-curve-action-%d',j);
end
q0=2*pi/double(z.d);
m0=257;
b=abs(double(z.beta));
rho_exterior=1;
ke=double(z.khat)*sqrt(rho_exterior);
b0=q0*m0-b-ke;
Rbeta=1+ke/b0;
delta=min(g.left_clearance_lower,g.right_clearance_lower);
D=(2*Rbeta*At+Az/b0)/(2*sqrt(double(z.d)));
C=exp(delta*(ke+b))*D;
r=exp(-2*delta*q0);
primitive_floor_applied=m0*log(r)<log(realmin);
r_first=exp(max(log(realmin),m0*log(r)));
S0=r_first/(1-r);
raw_squared=2*C^2*S0;
aggregate_floor_applied=raw_squared<realmin;
squared=max(realmin,raw_squared);
values=[At,Az,q0,b,ke,b0,Rbeta,delta,D,C,r,S0,squared];
ledger=struct('map_labels',{map_labels},'density_tau_L1',At, ...
  'density_zeta_L1',Az,'normalization',1/(2*sqrt(double(z.d))), ...
  'rho_exterior',rho_exterior,'exterior_wavenumber',ke, ...
  'inverse_gamma_lower',b0,'beta_over_kappa_upper',Rbeta, ...
  'positive_distance',delta,'amplitude_D',D,'amplitude_C',C, ...
  'two_signs_combined_before_weight',true, ...
  'primitive_floor_applied',primitive_floor_applied, ...
  'aggregate_floor_applied',aggregate_floor_applied, ...
  'underflow_floor_applied', ...
    primitive_floor_applied||aggregate_floor_applied, ...
  'state_map_count',numel(maps),'pass',b0>0 && delta>0 && r>0 && r<1 && ...
    isequal(LOCAL_mu_contract(z,rho_exterior),true) && ...
    all(isfinite(values)) && all(values>=0));
end

function pass = LOCAL_mu_contract(z,rho_exterior)
pass=isequal(double(z.mu_h),double(z.khat)^2*rho_exterior);
end

%% ==================== General-curve quadrature ====================
% Strip bounds are geometry inputs, never maxima of sampled values.
function [rows,radius,ledger]=LOCAL_curve_rows( ...
    z,g,side,wall,beta_m,gamma_m,tau_nodes,zeta_nodes,tau,zeta,orders)
N=size(g.position,1); dt=2*pi/N;
distance=side*(wall-g.position(:,1));
assert(all(distance>0));
phase=exp(1i*distance*gamma_m.'-1i*g.position(:,2)*beta_m.');
factor=1i*(side*g.normal(:,1)*gamma_m.'+g.normal(:,2)*beta_m.');
scale=dt/(2*sqrt(double(z.d)));
rows=scale*((phase.*factor).'*(g.speed_nodes.*tau_nodes)+ ...
  phase.'*(g.speed_nodes.*zeta_nodes));
a=g.parameter_strip_width;
growth=exp(a*abs(orders));
D_tau=sum(growth.*vecnorm(tau,2,2));
D_zeta=sum(growth.*vecnorm(zeta,2,2));
if side<0
  delta=g.strip_left_clearance_lower;
else
  delta=g.strip_right_clearance_lower;
end

assert(a>0 && delta>0);
imag_position=g.strip_position_imag_upper;
log_phase=abs(real(gamma_m))*imag_position+abs(beta_m)*imag_position- ...
  imag(gamma_m)*delta;
normal_upper=g.source_normal_component_upper;
factor_bound=abs(gamma_m)*normal_upper(1)+abs(beta_m)*normal_upper(2);
M=g.strip_speed_upper/(2*sqrt(double(z.d)))* ...
  (factor_bound*D_tau+D_zeta);
log_denominator=a*N+log1p(-exp(-a*N));
radius=exp(max(log(realmin),log(4*pi)+log(M)+log_phase-log_denominator));
ledger=struct('exp_scalar_count',numel(phase), ...
  'exp_argument_real_range',[-max(imag(gamma_m))*max(distance),0], ...
  'strip_width',a,'minimum_strip_clearance',delta, ...
  'quadrature_radius_max',max(radius), ...
  'finite_evaluation','ORACLE; sf/fp UNRESOLVED', ...
  'source_jacobian_included_once',true);
end

function pass=LOCAL_geometry_gate(g)
required={'parameter_nodes','position','normal','speed_nodes','speed_upper', ...
  'boundary_length', ...
  'parameter_strip_width','strip_speed_upper','strip_position_imag_upper', ...
  'source_normal_component_upper','strip_left_clearance_lower', ...
  'strip_right_clearance_lower','left_clearance_lower','right_clearance_lower', ...
  'strip_certificate_pass','outward_normal_contract_pass','parameter_grid_contract_pass', ...
  'wall_lift_collars','lift_geometry_gates'};
pass=all(isfield(g,required));
if ~pass
  return;
end
N=numel(g.parameter_nodes);
bounds=[g.boundary_length,g.speed_upper,g.parameter_strip_width,g.strip_speed_upper, ...
  g.strip_left_clearance_lower,g.strip_right_clearance_lower, ...
  g.left_clearance_lower,g.right_clearance_lower];
nonnegative=[g.strip_position_imag_upper,g.source_normal_component_upper];
pass=N>=2 && mod(N,2)==0 && isequal(size(g.position),[N,2]) && ...
  isequal(size(g.normal),[N,2]) && numel(g.speed_nodes)==N && ...
  isreal(g.position) && isreal(g.normal) && isreal(g.speed_nodes) && ...
  numel(g.source_normal_component_upper)==2 && ...
  isreal(bounds) && all(isfinite(bounds)) && all(bounds>0) && ...
  isreal(nonnegative) && all(isfinite(nonnegative)) && all(nonnegative>=0) && ...
  all(isfinite([g.position(:);g.normal(:);g.speed_nodes(:);g.parameter_nodes(:)])) && ...
  all(g.speed_nodes>0) && logical(g.strip_certificate_pass) && ...
  logical(g.outward_normal_contract_pass) && logical(g.parameter_grid_contract_pass) && ...
  isfield(g.wall_lift_collars,'plus') && isfield(g.wall_lift_collars,'minus') && ...
  g.wall_lift_collars.plus.pass && g.wall_lift_collars.minus.pass && ...
  g.lift_geometry_gates.all_collars_disjoint && ...
  g.lift_geometry_gates.all_rims_zero;
end

%% ==================== Finite and infinite state sums ====================
% Frobenius bounds replace infinite-dimensional or spectral-radius proxies.
function out=LOCAL_block(P,b)
power=eye(size(P)); norms=zeros(b,1);
for j=1:b
  if j==1
    norms(j)=1;
  else
    norms(j)=norm(power,'fro');
  end
  power=power*P;
end
contraction=norm(power,'fro');
assert(contraction<1,'I5v7Wall:Propagation','Block power is not contractive.');
out=struct('block_length',b,'block_upper',contraction, ...
  'power_upper',norms,'sum_power_squared_upper',sum(norms.^2)/(1-contraction^2), ...
  'pass',isfinite(contraction)&&contraction<1);
end

function out=LOCAL_empty
out=struct('finite_squared',0,'signed_center_squared',0, ...
  'quadrature_radius_squared',0,'triangle_component_squared',0, ...
  'row_center',[],'row_radius',[],'row_weight',[],'state_labels',{{}});
end

function out=LOCAL_add(out,c,r,triangle,weight,label)
out.finite_squared=out.finite_squared+sum(weight.*(abs(c)+r).^2);
out.signed_center_squared=out.signed_center_squared+sum(weight.*abs(c).^2);
out.quadrature_radius_squared=out.quadrature_radius_squared+sum(weight.*r.^2);
out.triangle_component_squared=out.triangle_component_squared+sum(weight.*triangle.^2);
out.row_center(:,end+1)=c;
out.row_radius(:,end+1)=r;
out.row_weight=weight;
out.state_labels{end+1}=label;
end

function value=LOCAL_omega(C,r,weight)
value=sum(weight.*(vecnorm(C,2,2)+r).^2);
end

function out=LOCAL_finish(out)
out.bound_squared=out.finite_squared+out.propagation_tail_squared+ ...
  out.high_mode_tail_squared;
out.signed_center_norm=sqrt(out.signed_center_squared);
out.non_special_function_radius_norm=sqrt(out.quadrature_radius_squared);
out.omission_tail_norm=sqrt(out.propagation_tail_squared+out.high_mode_tail_squared);
out.cancellation_ratio=sqrt(out.signed_center_squared/ ...
  max(realmin,out.triangle_component_squared));
out.retained_rows=struct('signed_center',out.row_center, ...
  'quadrature_radius',out.row_radius,'weight',out.row_weight, ...
  'state_labels',{out.state_labels});
end

%% ==================== Positive-distance high-mode tails ====================
% Two-sided geometric moments include only absolute orders at least 257.
function [value,primitive_floor_applied,aggregate_floor_applied]= ...
    LOCAL_normal_high(z,delta,Pcurve,tau,zeta,maps)
At=0; Az=0;
for j=1:numel(maps)
  At=At+Pcurve*sum(vecnorm(tau*maps{j},2,2));
  Az=Az+Pcurve*sum(vecnorm(zeta*maps{j},2,2));
end
q0=2*pi/double(z.d); b=abs(double(z.beta)); k=double(z.khat);
first=257; b0=q0*first-b; assert(b0>2*k);
r=exp(-2*delta*q0);
primitive_floor_applied=first*log(r)<log(realmin);
r_first=exp(max(log(realmin),first*log(r)));
S0=r_first/(1-r);
S1=r_first*(first/(1-r)+r/(1-r)^2);
S2=r_first*(first^2/(1-r)+2*first*r/(1-r)^2+ ...
  r*(1+r)/(1-r)^3);
bracket=4*At^2*(q0^2*S2+2*q0*b*S1+b^2*S0)+ ...
  4*At*Az*(q0*S1+b*S0)+Az^2*S0;
raw_value=exp(2*delta*(b+k))/(2*double(z.d))*bracket;
aggregate_floor_applied=raw_value<realmin;
value=max(realmin,raw_value);
end

function out=LOCAL_embed(values,source_orders,target_orders)
[present,at]=ismember(source_orders,target_orders);
assert(all(present));
out=zeros(numel(target_orders),size(values,2),'like',values);
out(at,:)=values;
end
