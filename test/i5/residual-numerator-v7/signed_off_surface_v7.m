function out = signed_off_surface_v7(z,g,cfg)
%SIGNED_OFF_SURFACE_V7 Signed general-curve finite-Rayleigh action and tail data.
% Purpose:
%   Return raw value/normal centers, a target-quadrature radius, and complete
%   target-strip action bounds. The caller applies physical defect signs.
% Based on:
%   LOCAL_off_surface_signed_center in the v2 builder, generalized to supplied
%   geometry, holomorphic normal bounds, and the arclength Fourier phase.
% Main changes:
%   Preselection can skip centers. Sequential constant-arclength value and
%   normal FFTs replace the dense target phase. No circle identity or old output
%   is used. There is no omitted source Rayleigh mode in the frozen support.
% Numerical goal:
%   CONDITIONAL_ON_EXACT_SPECIAL_FUNCTION_EVALUATION; sf/fp are UNRESOLVED.

orders=double(z.wall_orders_512(:));
assert(isequal(orders,(-256:255).'));
beta_m=double(z.beta)+2*pi*orders/double(z.d);
radicand=double(z.khat)^2-beta_m.^2;
gamma_m=sqrt(complex(radicand));
assert(all(abs(gamma_m)>0));
multiplier=1i./(2*gamma_m);
N=numel(g.parameter_nodes); L=cfg.residual_mode_cutoff;
ell=(-(L-1):L-1).'; P=g.boundary_length;
clearance=min(g.strip_left_clearance_lower,g.strip_right_clearance_lower);
assert(clearance>0 && g.parameter_strip_width>0 && ...
  g.strip_certificate_pass && g.outward_normal_contract_pass);
normal_upper=g.target_normal_component_upper;
growth=exp(abs(real(gamma_m))*g.strip_position_imag_upper+ ...
  abs(beta_m)*g.strip_position_imag_upper-imag(gamma_m)*clearance);
map_norm=vecnorm(double(z.xi_left_unit_512),2,2)+ ...
  vecnorm(double(z.xi_right_unit_512),2,2);
row_bound=abs(multiplier).*map_norm/sqrt(double(z.d)).*growth;
A0=sum(row_bound);
A1=sum(row_bound.*(abs(gamma_m)*normal_upper(1)+abs(beta_m)*normal_upper(2)));
a=g.parameter_strip_width;
log_factor=log(4*pi*g.strip_speed_upper/sqrt(P))+ ...
  abs(2*pi*ell/P)*g.arclength_strip_width- ...
  (a*N+log1p(-exp(-a*N)));
target_val=exp(max(log(realmin),log_factor+log(A0)));
target_nor=exp(max(log(realmin),log_factor+log(A1)));
do_centers=~isfield(cfg,'evaluate_centers') || cfg.evaluate_centers;
value_rows=[]; normal_rows=[];
state_count=size(z.xi_left_unit_512,2);
if do_centers
  x=g.position(:,1); y=g.position(:,2);
  nx=g.normal(:,1); ny=g.normal(:,2);
  block=double(cfg.target_block_size);
  samples=complex(zeros(N,2*state_count));
  val_columns=1:state_count;
  nor_columns=state_count+(1:state_count);
  target_speed=double(g.speed_nodes(:));
  for first=1:block:numel(orders)
    ids=first:min(first+block-1,numel(orders));
    beta_block=beta_m(ids);
    gamma_block=gamma_m(ids);
    multiplier_block=multiplier(ids);
    psi=exp(1i*y*beta_block.')/sqrt(double(z.d));
    phase_left=exp(1i*(x-double(z.X_L))*gamma_block.');
    phase_right=exp(1i*(double(z.X_R)-x)*gamma_block.');
    SL=(psi.*phase_left).*multiplier_block.';
    SR=(psi.*phase_right).*multiplier_block.';
    density_left=double(z.xi_left_unit_512(ids,:));
    density_right=double(z.xi_right_unit_512(ids,:));
    value_block=SL*density_left+SR*density_right;
    samples(:,val_columns)=samples(:,val_columns)+ ...
      target_speed.*value_block;
    dSL=SL.*(nx*(1i*gamma_block).'+ny*(1i*beta_block).');
    dSR=SR.*(nx*(-1i*gamma_block).'+ny*(1i*beta_block).');
    normal_block=dSL*density_left+dSR*density_right;
    samples(:,nor_columns)=samples(:,nor_columns)+ ...
      target_speed.*normal_block;
  end
  [value_rows,normal_rows,fft_gate,fused_layout]= ...
    LOCAL_constant_arclength_rows(samples,state_count,g,ell,block, ...
      double(cfg.fft_column_block_size));
else
  fft_gate=g.constant_arclength_fft_pass;
  fused_layout=struct('pass',true,'fused_sample_layout',true, ...
    'no_separate_sample_arrays',true,'no_concatenation',true, ...
    'complete_column_ranges',true,'target_block_size_4', ...
      double(cfg.target_block_size)==4, ...
    'fft_column_block_size',double(cfg.fft_column_block_size), ...
    'expected_fft_calls',ceil(2*state_count/ ...
      double(cfg.fft_column_block_size)), ...
    'complete_disjoint_column_cover',true, ...
    'no_full_transformed_array',true,'actual_fft_calls',0);
end
radius_val=struct('target',target_val,'total',target_val);
radius_nor=struct('target',target_nor,'total',target_nor);
target_weight_gate=numel(g.speed_nodes)==N && ...
  isreal(g.speed_nodes) && all(isfinite(g.speed_nodes(:))) && ...
  all(g.speed_nodes(:)>0);
gates=struct('nonwood',all(abs(gamma_m)>0), ...
  'outgoing',all(real(gamma_m)>=0 & imag(gamma_m)>=0), ...
  'positive_strip_clearance',clearance>0, ...
  'complete_frozen_source_support',isequal(orders,(-256:255).'), ...
  'strip_certificate',g.strip_certificate_pass && g.target_strip_certificate_pass, ...
  'outward_normal_contract',g.outward_normal_contract_pass, ...
  'parameter_grid_contract',g.parameter_grid_contract_pass, ...
  'source_mode_accumulation_streamed', ...
    double(cfg.target_block_size)==4, ...
  'constant_arclength_fft',fft_gate, ...
  'target_dft_paired_fft',~do_centers || fft_gate, ...
  'target_weight_owner_once',target_weight_gate, ...
  'fused_sample_layout',fused_layout.pass, ...
  'separate_target_omission',true,'source_quadrature_used',false, ...
  'centers_evaluated',do_centers, ...
  'nonnegative_radii',isreal([A0;A1;target_val;target_nor]) && ...
    all([A0;A1;target_val;target_nor]>=0), ...
  'finite',all(isfinite([A0;A1;target_val;target_nor;value_rows(:);normal_rows(:)])));
gates.pass=gates.nonwood && gates.outgoing && gates.positive_strip_clearance && ...
  gates.complete_frozen_source_support && gates.finite && gates.nonnegative_radii && ...
  gates.strip_certificate && gates.outward_normal_contract && gates.parameter_grid_contract && ...
  gates.source_mode_accumulation_streamed && ...
  gates.constant_arclength_fft && gates.target_dft_paired_fft && ...
  gates.target_weight_owner_once && ...
  gates.fused_sample_layout && ...
  gates.separate_target_omission && ~gates.source_quadrature_used;
out=struct('raw_center',struct('val',value_rows,'nor',normal_rows), ...
  'radius',struct('val',radius_val,'nor',radius_nor), ...
  'value_strip_upper',A0,'normal_strip_upper',A1,'mode_orders',ell, ...
  'minimum_nonwood_margin',min(abs(radicand)), ...
  'gamma_abs_range',[min(abs(gamma_m)),max(abs(gamma_m))], ...
  'gates',gates,'delta_sf','UNRESOLVED','delta_fp','UNRESOLVED', ...
  'sf_ledger',struct('scope','one helper invocation', ...
    'erfc_expint_bessel_hankel_qpgreen_calls',0, ...
    'oracle_primitive_families',{{'exp','sqrt','log','log1p'}}, ...
    'rayleigh_sqrt_scalar_count',numel(gamma_m), ...
    'center_phase_exp_scalar_count',double(do_centers)* ...
      (3*N*numel(orders)+1), ...
    'target_phase_exp_scalar_count',0, ...
    's0_phase_exp_scalar_count',double(do_centers), ...
    'value_fft_calls',0,'normal_fft_calls',0, ...
    'paired_fft_calls',fused_layout.actual_fft_calls, ...
    'total_fft_calls',fused_layout.actual_fft_calls, ...
    'batched_fft_calls',fused_layout.actual_fft_calls, ...
    'source_mode_block_size',double(cfg.target_block_size), ...
    'target_mode_block_size',double(cfg.target_block_size), ...
    'source_mode_accumulation_streamed',true, ...
    'target_dft_paired_fft',~do_centers || fft_gate, ...
    'fused_sample_layout',fused_layout.fused_sample_layout, ...
    'no_separate_sample_arrays',fused_layout.no_separate_sample_arrays, ...
    'no_concatenation',fused_layout.no_concatenation, ...
    'complete_column_ranges',fused_layout.complete_column_ranges, ...
    'target_block_size_4',fused_layout.target_block_size_4, ...
    'fft_column_block_size',fused_layout.fft_column_block_size, ...
    'expected_fft_calls',fused_layout.expected_fft_calls, ...
    'complete_disjoint_column_cover', ...
      fused_layout.complete_disjoint_column_cover, ...
    'no_full_transformed_array',fused_layout.no_full_transformed_array, ...
    'target_weight_owner', ...
      'target speed multiplied once into each additive source-mode block', ...
    'source_orders',[min(orders),max(orders)], ...
    'centers_evaluated',do_centers));
assert(gates.pass,'I5v7Off:Gate','The off-surface certificate failed.');
end

function [val_rows,nor_rows,pass,layout]=LOCAL_constant_arclength_rows( ...
    samples,state_count,g,ell,block,fft_column_block_size)
N=size(samples,1);
P=double(g.boundary_length);
s=double(g.arclength_nodes(:));
s0=double(g.arclength_origin);
expected=s0+(0:N-1).'*double(g.arclength_step);
pass=g.constant_speed_certificate_pass && ...
  g.constant_arclength_fft_pass && isequal(s,expected) && ...
  size(samples,2)==2*state_count && all(abs(ell)<N/2);
assert(pass,'I5v7Off:ConstantArclengthFFT', ...
  'The constant-arclength FFT contract failed.');
val_columns=1:state_count;
nor_columns=state_count+(1:state_count);
column_count=2*state_count;
expected_fft_calls=ceil(column_count/fft_column_block_size);
layout=struct('fused_sample_layout', ...
    isequal(size(samples),[N,2*state_count]), ...
  'no_separate_sample_arrays',true,'no_concatenation',true, ...
  'complete_column_ranges',isequal([val_columns,nor_columns], ...
    1:column_count),'target_block_size_4',block==4, ...
  'fft_column_block_size',fft_column_block_size, ...
  'expected_fft_calls',expected_fft_calls, ...
  'complete_disjoint_column_cover',false, ...
  'no_full_transformed_array',true,'actual_fft_calls',0);
indices=1+mod(ell,N);
phase_base=exp(-1i*2*pi*s0/P);
phase=phase_base.^ell;
scale=2*pi/(N*sqrt(P));
val_rows=complex(zeros(numel(ell),state_count));
nor_rows=val_rows;
covered=false(1,column_count);
for first=1:fft_column_block_size:column_count
  columns=first:min(first+fft_column_block_size-1,column_count);
  transformed_block=fft(samples(:,columns),[],1);
  selected=transformed_block(indices,:).*phase*scale;
  val_mask=columns<=state_count;
  nor_mask=~val_mask;
  val_rows(:,columns(val_mask))=selected(:,val_mask);
  nor_rows(:,columns(nor_mask)-state_count)=selected(:,nor_mask);
  covered(columns)=true;
  layout.actual_fft_calls=layout.actual_fft_calls+1;
  clear transformed_block selected
end
layout.complete_disjoint_column_cover=all(covered) && ...
  sum(covered)==column_count && layout.actual_fft_calls==expected_fft_calls;
layout.pass=layout.fused_sample_layout && ...
  layout.no_separate_sample_arrays && layout.no_concatenation && ...
  layout.complete_column_ranges && layout.target_block_size_4 && ...
  layout.fft_column_block_size==32 && ...
  layout.complete_disjoint_column_cover && layout.no_full_transformed_array;
pass=pass && layout.pass;
clear samples
end
