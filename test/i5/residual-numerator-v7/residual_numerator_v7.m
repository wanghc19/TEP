function result = residual_numerator_v7(input_path, output_path)
%RESIDUAL_NUMERATOR_V7 Assemble the I5.1i FFT two-band conditional majorant.
% Purpose:
%   Combine the disjoint material core, signed recapture band, far p=4 tail,
%   unchanged material-normal module, and unchanged paired-wall module.
% Input:
%   input_path - Explicit self-contained v7 MAT input.
%   output_path - Explicit create-once result MAT target.
% Output:
%   result - Three ideal modules, two-band decomposition, and gate audit.
% Main algorithm:
%   Validate the I5.1i finite-algebra gates and (I5.1h-5)--(I5.1h-12), add
%   disjoint collar energies, and keep
%   finite special-function and ordinary floating-point errors unresolved.
% Based on:
%   design-5-1h.md and s-lift-tail.md (ME-P4.17)--(ME-P4.22).

timer = tic;
[input_path, output_path] = LOCAL_paths(input_path, output_path);
loaded = load(input_path, 'experiment_input');
if ~isfield(loaded, 'experiment_input')
  error('I5v7:Schema', 'input_path lacks experiment_input.');
end
input = loaded.experiment_input;
audit = LOCAL_audit(input);
if ~audit.pass
  result = LOCAL_stopped(input, audit, toc(timer));
  save(output_path, 'result', '-v7.3');
  return;
end

wall_normal = double(input.wall.normal.bound_squared);
material_normal = double(input.material.finite.normal_squared) + ...
  double(input.material.cell_tail.normal_squared) + ...
  double(input.material.high_tail.normal_squared);
material_lift = double(input.material.finite.lifting_squared) + ...
  double(input.material.cell_tail.lifting_squared) + ...
  double(input.material.high_tail.lifting_squared);
wall_lift = double(input.wall.lifting.bound_squared);
B_Gamma_pm_ideal = sqrt(wall_normal);
B_Upsilon_ideal = sqrt(material_normal);
B_lift_ideal = sqrt(material_lift + wall_lift);
M_ideal = B_Gamma_pm_ideal + B_Upsilon_ideal + B_lift_ideal;
fft_reordering_difference = abs( ...
  M_ideal - double(input.configuration.attempt3_reference_M_ideal));
fft_reordering_diagnostic = struct( ...
  'attempt3_reference_M_ideal', ...
    double(input.configuration.attempt3_reference_M_ideal), ...
  'attempt7_M_ideal', M_ideal, ...
  'absolute_difference', fft_reordering_difference, ...
  'tolerance', double(input.configuration.fft_reordering_diagnostic_tolerance), ...
  'absolute_difference_gate', fft_reordering_difference <= ...
    double(input.configuration.fft_reordering_diagnostic_tolerance), ...
  'value_nonincrease_gate', M_ideal <= ...
    double(input.configuration.attempt3_reference_M_ideal) + ...
    double(input.configuration.fft_reordering_diagnostic_tolerance), ...
  'enters_selector', false, 'enters_reliability', false);
route_upgrade_required = ...
  ~isequal(input.cutoff_selection.tightness_pass, true) || ...
  ~isequal(input.evaluation_selection.tightness_pass, true);
% This post-selection fraction is a route diagnostic and never feeds L1 or N.
far_lifting_square_fraction = ...
  double(input.material.high_tail.far_lifting_squared) / ...
  max(realmin, material_lift + wall_lift);
next_method_required = route_upgrade_required || ...
  far_lifting_square_fraction >= 0.5;
final_values = [B_Gamma_pm_ideal; B_Upsilon_ideal; B_lift_ideal; M_ideal];
final_assembly_pass = isreal(final_values) && all(isfinite(final_values)) && ...
  all(final_values >= 0) && isreal(far_lifting_square_fraction) && ...
  isfinite(far_lifting_square_fraction) && ...
  far_lifting_square_fraction >= 0 && far_lifting_square_fraction <= 1;
audit.final_assembly_real_finite_nonnegative = final_assembly_pass;
audit.post_selection_far_fraction_finite_nonnegative = ...
  isreal(far_lifting_square_fraction) && ...
  isfinite(far_lifting_square_fraction) && ...
  far_lifting_square_fraction >= 0 && far_lifting_square_fraction <= 1;
audit.pass = audit.pass && final_assembly_pass;
if ~audit.pass
  result = LOCAL_stopped(input, audit, toc(timer));
  save(output_path, 'result', '-v7.3');
  return;
end

analytic_radius = LOCAL_radius_ownership(input);
center_diagnostic = LOCAL_center_diagnostic(input);
workspace = whos;
result = struct( ...
  'status', 'CONDITIONAL_TWO_BAND_P4_MAJORANT_SF_FP_UNRESOLVED', ...
  'claim_scope', input.claim_scope, ...
  'condition_label', input.condition_label, ...
  'certification_label', input.certification_label, ...
  'delta_sf', 'UNRESOLVED', 'delta_fp', 'UNRESOLVED', ...
  'M_ideal', M_ideal, 'numerical_reliable_majorant', 'UNRESOLVED', ...
  'B_Gamma_pm_ideal', B_Gamma_pm_ideal, ...
  'B_Upsilon_ideal', B_Upsilon_ideal, ...
  'B_lift_ideal', B_lift_ideal, ...
  'minimum_energy_lifting_factor', 1, ...
  'wall', struct('normal_squared', wall_normal, ...
    'normal', input.wall.normal, 'lifting', input.wall.lifting), ...
  'material', input.material, ...
  'two_band_decomposition', input.material.two_band, ...
  'analytic_radius_ownership', analytic_radius, ...
  'center_diagnostic', center_diagnostic, ...
  'component_share', struct( ...
    'B_Gamma_pm', B_Gamma_pm_ideal / max(realmin, M_ideal), ...
    'B_Upsilon', B_Upsilon_ideal / max(realmin, M_ideal), ...
    'B_lift', B_lift_ideal / max(realmin, M_ideal)), ...
  'cutoff_selection', input.cutoff_selection, ...
  'evaluation_selection', input.evaluation_selection, ...
  'tightness', input.tightness, ...
  'fft_reordering_diagnostic', fft_reordering_diagnostic, ...
  'route_gate', struct( ...
    'active_branch', 'two-band-p4-fallback', ...
    'full_p6_blocked', startsWith( ...
      input.configuration.full_p6_instance_status, 'BLOCKED:'), ...
    'full_p6_blocker', ...
      'order-six regular-image derivative certificate unavailable', ...
    'route_upgrade_required', route_upgrade_required, ...
    'far_lifting_square_fraction', far_lifting_square_fraction, ...
    'far_fraction_denominator', 'complete lifting bound squared', ...
    'next_method_required', next_method_required, ...
    'post_selection_only', true, ...
    'one_center_after_selection', true, 'center_drift_used', false), ...
  'sf_ledger', input.sf_ledger, ...
  'gate_audit', audit, ...
  'theorem_gate', struct( ...
    'two_band_analytic_pass', true, ...
    'conditional_diagnostic_pass', true, ...
    'delta_sf_resolved', false, 'delta_fp_resolved', false, ...
    'reliable_eval_enclosure_pass', false, ...
    'total_reliable_pass', false, 'outward_rounding', false), ...
  'provenance', input.provenance, ...
  'resource', struct('elapsed_seconds_before_save', toc(timer), ...
    'workspace_proxy_mib_before_save', sum([workspace.bytes]) / 2^20));
save(output_path, 'result', '-v7.3');
end

%% ==================== Portable input and fail-closed audit ====================
% The evaluator consumes one self-contained input and no historical output.

function [input_path, output_path] = LOCAL_paths(input_path, output_path)
input_path = LOCAL_path(input_path, 'input_path');
output_path = LOCAL_path(output_path, 'output_path');
if ~isfile(input_path)
  error('I5v7:InputPath', 'input_path must exist.');
end
if isfile(output_path) || isfolder(output_path)
  error('I5v7:CreateOnce', 'output_path must be a new target.');
end
if ~isfolder(fileparts(output_path))
  error('I5v7:OutputDirectory', 'The output directory does not exist.');
end
end

function value = LOCAL_path(value, name)
if isstring(value) && isscalar(value)
  value = char(value);
end
if ~ischar(value) || isempty(value)
  error('I5v7:Path', '%s must be nonempty text.', name);
end
end

