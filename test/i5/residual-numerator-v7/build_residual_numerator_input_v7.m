  'displacement_abs_upper', [2 * position_abs, 2 * position_abs], ...
  'displacement_real_upper', [2 * position_abs, 2 * position_abs], ...
  'displacement_imag_upper', [2 * position_imag, 2 * position_imag], ...
  'target_normal_component_upper', cosh(a) * [1, 1], ...
  'source_normal_component_upper', cosh(a) * [1, 1], ...
  'left_clearance_lower', abs(double(z.X_L)) - R, ...
  'right_clearance_lower', abs(double(z.X_R)) - R, ...
  'strip_left_clearance_lower', abs(double(z.X_L)) - position_abs, ...
  'strip_right_clearance_lower', abs(double(z.X_R)) - position_abs, ...
