derivative = [double(contour(2, :).'), double(contour(5, :).')];
speed = vecnorm(derivative, 2, 2);
normal = [derivative(:, 2), -derivative(:, 1)] ./ speed;
P = 2 * pi * R;
h = double(z.delta_c);
theta = 1 - h / R;
Theta = 1 + h / R;
if theta <= 0
  error('I5v7Input:Collar', 'The material collar exceeds the reach.');
