pre_configuration.residual_mode_cutoff = configuration.L1_schedule(1);
pre_configuration.evaluation_node_count = configuration.N_schedule(1);
pre_configuration.evaluate_centers = false;
pre_configuration.certificate_only = true;
pre_geometry = LOCAL_circle_geometry(z, pre_configuration);
regular_pre = signed_regular_image_v7( ...
  z, pre_geometry, pre_configuration, density);
off_pre = signed_off_surface_v7(z, pre_geometry, pre_configuration);
