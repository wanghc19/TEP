function side = LOCAL_collar_side(label, width, rho_upper, radius)
kappa_upper = 1 / radius;
theta = 1 - width * kappa_upper;
Theta = 1 + width * kappa_upper;
pass = width > 0 && rho_upper > 0 && theta > 0 && ...
  all(isfinite([width, rho_upper, kappa_upper, theta, Theta]));
side = struct('label', label, 'width', width, 'rho_upper', rho_upper, ...
  'curvature_upper', kappa_upper, 'theta_lower', theta, ...
  'Theta_upper', Theta, 'zero_rim', pass, ...
  'profile', 'sinh(alpha*(h-t))/sinh(alpha*h)', 'pass', pass);
end

function side = LOCAL_flat_collar_side(label, width, rho_upper)
pass = width > 0 && rho_upper > 0 && isfinite(width) && isfinite(rho_upper);
side = struct('label', label, 'width', width, 'rho_upper', rho_upper, ...
  'curvature_upper', 0, 'theta_lower', 1, 'Theta_upper', 1, ...
  'zero_rim', pass, 'profile', ...
  'sinh(lambda*(h-t))/sinh(lambda*h)', 'pass', pass);
end

function w = LOCAL_material_weights(z, g, L)
ell = (-(L - 1):L - 1).';
xi = 2 * pi * ell / g.boundary_length;
R = double(z.R);
h = double(z.delta_c);
theta = 1 - h / R;
Theta = 1 + h / R;
li = sqrt(double(z.mu_h) * double(z.rho_disk) + xi.^2 / (theta * Theta));
le = sqrt(double(z.mu_h) + xi.^2 / (theta * Theta));
trace = theta * li .* tanh(h * li) + theta * le .* tanh(h * le);
plus = g.material_lift_collars.plus;
minus = g.material_lift_collars.minus;
[kappa_plus, plus_pass] = LOCAL_collar_mode_cost( ...
  plus, double(z.mu_h), xi);
[kappa_minus, minus_pass] = LOCAL_collar_mode_cost( ...
  minus, double(z.mu_h), xi);
lift = kappa_plus .* kappa_minus ./ (kappa_plus + kappa_minus);
if any(~isfinite([trace; lift])) || any([trace; lift] <= 0)
  error('I5v7Input:Weights', 'A material trace/lift weight is invalid.');
end
w = struct('mode_orders', ell, 'trace', trace, ...
  'normal_inverse_trace', 1 ./ trace, 'lifting', lift, ...
  'minimum_energy', struct('kappa_plus', kappa_plus, ...
    'kappa_minus', kappa_minus, 'harmonic_weight', lift, ...
    'side_plus', plus, 'side_minus', minus), ...
  'gates', struct('plus_side', plus_pass, 'minus_side', minus_pass, ...
    'harmonic_formula', isequal(lift, ...
      kappa_plus .* kappa_minus ./ (kappa_plus + kappa_minus)), ...
    'positive_finite', isreal(lift) && all(isfinite(lift)) && ...
      all(lift > 0), ...
    'pass', plus_pass && minus_pass && isreal(lift) && ...
      all(isfinite(lift)) && all(lift > 0)));
end

function [kappa, pass] = LOCAL_collar_mode_cost(side, mu, xi)
A = double(side.Theta_upper);
B = xi.^2 / double(side.theta_lower) + ...
  mu * double(side.rho_upper) * double(side.Theta_upper);
alpha = sqrt(B / A);
kappa = sqrt(A * B) ./ tanh(double(side.width) * alpha);
zero = B == 0;
kappa(zero) = A / double(side.width);
pass = side.pass && mu > 0 && isreal(B) && all(isfinite(B)) && ...
  all(B >= 0) && isreal(kappa) && all(isfinite(kappa)) && all(kappa > 0);
end

%% ==================== Analytic cutoff and evaluation selection ====================
% Selection uses only proved remainders and never observed centre drift.

function [out, selected_local] = LOCAL_select_L( ...
    z, g, c, density, regular, off, propagation)
L_schedule = double(c.L1_schedule(:).');
candidate_count = numel(L_schedule);
candidate_trace_slope = NaN(1, candidate_count);
local_tail_norm = NaN(1, candidate_count);
regular_tail_norm = NaN(1, candidate_count);
off_tail_norm = NaN(1, candidate_count);
far_norm = NaN(1, candidate_count);
far_squared = NaN(1, candidate_count);
far_contribution = NaN(1, candidate_count);
analytic_gate = false(1, candidate_count);
candidate_local_sf_ledgers = cell(1, candidate_count);
candidate_local = cell(1, candidate_count);
state_sum = LOCAL_state_energy(z, propagation, 0);
for j = 1:candidate_count
  L = L_schedule(j);
  trial = c;
  trial.residual_mode_cutoff = L;
  trial.evaluation_node_count = c.N_schedule(1);
  trial.evaluate_centers = false;
  trial.certificate_only = true;
  local = signed_local_center_v7(z, g, trial, density);
  trace_slope = LOCAL_trace_slope(z, g, L);
  local_high = LOCAL_local_high_at(local.derivative_certificate, g, L, trace_slope);
  regular_high = LOCAL_strip_high(regular, g, L, trace_slope);
  off_high = LOCAL_strip_high(off, g, L, trace_slope);
  candidate_trace_slope(j) = trace_slope;
  local_tail_norm(j) = sqrt(local_high.val);
  regular_tail_norm(j) = sqrt(regular_high.val);
  off_tail_norm(j) = sqrt(off_high.val);
  far_norm(j) = local_tail_norm(j) + regular_tail_norm(j) + off_tail_norm(j);
  far_squared(j) = state_sum * far_norm(j)^2;
  far_contribution(j) = sqrt(far_squared(j));
  analytic_gate(j) = local.gates.active_branch_pass && ...
    local.gates.p4_factor_ratio && local.gates.p4_source_certificate && ...
    regular.gates.pass && off.gates.pass && ...
    all(isfinite([local_tail_norm(j), regular_tail_norm(j), ...
      off_tail_norm(j), far_norm(j), far_squared(j), far_contribution(j)])) && ...
    all([local_tail_norm(j), regular_tail_norm(j), ...
      off_tail_norm(j), far_norm(j), far_squared(j), far_contribution(j)] >= 0);
  candidate_local_sf_ledgers{j} = local.sf_ledger;
  candidate_local{j} = local;
end
first = find(analytic_gate & far_contribution < c.two_band_high_allocation, 1, 'first');
if isempty(first)
  selected = find(analytic_gate, 1, 'last');
  if isempty(selected)
    error('I5v7Input:LCertificate', ...
      'No preregistered L1 candidate passed every analytic gate.');
  end
  reason = 'largest analytic L1; far-tail allocation failed';
else
  selected = first;
  reason = 'first analytic L1 below the far-tail allocation';
end
selected_local = candidate_local{selected};
out = struct('candidate_L', L_schedule, ...
  'candidate_trace_slope', candidate_trace_slope, ...
  'local_tail_norm', local_tail_norm, ...
  'regular_tail_norm', regular_tail_norm, ...
  'off_surface_tail_norm', off_tail_norm, ...
  'far_norm', far_norm, 'far_squared', far_squared, ...
  'far_contribution', far_contribution, ...
  'candidate_analytic_gate', analytic_gate, ...
  'candidate_local_sf_ledgers', {candidate_local_sf_ledgers}, ...
  'allocation', c.two_band_high_allocation, ...
  'selected_index', selected, 'selected_L', L_schedule(selected), ...
  'selected_target_panels', c.value_convolution_target_panels, ...
  'selected_relative_panels', c.value_convolution_relative_panels, ...
  'tightness_pass', ~isempty(first), 'selection_reason', reason, ...
  'selection_owner', c.L1_selection_owner, ...
  'active_branch', 'two-band-p4-fallback', ...
  'center_evaluations', 0, 'center_drift_used', false, ...
  'pass', analytic_gate(selected) && ...
    all(isfinite([far_norm(selected), far_contribution(selected), ...
      candidate_trace_slope(selected)])) && candidate_trace_slope(selected) > 0);
if ~out.pass
  error('I5v7Input:LCertificate', 'The analytic L1 ledger is incomplete.');
end
end

function out = LOCAL_select_N(z, c, density, propagation)
L0 = double(c.core_mode_cutoff);
L1 = double(c.residual_mode_cutoff);
schedule = double(c.N_schedule(:).');
schedule = schedule(mod(schedule, 2) == 0 & ...
  schedule > 2 * max(L1, density.maximum_order));
if isempty(schedule)
  error('I5v7Input:NSchedule', 'No strict N candidate is available.');
end
band_radius_squared = NaN(size(schedule));
band_radius_contribution = NaN(size(schedule));
maximum_radius = NaN(size(schedule));
candidate_gate = false(size(schedule));
candidate_radius_edges = cell(size(schedule));
local_sf_ledger = cell(size(schedule));
regular_sf_ledger = cell(size(schedule));
off_sf_ledger = cell(size(schedule));
state_sum = LOCAL_state_energy(z, propagation, 0);
for j = 1:numel(schedule)
  trial = c;
  trial.evaluation_node_count = schedule(j);
  trial.evaluate_centers = false;
  trial.certificate_only = false;
  g = LOCAL_circle_geometry(z, trial);
  local = signed_local_center_v7(z, g, trial, density);
  regular = signed_regular_image_v7(z, g, trial, density);
  off = signed_off_surface_v7(z, g, trial);
  radius_edges = LOCAL_value_radius_edges(local, regular, off);
  w = LOCAL_material_weights(z, g, L1);
  band = abs(w.mode_orders) >= L0 & abs(w.mode_orders) < L1;
  band_radius_squared(j) = state_sum * ...
    sum(w.lifting(band) .* radius_edges.total(band).^2);
  band_radius_contribution(j) = sqrt(band_radius_squared(j));
  maximum_radius(j) = max(radius_edges.total(band));
  candidate_gate(j) = local.gates.active_branch_pass && ...
    local.gates.p4_factor_ratio && local.gates.p4_source_certificate && ...
    local.gates.p4_target_alias && local.gates.series_delta_tail_only && ...
    regular.gates.pass && off.gates.pass && radius_edges.gates.pass && ...
    any(band) && all(isfinite([band_radius_squared(j), ...
      band_radius_contribution(j), maximum_radius(j)])) && ...
    all([band_radius_squared(j), band_radius_contribution(j), ...
      maximum_radius(j)] >= 0);
  candidate_radius_edges{j} = radius_edges;
  local_sf_ledger{j} = local.sf_ledger;
  regular_sf_ledger{j} = regular.sf_ledger;
  off_sf_ledger{j} = off.sf_ledger;
end
first = find(candidate_gate & ...
  band_radius_contribution < c.two_band_retained_allocation, 1, 'first');
if isempty(first)
  selected = find(candidate_gate, 1, 'last');
  if isempty(selected)
    error('I5v7Input:NCertificate', ...
      'No strict preregistered N passed every band-radius gate.');
  end
  reason = 'largest analytic N; middle-band radius allocation failed';
else
  selected = first;
  reason = 'first strict N below the middle-band radius allocation';
end
out = struct('candidate_N', schedule, ...
  'band_radius_squared', band_radius_squared, ...
  'band_radius_contribution', band_radius_contribution, ...
  'maximum_unit_row_radius', maximum_radius, ...
  'candidate_analytic_gate', candidate_gate, ...
  'candidate_radius_edges', {candidate_radius_edges}, ...
  'allocation', c.two_band_retained_allocation, ...
  'selected_index', selected, 'selected_N', schedule(selected), ...
  'tightness_pass', ~isempty(first), 'selection_reason', reason, ...
  'selection_owner', c.N_selection_owner, ...
  'inter_level_drift_used', false, 'center_evaluations', 0, ...
  'local_preselection_sf_ledgers', {local_sf_ledger}, ...
  'regular_preselection_sf_ledgers', {regular_sf_ledger}, ...
  'off_preselection_sf_ledgers', {off_sf_ledger}, ...
  'pass', candidate_gate(selected) && ...
    all(isfinite([band_radius_squared(selected), ...
      band_radius_contribution(selected), maximum_radius(selected)])));
if ~out.pass
  error('I5v7Input:NCertificate', 'The analytic N selection gate failed.');
end
end

function out = LOCAL_value_radius_edges(local, regular, off)
