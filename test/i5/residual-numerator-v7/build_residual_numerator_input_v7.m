function out = LOCAL_tightness_diagnostic( ...
    z, c, w, local, regular, off, wall, material, propagation, ...
    evaluation_selection)
state_energy = LOCAL_state_energy(z, propagation, 0);
regular_normal = state_energy * sum(w.normal_inverse_trace .* ...
  double(regular.radius.nor.total(:)).^2);
regular_lifting = state_energy * sum(w.lifting .* ...
  double(regular.radius.val.total(:)).^2);
off_normal = state_energy * sum(w.normal_inverse_trace .* ...
  double(off.radius.nor.total(:)).^2);
off_lifting = state_energy * sum(w.lifting .* ...
  double(off.radius.val.total(:)).^2);
regular_wall_contribution = sqrt(regular_normal) + sqrt(regular_lifting) + ...
  sqrt(off_normal) + sqrt(off_lifting) + ...
  double(wall.normal.non_special_function_radius_norm) + ...
  double(wall.lifting.non_special_function_radius_norm) + ...
  sqrt(double(wall.normal.high_mode_tail_squared)) + ...
  sqrt(double(wall.lifting.high_mode_tail_squared));
cell_contribution = sqrt(material.cell_tail.normal_squared) + ...
  sqrt(material.cell_tail.lifting_squared) + ...
  sqrt(wall.normal.propagation_tail_squared) + ...
  sqrt(wall.lifting.propagation_tail_squared);
selected_index = double(evaluation_selection.selected_index);
band_radius = ...
  double(evaluation_selection.band_radius_contribution(selected_index));
out = struct( ...
  'far_allocation', c.two_band_high_allocation, ...
  'far_selected_contribution', sqrt(material.high_tail.far_lifting_squared), ...
  'far_pass', sqrt(material.high_tail.far_lifting_squared) < ...
    c.two_band_high_allocation, ...
  'band_radius_allocation', c.two_band_retained_allocation, ...
  'band_radius_selected_contribution', band_radius, ...
  'band_radius_pass', band_radius < c.two_band_retained_allocation, ...
  'regular_wall_allocation', c.regular_wall_allocation, ...
  'regular_wall_analytic_contribution', regular_wall_contribution, ...
  'regular_wall_pass', regular_wall_contribution <= c.regular_wall_allocation, ...
  'cell_tail_allocation', c.cell_tail_allocation, ...
  'cell_tail_contribution', cell_contribution, ...
  'cell_tail_pass', cell_contribution <= c.cell_tail_allocation, ...
  'allocation_failure_blocks_finite_report', false, ...
  'local_value_center_evaluated_once', local.centers_evaluated);
end
