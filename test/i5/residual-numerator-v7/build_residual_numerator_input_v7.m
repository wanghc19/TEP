  'strict_radius_only_N_selection', strict_radius_only_N_selection, ...
  'active_local_branch', strcmp(configuration.active_local_branch, ...
    'current-circle-value-convolution') && local.gates.active_branch_pass, ...
  'value_convolution_panel_certificate', ...
    local.value_convolution_certificate.gates.pass, ...
  'value_convolution_identity_once', ...
    local.value_convolution_certificate.gates.identity_included_once, ...
  'two_band_preregistered_schedules', ...
    isequal(configuration.core_mode_cutoff,256) && ...
    isequal(configuration.L1_schedule,[512,1024]) && ...
    isequal(configuration.N_schedule,[8192,16384]), ...
  'two_band_p4_fallback', material.gates.two_band_p4_fallback, ...
  'five_edge_radius_map', material.gates.five_edge_radius_map, ...
  'off_analytic_edge_zero_authorized', ...
    material.gates.off_analytic_edge_zero_authorized, ...
  'core_band_far_exhaustive', material.gates.core_band_far_exhaustive, ...
