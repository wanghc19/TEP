function experiment_input = build_residual_numerator_input_v7( ...
    artifact_path, curve_contract_path, input_path)
%BUILD_RESIDUAL_NUMERATOR_INPUT_V7 Build the I5.1h two-band fallback input.
% Purpose:
%   Instantiate the conditional I5.1h two-band p=4 fallback from
%   the explicit frozen certificate and curve contract. Historical experiment
%   inputs and outputs are not read.
% Input:
%   artifact_path - Explicit frozen I3 certificate MAT path.
%   curve_contract_path - Explicit accepted curve-contract MAT path.
%   input_path - Explicit create-once v7 MAT target.
% Output:
%   experiment_input - Self-contained centres, analytic radii and assemblies.
% Main algorithm:
%   Freeze L1 from the far p=4 tail, freeze N from the middle-band radius,
%   evaluate one signed centre, and assemble the disjoint core/band/far lift.
% Based on:
%   design-5-1h.md, equations (I5.1h-5)--(I5.1h-12), and
%   s-lift-tail.md, equations (ME-P4.17)--(ME-P4.22).
% Numerical goal:
%   Quantify the conditional ideal numerator with the lifting factor one,
%   while leaving delta_sf and delta_fp unresolved.

timer = tic;
[artifact_path, curve_contract_path, input_path] = LOCAL_paths( ...
  artifact_path, curve_contract_path, input_path);
loaded_artifact = load(artifact_path, 'staged');
loaded_curve = load(curve_contract_path, 'curve_contract');
if ~isfield(loaded_artifact, 'staged') || ...
    ~isfield(loaded_artifact.staged, 'certificate') || ...
    ~isfield(loaded_curve, 'curve_contract')
  error('I5v7Input:Schema', 'The explicit input MAT schema is invalid.');
