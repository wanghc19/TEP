    configuration.evaluation_node_count), ...
  'selected_trace_slope_match', selected_trace_slope_match, ...
  'selected_panel_match', selected_panel_match, ...
  'selected_far_match', selected_far_match, ...
  'selected_band_radius_match', selected_band_radius_match, ...
  'attempt3_expected_selection', attempt3_expected_selection_match, ...
  'attempt3_allocation_contract', attempt3_allocation_contract, ...
  'attempt3_provenance', attempt3_provenance, ...
  'streamed_memory_plan', configuration.target_block_size==16 && ...
    regular.gates.target_dft_streamed && ...
