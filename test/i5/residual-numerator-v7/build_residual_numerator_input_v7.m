  'wall_collars_injective', wall_plus.pass && wall_minus.pass, ...
  'material_wall_disjoint', material_wall_disjoint, ...
  'material_cell_copies_disjoint', material_cell_copy_disjoint, ...
  'material_transverse_periodic_copies_disjoint', ...
    material_transverse_copy_disjoint, ...
  'wall_pair_disjoint', wall_pair_disjoint, ...
  'all_collars_disjoint', material_wall_disjoint && ...
    material_cell_copy_disjoint && material_transverse_copy_disjoint && ...
    wall_pair_disjoint, ...
  'all_rims_zero', material_plus.zero_rim && material_minus.zero_rim && ...
    wall_plus.zero_rim && wall_minus.zero_rim, ...
  'simultaneous_jump_label_list_complete', ...
    numel(lift_interfaces)==3 && ...
    numel(unique(lift_interfaces))==3 && ...
    sum(strcmp(lift_interfaces,'material-interface'))==1 && ...
    sum(contains(lift_interfaces,'wall'))==2, ...
  'simultaneous_jump_labels', {lift_interfaces}, ...
  'jump_correction_sign', 'J_all e = -a', ...
  'broken_energy_direct_sum', material_wall_disjoint && ...
    material_cell_copy_disjoint && material_transverse_copy_disjoint && ...
    wall_pair_disjoint);
g = struct( ...
  'boundary_length', P, 'speed_lower', R, 'speed_upper', R, ...
  'mu_shift', double(z.mu_h), ...
  'speed_first_upper', 0, 'speed_second_upper', 0, ...
  'constant_speed_parameterization', true, ...
  'parameter_nodes', t, 'arclength_nodes', R * t, ...
  'position', position, 'normal', normal, 'speed_nodes', speed, ...
  'reach_lower', R, 'curvature_upper', 1 / R, ...
  'material_lift_collars', struct('plus', material_plus, ...
    'minus', material_minus), ...
