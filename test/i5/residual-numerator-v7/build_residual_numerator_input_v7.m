  evaluation_selection.selection_owner, configuration.N_selection_owner) && ...
  all(mod(evaluation_selection.candidate_N, 2) == 0) && ...
  all(evaluation_selection.candidate_N > 2 * max( ...
    configuration.residual_mode_cutoff, density.maximum_order));
attempt3_allocation_contract = isequal( ...
  configuration.two_band_high_allocation, ...
  configuration.allocation_reference_lifting_bound / 4) && ...
  isequal(configuration.two_band_retained_allocation, ...
  configuration.allocation_reference_lifting_bound / 4);
attempt3_provenance = strcmp(provenance.attempt_identifier, 'attempt-3') && ...
  strcmp(provenance.allocation_source, configuration.allocation_source) && ...
  isequal(provenance.allocation_reference_lifting_bound, ...
    configuration.allocation_reference_lifting_bound);
