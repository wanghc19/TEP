  'N=%d bandRadius=%.17g pass=%d. Starting one signed centre.\n'], ...
  configuration.core_mode_cutoff, ...
  configuration.residual_mode_cutoff, ...
  cutoff_selection.far_contribution(cutoff_selection.selected_index), ...
  cutoff_selection.tightness_pass, configuration.evaluation_node_count, ...
