configuration.certificate_only = false;
if ~isequal(configuration.residual_mode_cutoff, ...
    configuration.expected_selected_L1)
  error('I5v7Input:Attempt2L1', ...
    'Attempt 2 requires the far-only selector to freeze L1=1024.');
end

