  isequal(off.gates.source_quadrature_used, false) && ...
  isequal(off_analytic, zeros(size(off_analytic)));
values = [source; target; series; ewald; off_analytic; total];
gates = struct( ...
  'source_local_only', isequal(source, double(local.radius.val.source(:))), ...
  'target_complete_once', isequal(target, ...
    double(local.radius.val.target(:)) + ...
    double(regular.radius.val.target(:)) + double(off.radius.val.target(:))), ...
  'series_local_only', isequal(series, double(local.radius.val.series(:))), ...
  'ewald_complete_once', isequal(ewald, ...
    double(regular.radius.val.source(:)) + ...
    double(regular.radius.val.M_R(:)) + double(regular.radius.val.M_I(:)) + ...
    double(regular.radius.val.M_T(:)) + double(regular.radius.val.M_L(:))), ...
  'off_analytic_zero_authorized', off_zero_authorized, ...
  'sf_fp_remain_unresolved', strcmp(local.delta_sf, 'UNRESOLVED') && ...
    strcmp(regular.delta_sf, 'UNRESOLVED') && strcmp(off.delta_sf, 'UNRESOLVED') && ...
    strcmp(local.delta_fp, 'UNRESOLVED') && strcmp(regular.delta_fp, 'UNRESOLVED') && ...
    strcmp(off.delta_fp, 'UNRESOLVED'), ...
  'finite_nonnegative', same_size && isreal(values) && ...
    all(isfinite(values)) && all(values >= 0));
gates.pass = all(structfun(@(x) isequal(x, true), gates));
out = struct('source', source, 'target', target, 'series', series, ...
  'Ewald', ewald, 'off_analytic', off_analytic, 'total', total, ...
  'owner_labels', {{'local.val.source', ...
    'local.val.target + regular.val.target + off.val.target', ...
    'local.val.series', ...
    'regular.val.source + regular.val.M_R/M_I/M_T/M_L', ...
    'zero: off source_quadrature_used=false'}}, ...
  'gates', gates);
end
function high = LOCAL_local_high_at(certificate, g, L, trace_slope)
P = g.boundary_length;
tail_weight = LOCAL_material_tail_weight(g);
C0 = tail_weight.W0;
C1 = tail_weight.W1;
n2 = 2 * certificate.nor.Q2^2 / (P * trace_slope) * ...
  (P / (2 * pi))^5 * (L^(-5) + L^(-4) / 4);
v4 = 2 * certificate.val.Q4^2 / P * (C0 * (P / (2 * pi))^8 * ...
  (L^(-8) + L^(-7) / 7) + C1 * (P / (2 * pi))^7 * ...
  (L^(-7) + L^(-6) / 6));
n4 = 2 * certificate.nor.Q4^2 / (P * trace_slope) * ...
  (P / (2 * pi))^9 * (L^(-9) + L^(-8) / 8);
high = struct('val', v4, 'nor', min(n2, n4), ...
  'value_owner', ...
    'I5.1g-36d value-convolution Q4 in ME-18 affine harmonic tail', ...
  'normal_owner', 'unchanged minimum of established p2 and p4 tails', ...
  'index_owner', '|ell|>=L1', 'cutoff', L);
end

function out = LOCAL_material_tail_weight(g)
plus = g.material_lift_collars.plus;
minus = g.material_lift_collars.minus;
C0_plus = plus.Theta_upper / plus.width + plus.Theta_upper * ...
  sqrt(g.mu_shift * plus.rho_upper);
C0_minus = minus.Theta_upper / minus.width + minus.Theta_upper * ...
  sqrt(g.mu_shift * minus.rho_upper);
C1_plus = sqrt(plus.Theta_upper / plus.theta_lower);
C1_minus = sqrt(minus.Theta_upper / minus.theta_lower);
out = struct('C0_plus', C0_plus, 'C0_minus', C0_minus, ...
  'C1_plus', C1_plus, 'C1_minus', C1_minus, ...
  'W0', (C0_plus + C0_minus) / 4, ...
  'W1', (C1_plus + C1_minus) / 4);
end

function ctr = LOCAL_trace_slope(z, g, L)
R = double(z.R);
h = double(z.delta_c);
theta = 1 - h / R;
Theta = 1 + h / R;
xiL = 2 * pi * L / g.boundary_length;
ctr = 2 * sqrt(theta / Theta) * tanh(h * xiL / sqrt(theta * Theta));
end

function high = LOCAL_strip_high(certificate, g, L, trace_slope)
P = g.boundary_length;
r = exp(-4 * pi * g.arclength_strip_width / P);
normal_A = double(certificate.normal_strip_upper);
value_A = double(certificate.value_strip_upper);
S0 = r^L / (1 - r);
S1 = r^L * (L / (1 - r) + r / (1 - r)^2);
high.nor = P^2 * normal_A^2 / (pi * trace_slope) * ...
  r^L / (L * (1 - r));
tail_weight = LOCAL_material_tail_weight(g);
high.val = 2 * P * value_A^2 * (tail_weight.W0 * S0 + ...
  tail_weight.W1 * (2 * pi / P) * S1);
high.lifting_weight_owner = tail_weight;
high.index_owner = '|ell|>=L';
high.cutoff = L;
end

function energy = LOCAL_state_energy(z, propagation, start_cell)
cm = double(z.cminus(:));
cp = double(z.cplus(:));
for j = 1:start_cell
  cm = double(z.Pminus) * cm;
  cp = double(z.Pplus) * cp;
end
energy = norm(double(z.q_center), 2)^2 + ...
  norm(double(z.Gminus), 'fro')^2 * ...
    propagation.minus.sum_power_squared_upper * norm(cm, 2)^2 + ...
  norm(double(z.Gplus), 'fro')^2 * ...
    propagation.plus.sum_power_squared_upper * norm(cp, 2)^2;
end

function out = LOCAL_block_certificate(P, block_length)
P = double(P);
power = eye(size(P));
prefix = 0;
for j = 0:block_length - 1
  prefix = prefix + norm(power, 'fro')^2;
  power = P * power;
end
block = norm(power, 'fro');
pass = isfinite(block) && block < 1 && isfinite(prefix);
if pass
  total = prefix / (1 - block^2);
else
  total = Inf;
end
out = struct('block_length', block_length, 'block_norm_upper', block, ...
  'prefix_sum_upper', prefix, 'sum_power_squared_upper', total, 'pass', pass);
end

%% ==================== Signed material assembly ====================
% One physical centre and one triangle radius are weighted exactly once.

function out = LOCAL_material_assembly( ...
    z, geometry, c, w, local, regular, off, propagation)
ell = w.mode_orders;
L0 = double(c.core_mode_cutoff);
L1 = double(c.residual_mode_cutoff);
if ~isequal(local.mode_orders, ell, regular.mode_orders, ell, off.mode_orders, ell)
  error('I5v7Input:ModeOrder', 'Material retained row orders differ.');
end
if ~local.centers_evaluated || ~regular.gates.centers_evaluated || ...
    ~off.gates.centers_evaluated
  error('I5v7Input:Centers', 'The frozen signed centre was not evaluated.');
end
center_val = double(local.center.val) + double(regular.raw_center.val) + ...
  double(off.raw_center.val);
center_nor = double(local.center.nor) - double(regular.raw_center.nor) - ...
  double(off.raw_center.nor);
radius_edges = LOCAL_value_radius_edges(local, regular, off);
radius_val = radius_edges.total;
radius_nor = double(local.radius.nor.total(:)) + ...
  double(regular.radius.nor.total(:)) + double(off.radius.nor.total(:));
core = abs(ell) < L0;
band = abs(ell) >= L0 & abs(ell) < L1;
[states, labels, tail_states] = LOCAL_states(z, c.cell_cutoff);
finite_normal = 0;
finite_lifting = 0;
center_normal = 0;
center_lifting = 0;
radius_normal = 0;
radius_lifting = 0;
triangle_center_normal = 0;
triangle_center_lifting = 0;
for j = 1:numel(states)
  state = states{j};
  state_norm = norm(state, 2);
  cn = center_nor * state;
  cv = center_val * state;
  rn = radius_nor * state_norm;
  rv = radius_val * state_norm;
  triangle_nor = abs(double(local.center.nor) * state) + ...
    abs(double(regular.raw_center.nor) * state) + ...
    abs(double(off.raw_center.nor) * state);
  triangle_val = abs(double(local.center.val) * state) + ...
    abs(double(regular.raw_center.val) * state) + ...
    abs(double(off.raw_center.val) * state);
  finite_normal = finite_normal + ...
    sum(w.normal_inverse_trace .* (abs(cn) + rn).^2);
  finite_lifting = finite_lifting + ...
    sum(w.lifting(core) .* (abs(cv(core)) + rv(core)).^2);
  center_normal = center_normal + sum(w.normal_inverse_trace .* abs(cn).^2);
  center_lifting = center_lifting + ...
    sum(w.lifting(core) .* abs(cv(core)).^2);
  radius_normal = radius_normal + sum(w.normal_inverse_trace .* rn.^2);
  radius_lifting = radius_lifting + ...
    sum(w.lifting(core) .* rv(core).^2);
  triangle_center_normal = triangle_center_normal + ...
    sum(w.normal_inverse_trace .* triangle_nor.^2);
  triangle_center_lifting = triangle_center_lifting + ...
    sum(w.lifting(core) .* triangle_val(core).^2);
end
[cell_normal, cell_lifting, cell_ledger] = LOCAL_cell_tail( ...
  z, w, center_nor, center_val, radius_nor, radius_val, ...
  propagation, tail_states, true(size(ell)), core);
state_sum = LOCAL_state_energy(z, propagation, 0);
local_high = LOCAL_local_high_at(local.derivative_certificate, geometry, ...
  L1, geometry.trace_tail_slope_lower);
reg_high = LOCAL_strip_high(regular, geometry, ...
  L1, geometry.trace_tail_slope_lower);
off_high = LOCAL_strip_high(off, geometry, ...
  L1, geometry.trace_tail_slope_lower);
high_normal = state_sum * (sqrt(local_high.nor) + ...
  sqrt(reg_high.nor) + sqrt(off_high.nor))^2;
band_row_norm = vecnorm(center_val(band, :), 2, 2);
band_radius_lifting = state_sum * ...
  sum(w.lifting(band) .* radius_val(band).^2);
band_lifting = state_sum * sum(w.lifting(band) .* ...
  (band_row_norm + radius_val(band)).^2);
far_norm = sqrt(local_high.val) + sqrt(reg_high.val) + sqrt(off_high.val);
far_lifting = state_sum * far_norm^2;
band_cell_lifting = 0;
high_lifting = band_lifting + far_lifting;
all_values = [center_val(:); center_nor(:); radius_val; radius_nor; ...
  finite_normal; finite_lifting; cell_normal; cell_lifting; ...
  high_normal; band_lifting; far_lifting; high_lifting];
retained_index_pass = isequal(ell, (-(L1 - 1):L1 - 1).') && all(abs(ell) < L1);
three_sets_pass = L0 == 256 && L1 > L0 && ...
  ~any(core & band) && all(core | band) && ...
  all(abs(ell(core)) < L0) && ...
  all(abs(ell(band)) >= L0 & abs(ell(band)) < L1);
retained_state_owner_pass = numel(labels) == 1 + 2 * c.cell_cutoff && ...
  numel(unique(labels)) == 1 + 2 * c.cell_cutoff;
cell_owner_pass = numel(cell_ledger) == 2 && ...
  all(strcmp({cell_ledger.side}, {'minus', 'plus'})) && ...
  all(strcmp({cell_ledger.value_index_owner}, '|ell|<L0'));
high_owner_pass = strcmp(local_high.value_owner, ...
  'I5.1g-36d value-convolution Q4 in ME-18 affine harmonic tail') && ...
  strcmp(local_high.index_owner, '|ell|>=L1') && ...
  isequal(local_high.cutoff, L1) && ...
  strcmp(reg_high.index_owner, '|ell|>=L') && ...
  isequal(reg_high.cutoff, L1) && ...
  strcmp(off_high.index_owner, '|ell|>=L') && ...
  isequal(off_high.cutoff, L1);
finite_index_owner_pass = retained_index_pass && ...
  all(abs(ell) < L1) && all(abs(ell(core)) < L0);
tail_ownership_pass = retained_index_pass && three_sets_pass && ...
  cell_owner_pass && high_owner_pass && ...
  isequal(high_lifting, band_lifting + far_lifting);
actual_jump_owner_complete = retained_index_pass && retained_state_owner_pass && ...
  cell_owner_pass && high_owner_pass;
out = struct( ...
  'mode_orders', ell, ...
  'physical_center', struct('val', center_val, 'nor', center_nor), ...
  'analytic_radius', struct('val', radius_val, 'nor', radius_nor), ...
  'finite', struct('normal_squared', finite_normal, ...
    'lifting_squared', finite_lifting, ...
    'center_normal_squared', center_normal, ...
    'center_lifting_squared', center_lifting, ...
    'radius_normal_squared', radius_normal, ...
    'radius_lifting_squared', radius_lifting, ...
    'triangle_center_normal_squared', triangle_center_normal, ...
    'triangle_center_lifting_squared', triangle_center_lifting, ...
    'normal_cancellation_ratio', sqrt(center_normal / ...
      max(realmin, triangle_center_normal)), ...
    'lifting_cancellation_ratio', sqrt(center_lifting / ...
      max(realmin, triangle_center_lifting)), ...
    'state_labels', {labels}, ...
    'normal_index_owner', '|ell|<L1', ...
    'value_index_owner', '|ell|<L0'), ...
  'cell_tail', struct('normal_squared', cell_normal, ...
    'lifting_squared', cell_lifting, 'ledger', cell_ledger, ...
    'value_index_owner', '|ell|<L0'), ...
  'high_tail', struct('normal_squared', high_normal, ...
    'lifting_squared', high_lifting, ...
    'band_lifting_squared', band_lifting, ...
    'far_lifting_squared', far_lifting, 'far_norm', far_norm, ...
    'band_index_owner', 'L0<=|ell|<L1', ...
    'far_index_owner', '|ell|>=L1', ...
    'local', local_high, 'regular', reg_high, 'off_surface', off_high), ...
  'two_band', struct('L0', L0, 'L1', L1, ...
    'core_mask', core, 'band_mask', band, ...
    'state_energy', state_sum, 'radius_edges', radius_edges, ...
    'band_radius_squared', band_radius_lifting, ...
    'core_finite_squared', finite_lifting, ...
    'core_cell_squared', cell_lifting, ...
    'band_squared', band_lifting, ...
    'band_cell_squared', band_cell_lifting, ...
    'far_squared', far_lifting, ...
    'full_p6_blocker', ...
      'order-six regular-image derivative certificate unavailable'), ...
  'gates', struct('value_sign', isequal(center_val, ...
      double(local.center.val) + double(regular.raw_center.val) + ...
      double(off.raw_center.val)), ...
    'normal_sign', isequal(center_nor, double(local.center.nor) - ...
      double(regular.raw_center.nor) - double(off.raw_center.nor)), ...
    'all_centers_evaluated', local.centers_evaluated && ...
      regular.gates.centers_evaluated && off.gates.centers_evaluated, ...
    'centers_evaluated_once_after_selection', logical(c.evaluate_centers), ...
    'five_edge_radius_map', radius_edges.gates.pass, ...
    'off_analytic_edge_zero_authorized', ...
      radius_edges.gates.off_analytic_zero_authorized, ...
    'two_band_p4_fallback', strcmp(c.attempt_method, ...
      'I5.1h v7 attempt-3 streamed two-band-p4-fallback'), ...
    'core_band_far_exhaustive', three_sets_pass, ...
    'old_value_tail_L0_excluded', ...
      L1 > L0 && high_owner_pass && ...
      isequal(high_lifting, band_lifting + far_lifting), ...
    'current_L1_tail_owner', high_owner_pass, ...
    'finite_index_owner_split', finite_index_owner_pass, ...
    'no_band_cell_term', isequal(band_cell_lifting, 0) && ...
      all(strcmp({cell_ledger.value_index_owner}, '|ell|<L0')), ...
    'high_trace_slope_match', isequal(geometry.trace_tail_slope_lower, ...
      LOCAL_trace_slope(z, geometry, L1)), ...
    'tail_ownership_disjoint', tail_ownership_pass, ...
    'actual_jump_owner_complete', actual_jump_owner_complete, ...
    'weights_once', isequal(w.lifting, w.minimum_energy.harmonic_weight), ...
    'finite_nonnegative', all(isfinite(all_values)) && ...
      all([radius_val; radius_nor; finite_normal; finite_lifting; ...
      cell_normal; cell_lifting; high_normal; band_lifting; ...
      far_lifting; high_lifting] >= 0), ...
    'pass', local.centers_evaluated && regular.gates.centers_evaluated && ...
      off.gates.centers_evaluated && logical(c.evaluate_centers) && ...
      radius_edges.gates.pass && three_sets_pass && high_owner_pass && ...
      finite_index_owner_pass && ...
      tail_ownership_pass && actual_jump_owner_complete && ...
      isequal(w.lifting, w.minimum_energy.harmonic_weight) && ...
      isequal(geometry.trace_tail_slope_lower, ...
        LOCAL_trace_slope(z, geometry, L1)) && ...
      all(isfinite(all_values)) && ...
      all([radius_val; radius_nor; finite_normal; finite_lifting; ...
      cell_normal; cell_lifting; high_normal; band_lifting; ...
      far_lifting; high_lifting] >= 0)));
end
function [states, labels, tail_states] = LOCAL_states(z, J)
states = {double(z.q_center)};
labels = {'center'};
sides = {'minus', 'plus'};
tail_states = cell(2, 1);
for side = 1:2
  P = double(z.(['P', sides{side}]));
  G = double(z.(['G', sides{side}]));
  state = double(z.(['c', sides{side}]));
  for n = 0:J - 1
    states{end + 1} = G * state; %#ok<AGROW>
    labels{end + 1} = sprintf('%s-cell-%d', sides{side}, n); %#ok<AGROW>
    state = P * state;
  end
  tail_states{side} = state;
end
end

function [normal, lifting, ledger] = LOCAL_cell_tail( ...
    z, w, Cn, Cv, rn, rv, propagation, tail_states, normal_mask, value_mask)
normal = 0;
lifting = 0;
sides = {'minus', 'plus'};
entries = cell(2, 1);
for side = 1:2
  G = double(z.(['G', sides{side}]));
  map_norm = norm(G, 'fro');
  omega_n = sum(w.normal_inverse_trace(normal_mask) .* ...
    (vecnorm(Cn(normal_mask, :) * G, 2, 2) + ...
    rn(normal_mask) * map_norm).^2);
  omega_v = sum(w.lifting(value_mask) .* ...
    (vecnorm(Cv(value_mask, :) * G, 2, 2) + ...
    rv(value_mask) * map_norm).^2);
  cap = propagation.(sides{side}).sum_power_squared_upper;
  state_norm = norm(tail_states{side}, 2);
  normal = normal + omega_n * cap * state_norm^2;
  lifting = lifting + omega_v * cap * state_norm^2;
  entries{side} = struct('side', sides{side}, 'omega_normal', omega_n, ...
    'omega_lifting', omega_v, 'state_norm', state_norm, ...
    'sum_power_squared_upper', cap, ...
    'normal_index_owner', '|ell|<L1', ...
    'value_index_owner', '|ell|<L0');
end
ledger = vertcat(entries{:});
end
