function result = residual_numerator_v3( ...
    input_path, v2_input_path, same_run_v2_output_path, output_path)
%RESIDUAL_NUMERATOR_V3 Assemble the I5.1d conditional material delta.
% Purpose:
%   Recompute the material-normal finite and low-cell bounds after replacing
%   the I5.1c zero regular-image center by a signed finite Ewald center.
% Input:
%   input_path - Explicit self-contained I5.1d input MAT path.
%   v2_input_path - Explicit self-contained I5.1c data input MAT path.
%   same_run_v2_output_path - New create-once path written by the v2 evaluator
%     during this invocation; it is never loaded as historical input.
%   output_path - Explicit create-once I5.1d result MAT path.
% Output:
%   result - Conditional diagnostic numerator with the v2 lifting unchanged.
% Main algorithm:
%   Obtain a fresh v2 baseline through normal MATLAB function resolution,
%   replace the material regular center/radius, recompute every nonlinear
%   retained summand and low-cell omega, and carry all index-disjoint high
%   tails and the lifting module through unchanged.
% Based on:
%   (KR-26)--(KR-32) in s-kress-real.md and (M-action), (M-R)--(M-L) in
%   s-material-tail.md.
% Notes:
%   Finite special-function evaluation is assumed exact.  The result is a
%   conditional diagnostic, not a reliable or roundoff-inclusive enclosure.

timer = tic;
[input_path, v2_input_path, same_run_v2_output_path, output_path] = ...
  LOCAL_paths(input_path, v2_input_path, same_run_v2_output_path, output_path);
loaded = load(input_path, 'experiment_input');
loaded_v2 = load(v2_input_path, 'experiment_input');
if ~isfield(loaded, 'experiment_input') || ...
    ~isfield(loaded_v2, 'experiment_input')
  error('I51d:Schema', 'A required experiment_input variable is absent.');
end
input = loaded.experiment_input;
v2 = loaded_v2.experiment_input;
LOCAL_validate_input(input, v2);
if exist('residual_numerator_v2', 'file') ~= 2.0
  error('I51d:V2Function', ...
    'residual_numerator_v2 must be supplied through the MATLAB path.');
end

% --- stage 1: fresh same-run I5.1c baseline ---
baseline = residual_numerator_v2(v2_input_path, same_run_v2_output_path);
if strcmp(char(baseline.status), 'PRE_RUN_CERTIFICATE_STOP') || ...
    ~isfield(baseline, 'gate_audit') || ~baseline.gate_audit.pass || ...
    ~isequaln(baseline.configuration, input.baseline_contract.configuration)
  error('I51d:BaselineStop', ...
    'The fresh same-run v2 baseline failed its structural contract.');
end

% --- stage 2: nonlinear retained material recomputation ---
delta = input.material_delta;
base_finite = baseline.material.finite;
count = numel(base_finite.mode_orders);
required_finite = {'combined_center', ...
  'local_source_target_series_radius', 'off_surface_radius', ...
  'other_radius', 'weight_factor'};
if ~all(isfield(base_finite, required_finite)) || ...
    numel(delta.finite_physical_center) ~= count || ...
    numel(delta.finite_regular_radius) ~= count || ...
    ~isequal(double(base_finite.mode_orders(:)), ...
      double(delta.mode_orders(:)))
  error('I51d:FiniteShape', ...
    'The fresh v2 finite rows do not match the v3 material delta.');
end
combined_center = double(base_finite.combined_center(:)) + ...
  double(delta.finite_physical_center(:));
regular_radius = double(delta.finite_regular_radius(:));
total_radius = double(base_finite.local_source_target_series_radius(:)) + ...
  regular_radius + double(base_finite.off_surface_radius(:)) + ...
  double(base_finite.other_radius(:));
weight = double(base_finite.weight_factor(:));
finite_values = [combined_center; total_radius; weight];
if any(~isfinite(finite_values)) || any(total_radius < 0.0) || ...
    any(weight < 0.0)
  error('I51d:FiniteValue', ...
    'The recomputed material finite arrays contain invalid values.');
end
summand = weight .* (abs(combined_center) + total_radius).^2;
material_finite = base_finite;
material_finite.component_labels = LOCAL_replace_regular_label( ...
  base_finite.component_labels);
material_finite.combined_center = combined_center;
material_finite.regular_finite_center_zero_radius = zeros(count, 1);
material_finite.regular_source_quadrature_radius = ...
  double(delta.finite_source_quadrature_radius(:));
material_finite.regular_target_quadrature_radius = ...
  double(delta.finite_target_quadrature_radius(:));
material_finite.regular_finite_special_function_eval_radius = ...
  double(delta.finite_special_function_eval_radius(:));
material_finite.regular_M_R_radius = double(delta.finite_M_R_radius(:));
material_finite.regular_M_I_radius = double(delta.finite_M_I_radius(:));
material_finite.regular_M_T_radius = double(delta.finite_M_T_radius(:));
material_finite.regular_M_L_radius = double(delta.finite_M_L_radius(:));
material_finite.regular_omission_radius = ...
  material_finite.regular_M_R_radius + ...
  material_finite.regular_M_I_radius + ...
  material_finite.regular_M_T_radius + ...
  material_finite.regular_M_L_radius;
material_finite.regular_signed_center = ...
  double(delta.finite_physical_center(:));
material_finite.regular_conditional_total_radius = regular_radius;
material_finite.total_radius = total_radius;
material_finite.summand = summand;
material_finite.finite_squared = sum(summand);
material_finite.affected_nonlinear_sum_recomputed = true;

% --- stage 3: low-cell material recomputation ---
local_unit_radius = double(baseline.local_normal.total_radius(:));
low_cell_squared = LOCAL_low_cell_tail( ...
  delta.low_cell, local_unit_radius);
base_tail = baseline.material.tail;
required_tail = {'same_defect_squared', 'disjoint_tail_squared'};
if ~all(isfield(base_tail, required_tail))
  error('I51d:TailSchema', ...
    'The fresh v2 material tail lacks a required disjoint group.');
end
tail_squared = sum(double(base_tail.same_defect_squared(:))) + ...
  low_cell_squared + sum(double(base_tail.disjoint_tail_squared(:)));
material_tail = base_tail;
material_tail.low_mode_propagation_tail_squared = low_cell_squared;
material_tail.tail_squared = tail_squared;
material_tail.low_cell_recomputed_with_signed_regular_center = true;

% --- stage 4: conditional numerator diagnostic ---
B_Upsilon = sqrt(material_finite.finite_squared + material_tail.tail_squared);
B_Gamma_pm = double(baseline.B_Gamma_pm);
B_lift = double(baseline.B_lift);
numerator_majorant = B_Gamma_pm + B_Upsilon + B_lift;
conditional_pass = input.gates.conditional_diagnostic_pass && ...
  all(isfinite([B_Gamma_pm, B_Upsilon, B_lift, numerator_majorant, ...
    material_finite.finite_squared, material_tail.tail_squared])) && ...
  material_finite.finite_squared >= 0.0 && material_tail.tail_squared >= 0.0;
if ~conditional_pass
  error('I51d:ConditionalStop', ...
    'The conditional diagnostic assembly failed a finite structural gate.');
end

workspace = whos;
result = struct( ...
  'status', ...
    'CONDITIONAL_DIAGNOSTIC_FINITE_SPECIAL_FUNCTION_EVAL_ASSUMED_EXACT', ...
  'claim_scope', 'CONTINUOUS_RESIDUAL_NUMERATOR_CONDITIONAL_DIAGNOSTIC', ...
  'certification_label', 'NON_CERTIFIED_ROUNDOFF_EXCLUDED', ...
  'FINITE_SPECIAL_FUNCTION_EVAL_ASSUMED_EXACT', true, ...
  'conditional_assumption_pass', true, ...
  'reliable_eval_enclosure_pass', false, ...
  'total_reliable_pass', false, ...
  'conditional_diagnostic_pass', true, ...
  'roundoff_excluded', true, ...
  'reliability_certified', false, ...
  'configuration', input.configuration, ...
  'regular_signed_normal_certificate', ...
    input.regular_signed_normal_certificate, ...
  'wall', baseline.wall, ...
  'B_Gamma_pm', B_Gamma_pm, ...
  'material', struct( ...
    'finite', material_finite, ...
    'tail', material_tail, ...
    'bound', B_Upsilon, ...
    'conditional_diagnostic', true), ...
  'B_Upsilon', B_Upsilon, ...
  'lifting', baseline.lifting, ...
  'B_lift', B_lift, ...
  'numerator_majorant', numerator_majorant, ...
  'component_share', struct( ...
    'B_Gamma_pm', B_Gamma_pm / numerator_majorant, ...
    'B_Upsilon', B_Upsilon / numerator_majorant, ...
    'B_lift', B_lift / numerator_majorant), ...
  'baseline_comparison', struct( ...
    'fresh_same_run_v2_B_Upsilon', double(baseline.B_Upsilon), ...
    'fresh_same_run_v2_numerator_majorant', ...
      double(baseline.numerator_majorant), ...
    'historical_output_read', false), ...
  'gates', struct( ...
    'baseline_v2_structural_pass', baseline.gate_audit.pass, ...
    'affected_nonlinear_assembly_recomputed', true, ...
    'low_cell_recomputed', true, ...
    'lifting_carried_unchanged', true, ...
    'lifting_source', 'fresh_same_run_v2_function_return', ...
    'FINITE_SPECIAL_FUNCTION_EVAL_ASSUMED_EXACT', true, ...
    'conditional_assumption_pass', true, ...
    'reliable_eval_enclosure_pass', false, ...
    'total_reliable_pass', false, ...
    'conditional_diagnostic_pass', true, ...
    'sampled_maximum_used', false, ...
    'inter_level_drift_used', false, ...
    'empirical_safety_factor_used', false), ...
  'provenance', struct( ...
    'v2_baseline_kind', 'fresh_same_run_function_return', ...
    'same_run_v2_output_path', same_run_v2_output_path, ...
    'historical_output_read', false, ...
    'source_provenance', input.provenance, ...
    'eigenpair_solves', 0.0, ...
    'bie_density_solves', 0.0, ...
    'qz_decompositions', 0.0, ...
    'propagation_matrix_solves', 0.0), ...
  'resource', struct( ...
    'elapsed_seconds_before_save', toc(timer), ...
    'workspace_proxy_mib_before_save', ...
      sum([workspace.bytes]) / 2.0^20));
save(output_path, 'result', '-v7.3');
end

%% ==================== Explicit paths and contracts ====================
% These helpers reject historical outputs and mismatched v2 data inputs.

function [input_path, v2_input_path, baseline_path, output_path] = ...
    LOCAL_paths(input_path, v2_input_path, baseline_path, output_path)
input_path = LOCAL_char_path(input_path, 'input_path');
v2_input_path = LOCAL_char_path(v2_input_path, 'v2_input_path');
baseline_path = LOCAL_char_path(baseline_path, 'same_run_v2_output_path');
output_path = LOCAL_char_path(output_path, 'output_path');
if ~isfile(input_path) || ~isfile(v2_input_path)
  error('I51d:InputPath', ...
    'input_path and v2_input_path must name existing MAT inputs.');
end
if isfile(baseline_path) || isfolder(baseline_path) || ...
    isfile(output_path) || isfolder(output_path)
  error('I51d:OutputExists', ...
    'Both result paths must be new create-once targets.');
end
if strcmp(baseline_path, output_path)
  error('I51d:OutputAlias', 'The two output paths must be distinct.');
end
directories = {fileparts(baseline_path), fileparts(output_path)};
for index = 1:numel(directories)
  if ~isempty(directories{index}) && ~isfolder(directories{index})
    error('I51d:OutputDirectory', ...
      'Every explicit output directory must already exist.');
  end
end
end

function value = LOCAL_char_path(value, name)
if isstring(value) && isscalar(value)
  value = char(value);
end
if ~ischar(value) || isempty(value)
  error('I51d:Path', '%s must be a nonempty path.', name);
end
end

function LOCAL_validate_input(input, v2)
required = {'schema', 'certification_label', 'condition_label', ...
  'configuration', 'baseline_contract', ...
  'regular_signed_normal_certificate', 'material_delta', 'gates'};
if ~all(isfield(input, required)) || ...
    ~strcmp(char(input.schema), 'EPOST_I5_1D_INPUT_V3') || ...
    ~strcmp(char(input.certification_label), ...
      'NON_CERTIFIED_ROUNDOFF_EXCLUDED') || ...
    ~strcmp(char(input.condition_label), ...
      'FINITE_SPECIAL_FUNCTION_EVAL_ASSUMED_EXACT') || ...
    ~strcmp(char(v2.schema), 'EPOST_I5_1C_INPUT_V2')
  error('I51d:InputSchema', 'The v3 or v2 input contract is invalid.');
end
if ~isequaln(v2.configuration, input.baseline_contract.configuration) || ...
    ~isequaln(v2.frozen, input.baseline_contract.frozen) || ...
    ~isequal(double(v2.enclosure.retained_assembly.material.mode_orders(:)), ...
      double(input.baseline_contract.material_mode_orders(:))) || ...
    ~isequal(cellstr(v2.enclosure.retained_assembly.material.state_labels), ...
      cellstr(input.baseline_contract.material_state_labels))
  error('I51d:BaselineContract', ...
    'The explicit v2 input differs from the builder-audited contract.');
end
gates = input.gates;
required_true = {'artifact_revalidated', 'signed_regular_raw_normal_rows', ...
  'outgoing_reciprocal_branch', ...
  'physical_regular_sign_applied_once', ...
  'separate_source_target_strips', 'holomorphic_speed_branch', ...
  'm_r_tail', 'm_i_tail', 'm_t_tail', 'm_l_tail', ...
  'tail_ownership_disjoint', 'affected_nonlinear_assembly_recomputed', ...
  'FINITE_SPECIAL_FUNCTION_EVAL_ASSUMED_EXACT', ...
  'conditional_assumption_pass', 'conditional_diagnostic_pass'};
required_false = {'reliable_eval_enclosure_pass', 'total_reliable_pass', ...
  'sampled_maximum_used', 'inter_level_drift_used', ...
  'empirical_safety_factor_used'};
for index = 1:numel(required_true)
  name = required_true{index};
  if ~isfield(gates, name) || ~isequal(gates.(name), true)
    error('I51d:RequiredTrueGate', 'Required gate %s is false.', name);
  end
end
for index = 1:numel(required_false)
  name = required_false{index};
  if ~isfield(gates, name) || ~isequal(gates.(name), false)
    error('I51d:RequiredFalseGate', 'Required false gate %s is true.', name);
  end
end
end

function labels = LOCAL_replace_regular_label(labels)
labels = cellstr(labels);
match = strcmp(labels, 'regular_zero');
if sum(match) ~= 1.0
  error('I51d:RegularLabel', ...
    'The v2 retained assembly must contain one regular_zero component.');
end
labels{match} = 'regular_signed_center';
end

%% ==================== Material low-cell recomputation ====================
% This helper reuses high-mode groups but replaces the complete low-cell row.

function squared = LOCAL_low_cell_tail(data, local_unit_radius)
if ~isstruct(data) || isempty(data)
  error('I51d:LowCellSchema', 'The material low-cell delta is absent.');
end
local_unit_radius = double(local_unit_radius(:));
squared = 0.0;
for side_index = 1:numel(data)
  item = data(side_index);
  required = {'combined_center_row_map', 'state_map_norm_upper', ...
    'regular_unit_radius', 'off_surface_unit_radius', ...
    'weight_factor', 'tail_state_norm', 'sum_power_squared_upper', ...
    'regular_center_added', 'old_zero_center_radius_replaced'};
  if ~all(isfield(item, required))
    error('I51d:LowCellSchema', ...
      'A material low-cell delta side is incomplete.');
  end
  center_norm = vecnorm(double(item.combined_center_row_map), 2, 2);
  regular_radius = double(item.regular_unit_radius(:));
  off_surface_radius = double(item.off_surface_unit_radius(:));
  weight = double(item.weight_factor(:));
  map_norm = double(item.state_map_norm_upper);
  row_norm = center_norm + map_norm * (local_unit_radius + ...
    regular_radius + off_surface_radius);
  values = [center_norm; regular_radius; off_surface_radius; weight; ...
    map_norm; double(item.tail_state_norm); ...
    double(item.sum_power_squared_upper)];
  if numel(center_norm) ~= numel(local_unit_radius) || ...
      numel(regular_radius) ~= numel(local_unit_radius) || ...
      numel(off_surface_radius) ~= numel(local_unit_radius) || ...
      numel(weight) ~= numel(local_unit_radius) || ...
      any(~isfinite(values)) || any(values < 0.0) || ...
      ~item.regular_center_added || ...
      ~item.old_zero_center_radius_replaced
    error('I51d:LowCellValue', ...
      'A recomputed material low-cell side is invalid.');
  end
  omega = sum(weight .* row_norm.^2);
  squared = squared + omega * ...
    double(item.sum_power_squared_upper) * ...
    double(item.tail_state_norm)^2;
end
end
