function experiment_input = build_residual_numerator_input_v3( ...
    v2_input_path, artifact_path, input_path)
%BUILD_RESIDUAL_NUMERATOR_INPUT_V3 Build the I5.1d conditional delta input.
% Purpose:
%   Replace the I5.1c zero-centered regular-image material-normal term by a
%   signed finite Ewald center and explicit source, target, and Ewald radii.
% Input:
%   v2_input_path - Explicit self-contained I5.1c input MAT path.
%   artifact_path - Explicit frozen I3 certificate MAT path.
%   input_path    - Explicit create-once I5.1d input MAT path.
% Output:
%   experiment_input - Self-contained material-normal delta contract.
% Main algorithm:
%   Revalidate the frozen density and state maps; evaluate the signed retained
%   reciprocal, nonzero-image, and branch-free local Ewald sums; attach the
%   M-R, M-I, M-T, and M-L tails; and map the result to every retained and
%   low-cell material state.
% Based on:
%   (M-action), (M-target-quad), (M-source-quad), (M-R), (M-I), (M-T), and
%   (M-L) in s-material-tail.md and the I5.1c assembly in
%   build_residual_numerator_input_v2.m.
% Main changes:
%   Only the material-normal regular-image center and radius are replaced.
%   Finite special-function evaluations are assumed exact, so this is a
%   conditional diagnostic and never a reliable finite-evaluation enclosure.
% Numerical goal:
%   Produce the immutable input for one fail-closed I5.1d diagnostic run.

[v2_input_path, artifact_path, input_path] = LOCAL_paths( ...
  v2_input_path, artifact_path, input_path);
loaded_v2 = load(v2_input_path, 'experiment_input');
loaded_artifact = load(artifact_path, 'staged');
if ~isfield(loaded_v2, 'experiment_input') || ...
    ~isfield(loaded_artifact, 'staged') || ...
    ~isfield(loaded_artifact.staged, 'certificate')
  error('I51dInput:Schema', ...
    'The explicit v2 input or frozen artifact has the wrong schema.');
end
v2 = loaded_v2.experiment_input;
z = loaded_artifact.staged.certificate;
LOCAL_validate_v2(v2);
artifact_audit = LOCAL_validate_artifact(v2, z);

configuration = v2.configuration;
configuration.regular_taylor_cutoff = ...
  double(configuration.ewald_local_cutoff);
configuration.regular_target_strip_width = ...
  double(configuration.parameter_strip_width);
configuration.regular_source_strip_width = ...
  double(configuration.parameter_strip_width);
geometry = v2.enclosure.geometry;
regular = LOCAL_regular_signed_normal( ...
  v2, z, geometry, configuration);
material_delta = LOCAL_material_delta( ...
  v2, z, regular, configuration);

all_finite = all(isfinite([regular.raw_normal_rows(:); ...
  regular.physical_normal_rows(:); regular.total_retained_row_radius(:); ...
  material_delta.finite_physical_center(:); ...
  material_delta.finite_regular_radius(:)]));
conditional_assumption_pass = artifact_audit.pass && regular.gate.pass && ...
  material_delta.gate.pass && all_finite;

baseline_contract = struct( ...
  'schema', char(v2.schema), ...
  'configuration', v2.configuration, ...
  'frozen', v2.frozen, ...
  'material_mode_orders', ...
    v2.enclosure.retained_assembly.material.mode_orders, ...
  'material_state_labels', ...
    {v2.enclosure.retained_assembly.material.state_labels});

experiment_input = struct( ...
  'schema', 'EPOST_I5_1D_INPUT_V3', ...
  'claim_scope', 'MATERIAL_NORMAL_REGULAR_IMAGE_CONDITIONAL_DIAGNOSTIC', ...
  'certification_label', 'NON_CERTIFIED_ROUNDOFF_EXCLUDED', ...
  'condition_label', 'FINITE_SPECIAL_FUNCTION_EVAL_ASSUMED_EXACT', ...
  'configuration', configuration, ...
  'baseline_contract', baseline_contract, ...
  'regular_signed_normal_certificate', regular, ...
  'material_delta', material_delta, ...
  'gates', struct( ...
    'artifact_revalidated', artifact_audit.pass, ...
    'signed_regular_raw_normal_rows', regular.gate.signed_raw_rows, ...
    'outgoing_reciprocal_branch', ...
      regular.gate.outgoing_reciprocal_branch, ...
    'physical_regular_sign_applied_once', ...
      regular.gate.physical_sign_applied_once, ...
    'separate_source_target_strips', ...
      regular.gate.separate_source_target_strips, ...
    'holomorphic_speed_branch', regular.gate.holomorphic_speed_branch, ...
    'm_r_tail', regular.gate.m_r_tail, ...
    'm_i_tail', regular.gate.m_i_tail, ...
    'm_t_tail', regular.gate.m_t_tail, ...
    'm_l_tail', regular.gate.m_l_tail, ...
    'tail_ownership_disjoint', regular.gate.tail_ownership_disjoint, ...
    'affected_nonlinear_assembly_recomputed', material_delta.gate.pass, ...
    'FINITE_SPECIAL_FUNCTION_EVAL_ASSUMED_EXACT', true, ...
    'conditional_assumption_pass', conditional_assumption_pass, ...
    'reliable_eval_enclosure_pass', false, ...
    'total_reliable_pass', false, ...
    'conditional_diagnostic_pass', conditional_assumption_pass, ...
    'sampled_maximum_used', false, ...
    'inter_level_drift_used', false, ...
    'empirical_safety_factor_used', false), ...
  'provenance', struct( ...
    'v2_input_kind', 'explicit_self_contained_data_input', ...
    'v2_input_path', v2_input_path, ...
    'artifact_path', artifact_path, ...
    'artifact_audit', artifact_audit, ...
    'historical_output_read', false, ...
    'eigenpair_solves', 0.0, ...
    'bie_density_solves', 0.0, ...
    'qz_decompositions', 0.0, ...
    'propagation_matrix_solves', 0.0));
save(input_path, 'experiment_input', '-v7.3');
end

%% ==================== Explicit paths and schemas ====================
% These helpers enforce explicit portable inputs and immutable output ownership.

function [v2_input_path, artifact_path, input_path] = LOCAL_paths( ...
    v2_input_path, artifact_path, input_path)
v2_input_path = LOCAL_char_path(v2_input_path, 'v2_input_path');
artifact_path = LOCAL_char_path(artifact_path, 'artifact_path');
input_path = LOCAL_char_path(input_path, 'input_path');
if ~isfile(v2_input_path) || ~isfile(artifact_path)
  error('I51dInput:InputPath', ...
    'v2_input_path and artifact_path must name existing MAT files.');
end
if isfile(input_path) || isfolder(input_path)
  error('I51dInput:OutputExists', ...
    'input_path must be a new create-once MAT target.');
end
output_directory = fileparts(input_path);
if ~isempty(output_directory) && ~isfolder(output_directory)
  error('I51dInput:OutputDirectory', ...
    'The explicit input output directory does not exist.');
end
end

function value = LOCAL_char_path(value, name)
if isstring(value) && isscalar(value)
  value = char(value);
end
if ~ischar(value) || isempty(value)
  error('I51dInput:Path', '%s must be a nonempty path.', name);
end
end

function LOCAL_validate_v2(v2)
required = {'schema', 'configuration', 'frozen', 'enclosure'};
if ~all(isfield(v2, required)) || ...
    ~strcmp(char(v2.schema), 'EPOST_I5_1C_INPUT_V2') || ...
    ~isfield(v2.enclosure, 'schema') || ...
    ~strcmp(char(v2.enclosure.schema), 'EPOST_I5_1C_ENCLOSURE_V2')
  error('I51dInput:V2Schema', 'The v2 data input contract is invalid.');
end
required_enclosure = {'geometry', 'regular_zero_center_certificate', ...
  'retained_assembly', 'tail_assembly', 'gates'};
if ~all(isfield(v2.enclosure, required_enclosure)) || ...
    ~isfield(v2.enclosure.retained_assembly, 'material') || ...
    ~isfield(v2.enclosure.tail_assembly, 'material')
  error('I51dInput:V2Enclosure', ...
    'The v2 material assembly contract is incomplete.');
end
required_configuration = {'residual_mode_cutoff', ...
  'evaluation_node_count', 'parameter_strip_width', ...
  'reciprocal_cutoff', 'image_cutoff', 'ewald_split', ...
  'ewald_local_cutoff', 'cell_cutoff'};
if ~all(isfield(v2.configuration, required_configuration))
  error('I51dInput:V2Configuration', ...
    'The v2 Ewald or cutoff configuration is incomplete.');
end
required_true = {'artifact_scalar_match', 'geometry_certificate', ...
  'parameterization_ccw_outward', 'density_node_phase_match', ...
  'density_sign_and_support', 'ewald_tail_gates', ...
  'off_surface_signed_center', 'low_cell_complete_combined_map', ...
  'propagation_certificate', 'tail_ownership_disjoint'};
gates = v2.enclosure.gates;
for index = 1:numel(required_true)
  name = required_true{index};
  if ~isfield(gates, name) || ~isequal(gates.(name), true)
    error('I51dInput:V2Gate', 'Required v2 gate %s is false.', name);
  end
end
L = double(v2.configuration.residual_mode_cutoff);
N = double(v2.configuration.evaluation_node_count);
M_eta = double(v2.frozen.density_fourier_degree);
if mod(N, 2.0) ~= 0.0 || N <= 2.0 * max(L, M_eta)
  error('I51dInput:Cutoff', 'The strict v2 N/L/M_eta gate failed.');
end
end

function audit = LOCAL_validate_artifact(v2, z)
required = {'khat', 'mu_h', 'beta', 'd', 'R', 'rho_disk', ...
  'eta_unit_256', 'density_coordinate', 'q_center', 'Gminus', ...
  'Gplus', 'Pminus', 'Pplus', 'cminus', 'cplus'};
if ~all(isfield(z, required))
  error('I51dInput:ArtifactSchema', ...
    'The frozen artifact lacks a required material-state field.');
end
frozen = v2.frozen;
scalar_match = isequal(double(z.khat), double(frozen.khat)) && ...
  isequal(double(z.mu_h), double(frozen.mu_shift)) && ...
  isequal(double(z.beta), double(frozen.beta_bloch)) && ...
  isequal(double(z.d), double(frozen.period_y)) && ...
  isequal(double(z.R), double(frozen.circle_radius)) && ...
  isequal(double(z.rho_disk), double(frozen.material_coefficient_inner));
N_eta = double(frozen.source_node_count);
orders = double(frozen.density_orders(:));
eta_native = double(z.eta_unit_256);
if size(eta_native, 1) ~= 2.0 * N_eta || ...
    size(eta_native, 2) ~= size(frozen.tau_coeff_map, 2) || ...
    ~strcmp(strtrim(char(z.density_coordinate)), ...
      '[tau;zeta], zeta=-sigma')
  error('I51dInput:DensitySchema', ...
    'The frozen density coordinate or size does not match v2.');
end
tau_coeff = fftshift(fft(eta_native(1:N_eta, :), [], 1), 1) / N_eta;
eta_second_coeff = ...
  fftshift(fft(eta_native(N_eta + 1.0:end, :), [], 1), 1) / N_eta;
density_scale = max(1.0, norm([tau_coeff(:); eta_second_coeff(:)], 2));
density_difference = norm([tau_coeff(:) - frozen.tau_coeff_map(:); ...
  eta_second_coeff(:) - frozen.eta_second_coeff_map(:)], 2);
density_tolerance = 128.0 * eps(density_scale) * sqrt(numel(tau_coeff) + ...
  numel(eta_second_coeff));
density_match = isequal(orders, double(frozen.density_orders(:))) && ...
  density_difference <= density_tolerance;
state_finite = all(isfinite([z.q_center(:); z.Gminus(:); z.Gplus(:); ...
  z.Pminus(:); z.Pplus(:); z.cminus(:); z.cplus(:)]));
audit = struct( ...
  'scalar_match', scalar_match, ...
  'density_match', density_match, ...
  'density_difference', density_difference, ...
  'density_tolerance', density_tolerance, ...
  'state_maps_finite', state_finite, ...
  'pass', scalar_match && density_match && state_finite);
if ~audit.pass
  error('I51dInput:ArtifactMismatch', ...
    'The explicit frozen artifact does not match the v2 input contract.');
end
end

%% ==================== Signed regular-image normal row ====================
% These helpers instantiate the retained Ewald center and disjoint radii.

function out = LOCAL_regular_signed_normal(v2, z, geometry, configuration)
N = double(configuration.evaluation_node_count);
L = double(configuration.residual_mode_cutoff);
orders = double(v2.frozen.density_orders(:));
tau_coeff = double(v2.frozen.tau_coeff_map);
eta_second_coeff = double(v2.frozen.eta_second_coeff_map);
nodes = double(geometry.parameter_nodes(:));
if numel(nodes) ~= N || size(tau_coeff, 1) ~= numel(orders) || ...
    size(eta_second_coeff, 1) ~= numel(orders)
  error('I51dInput:RegularShape', ...
    'The Ewald geometry and density maps have inconsistent sizes.');
end
phase = exp(1i * nodes * orders.');
tau_values = phase * tau_coeff;
eta_second_values = phase * eta_second_coeff;
reciprocal_ledger = LOCAL_reciprocal_ledger(z, configuration);
position = double(geometry.position);
normal = double(geometry.normal);
speed = double(geometry.speed_nodes(:));
dt = 2.0 * pi / N;
source_weight = speed * dt;
raw_samples = complex(zeros(N, size(tau_coeff, 2)));
for first = 1:32:N
  ids = first:min(first + 31, N);
  coordinate = LOCAL_ewald_signed_coordinates( ...
    position(ids, :), position, double(z.khat), double(z.beta), ...
    double(z.d), configuration, configuration.regular_taylor_cutoff);
  nsx = normal(:, 1).';
  nsy = normal(:, 2).';
  ntx = normal(ids, 1);
  nty = normal(ids, 2);
  target_normal = coordinate.dx .* ntx + coordinate.dy .* nty;
  mixed_normal = -(coordinate.dxx .* (ntx * nsx) + ...
    coordinate.dxy .* (ntx * nsy + nty * nsx) + ...
    coordinate.dyy .* (nty * nsy));
  weighted_tau = tau_values .* source_weight;
  weighted_eta_second = eta_second_values .* source_weight;
  raw_samples(ids, :) = mixed_normal * weighted_tau - ...
    target_normal * weighted_eta_second;
end
retained_orders = (-(L - 1.0):L - 1.0).';
raw_rows = LOCAL_parameter_rows( ...
  raw_samples, nodes, retained_orders, double(geometry.boundary_length));
physical_rows = -raw_rows;

base_regular = v2.enclosure.regular_zero_center_certificate;
required_coordinate = {'coordinate_real_axis', ...
  'coordinate_high_target_strip'};
if ~all(isfield(base_regular, required_coordinate))
  error('I51dInput:RegularBaseline', ...
    'The v2 coordinate-tail certificate is incomplete.');
end
coordinate_real = base_regular.coordinate_real_axis;
required_tail = {'reciprocal_tail', 'omitted_image_tail', ...
  'local_factorial_tail'};
if ~all(isfield(coordinate_real, required_tail))
  error('I51dInput:RegularTailBaseline', ...
    'The v2 real-axis Ewald tail split is incomplete.');
end
if ~isfield(coordinate_real, 'gate') || ~coordinate_real.gate.pass
  error('I51dInput:RegularRealGate', ...
    'The v2 real-axis Ewald coordinate gate is false.');
end
m_r = double(coordinate_real.reciprocal_tail);
m_i = double(coordinate_real.omitted_image_tail);
m_l = double(coordinate_real.local_factorial_tail);
[m_t, m_t_gate] = LOCAL_retained_image_taylor_tail( ...
  z, geometry, configuration, configuration.regular_taylor_cutoff);
tail_coordinate = m_r + m_i + m_t + m_l;
real_normal_components = [1.0, 1.0];
k_m_r = LOCAL_contract_coordinate(m_r, ...
  real_normal_components, real_normal_components);
k_m_i = LOCAL_contract_coordinate(m_i, ...
  real_normal_components, real_normal_components);
k_m_t = LOCAL_contract_coordinate(m_t, ...
  real_normal_components, real_normal_components);
k_m_l = LOCAL_contract_coordinate(m_l, ...
  real_normal_components, real_normal_components);

P = double(geometry.boundary_length);
tau_real = sum(vecnorm(tau_coeff, 2, 2));
eta_second_real = sum(vecnorm(eta_second_coeff, 2, 2));
A_tau = P * tau_real;
A_sigma = P * eta_second_real;
m_r_radius = sqrt(P) * (k_m_r(4) * A_tau + k_m_r(3) * A_sigma);
m_i_radius = sqrt(P) * (k_m_i(4) * A_tau + k_m_i(3) * A_sigma);
m_t_radius = sqrt(P) * (k_m_t(4) * A_tau + k_m_t(3) * A_sigma);
m_l_radius = sqrt(P) * (k_m_l(4) * A_tau + k_m_l(3) * A_sigma);
ewald_radius = m_r_radius + m_i_radius + m_t_radius + m_l_radius;

strip_coordinate = base_regular.coordinate_high_target_strip;
if ~isfield(strip_coordinate, 'finite') || ~isfield(strip_coordinate, 'tail')
  error('I51dInput:StripCertificate', ...
    'The v2 high-target coordinate certificate is incomplete.');
end
if ~isfield(strip_coordinate, 'gate') || ~strip_coordinate.gate.pass
  error('I51dInput:RegularStripGate', ...
    'The v2 strip Ewald coordinate gate is false.');
end
strip_kernel = LOCAL_contract_coordinate( ...
  double(strip_coordinate.finite) + double(strip_coordinate.tail), ...
  double(geometry.target_normal_component_upper), ...
  double(geometry.source_normal_component_upper));
target_width = double(configuration.regular_target_strip_width);
source_width = double(configuration.regular_source_strip_width);
density_source_weight = exp(source_width * abs(orders));
tau_source_strip = sum(density_source_weight .* vecnorm(tau_coeff, 2, 2));
eta_second_source_strip = sum( ...
  density_source_weight .* vecnorm(eta_second_coeff, 2, 2));
normal_action_target_strip = strip_kernel(4) * A_tau + ...
  strip_kernel(3) * A_sigma;
normal_integrand_source_strip = strip_kernel(4) * tau_source_strip + ...
  strip_kernel(3) * eta_second_source_strip;
normal_parameter_integrand_source_strip = ...
  double(geometry.strip_speed_upper) * normal_integrand_source_strip;
target_radius = 4.0 * pi * double(geometry.strip_speed_upper) * ...
  normal_action_target_strip .* exp(target_width * abs(retained_orders)) / ...
  (sqrt(P) * expm1(target_width * N));
source_node_weight_sum = dt * sum(speed);
source_radius = 4.0 * pi * source_node_weight_sum / sqrt(P) * ...
  normal_parameter_integrand_source_strip / expm1(source_width * N);
finite_eval_radius = zeros(size(retained_orders));
total_radius = source_radius + target_radius + ewald_radius + ...
  finite_eval_radius;

finite_values = [raw_rows(:); physical_rows(:); m_r(:); m_i(:); ...
  m_t(:); m_l(:); target_radius(:); source_radius; ewald_radius];
tail_pass = all(isfinite(tail_coordinate)) && ...
  all(tail_coordinate >= 0.0) && m_t_gate.pass;
out = struct( ...
  'mode_orders', retained_orders, ...
  'raw_normal_rows', raw_rows, ...
  'physical_normal_rows', physical_rows, ...
  'physical_material_sign', -1.0, ...
  'density_coordinate', '[tau;zeta], zeta=-sigma', ...
  'source_normal_formula', ...
    'mixed_normal*tau-target_normal*eta_second', ...
  'reciprocal_ledger', reciprocal_ledger, ...
  'coordinate_order', {{'00', '10', '01', '20', '11', '02'}}, ...
  'M_R_coordinate_tail', m_r, ...
  'M_I_coordinate_tail', m_i, ...
  'M_T_coordinate_tail', m_t, ...
  'M_L_coordinate_tail', m_l, ...
  'coordinate_tail_total', tail_coordinate, ...
  'M_R_row_radius', m_r_radius, ...
  'M_I_row_radius', m_i_radius, ...
  'M_T_row_radius', m_t_radius, ...
  'M_L_row_radius', m_l_radius, ...
  'ewald_truncation_row_radius', ewald_radius, ...
  'source_quadrature_row_radius', source_radius, ...
  'target_quadrature_row_radius', target_radius, ...
  'finite_special_function_eval_row_radius', finite_eval_radius, ...
  'total_retained_row_radius', total_radius, ...
  'target_strip_action_upper', normal_action_target_strip, ...
  'source_strip_integrand_upper', normal_integrand_source_strip, ...
  'source_strip_parameter_integrand_upper', ...
    normal_parameter_integrand_source_strip, ...
  'target_strip_width', target_width, ...
  'source_strip_width', source_width, ...
  'finite_special_function_condition', ...
    'FINITE_SPECIAL_FUNCTION_EVAL_ASSUMED_EXACT', ...
  'finite_special_function_families', ...
    {{'Faddeeva_erfc', 'expint', 'exp', 'gammaln', 'polyval', ...
      'geometry-density-speed-phase node evaluations'}}, ...
  'finite_special_function_eval_assumed_exact', true, ...
  'reliable_eval_enclosure_pass', false, ...
  'taylor_tail_certificate', m_t_gate, ...
  'gate', struct( ...
    'signed_raw_rows', all(isfinite(raw_rows(:))), ...
    'outgoing_reciprocal_branch', reciprocal_ledger.pass, ...
    'physical_sign_applied_once', ...
      isequal(physical_rows, -raw_rows), ...
    'separate_source_target_strips', target_width > 0.0 && ...
      source_width > 0.0, ...
    'holomorphic_speed_branch', ...
      geometry.constant_speed_parameterization && ...
      double(geometry.speed_lower) == double(z.R), ...
    'm_r_tail', all(isfinite(m_r)) && all(m_r >= 0.0), ...
    'm_i_tail', all(isfinite(m_i)) && all(m_i >= 0.0), ...
    'm_t_tail', m_t_gate.pass, ...
    'm_l_tail', all(isfinite(m_l)) && all(m_l >= 0.0), ...
    'tail_ownership_disjoint', true, ...
    'FINITE_SPECIAL_FUNCTION_EVAL_ASSUMED_EXACT', true, ...
    'reliable_eval_enclosure_pass', false, ...
    'pass', all(isfinite(finite_values)) && tail_pass && ...
      reciprocal_ledger.pass));
end

function ledger = LOCAL_reciprocal_ledger(z, configuration)
kappa = double(z.khat);
beta = double(z.beta);
d = double(z.d);
modes = (-(configuration.reciprocal_cutoff - 1.0): ...
  configuration.reciprocal_cutoff - 1.0).';
transverse = beta + 2.0 * pi * modes / d;
radicand = transverse.^2 - kappa^2;
q_mode = sqrt(complex(radicand));
flip = real(q_mode) < 0.0 | ...
  (real(q_mode) == 0.0 & imag(q_mode) > 0.0);
q_mode(flip) = -q_mode(flip);
nonwood = all(q_mode ~= 0.0);
branch = all(real(q_mode(radicand > 0.0)) > 0.0) && ...
  all(imag(q_mode(radicand < 0.0)) < 0.0);
ledger = struct( ...
  'mode_orders', modes, ...
  'transverse_wavenumber', transverse, ...
  'linton_q', q_mode, ...
  'minimum_denominator_magnitude', min(abs(q_mode)), ...
  'nonwood', nonwood, ...
  'outgoing_decaying_branch', branch, ...
  'pass', nonwood && branch && all(isfinite(q_mode)));
end

function coordinate = LOCAL_ewald_signed_coordinates( ...
    target, source, kappa, beta, d, configuration, taylor_cutoff)
X = target(:, 1) - source(:, 1).';
Y = target(:, 2) - source(:, 2).';
h = configuration.ewald_split / d;
chi_E = (kappa * d / (2.0 * configuration.ewald_split))^2;
value = complex(zeros(size(X)));
dx = value;
dy = value;
dxx = value;
dxy = value;
dyy = value;
for mode = -(configuration.reciprocal_cutoff - 1.0): ...
    configuration.reciprocal_cutoff - 1.0
  transverse = beta + 2.0 * pi * mode / d;
  q_mode = sqrt(complex(transverse^2 - kappa^2));
  if real(q_mode) < 0.0 || ...
      (real(q_mode) == 0.0 && imag(q_mode) > 0.0)
    q_mode = -q_mode;
  end
  if q_mode == 0.0
    error('I51dInput:ExactWood', ...
      'A retained reciprocal Ewald denominator is zero.');
  end
  phase = exp(1i * transverse * Y) / (4.0 * d * q_mode);
  F0 = complex(zeros(size(X)));
  F1 = F0;
  F2 = F0;
  for epsilon = [-1.0, 1.0]
    argument = q_mode / (2.0 * h) + epsilon * h * X;
    exponential = exp(epsilon * q_mode * X);
    erfc_value = Faddeeva_erfc(argument);
    erfc_first = -2.0 / sqrt(pi) * exp(-argument.^2);
    erfc_second = 4.0 / sqrt(pi) * argument .* exp(-argument.^2);
    F0 = F0 + exponential .* erfc_value;
    F1 = F1 + epsilon * exponential .* ...
      (q_mode * erfc_value + h * erfc_first);
    F2 = F2 + exponential .* (q_mode^2 * erfc_value + ...
      2.0 * q_mode * h * erfc_first + h^2 * erfc_second);
  end
  value = value + phase .* F0;
  dx = dx + phase .* F1;
  dy = dy + 1i * transverse * phase .* F0;
  dxx = dxx + phase .* F2;
  dxy = dxy + 1i * transverse * phase .* F1;
  dyy = dyy - transverse^2 * phase .* F0;
end
for image_index = [-(configuration.image_cutoff - 1.0):-1.0, ...
    1.0:configuration.image_cutoff - 1.0]
  shifted_y = Y - image_index * d;
  zeta = h^2 * (X.^2 + shifted_y.^2);
  [H0, H1, H2] = LOCAL_H_chi_finite(zeta, chi_E, taylor_cutoff);
  phase = exp(1i * beta * image_index * d) / (4.0 * pi);
  zx = 2.0 * h^2 * X;
  zy = 2.0 * h^2 * shifted_y;
  value = value + phase * H0;
  dx = dx + phase * (H1 .* zx);
  dy = dy + phase * (H1 .* zy);
  dxx = dxx + phase * (H2 .* zx.^2 + 2.0 * h^2 * H1);
  dxy = dxy + phase * (H2 .* zx .* zy);
  dyy = dyy + phase * (H2 .* zy.^2 + 2.0 * h^2 * H1);
end
zeta = h^2 * (X.^2 + Y.^2);
[C0, C1, C2] = LOCAL_C_chi_finite(zeta, chi_E, taylor_cutoff);
zx = 2.0 * h^2 * X;
zy = 2.0 * h^2 * Y;
value = value - C0;
dx = dx - C1 .* zx;
dy = dy - C1 .* zy;
dxx = dxx - (C2 .* zx.^2 + 2.0 * h^2 * C1);
dxy = dxy - C2 .* zx .* zy;
dyy = dyy - (C2 .* zy.^2 + 2.0 * h^2 * C1);
coordinate = struct('value', value, 'dx', dx, 'dy', dy, ...
  'dxx', dxx, 'dxy', dxy, 'dyy', dyy);
end

function [H0, H1, H2] = LOCAL_H_chi_finite(zeta, chi_E, cutoff)
exp_minus = exp(-zeta);
Eminus = exp_minus .* (1.0 ./ zeta + 1.0 ./ zeta.^2);
Ezero = exp_minus ./ zeta;
Eplus = expint(zeta);
H0 = complex(zeros(size(zeta)));
H1 = H0;
H2 = H0;
coefficient = 1.0;
for order = 0:cutoff
  H0 = H0 + coefficient * Eplus;
  H1 = H1 - coefficient * Ezero;
  H2 = H2 + coefficient * Eminus;
  if order < cutoff
    Enext = (exp_minus - zeta .* Eplus) / (order + 1.0);
    Eminus = Ezero;
    Ezero = Eplus;
    Eplus = Enext;
    coefficient = coefficient * chi_E / (order + 1.0);
  end
end
end

function [C0, C1, C2] = LOCAL_C_chi_finite(zeta, chi_E, cutoff)
gamma_E = 0.57721566490153286060;
J = zeros(1, cutoff + 1.0);
S = J;
D = J;
Q = J;
harmonic = 0.0;
for order = 0:cutoff
  J(order + 1.0) = (-chi_E)^order / ...
    exp(2.0 * gammaln(order + 1.0));
  if order >= 1.0
    harmonic = harmonic + 1.0 / order;
    S(order + 1.0) = (-1.0)^order / ...
      (order * exp(gammaln(order + 1.0)));
    D(order + 1.0) = (-1.0)^order * harmonic * chi_E^order / ...
      exp(2.0 * gammaln(order + 1.0));
    for degree = 0:order - 1.0
      Q(degree + 1.0) = Q(degree + 1.0) + chi_E^order / ...
        exp(2.0 * gammaln(order + 1.0)) * ...
        exp(gammaln(order - degree)) * (-1.0)^degree;
    end
  end
end
c_chi = log(chi_E) + gamma_E - 1i * pi;
polynomial = conv(J, S);
polynomial(1:numel(J)) = polynomial(1:numel(J)) - c_chi * J;
polynomial(1:numel(D)) = polynomial(1:numel(D)) + 2.0 * D;
polynomial = polynomial / (4.0 * pi);
[P0, P1, P2] = LOCAL_polynomial_012(polynomial, zeta);
[Q0, Q1, Q2] = LOCAL_polynomial_012(Q, zeta);
exp_factor = exp(-zeta) / (4.0 * pi);
C0 = P0 - exp_factor .* Q0;
C1 = P1 - exp_factor .* (Q1 - Q0);
C2 = P2 - exp_factor .* (Q2 - 2.0 * Q1 + Q0);
end

function [v0, v1, v2] = LOCAL_polynomial_012(coefficients, zeta)
degrees = 0:numel(coefficients) - 1.0;
v0 = polyval(fliplr(coefficients), zeta);
if numel(coefficients) > 1.0
  first = coefficients(2:end) .* degrees(2:end);
  v1 = polyval(fliplr(first), zeta);
else
  v1 = zeros(size(zeta));
end
if numel(coefficients) > 2.0
  second = coefficients(3:end) .* degrees(3:end) .* ...
    (degrees(3:end) - 1.0);
  v2 = polyval(fliplr(second), zeta);
else
  v2 = zeros(size(zeta));
end
end

function [tail, gate] = LOCAL_retained_image_taylor_tail( ...
    z, geometry, configuration, cutoff)
kappa = double(z.khat);
d = double(z.d);
h = configuration.ewald_split / d;
chi_E = (kappa * d / (2.0 * configuration.ewald_split))^2;
R = double(z.R);
RX = 2.0 * R;
RY = 2.0 * R;
UY = 2.0 * R;
ratio = chi_E / (cutoff + 2.0);
first = exp((cutoff + 1.0) * log(chi_E) - ...
  gammaln(cutoff + 2.0));
poisson_tail = first / (1.0 - ratio);
tail = zeros(1, 6);
u_values = zeros(1, 2.0 * (configuration.image_cutoff - 1.0));
counter = 0.0;
for image_index = [-(configuration.image_cutoff - 1.0):-1.0, ...
    1.0:configuration.image_cutoff - 1.0]
  counter = counter + 1.0;
  u = h^2 * (abs(image_index) * d - UY)^2;
  u_values(counter) = u;
  theta = poisson_tail * exp(-u) / u;
  zx = 2.0 * h^2 * RX;
  zy = 2.0 * h^2 * (abs(image_index) * d + RY);
  tail = tail + theta / (4.0 * pi) * [1.0, zx, zy, ...
    zx^2 + 2.0 * h^2, zx * zy, zy^2 + 2.0 * h^2];
end
gate = struct( ...
  'taylor_cutoff', cutoff, ...
  'first_omitted_order', cutoff + 1.0, ...
  'poisson_ratio', ratio, ...
  'poisson_tail_upper', poisson_tail, ...
  'retained_image_real_lower', u_values, ...
  'pass', ratio < 1.0 && all(u_values > 0.0) && ...
    all(isfinite([poisson_tail, tail])) && all(tail >= 0.0) && ...
    geometry.constant_speed_parameterization);
end

function kernel = LOCAL_contract_coordinate(coordinate, Nt, Ns)
kernel = [ ...
  coordinate(1), ...
  Ns(1) * coordinate(2) + Ns(2) * coordinate(3), ...
  Nt(1) * coordinate(2) + Nt(2) * coordinate(3), ...
  Nt(1) * Ns(1) * coordinate(4) + ...
    (Nt(1) * Ns(2) + Nt(2) * Ns(1)) * coordinate(5) + ...
    Nt(2) * Ns(2) * coordinate(6)];
end

function rows = LOCAL_parameter_rows(samples, nodes, orders, P)
phase = exp(-1i * orders * nodes.');
rows = phase * (samples * (P / numel(nodes))) / sqrt(P);
end

%% ==================== Material delta mapping ====================
% These helpers map the signed unit row to retained and propagated states.

function out = LOCAL_material_delta(v2, z, regular, configuration)
baseline = v2.enclosure.retained_assembly.material;
L = double(configuration.residual_mode_cutoff);
ell_count = 2.0 * L - 1.0;
J = double(configuration.cell_cutoff);
[states, labels] = LOCAL_retained_states(z, J);
state_count = numel(states);
expected_count = ell_count * state_count;
if numel(baseline.mode_orders) ~= expected_count || ...
    size(baseline.center_components, 1) ~= expected_count || ...
    size(baseline.center_components, 2) < 3.0 || ...
    any(baseline.center_components(:, 2) ~= 0.0)
  error('I51dInput:BaselineMaterial', ...
    'The v2 zero-centered material assembly has an unexpected shape.');
end
finite_center = complex(zeros(expected_count, 1));
finite_radius = zeros(expected_count, 1);
finite_source_radius = zeros(expected_count, 1);
finite_target_radius = zeros(expected_count, 1);
finite_eval_radius = zeros(expected_count, 1);
finite_m_r_radius = zeros(expected_count, 1);
finite_m_i_radius = zeros(expected_count, 1);
finite_m_t_radius = zeros(expected_count, 1);
finite_m_l_radius = zeros(expected_count, 1);
expected_orders = repmat(regular.mode_orders, state_count, 1);
expected_labels = cell(expected_count, 1);
for state_index = 1:state_count
  rows = (state_index - 1.0) * ell_count + (1:ell_count);
  state = states{state_index};
  state_norm = norm(state, 2);
  finite_center(rows) = regular.physical_normal_rows * state;
  finite_source_radius(rows) = regular.source_quadrature_row_radius * ...
    state_norm;
  finite_target_radius(rows) = regular.target_quadrature_row_radius * ...
    state_norm;
  finite_eval_radius(rows) = ...
    regular.finite_special_function_eval_row_radius * state_norm;
  finite_m_r_radius(rows) = regular.M_R_row_radius * state_norm;
  finite_m_i_radius(rows) = regular.M_I_row_radius * state_norm;
  finite_m_t_radius(rows) = regular.M_T_row_radius * state_norm;
  finite_m_l_radius(rows) = regular.M_L_row_radius * state_norm;
  finite_radius(rows) = finite_source_radius(rows) + ...
    finite_target_radius(rows) + finite_eval_radius(rows) + ...
    finite_m_r_radius(rows) + finite_m_i_radius(rows) + ...
    finite_m_t_radius(rows) + finite_m_l_radius(rows);
  expected_labels(rows) = repmat(labels(state_index), ell_count, 1);
end
if ~isequal(double(baseline.mode_orders(:)), expected_orders) || ...
    ~isequal(cellstr(baseline.state_labels), expected_labels)
  error('I51dInput:StateOrder', ...
    'The reconstructed frozen states do not match the v2 row ordering.');
end

base_low = v2.enclosure.tail_assembly.material.low_cell;
if numel(base_low) ~= 2.0
  error('I51dInput:LowCellCount', ...
    'The v2 material low-cell certificate must contain two sides.');
end
side_maps = {double(z.Gminus), double(z.Gplus)};
low_cell = base_low;
for side_index = 1:2
  item = base_low(side_index);
  required = {'combined_center_row_map', 'state_map_norm_upper', ...
    'off_surface_unit_radius', 'weight_factor', 'tail_state_norm', ...
    'sum_power_squared_upper'};
  if ~all(isfield(item, required))
    error('I51dInput:LowCellSchema', ...
      'A v2 material low-cell side is incomplete.');
  end
  low_cell(side_index).combined_center_row_map = ...
    double(item.combined_center_row_map) + ...
    regular.physical_normal_rows * side_maps{side_index};
  low_cell(side_index).regular_unit_radius = ...
    regular.total_retained_row_radius;
  low_cell(side_index).regular_center_added = true;
  low_cell(side_index).old_zero_center_radius_replaced = true;
end
finite_values = [finite_center(:); finite_radius(:); ...
  finite_source_radius(:); finite_target_radius(:); finite_eval_radius(:); ...
  finite_m_r_radius(:); finite_m_i_radius(:); finite_m_t_radius(:); ...
  finite_m_l_radius(:)];
for side_index = 1:2
  finite_values = [finite_values; ...
    low_cell(side_index).combined_center_row_map(:); ...
    low_cell(side_index).regular_unit_radius(:)]; %#ok<AGROW>
end
out = struct( ...
  'mode_orders', expected_orders, ...
  'state_labels', {expected_labels}, ...
  'finite_physical_center', finite_center, ...
  'finite_regular_radius', finite_radius, ...
  'finite_source_quadrature_radius', finite_source_radius, ...
  'finite_target_quadrature_radius', finite_target_radius, ...
  'finite_special_function_eval_radius', finite_eval_radius, ...
  'finite_M_R_radius', finite_m_r_radius, ...
  'finite_M_I_radius', finite_m_i_radius, ...
  'finite_M_T_radius', finite_m_t_radius, ...
  'finite_M_L_radius', finite_m_l_radius, ...
  'low_cell', low_cell, ...
  'old_regular_center', 'zero', ...
  'new_regular_center', 'physical_signed_normal', ...
  'gate', struct( ...
    'retained_state_order_match', true, ...
    'old_regular_center_zero', true, ...
    'low_cell_center_recomputed', true, ...
    'low_cell_radius_replaced', true, ...
    'pass', all(isfinite(finite_values)) && ...
      all(finite_radius >= 0.0)));
end

function [states, labels] = LOCAL_retained_states(z, cell_cutoff)
states = {double(z.q_center)};
labels = {'center'};
sides = {struct('name', 'minus', 'G', double(z.Gminus), ...
  'P', double(z.Pminus), 'c', double(z.cminus)), ...
  struct('name', 'plus', 'G', double(z.Gplus), ...
  'P', double(z.Pplus), 'c', double(z.cplus))};
for side_index = 1:2
  item = sides{side_index};
  state = item.c;
  for cell_index = 0:cell_cutoff - 1.0
    states{end + 1} = item.G * state; %#ok<AGROW>
    labels{end + 1} = sprintf('%s-cell-%d', ...
      item.name, cell_index); %#ok<AGROW>
    state = item.P * state;
  end
end
end
