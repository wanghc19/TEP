function result = residual_numerator_a1(artifact_path, input_path, output_path)
%RESIDUAL_NUMERATOR_A1 Evaluate the I5 continuous residual numerator.
% Purpose:
%   Evaluate ordinary retained material value/normal rows and attach explicit
%   exact-Ewald, local-panel, angular, and full-propagation omission bounds;
%   add the frozen accepted artificial-wall normal module and both wall and
%   material value-defect lifts.
% Input:
%   artifact_path - Explicit frozen fbie-a1 certificate MAT path.
%   input_path    - Explicit residual-numerator input MAT path.
%   output_path   - Explicit create-once result MAT path.
% Output:
%   result        - B_Gamma_pm, B_Upsilon, and complete B_lift assembly.
% Main algorithm:
%   Reconstruct frozen finite densities; evaluate shape-general Kress local
%   rows, a finite exact Ewald representation of the regular images, and the
%   separated finite wall action; widen rows by analytic bounds; then apply
%   a whole-matrix block-power certificate to the frozen half-guide states.
% Based on:
%   (M-R)--(M-L), (M-off), and (M-weight) in s-material-tail.md; (P1)--
%   (P29) in s-local-panel.md; and (T-lift) in s-lift-tail.md.
% Main changes:
%   The governing QP kernel is Ewald, never the MFS proxy.  The local action
%   is assembled on a parameterized curve and never uses circular Bessel or
%   Fourier diagonalization.  Kress values are only enclosure centers.
% Numerical goal:
%   Produce a finite, possibly wide, drift-free ordinary display of the full
%   continuous residual numerator for the frozen reconstruction.
% Notes:
%   Floating-point rounding is deliberately not enclosed.  Every persisted
%   result is labeled NON_CERTIFIED_ROUNDOFF_EXCLUDED.

timer = tic;
[artifact_path, input_path, output_path] = LOCAL_paths( ...
  artifact_path, input_path, output_path);
loaded_artifact = load(artifact_path, 'staged');
loaded_input = load(input_path, 'experiment_input');
if ~isfield(loaded_artifact, 'staged') || ...
    ~isfield(loaded_input, 'experiment_input')
  error('I5Residual:Schema', 'A required top-level MAT variable is absent.');
end
staged = loaded_artifact.staged;
experiment_input = loaded_input.experiment_input;
z = staged.certificate;
cfg = experiment_input.configuration;
LOCAL_validate(z, staged, experiment_input, output_path);

% --- stage 1: frozen density, geometry, branch, and propagation gates ---
density = LOCAL_density(z, experiment_input);
geometry = LOCAL_geometry(experiment_input);
branch = LOCAL_branch(z);
propagation_minus = LOCAL_block_certificate(z.Pminus, cfg.block_length);
propagation_plus = LOCAL_block_certificate(z.Pplus, cfg.block_length);
if ~branch.pass || ~propagation_minus.contraction_pass || ...
    ~propagation_plus.contraction_pass
  error('I5Residual:FiniteGate', ...
    'A branch, non-Wood, geometry, or block-power gate failed.');
end

% --- stage 2: local, regular-image, and off-surface action rows ---
local_factors = LOCAL_local_factor_bounds(z, geometry, cfg);
local_action = LOCAL_local_action(z, geometry, density, local_factors, cfg);
regular_certificate = LOCAL_ewald_certificate(z, geometry, cfg);
regular_action = LOCAL_regular_action( ...
  z, geometry, density, regular_certificate, cfg);
off_surface_action = LOCAL_off_surface_action(z, geometry, cfg);
rows = LOCAL_combined_rows( ...
  geometry, local_action, regular_action, off_surface_action, cfg);
wall_value_action = LOCAL_wall_value_action( ...
  z, geometry, density, propagation_minus, propagation_plus, cfg);

% --- stage 3: material trace and tubular lifting assemblies ---
weights = LOCAL_weights(z, geometry, cfg);
material = LOCAL_material_assembly(z, geometry, rows, weights, local_action, ...
  regular_action, off_surface_action, propagation_minus, ...
  propagation_plus, cfg);
material_lifting = LOCAL_lifting_assembly(z, geometry, rows, weights, local_action, ...
  regular_action, off_surface_action, propagation_minus, ...
  propagation_plus, cfg);
lifting = LOCAL_total_lifting(material_lifting, wall_value_action, cfg);

% --- stage 4: conditional eigenvalue-error display from the numerator ---
wall_normal = struct( ...
  'B_Gamma_pm', cfg.accepted_B_Gamma_pm, ...
  'source_path', cfg.accepted_B_Gamma_pm_source_path, ...
  'source_field', cfg.accepted_B_Gamma_pm_source_field, ...
  'read_from_historical_output_at_runtime', false, ...
  'ordinary_floating_point', true);
numerator_majorant = wall_normal.B_Gamma_pm + material.bound + lifting.bound;
prediction = LOCAL_prediction(z, staged.ordinary_anchor, numerator_majorant);
acceptance_pass = local_action.gate.pass && regular_certificate.gate.pass && ...
  off_surface_action.gate.pass && wall_value_action.gate.pass && ...
  material.tail_budget_pass && lifting.tail_budget_pass;
if acceptance_pass
  run_status = 'COMPLETE_RESIDUAL_NUMERATOR_ORDINARY';
else
  run_status = 'FINITE_BOUND_STOPPING_TOLERANCE_FAILED_ORDINARY';
end
component_scale = struct( ...
  'B_Gamma_pm', wall_normal.B_Gamma_pm, ...
  'B_Upsilon', material.bound, ...
  'B_lift', lifting.bound, ...
  'B_Gamma_pm_share', wall_normal.B_Gamma_pm / numerator_majorant, ...
  'B_Upsilon_share', material.bound / numerator_majorant, ...
  'B_lift_share', lifting.bound / numerator_majorant);
workspace = whos;
result = struct( ...
  'status', run_status, ...
  'claim_scope', 'B_GAMMA_PM_PLUS_B_UPSILON_PLUS_B_LIFT', ...
  'certification_label', cfg.roundoff_label, ...
  'roundoff_excluded', true, ...
  'reliability_certified', false, ...
  'numerator_majorant', numerator_majorant, ...
  'component_scale', component_scale, ...
  'wall_normal', wall_normal, ...
  'material', material, ...
  'lifting', lifting, ...
  'prediction', prediction, ...
  'rows', rows, ...
  'local_panel', local_action, ...
  'regular_image', regular_action, ...
  'regular_image_certificate', regular_certificate, ...
  'off_surface', off_surface_action, ...
  'wall_value_action', wall_value_action, ...
  'weights', weights, ...
  'density_audit', density.audit, ...
  'branch_audit', branch, ...
  'propagation_minus', propagation_minus, ...
  'propagation_plus', propagation_plus, ...
  'theorem_gate', struct( ...
    'local_panel_finite_enclosure', local_action.gate.pass, ...
    'regular_image_truncation', regular_certificate.gate.pass, ...
    'off_surface_finite_support', off_surface_action.gate.pass, ...
    'material_tail_tolerance', material.tail_budget_pass, ...
    'lifting_tail_tolerance', lifting.tail_budget_pass, ...
    'outward_rounding', false, ...
    'wall_value_lifting_complete', wall_value_action.gate.pass, ...
    'analytic_coverage_complete', local_action.gate.pass && ...
      regular_certificate.gate.pass && off_surface_action.gate.pass && ...
      wall_value_action.gate.pass, ...
    'total_residual_numerator_complete', acceptance_pass), ...
  'missing_modules', {{}}, ...
  'provenance', struct( ...
    'artifact_path', artifact_path, ...
    'input_path', input_path, ...
    'governing_kernel', 'finite exact Ewald representation plus analytic tails', ...
    'mfs_proxy_used', false, ...
    'circle_bessel_diagonalization_used', false, ...
    'sampling_drift_used', false, ...
    'eigenpair_solves', 0.0, ...
    'bie_density_solves', 0.0, ...
    'qz_decompositions', 0.0, ...
    'propagation_matrix_solves', 0.0), ...
  'resource', struct( ...
    'elapsed_seconds_before_save', toc(timer), ...
    'workspace_proxy_mib_before_save', ...
      sum([workspace.bytes]) / 2.0^20));
save(output_path, 'result', '-v7.3');
end

%% ==================== Input contracts ====================
% These helpers validate explicit MAT interfaces and frozen dimensions.

function [artifact_path, input_path, output_path] = LOCAL_paths( ...
    artifact_path, input_path, output_path)
artifact_path = LOCAL_char_path(artifact_path, 'artifact_path');
input_path = LOCAL_char_path(input_path, 'input_path');
output_path = LOCAL_char_path(output_path, 'output_path');
if ~isfile(artifact_path) || ~isfile(input_path)
  error('I5Residual:InputPath', 'Both explicit MAT inputs must exist.');
end
if isfile(output_path) || isfolder(output_path)
  error('I5Residual:OutputExists', 'output_path must be a new MAT target.');
end
output_directory = fileparts(output_path);
if ~isempty(output_directory) && ~isfolder(output_directory)
  error('I5Residual:OutputDirectory', ...
    'The explicit result directory does not exist.');
end
end

function value = LOCAL_char_path(value, name)
if isstring(value) && isscalar(value)
  value = char(value);
end
if ~ischar(value) || isempty(value)
  error('I5Residual:Path', '%s must be a nonempty path.', name);
end
end

function LOCAL_validate(z, staged, input, output_path)
required = {'khat', 'gamma', 'mu_h', 'beta', 'd', 'R', 'rho_disk', ...
  'delta_c', 'M', 'K', 'q_center', 'Gplus', 'Gminus', 'Pplus', ...
  'Pminus', 'cplus', 'cminus', 'eta_unit_256', ...
  'xi_left_unit_512', 'xi_right_unit_512', 'density_coordinate'};
required = [required, {'wall_input_unit_512', 'wall_orders_512', ...
  'center_wall_jumps', 'delta_w'}];
input_required = {'schema', 'contour', 'parameter_nodes', ...
  'arclength_nodes', 'speed', 'normal', 'curve_certificate', ...
  'self_tube_certificate', 'cancellation_safe_certificate', ...
  'local_complex_strip_certificate', ...
  'ewald_gate_certificate', 'configuration'};
if ~all(isfield(z, required)) || ~all(isfield(input, input_required)) || ...
    ~isfield(staged, 'ordinary_anchor') || ...
    ~strcmp(input.schema, 'TEP_I5_RESIDUAL_NUMERATOR_INPUT_V1')
  error('I5Residual:Schema', 'The frozen artifact or input schema is incomplete.');
end
K = double(z.K);
N = double(input.configuration.boundary_node_count);
if ~isequal(size(z.eta_unit_256), [512, 2 * K]) || ...
    ~ismember(N, [256.0, 512.0]) || ...
    double(input.configuration.retained_mode_cutoff) ~= N / 2.0 - 1.0 || ...
    ~isequal(size(input.contour), [6, N]) || ...
    ~isequal(size(z.Gplus), [2 * K, K]) || ...
    ~isequal(size(z.Gminus), [2 * K, K]) || ...
    ~isequal(size(z.Pplus), [K, K]) || ...
    ~isequal(size(z.Pminus), [K, K]) || ...
    ~strcmp(strtrim(z.density_coordinate), '[tau;zeta], zeta=-sigma') || ...
    ~all(isfield(z.center_wall_jumps, ...
      {'left_coefficients', 'right_coefficients'})) || ...
    ~input.ewald_gate_certificate.finite_nonwood_pass || ...
    ~input.ewald_gate_certificate.retained_image_positive_pass || ...
    ~input.ewald_gate_certificate.local_series_ratio_pass || ...
    ~input.local_complex_strip_certificate.normalized_chord_zero_free || ...
    ~input.local_complex_strip_certificate.log_chord_branch_fixed || ...
    ~input.local_complex_strip_certificate.simultaneous_shift_admissible || ...
    ~all(isfield(input.local_complex_strip_certificate, ...
      {'normalized_tangent_dot_abs_upper', ...
      'target_tangent_projection_abs_upper'})) || ...
    z.gamma ~= z.mu_h || z.khat <= 0.0 || z.d <= 0.0 || ...
    isfile(output_path)
  error('I5Residual:FrozenGate', 'A frozen dimension or convention failed.');
end
end

%% ==================== Frozen data and geometry ====================
% Density signs, arclength coordinates, and Rayleigh branches are fixed here.

function density = LOCAL_density(z, input)
N = 256.0;
orders = (-N / 2.0:N / 2.0 - 1.0).';
tau_native = double(z.eta_unit_256(1:N, :));
zeta_native = double(z.eta_unit_256(N + 1.0:end, :));
tau_coeff_map = fftshift(fft(tau_native, [], 1), 1) / N;
zeta_coeff_map = fftshift(fft(zeta_native, [], 1), 1) / N;
sigma_coeff_map = -zeta_coeff_map;
tau_values = exp(1i * input.parameter_nodes * orders.') * tau_coeff_map;
sigma_values = exp(1i * input.parameter_nodes * orders.') * sigma_coeff_map;
tau_parseval = abs(norm(tau_native, 'fro')^2 / N - ...
  norm(tau_coeff_map, 'fro')^2) / max(realmin, norm(tau_coeff_map, 'fro')^2);
sigma_parseval = abs(norm(zeta_native, 'fro')^2 / N - ...
  norm(sigma_coeff_map, 'fro')^2) / max(realmin, norm(sigma_coeff_map, 'fro')^2);
density = struct( ...
  'orders', orders, ...
  'tau_coeff_map', tau_coeff_map, ...
  'sigma_coeff_map', sigma_coeff_map, ...
  'tau_values', tau_values, ...
  'sigma_values', sigma_values, ...
  'tau_linf_upper', sum(vecnorm(tau_coeff_map, 2, 2)), ...
  'sigma_linf_upper', sum(vecnorm(sigma_coeff_map, 2, 2)), ...
  'audit', struct( ...
    'transform', 'fftshift(fft(native_samples))/256', ...
    'midpoint_phase_applied', false, ...
    'stored_zeta_changed_to_sigma_once', true, ...
    'tau_parseval_relative_defect', tau_parseval, ...
    'sigma_parseval_relative_defect', sigma_parseval, ...
    'pass', max(tau_parseval, sigma_parseval) <= 4096.0 * eps));
if ~density.audit.pass
  error('I5Residual:DensityAudit', 'The frozen density transform failed.');
end
end

function geometry = LOCAL_geometry(input)
C = double(input.contour);
geometry = struct( ...
  'position', [C(1, :).', C(4, :).'], ...
  'derivative', [C(2, :).', C(5, :).'], ...
  'second_derivative', [C(3, :).', C(6, :).'], ...
  'speed', double(input.speed(:)), ...
  'normal', double(input.normal), ...
  'parameter_nodes', double(input.parameter_nodes(:)), ...
  'arclength_nodes', double(input.arclength_nodes(:)), ...
  'certificate', input.curve_certificate, ...
  'tube', input.self_tube_certificate, ...
  'cancellation', input.cancellation_safe_certificate, ...
  'local_complex', input.local_complex_strip_certificate);
if any(~isfinite([geometry.position(:); geometry.derivative(:); ...
    geometry.speed(:); geometry.normal(:)])) || ...
    min(geometry.speed) <= 0.0 || ...
    ~input.panel_width_gate || ...
    ~geometry.tube.embedded_complex_tube
  error('I5Residual:GeometryGate', 'The curve certificate is invalid.');
end
end

function branch = LOCAL_branch(z)
orders = (-256.0:255.0).';
transverse_wavenumber = double(z.beta) + 2.0 * pi * orders / double(z.d);
radicand = double(z.khat)^2 - transverse_wavenumber.^2;
rayleigh_wavenumber = sqrt(complex(radicand));
flip = imag(rayleigh_wavenumber) < 0.0 | ...
  (imag(rayleigh_wavenumber) == 0.0 & real(rayleigh_wavenumber) < 0.0);
rayleigh_wavenumber(flip) = -rayleigh_wavenumber(flip);
exact_wood = any(rayleigh_wavenumber == 0.0);
branch = struct( ...
  'orders', orders, ...
  'transverse_wavenumber', transverse_wavenumber, ...
  'rayleigh_wavenumber', rayleigh_wavenumber, ...
  'minimum_nonwood_margin', min(abs(radicand)), ...
  'exact_wood', exact_wood, ...
  'pass', ~exact_wood && all(isfinite(rayleigh_wavenumber)));
end

%% ==================== Shape-general local action ====================
% Kress matrices are retained centers; P19/P28 bounds enclose all row error.

function action = LOCAL_local_action(z, geometry, density, factors, cfg)
N = numel(geometry.parameter_nodes);
dt = 2.0 * pi / N;
geom_data = struct( ...
  'z', geometry.position, ...
  'zp', geometry.derivative, ...
  'zpp', geometry.second_derivative, ...
  'speed', geometry.speed);
[parameter_nodes, D] = utils.triginterp(N);
if max(abs(parameter_nodes(:) - geometry.parameter_nodes(:))) > 4096.0 * eps
  error('I5Residual:ParameterGrid', 'The Kress grid differs from the contract.');
end
R = LOCAL_kress_matrix(N);
k_outer = double(z.khat);
k_inner = sqrt(double(z.rho_disk)) * k_outer;
[M1e, M2e, N1e, N2e] = kernel.kress_mn_splits( ...
  k_outer, parameter_nodes, geom_data);
[M1i, M2i, N1i, N2i] = kernel.kress_mn_splits( ...
  k_inner, parameter_nodes, geom_data);
[L1e, L2e, Ls1e, Ls2e] = kernel.kress_l_splits( ...
  k_outer, parameter_nodes, geom_data);
[L1i, L2i, Ls1i, Ls2i] = kernel.kress_l_splits( ...
  k_inner, parameter_nodes, geom_data);
A11 = R .* (L1e - L1i) + dt * (L2e - L2i);
A12 = R .* (M1i - M1e) + dt * (M2i - M2e);
A22 = R .* (Ls1i - Ls1e) + dt * (Ls2i - Ls2e);
G = (geom_data.zp * geom_data.zp.') ./ ...
  (geom_data.speed * geom_data.speed.');
delta_M1 = k_outer^2 * M1e - k_inner^2 * M1i;
delta_M2 = k_outer^2 * M2e - k_inner^2 * M2i;
delta_N1 = N1e - N1i;
delta_N2 = N2e - N2i;
Tdiff = (R .* delta_M1 + dt * delta_M2) .* G + ...
  bsxfun(@rdivide, R .* delta_N1 + dt * delta_N2, ...
  geom_data.speed) * D;
zeta_values = -density.sigma_values;
value_samples = (eye(N) + A11) * density.tau_values + ...
  A12 * zeta_values;
normal_samples = -(Tdiff * density.tau_values + ...
  (eye(N) + A22) * zeta_values);
[value_rows, mode_orders] = LOCAL_rows(value_samples, geometry, cfg);
[normal_rows, ~] = LOCAL_rows(normal_samples, geometry, cfg);
P = geometry.certificate.boundary_length;
a = geometry.local_complex.parameter_strip_width;
strip_geometry = geometry;
strip_geometry.cancellation = geometry.local_complex;
strip_factors = LOCAL_local_factor_bounds(z, strip_geometry, cfg);
maue_geometry = strip_geometry;
maue_geometry.cancellation.pi_s_abs_upper = ...
  geometry.local_complex.target_tangent_projection_abs_upper;
maue_factors = LOCAL_local_factor_bounds(z, maue_geometry, cfg);
density_weight = exp(a * abs(density.orders));
tau_strip = sum(density_weight .* ...
  vecnorm(density.tau_coeff_map, 2, 2));
tau_prime_strip = sum(abs(density.orders) .* density_weight .* ...
  vecnorm(density.tau_coeff_map, 2, 2));
sigma_strip = sum(density_weight .* ...
  vecnorm(density.sigma_coeff_map, 2, 2));
strip_speed = geometry.local_complex.strip_speed_upper;
strip_path_length = geometry.local_complex.strip_path_length_upper;
value_log_integrand = strip_speed * (...
  strip_factors.C_K * tau_strip + strip_factors.C_S * sigma_strip);
value_smooth_integrand = strip_speed * (...
  strip_factors.R_K * tau_strip + strip_factors.R_S * sigma_strip);
k_outer = double(z.khat);
k_inner = sqrt(double(z.rho_disk)) * k_outer;
J_outer = strip_factors.series_outer.J(1);
J_inner = strip_factors.series_inner.J(1);
D_outer = strip_factors.series_outer.D(1);
D_inner = strip_factors.series_inner.D(1);
euler_constant = 0.57721566490153286060;
c_outer = abs(1i / 4.0 - ...
  (log(k_outer / 2.0) + euler_constant) / (2.0 * pi));
c_inner = abs(1i / 4.0 - ...
  (log(k_inner / 2.0) + euler_constant) / (2.0 * pi));
maue_M_log = (k_outer^2 * J_outer + k_inner^2 * J_inner) / ...
  (4.0 * pi);
maue_M_smooth = maue_M_log * ...
  geometry.local_complex.log_chord_quotient_upper + ...
  k_outer^2 * (c_outer * J_outer + D_outer / (2.0 * pi)) + ...
  k_inner^2 * (c_inner * J_inner + D_inner / (2.0 * pi));
tangent_dot = geometry.local_complex.normalized_tangent_dot_abs_upper;
normal_log_integrand = strip_speed * tangent_dot * maue_M_log * ...
  tau_strip + maue_factors.C_Kstar * tau_prime_strip;
normal_smooth_integrand = strip_speed * tangent_dot * maue_M_smooth * ...
  tau_strip + maue_factors.R_Kstar * tau_prime_strip;
alias_factor = 4.0 * pi * exp(-a * N / 2.0) * ...
  (1.0 + exp(-a)) / (1.0 - exp(-a));
smooth_factor = 4.0 * pi / expm1(a * N);
source_value_error = alias_factor * value_log_integrand + ...
  smooth_factor * value_smooth_integrand;
source_normal_error = alias_factor * normal_log_integrand + ...
  smooth_factor * normal_smooth_integrand;
value_strip_upper = tau_strip + ...
  (4.0 * strip_path_length * log(2.0) * strip_factors.C_K + ...
  strip_path_length * strip_factors.R_K) * tau_strip + ...
  (4.0 * strip_path_length * log(2.0) * strip_factors.C_S + ...
  strip_path_length * strip_factors.R_S) * sigma_strip;
normal_strip_upper = sigma_strip + ...
  (4.0 * strip_path_length * log(2.0) * strip_factors.C_T + ...
  strip_path_length * strip_factors.R_T) * tau_strip + ...
  (4.0 * strip_path_length * log(2.0) * strip_factors.C_Kstar + ...
  strip_path_length * strip_factors.R_Kstar) * sigma_strip;
xi = 2.0 * pi * mode_orders / P;
phase_growth = exp(abs(xi) * ...
  geometry.local_complex.arclength_imag_upper);
target_factor = 4.0 * pi * strip_speed / ...
  (sqrt(P) * expm1(a * N));
target_value_error = target_factor * value_strip_upper .* phase_growth;
target_normal_error = target_factor * normal_strip_upper .* phase_growth;
source_to_row = sum((2.0 * pi / N) * geometry.speed) / sqrt(P);
value_error = source_to_row * source_value_error + target_value_error;
normal_error = source_to_row * source_normal_error + target_normal_error;
tau_identity_l2 = sqrt(2.0 * pi * ...
  geometry.certificate.speed_upper) * density.tau_linf_upper;
sigma_identity_l2 = sqrt(2.0 * pi * ...
  geometry.certificate.speed_upper) * density.sigma_linf_upper;
value_action = (4.0 * P * log(2.0) * factors.C_K + ...
  P * factors.R_K) * density.tau_linf_upper + ...
  (4.0 * P * log(2.0) * factors.C_S + ...
  P * factors.R_S) * density.sigma_linf_upper;
normal_action = (4.0 * P * log(2.0) * factors.C_T + ...
  P * factors.R_T) * density.tau_linf_upper + ...
  (4.0 * P * log(2.0) * factors.C_Kstar + ...
  P * factors.R_Kstar) * density.sigma_linf_upper;
value_l2_upper = tau_identity_l2 + sqrt(P) * value_action;
normal_l2_upper = sigma_identity_l2 + sqrt(P) * normal_action;
tau_second_l2 = sqrt(2.0 * pi * geometry.certificate.speed_upper) * ...
  (geometry.certificate.speed_lower^(-2.0) * ...
  sum((density.orders.^2) .* vecnorm(density.tau_coeff_map, 2, 2)) + ...
  geometry.certificate.speed_derivative_upper * ...
  geometry.certificate.speed_lower^(-3.0) * ...
  sum(abs(density.orders) .* vecnorm(density.tau_coeff_map, 2, 2)));
value_second_action = (4.0 * P * log(2.0) * factors.C_K2 + ...
  P * factors.R_K2) * density.tau_linf_upper + ...
  (4.0 * P * log(2.0) * factors.C_S2 + ...
  P * factors.R_S2) * density.sigma_linf_upper;
value_second_l2_upper = tau_second_l2 + sqrt(P) * value_second_action;
action = struct( ...
  'mode_orders', mode_orders, ...
  'value_rows', value_rows, ...
  'normal_rows', normal_rows, ...
  'value_row_error', value_error, ...
  'normal_row_error', normal_error, ...
  'value_l2_upper', value_l2_upper, ...
