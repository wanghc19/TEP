tail = reciprocal_tail + image_tail + local_tail;
out = struct( ...
  'coordinate_order', {{'00', '10', '01', '20', '11', '02'}}, ...
  'finite', finite, ...
  'reciprocal_tail', reciprocal_tail, ...
  'omitted_image_tail', image_tail, ...
  'local_factorial_tail', local_tail, ...
