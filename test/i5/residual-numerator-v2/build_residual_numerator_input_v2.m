    all(isfinite(item.combined_center_row_map(:)));
  low_cell_weight_once = low_cell_weight_once && ...
    isfield(item, 'center_combined_before_weight') && ...
    isequal(item.center_combined_before_weight, true) && ...
    isfield(item, 'weight_application') && ...
    strcmp(item.weight_application, 'single post-combination factor');
