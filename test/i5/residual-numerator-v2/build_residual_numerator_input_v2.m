%BUILD_RESIDUAL_NUMERATOR_INPUT_V2 Build the I5.1c data-only input.
% Purpose:
%   Join the frozen reconstruction data to explicit accepted wall scalars and build
%   a conservative current-circle instance of the KR-15 local certificate.
% Input:
%   artifact_path  - Explicit frozen I3 certificate MAT path.
%   curve_contract_path - Explicit accepted circle curve-contract MAT path.
%   wall_finite_squared - Accepted nonnegative wall finite square.
%   wall_tail_squared - Accepted nonnegative wall omission-tail square.
%   input_path     - Explicit create-once MAT output path.
%   wall_provenance_label - Optional non-authorizing provenance text.
% Output:
%   experiment_input - Self-contained data contract for residual_numerator_v2.
% Main algorithm:
%   Verify the frozen density convention, form its finite Fourier coefficient
%   maps once, audit independent L/N separation, construct the local
%   power-series enclosure, and validate the explicit wall finite/tail datum.
% Based on:
%   (KR-2), (KR-8)--(KR-15), and the finite-input contract in s-kress-real.md.
% Main changes:
%   This version rejects the historical N=512, L=256 pairing and contains no
%   complex-strip/P32 gate.
% Numerical goal:
%   Produce the immutable input for one fail-closed I5.1c scientific run.

if nargin < 6 || isempty(wall_provenance_label)
  wall_provenance_label = 'UNSPECIFIED_NONAUTHORIZING_PROVENANCE';
end
[artifact_path, curve_contract_path, input_path] = ...
  LOCAL_paths(artifact_path, curve_contract_path, input_path);
[wall_finite_squared, wall_tail_squared, wall_provenance_label] = ...
  LOCAL_wall_inputs( ...
    wall_finite_squared, wall_tail_squared, wall_provenance_label);
