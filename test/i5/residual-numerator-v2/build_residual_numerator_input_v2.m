  local.derivative.nor.target_diagonal_sup(:).', ...
  local.derivative.nor.H_q, local.derivative.nor.Q2, ...
  local.derivative.nor.delta_Ctan2_source_second_upper, ...
  local.derivative.nor.delta_Dstar2_source_second_upper];
