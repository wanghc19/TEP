%% ==================== Contract validation ====================
% These helpers reject convention drift before any scientific evaluation.

function LOCAL_validate_frozen(z)
required = {'khat', 'gamma', 'mu_h', 'beta', 'd', 'R', 'rho_disk', ...
  'delta_c', 'delta_w', 'X_L', 'X_R', 'q_center', 'Gplus', 'Gminus', ...
  'Pplus', 'Pminus', 'cplus', 'cminus', 'xi_left_unit_512', ...
  'xi_right_unit_512', 'eta_unit_256', 'density_coordinate', ...
  'wall_input_unit_512', 'wall_orders_512', ...
  'center_left_value_mismatch', 'center_right_value_mismatch'};
if ~all(isfield(z, required)) || ...
    ~ismatrix(z.eta_unit_256) || mod(size(z.eta_unit_256, 1), 2) ~= 0 || ...
    size(z.eta_unit_256, 1) ~= 512 || ...
    ~strcmp(strtrim(char(z.density_coordinate)), ...
      '[tau;zeta], zeta=-sigma') || ...
    any(~isfinite([double(z.khat), double(z.mu_h), double(z.beta), ...
      double(z.d), double(z.R), double(z.rho_disk)])) || ...
    z.gamma ~= z.mu_h || z.khat <= 0.0 || z.d <= 0.0 || z.R <= 0.0
  error('I51cInput:FrozenGate', ...
    'The frozen scalar, density-size, or density-sign contract failed.');
end
end

function audit = LOCAL_validate_curve(z, contract)
required = {'schema', 'parameter_period', 'source_node_count', ...
  'source_contour', 'density_coordinate', 'orientation', 'node_rule', ...
  'adapter_metadata'};
if ~all(isfield(contract, required)) || ...
    ~strcmp(char(contract.schema), 'TEP_I5_WALL_CURVE_CONTRACT_V1') || ...
    double(contract.parameter_period) ~= 2.0 * pi || ...
    double(contract.source_node_count) ~= 256.0 || ...
    ~strcmp(char(contract.orientation), ...
      'counter-clockwise; outward normal=(dy_dt,-dx_dt)/speed') || ...
    ~strcmp(char(contract.node_rule), ...
      't_j=2*pi*j/N, j=0,...,N-1; no midpoint shift') || ...
    ~strcmp(strtrim(char(contract.density_coordinate)), ...
      strtrim(char(z.density_coordinate))) || ...
    ~isfield(contract.adapter_metadata, 'radius') || ...
    double(contract.adapter_metadata.radius) ~= double(z.R) || ...
    ~isfield(contract.adapter_metadata, 'center') || ...
    ~isequal(double(contract.adapter_metadata.center), [0.0, 0.0]) || ...
    ~isfield(contract.adapter_metadata, 'geometry_constructor') || ...
    ~strcmp(char(contract.adapter_metadata.geometry_constructor), ...
      'geom.construct_cont')
  error('I51cInput:CurveContract', ...
    'The explicit curve contract does not match the frozen circle adapter.');
end
N_eta = double(contract.source_node_count);
[constructed, period] = geom.construct_cont( ...
  N_eta, 'circle', 0, 0, double(z.R));
contract_contour = double(contract.source_contour);
if period ~= 2.0 * pi || ...
    ~isequal(size(constructed), [6, N_eta]) || ...
    ~isequal(size(contract_contour), [6, N_eta])
  error('I51cInput:CurveShape', ...
    'The authoritative circle parameterization has the wrong shape.');
end
scale = max(1.0, max(abs(contract_contour(:))));
relative_defect = max(abs(constructed(:) - contract_contour(:))) / scale;
x = constructed(1, :).';
dx = constructed(2, :).';
y = constructed(4, :).';
dy = constructed(5, :).';
speed = hypot(dx, dy);
normal = [dy, -dx] ./ speed;
area = pi / N_eta * sum(x .* dy - y .* dx);
radial_dot = x .* normal(:, 1) + y .* normal(:, 2);
tolerance = 4096.0 * eps(scale);
parameterization_pass = all(isfinite(constructed(:))) && ...
  all(speed > 0.0) && area > 0.0 && all(radial_dot > 0.0);
density_phase_pass = relative_defect <= tolerance;
if ~parameterization_pass || ~density_phase_pass
  error('I51cInput:CurveAudit', ...
    'The CCW/outward or frozen density-node phase audit failed.');
end
audit = struct( ...
  'parameterization_ccw_outward', parameterization_pass, ...
  'density_node_phase_match', density_phase_pass, ...
  'orientation_area', area, ...
  'minimum_outward_radial_dot', min(radial_dot), ...
  'constructed_contract_relative_defect', relative_defect, ...
  'ordinary_identity_tolerance', tolerance, ...
  'geometry_constructor', 'geom.construct_cont', ...
  'pass', parameterization_pass && density_phase_pass);
end

%% ==================== Circle instance of KR-15 ====================
% These helpers use circle identities only to certify the current instance.

function out = LOCAL_circle_real_certificate( ...
    z, configuration, orders, tau_coeff_map, eta_second_coeff_map, ...
    build_center)
R = double(z.R);
kappa_e = double(z.khat);
kappa_i = sqrt(double(z.rho_disk)) * kappa_e;
Q = 4.0 * R^2;
series_cutoff = double(configuration.kernel_series_cutoff);
log_c = abs(log(R^2));

density_tau = LOCAL_density_derivative_bounds( ...
  orders, tau_coeff_map, 3.0);
density_eta_second = LOCAL_density_derivative_bounds( ...
  orders, eta_second_coeff_map, 2.0);
outer = LOCAL_primitive_series( ...
  kappa_e, Q, series_cutoff);
inner = LOCAL_primitive_series( ...
  kappa_i, Q, series_cutoff);
signed_outer = LOCAL_signed_primitive_series(kappa_e, series_cutoff);
signed_inner = LOCAL_signed_primitive_series(kappa_i, series_cutoff);

J_delta = (outer.J.upper + inner.J.upper) / (4.0 * pi);
J_delta_tail = (outer.J.tail + inner.J.tail) / (4.0 * pi);
j_delta = (outer.j_shift.upper + inner.j_shift.upper) / (4.0 * pi);
j_delta_tail = ...
  (outer.j_shift.tail + inner.j_shift.tail) / (4.0 * pi);
R_delta = outer.c_abs * outer.J.upper + ...
  inner.c_abs * inner.J.upper + ...
  (outer.Y.upper + inner.Y.upper) / (2.0 * pi);
R_delta_tail = outer.c_abs * outer.J.tail + ...
  inner.c_abs * inner.J.tail + ...
  (outer.Y.tail + inner.Y.tail) / (2.0 * pi);
% KR-13 uses W=2*U1.  Keeping this factor explicit supplies the
% j_shift/(2*pi), 2*c_k*J', and Y'/pi terms in KR-11.
W = 2.0 * (log_c * J_delta(2:4) + j_delta + R_delta(2:4));
W_tail = 2.0 * (log_c * J_delta_tail(2:4) + ...
  j_delta_tail + R_delta_tail(2:4));

S_delta_1_x = R * J_delta(1:3);
S_delta_1_tail = R * J_delta_tail(1);
S_delta_2_x = R * (log_c * J_delta(1:3) + R_delta(1:3));
S_delta_2_tail = R * ( ...
  log_c * J_delta_tail(1) + R_delta_tail(1));
S_outer_2_x = R * ((log_c / (4.0 * pi) + outer.c_abs) * ...
  outer.J.upper(1:3) + outer.Y.upper(1:3) / (2.0 * pi));
S_inner_2_x = R * ((log_c / (4.0 * pi) + inner.c_abs) * ...
  inner.J.upper(1:3) + inner.Y.upper(1:3) / (2.0 * pi));
weighted_S_1_x = R / (4.0 * pi) * ( ...
  kappa_e^2 * outer.J.upper(1:3) + ...
  kappa_i^2 * inner.J.upper(1:3));
weighted_S_1_tail = R / (4.0 * pi) * ( ...
  kappa_e^2 * outer.J.tail(1) + ...
  kappa_i^2 * inner.J.tail(1));
weighted_S_2_x = kappa_e^2 * S_outer_2_x + ...
  kappa_i^2 * S_inner_2_x;
weighted_S_2_tail = R * ( ...
  kappa_e^2 * ((log_c / (4.0 * pi) + outer.c_abs) * ...
    outer.J.tail(1) + outer.Y.tail(1) / (2.0 * pi)) + ...
  kappa_i^2 * ((log_c / (4.0 * pi) + inner.c_abs) * ...
    inner.J.tail(1) + inner.Y.tail(1) / (2.0 * pi)));

unit_multiplier = [1.0, 0.0, 0.0];
normal_chord_multiplier = [2.0 * R^2, R^2, R^2];
tangent_chord_multiplier = [R^2, R^2, R^2];
cosine_multiplier = [1.0, 1.0, 1.0];
S_1 = LOCAL_x_to_h_factor( ...
  S_delta_1_x, S_delta_1_tail, unit_multiplier, R);
S_2 = LOCAL_x_to_h_factor( ...
  S_delta_2_x, S_delta_2_tail, unit_multiplier, R);
D_1 = LOCAL_x_to_h_factor( ...
  2.0 * J_delta(2:4), 2.0 * J_delta_tail(2), ...
  normal_chord_multiplier, R);
D_2 = LOCAL_x_to_h_factor( ...
  W, W_tail(1), normal_chord_multiplier, R);
C_1 = LOCAL_x_to_h_factor( ...
  2.0 * J_delta(2:4), 2.0 * J_delta_tail(2), ...
  tangent_chord_multiplier, R);
C_2 = LOCAL_x_to_h_factor( ...
  W, W_tail(1), tangent_chord_multiplier, R);
weighted_S_1 = LOCAL_x_to_h_factor( ...
  weighted_S_1_x, weighted_S_1_tail, cosine_multiplier, R);
weighted_S_2 = LOCAL_x_to_h_factor( ...
  weighted_S_2_x, weighted_S_2_tail, cosine_multiplier, R);

val = LOCAL_complete_derivative_certificate( ...
  D_1, D_2, S_1, S_2, [], [], ...
  density_tau, density_eta_second, R, 'val');
nor = LOCAL_complete_derivative_certificate( ...
  D_1, D_2, weighted_S_1, weighted_S_2, C_1, C_2, ...
  density_tau, density_eta_second, R, 'nor');
geometry = LOCAL_circle_geometry(z, configuration);
val.H_q = val.identity_derivative_upper + ...
  8.0 * pi * log(2.0) * val.target_diagonal_sup(1, :) + ...
  2.0 * pi * val.target_diagonal_sup(2, :);
nor.H_q = nor.identity_derivative_upper + ...
  8.0 * pi * log(2.0) * nor.target_diagonal_sup(1, :) + ...
  2.0 * pi * nor.target_diagonal_sup(2, :);
val.Q2 = 2.0 * pi * val.H_q(3) / geometry.speed_lower;
nor.Q2 = 2.0 * pi * nor.H_q(3) / geometry.speed_lower;
nor.delta_Ctan2_source_second_upper = C_2.h_derivative_upper(3);
nor.delta_Dstar2_source_second_upper = D_2.h_derivative_upper(3);
nor.cotangent_difference_cancelled_before_bound = true;

[val_rows, nor_rows] = LOCAL_retained_operator_rows( ...
  z, configuration, orders, tau_coeff_map, eta_second_coeff_map, ...
  signed_outer, signed_inner, D_1, D_2, S_1, S_2, ...
  weighted_S_1, weighted_S_2, C_1, C_2, build_center);
retained_orders = (-(configuration.residual_mode_cutoff - 1.0): ...
  configuration.residual_mode_cutoff - 1.0).';
[~, val_alias] = LOCAL_constant_speed_alias_radius( ...
  val, geometry, retained_orders, configuration.evaluation_node_count);
[~, nor_alias] = LOCAL_constant_speed_alias_radius( ...
  nor, geometry, retained_orders, configuration.evaluation_node_count);
out = struct( ...
  'derivative', struct('val', val, 'nor', nor), ...
  'rows', struct('val', val_rows, 'nor', nor_rows), ...
  'target_alias_certificate', struct('val', val_alias, 'nor', nor_alias), ...
  'series', struct( ...
    'outer', outer, ...
    'inner', inner, ...
    'signed_outer', signed_outer, ...
    'signed_inner', signed_inner, ...
    'cutoff', series_cutoff, ...
    'all_ratio_gates_pass', outer.pass && inner.pass), ...
  'density_derivative_upper', struct( ...
    'tau', density_tau, 'eta_second', density_eta_second), ...
  'adapter_identity', struct( ...
    'q_upper', Q, ...
    'normalized_chord', R^2, ...
    'p_source_equals_minus_q_over_two', true, ...
    'p_target_equals_q_over_two', true, ...
    'p_tangent_formula', 'R^2*sin(t-u)'), ...
  'center_policy', ...
    'identity plus signed retained polynomial Kress operator center');
end

function bounds = LOCAL_density_derivative_bounds(orders, coeff_map, max_order)
row_norm = vecnorm(coeff_map, 2, 2);
bounds = zeros(1, max_order + 1.0);
for derivative_order = 0:max_order
  bounds(derivative_order + 1.0) = sum( ...
    abs(orders).^derivative_order .* row_norm);
end
end

function primitive = LOCAL_primitive_series(kappa, Q, cutoff)
max_derivative = 3.0;
J = LOCAL_entire_series(kappa, Q, cutoff, max_derivative, 'J');
Y = LOCAL_entire_series(kappa, Q, cutoff, max_derivative, 'Y');
j_shift = LOCAL_entire_series(kappa, Q, cutoff, 2.0, 'j_shift');
euler_constant = 0.57721566490153286060;
c_abs = abs(1i / 4.0 - ...
  (log(kappa / 2.0) + euler_constant) / (2.0 * pi));
primitive = struct( ...
  'J', J, 'Y', Y, 'j_shift', j_shift, ...
  'c_abs', c_abs, ...
  'pass', J.pass && Y.pass && j_shift.pass);
end

function primitive = LOCAL_signed_primitive_series(kappa, cutoff)
alpha = kappa^2 / 4.0;
euler_constant = 0.57721566490153286060;
c0 = 1i / 4.0 - ...
  (log(kappa / 2.0) + euler_constant) / (2.0 * pi);
a = complex(zeros(cutoff + 1.0, 1));
y = complex(zeros(cutoff + 1.0, 1));
a(1) = 1.0;
harmonic = 0.0;
for n = 1:cutoff
  a(n + 1.0) = a(n) * (-alpha) / n^2;
  harmonic = harmonic + 1.0 / n;
  y(n + 1.0) = harmonic * a(n + 1.0);
end
m = (0:cutoff - 1.0).';
u = a(2:end);
j_first = -2.0 * (m + 1.0) .* a(2:end);
c_regular = -a(2:end) / (2.0 * pi) + ...
  2.0 * c0 * (m + 1.0) .* a(2:end) + ...
  (m + 1.0) .* y(2:end) / pi;
primitive = struct( ...
  'J_coefficients', a, ...
  'Y_regular_coefficients', y, ...
  'j_shift_coefficients', u, ...
  'J_first_coefficients', j_first, ...
  'c_regular_coefficients', c_regular, ...
  'c0', c0, ...
  'J_retained_orders', (0:cutoff).', ...
  'shifted_retained_orders', m, ...
  'J_Y_first_omitted_order', cutoff + 1.0, ...
  'J_first_shifted_c_first_omitted_order', cutoff);
end

function record = LOCAL_entire_series( ...
    kappa, Q, cutoff, max_derivative, kind)
a = kappa^2 / 4.0;
upper = zeros(1, max_derivative + 1.0);
tail = zeros(1, max_derivative + 1.0);
ratio = zeros(1, max_derivative + 1.0);
for derivative_order = 0:max_derivative
  if strcmp(kind, 'j_shift')
    last_index = cutoff - 1.0;
    for m = derivative_order:last_index
      upper(derivative_order + 1.0) = ...
        upper(derivative_order + 1.0) + exp( ...
        gammaln(m + 1.0) - gammaln(m - derivative_order + 1.0) + ...
        (m + 1.0) * log(a) + ...
        (m - derivative_order) * log(Q) - ...
        2.0 * gammaln(m + 2.0));
    end
    m = cutoff;
    first = exp( ...
      gammaln(m + 1.0) - gammaln(m - derivative_order + 1.0) + ...
      (m + 1.0) * log(a) + ...
      (m - derivative_order) * log(Q) - ...
      2.0 * gammaln(m + 2.0));
    ratio(derivative_order + 1.0) = a * Q * (m + 1.0) / ...
      ((m + 1.0 - derivative_order) * (m + 2.0)^2);
  else
    first_index = derivative_order;
    if strcmp(kind, 'Y')
      first_index = max(1.0, derivative_order);
    end
    for n = first_index:cutoff
      harmonic = 1.0;
      if strcmp(kind, 'Y')
        harmonic = sum(1.0 ./ (1.0:n));
      end
      upper(derivative_order + 1.0) = ...
        upper(derivative_order + 1.0) + harmonic * exp( ...
        gammaln(n + 1.0) - gammaln(n - derivative_order + 1.0) + ...
        n * log(a) + (n - derivative_order) * log(Q) - ...
        2.0 * gammaln(n + 1.0));
    end
    n = cutoff + 1.0;
    harmonic = 1.0;
    if strcmp(kind, 'Y')
      harmonic = sum(1.0 ./ (1.0:n));
    end
    first = harmonic * exp( ...
      gammaln(n + 1.0) - gammaln(n - derivative_order + 1.0) + ...
      n * log(a) + (n - derivative_order) * log(Q) - ...
      2.0 * gammaln(n + 1.0));
    ratio(derivative_order + 1.0) = a * Q / ...
      ((n + 1.0) * (n + 1.0 - derivative_order));
    if strcmp(kind, 'Y')
      ratio(derivative_order + 1.0) = ...
        ratio(derivative_order + 1.0) * (1.0 + 1.0 / (n + 1.0));
    end
  end
  if ratio(derivative_order + 1.0) >= 1.0
    tail(derivative_order + 1.0) = Inf;
  else
    tail(derivative_order + 1.0) = first / ...
      (1.0 - ratio(derivative_order + 1.0));
  end
  upper(derivative_order + 1.0) = ...
    upper(derivative_order + 1.0) + tail(derivative_order + 1.0);
end
record = struct( ...
  'upper', upper, 'tail', tail, 'ratio', ratio, ...
  'pass', all(isfinite(upper)) && all(ratio < 1.0));
end

function factor = LOCAL_x_to_h_factor( ...
    x_derivative_upper, x_tail_value, multiplier, R)
x_derivative_upper = double(x_derivative_upper(:).');
multiplier = double(multiplier(:).');
x_first = 2.0 * R^2;
x_second = 2.0 * R^2;
h0 = multiplier(1) * x_derivative_upper(1);
h1 = multiplier(2) * x_derivative_upper(1) + ...
  multiplier(1) * x_derivative_upper(2) * x_first;
h2 = multiplier(3) * x_derivative_upper(1) + ...
  2.0 * multiplier(2) * x_derivative_upper(2) * x_first + ...
  multiplier(1) * (x_derivative_upper(3) * x_first^2 + ...
  x_derivative_upper(2) * x_second);
factor = struct( ...
  'h_derivative_upper', [h0, h1, h2], ...
  'series_tail_value_upper', multiplier(1) * x_tail_value);
end

function out = LOCAL_complete_derivative_certificate( ...
    D1, D2, S1, S2, C1, C2, tau, eta_second, R, action)
if strcmp(action, 'val')
  factor_1 = {D1, S1};
  factor_2 = {D2, S2};
  density_1 = {tau, eta_second};
  density_2 = density_1;
  identity = tau(1:3);
else
  factor_1 = {S1, C1, D1};
  factor_2 = {S2, C2, D2};
  density_1 = {tau, tau(2:4) / R, eta_second};
  density_2 = density_1;
  identity = eta_second(1:3);
end
source = zeros(1, 2);
target = zeros(2, 3);
factor_groups = {factor_1, factor_2};
density_groups = {density_1, density_2};
for split_index = 1:2
  factors = factor_groups{split_index};
  densities = density_groups{split_index};
  second_bound = 0.0;
  for term_index = 1:numel(factors)
    f = factors{term_index}.h_derivative_upper;
    density = densities{term_index};
    second_bound = second_bound + ...
      f(3) * density(1) + 2.0 * f(2) * density(2) + ...
      f(1) * density(3);
    for derivative_order = 0:2
      target(split_index, derivative_order + 1.0) = ...
        target(split_index, derivative_order + 1.0) + ...
        f(1) * density(derivative_order + 1.0);
    end
  end
  source(split_index) = 2.0 * pi * second_bound;
end
out = struct( ...
  'source_L1_p', source, ...
  'target_diagonal_sup', target, ...
  'identity_derivative_upper', identity, ...
  'H_q', NaN(1, 3), ...
  'Q2', NaN, ...
  'source_derivative_order', 2.0, ...
  'simultaneous_derivative_orders', 0:2, ...
  'density_included', true);
end

function [val_rows, nor_rows] = LOCAL_retained_operator_rows( ...
    z, configuration, orders, tau_coeff_map, eta_second_coeff_map, ...
    outer, inner, D1_bound, D2_bound, S1_bound, S2_bound, ...
    A1_bound, A2_bound, C1_bound, C2_bound, build_center)
N = double(configuration.evaluation_node_count);
L = double(configuration.residual_mode_cutoff);
R_circle = double(z.R);
dt = 2.0 * pi / N;
parameter_nodes = (0:N - 1.0).' * dt;
phase = exp(1i * parameter_nodes * orders.');
tau_nodes = phase * tau_coeff_map;
eta_second_nodes = phase * eta_second_coeff_map;
tau_prime_nodes = phase * ((1i * orders) .* tau_coeff_map);
mode_orders = (-(L - 1.0):L - 1.0).';

value_center_rows = complex(zeros(0, size(tau_coeff_map, 2)));
normal_center_rows = complex(zeros(0, size(tau_coeff_map, 2)));
if build_center
h = parameter_nodes - parameter_nodes.';
x = 4.0 * R_circle^2 * sin(h / 2.0).^2;
p_tangent = R_circle^2 * sin(h);
cos_h = cos(h);
log_c = log(R_circle^2);
J_outer = LOCAL_polyval_ascending(outer.J_coefficients, x);
J_inner = LOCAL_polyval_ascending(inner.J_coefficients, x);
Y_outer = LOCAL_polyval_ascending(outer.Y_regular_coefficients, x);
Y_inner = LOCAL_polyval_ascending(inner.Y_regular_coefficients, x);
J_first_outer = LOCAL_polyval_ascending(outer.J_first_coefficients, x);
J_first_inner = LOCAL_polyval_ascending(inner.J_first_coefficients, x);
c_outer = LOCAL_polyval_ascending(outer.c_regular_coefficients, x);
c_inner = LOCAL_polyval_ascending(inner.c_regular_coefficients, x);
q_outer_coefficients = ...
  (-log_c / (4.0 * pi) + outer.c0) * outer.J_coefficients + ...
  outer.Y_regular_coefficients / (2.0 * pi);
q_inner_coefficients = ...
  (-log_c / (4.0 * pi) + inner.c0) * inner.J_coefficients + ...
  inner.Y_regular_coefficients / (2.0 * pi);
q_outer = LOCAL_polyval_ascending(q_outer_coefficients, x);
q_inner = LOCAL_polyval_ascending(q_inner_coefficients, x);

delta_J = J_outer - J_inner;
delta_J_first = J_first_outer - J_first_inner;
W = log_c * delta_J_first / (4.0 * pi) + c_outer - c_inner;
delta_S1 = -R_circle * delta_J / (4.0 * pi);
delta_S2 = R_circle * (q_outer - q_inner);
delta_D1 = x .* delta_J_first / (8.0 * pi);
delta_D2 = x .* W / 2.0;
delta_C1 = p_tangent .* delta_J_first / (4.0 * pi);
delta_C2 = p_tangent .* W;
S_outer1 = -R_circle * J_outer / (4.0 * pi);
S_inner1 = -R_circle * J_inner / (4.0 * pi);
S_outer2 = R_circle * q_outer;
S_inner2 = R_circle * q_inner;
A1 = double(z.khat)^2 * S_outer1 - ...
  (sqrt(double(z.rho_disk)) * double(z.khat))^2 * S_inner1;
A2 = double(z.khat)^2 * S_outer2 - ...
  (sqrt(double(z.rho_disk)) * double(z.khat))^2 * S_inner2;

R_kress = LOCAL_kress_matrix(N);
D_action = R_kress .* delta_D1 + dt * delta_D2;
S_action = R_kress .* delta_S1 + dt * delta_S2;
value_operator_samples = D_action * tau_nodes - ...
  S_action * eta_second_nodes;
A_action = R_kress .* (A1 .* cos_h) + dt * (A2 .* cos_h);
C_action = R_kress .* (delta_C1 / R_circle) + ...
  dt * (delta_C2 / R_circle);
normal_operator_samples = -A_action * tau_nodes - ...
  C_action * tau_prime_nodes + D_action * eta_second_nodes;
value_samples = tau_nodes + value_operator_samples;
normal_samples = -eta_second_nodes + normal_operator_samples;
value_center_rows = LOCAL_parameter_rows( ...
  value_samples, parameter_nodes, mode_orders, R_circle);
normal_center_rows = LOCAL_parameter_rows( ...
  normal_samples, parameter_nodes, mode_orders, R_circle);
end

tau_node_norm = vecnorm(tau_nodes, 2, 2);
eta_second_node_norm = vecnorm(eta_second_nodes, 2, 2);
tau_prime_node_norm = vecnorm(tau_prime_nodes, 2, 2);
value_delta_log = D1_bound.series_tail_value_upper * tau_node_norm + ...
  S1_bound.series_tail_value_upper * eta_second_node_norm;
value_delta_smooth = D2_bound.series_tail_value_upper * tau_node_norm + ...
  S2_bound.series_tail_value_upper * eta_second_node_norm;
normal_delta_log = A1_bound.series_tail_value_upper * tau_node_norm + ...
  C1_bound.series_tail_value_upper / R_circle * tau_prime_node_norm + ...
  D1_bound.series_tail_value_upper * eta_second_node_norm;
normal_delta_smooth = A2_bound.series_tail_value_upper * tau_node_norm + ...
  C2_bound.series_tail_value_upper / R_circle * tau_prime_node_norm + ...
  D2_bound.series_tail_value_upper * eta_second_node_norm;

common = struct( ...
  'mode_orders', mode_orders, ...
  'center_policy', ...
    'identity plus signed retained polynomial Kress operator', ...
  'signed_retained_polynomial_center', true, ...
  'center_rows_built', logical(build_center), ...
  'identity_included_once', true, ...
  'series_delta_tail_only', true, ...
  'source_radius_uses_complete_integrand', true, ...
  'target_radius_uses_complete_action', true, ...
  'telescope_partition', ...
    'exact action to exact Kress to retained-series Kress center', ...
  'series_cutoff', double(configuration.kernel_series_cutoff), ...
  'J_Y_first_omitted_order', ...
    double(configuration.kernel_series_cutoff) + 1.0, ...
  'J_first_shifted_c_first_omitted_order', ...
    double(configuration.kernel_series_cutoff), ...
  'finite_special_function_library_used', false);
val_rows = common;
val_rows.center_rows = value_center_rows;
val_rows.series_delta_log_source_upper = value_delta_log;
val_rows.series_delta_smooth_source_upper = value_delta_smooth;
nor_rows = common;
nor_rows.center_rows = normal_center_rows;
nor_rows.series_delta_log_source_upper = normal_delta_log;
nor_rows.series_delta_smooth_source_upper = normal_delta_smooth;
if any(~isfinite([value_center_rows(:); normal_center_rows(:); ...
    value_delta_log; value_delta_smooth; normal_delta_log; ...
    normal_delta_smooth])) || ...
    any([value_delta_log; value_delta_smooth; normal_delta_log; ...
    normal_delta_smooth] < 0.0)
  error('I51cInput:LocalCenterFinite', ...
    'The signed retained local center or tail-only series radius is invalid.');
end
end

function values = LOCAL_polyval_ascending(coefficients, x)
coefficients = coefficients(:);
values = complex(zeros(size(x)));
for index = numel(coefficients):-1:1
  values = values .* x + coefficients(index);
end
end

function R = LOCAL_kress_matrix(N)
rvec = quad.quad_kress_rvec(N);
offset = mod((0:N - 1.0) - (0:N - 1.0).', N) + 1.0;
R = rvec(offset);
end

function rows = LOCAL_parameter_rows(samples, parameter_nodes, orders, R_circle)
P = 2.0 * pi * R_circle;
phase = exp(-1i * orders * parameter_nodes.');
rows = phase * (samples * (2.0 * pi * R_circle / numel(parameter_nodes))) / ...
  sqrt(P);
end

function geometry = LOCAL_circle_geometry(z, configuration)
R = double(z.R);
P = 2.0 * pi * R;
L = double(configuration.residual_mode_cutoff);
mu_shift = double(z.mu_h);
rho_inner = double(z.rho_disk);
collar_width = double(z.delta_c);
theta = 1.0 - collar_width / R;
Theta = 1.0 + collar_width / R;
if theta <= 0.0
  error('I51cInput:Collar', 'The material collar is not injective.');
end
xi_L = 2.0 * pi * L / P;
trace_tail_slope_lower = sqrt(theta / Theta) * ( ...
  tanh(collar_width * xi_L / sqrt(theta * Theta)) + ...
  tanh(collar_width * xi_L / sqrt(theta * Theta)));
I0 = 13.0 / 35.0;
I1 = 6.0 / 5.0;
cut_minus = 0.5;
cut_plus = -0.5;
