source_node_count = size(z.eta_unit_256, 1) / 2.0;
density_orders = (-source_node_count / 2.0: ...
  source_node_count / 2.0 - 1.0).';
tau_native = double(z.eta_unit_256(1:source_node_count, :));
eta_second_native = double(z.eta_unit_256(source_node_count + 1.0:end, :));
tau_coeff_map = fftshift(fft(tau_native, [], 1), 1) / source_node_count;
eta_second_coeff_map = ...
  fftshift(fft(eta_second_native, [], 1), 1) / source_node_count;
