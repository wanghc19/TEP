function [radius_upper, radius_floor] = LOCAL_candidate_retained_radius( ...
    z, configuration, geometry, local, regular, off_surface)
L = double(configuration.residual_mode_cutoff);
N = double(configuration.evaluation_node_count);
ell = (-(L - 1.0):L - 1.0).';
value_local = LOCAL_candidate_local_radius( ...
  local.derivative.val, local.rows.val, geometry, ell, N);
normal_local = LOCAL_candidate_local_radius( ...
  local.derivative.nor, local.rows.nor, geometry, ell, N);
value_total = value_local + double(regular.value_retained_row_radius) + ...
  double(off_surface.value_target_quadrature_radius(:));
normal_total = normal_local + double(regular.normal_retained_row_radius) + ...
  double(off_surface.normal_target_quadrature_radius(:));
radius_upper = max([value_total; normal_total]);
radius_floor = max([double(regular.value_retained_row_radius), ...
  double(regular.normal_retained_row_radius)]);
if any(~isfinite([radius_upper, radius_floor])) || ...
    any([radius_upper, radius_floor] < 0.0) || ...
    numel(value_total) ~= 2.0 * L - 1.0 || ...
    numel(normal_total) ~= 2.0 * L - 1.0
  error('I51cInput:CandidateRadius', ...
    'A candidate retained-row radius is invalid.');
end
if double(z.R) ~= double(geometry.speed_lower)
  error('I51cInput:CandidateGeometry', ...
    'The circle adapter speed is inconsistent with the frozen radius.');
end
end

function total = LOCAL_candidate_local_radius( ...
    derivative, rows, geometry, ell, N)
p = 2.0;
half = N / 2.0;
harmonic = sum(1.0 ./ (1.0:half - 1.0));
C_K = 2.0 * N^(-p) * (2.0 * harmonic + 2.0 / N) * ...
  (2.0^p + 2.0^(p - 1.0) / (p - 1.0)) + ...
  half^(-p - 1.0) + 2.0 / p * half^(-p);
C_T = 2.0 * N^(-p) * (1.0 + 1.0 / (p - 1.0));
P = double(geometry.boundary_length);
s_upper = double(geometry.speed_upper);
source_L1 = double(derivative.source_L1_p(:).');
source = 2.0 * pi * s_upper / sqrt(P) * ...
  (source_L1(1) * C_K + source_L1(2) * C_T);
H_q = double(derivative.H_q(:).');
xi = 2.0 * pi * ell / P;
Psi_second = double(geometry.speed_second_upper) * H_q(1) + ...
  2.0 * double(geometry.speed_first_upper) * H_q(2) + ...
  s_upper * H_q(3) + ...
  abs(xi) .* (3.0 * s_upper * ...
  double(geometry.speed_first_upper) * H_q(1) + ...
  2.0 * s_upper^2 * H_q(2)) + xi.^2 * s_upper^3 * H_q(1);
target_KR19 = 4.0 * pi * (pi^2 / 6.0) / (sqrt(P) * N^2) * ...
  Psi_second;
target_alias = LOCAL_constant_speed_alias_radius( ...
  derivative, geometry, ell, N);
target = min(target_KR19, target_alias);
series = LOCAL_candidate_series_radius(rows, geometry, N);
total = source + target + series;
end

function [radius, certificate] = LOCAL_constant_speed_alias_radius( ...
    derivative, geometry, ell, N)
alias_cutoff = 64.0;
ell = double(ell(:));
a = abs(ell);
if ~geometry.constant_speed_parameterization || ...
    any(~isfinite([double(derivative.Q2); a; N])) || ...
    double(derivative.Q2) < 0.0 || N <= 0.0 || ...
    any(a >= N / 2.0)
  error('I51cInput:ConstantSpeedAliasGate', ...
    'The constant-speed DFT alias assumptions failed.');
end
retained_sum = zeros(size(a));
for q = 1:alias_cutoff
  retained_sum = retained_sum + ...
    1.0 ./ (q * N + a).^2 + 1.0 ./ (q * N - a).^2;
end
q0 = alias_cutoff + 1.0;
tail_plus = 1.0 ./ (q0 * N + a).^2 + ...
  1.0 ./ (N * (q0 * N + a));
tail_minus = 1.0 ./ (q0 * N - a).^2 + ...
  1.0 ./ (N * (q0 * N - a));
tail_upper = tail_plus + tail_minus;
alias_sum_upper = retained_sum + tail_upper;
P = double(geometry.boundary_length);
radius = double(derivative.Q2) * P^(3.0 / 2.0) / ...
  (4.0 * pi^2) * alias_sum_upper;
gate = all(isfinite([retained_sum; tail_upper; radius])) && ...
  all([retained_sum; tail_upper; radius] >= 0.0) && ...
  all(a < N / 2.0) && geometry.constant_speed_parameterization;
if ~gate
  error('I51cInput:ConstantSpeedAliasFinite', ...
    'The constant-speed DFT alias enclosure is invalid.');
end
certificate = struct( ...
  'alias_cutoff', alias_cutoff, ...
  'first_omitted_alias_index', q0, ...
  'retained_two_sided_sum', retained_sum, ...
  'tail_plus_upper', tail_plus, ...
  'tail_minus_upper', tail_minus, ...
  'tail_upper', tail_upper, ...
  'alias_sum_upper', alias_sum_upper, ...
  'gate', gate);
end

function radius = LOCAL_candidate_series_radius(rows, geometry, N)
delta_log = double(rows.series_delta_log_source_upper(:));
delta_smooth = double(rows.series_delta_smooth_source_upper(:));
if numel(delta_log) ~= N || numel(delta_smooth) ~= N || ...
    any(~isfinite([delta_log; delta_smooth])) || ...
    any([delta_log; delta_smooth] < 0.0)
  error('I51cInput:CandidateSeriesDelta', ...
    'A tail-only source-node series delta is invalid.');
end
rvec = quad.quad_kress_rvec(N);
offset = mod((0:N - 1.0) - (0:N - 1.0).', N) + 1.0;
error_by_target = abs(rvec(offset)) * delta_log + ...
  (2.0 * pi / N) * sum(delta_smooth);
radius = 2.0 * pi / (N * sqrt(double(geometry.boundary_length))) * ...
  sum(double(geometry.speed_nodes(:)) .* error_by_target);
end

function out = LOCAL_block_certificate(Pmatrix, block_length)
Pmatrix = double(Pmatrix);
power = eye(size(Pmatrix));
prefix = 0.0;
for index = 0:block_length - 1.0
  prefix = prefix + norm(power, 'fro')^2;
  power = Pmatrix * power;
end
block_norm_upper = norm(power, 'fro');
pass = block_norm_upper < 1.0 && isfinite(prefix);
if pass
  sum_power_squared_upper = prefix / (1.0 - block_norm_upper^2);
else
  sum_power_squared_upper = Inf;
end
out = struct( ...
  'block_length', block_length, ...
  'matrix_norm', 'Frobenius upper bound for spectral 2-norm', ...
  'block_norm_upper', block_norm_upper, ...
  'prefix_sum_upper', prefix, ...
  'sum_power_squared_upper', sum_power_squared_upper, ...
  'pass', pass);
end

function out = LOCAL_select_residual_cutoff( ...
    z, configuration, derivative, geometry, regular, off_surface, pm, pp)
candidates = [32.0, 64.0, 128.0, 256.0];
P = geometry.boundary_length;
R = double(z.R);
theta = 1.0 - double(z.delta_c) / R;
Theta = 1.0 + double(z.delta_c) / R;
C0 = geometry.tubular_C0;
C1 = geometry.tubular_C1;
state_sum = norm(double(z.q_center), 2)^2 + ...
  norm(double(z.Gminus), 'fro')^2 * pm.sum_power_squared_upper * ...
    norm(double(z.cminus), 2)^2 + ...
  norm(double(z.Gplus), 'fro')^2 * pp.sum_power_squared_upper * ...
    norm(double(z.cplus), 2)^2;
material_tail = Inf(size(candidates));
lifting_tail = Inf(size(candidates));
local_material = Inf(size(candidates));
local_lifting = Inf(size(candidates));
regular_material = Inf(size(candidates));
regular_lifting = Inf(size(candidates));
off_material = Inf(size(candidates));
off_lifting = Inf(size(candidates));
strip_ratio = exp(-4.0 * pi * geometry.arclength_strip_width / P);
for index = 1:numel(candidates)
  L = candidates(index);
  xi_L = 2.0 * pi * L / P;
  c_trace = sqrt(theta / Theta) * ( ...
    tanh(double(z.delta_c) * xi_L / sqrt(theta * Theta)) + ...
    tanh(double(z.delta_c) * xi_L / sqrt(theta * Theta)));
  local_material(index) = 2.0 * derivative.nor.Q2^2 / ...
    (P * c_trace) * (P / (2.0 * pi))^5 * ...
    (L^(-5.0) + L^(-4.0) / 4.0);
  local_lifting(index) = 2.0 * derivative.val.Q2^2 / P * ( ...
    C0 * (P / (2.0 * pi))^4 * ...
      (L^(-4.0) + L^(-3.0) / 3.0) + ...
    C1 * (P / (2.0 * pi))^2 * ...
      (L^(-2.0) + L^(-1.0)));
  d_scaled = double(z.delta_c) / sqrt(theta * Theta);
  trace_denominator = 2.0 * sqrt(theta / Theta) * ...
    tanh(xi_L * d_scaled);
  regular_material(index) = LOCAL_analytic_material_tail( ...
    regular.normal_strip_upper, P, trace_denominator, strip_ratio, L);
  off_material(index) = LOCAL_analytic_material_tail( ...
    off_surface.normal_strip_upper, P, trace_denominator, strip_ratio, L);
  regular_lifting(index) = LOCAL_analytic_lifting_tail( ...
    regular.value_strip_upper, P, C0, C1, strip_ratio, L);
  off_lifting(index) = LOCAL_analytic_lifting_tail( ...
    off_surface.value_strip_upper, P, C0, C1, strip_ratio, L);
  material_tail(index) = state_sum * (sqrt(local_material(index)) + ...
    sqrt(regular_material(index)) + sqrt(off_material(index)))^2;
  lifting_tail(index) = state_sum * (sqrt(local_lifting(index)) + ...
    sqrt(regular_lifting(index)) + sqrt(off_lifting(index)))^2;
end
passes = sqrt(material_tail) <= configuration.material_tail_tolerance & ...
  2.0 * sqrt(lifting_tail) <= configuration.lifting_tail_tolerance;
selected_index = find(passes, 1, 'first');
if isempty(selected_index)
  selected_L = candidates(end);
else
  selected_L = candidates(selected_index);
end
out = struct( ...
  'candidate_L', candidates, ...
  'material_tail_squared', material_tail, ...
  'lifting_tail_squared', lifting_tail, ...
  'local_material_squared', local_material, ...
  'regular_material_squared', regular_material, ...
  'off_surface_material_squared', off_material, ...
  'local_lifting_squared', local_lifting, ...
  'regular_lifting_squared', regular_lifting, ...
  'off_surface_lifting_squared', off_lifting, ...
  'state_sum_upper', state_sum, ...
  'selected_L', selected_L, ...
  'first_passing_candidate_index', selected_index, ...
  'tail_tolerance_pass', ~isempty(selected_index), ...
  'stopping_rule', ...
    'first candidate passing complete local+regular+off angular tails', ...
  'pass', all(isfinite([material_tail, lifting_tail])));
end

function squared = LOCAL_analytic_material_tail(A, P, denominator, r, L)
squared = P^2 * A^2 / (pi * denominator) * ...
  r^L / (L * (1.0 - r));
end

function squared = LOCAL_analytic_lifting_tail(A, P, C0, C1, r, L)
S0 = r^L / (1.0 - r);
S2 = r^L * (L^2 / (1.0 - r) + ...
  2.0 * L * r / (1.0 - r)^2 + ...
  r * (1.0 + r) / (1.0 - r)^3);
squared = 2.0 * P * A^2 * ( ...
  C0 * S0 + C1 * (2.0 * pi / P)^2 * S2);
end

function weights = LOCAL_material_weights(z, geometry, L)
ell = (-(L - 1.0):L - 1.0).';
P = geometry.boundary_length;
xi = 2.0 * pi * ell / P;
R = double(z.R);
h = double(z.delta_c);
theta = 1.0 - h / R;
Theta = 1.0 + h / R;
lambda_inner = sqrt(double(z.mu_h) * double(z.rho_disk) + ...
  xi.^2 / (theta * Theta));
lambda_outer = sqrt(double(z.mu_h) + xi.^2 / (theta * Theta));
trace = theta * lambda_inner .* tanh(h * lambda_inner) + ...
  theta * lambda_outer .* tanh(h * lambda_outer);
lifting = geometry.tubular_C0 + geometry.tubular_C1 * xi.^2;
if theta <= 0.0 || any(trace <= 0.0) || any(lifting <= 0.0)
  error('I51cInput:MaterialWeight', ...
    'A trace or tubular retained weight is nonpositive.');
end
weights = struct( ...
  'mode_orders', ell, ...
  'trace', trace, ...
  'material_inverse_trace', 1.0 ./ trace, ...
  'lifting', lifting);
end

