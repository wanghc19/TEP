    local.rows.val.source_radius_uses_complete_integrand && ...
    local.rows.nor.source_radius_uses_complete_integrand && ...
    local.rows.val.target_radius_uses_complete_action && ...
    local.rows.nor.target_radius_uses_complete_action && ...
    local.rows.val.series_delta_tail_only && ...
    local.rows.nor.series_delta_tail_only, ...
  'identity_included_once', identity_count, ...
