    local.rows.nor.J_Y_first_omitted_order == local.series.cutoff + 1.0 && ...
    local.rows.val.J_first_shifted_c_first_omitted_order == ...
      local.series.cutoff && ...
    local.rows.nor.J_first_shifted_c_first_omitted_order == ...
