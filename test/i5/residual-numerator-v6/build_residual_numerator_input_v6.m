%% ==================== Geometry and trace/lift data ====================
% The circle supplies an exact certificate for a shape-general interface.

function g = LOCAL_circle_geometry(z, c)
R = double(z.R);
N = double(c.evaluation_node_count);
a = double(c.parameter_strip_width);
t = (0:N - 1).' * (2 * pi / N);
[contour, period] = geom.construct_cont(N, 'circle', 0, 0, R);
if ~isequal(period, 2 * pi) || ~isequal(size(contour), [6, N])
  error('I5v6Input:Geometry', 'The geometry adapter returned wrong shape.');
end
position = [double(contour(1, :).'), double(contour(4, :).')];
derivative = [double(contour(2, :).'), double(contour(5, :).')];
speed = vecnorm(derivative, 2, 2);
normal = [derivative(:, 2), -derivative(:, 1)] ./ speed;
P = 2 * pi * R;
h = double(z.delta_c);
theta = 1 - h / R;
Theta = 1 + h / R;
if theta <= 0
  error('I5v6Input:Collar', 'The material collar exceeds the reach.');
end
xiL = 2 * pi * double(c.residual_mode_cutoff) / P;
trace_slope = 2 * sqrt(theta / Theta) * ...
  tanh(h * xiL / sqrt(theta * Theta));
position_abs = R * cosh(a);
position_imag = R * sinh(a);
material_plus = LOCAL_collar_side('material-plus-exterior', h, 1, R);
material_minus = LOCAL_collar_side( ...
  'material-minus-interior', h, double(z.rho_disk), R);
wall_plus = LOCAL_flat_collar_side( ...
  'wall-plus-neighbour-side', double(z.delta_w), 1);
wall_minus = LOCAL_flat_collar_side( ...
  'wall-minus-central-side', double(z.delta_w), 1);
real_left_clearance = abs(double(z.X_L)) - R;
real_right_clearance = abs(double(z.X_R)) - R;
material_wall_disjoint = h + double(z.delta_w) <= ...
  min(real_left_clearance, real_right_clearance);
material_cell_copy_disjoint = 2 * (R + h) <= double(z.L);
material_transverse_copy_disjoint = 2 * (R + h) <= double(z.d);
wall_pair_disjoint = 2 * double(z.delta_w) <= double(z.L);
lift_interfaces = {'material-interface','left-wall','right-wall'};
lift_geometry_gates = struct( ...
  'material_sides_stored_separately', ...
    ~strcmp(material_plus.label, material_minus.label) && ...
    isequal(material_plus.rho_upper, 1) && ...
    isequal(material_minus.rho_upper, double(z.rho_disk)), ...
  'wall_sides_stored_separately', ...
    ~strcmp(wall_plus.label, wall_minus.label), ...
  'material_collars_injective', material_plus.pass && material_minus.pass, ...
  'wall_collars_injective', wall_plus.pass && wall_minus.pass, ...
  'material_wall_disjoint', material_wall_disjoint, ...
  'material_cell_copies_disjoint', material_cell_copy_disjoint, ...
  'material_transverse_periodic_copies_disjoint', ...
    material_transverse_copy_disjoint, ...
  'wall_pair_disjoint', wall_pair_disjoint, ...
  'all_collars_disjoint', material_wall_disjoint && ...
    material_cell_copy_disjoint && material_transverse_copy_disjoint && ...
    wall_pair_disjoint, ...
  'all_rims_zero', material_plus.zero_rim && material_minus.zero_rim && ...
    wall_plus.zero_rim && wall_minus.zero_rim, ...
  'simultaneous_jump_label_list_complete', ...
    numel(lift_interfaces)==3 && ...
    numel(unique(lift_interfaces))==3 && ...
    sum(strcmp(lift_interfaces,'material-interface'))==1 && ...
    sum(contains(lift_interfaces,'wall'))==2, ...
  'simultaneous_jump_labels', {lift_interfaces}, ...
  'jump_correction_sign', 'J_all e = -a', ...
  'broken_energy_direct_sum', material_wall_disjoint && ...
    material_cell_copy_disjoint && material_transverse_copy_disjoint && ...
    wall_pair_disjoint);
g = struct( ...
  'boundary_length', P, 'speed_lower', R, 'speed_upper', R, ...
  'mu_shift', double(z.mu_h), ...
  'speed_first_upper', 0, 'speed_second_upper', 0, ...
  'constant_speed_parameterization', true, ...
  'parameter_nodes', t, 'arclength_nodes', R * t, ...
  'position', position, 'normal', normal, 'speed_nodes', speed, ...
  'reach_lower', R, 'curvature_upper', 1 / R, ...
  'material_lift_collars', struct('plus', material_plus, ...
    'minus', material_minus), ...
  'wall_lift_collars', struct('plus', wall_plus, 'minus', wall_minus), ...
  'lift_geometry_gates', lift_geometry_gates, ...
  'trace_tail_slope_lower', trace_slope, ...
  'parameter_strip_width', a, 'arclength_strip_width', R * a, ...
  'strip_speed_upper', R, 'strip_position_abs_upper', position_abs, ...
  'strip_position_imag_upper', position_imag, ...
  'real_displacement_abs_upper', [2 * R, 2 * R], ...
  'displacement_abs_upper', [2 * position_abs, 2 * position_abs], ...
  'displacement_real_upper', [2 * position_abs, 2 * position_abs], ...
  'displacement_imag_upper', [2 * position_imag, 2 * position_imag], ...
  'target_normal_component_upper', cosh(a) * [1, 1], ...
  'source_normal_component_upper', cosh(a) * [1, 1], ...
  'left_clearance_lower', abs(double(z.X_L)) - R, ...
  'right_clearance_lower', abs(double(z.X_R)) - R, ...
  'strip_left_clearance_lower', abs(double(z.X_L)) - position_abs, ...
  'strip_right_clearance_lower', abs(double(z.X_R)) - position_abs, ...
  'strip_certificate_pass', abs(double(z.X_L)) > position_abs && ...
    abs(double(z.X_R)) > position_abs, ...
  'source_strip_certificate_pass', abs(double(z.X_L)) > position_abs && ...
    abs(double(z.X_R)) > position_abs, ...
  'target_strip_certificate_pass', abs(double(z.X_L)) > position_abs && ...
    abs(double(z.X_R)) > position_abs, ...
  'strip_domain_contract', ...
    'separate target-real/source-strip and target-strip/source-real domains', ...
  'outward_normal_contract_pass', all(sum(position .* normal, 2) > 0), ...
  'parameter_grid_contract_pass', isequal(t, (0:N - 1).' * (2 * pi / N)), ...
  'certificate_authority', ...
    'circle geometry adapter; governing theorem shape general');
end

function side = LOCAL_collar_side(label, width, rho_upper, radius)
kappa_upper = 1 / radius;
theta = 1 - width * kappa_upper;
Theta = 1 + width * kappa_upper;
pass = width > 0 && rho_upper > 0 && theta > 0 && ...
  all(isfinite([width, rho_upper, kappa_upper, theta, Theta]));
side = struct('label', label, 'width', width, 'rho_upper', rho_upper, ...
  'curvature_upper', kappa_upper, 'theta_lower', theta, ...
  'Theta_upper', Theta, 'zero_rim', pass, ...
  'profile', 'sinh(alpha*(h-t))/sinh(alpha*h)', 'pass', pass);
end

function side = LOCAL_flat_collar_side(label, width, rho_upper)
pass = width > 0 && rho_upper > 0 && isfinite(width) && isfinite(rho_upper);
side = struct('label', label, 'width', width, 'rho_upper', rho_upper, ...
  'curvature_upper', 0, 'theta_lower', 1, 'Theta_upper', 1, ...
  'zero_rim', pass, 'profile', ...
  'sinh(lambda*(h-t))/sinh(lambda*h)', 'pass', pass);
end

function w = LOCAL_material_weights(z, g, L)
ell = (-(L - 1):L - 1).';
xi = 2 * pi * ell / g.boundary_length;
R = double(z.R);
h = double(z.delta_c);
theta = 1 - h / R;
Theta = 1 + h / R;
li = sqrt(double(z.mu_h) * double(z.rho_disk) + xi.^2 / (theta * Theta));
le = sqrt(double(z.mu_h) + xi.^2 / (theta * Theta));
trace = theta * li .* tanh(h * li) + theta * le .* tanh(h * le);
plus = g.material_lift_collars.plus;
minus = g.material_lift_collars.minus;
[kappa_plus, plus_pass] = LOCAL_collar_mode_cost( ...
  plus, double(z.mu_h), xi);
[kappa_minus, minus_pass] = LOCAL_collar_mode_cost( ...
  minus, double(z.mu_h), xi);
lift = kappa_plus .* kappa_minus ./ (kappa_plus + kappa_minus);
if any(~isfinite([trace; lift])) || any([trace; lift] <= 0)
  error('I5v6Input:Weights', 'A material trace/lift weight is invalid.');
end
w = struct('mode_orders', ell, 'trace', trace, ...
  'normal_inverse_trace', 1 ./ trace, 'lifting', lift, ...
  'minimum_energy', struct('kappa_plus', kappa_plus, ...
    'kappa_minus', kappa_minus, 'harmonic_weight', lift, ...
    'side_plus', plus, 'side_minus', minus), ...
  'gates', struct('plus_side', plus_pass, 'minus_side', minus_pass, ...
    'harmonic_formula', isequal(lift, ...
      kappa_plus .* kappa_minus ./ (kappa_plus + kappa_minus)), ...
    'positive_finite', isreal(lift) && all(isfinite(lift)) && ...
      all(lift > 0), ...
    'pass', plus_pass && minus_pass && isreal(lift) && ...
      all(isfinite(lift)) && all(lift > 0)));
end

function [kappa, pass] = LOCAL_collar_mode_cost(side, mu, xi)
A = double(side.Theta_upper);
B = xi.^2 / double(side.theta_lower) + ...
  mu * double(side.rho_upper) * double(side.Theta_upper);
alpha = sqrt(B / A);
kappa = sqrt(A * B) ./ tanh(double(side.width) * alpha);
zero = B == 0;
kappa(zero) = A / double(side.width);
pass = side.pass && mu > 0 && isreal(B) && all(isfinite(B)) && ...
  all(B >= 0) && isreal(kappa) && all(isfinite(kappa)) && all(kappa > 0);
end

%% ==================== Analytic cutoff and evaluation selection ====================
% Selection uses only proved remainders and never observed centre drift.

function out = LOCAL_select_L(z, g, c, local, regular, off, propagation)
schedule = double(c.L_schedule(:).');
state_sum = LOCAL_state_energy(z, propagation, 0);
normal_sq = NaN(size(schedule));
lifting_sq = NaN(size(schedule));
candidate_trace_slope = NaN(size(schedule));
for j = 1:numel(schedule)
  L = schedule(j);
  trace_slope = LOCAL_trace_slope(z, g, L);
  candidate_trace_slope(j) = trace_slope;
  local_high = LOCAL_local_high_at( ...
    local.derivative_certificate, g, L, trace_slope);
  regular_high = LOCAL_strip_high(regular, g, L, trace_slope);
  off_high = LOCAL_strip_high(off, g, L, trace_slope);
  normal_sq(j) = state_sum * (sqrt(local_high.nor) + ...
    sqrt(regular_high.nor) + sqrt(off_high.nor))^2;
  lifting_sq(j) = state_sum * (sqrt(local_high.val) + ...
    sqrt(regular_high.val) + sqrt(off_high.val))^2;
end
contribution = sqrt(normal_sq) + sqrt(lifting_sq);
first = find(contribution <= c.high_mode_allocation, 1, 'first');
if isempty(first)
  selected = numel(schedule);
  reason = 'largest predeclared finite L; tightness allocation failed';
else
  selected = first;
  reason = 'first complete propagated high-tail allocation pass';
end
analytic_gate = local.gates.p4_factor_ratio && ...
  local.gates.p4_source_certificate && local.gates.p4_target_alias && ...
  local.gates.series_delta_tail_only && regular.gates.pass && off.gates.pass;
out = struct('candidate_L', schedule, 'normal_squared', normal_sq, ...
  'lifting_squared', lifting_sq, 'numerator_contribution', contribution, ...
  'candidate_trace_slope', candidate_trace_slope, ...
  'allocation', c.high_mode_allocation, 'selected_index', selected, ...
  'selected_L', schedule(selected), 'tightness_pass', ~isempty(first), ...
  'selection_reason', reason, 'center_drift_used', false, ...
  'analytic_gate', analytic_gate, ...
  'pass', analytic_gate && all(isfinite([normal_sq, lifting_sq, ...
    contribution, candidate_trace_slope])) && all(candidate_trace_slope > 0));
if ~out.pass
  error('I5v6Input:LCertificate', 'The analytic L selection gate failed.');
end
end

function out = LOCAL_select_N(z, c, density, propagation)
L = double(c.residual_mode_cutoff);
base = 2 * max(L, density.maximum_order) + 2;
schedule = unique([base, c.N_cap_schedule(c.N_cap_schedule >= base)]);
if isempty(schedule)
  error('I5v6Input:NSchedule', 'No strict N candidate is available.');
end
normal_sq = NaN(size(schedule));
lifting_sq = NaN(size(schedule));
maximum_radius = NaN(size(schedule));
local_sf_ledger = cell(size(schedule));
candidate_gate = false(size(schedule));
state_sum = LOCAL_state_energy(z, propagation, 0);
for j = 1:numel(schedule)
  trial = c;
  trial.evaluation_node_count = schedule(j);
  trial.evaluate_centers = false;
  g = LOCAL_circle_geometry(z, trial);
  local = signed_local_center_v6(z, g, trial, density);
  local_sf_ledger{j} = local.sf_ledger;
  candidate_gate(j) = local.gates.p4_factor_ratio && ...
    local.gates.p4_source_certificate && local.gates.p4_target_alias && ...
    local.gates.series_delta_tail_only;
  rn = double(local.radius.nor.total(:));
  rv = double(local.radius.val.total(:));
  w = LOCAL_material_weights(z, g, L);
  normal_sq(j) = state_sum * sum(w.normal_inverse_trace .* rn.^2);
  lifting_sq(j) = state_sum * sum(w.lifting .* rv.^2);
  maximum_radius(j) = max([rn; rv]);
end
contribution = sqrt(normal_sq) + sqrt(lifting_sq);
first = find(contribution <= c.retained_local_allocation, 1, 'first');
if isempty(first)
  selected = numel(schedule);
  reason = 'largest predeclared N; retained analytic allocation failed';
else
  selected = first;
  reason = 'first propagated p4 source-target-series allocation pass';
end
out = struct('candidate_N', schedule, 'normal_squared', normal_sq, ...
  'lifting_squared', lifting_sq, 'numerator_contribution', contribution, ...
  'maximum_unit_row_radius', maximum_radius, ...
  'candidate_analytic_gate', candidate_gate, ...
  'allocation', c.retained_local_allocation, 'selected_index', selected, ...
  'selected_N', schedule(selected), 'tightness_pass', ~isempty(first), ...
  'selection_reason', reason, 'inter_level_drift_used', false, ...
  'local_preselection_sf_ledgers', {local_sf_ledger}, ...
  'pass', all(candidate_gate) && ...
    all(isfinite([normal_sq, lifting_sq, contribution])));
if ~out.pass
  error('I5v6Input:NCertificate', 'The analytic N selection gate failed.');
end
end

function high = LOCAL_local_high_at(certificate, g, L, trace_slope)
P = g.boundary_length;
tail_weight = LOCAL_material_tail_weight(g);
C0 = tail_weight.W0;
C1 = tail_weight.W1;
n2 = 2 * certificate.nor.Q2^2 / (P * trace_slope) * ...
  (P / (2 * pi))^5 * (L^(-5) + L^(-4) / 4);
v4 = 2 * certificate.val.Q4^2 / P * (C0 * (P / (2 * pi))^8 * ...
  (L^(-8) + L^(-7) / 7) + C1 * (P / (2 * pi))^7 * ...
  (L^(-7) + L^(-6) / 6));
n4 = 2 * certificate.nor.Q4^2 / (P * trace_slope) * ...
  (P / (2 * pi))^9 * (L^(-9) + L^(-8) / 8);
high = struct('val', v4, 'nor', min(n2, n4), ...
  'value_owner', 'I5.1g-9 local p4 under affine harmonic weight', ...
  'normal_owner', 'unchanged minimum of established p2 and p4 tails');
end

function out = LOCAL_material_tail_weight(g)
plus = g.material_lift_collars.plus;
minus = g.material_lift_collars.minus;
C0_plus = plus.Theta_upper / plus.width + plus.Theta_upper * ...
  sqrt(g.mu_shift * plus.rho_upper);
C0_minus = minus.Theta_upper / minus.width + minus.Theta_upper * ...
  sqrt(g.mu_shift * minus.rho_upper);
C1_plus = sqrt(plus.Theta_upper / plus.theta_lower);
C1_minus = sqrt(minus.Theta_upper / minus.theta_lower);
out = struct('C0_plus', C0_plus, 'C0_minus', C0_minus, ...
  'C1_plus', C1_plus, 'C1_minus', C1_minus, ...
  'W0', (C0_plus + C0_minus) / 4, ...
  'W1', (C1_plus + C1_minus) / 4);
end

function ctr = LOCAL_trace_slope(z, g, L)
R = double(z.R);
h = double(z.delta_c);
theta = 1 - h / R;
Theta = 1 + h / R;
xiL = 2 * pi * L / g.boundary_length;
ctr = 2 * sqrt(theta / Theta) * tanh(h * xiL / sqrt(theta * Theta));
end

function high = LOCAL_strip_high(certificate, g, L, trace_slope)
P = g.boundary_length;
r = exp(-4 * pi * g.arclength_strip_width / P);
normal_A = double(certificate.normal_strip_upper);
value_A = double(certificate.value_strip_upper);
S0 = r^L / (1 - r);
S1 = r^L * (L / (1 - r) + r / (1 - r)^2);
high.nor = P^2 * normal_A^2 / (pi * trace_slope) * ...
  r^L / (L * (1 - r));
tail_weight = LOCAL_material_tail_weight(g);
high.val = 2 * P * value_A^2 * (tail_weight.W0 * S0 + ...
  tail_weight.W1 * (2 * pi / P) * S1);
high.lifting_weight_owner = tail_weight;
high.index_owner = '|ell|>=L';
end

function energy = LOCAL_state_energy(z, propagation, start_cell)
cm = double(z.cminus(:));
cp = double(z.cplus(:));
for j = 1:start_cell
  cm = double(z.Pminus) * cm;
  cp = double(z.Pplus) * cp;
end
energy = norm(double(z.q_center), 2)^2 + ...
  norm(double(z.Gminus), 'fro')^2 * ...
    propagation.minus.sum_power_squared_upper * norm(cm, 2)^2 + ...
  norm(double(z.Gplus), 'fro')^2 * ...
    propagation.plus.sum_power_squared_upper * norm(cp, 2)^2;
end

function out = LOCAL_block_certificate(P, block_length)
P = double(P);
power = eye(size(P));
prefix = 0;
for j = 0:block_length - 1
  prefix = prefix + norm(power, 'fro')^2;
  power = P * power;
end
block = norm(power, 'fro');
pass = isfinite(block) && block < 1 && isfinite(prefix);
if pass
  total = prefix / (1 - block^2);
else
  total = Inf;
end
out = struct('block_length', block_length, 'block_norm_upper', block, ...
  'prefix_sum_upper', prefix, 'sum_power_squared_upper', total, 'pass', pass);
end

%% ==================== Signed material assembly ====================
% One physical centre and one triangle radius are weighted exactly once.

function out = LOCAL_material_assembly( ...
    z, geometry, c, w, local, regular, off, propagation)
ell = w.mode_orders;
if ~isequal(local.mode_orders, ell, regular.mode_orders, ell, off.mode_orders, ell)
  error('I5v6Input:ModeOrder', 'Material retained row orders differ.');
end
if ~local.centers_evaluated || ~regular.gates.centers_evaluated || ...
    ~off.gates.centers_evaluated
  error('I5v6Input:Centers', 'A final retained centre was not evaluated.');
end
center_val = double(local.center.val) + double(regular.raw_center.val) + ...
  double(off.raw_center.val);
center_nor = double(local.center.nor) - double(regular.raw_center.nor) - ...
  double(off.raw_center.nor);
radius_val = double(local.radius.val.total(:)) + ...
  double(regular.radius.val.total(:)) + double(off.radius.val.total(:));
radius_nor = double(local.radius.nor.total(:)) + ...
  double(regular.radius.nor.total(:)) + double(off.radius.nor.total(:));
[states, labels, tail_states] = LOCAL_states(z, c.cell_cutoff);
finite_normal = 0;
finite_lifting = 0;
center_normal = 0;
center_lifting = 0;
radius_normal = 0;
radius_lifting = 0;
triangle_center_normal = 0;
triangle_center_lifting = 0;
for j = 1:numel(states)
  state = states{j};
  state_norm = norm(state, 2);
  cn = center_nor * state;
  cv = center_val * state;
  rn = radius_nor * state_norm;
  rv = radius_val * state_norm;
  triangle_nor = abs(double(local.center.nor) * state) + ...
    abs(double(regular.raw_center.nor) * state) + ...
    abs(double(off.raw_center.nor) * state);
  triangle_val = abs(double(local.center.val) * state) + ...
    abs(double(regular.raw_center.val) * state) + ...
    abs(double(off.raw_center.val) * state);
  finite_normal = finite_normal + sum(w.normal_inverse_trace .* (abs(cn) + rn).^2);
  finite_lifting = finite_lifting + sum(w.lifting .* (abs(cv) + rv).^2);
  center_normal = center_normal + sum(w.normal_inverse_trace .* abs(cn).^2);
  center_lifting = center_lifting + sum(w.lifting .* abs(cv).^2);
  radius_normal = radius_normal + sum(w.normal_inverse_trace .* rn.^2);
  radius_lifting = radius_lifting + sum(w.lifting .* rv.^2);
  triangle_center_normal = triangle_center_normal + ...
    sum(w.normal_inverse_trace .* triangle_nor.^2);
  triangle_center_lifting = triangle_center_lifting + ...
    sum(w.lifting .* triangle_val.^2);
end
[cell_normal, cell_lifting, cell_ledger] = LOCAL_cell_tail( ...
  z, w, center_nor, center_val, radius_nor, radius_val, ...
  propagation, tail_states);
state_sum = LOCAL_state_energy(z, propagation, 0);
local_high = LOCAL_local_high_at(local.derivative_certificate, geometry, ...
  c.residual_mode_cutoff, geometry.trace_tail_slope_lower);
reg_high = LOCAL_strip_high(regular, geometry, ...
  c.residual_mode_cutoff, geometry.trace_tail_slope_lower);
off_high = LOCAL_strip_high(off, geometry, ...
  c.residual_mode_cutoff, geometry.trace_tail_slope_lower);
high_normal = state_sum * (sqrt(local_high.nor) + ...
  sqrt(reg_high.nor) + sqrt(off_high.nor))^2;
high_lifting = state_sum * (sqrt(local_high.val) + ...
  sqrt(reg_high.val) + sqrt(off_high.val))^2;
all_values = [center_val(:); center_nor(:); radius_val; radius_nor; ...
  finite_normal; finite_lifting; cell_normal; cell_lifting; ...
  high_normal; high_lifting];
retained_index_pass = isequal(ell, (-(c.residual_mode_cutoff-1): ...
  c.residual_mode_cutoff-1).') && all(abs(ell)<c.residual_mode_cutoff);
retained_state_owner_pass = numel(labels)==1+2*c.cell_cutoff && ...
  numel(unique(labels))==1+2*c.cell_cutoff;
cell_owner_pass = numel(cell_ledger)==2 && ...
  all(strcmp({cell_ledger.side},{'minus','plus'}));
high_owner_pass = strcmp(local_high.value_owner, ...
  'I5.1g-9 local p4 under affine harmonic weight') && ...
  strcmp(reg_high.index_owner,'|ell|>=L') && ...
  strcmp(off_high.index_owner,'|ell|>=L');
tail_ownership_pass = retained_index_pass && cell_owner_pass && high_owner_pass;
actual_jump_owner_complete = retained_index_pass && retained_state_owner_pass && ...
  cell_owner_pass && high_owner_pass;
out = struct( ...
  'mode_orders', ell, ...
  'physical_center', struct('val', center_val, 'nor', center_nor), ...
  'analytic_radius', struct('val', radius_val, 'nor', radius_nor), ...
  'finite', struct('normal_squared', finite_normal, ...
    'lifting_squared', finite_lifting, ...
    'center_normal_squared', center_normal, ...
    'center_lifting_squared', center_lifting, ...
    'radius_normal_squared', radius_normal, ...
    'radius_lifting_squared', radius_lifting, ...
    'triangle_center_normal_squared', triangle_center_normal, ...
    'triangle_center_lifting_squared', triangle_center_lifting, ...
    'normal_cancellation_ratio', sqrt(center_normal / ...
      max(realmin, triangle_center_normal)), ...
    'lifting_cancellation_ratio', sqrt(center_lifting / ...
      max(realmin, triangle_center_lifting)), ...
    'state_labels', {labels}), ...
  'cell_tail', struct('normal_squared', cell_normal, ...
    'lifting_squared', cell_lifting, 'ledger', cell_ledger), ...
  'high_tail', struct('normal_squared', high_normal, ...
    'lifting_squared', high_lifting, ...
    'local', local_high, 'regular', reg_high, 'off_surface', off_high), ...
  'gates', struct('value_sign', isequal(center_val, ...
      double(local.center.val) + double(regular.raw_center.val) + ...
      double(off.raw_center.val)), ...
    'normal_sign', isequal(center_nor, double(local.center.nor) - ...
      double(regular.raw_center.nor) - double(off.raw_center.nor)), ...
    'all_centers_evaluated', ~isempty(local.center.val) && ...
      ~isempty(regular.raw_center.val) && ~isempty(off.raw_center.val), ...
    'high_trace_slope_match', isequal(geometry.trace_tail_slope_lower, ...
      LOCAL_trace_slope(z, geometry, c.residual_mode_cutoff)), ...
    'tail_ownership_disjoint', tail_ownership_pass, ...
    'actual_jump_owner_complete', actual_jump_owner_complete, ...
    'weights_once', isequal(w.lifting,w.minimum_energy.harmonic_weight), ...
    'finite_nonnegative', all(isfinite(all_values)) && ...
      all([radius_val; radius_nor; finite_normal; finite_lifting; ...
      cell_normal; cell_lifting; high_normal; high_lifting] >= 0), ...
    'pass', ~isempty(local.center.val) && ~isempty(regular.raw_center.val) && ...
      ~isempty(off.raw_center.val) && ...
      isequal(geometry.trace_tail_slope_lower, ...
      LOCAL_trace_slope(z, geometry, c.residual_mode_cutoff)) && ...
      tail_ownership_pass && actual_jump_owner_complete && ...
      isequal(w.lifting,w.minimum_energy.harmonic_weight) && ...
      all(isfinite(all_values)) && ...
      all([radius_val; radius_nor; finite_normal; finite_lifting; ...
      cell_normal; cell_lifting; high_normal; high_lifting] >= 0)));
end

function [states, labels, tail_states] = LOCAL_states(z, J)
states = {double(z.q_center)};
labels = {'center'};
sides = {'minus', 'plus'};
tail_states = cell(2, 1);
for side = 1:2
  P = double(z.(['P', sides{side}]));
  G = double(z.(['G', sides{side}]));
  state = double(z.(['c', sides{side}]));
  for n = 0:J - 1
    states{end + 1} = G * state; %#ok<AGROW>
    labels{end + 1} = sprintf('%s-cell-%d', sides{side}, n); %#ok<AGROW>
    state = P * state;
  end
  tail_states{side} = state;
end
end

function [normal, lifting, ledger] = LOCAL_cell_tail( ...
    z, w, Cn, Cv, rn, rv, propagation, tail_states)
normal = 0;
lifting = 0;
sides = {'minus', 'plus'};
entries = cell(2, 1);
for side = 1:2
  G = double(z.(['G', sides{side}]));
  map_norm = norm(G, 'fro');
  omega_n = sum(w.normal_inverse_trace .* ...
    (vecnorm(Cn * G, 2, 2) + rn * map_norm).^2);
  omega_v = sum(w.lifting .* ...
    (vecnorm(Cv * G, 2, 2) + rv * map_norm).^2);
  cap = propagation.(sides{side}).sum_power_squared_upper;
  state_norm = norm(tail_states{side}, 2);
  normal = normal + omega_n * cap * state_norm^2;
  lifting = lifting + omega_v * cap * state_norm^2;
  entries{side} = struct('side', sides{side}, 'omega_normal', omega_n, ...
    'omega_lifting', omega_v, 'state_norm', state_norm, ...
    'sum_power_squared_upper', cap);
end
ledger = vertcat(entries{:});
end

