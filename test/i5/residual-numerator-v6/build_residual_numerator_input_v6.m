function out = LOCAL_tightness_diagnostic( ...
    z, c, w, local, regular, off, wall, material, propagation, ...
    evaluation_selection)
state_energy = LOCAL_state_energy(z, propagation, 0);
regular_normal = state_energy * sum(w.normal_inverse_trace .* ...
  double(regular.radius.nor.total(:)).^2);
regular_lifting = state_energy * sum(w.lifting .* ...
  double(regular.radius.val.total(:)).^2);
off_normal = state_energy * sum(w.normal_inverse_trace .* ...
  double(off.radius.nor.total(:)).^2);
off_lifting = state_energy * sum(w.lifting .* ...
  double(off.radius.val.total(:)).^2);
regular_wall_contribution = sqrt(regular_normal) + sqrt(regular_lifting) + ...
  sqrt(off_normal) + sqrt(off_lifting) + ...
  double(wall.normal.non_special_function_radius_norm) + ...
  double(wall.lifting.non_special_function_radius_norm) + ...
  sqrt(double(wall.normal.high_mode_tail_squared)) + ...
  sqrt(double(wall.lifting.high_mode_tail_squared));
cell_contribution = sqrt(material.cell_tail.normal_squared) + ...
  sqrt(material.cell_tail.lifting_squared) + ...
  sqrt(wall.normal.propagation_tail_squared) + ...
