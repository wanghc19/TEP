function experiment_input = build_residual_numerator_input_v6( ...
    artifact_path, curve_contract_path, input_path)
%BUILD_RESIDUAL_NUMERATOR_INPUT_V6 Build the minimum-energy lifting input.
% Purpose:
%   Instantiate the conditional I5.1g minimum-energy comparison theorem from
%   the explicit frozen certificate and curve contract. Historical experiment
%   inputs and outputs are not read.
% Input:
%   artifact_path - Explicit frozen I3 certificate MAT path.
%   curve_contract_path - Explicit accepted curve-contract MAT path.
%   input_path - Explicit create-once v6 MAT target.
% Output:
%   experiment_input - Self-contained centres, analytic radii and assemblies.
% Main algorithm:
%   Audit frozen data, generate two-sided collar certificates, select L and N
%   from proved analytic remainders, build signed centres, pair actual wall
%   jumps, and apply the harmonic minimum-energy comparison weights once.
% Based on:
%   design-5-1g.md, equations (I5.1g-1)--(I5.1g-24), and
%   s-lift-tail.md, equations (ME-1)--(ME-31).
% Numerical goal:
%   Quantify the conditional ideal numerator with the lifting factor one,
%   while leaving delta_sf and delta_fp unresolved.

timer = tic;
[artifact_path, curve_contract_path, input_path] = LOCAL_paths( ...
  artifact_path, curve_contract_path, input_path);
loaded_artifact = load(artifact_path, 'staged');
loaded_curve = load(curve_contract_path, 'curve_contract');
if ~isfield(loaded_artifact, 'staged') || ...
    ~isfield(loaded_artifact.staged, 'certificate') || ...
    ~isfield(loaded_curve, 'curve_contract')
  error('I5v6Input:Schema', 'The explicit input MAT schema is invalid.');
end
z = loaded_artifact.staged.certificate;
curve_contract = loaded_curve.curve_contract;
artifact_audit = LOCAL_validate_frozen(z, loaded_artifact.staged);
curve_audit = LOCAL_validate_curve(z, curve_contract);
density = LOCAL_density(z);
configuration = LOCAL_configuration;

% --- stage 1: analytic L selection before any signed centre ---
pre_configuration = configuration;
pre_configuration.residual_mode_cutoff = configuration.L_schedule(1);
pre_configuration.evaluation_node_count = 514;
pre_configuration.evaluate_centers = false;
pre_geometry = LOCAL_circle_geometry(z, pre_configuration);
local_pre = signed_local_center_v6( ...
  z, pre_geometry, pre_configuration, density);
regular_pre = signed_regular_image_v6( ...
  z, pre_geometry, pre_configuration, density);
off_pre = signed_off_surface_v6(z, pre_geometry, pre_configuration);
propagation = struct( ...
  'minus', LOCAL_block_certificate(z.Pminus, configuration.block_length), ...
  'plus', LOCAL_block_certificate(z.Pplus, configuration.block_length));
cutoff_selection = LOCAL_select_L( ...
  z, pre_geometry, configuration, local_pre, regular_pre, off_pre, propagation);
configuration.residual_mode_cutoff = cutoff_selection.selected_L;

% --- stage 2: p=4 source/target/series selection with fixed L ---
evaluation_selection = LOCAL_select_N( ...
  z, configuration, density, propagation);
configuration.evaluation_node_count = evaluation_selection.selected_N;
fprintf(['I5.1g analytic preselection: L=%d high=%.17g pass=%d; ', ...
  'N=%d local=%.17g pass=%d. Starting signed centres.\n'], ...
  configuration.residual_mode_cutoff, ...
  cutoff_selection.numerator_contribution(cutoff_selection.selected_index), ...
  cutoff_selection.tightness_pass, configuration.evaluation_node_count, ...
  evaluation_selection.numerator_contribution(evaluation_selection.selected_index), ...
  evaluation_selection.tightness_pass);
configuration.evaluate_centers = true;
geometry = LOCAL_circle_geometry(z, configuration);

% --- stage 3: conditional signed centres and analytic radii ---
local = signed_local_center_v6(z, geometry, configuration, density);
regular = signed_regular_image_v6(z, geometry, configuration, density);
off_surface = signed_off_surface_v6(z, geometry, configuration);
wall = signed_wall_center_v6(z, geometry, configuration);
weights = LOCAL_material_weights(z, geometry, ...
  configuration.residual_mode_cutoff);
material = LOCAL_material_assembly( ...
  z, geometry, configuration, weights, local, regular, off_surface, propagation);
tightness = LOCAL_tightness_diagnostic( ...
  z, configuration, weights, local, regular, off_surface, wall, ...
  material, propagation, evaluation_selection);

strict_cutoff = mod(configuration.evaluation_node_count, 2) == 0 && ...
  configuration.evaluation_node_count > 2 * max( ...
  configuration.residual_mode_cutoff, density.maximum_order);
selected_trace_slope_match = isequal( ...
  cutoff_selection.candidate_trace_slope(cutoff_selection.selected_index), ...
  geometry.trace_tail_slope_lower);
analytic_gates = struct( ...
  'artifact', artifact_audit.pass, ...
  'curve', curve_audit.pass, ...
  'strict_cutoff', strict_cutoff, ...
  'cutoff_selection', cutoff_selection.pass, ...
  'evaluation_selection', evaluation_selection.pass, ...
  'selected_cutoff_match', isequal(cutoff_selection.selected_L, ...
    configuration.residual_mode_cutoff), ...
  'selected_evaluation_match', isequal(evaluation_selection.selected_N, ...
    configuration.evaluation_node_count), ...
  'selected_trace_slope_match', selected_trace_slope_match, ...
  'local', local.gates.pass, ...
  'regular', regular.gates.pass, ...
  'off_surface', off_surface.gates.pass, ...
  'wall', wall.gates.pass, ...
  'propagation_minus', propagation.minus.pass, ...
  'propagation_plus', propagation.plus.pass, ...
  'material', material.gates.pass, ...
  'identity_once', local.gates.identity_included_once, ...
  'physical_value_sign', material.gates.value_sign, ...
  'physical_normal_sign', material.gates.normal_sign, ...
  'source_target_strips_separate', ...
    regular.gates.source_strip_certificate && ...
    regular.gates.target_strip_certificate && ...
    regular.gates.one_variable_strip_union_only, ...
  'tail_ownership_disjoint', material.gates.tail_ownership_disjoint && ...
    wall.gates.tail_ownership_once, ...
  'minimum_energy_factor_one', ...
    isequal(configuration.minimum_energy_lifting_factor, 1), ...
  'material_two_sided_comparison', weights.gates.pass, ...
  'material_sides_stored_separately', ...
    geometry.lift_geometry_gates.material_sides_stored_separately, ...
  'wall_sides_stored_separately', ...
    geometry.lift_geometry_gates.wall_sides_stored_separately, ...
  'wall_actual_jumps_paired', wall.gates.actual_jumps_paired, ...
  'wall_cutoff_selection', wall.gates.wall_cutoff_analytic, ...
  'shared_identity_audited', wall.gates.shared_identity_audited, ...
  'all_collars_disjoint', geometry.lift_geometry_gates.all_collars_disjoint, ...
  'material_transverse_periodic_copies_disjoint', ...
    geometry.lift_geometry_gates.material_transverse_periodic_copies_disjoint, ...
  'all_collar_rims_zero', geometry.lift_geometry_gates.all_rims_zero, ...
  'jump_correction_sign', strcmp( ...
    geometry.lift_geometry_gates.jump_correction_sign, 'J_all e = -a'), ...
  'broken_energy_direct_sum', ...
    geometry.lift_geometry_gates.broken_energy_direct_sum, ...
  'simultaneous_jump_list_complete', ...
    geometry.lift_geometry_gates.simultaneous_jump_label_list_complete && ...
    material.gates.actual_jump_owner_complete && ...
    wall.gates.actual_jump_owner_complete, ...
  'sampled_maximum_used', false, ...
  'inter_level_drift_used', false, ...
  'Richardson_used', false, ...
  'empirical_safety_factor_used', false);
structural_pass = all([artifact_audit.pass, curve_audit.pass, strict_cutoff, ...
  cutoff_selection.pass, evaluation_selection.pass, ...
  isequal(cutoff_selection.selected_L, configuration.residual_mode_cutoff), ...
  isequal(evaluation_selection.selected_N, configuration.evaluation_node_count), ...
  selected_trace_slope_match, ...
  local.gates.pass, regular.gates.pass, off_surface.gates.pass, ...
  wall.gates.pass, propagation.minus.pass, propagation.plus.pass, ...
  material.gates.pass, weights.gates.pass, wall.gates.actual_jumps_paired, ...
  geometry.lift_geometry_gates.material_sides_stored_separately, ...
  geometry.lift_geometry_gates.wall_sides_stored_separately, ...
  wall.gates.wall_cutoff_analytic, ...
  wall.gates.shared_identity_audited, wall.gates.tail_ownership_once, ...
  geometry.lift_geometry_gates.all_collars_disjoint, ...
  geometry.lift_geometry_gates.material_transverse_periodic_copies_disjoint, ...
  geometry.lift_geometry_gates.all_rims_zero, ...
  strcmp(geometry.lift_geometry_gates.jump_correction_sign,'J_all e = -a'), ...
  geometry.lift_geometry_gates.broken_energy_direct_sum, ...
  geometry.lift_geometry_gates.simultaneous_jump_label_list_complete, ...
  material.gates.actual_jump_owner_complete, ...
  wall.gates.actual_jump_owner_complete]);

experiment_input = struct( ...
  'schema', 'EPOST_I5_1G_INPUT_V6', ...
  'claim_scope', ...
    'CONDITIONAL_CONTINUOUS_RESIDUAL_NUMERATOR_MINIMUM_ENERGY_LIFT', ...
  'condition_label', 'CONDITIONAL_ON_EXACT_SPECIAL_FUNCTION_EVALUATION', ...
  'certification_label', 'NON_CERTIFIED_ROUNDOFF_EXCLUDED', ...
  'delta_sf', 'UNRESOLVED', ...
  'delta_fp', 'UNRESOLVED', ...
  'configuration', configuration, ...
  'density', density, ...
  'geometry', geometry, ...
  'cutoff_selection', cutoff_selection, ...
  'evaluation_selection', evaluation_selection, ...
  'local', local, ...
  'regular', regular, ...
  'off_surface', off_surface, ...
  'wall', wall, ...
  'weights', weights, ...
  'propagation', propagation, ...
  'material', material, ...
  'tightness', tightness, ...
  'gates', analytic_gates, ...
  'structural_pass', structural_pass, ...
  'sf_ledger', LOCAL_sf_ledger( ...
    local_pre, regular_pre, off_pre, evaluation_selection, ...
    local, regular, off_surface, wall), ...
  'provenance', struct( ...
    'artifact_path', artifact_path, ...
    'curve_contract_path', curve_contract_path, ...
    'historical_output_read', false, ...
    'eigenpair_solves', 0, 'bie_density_solves', 0, ...
    'qz_decompositions', 0, 'propagation_matrix_solves', 0, ...
    'artifact_audit', artifact_audit, 'curve_audit', curve_audit, ...
    'builder_elapsed_seconds_before_save', toc(timer)));
save(input_path, 'experiment_input', '-v7.3');
end

%% ==================== Explicit paths and frozen contracts ====================
% Runtime authority comes only from caller-supplied MAT files.

function [artifact_path, curve_path, input_path] = LOCAL_paths( ...
    artifact_path, curve_path, input_path)
artifact_path = LOCAL_path(artifact_path, 'artifact_path');
curve_path = LOCAL_path(curve_path, 'curve_contract_path');
input_path = LOCAL_path(input_path, 'input_path');
if ~isfile(artifact_path) || ~isfile(curve_path)
  error('I5v6Input:InputPath', 'Both explicit input MAT files must exist.');
end
if isfile(input_path) || isfolder(input_path)
  error('I5v6Input:CreateOnce', 'input_path must be a new target.');
end
if ~isfolder(fileparts(input_path))
  error('I5v6Input:OutputDirectory', 'The input directory does not exist.');
end
end

function value = LOCAL_path(value, name)
if isstring(value) && isscalar(value)
  value = char(value);
end
if ~ischar(value) || isempty(value)
  error('I5v6Input:Path', '%s must be nonempty text.', name);
end
end

function audit = LOCAL_validate_frozen(z, staged)
required = {'khat', 'gamma', 'mu_h', 'beta', 'd', 'R', 'rho_disk', ...
  'delta_c', 'delta_w', 'X_L', 'X_R', 'L', 'M', 'K', 'q_center', ...
  'Dplus', 'Dminus', 'Gplus', 'Gminus', 'Pplus', 'Pminus', ...
  'cplus', 'cminus', 'eta_unit_256', 'density_coordinate', ...
  'xi_left_unit_512', 'xi_right_unit_512', 'wall_input_unit_512', ...
  'wall_orders_512'};
if ~all(isfield(z, required))
  error('I5v6Input:FrozenFields', 'The frozen certificate is incomplete.');
end
density_pass = isequal(size(z.eta_unit_256, 1), 512) && ...
  strcmp(strtrim(char(z.density_coordinate)), '[tau;zeta], zeta=-sigma');
K = double(z.K);
M = double(z.M);
state_pass = K == 2 * M + 1 && ...
  isequal(size(z.q_center), [2 * K, 1]) && ...
  isequal(size(z.Dplus), [K, K]) && isequal(size(z.Dminus), [K, K]) && ...
  isequal(size(z.Gplus), [2 * K, K]) && ...
  isequal(size(z.Gminus), [2 * K, K]) && ...
  isequal(size(z.Pplus), [K, K]) && isequal(size(z.Pminus), [K, K]) && ...
  isequal(size(z.cplus), [K, 1]) && isequal(size(z.cminus), [K, 1]) && ...
  isequal(size(z.eta_unit_256), [512, 2 * K]) && ...
  isequal(size(z.xi_left_unit_512), [512, 2 * K]) && ...
  isequal(size(z.xi_right_unit_512), [512, 2 * K]) && ...
  isequal(size(z.wall_input_unit_512), [1024, 2 * K]);
wall_index_pass = isequal(double(z.wall_orders_512(:)), (-256:255).');
input_contract_pass = isfield(staged, 'input_contract') && ...
  isfield(staged.input_contract, 'no_resolve_required') && ...
  logical(staged.input_contract.no_resolve_required);
scalar_pass = isequal(double(z.gamma), double(z.mu_h)) && ...
  isequal(double(z.mu_h), double(z.khat)^2) && ...
  all(isfinite([double(z.khat), double(z.mu_h), double(z.beta), ...
  double(z.d), double(z.R), double(z.rho_disk)])) && ...
  all([double(z.khat), double(z.d), double(z.R), ...
  double(z.rho_disk), double(z.delta_c), double(z.delta_w)] > 0);
audit = struct('density', density_pass, 'state', state_pass, ...
  'wall_index_half_open', wall_index_pass, ...
  'input_contract_no_resolve', input_contract_pass, ...
  'scalar', scalar_pass, 'pass', density_pass && state_pass && ...
    wall_index_pass && input_contract_pass && scalar_pass);
if ~audit.pass
  error('I5v6Input:FrozenGate', 'A frozen-data contract failed.');
end
end

function audit = LOCAL_validate_curve(z, contract)
required = {'schema', 'parameter_period', 'source_node_count', ...
  'source_contour', 'density_coordinate', 'orientation', 'node_rule', ...
  'adapter_metadata', 'wall_left_x', 'wall_right_x'};
pass = all(isfield(contract, required)) && ...
  strcmp(char(contract.schema), 'TEP_I5_WALL_CURVE_CONTRACT_V1') && ...
  isequal(double(contract.parameter_period), 2 * pi) && ...
  isequal(double(contract.source_node_count), 256) && ...
  strcmp(char(contract.orientation), ...
    'counter-clockwise; outward normal=(dy_dt,-dx_dt)/speed') && ...
  strcmp(char(contract.node_rule), ...
    't_j=2*pi*j/N, j=0,...,N-1; no midpoint shift') && ...
  strcmp(strtrim(char(contract.density_coordinate)), ...
    strtrim(char(z.density_coordinate))) && ...
  isfield(contract.adapter_metadata, 'radius') && ...
  isequal(double(contract.adapter_metadata.radius), double(z.R)) && ...
  isfield(contract.adapter_metadata, 'center') && ...
  isequal(double(contract.adapter_metadata.center(:).'), [0, 0]) && ...
  isfield(contract.adapter_metadata, 'geometry_constructor') && ...
  strcmp(char(contract.adapter_metadata.geometry_constructor), ...
    'geom.construct_cont') && ...
  isequal(double(contract.wall_left_x), double(z.X_L)) && ...
  isequal(double(contract.wall_right_x), double(z.X_R));
audit = struct('schema_orientation_phase', pass, ...
  'circle_adapter_only', true, 'pass', pass);
if ~pass
  error('I5v6Input:CurveGate', 'The explicit curve contract failed.');
end
end

function density = LOCAL_density(z)
N_eta = size(z.eta_unit_256, 1) / 2;
orders = (-N_eta / 2:N_eta / 2 - 1).';
eta = double(z.eta_unit_256);
tau_coeff = fftshift(fft(eta(1:N_eta, :), [], 1), 1) / N_eta;
zeta_coeff = fftshift(fft(eta(N_eta + 1:end, :), [], 1), 1) / N_eta;
density = struct('orders', orders, 'tau_coeff', tau_coeff, ...
  'zeta_coeff', zeta_coeff, 'source_node_count', N_eta, ...
  'maximum_order', max(abs(orders)), ...
  'coordinate', '[tau;zeta], zeta=-sigma', ...
  'coefficient_norm', 'row 2-norm', ...
  'finite_DFT_call_count', 2, ...
  'finite_DFT_evaluation', 'ORACLE; fp UNRESOLVED');
end

