function out = LOCAL_center_diagnostic(input)
local_val = vecnorm(input.local.center.val, 2, 2);
regular_val = vecnorm(input.regular.raw_center.val, 2, 2);
off_val = vecnorm(input.off_surface.raw_center.val, 2, 2);
local_nor = vecnorm(input.local.center.nor, 2, 2);
regular_nor = vecnorm(input.regular.raw_center.nor, 2, 2);
off_nor = vecnorm(input.off_surface.raw_center.nor, 2, 2);
combined_val = vecnorm(input.material.physical_center.val, 2, 2);
combined_nor = vecnorm(input.material.physical_center.nor, 2, 2);
triangle_val = local_val + regular_val + off_val;
triangle_nor = local_nor + regular_nor + off_nor;
out = struct( ...
  'local_value_row_norm', local_val, ...
  'regular_value_row_norm', regular_val, ...
  'off_value_row_norm', off_val, ...
  'combined_value_row_norm', combined_val, ...
  'value_cancellation_ratio', combined_val ./ max(realmin, triangle_val), ...
  'local_normal_row_norm', local_nor, ...
  'regular_normal_row_norm', regular_nor, ...
  'off_normal_row_norm', off_nor, ...
  'combined_normal_row_norm', combined_nor, ...
  'normal_cancellation_ratio', combined_nor ./ max(realmin, triangle_nor), ...
  'wall_normal_cancellation_ratio', input.wall.normal.cancellation_ratio, ...
  'wall_lifting_cancellation_ratio', input.wall.lifting.cancellation_ratio);
end
