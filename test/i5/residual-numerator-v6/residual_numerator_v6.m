function result = residual_numerator_v6(input_path, output_path)
%RESIDUAL_NUMERATOR_V6 Assemble the I5.1g conditional ideal majorant.
% Purpose:
%   Combine signed local, regular-image, off-surface, and wall centres with
%   every analytic radius while preserving unresolved sf/fp obligations.
% Input:
%   input_path - Explicit self-contained v6 MAT input.
%   output_path - Explicit create-once result MAT target.
% Output:
%   result - Three ideal modules, decomposition, gates, and phase decision.
% Main algorithm:
%   Validate the theorem contract, add energies of disjoint collars, and use
%   the minimum-energy lifting factor one from (ME-5).
% Based on:
%   design-5-1g.md, equations (I5.1g-1)--(I5.1g-24).
% Numerical goal:
%   Report M_ideal only; never convert unresolved delta_sf/delta_fp to zero.

timer = tic;
[input_path, output_path] = LOCAL_paths(input_path, output_path);
loaded = load(input_path, 'experiment_input');
if ~isfield(loaded, 'experiment_input')
  error('I5v6:Schema', 'input_path lacks experiment_input.');
end
input = loaded.experiment_input;
audit = LOCAL_audit(input);
if ~audit.pass
  result = LOCAL_stopped(input, audit, toc(timer));
  save(output_path, 'result', '-v7.3');
  return;
end

wall_normal = double(input.wall.normal.bound_squared);
material_normal = double(input.material.finite.normal_squared) + ...
  double(input.material.cell_tail.normal_squared) + ...
  double(input.material.high_tail.normal_squared);
material_lift = double(input.material.finite.lifting_squared) + ...
  double(input.material.cell_tail.lifting_squared) + ...
  double(input.material.high_tail.lifting_squared);
wall_lift = double(input.wall.lifting.bound_squared);
B_Gamma_pm_ideal = sqrt(wall_normal);
B_Upsilon_ideal = sqrt(material_normal);
B_lift_ideal = sqrt(material_lift + wall_lift);
M_ideal = B_Gamma_pm_ideal + B_Upsilon_ideal + B_lift_ideal;
final_values = [B_Gamma_pm_ideal; B_Upsilon_ideal; B_lift_ideal; M_ideal];
final_assembly_pass = isreal(final_values) && all(isfinite(final_values)) && ...
  all(final_values >= 0);
audit.final_assembly_real_finite_nonnegative = final_assembly_pass;
audit.pass = audit.pass && final_assembly_pass;
if ~audit.pass
  result = LOCAL_stopped(input, audit, toc(timer));
  save(output_path, 'result', '-v7.3');
  return;
end

if M_ideal < 1
  phase_decision = 'PHASE2_MAY_PROCEED_AFTER_SKEPTIC_REVIEW';
elseif M_ideal < 87.9091
  phase_decision = ...
    'PHASE2_REQUIRES_INDEPENDENT_DOMINANT_SF_UNCERTAINTY_FINDING';
else
  phase_decision = 'STOP_AFTER_PHASE1_IDEAL_MAJORANT_AT_OR_ABOVE_87_9091';
end
analytic_radius = LOCAL_radius_ownership(input);
center_diagnostic = LOCAL_center_diagnostic(input);
workspace = whos;
result = struct( ...
  'status', 'CONDITIONAL_IDEAL_MAJORANT_COMPLETE_SF_FP_UNRESOLVED', ...
  'claim_scope', input.claim_scope, ...
  'condition_label', input.condition_label, ...
  'certification_label', input.certification_label, ...
  'delta_sf', 'UNRESOLVED', ...
  'delta_fp', 'UNRESOLVED', ...
  'M_ideal', M_ideal, ...
  'numerical_reliable_majorant', 'UNRESOLVED', ...
  'B_Gamma_pm_ideal', B_Gamma_pm_ideal, ...
  'B_Upsilon_ideal', B_Upsilon_ideal, ...
  'B_lift_ideal', B_lift_ideal, ...
  'minimum_energy_lifting_factor', 1, ...
  'wall', struct('normal_squared', wall_normal, ...
    'normal', input.wall.normal, 'lifting', input.wall.lifting), ...
  'material', input.material, ...
  'analytic_radius_ownership', analytic_radius, ...
  'center_diagnostic', center_diagnostic, ...
  'component_share', struct( ...
    'B_Gamma_pm', B_Gamma_pm_ideal / max(realmin, M_ideal), ...
    'B_Upsilon', B_Upsilon_ideal / max(realmin, M_ideal), ...
    'B_lift', B_lift_ideal / max(realmin, M_ideal)), ...
  'cutoff_selection', input.cutoff_selection, ...
  'evaluation_selection', input.evaluation_selection, ...
  'tightness', input.tightness, ...
  'phase_gate', struct('lower_threshold', 1, ...
    'upper_threshold', 87.9091, 'decision', phase_decision, ...
    'special_function_dominance_established', false, ...
    'phase2_started', false), ...
  'sf_ledger', input.sf_ledger, ...
  'gate_audit', audit, ...
  'theorem_gate', struct( ...
    'conditional_diagnostic_pass', true, ...
    'analytic_telescope_pass', true, ...
    'delta_sf_resolved', false, ...
    'delta_fp_resolved', false, ...
    'reliable_eval_enclosure_pass', false, ...
    'total_reliable_pass', false, ...
    'outward_rounding', false), ...
  'provenance', input.provenance, ...
  'resource', struct('elapsed_seconds_before_save', toc(timer), ...
    'workspace_proxy_mib_before_save', sum([workspace.bytes]) / 2^20));
save(output_path, 'result', '-v7.3');
end

%% ==================== Portable input and fail-closed audit ====================
% The evaluator consumes one self-contained input and no historical output.

function [input_path, output_path] = LOCAL_paths(input_path, output_path)
input_path = LOCAL_path(input_path, 'input_path');
output_path = LOCAL_path(output_path, 'output_path');
if ~isfile(input_path)
  error('I5v6:InputPath', 'input_path must exist.');
end
if isfile(output_path) || isfolder(output_path)
  error('I5v6:CreateOnce', 'output_path must be a new target.');
end
if ~isfolder(fileparts(output_path))
  error('I5v6:OutputDirectory', 'The output directory does not exist.');
end
end

function value = LOCAL_path(value, name)
if isstring(value) && isscalar(value)
  value = char(value);
end
if ~ischar(value) || isempty(value)
  error('I5v6:Path', '%s must be nonempty text.', name);
end
end

function audit = LOCAL_audit(input)
required = {'schema', 'claim_scope', 'condition_label', ...
  'certification_label', 'delta_sf', 'delta_fp', 'configuration', ...
  'geometry', 'density', 'local', 'regular', 'off_surface', 'wall', ...
  'material', 'propagation', 'gates', 'structural_pass', 'provenance', ...
  'cutoff_selection', 'evaluation_selection'};
required{end + 1} = 'tightness';
schema_pass = all(isfield(input, required)) && ...
  strcmp(char(input.schema), 'EPOST_I5_1G_INPUT_V6') && ...
  strcmp(char(input.claim_scope), ...
    'CONDITIONAL_CONTINUOUS_RESIDUAL_NUMERATOR_MINIMUM_ENERGY_LIFT') && ...
  strcmp(char(input.condition_label), ...
    'CONDITIONAL_ON_EXACT_SPECIAL_FUNCTION_EVALUATION') && ...
  strcmp(char(input.delta_sf), 'UNRESOLVED') && ...
  strcmp(char(input.delta_fp), 'UNRESOLVED') && ...
  strcmp(char(input.certification_label), 'NON_CERTIFIED_ROUNDOFF_EXCLUDED');
if ~schema_pass
  audit = struct('schema', false, 'pass', false);
  return;
end
true_gates = {'artifact', 'curve', 'strict_cutoff', 'local', 'regular', ...
  'off_surface', 'wall', 'propagation_minus', 'propagation_plus', ...
  'material', 'identity_once', 'physical_value_sign', ...
  'physical_normal_sign', 'source_target_strips_separate', ...
  'tail_ownership_disjoint', 'cutoff_selection', 'evaluation_selection', ...
  'selected_cutoff_match', 'selected_evaluation_match', ...
  'selected_trace_slope_match', 'minimum_energy_factor_one', ...
  'material_two_sided_comparison', 'material_sides_stored_separately', ...
  'wall_sides_stored_separately', 'wall_actual_jumps_paired', ...
  'wall_cutoff_selection', ...
  'shared_identity_audited', 'all_collars_disjoint', ...
  'material_transverse_periodic_copies_disjoint', ...
  'all_collar_rims_zero', 'jump_correction_sign', ...
  'broken_energy_direct_sum', 'simultaneous_jump_list_complete'};
false_gates = {'sampled_maximum_used', 'inter_level_drift_used', ...
  'Richardson_used', 'empirical_safety_factor_used'};
true_values = false(size(true_gates));
false_values = true(size(false_gates));
for j = 1:numel(true_gates)
  true_values(j) = isfield(input.gates, true_gates{j}) && ...
    isequal(input.gates.(true_gates{j}), true);
end
for j = 1:numel(false_gates)
  false_values(j) = isfield(input.gates, false_gates{j}) && ...
    isequal(input.gates.(false_gates{j}), false);
end
solve_fields = {'eigenpair_solves', 'bie_density_solves', ...
  'qz_decompositions', 'propagation_matrix_solves'};
solve_pass = all(isfield(input.provenance, solve_fields));
for j = 1:numel(solve_fields)
  solve_pass = solve_pass && input.provenance.(solve_fields{j}) == 0;
end
L = double(input.configuration.residual_mode_cutoff);
N = double(input.configuration.evaluation_node_count);
strict = mod(N, 2) == 0 && N > 2 * max(L, input.density.maximum_order);
selection_indices_pass = isscalar(input.cutoff_selection.selected_index) && ...
  isscalar(input.evaluation_selection.selected_index) && ...
  input.cutoff_selection.selected_index >= 1 && ...
  input.cutoff_selection.selected_index <= ...
    numel(input.cutoff_selection.candidate_L) && ...
  input.evaluation_selection.selected_index >= 1 && ...
  input.evaluation_selection.selected_index <= ...
    numel(input.evaluation_selection.candidate_N) && ...
  input.cutoff_selection.selected_index == ...
    floor(input.cutoff_selection.selected_index) && ...
  input.evaluation_selection.selected_index == ...
    floor(input.evaluation_selection.selected_index);
selection_pass = false;
if selection_indices_pass && ...
    isfield(input.cutoff_selection, 'candidate_trace_slope')
  selection_pass = isequal(input.cutoff_selection.pass, true) && ...
    isequal(input.evaluation_selection.pass, true) && ...
    isequal(input.cutoff_selection.selected_L, L) && ...
    isequal(input.evaluation_selection.selected_N, N) && ...
    isequal(input.cutoff_selection.candidate_trace_slope( ...
      input.cutoff_selection.selected_index), ...
      input.geometry.trace_tail_slope_lower);
end
finite_values = [input.wall.normal.bound_squared; ...
  input.wall.lifting.bound_squared; input.material.finite.normal_squared; ...
  input.material.finite.lifting_squared; ...
  input.material.cell_tail.normal_squared; ...
  input.material.cell_tail.lifting_squared; ...
  input.material.high_tail.normal_squared; ...
  input.material.high_tail.lifting_squared];
finite_pass = isreal(finite_values) && all(isfinite(finite_values)) && ...
  all(finite_values >= 0);
audit = struct('schema', schema_pass, 'required_true', {true_gates}, ...
  'required_false', {false_gates}, 'true_values', true_values, ...
  'false_values', false_values, 'zero_solves', solve_pass, ...
  'strict_cutoff', strict, 'finite_nonnegative', finite_pass, ...
  'selection_indices', selection_indices_pass, ...
  'selection_contract', selection_pass, ...
  'delta_sf_unresolved', strcmp(input.delta_sf, 'UNRESOLVED'), ...
  'delta_fp_unresolved', strcmp(input.delta_fp, 'UNRESOLVED'), ...
  'pass', schema_pass && all(true_values) && all(false_values) && ...
    solve_pass && strict && selection_pass && finite_pass && ...
    input.structural_pass);
end

function result = LOCAL_stopped(input, audit, elapsed)
result = struct('status', 'PRE_RUN_CERTIFICATE_STOP', ...
  'claim_scope', ...
    'CONDITIONAL_CONTINUOUS_RESIDUAL_NUMERATOR_MINIMUM_ENERGY_LIFT', ...
  'certification_label', 'NON_CERTIFIED_ROUNDOFF_EXCLUDED', ...
  'delta_sf', 'UNRESOLVED', 'delta_fp', 'UNRESOLVED', ...
  'gate_audit', audit, 'configuration', input.configuration, ...
  'resource', struct('elapsed_seconds_before_save', elapsed));
end

