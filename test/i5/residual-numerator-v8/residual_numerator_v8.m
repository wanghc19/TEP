function result = residual_numerator_v8(input_path, output_path)
%RESIDUAL_NUMERATOR_V8 Assemble the RI direct-bridge conditional majorant.
% Purpose:
%   Validate a self-contained v8 input and report (RI-1)--(RI-3).
% Input:
%   input_path - Explicit v8 MAT input; output_path - create-once MAT target.
% Output:
%   result - Conditional ideal modules, bridge decomposition, and gate audit.
% Main algorithm:
%   Add the unchanged wall/material-normal modules to the RI material and wall
%   lifting energies with factor one. No material target Fourier object exists.
% Based on:
%   s-lift-real-interpolation.md, equations (RI-1)--(RI-19).

timer = tic;
[input_path, output_path] = LOCAL_paths(input_path, output_path);
loaded = load(input_path, 'experiment_input');
if ~isfield(loaded, 'experiment_input')
  error('I5v8:Schema', 'input_path lacks experiment_input.');
end
input = loaded.experiment_input;
audit = LOCAL_audit(input);
if ~audit.pass
  error('I5v8:Preflight', 'A fail-closed v8 input gate failed.');
end

accepted = input.accepted_unchanged_modules;
B_Gamma_pm_ideal = double(accepted.B_Gamma_pm);
B_Upsilon_ideal = double(accepted.B_Upsilon);
material_finite = double(input.material.finite_squared);
material_cell = double(input.material.cell_tail_squared);
wall_lifting = double(accepted.wall_lifting_squared);
B_lift_ideal = sqrt(material_finite+material_cell+wall_lifting);
M_ideal = B_Gamma_pm_ideal+B_Upsilon_ideal+B_lift_ideal;
expected = input.expected_result;
assembly_match = isequal(B_Gamma_pm_ideal,expected.B_Gamma_pm_ideal) && ...
  isequal(B_Upsilon_ideal,expected.B_Upsilon_ideal) && ...
  isequal(B_lift_ideal,expected.B_lift_ideal) && ...
  isequal(M_ideal,expected.M_ideal);
values = [B_Gamma_pm_ideal;B_Upsilon_ideal;B_lift_ideal;M_ideal; ...
  material_finite;material_cell;wall_lifting];
audit.final_assembly_match = assembly_match;
audit.final_real_finite_nonnegative = isreal(values) && ...
  all(isfinite(values)) && all(values>=0);
audit.pass = audit.pass && audit.final_assembly_match && ...
  audit.final_real_finite_nonnegative;
if ~audit.pass
  error('I5v8:Assembly', 'The RI final assembly gate failed.');
end

workspace = whos;
result = struct( ...
  'status','CONDITIONAL_IDEAL_MAJORANT_COMPLETE_SF_FP_UNRESOLVED', ...
  'claim_scope',input.claim_scope,'condition_label',input.condition_label, ...
  'delta_sf','UNRESOLVED','delta_fp','UNRESOLVED', ...
  'B_Gamma_pm_ideal',B_Gamma_pm_ideal, ...
  'B_Upsilon_ideal',B_Upsilon_ideal, ...
  'B_lift_ideal',B_lift_ideal,'M_ideal',M_ideal, ...
  'minimum_energy_lifting_factor',1, ...
  'lifting_decomposition',struct('material_finite_squared',material_finite, ...
    'material_cell_tail_squared',material_cell, ...
    'wall_lifting_squared',wall_lifting), ...
  'source_selection',input.source_selection,'bridge',input.bridge, ...
  'bridge_tightness',input.bridge_tightness, ...
  'material',input.material,'sf_ledger',input.sf_ledger, ...
  'gate_audit',audit,'theorem_gate',struct( ...
    'RI_direct_bridge_pass',true,'conditional_ideal_pass',true, ...
    'delta_sf_resolved',false,'delta_fp_resolved',false, ...
    'total_reliable_pass',false,'outward_rounding',false), ...
  'provenance',input.provenance,'resource',struct( ...
    'elapsed_seconds_before_save',toc(timer), ...
    'workspace_proxy_mib_before_save',sum([workspace.bytes])/2^20));
save(output_path,'result','-v7.3');
end

function [input_path, output_path] = LOCAL_paths(input_path, output_path)
input_path = LOCAL_path(input_path,'input_path');
output_path = LOCAL_path(output_path,'output_path');
if ~isfile(input_path)
  error('I5v8:MissingInput','input_path does not exist.');
end
if isfile(output_path)
  error('I5v8:CreateOnce','output_path already exists.');
end
parent = fileparts(output_path);
if isempty(parent) || ~isfolder(parent)
  error('I5v8:OutputDirectory','output_path parent must already exist.');
end
end

function value = LOCAL_path(value,name)
if isstring(value) && isscalar(value)
  value = char(value);
end
if ~ischar(value) || isempty(value)
  error('I5v8:Path','%s must be nonempty text.',name);
end
end

function audit = LOCAL_audit(input)
required = {'schema','status','claim_scope','condition_label','configuration', ...
  'source_selection','physical_value_row','bridge','bridge_tightness', ...
  'input_identity','geometry','propagation','material', ...
  'accepted_unchanged_modules','expected_result','sf_ledger', ...
  'delta_sf','delta_fp','gates','provenance'};
schema = all(isfield(input,required)) && ...
  strcmp(input.schema,'EPOST_I5_RESIDUAL_NUMERATOR_V8_RI_V1');
if ~schema
  error('I5v8:Schema','The v8 input schema is incomplete.');
end
p = input.provenance;
zero_solves = isequal(p.eigenpair_solves,0) && ...
  isequal(p.bie_density_solves,0) && isequal(p.qz_decompositions,0) && ...
  isequal(p.propagation_matrix_solves,0) && isequal(p.rayleigh_solves,0);
no_fourier = input.gates.material_target_dft_absent && ...
  input.gates.material_fourier_owner_absent && ...
  input.sf_ledger.material_target_fft_calls==0;
condition = strcmp(input.status, ...
  'CONDITIONAL_IDEAL_MAJORANT_COMPLETE_SF_FP_UNRESOLVED') && ...
  strcmp(input.delta_sf,'UNRESOLVED') && strcmp(input.delta_fp,'UNRESOLVED');
accepted_binding = input.accepted_unchanged_modules.binding;
identity = input.input_identity;
scientific_binding = identity.pass && ...
  strcmp(p.artifact_sha256,identity.artifact_sha256) && ...
  strcmp(p.curve_sha256,identity.curve_sha256) && ...
  strcmp(accepted_binding.artifact_sha256,identity.artifact_sha256) && ...
  strcmp(accepted_binding.curve_sha256,identity.curve_sha256) && ...
  input.accepted_unchanged_modules.gates.scientific_binding && ...
  input.accepted_unchanged_modules.gates.collar_geometry_binding;
direct_sum = input.geometry.lift_geometry_gates.all_collars_disjoint && ...
  input.geometry.lift_geometry_gates.all_rims_zero && ...
  input.geometry.lift_geometry_gates.broken_energy_direct_sum && ...
  input.geometry.lift_geometry_gates.simultaneous_jump_label_list_complete;
audit = struct('schema',schema,'builder_gates',input.gates.pass, ...
  'selection',input.source_selection.pass,'bridge',input.bridge.gates.pass, ...
  'material',input.material.gates.pass, ...
  'unchanged_modules',input.accepted_unchanged_modules.gates.pass, ...
  'state_maps_once',input.material.gates.state_maps_once, ...
  'material_target_fourier_absent',no_fourier, ...
  'bridge_tightness_recorded',input.gates.bridge_tightness_recorded && ...
    ~input.bridge_tightness.governing_reliability_gate, ...
  'scientific_binding',scientific_binding, ...
  'global_broken_energy_direct_sum',direct_sum, ...
  'factor_one',input.gates.factor_one && direct_sum, ...
  'zero_solves',zero_solves, ...
  'conditional_labels',condition,'historical_output_not_read', ...
    ~logical(p.historical_output_read));
audit.pass = all(structfun(@(x) isequal(x,true),audit));
end
