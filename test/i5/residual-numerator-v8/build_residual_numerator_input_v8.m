function experiment_input = build_residual_numerator_input_v8( ...
    artifact_path, curve_contract_path, input_path)
%BUILD_RESIDUAL_NUMERATOR_INPUT_V8 Build the RI direct-bridge input.
% Purpose:
%   Instantiate (RI-5)--(RI-18) from explicit frozen data without a material
%   target DFT, a material Fourier cutoff, or a historical runtime output.
% Input:
%   artifact_path - Explicit frozen I3 certificate MAT file.
%   curve_contract_path - Explicit circle-contract MAT file.
%   input_path - Explicit create-once v8 input MAT target.
% Output:
%   experiment_input - Signed node balls, RI Gram data, state energies, gates.
% Main algorithm:
%   Select N from analytic point-row radii, evaluate one signed physical row,
%   form the periodic piecewise-linear bridge, and precompose each state map
%   exactly once in the finite and block-power terms.
% Based on:
%   s-lift-real-interpolation.md, equations (RI-5)--(RI-18).
% Numerical goal:
%   A conditional ideal numerator; delta_sf and delta_fp remain unresolved.

timer = tic;
[artifact_path, curve_contract_path, input_path] = LOCAL_paths( ...
  artifact_path, curve_contract_path, input_path);
if isfile(input_path)
  error('I5v8Input:CreateOnce', 'input_path already exists.');
end
artifact = load(artifact_path, 'staged');
curve = load(curve_contract_path, 'curve_contract');
if ~isfield(artifact, 'staged') || ...
    ~isfield(artifact.staged, 'certificate') || ...
    ~isfield(curve, 'curve_contract')
  error('I5v8Input:Schema', 'An explicit input MAT has the wrong schema.');
end
input_identity = LOCAL_input_identity(artifact_path, curve_contract_path);
z = artifact.staged.certificate;
artifact_audit = LOCAL_validate_frozen(z, artifact.staged);
curve_audit = LOCAL_validate_curve(z, curve.curve_contract);
density = LOCAL_density(z);
configuration = LOCAL_configuration;

% --- stage 1: radius-only source-size selection ---
selection = LOCAL_select_N(z, density, configuration);
configuration.evaluation_node_count = selection.selected_N;
configuration.evaluate_centers = true;
geometry = LOCAL_circle_geometry(z, configuration);
fprintf('RI radius selection: N=%d maxNodeRadius=%.17g pass=%d.\n', ...
  selection.selected_N, selection.selected_radius, selection.tightness_pass);

% --- stage 2: one complete signed physical node row ---
local = signed_local_center_v8(z, geometry, configuration, density);
regular = signed_regular_image_v8(z, geometry, configuration, density);
off_surface = signed_off_surface_v8(z, geometry, configuration);
center_nodes = double(local.nodes.val) + double(regular.nodes.val) + ...
  double(off_surface.nodes.val);
node_radius = double(local.radius.val.total(:)) + ...
  double(regular.radius.val.total) + double(off_surface.radius.val.total(:));
local_derivative = double(local.derivative_action_upper.val);
regular_derivative = double(regular.first_arclength_derivative_upper);
off_derivative = double(off_surface.first_arclength_derivative_upper);
L_total = local_derivative + regular_derivative + off_derivative;
row_ball = LOCAL_bridge(center_nodes, node_radius, L_total, geometry, z, ...
  configuration);
propagation = struct( ...
  'minus', LOCAL_block_certificate(z.Pminus, configuration.block_length), ...
  'plus', LOCAL_block_certificate(z.Pplus, configuration.block_length));
material = LOCAL_material_energy(z, row_ball, propagation, configuration);
bridge_tightness = struct( ...
  'allocation',configuration.bridge_radius_allocation, ...
  'achieved',row_ball.R, ...
  'pass',row_ball.R<=configuration.bridge_radius_allocation, ...
  'route_upgrade_required',row_ball.R>configuration.bridge_radius_allocation, ...
  'governing_reliability_gate',false);

% These three accepted scalars are explicit source constants, never loaded
% from a historical output at runtime. Their mathematical owners are unchanged.
accepted = LOCAL_accepted_unchanged_modules(z, geometry, input_identity);
B_Gamma_pm_ideal = accepted.B_Gamma_pm;
B_Upsilon_ideal = accepted.B_Upsilon;
B_lift_ideal = sqrt(material.finite_squared + material.cell_tail_squared + ...
  accepted.wall_lifting_squared);
M_ideal = B_Gamma_pm_ideal + B_Upsilon_ideal + B_lift_ideal;
final_values = [B_Gamma_pm_ideal; B_Upsilon_ideal; B_lift_ideal; M_ideal];
solve_counts = struct('eigenpair',0,'bie_density',0,'qz',0, ...
  'propagation_matrix',0,'rayleigh',0);

gates = struct( ...
  'artifact_contract', artifact_audit.pass, ...
  'curve_contract', curve_audit.pass, ...
  'source_selection', selection.pass, ...
  'strict_source_index', mod(selection.selected_N, 2) == 0 && ...
    selection.selected_N > 2 * density.maximum_order, ...
  'local_node_ball', local.gates.pass, ...
  'regular_node_ball', regular.gates.pass, ...
  'off_surface_node_ball', off_surface.gates.pass, ...
  'physical_value_sign', isequal(center_nodes, ...
    double(local.nodes.val) + double(regular.nodes.val) + ...
    double(off_surface.nodes.val)), ...
  'identity_once', local.gates.identity_included_once && ...
    ~regular.gates.identity_included && ...
    ~isfield(off_surface.gates, 'identity_included'), ...
  'node_radius_owner_complete', isequal(node_radius, ...
    double(local.radius.val.total(:)) + ...
    double(regular.radius.val.total) + ...
    double(off_surface.radius.val.total(:))), ...
  'off_source_error_zero_authorized', ...
    ~off_surface.gates.source_quadrature_used && ...
    off_surface.gates.finite_support_exact && ...
    all(off_surface.radius.val.total == 0), ...
  'derivative_triangle_complete', isfinite(L_total) && L_total >= 0 && ...
    isequal(L_total, local_derivative + regular_derivative + off_derivative), ...
  'bridge_RI_5_16', row_ball.gates.pass, ...
  'bridge_tightness_recorded',isfinite(bridge_tightness.achieved) && ...
    bridge_tightness.achieved>=0 && ...
    xor(bridge_tightness.pass,bridge_tightness.route_upgrade_required), ...
  'state_maps_once', material.gates.state_maps_once, ...
  'block_power', propagation.minus.pass && propagation.plus.pass, ...
  'all_collars_disjoint',geometry.lift_geometry_gates.all_collars_disjoint, ...
  'all_collar_rims_zero',geometry.lift_geometry_gates.all_rims_zero, ...
  'broken_energy_direct_sum', ...
    geometry.lift_geometry_gates.broken_energy_direct_sum, ...
  'simultaneous_jump_list_complete', ...
    geometry.lift_geometry_gates.simultaneous_jump_label_list_complete, ...
  'material_target_dft_absent', local.sf_ledger.finite_fft_calls == 0 && ...
    regular.sf_ledger.total_fft_calls == 0 && ...
    off_surface.sf_ledger.total_fft_calls == 0, ...
  'material_fourier_owner_absent', ...
    ~isfield(configuration,'residual_mode_cutoff') && ...
    ~isfield(configuration,'alias_cutoff') && ...
    local.sf_ledger.finite_fft_calls==0 && ...
    regular.sf_ledger.target_phase_exp_scalar_count==0 && ...
    off_surface.sf_ledger.target_dft_calls==0, ...
  'unchanged_module_constants', accepted.gates.pass, ...
  'accepted_module_scientific_binding', ...
    accepted.gates.scientific_binding && ...
    accepted.gates.collar_geometry_binding, ...
  'factor_one', geometry.lift_geometry_gates.all_collars_disjoint && ...
    geometry.lift_geometry_gates.broken_energy_direct_sum, ...
  'all_solves_zero', all(struct2array(solve_counts)==0), ...
  'sf_unresolved', true, 'fp_unresolved', true, ...
  'finite_nonnegative', isreal(final_values) && ...
    all(isfinite(final_values)) && all(final_values >= 0));
gates.pass = all(structfun(@(x) isequal(x, true), gates));
if ~gates.pass
  names = fieldnames(gates);
  for gate_index = 1:numel(names)
    if ~strcmp(names{gate_index},'pass') && ...
        ~isequal(gates.(names{gate_index}),true)
      fprintf(2,'FAILED_GATE=%s\n',names{gate_index});
    end
  end
  error('I5v8Input:Gate', 'A direct-bridge input gate failed.');
end

provenance = struct( ...
  'artifact_path', artifact_path, ...
  'curve_contract_path', curve_contract_path, ...
  'attempt_identifier', configuration.attempt_identifier, ...
  'algorithm_variant', configuration.algorithm_variant, ...
  'historical_output_read', false, ...
  'accepted_unchanged_module_source', accepted.provenance, ...
  'artifact_sha256',input_identity.artifact_sha256, ...
  'curve_sha256',input_identity.curve_sha256, ...
  'eigenpair_solves', solve_counts.eigenpair, ...
  'bie_density_solves', solve_counts.bie_density, ...
  'qz_decompositions', solve_counts.qz, ...
  'propagation_matrix_solves', solve_counts.propagation_matrix, ...
  'rayleigh_solves',solve_counts.rayleigh, ...
  'artifact_audit', artifact_audit, 'curve_audit', curve_audit, ...
  'builder_elapsed_seconds_before_save', toc(timer));
experiment_input = struct( ...
  'schema', 'EPOST_I5_RESIDUAL_NUMERATOR_V8_RI_V1', ...
  'status', 'CONDITIONAL_IDEAL_MAJORANT_COMPLETE_SF_FP_UNRESOLVED', ...
  'claim_scope', 'RI direct ME-13 bridge; finite frozen data exact; sf/fp unresolved', ...
  'condition_label', 'CONDITIONAL_ON_EXACT_SPECIAL_FUNCTION_AND_FINITE_ARITHMETIC', ...
  'configuration', configuration, 'density', density, 'geometry', geometry, ...
  'input_identity',input_identity, ...
  'source_selection', selection, ...
  'physical_value_row', struct('center_nodes', center_nodes, ...
    'node_radius', node_radius, ...
    'derivative_center', complex(zeros(size(center_nodes))), ...
    'derivative_radius_global', L_total, ...
    'component_derivative_upper', struct('local', local_derivative, ...
      'regular', regular_derivative, 'off_surface', off_derivative), ...
    'component_radius', struct('local_source', local.radius.val.source, ...
      'local_series', local.radius.val.series, ...
      'regular_source', regular.radius.val.source, ...
      'regular_M_R', regular.radius.val.M_R, ...
      'regular_M_I', regular.radius.val.M_I, ...
      'regular_M_T', regular.radius.val.M_T, ...
      'regular_M_L', regular.radius.val.M_L, ...
      'off_source', off_surface.radius.val.total), ...
    'component_nodes_persisted_separately', false, ...
    'identity_owner', 'local value node exactly once'), ...
  'bridge', row_ball, 'bridge_tightness',bridge_tightness, ...
  'propagation', propagation, 'material', material, ...
  'accepted_unchanged_modules', accepted, ...
  'expected_result', struct('B_Gamma_pm_ideal', B_Gamma_pm_ideal, ...
    'B_Upsilon_ideal', B_Upsilon_ideal, 'B_lift_ideal', B_lift_ideal, ...
    'M_ideal', M_ideal), ...
  'sf_ledger', struct('local', local.sf_ledger, ...
    'regular', regular.sf_ledger, 'off_surface', off_surface.sf_ledger, ...
    'material_target_fft_calls', 0), ...
  'delta_sf', 'UNRESOLVED', 'delta_fp', 'UNRESOLVED', ...
  'gates', gates, 'provenance', provenance);
save(input_path, 'experiment_input', '-v7.3');
end

%% ==================== Explicit input and frozen-data contract ====================
% These helpers validate only the two explicit scientific input MAT files.

function [artifact_path, curve_path, input_path] = LOCAL_paths( ...
    artifact_path, curve_path, input_path)
artifact_path = LOCAL_path(artifact_path, 'artifact_path');
curve_path = LOCAL_path(curve_path, 'curve_contract_path');
input_path = LOCAL_path(input_path, 'input_path');
if ~isfile(artifact_path) || ~isfile(curve_path)
  error('I5v8Input:MissingInput', 'An explicit scientific input is missing.');
end
parent = fileparts(input_path);
if isempty(parent) || ~isfolder(parent)
  error('I5v8Input:OutputDirectory', 'input_path parent must already exist.');
end
end

function value = LOCAL_path(value, name)
if isstring(value) && isscalar(value)
  value = char(value);
end
if ~ischar(value) || isempty(value)
  error('I5v8Input:Path', '%s must be nonempty text.', name);
end
end

function audit = LOCAL_validate_frozen(z, staged)
required = {'khat','gamma','mu_h','beta','d','R','rho_disk', ...
  'delta_c','delta_w','X_L','X_R','L','M','K','q_center', ...
  'Dplus','Dminus','Gplus','Gminus','Pplus','Pminus','cplus','cminus', ...
  'eta_unit_256','density_coordinate','xi_left_unit_512', ...
  'xi_right_unit_512','wall_input_unit_512','wall_orders_512'};
if ~all(isfield(z, required))
  error('I5v8Input:FrozenFields', 'The frozen certificate is incomplete.');
end
K = double(z.K);
M = double(z.M);
shape_pass = K == 2*M+1 && ...
  isequal(size(z.q_center),[2*K,1]) && ...
  isequal(size(z.Gplus),[2*K,K]) && isequal(size(z.Gminus),[2*K,K]) && ...
  isequal(size(z.Pplus),[K,K]) && isequal(size(z.Pminus),[K,K]) && ...
  isequal(size(z.cplus),[K,1]) && isequal(size(z.cminus),[K,1]) && ...
  isequal(size(z.eta_unit_256),[512,2*K]);
density_pass = strcmp(strtrim(char(z.density_coordinate)), ...
  '[tau;zeta], zeta=-sigma');
scalar_pass = isequal(double(z.gamma),double(z.mu_h)) && ...
  isequal(double(z.mu_h),double(z.khat)^2) && ...
  all(isfinite([double(z.khat),double(z.mu_h),double(z.beta), ...
  double(z.d),double(z.R),double(z.rho_disk)])) && ...
  all([double(z.khat),double(z.d),double(z.R),double(z.rho_disk), ...
  double(z.delta_c),double(z.delta_w)]>0);
input_pass = isfield(staged,'input_contract') && ...
  isfield(staged.input_contract,'no_resolve_required') && ...
  logical(staged.input_contract.no_resolve_required);
audit = struct('shape',shape_pass,'density',density_pass, ...
  'scalar',scalar_pass,'no_resolve',input_pass, ...
  'pass',shape_pass && density_pass && scalar_pass && input_pass);
if ~audit.pass
  error('I5v8Input:FrozenGate', 'A frozen-data gate failed.');
end
end

function audit = LOCAL_validate_curve(z, contract)
required = {'schema','parameter_period','source_node_count','source_contour', ...
  'density_coordinate','orientation','node_rule','adapter_metadata', ...
  'wall_left_x','wall_right_x'};
pass = all(isfield(contract,required)) && ...
  strcmp(char(contract.schema),'TEP_I5_WALL_CURVE_CONTRACT_V1') && ...
  isequal(double(contract.parameter_period),2*pi) && ...
  isequal(double(contract.source_node_count),256) && ...
  strcmp(char(contract.orientation), ...
    'counter-clockwise; outward normal=(dy_dt,-dx_dt)/speed') && ...
  strcmp(char(contract.node_rule), ...
    't_j=2*pi*j/N, j=0,...,N-1; no midpoint shift') && ...
  strcmp(strtrim(char(contract.density_coordinate)), ...
    strtrim(char(z.density_coordinate))) && ...
  isfield(contract.adapter_metadata,'radius') && ...
  isequal(double(contract.adapter_metadata.radius),double(z.R)) && ...
  isfield(contract.adapter_metadata,'center') && ...
  isequal(double(contract.adapter_metadata.center(:).'),[0,0]) && ...
  isequal(double(contract.wall_left_x),double(z.X_L)) && ...
  isequal(double(contract.wall_right_x),double(z.X_R));
audit = struct('schema_orientation_phase',pass,'circle_adapter_only',true, ...
  'pass',pass);
if ~pass
  error('I5v8Input:CurveGate', 'The explicit curve contract failed.');
end
end

function density = LOCAL_density(z)
N_eta = size(z.eta_unit_256,1)/2;
orders = (-N_eta/2:N_eta/2-1).';
eta = double(z.eta_unit_256);
tau_coeff = fftshift(fft(eta(1:N_eta,:),[],1),1)/N_eta;
zeta_coeff = fftshift(fft(eta(N_eta+1:end,:),[],1),1)/N_eta;
density = struct('orders',orders,'tau_coeff',tau_coeff, ...
  'zeta_coeff',zeta_coeff,'source_node_count',N_eta, ...
  'maximum_order',max(abs(orders)),'coordinate','[tau;zeta], zeta=-sigma', ...
  'finite_DFT_call_count',2,'finite_DFT_evaluation','ORACLE; fp UNRESOLVED');
end

