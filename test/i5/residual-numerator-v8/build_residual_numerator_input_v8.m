%% ==================== Circle instance geometry ====================
% The current circle supplies a certificate to the shape-general interface.

function g = LOCAL_circle_geometry(z,c)
R = double(z.R);
N = double(c.evaluation_node_count);
a = double(c.parameter_strip_width);
P = 2*pi*R;
t = (0:N-1).'*(2*pi/N);
s_nodes = (0:N-1).'*(P/N);
[contour,period] = geom.construct_cont(N,'circle',0,0,R);
if ~isequal(period,2*pi) || ~isequal(size(contour),[6,N])
  error('I5v8Input:Geometry','The circle adapter returned the wrong shape.');
end
position = [double(contour(1,:).'),double(contour(4,:).')];
derivative = [double(contour(2,:).'),double(contour(5,:).')];
speed = vecnorm(derivative,2,2);
normal = [derivative(:,2),-derivative(:,1)]./speed;
h = double(z.delta_c);
material_plus = LOCAL_collar_side('material-plus-exterior',h,1,R);
material_minus = LOCAL_collar_side( ...
  'material-minus-interior',h,double(z.rho_disk),R);
wall_plus = LOCAL_flat_collar_side('wall-plus-neighbour-side', ...
  double(z.delta_w),1);
wall_minus = LOCAL_flat_collar_side('wall-minus-central-side', ...
  double(z.delta_w),1);
real_left_clearance = abs(double(z.X_L))-R;
real_right_clearance = abs(double(z.X_R))-R;
material_wall_disjoint = h+double(z.delta_w)<= ...
  min(real_left_clearance,real_right_clearance);
material_cell_copy_disjoint = 2*(R+h)<=double(z.L);
material_transverse_copy_disjoint = 2*(R+h)<=double(z.d);
wall_pair_disjoint = 2*double(z.delta_w)<=double(z.L);
lift_interfaces = {'material-interface','left-wall','right-wall'};
lift_geometry_gates = struct( ...
  'material_sides_stored_separately', ...
    ~strcmp(material_plus.label,material_minus.label) && ...
    isequal(material_plus.rho_upper,1) && ...
    isequal(material_minus.rho_upper,double(z.rho_disk)), ...
  'wall_sides_stored_separately', ...
    ~strcmp(wall_plus.label,wall_minus.label), ...
  'material_collars_injective',material_plus.pass && material_minus.pass, ...
  'wall_collars_injective',wall_plus.pass && wall_minus.pass, ...
  'material_wall_disjoint',material_wall_disjoint, ...
  'material_cell_copies_disjoint',material_cell_copy_disjoint, ...
  'material_transverse_periodic_copies_disjoint', ...
    material_transverse_copy_disjoint, ...
  'wall_pair_disjoint',wall_pair_disjoint, ...
  'all_collars_disjoint',material_wall_disjoint && ...
    material_cell_copy_disjoint && material_transverse_copy_disjoint && ...
    wall_pair_disjoint, ...
  'all_rims_zero',material_plus.zero_rim && material_minus.zero_rim && ...
    wall_plus.zero_rim && wall_minus.zero_rim, ...
  'simultaneous_jump_label_list_complete',numel(lift_interfaces)==3 && ...
    numel(unique(lift_interfaces))==3 && ...
    sum(strcmp(lift_interfaces,'material-interface'))==1 && ...
    sum(contains(lift_interfaces,'wall'))==2, ...
  'simultaneous_jump_labels',{lift_interfaces}, ...
  'jump_correction_sign','J_all e = -a', ...
  'broken_energy_direct_sum',material_wall_disjoint && ...
    material_cell_copy_disjoint && material_transverse_copy_disjoint && ...
    wall_pair_disjoint);
position_abs = R*cosh(a);
g = struct('boundary_length',P,'speed_lower',R,'speed_upper',R, ...
  'mu_shift',double(z.mu_h),'constant_speed_parameterization',true, ...
  'constant_speed_certificate_pass',isequal(P,2*pi*R), ...
  'parameter_nodes',t,'arclength_nodes',s_nodes, ...
  'arclength_origin',0,'arclength_step',P/N, ...
  'constant_arclength_grid_pass',true, ...
  'arclength_partition_pass',P>0 && N>=2 && N==fix(N) && ...
    numel(s_nodes)==N && all(diff(s_nodes)>0) && s_nodes(1)==0, ...
  'position',position,'normal',normal,'speed_nodes',speed, ...
  'material_lift_collars',struct('plus',material_plus,'minus',material_minus), ...
  'wall_lift_collars',struct('plus',wall_plus,'minus',wall_minus), ...
  'lift_geometry_gates',lift_geometry_gates, ...
  'parameter_strip_width',a,'arclength_strip_width',R*a, ...
  'strip_speed_upper',R,'strip_position_abs_upper',position_abs, ...
  'strip_position_imag_upper',R*sinh(a), ...
  'real_displacement_abs_upper',[2*R,2*R], ...
  'displacement_abs_upper',[2*position_abs,2*position_abs], ...
  'displacement_real_upper',[2*position_abs,2*position_abs], ...
  'displacement_imag_upper',[2*R*sinh(a),2*R*sinh(a)], ...
  'target_normal_component_upper',cosh(a)*[1,1], ...
  'source_normal_component_upper',cosh(a)*[1,1], ...
  'left_clearance_lower',abs(double(z.X_L))-R, ...
  'right_clearance_lower',abs(double(z.X_R))-R, ...
  'strip_left_clearance_lower',abs(double(z.X_L))-position_abs, ...
  'strip_right_clearance_lower',abs(double(z.X_R))-position_abs, ...
  'strip_certificate_pass',abs(double(z.X_L))>position_abs && ...
    abs(double(z.X_R))>position_abs, ...
  'source_strip_certificate_pass',abs(double(z.X_L))>position_abs && ...
    abs(double(z.X_R))>position_abs, ...
  'target_strip_certificate_pass',abs(double(z.X_L))>position_abs && ...
    abs(double(z.X_R))>position_abs, ...
  'outward_normal_contract_pass',all(sum(position.*normal,2)>0), ...
  'parameter_grid_contract_pass',isequal(t,(0:N-1).'*(2*pi/N)), ...
  'certificate_authority','circle instance adapter; theorem shape general');
end

function side = LOCAL_collar_side(label,width,rho_upper,R)
theta = 1-width/R;
Theta = 1+width/R;
pass = width>0 && rho_upper>0 && theta>0;
side = struct('label',label,'width',width,'rho_upper',rho_upper, ...
  'curvature_upper',1/R,'theta_lower',theta,'Theta_upper',Theta, ...
  'zero_rim',pass,'pass',pass);
end

function side = LOCAL_flat_collar_side(label,width,rho_upper)
pass = width>0 && rho_upper>0;
side = struct('label',label,'width',width,'rho_upper',rho_upper, ...
  'curvature_upper',0,'theta_lower',1,'Theta_upper',1, ...
  'zero_rim',pass,'pass',pass);
end

%% ==================== Radius-only selection ====================
% Candidate centers are never evaluated and no inter-level drift is formed.

function selection = LOCAL_select_N(z,density,c)
candidate_count = numel(c.N_schedule);
radii = Inf(candidate_count,1);
analytic = false(candidate_count,1);
ledgers = cell(candidate_count,1);
for index = 1:candidate_count
  candidate = c;
  candidate.evaluation_node_count = c.N_schedule(index);
  candidate.evaluate_centers = false;
  g = LOCAL_circle_geometry(z,candidate);
  local = signed_local_center_v8(z,g,candidate,density);
  regular = signed_regular_image_v8(z,g,candidate,density);
  radii(index) = max(double(local.radius.val.total(:)) + ...
    double(regular.radius.val.total));
  analytic(index) = local.gates.pass && regular.gates.pass && ...
    mod(candidate.evaluation_node_count,2)==0 && ...
    candidate.evaluation_node_count>2*density.maximum_order && ...
    isfinite(radii(index)) && radii(index)>=0;
  ledgers{index} = struct('N',candidate.evaluation_node_count, ...
    'local',local.sf_ledger,'regular',regular.sf_ledger, ...
    'centers_evaluated',local.centers_evaluated || regular.centers_evaluated);
end
passing = find(analytic & radii<=c.node_radius_allocation,1,'first');
if isempty(passing)
  passing = find(analytic,1,'last');
  tightness = false;
else
  tightness = true;
end
if isempty(passing)
  error('I5v8Input:Selection','No source-size candidate is analytic.');
end
no_centers = all(cellfun(@(x) ~x.centers_evaluated,ledgers));
selection = struct('candidates',c.N_schedule(:), ...
  'maximum_node_radius',radii,'analytic_pass',analytic, ...
  'allocation',c.node_radius_allocation,'selected_index',passing, ...
  'selected_N',c.N_schedule(passing),'selected_radius',radii(passing), ...
  'tightness_pass',tightness,'candidate_ledgers',{ledgers}, ...
  'selection_owner','node source-rule plus kernel-series radius only', ...
  'center_drift_used',false,'candidate_centers_evaluated',~no_centers, ...
  'pass',analytic(passing) && no_centers && ...
    mod(c.N_schedule(passing),2)==0 && ...
    c.N_schedule(passing)>2*density.maximum_order);
end

%% ==================== RI bridge and material state assembly ====================
% RI-10--RI-18 are evaluated in the complete pre-G state space.

function bridge = LOCAL_bridge(c,r,L_total,g,z,configuration)
N = size(c,1);
m = size(c,2);
h = double(g.boundary_length)/N;
Q0 = complex(zeros(m,m));
Q1 = complex(zeros(m,m));
R0 = 0;
R1 = 0;
b_norm = zeros(N,1);
sigma = zeros(N,1);
for j = 1:N
  next = mod(j,N)+1;
  cj = c(j,:);
  ck = c(next,:);
  b = (ck-cj)/h;
  b_norm(j) = norm(b,2);
  sigma(j) = b_norm(j)+L_total;
  Q0 = Q0+h*((cj'*cj+ck'*ck)/3+(cj'*ck+ck'*cj)/6);
  Q1 = Q1+h*(b'*b);
  R0 = R0+h*(r(j)^2+r(j)*r(next)+r(next)^2)/3+ ...
    h^2*L_total*(r(j)+r(next))/3+2*h^3*L_total^2/15;
  R1 = R1+h*sigma(j)^2;
end
Q0 = (Q0+Q0')/2;
Q1 = (Q1+Q1')/2;
plus = g.material_lift_collars.plus;
minus = g.material_lift_collars.minus;
C0p = plus.Theta_upper/plus.width+plus.Theta_upper* ...
  sqrt(double(z.mu_h)*plus.rho_upper);
C0m = minus.Theta_upper/minus.width+minus.Theta_upper* ...
  sqrt(double(z.mu_h)*minus.rho_upper);
C1p = sqrt(plus.Theta_upper/plus.theta_lower);
C1m = sqrt(minus.Theta_upper/minus.theta_lower);
W0 = (C0p+C0m)/4;
W1 = (C1p+C1m)/4;
alpha = sqrt(double(z.mu_h));
a0 = W0+W1*alpha/2;
a1 = W1/(2*alpha);
H = a0*Q0+a1*Q1;
H = (H+H')/2;
R = sqrt(a0*R0+a1*R1);
finite_values = [r;L_total;R0;R1;W0;W1;alpha;a0;a1;R; ...
  real(Q0(:));imag(Q0(:));real(Q1(:));imag(Q1(:)); ...
  real(H(:));imag(H(:))];
gates = struct('periodic_seam_wraps_last_to_first',mod(N,N)+1==1 && ...
    size(c,1)==N && numel(r)==N && g.arclength_partition_pass && ...
    isequal(g.parameter_nodes,(0:N-1).'*(2*pi/N)), ...
  'periodic_geometry_contract', ...
    isequal(g.arclength_origin,0) && isequal(g.arclength_nodes(1),0) && ...
    isequal(g.arclength_step,h) && ...
    isequal(g.arclength_nodes,(0:N-1).'*h), ...
  'positive_uniform_panels',h>0 && isequal(h,g.boundary_length/N), ...
  'derivative_center_zero',true, ...
  'derivative_radius_global',isfinite(L_total) && L_total>=0, ...
  'RI_10_exact_scalars',isfinite(R0) && isfinite(R1) && R0>=0 && R1>=0, ...
  'RI_11_gram_construction',isequal(Q0,Q0') && isequal(Q1,Q1'), ...
  'psd_by_gram_construction',h>0 && a0>0 && a1>0 && ...
    isequal(H,(H+H')/2), ...
  'alpha_prefrozen',isequal(alpha,sqrt(double(z.mu_h))) && alpha>0 && ...
    strcmp(configuration.alpha_owner, ...
      'pre-frozen sqrt(mu_h); not selected by centers'), ...
  'ME_13_constants',all(isfinite([W0,W1,a0,a1])) && ...
    all([W0,W1,a0,a1]>0), ...
  'finite_nonnegative',all(isfinite(finite_values)) && ...
    all([r;L_total;R0;R1;W0;W1;alpha;a0;a1;R]>=0));
gates.pass = all(structfun(@(x) isequal(x,true),gates));
if ~gates.pass
  names = fieldnames(gates);
  for gate_index = 1:numel(names)
    if ~strcmp(names{gate_index},'pass') && ...
        ~isequal(gates.(names{gate_index}),true)
      fprintf(2,'FAILED_BRIDGE_GATE=%s\n',names{gate_index});
    end
  end
end
bridge = struct('panel_count',N,'panel_length',h,'center_nodes',c, ...
  'node_radius',r,'derivative_center',complex(zeros(N,m)), ...
  'derivative_radius',repmat(L_total,N,1), ...
  'chord_derivative_norm',b_norm,'sigma',sigma, ...
  'R0_squared',R0,'R1_squared',R1,'Q0',Q0,'Q1',Q1, ...
  'W0',W0,'W1',W1,'alpha',alpha,'a0',a0,'a1',a1, ...
  'H',H,'R',R,'gates',gates);
end

function material = LOCAL_material_energy(z,bridge,propagation,c)
H = double(bridge.H);
R = double(bridge.R);
central = LOCAL_phi(H,R,double(z.q_center));
finite = central^2;
entries = struct('label','center','energy_squared',central^2, ...
  'state_map_owner','base pre-G row; no G');
sides = {'minus','plus'};
tail = 0;
map_ledgers = cell(2,1);
for side_index = 1:2
  side = sides{side_index};
  G = double(z.(['G',side]));
  P = double(z.(['P',side]));
  state = double(z.(['c',side]));
  for n = 0:c.cell_cutoff-1
    y = G*state;
    value = LOCAL_phi(H,R,y);
    finite = finite+value^2;
    entries(end+1) = struct('label',sprintf('%s-cell-%d',side,n), ...
      'energy_squared',value^2, ...
      'state_map_owner','y=G*(P^n*c), G exactly once'); %#ok<AGROW>
    state = P*state;
  end
  Hside = G'*H*G;
  Rside = R*norm(G,2);
  omega = (sqrt(norm(Hside,2))+Rside)^2;
  side_tail = omega*propagation.(side).sum_power_squared_upper*norm(state,2)^2;
  tail = tail+side_tail;
  map_ledgers{side_index} = struct('side',side,'H_side',Hside, ...
    'R_side',Rside,'omega',omega,'tail_state_norm',norm(state,2), ...
    'tail_squared',side_tail,'G_owner_count',1);
end
all_values = [finite;tail;[entries.energy_squared].'];
state_maps_once = all(cellfun(@(x) x.G_owner_count==1,map_ledgers)) && ...
  numel(entries)==1+2*c.cell_cutoff;
material = struct('finite_squared',finite,'cell_tail_squared',tail, ...
  'state_entries',entries,'side_tail_ledger',{map_ledgers}, ...
  'gates',struct('state_maps_once',state_maps_once, ...
    'central_once',sum(strcmp({entries.label},'center'))==1, ...
    'all_n_ge_0_block_power',numel(entries)==1+2*c.cell_cutoff, ...
    'finite_nonnegative',isreal(all_values) && ...
      all(isfinite(all_values)) && all(all_values>=0), ...
    'pass',state_maps_once && numel(entries)==1+2*c.cell_cutoff && ...
      isreal(all_values) && all(isfinite(all_values)) && all(all_values>=0)));
end

function value = LOCAL_phi(H,R,x)
quadratic = real(x'*H*x);
if ~isfinite(quadratic) || quadratic<0
  error('I5v8Input:Quadratic','A bridge quadratic form is invalid.');
end
value = sqrt(quadratic)+R*norm(x,2);
end

function out = LOCAL_block_certificate(P,block_length)
P = double(P);
power = eye(size(P));
prefix = 0;
for j = 0:block_length-1
  prefix = prefix+norm(power,'fro')^2;
  power = P*power;
end
block = norm(power,'fro');
pass = isfinite(block) && block<1 && isfinite(prefix);
if pass
  total = prefix/(1-block^2);
else
  total = Inf;
end
out = struct('block_length',block_length,'block_norm_upper',block, ...
  'prefix_sum_upper',prefix,'sum_power_squared_upper',total,'pass',pass);
end

