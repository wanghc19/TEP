function identity = LOCAL_input_identity(artifact_path,curve_path)
expected_artifact = ...
  'bb502ed97bfda5d60bd653fcb9e75f67fe15e86e053e160750ed5a735280e1b3';
expected_curve = ...
  '1d4ecd0aa9e84fc37fb45ea7580b7e72a07afc7fd0d336faf772666e67807073';
artifact_sha256 = LOCAL_sha256(artifact_path);
curve_sha256 = LOCAL_sha256(curve_path);
identity = struct('algorithm','SHA-256 over exact input file bytes', ...
  'artifact_sha256',artifact_sha256,'curve_sha256',curve_sha256, ...
  'expected_artifact_sha256',expected_artifact, ...
  'expected_curve_sha256',expected_curve, ...
  'artifact_match',strcmp(artifact_sha256,expected_artifact), ...
  'curve_match',strcmp(curve_sha256,expected_curve));
identity.pass = identity.artifact_match && identity.curve_match;
if ~identity.pass
  error('I5v8Input:ScientificIdentity', ...
    'An explicit scientific input does not match the accepted module contract.');
end
end

function value = LOCAL_sha256(path)
digest = java.security.MessageDigest.getInstance('SHA-256');
fid = fopen(path,'rb');
if fid<0
  error('I5v8Input:DigestOpen','Cannot open an explicit scientific input.');
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
while true
  bytes = fread(fid,1048576,'*uint8');
  if isempty(bytes)
    break
  end
  digest.update(typecast(bytes(:),'int8'));
end
raw = typecast(digest.digest(),'uint8');
value = lower(reshape(dec2hex(raw,2).',1,[]));
end
