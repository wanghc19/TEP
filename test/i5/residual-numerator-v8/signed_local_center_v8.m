  L_tau4;L_zeta4;Q4]>=0);
gates = struct( ...
  'active_branch',strcmp(char(configuration.active_local_branch), ...
    'current-circle-value-convolution'), ...
  'circle_constant_speed',geometry.constant_speed_parameterization && ...
    isequal(double(geometry.speed_lower),R) && ...
    isequal(double(geometry.speed_upper),R) && ...
    isequal(double(geometry.boundary_length),2*pi*R) && ...
    geometry.parameter_grid_contract_pass && ...
    geometry.outward_normal_contract_pass, ...
  'signed_exterior_minus_interior_before_absolute',true, ...
  'source_jacobian_in_factors',true, ...
  'density_sign_zeta_minus_sigma',strcmp(char(density.coordinate), ...
    '[tau;zeta], zeta=-sigma'), ...
  'relative_panels_cover_period',panel_gate.cover_period, ...
  'mandatory_breaks',panel_gate.mandatory_breaks, ...
  'single_symmetric_diagonal_panel',panel_gate.single_diagonal, ...
  'midpoint_polynomial_enclosure',true, ...
  'factorial_ratio_tails_included',all(structfun(@isfinite,factor_tails)), ...
  'analytic_log_moment_upper',all(isfinite(log_moment)) && all(log_moment>=0), ...
  'density_half_open_support',isequal(orders,(-128:127).'), ...
  'density_parseval_frobenius',isfinite(L_tau4) && isfinite(L_zeta4), ...
  'identity_included_once',true, ...
  'replaces_only_value_Q4',true, ...
  'inactive_target_panel_not_used_as_evidence',target_panel_count>=1, ...
  'finite_nonnegative',finite_gate);
gates.pass = all(structfun(@(x) isequal(x,true),gates));
out = struct('branch','current-circle-value-convolution', ...
  'target_panel_count_inactive',target_panel_count, ...
  'base_relative_panel_count',relative_panel_count, ...
  'relative_panels',panels,'x_intervals',x_interval, ...
