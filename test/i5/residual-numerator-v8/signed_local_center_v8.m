  'Phi_tau',Phi_tau,'Phi_zeta',Phi_zeta, ...
  'L_tau4',L_tau4,'L_zeta4',L_zeta4,'Q4',Q4, ...
  'log_moment_method', ...
    'sine lower bound inside pi/3; length*log(4) coarse upper outside', ...
  'identity_owner','L_tau4 appears once in I5.1g-36d','gates',gates);
end

function [coefficients,tails] = LOCAL_signed_value_coefficients( ...
    R,outer,inner,global_tails)
logc = log(R^2);
dJ = outer.a-inner.a;
dJfirst = outer.jfirst-inner.jfirst;
W = logc*dJfirst/(4*pi)+outer.cfrak-inner.cfrak;
qe = (-logc/(4*pi)+outer.c0)*outer.a+outer.y/(2*pi);
qi = (-logc/(4*pi)+inner.c0)*inner.a+inner.y/(2*pi);
coefficients = struct( ...
  'F1_tau',[0;dJfirst/(8*pi)], ...
  'F2_tau',[0;W/2], ...
  'F1_zeta',R*dJ/(4*pi), ...
  'F2_zeta',-R*(qe-qi));
tails = struct('F1_tau',global_tails.D1, ...
  'F2_tau',global_tails.D2,'F1_zeta',global_tails.S1, ...
  'F2_zeta',global_tails.S2);
end

function [panels,gates] = LOCAL_relative_panels(base_count)
base_edges = linspace(-pi,pi,base_count+1).';
edges = unique(sort([base_edges;-pi;-pi/3;0;pi/3;pi]));
negative = edges(edges<0);
positive = edges(edges>0);
panels = [negative(1:end-1),negative(2:end); ...
  negative(end),positive(1);positive(1:end-1),positive(2:end)];
contiguous = panels(1,1)==-pi && panels(end,2)==pi && ...
  all(panels(1:end-1,2)==panels(2:end,1)) && all(panels(:,2)>panels(:,1));
mandatory = all(ismember([-pi;-pi/3;0;pi/3;pi],edges));
crossing = panels(:,1)<0 & panels(:,2)>0;
single_diagonal = sum(crossing)==1 && ...
  isequal(-panels(crossing,1),panels(crossing,2));
gates = struct('cover_period',contiguous, ...
  'mandatory_breaks',mandatory,'single_diagonal',single_diagonal);
end

function [x_lower,x_upper] = LOCAL_panel_x_interval(R,left,right)
if left<=0 && right>=0
  minimum_abs = 0;
else
  minimum_abs = min(abs(left),abs(right));
end
maximum_abs = max(abs(left),abs(right));
x_lower = 4*R^2*sin(minimum_abs/2)^2;
x_upper = 4*R^2*sin(maximum_abs/2)^2;
end

function upper = LOCAL_polynomial_panel_upper(coefficients,x_lower,x_upper)
midpoint = (x_lower+x_upper)/2;
radius = (x_upper-x_lower)/2;
degree = numel(coefficients)-1;
upper = 0;
for derivative_order = 0:degree
  derivative_at_midpoint = 0;
  for power = derivative_order:degree
    falling = exp(gammaln(power+1)-gammaln(power-derivative_order+1));
    derivative_at_midpoint = derivative_at_midpoint+ ...
      coefficients(power+1)*falling*midpoint^(power-derivative_order);
  end
  upper = upper+abs(derivative_at_midpoint)* ...
    radius^derivative_order/exp(gammaln(derivative_order+1));
end
end

function moment = LOCAL_log_moment(left,right)
if right<=0
  moment = LOCAL_positive_log_moment(-right,-left);
elseif left>=0
  moment = LOCAL_positive_log_moment(left,right);
else
  moment = LOCAL_positive_log_moment(0,-left)+ ...
    LOCAL_positive_log_moment(0,right);
end
end

function value = LOCAL_positive_log_moment(left,right)
threshold = pi/3;
inner_right = min(right,threshold);
value = 0;
if inner_right>left
  value = LOCAL_inner_log_primitive(inner_right)- ...
    LOCAL_inner_log_primitive(left);
end
outer_left = max(left,threshold);
if right>outer_left
  value = value+(right-outer_left)*log(4);
end
end

function value = LOCAL_inner_log_primitive(x)
if x==0
  value = 0;
else
  value = -2*(x*log(2*x/pi)-x);
end
end

%% ==================== Source, target, and high-mode radii ====================
% KR-17 and exact constant-speed DFT aliases supply finite p=4 constants.

function [radius, constants] = LOCAL_point_source_radius(S, geometry, N)
p = 4;
half = N / 2;
harmonic = sum(1 ./ (1:half - 1));
C_K = 2 * N^(-p) * (2 * harmonic + 2 / N) * ...
  (2^p + 2^(p - 1) / (p - 1)) + half^(-p - 1) + ...
  2 / p * half^(-p);
C_T = 2 * N^(-p) * (1 + 1 / (p - 1));
radius = S(1) * C_K + S(2) * C_T;
constants = struct('p', p, 'C_K', C_K, 'C_T', C_T, ...
  'harmonic_number', harmonic, ...
  'owner', 'RI local point source: S_val(1)*C_K+S_val(2)*C_T');
end

%% ==================== Streamed signed Kress centre ====================
% Blocks avoid forming a full N-by-N collection of every split kernel.

function [node_val, node_nor, series_val, series_nor, ledger] = ...
    LOCAL_streamed_nodes(z, geometry, configuration, density, outer, inner, ...
    tail, build_center)
N = double(configuration.evaluation_node_count);
R = double(z.R);
nodes = double(geometry.parameter_nodes(:));
orders = double(density.orders(:));
phase = exp(1i * nodes * orders.');
tau = phase * double(density.tau_coeff);
zeta = phase * double(density.zeta_coeff);
tau_prime = phase * ((1i * orders) .* double(density.tau_coeff));
state_count = size(tau, 2);
rvec = quad.quad_kress_rvec(N);
dt = 2 * pi / N;
block = double(configuration.target_block_size);
tau_norm = vecnorm(tau, 2, 2).';
zeta_norm = vecnorm(zeta, 2, 2).';
tau_prime_norm = vecnorm(tau_prime, 2, 2).';
delta1_val = tail.D1 * tau_norm + tail.S1 * zeta_norm;
delta2_val = tail.D2 * tau_norm + tail.S2 * zeta_norm;
delta1_nor = tail.A1cos * tau_norm + ...
  tail.C1 / R * tau_prime_norm + tail.D1 * zeta_norm;
delta2_nor = tail.A2cos * tau_norm + ...
  tail.C2 / R * tau_prime_norm + tail.D2 * zeta_norm;
P = double(geometry.boundary_length);
series_val = zeros(N, 1);
series_nor = zeros(N, 1);
for target = 1:N
  offset = mod((target - 1) - (0:N - 1), N) + 1;
  series_val(target) = sum(abs(double(rvec(offset))) .* delta1_val) + ...
    dt * sum(delta2_val);
  series_nor(target) = sum(abs(double(rvec(offset))) .* delta1_nor) + ...
    dt * sum(delta2_nor);
end
residues = mod(-(0:N - 1), N) + 1;
circulant_complete = isequal(sort(residues), 1:N) && ...
  numel(unique(residues)) == N;
tail_scalars = [tail.D1, tail.S1, tail.D2, tail.S2, ...
  tail.A1cos, tail.C1, tail.A2cos, tail.C2];
source_deltas = [delta1_val; delta2_val; delta1_nor; delta2_nor];
source_delta_nonnegative_finite = isreal(source_deltas) && ...
  all(isfinite(source_deltas(:))) && all(source_deltas(:) >= 0) && ...
  isequal(size(source_deltas), [4, N]);
tail_target_independent = isreal(tail_scalars) && ...
  all(isfinite(tail_scalars)) && all(tail_scalars >= 0) && ...
  source_delta_nonnegative_finite;
constant_arclength = geometry.constant_speed_parameterization && ...
  geometry.constant_speed_certificate_pass && ...
  geometry.constant_arclength_grid_pass && ...
  isequal(double(geometry.speed_lower), double(geometry.speed_upper)) && ...
  isequal(double(geometry.arclength_step), P / N);
node_val = complex(zeros(0, state_count));
node_nor = node_val;
if build_center
  node_val = complex(zeros(N, state_count));
  node_nor = node_val;
  for first = 1:block:N
    ids = first:min(first + block - 1, N);
    h = nodes(ids) - nodes.';
    x = 4 * R^2 * sin(h / 2).^2;
    pT = R^2 * sin(h);
    cosh_real = cos(h);
    [split, ~] = LOCAL_signed_splits( ...
      z, R, x, pT, cosh_real, outer, inner, tail);
    offset = mod((ids - 1).' - (0:N - 1), N) + 1;
    Rblock = rvec(offset);
    D = Rblock .* split.D1 + dt * split.D2;
    S = Rblock .* split.S1 + dt * split.S2;
    A = Rblock .* split.A1cos + dt * split.A2cos;
    C = Rblock .* (split.C1 / R) + dt * (split.C2 / R);
    node_val(ids, :) = tau(ids, :) + D * tau - S * zeta;
    node_nor(ids, :) = -zeta(ids, :) - A * tau - ...
      C * tau_prime + D * zeta;
  end
end
ledger = struct('series_delta_tail_only', true, ...
  'identity_included_once', true, 'target_blocks', ceil(N / block), ...
  'center_required', logical(build_center), ...
  'series_radius_val', series_val, 'series_radius_nor', series_nor, ...
  'delta1_sum_val', sum(delta1_val), 'delta2_sum_val', sum(delta2_val), ...
  'delta1_sum_nor', sum(delta1_nor), 'delta2_sum_nor', sum(delta2_nor), ...
  'pointwise_series_formula', ...
    'sum_j abs(rvec(i-j))*delta1(j)+(2*pi/N)*sum_j delta2(j)', ...
  'circulant_complete_residues', circulant_complete, ...
  'tail_scalar_target_independent', tail_target_independent, ...
  'source_delta_nonnegative_finite', source_delta_nonnegative_finite, ...
  'constant_speed_arclength', constant_arclength, ...
  'pointwise_series_pass', circulant_complete && ...
    tail_target_independent && constant_arclength && ...
    all(isfinite([series_val; series_nor])) && ...
    all([series_val; series_nor] >= 0), ...
  'exp_scalar_count', numel(phase), ...
  'target_phase_exp_scalar_count', 0, ...
  's0_phase_exp_scalar_count', 0, ...
  'trig_scalar_count', double(build_center) * 3 * N^2, ...
  'target_fft_calls', 0, 'batched_fft_calls', 0, ...
  'target_weight_applied', false, ...
  'finite_evaluation', 'ORACLE; sf/fp UNRESOLVED');
end

function [s, t] = LOCAL_signed_splits(z, R, x, pT, cosh_real, outer, inner, tail)
logc = log(R^2);
Je = LOCAL_polyval(outer.a, x);
Ji = LOCAL_polyval(inner.a, x);
Ye = LOCAL_polyval(outer.y, x);
Yi = LOCAL_polyval(inner.y, x);
Jfe = LOCAL_polyval(outer.jfirst, x);
Jfi = LOCAL_polyval(inner.jfirst, x);
Ce = LOCAL_polyval(outer.cfrak, x);
Ci = LOCAL_polyval(inner.cfrak, x);
qe = (-logc / (4 * pi) + outer.c0) * Je + Ye / (2 * pi);
qi = (-logc / (4 * pi) + inner.c0) * Ji + Yi / (2 * pi);
dJ = Je - Ji;
dJf = Jfe - Jfi;
W = logc * dJf / (4 * pi) + Ce - Ci;
s.S1 = -R * dJ / (4 * pi);
s.S2 = R * (qe - qi);
s.D1 = x .* dJf / (8 * pi);
s.D2 = x .* W / 2;
s.C1 = pT .* dJf / (4 * pi);
s.C2 = pT .* W;
Se1 = -R * Je / (4 * pi);
Si1 = -R * Ji / (4 * pi);
Se2 = R * qe;
Si2 = R * qi;
s.A1cos = (double(z.khat)^2 * Se1 - ...
  (sqrt(double(z.rho_disk)) * double(z.khat))^2 * Si1) .* cosh_real;
s.A2cos = (double(z.khat)^2 * Se2 - ...
  (sqrt(double(z.rho_disk)) * double(z.khat))^2 * Si2) .* cosh_real;
t = tail;
end

function values = LOCAL_polyval(coefficients, x)
values = complex(zeros(size(x)));
for j = numel(coefficients):-1:1
  values = values .* x + coefficients(j);
end
end
