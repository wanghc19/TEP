function out = signed_off_surface_v8(z,g,cfg)
%SIGNED_OFF_SURFACE_V8 Signed general-curve finite-Rayleigh action and tail data.
% Purpose:
%   Return raw value/normal actions at real target nodes and a complete
%   finite-Rayleigh first-arclength-derivative triangle upper.
% Based on:
%   LOCAL_off_surface_signed_center in the v2 builder, generalized to supplied
%   geometry, holomorphic normal bounds, and the arclength Fourier phase.
% Main changes:
%   No material target DFT is formed. No circle identity or old output is used.
%   There is no omitted source Rayleigh mode in the frozen support.
% Numerical goal:
%   CONDITIONAL_ON_EXACT_SPECIAL_FUNCTION_EVALUATION; sf/fp are UNRESOLVED.

orders=double(z.wall_orders_512(:));
assert(isequal(orders,(-256:255).'));
beta_m=double(z.beta)+2*pi*orders/double(z.d);
radicand=double(z.khat)^2-beta_m.^2;
gamma_m=sqrt(complex(radicand));
assert(all(abs(gamma_m)>0));
multiplier=1i./(2*gamma_m);
N=numel(g.parameter_nodes);
clearance=min(g.strip_left_clearance_lower,g.strip_right_clearance_lower);
assert(clearance>0 && g.parameter_strip_width>0 && ...
  g.strip_certificate_pass && g.outward_normal_contract_pass);
normal_upper=g.target_normal_component_upper;
growth=exp(abs(real(gamma_m))*g.strip_position_imag_upper+ ...
  abs(beta_m)*g.strip_position_imag_upper-imag(gamma_m)*clearance);
map_norm=vecnorm(double(z.xi_left_unit_512),2,2)+ ...
  vecnorm(double(z.xi_right_unit_512),2,2);
row_bound=abs(multiplier).*map_norm/sqrt(double(z.d)).*growth;
A0=sum(row_bound);
A1=sum(row_bound.*(abs(gamma_m)*normal_upper(1)+abs(beta_m)*normal_upper(2)));
state_count=size(z.xi_left_unit_512,2);
x=g.position(:,1); y=g.position(:,2);
nx=g.normal(:,1); ny=g.normal(:,2);
block=double(cfg.target_block_size);
value_nodes=complex(zeros(N,state_count));
normal_nodes=value_nodes;
for first=1:block:numel(orders)
  ids=first:min(first+block-1,numel(orders));
  beta_block=beta_m(ids);
  gamma_block=gamma_m(ids);
  multiplier_block=multiplier(ids);
  psi=exp(1i*y*beta_block.')/sqrt(double(z.d));
  phase_left=exp(1i*(x-double(z.X_L))*gamma_block.');
  phase_right=exp(1i*(double(z.X_R)-x)*gamma_block.');
  SL=(psi.*phase_left).*multiplier_block.';
  SR=(psi.*phase_right).*multiplier_block.';
  density_left=double(z.xi_left_unit_512(ids,:));
  density_right=double(z.xi_right_unit_512(ids,:));
  value_nodes=value_nodes+SL*density_left+SR*density_right;
  dSL=SL.*(nx*(1i*gamma_block).'+ny*(1i*beta_block).');
  dSR=SR.*(nx*(-1i*gamma_block).'+ny*(1i*beta_block).');
  normal_nodes=normal_nodes+dSL*density_left+dSR*density_right;
end
radius_val=struct('source',zeros(N,1),'total',zeros(N,1));
radius_nor=struct('source',zeros(N,1),'total',zeros(N,1));
gates=struct('nonwood',all(abs(gamma_m)>0), ...
  'outgoing',all(real(gamma_m)>=0 & imag(gamma_m)>=0), ...
  'positive_strip_clearance',clearance>0, ...
  'complete_frozen_source_support',isequal(orders,(-256:255).'), ...
  'strip_certificate',g.strip_certificate_pass && g.target_strip_certificate_pass, ...
  'outward_normal_contract',g.outward_normal_contract_pass, ...
  'parameter_grid_contract',g.parameter_grid_contract_pass, ...
  'source_mode_accumulation_streamed', ...
    double(cfg.target_block_size)==4, ...
  'material_target_dft_absent',true,'target_weight_not_applied',true, ...
  'source_quadrature_used',false,'finite_support_exact',true, ...
  'centers_evaluated',true, ...
  'nonnegative_radii',isreal([A0;A1]) && all([A0;A1]>=0), ...
  'finite',all(isfinite([A0;A1;value_nodes(:);normal_nodes(:)])));
gates.pass=gates.nonwood && gates.outgoing && gates.positive_strip_clearance && ...
  gates.complete_frozen_source_support && gates.finite && gates.nonnegative_radii && ...
  gates.strip_certificate && gates.outward_normal_contract && gates.parameter_grid_contract && ...
  gates.source_mode_accumulation_streamed && ...
  gates.material_target_dft_absent && gates.target_weight_not_applied && ...
  ~gates.source_quadrature_used && gates.finite_support_exact;
out=struct('nodes',struct('val',value_nodes,'nor',normal_nodes), ...
  'radius',struct('val',radius_val,'nor',radius_nor), ...
  'value_action_upper',A0,'first_arclength_derivative_upper',A1, ...
  'derivative_owner','finite Rayleigh q1 triangle bound with unit normal/tangent', ...
  'minimum_nonwood_margin',min(abs(radicand)), ...
  'gamma_abs_range',[min(abs(gamma_m)),max(abs(gamma_m))], ...
  'gates',gates,'delta_sf','UNRESOLVED','delta_fp','UNRESOLVED', ...
  'sf_ledger',struct('scope','one helper invocation', ...
    'erfc_expint_bessel_hankel_qpgreen_calls',0, ...
    'oracle_primitive_families',{{'exp','sqrt','log','log1p'}}, ...
    'rayleigh_sqrt_scalar_count',numel(gamma_m), ...
    'center_phase_exp_scalar_count',3*N*numel(orders), ...
    'target_phase_exp_scalar_count',0, ...
    's0_phase_exp_scalar_count',0, ...
    'value_fft_calls',0,'normal_fft_calls',0, ...
    'paired_fft_calls',0,'total_fft_calls',0,'batched_fft_calls',0, ...
    'source_mode_block_size',double(cfg.target_block_size), ...
    'target_mode_block_size',double(cfg.target_block_size), ...
    'source_mode_accumulation_streamed',true, ...
    'target_dft_calls',0,'target_weight_owner','absent for real-node bridge', ...
    'source_orders',[min(orders),max(orders)], ...
    'centers_evaluated',true));
assert(gates.pass,'I5v8Off:Gate','The off-surface certificate failed.');
end
