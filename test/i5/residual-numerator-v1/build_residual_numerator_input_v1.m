function geometry = LOCAL_circle_geometry(z, configuration)
R = double(z.R);
P = 2.0 * pi * R;
L = double(configuration.residual_mode_cutoff);
mu_shift = double(z.mu_h);
rho_inner = double(z.rho_disk);
collar_width = double(z.delta_c);
theta = 1.0 - collar_width / R;
Theta = 1.0 + collar_width / R;
if theta <= 0.0
  error('I51bInput:Collar', 'The material collar is not injective.');
end
xi_L = 2.0 * pi * L / P;
trace_tail_slope_lower = sqrt(theta / Theta) * ( ...
  tanh(collar_width * xi_L / sqrt(theta * Theta)) + ...
  tanh(collar_width * xi_L / sqrt(theta * Theta)));
I0 = 13.0 / 35.0;
I1 = 6.0 / 5.0;
cut_minus = 0.5;
cut_plus = -0.5;
tubular_C0 = abs(cut_minus)^2 * Theta * ( ...
  I1 / collar_width + mu_shift * rho_inner * collar_width * I0) + ...
  abs(cut_plus)^2 * Theta * ( ...
  I1 / collar_width + mu_shift * collar_width * I0);
tubular_C1 = (abs(cut_minus)^2 + abs(cut_plus)^2) * ...
  collar_width * I0 / theta;
N = double(configuration.evaluation_node_count);
strip_width = double(configuration.parameter_strip_width);
position_abs = R * cosh(strip_width);
position_imag = R * sinh(strip_width);
geometry = struct( ...
  'boundary_length', P, ...
  'speed_lower', R, ...
  'speed_upper', R, ...
  'speed_first_upper', 0.0, ...
  'speed_second_upper', 0.0, ...
  'speed_nodes', R * ones(N, 1), ...
  'reach_lower', R, ...
  'curvature_upper', 1.0 / R, ...
  'trace_tail_slope_lower', trace_tail_slope_lower, ...
  'tubular_C0', tubular_C0, ...
  'tubular_C1', tubular_C1, ...
  'parameter_strip_width', strip_width, ...
  'arclength_strip_width', R * strip_width, ...
  'strip_speed_upper', R, ...
  'strip_position_abs_upper', position_abs, ...
  'strip_position_imag_upper', position_imag, ...
  'displacement_abs_upper', 2.0 * position_abs * [1.0, 1.0], ...
  'displacement_imag_upper', 2.0 * position_imag * [1.0, 1.0], ...
  'displacement_real_upper', 2.0 * position_abs * [1.0, 1.0], ...
  'target_normal_component_upper', ...
    cosh(strip_width) * [1.0, 1.0], ...
  'source_normal_component_upper', ...
    cosh(strip_width) * [1.0, 1.0], ...
  'left_clearance_lower', abs(double(z.X_L)) - position_abs, ...
  'right_clearance_lower', abs(double(z.X_R)) - position_abs, ...
  'certificate_authority', ...
    'exact circle adapter for the shape-general KR theorem');
end

