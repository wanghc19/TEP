  coordinate(1), ...
  Ns(1) * coordinate(2) + Ns(2) * coordinate(3), ...
  Nt(1) * coordinate(2) + Nt(2) * coordinate(3), ...
  Nt(1) * Ns(1) * coordinate(4) + ...
    (Nt(1) * Ns(2) + Nt(2) * Ns(1)) * coordinate(5) + ...
    Nt(2) * Ns(2) * coordinate(6)];
end

function out = LOCAL_ewald_coordinate_bound(z, geometry, configuration)
kappa = double(z.khat);
d = double(z.d);
beta = double(z.beta);
h = configuration.ewald_split / d;
chi_E = (kappa * d / (2.0 * configuration.ewald_split))^2;
RX = geometry.displacement_abs_upper(1);
RY = geometry.displacement_abs_upper(2);
IX = geometry.displacement_imag_upper(1);
IY = geometry.displacement_imag_upper(2);
UX = geometry.displacement_real_upper(1);
UY = geometry.displacement_real_upper(2);
finite_images_and_reciprocal = LOCAL_ewald_finite_upper( ...
  kappa, beta, d, h, chi_E, RX, RY, IX, IY, UX, UY, configuration);
[reciprocal_tail, reciprocal_gate] = LOCAL_reciprocal_tail( ...
  kappa, beta, d, h, RX, IX, IY, UX, configuration.reciprocal_cutoff);
[image_tail, image_gate] = LOCAL_image_tail( ...
  d, h, chi_E, RX, RY, IX, IY, UY, configuration.image_cutoff);
[local_finite, local_tail, local_gate] = LOCAL_local_ewald_bound( ...
  h, chi_E, RX, RY, configuration);
finite = finite_images_and_reciprocal + local_finite;
tail = reciprocal_tail + image_tail + local_tail;
out = struct( ...
  'coordinate_order', {{'00', '10', '01', '20', '11', '02'}}, ...
  'finite', finite, ...
  'reciprocal_tail', reciprocal_tail, ...
  'omitted_image_tail', image_tail, ...
  'local_factorial_tail', local_tail, ...
  'retained_image_taylor_tail', zeros(1, 6), ...
  'tail', tail, ...
  'gate', struct( ...
    'reciprocal', reciprocal_gate, ...
    'image', image_gate, ...
    'local', local_gate, ...
    'M_T_absorbed_into_retained_full_image_radius', true, ...
    'pass', reciprocal_gate.pass && image_gate.pass && ...
      local_gate.pass && all(isfinite([finite, tail]))));
end

function upper = LOCAL_ewald_finite_upper( ...
    kappa, beta, d, h, chi_E, RX, RY, IX, IY, UX, UY, configuration)
upper = zeros(1, 6);
moments = [sqrt(pi) / 2.0, 0.5, sqrt(pi) / 4.0];
radial = [moments(1), ...
  2.0 * h^2 * RX * moments(1) + 2.0 * h * moments(2), ...
  (4.0 * h^4 * RX^2 + 2.0 * h^2) * moments(1) + ...
  8.0 * h^3 * RX * moments(2) + 4.0 * h^2 * moments(3)];
derivative_orders = [0, 0; 1, 0; 0, 1; 2, 0; 1, 1; 0, 2];
for mode = -(configuration.reciprocal_cutoff - 1.0): ...
    configuration.reciprocal_cutoff - 1.0
  transverse = beta + 2.0 * pi * mode / d;
  q_mode = sqrt(complex(transverse^2 - kappa^2));
  if real(q_mode) < 0.0 || ...
      (real(q_mode) == 0.0 && imag(q_mode) > 0.0)
    q_mode = -q_mode;
  end
  q_abs = abs(q_mode);
  if q_abs == 0.0
    upper(:) = Inf;
    return;
  end
  if isreal(q_mode) && q_mode >= 2.0 * h^2 * UX
    for index = 1:6
      r = derivative_orders(index, 1);
      s = derivative_orders(index, 2);
      upper(index) = upper(index) + radial(r + 1.0) / ...
        (d * sqrt(pi)) * abs(transverse)^s / q_mode * ...
        exp(-q_mode^2 / (4.0 * h^2) + ...
        h^2 * IX^2 + abs(transverse) * IY);
    end
  else
    u = q_abs / (2.0 * h) + h * RX;
    exp_u = exp(u^2);
    E0 = 1.0 + 2.0 * u * exp_u / sqrt(pi);
    E1 = 2.0 * exp_u / sqrt(pi);
    E2 = 4.0 * u * exp_u / sqrt(pi);
    exponential = exp(q_abs * RX + abs(transverse) * IY) / ...
      (2.0 * d * q_abs);
    F0 = exponential * E0;
    F1 = exponential * (q_abs * E0 + h * E1);
    F2 = exponential * (q_abs^2 * E0 + ...
      2.0 * q_abs * h * E1 + h^2 * E2);
    upper = upper + [F0, F1, abs(transverse) * F0, F2, ...
      abs(transverse) * F1, transverse^2 * F0];
  end
end
for image = [-(configuration.image_cutoff - 1.0):-1.0, ...
    1.0:configuration.image_cutoff - 1.0]
  u = h^2 * ((abs(image) * d - UY)^2 - IX^2 - IY^2);
  if u <= 0.0
    upper(:) = Inf;
    return;
  end
  H01 = exp(chi_E - u) / u;
  H2 = exp(chi_E - u) * (1.0 / u + 1.0 / u^2);
  zx = 2.0 * h^2 * RX;
  zy = 2.0 * h^2 * (abs(image) * d + RY);
  upper = upper + [H01, zx * H01, zy * H01, ...
    zx^2 * H2 + 2.0 * h^2 * H01, zx * zy * H2, ...
    zy^2 * H2 + 2.0 * h^2 * H01] / (4.0 * pi);
end
end

function [tail, gate] = LOCAL_reciprocal_tail( ...
    kappa, beta, d, h, RX, IX, IY, UX, reciprocal_cutoff)
step = 2.0 * pi / d;
moments = [sqrt(pi) / 2.0, 0.5, sqrt(pi) / 4.0];
radial = [moments(1), ...
  2.0 * h^2 * RX * moments(1) + 2.0 * h * moments(2), ...
  (4.0 * h^4 * RX^2 + 2.0 * h^2) * moments(1) + ...
  8.0 * h^3 * RX * moments(2) + 4.0 * h^2 * moments(3)];
tail = zeros(1, 6);
orders = [0, 0; 1, 0; 0, 1; 2, 0; 1, 1; 0, 2];
ratios = zeros(2, 3);
positive_gate = true;
side_sign = [-1.0, 1.0];
for side_index = 1:2
  transverse = step * reciprocal_cutoff + side_sign(side_index) * beta;
  q_first = sqrt(transverse^2 - kappa^2);
  positive_gate = positive_gate && transverse > kappa && ...
    q_first >= 2.0 * h^2 * UX;
  for s = 0:2
    ratios(side_index, s + 1.0) = ...
      (1.0 + step / transverse)^s * ...
      exp(-step * (2.0 * transverse + step) / ...
      (4.0 * h^2) + step * IY);
  end
  for index = 1:6
    r = orders(index, 1);
    s = orders(index, 2);
    first = transverse^s / q_first * ...
      exp(-q_first^2 / (4.0 * h^2) + transverse * IY);
    tail(index) = tail(index) + radial(r + 1.0) * ...
      exp(h^2 * IX^2) / (d * sqrt(pi)) * first / ...
      (1.0 - ratios(side_index, s + 1.0));
  end
end
gate = struct( ...
  'positive_first_omitted', positive_gate, ...
  'ratios', ratios, ...
  'pass', positive_gate && all(ratios(:) < 1.0));
end

function [tail, gate] = LOCAL_image_tail( ...
    d, h, chi_E, RX, RY, IX, IY, UY, image_cutoff)
u = h^2 * ((image_cutoff * d - UY)^2 - IX^2 - IY^2);
distance_upper = image_cutoff * d + RY;
ratios = zeros(1, 3);
S1 = zeros(1, 3);
S2 = zeros(1, 3);
for alpha = 0:2
  ratios(alpha + 1.0) = (1.0 + d / distance_upper)^alpha * ...
    exp(-h^2 * d * (2.0 * (image_cutoff * d - UY) + d));
  S1(alpha + 1.0) = 2.0 * distance_upper^alpha * exp(-u) / ...
    (u * (1.0 - ratios(alpha + 1.0)));
  S2(alpha + 1.0) = 2.0 * distance_upper^alpha * exp(-u) / ...
    (u^2 * (1.0 - ratios(alpha + 1.0)));
end
scale = exp(chi_E) / (4.0 * pi);
zx = 2.0 * h^2 * RX;
tail = scale * [S1(1), zx * S1(1), 2.0 * h^2 * S1(2), ...
  zx^2 * (S1(1) + S2(1)) + 2.0 * h^2 * S1(1), ...
  zx * 2.0 * h^2 * (S1(2) + S2(2)), ...
  (2.0 * h^2)^2 * (S1(3) + S2(3)) + ...
  2.0 * h^2 * S1(1)];
gate = struct( ...
  'first_u', u, 'ratios', ratios, ...
  'pass', image_cutoff * d > UY && u > 0.0 && all(ratios < 1.0));
end

function [finite, tail, gate] = LOCAL_local_ewald_bound( ...
    h, chi_E, RX, RY, configuration)
R0 = h^2 * (RX^2 + RY^2);
B = configuration.local_cauchy_radius_factor * R0;
cutoff = configuration.ewald_local_cutoff;
if B <= R0
  finite = Inf(1, 6);
  tail = finite;
  gate = struct('pass', false);
  return;
end
x = chi_E * B;
xQ = chi_E * (1.0 + B);
ratios = [x / (cutoff + 2.0)^2, ...
  B * (cutoff + 1.0) / (cutoff + 2.0)^2, ...
  x / (cutoff + 2.0)^2 * (1.0 + 1.0 / (cutoff + 2.0)), ...
  xQ * (cutoff + 1.0) / (cutoff + 2.0)^2];
harmonic = sum(1.0 ./ (1.0:cutoff + 1.0));
tau_J = x^(cutoff + 1.0) / ...
  (exp(2.0 * gammaln(cutoff + 2.0)) * (1.0 - ratios(1)));
tau_S = B^(cutoff + 1.0) / ((cutoff + 1.0) * ...
  exp(gammaln(cutoff + 2.0)) * (1.0 - ratios(2)));
tau_D = harmonic * x^(cutoff + 1.0) / ...
  (exp(2.0 * gammaln(cutoff + 2.0)) * (1.0 - ratios(3)));
tau_Q = xQ^(cutoff + 1.0) / ((1.0 + B) * ...
  (cutoff + 1.0) * exp(gammaln(cutoff + 2.0)) * ...
  (1.0 - ratios(4)));
c_eta = abs(log(chi_E) + 0.57721566490153286060 - 1i * pi);
tau_C = (tau_J * (exp(B) - 1.0 + c_eta) + ...
  exp(chi_E * B) * tau_S + exp(B) * tau_Q) / (4.0 * pi) + ...
  tau_D / (2.0 * pi);
L_derivative = [tau_C, tau_C / (B - R0), ...
  2.0 * tau_C / (B - R0)^2];
tail = LOCAL_radial_to_coordinate(L_derivative, h, RX, RY);

indices = 0:cutoff;
J_finite = sum((chi_E * B).^indices ./ ...
  exp(2.0 * gammaln(indices + 1.0)));
positive = 1:cutoff;
S_finite = sum(B.^positive ./ ...
  (positive .* exp(gammaln(positive + 1.0))));
harmonic_values = cumsum(1.0 ./ positive);
D_finite = sum(harmonic_values .* (chi_E * B).^positive ./ ...
  exp(2.0 * gammaln(positive + 1.0)));
Q_finite = 0.0;
for n = 1:cutoff
  inner = sum(exp(gammaln(n - (0:n - 1.0))) .* B.^(0:n - 1.0));
  Q_finite = Q_finite + chi_E^n / ...
    exp(2.0 * gammaln(n + 1.0)) * inner;
end
M_finite = J_finite * (S_finite + c_eta) / (4.0 * pi) + ...
  exp(B) * Q_finite / (4.0 * pi) + D_finite / (2.0 * pi);
finite_derivative = [M_finite, M_finite / (B - R0), ...
  2.0 * M_finite / (B - R0)^2];
finite = LOCAL_radial_to_coordinate( ...
  finite_derivative, h, RX, RY);
gate = struct( ...
  'local_z_radius', R0, ...
  'local_cauchy_radius', B, ...
  'ratios', ratios, ...
  'pass', all(ratios < 1.0) && all(isfinite([finite, tail])));
end

function coordinate = LOCAL_radial_to_coordinate(radial, h, RX, RY)
coordinate = [radial(1), ...
  2.0 * h^2 * RX * radial(2), ...
  2.0 * h^2 * RY * radial(2), ...
  4.0 * h^4 * RX^2 * radial(3) + 2.0 * h^2 * radial(2), ...
  4.0 * h^4 * RX * RY * radial(3), ...
  4.0 * h^4 * RY^2 * radial(3) + 2.0 * h^2 * radial(2)];
end

%% ==================== Off-surface and propagation certificates ====================
% These helpers enclose exact frozen Rayleigh actions and matrix powers.

function out = LOCAL_off_surface_zero_center_bound(z, geometry)
orders = (-256.0:255.0).';
beta_m = double(z.beta) + 2.0 * pi * orders / double(z.d);
radicand = double(z.khat)^2 - beta_m.^2;
gamma_m = sqrt(complex(radicand));
flip = imag(gamma_m) < 0.0 | ...
  (imag(gamma_m) == 0.0 & real(gamma_m) < 0.0);
gamma_m(flip) = -gamma_m(flip);
exact_wood = any(gamma_m == 0.0);
if size(z.xi_left_unit_512, 1) ~= numel(orders) || ...
    size(z.xi_right_unit_512, 1) ~= numel(orders)
  error('I51bInput:OffSurfaceShape', ...
    'A frozen Rayleigh map does not have the expected 512 rows.');
end
multiplier = 1i ./ (2.0 * gamma_m);
strip_imaginary = geometry.strip_position_imag_upper;
strip_tangent = geometry.strip_speed_upper * cosh( ...
  geometry.parameter_strip_width);
clearance = min(geometry.left_clearance_lower, ...
  geometry.right_clearance_lower);
A0 = 0.0;
A1 = 0.0;
for index = 1:numel(orders)
  map_norm = norm(double(z.xi_left_unit_512(index, :)), 2) + ...
    norm(double(z.xi_right_unit_512(index, :)), 2);
  row_norm = abs(multiplier(index)) * map_norm / sqrt(double(z.d));
  if imag(gamma_m(index)) == 0.0
    growth = exp((abs(gamma_m(index)) + abs(beta_m(index))) * ...
      strip_imaginary);
  else
    growth = exp(-imag(gamma_m(index)) * clearance + ...
      abs(beta_m(index)) * strip_imaginary);
  end
  normal_weight = (abs(gamma_m(index)) + abs(beta_m(index))) * ...
    strip_tangent / geometry.speed_lower;
  A0 = A0 + row_norm * growth;
  A1 = A1 + row_norm * growth * normal_weight;
end
P = geometry.boundary_length;
finite_values = [A0, A1, min(abs(radicand)), ...
  max(abs(multiplier))];
out = struct( ...
  'orders', orders, ...
  'transverse_wavenumber', beta_m, ...
  'rayleigh_wavenumber', gamma_m, ...
  'minimum_nonwood_margin', min(abs(radicand)), ...
  'maximum_inverse_multiplier', max(abs(multiplier)), ...
  'value_retained_row_radius', sqrt(P) * A0, ...
  'normal_retained_row_radius', sqrt(P) * A1, ...
  'value_strip_upper', A0, ...
  'normal_strip_upper', A1, ...
  'center', 'zero', ...
  'finite_support_exact_action_enclosed', true, ...
  'gate', struct( ...
    'outgoing_branch', all(real(gamma_m(radicand > 0.0)) > 0.0) && ...
      all(imag(gamma_m(radicand < 0.0)) > 0.0), ...
    'nonwood_and_inverse_wavenumber', ~exact_wood && ...
      all(isfinite(multiplier)), ...
    'positive_clearance', clearance > 0.0, ...
    'pass', ~exact_wood && clearance > 0.0 && ...
      all(isfinite(finite_values))));
end

function out = LOCAL_block_certificate(Pmatrix, block_length)
Pmatrix = double(Pmatrix);
power = eye(size(Pmatrix));
prefix = 0.0;
for index = 0:block_length - 1.0
  prefix = prefix + norm(power, 'fro')^2;
  power = Pmatrix * power;
end
block_norm_upper = norm(power, 'fro');
pass = block_norm_upper < 1.0 && isfinite(prefix);
if pass
  sum_power_squared_upper = prefix / (1.0 - block_norm_upper^2);
else
  sum_power_squared_upper = Inf;
end
out = struct( ...
  'block_length', block_length, ...
  'matrix_norm', 'Frobenius upper bound for spectral 2-norm', ...
  'block_norm_upper', block_norm_upper, ...
  'prefix_sum_upper', prefix, ...
  'sum_power_squared_upper', sum_power_squared_upper, ...
  'pass', pass);
end

function out = LOCAL_select_residual_cutoff( ...
    z, configuration, derivative, geometry, regular, off_surface, pm, pp)
candidates = [32.0, 64.0, 128.0, 256.0];
P = geometry.boundary_length;
R = double(z.R);
theta = 1.0 - double(z.delta_c) / R;
Theta = 1.0 + double(z.delta_c) / R;
C0 = geometry.tubular_C0;
C1 = geometry.tubular_C1;
state_sum = norm(double(z.q_center), 2)^2 + ...
  norm(double(z.Gminus), 'fro')^2 * pm.sum_power_squared_upper * ...
    norm(double(z.cminus), 2)^2 + ...
  norm(double(z.Gplus), 'fro')^2 * pp.sum_power_squared_upper * ...
    norm(double(z.cplus), 2)^2;
material_tail = Inf(size(candidates));
lifting_tail = Inf(size(candidates));
local_material = Inf(size(candidates));
local_lifting = Inf(size(candidates));
regular_material = Inf(size(candidates));
regular_lifting = Inf(size(candidates));
off_material = Inf(size(candidates));
off_lifting = Inf(size(candidates));
strip_ratio = exp(-4.0 * pi * geometry.arclength_strip_width / P);
for index = 1:numel(candidates)
  L = candidates(index);
  xi_L = 2.0 * pi * L / P;
  c_trace = sqrt(theta / Theta) * ( ...
    tanh(double(z.delta_c) * xi_L / sqrt(theta * Theta)) + ...
    tanh(double(z.delta_c) * xi_L / sqrt(theta * Theta)));
  local_material(index) = 2.0 * derivative.nor.Q2^2 / ...
    (P * c_trace) * (P / (2.0 * pi))^5 * ...
    (L^(-5.0) + L^(-4.0) / 4.0);
  local_lifting(index) = 2.0 * derivative.val.Q2^2 / P * ( ...
    C0 * (P / (2.0 * pi))^4 * ...
      (L^(-4.0) + L^(-3.0) / 3.0) + ...
    C1 * (P / (2.0 * pi))^2 * ...
      (L^(-2.0) + L^(-1.0)));
  d_scaled = double(z.delta_c) / sqrt(theta * Theta);
  trace_denominator = 2.0 * sqrt(theta / Theta) * ...
    tanh(xi_L * d_scaled);
  regular_material(index) = LOCAL_analytic_material_tail( ...
    regular.normal_strip_upper, P, trace_denominator, strip_ratio, L);
  off_material(index) = LOCAL_analytic_material_tail( ...
    off_surface.normal_strip_upper, P, trace_denominator, strip_ratio, L);
  regular_lifting(index) = LOCAL_analytic_lifting_tail( ...
    regular.value_strip_upper, P, C0, C1, strip_ratio, L);
  off_lifting(index) = LOCAL_analytic_lifting_tail( ...
    off_surface.value_strip_upper, P, C0, C1, strip_ratio, L);
  material_tail(index) = state_sum * (sqrt(local_material(index)) + ...
    sqrt(regular_material(index)) + sqrt(off_material(index)))^2;
  lifting_tail(index) = state_sum * (sqrt(local_lifting(index)) + ...
    sqrt(regular_lifting(index)) + sqrt(off_lifting(index)))^2;
end
passes = sqrt(material_tail) <= configuration.material_tail_tolerance & ...
  2.0 * sqrt(lifting_tail) <= configuration.lifting_tail_tolerance;
selected_index = find(passes, 1, 'first');
if isempty(selected_index)
  selected_L = candidates(end);
else
  selected_L = candidates(selected_index);
end
out = struct( ...
  'candidate_L', candidates, ...
  'material_tail_squared', material_tail, ...
  'lifting_tail_squared', lifting_tail, ...
  'local_material_squared', local_material, ...
  'regular_material_squared', regular_material, ...
  'off_surface_material_squared', off_material, ...
  'local_lifting_squared', local_lifting, ...
  'regular_lifting_squared', regular_lifting, ...
  'off_surface_lifting_squared', off_lifting, ...
  'state_sum_upper', state_sum, ...
  'selected_L', selected_L, ...
  'first_passing_candidate_index', selected_index, ...
  'tail_tolerance_pass', ~isempty(selected_index), ...
  'stopping_rule', ...
    'first candidate passing complete local+regular+off angular tails', ...
  'pass', all(isfinite([material_tail, lifting_tail])));
end

function squared = LOCAL_analytic_material_tail(A, P, denominator, r, L)
squared = P^2 * A^2 / (pi * denominator) * ...
  r^L / (L * (1.0 - r));
end

function squared = LOCAL_analytic_lifting_tail(A, P, C0, C1, r, L)
S0 = r^L / (1.0 - r);
S2 = r^L * (L^2 / (1.0 - r) + ...
  2.0 * L * r / (1.0 - r)^2 + ...
  r * (1.0 + r) / (1.0 - r)^3);
squared = 2.0 * P * A^2 * ( ...
  C0 * S0 + C1 * (2.0 * pi / P)^2 * S2);
end

function weights = LOCAL_material_weights(z, geometry, L)
ell = (-(L - 1.0):L - 1.0).';
P = geometry.boundary_length;
xi = 2.0 * pi * ell / P;
R = double(z.R);
h = double(z.delta_c);
theta = 1.0 - h / R;
Theta = 1.0 + h / R;
lambda_inner = sqrt(double(z.mu_h) * double(z.rho_disk) + ...
  xi.^2 / (theta * Theta));
lambda_outer = sqrt(double(z.mu_h) + xi.^2 / (theta * Theta));
trace = theta * lambda_inner .* tanh(h * lambda_inner) + ...
  theta * lambda_outer .* tanh(h * lambda_outer);
lifting = geometry.tubular_C0 + geometry.tubular_C1 * xi.^2;
if theta <= 0.0 || any(trace <= 0.0) || any(lifting <= 0.0)
  error('I51bInput:MaterialWeight', ...
    'A trace or tubular retained weight is nonpositive.');
end
weights = struct( ...
  'mode_orders', ell, ...
  'trace', trace, ...
  'material_inverse_trace', 1.0 ./ trace, ...
  'lifting', lifting);
end

