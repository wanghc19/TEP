function experiment_input = build_residual_numerator_input_v1( ...
    artifact_path, curve_contract_path, wall_finite_squared, ...
    wall_tail_squared, input_path, wall_provenance_label)
%BUILD_RESIDUAL_NUMERATOR_INPUT_V1 Build the I5.1b data-only input.
% Purpose:
%   Join the frozen reconstruction data to explicit accepted wall scalars and build
%   a conservative current-circle instance of the KR-15 local certificate.
% Input:
%   artifact_path  - Explicit frozen I3 certificate MAT path.
%   curve_contract_path - Explicit accepted circle curve-contract MAT path.
%   wall_finite_squared - Accepted nonnegative wall finite square.
%   wall_tail_squared - Accepted nonnegative wall omission-tail square.
%   input_path     - Explicit create-once MAT output path.
%   wall_provenance_label - Optional non-authorizing provenance text.
% Output:
%   experiment_input - Self-contained data contract for residual_numerator_v1.
% Main algorithm:
%   Verify the frozen density convention, form its finite Fourier coefficient
%   maps once, audit independent L/N separation, construct the local
%   power-series enclosure, and validate the explicit wall finite/tail datum.
% Based on:
%   (KR-2), (KR-8)--(KR-15), and the finite-input contract in s-kress-real.md.
% Main changes:
%   This version rejects the historical N=512, L=256 pairing and contains no
%   complex-strip/P32 gate.
% Numerical goal:
%   Produce the immutable input for one fail-closed I5.1b scientific run.

if nargin < 6 || isempty(wall_provenance_label)
  wall_provenance_label = 'UNSPECIFIED_NONAUTHORIZING_PROVENANCE';
end
[artifact_path, curve_contract_path, input_path] = ...
  LOCAL_paths(artifact_path, curve_contract_path, input_path);
[wall_finite_squared, wall_tail_squared, wall_provenance_label] = ...
  LOCAL_wall_inputs( ...
    wall_finite_squared, wall_tail_squared, wall_provenance_label);
loaded_artifact = load(artifact_path, 'staged');
loaded_curve = load(curve_contract_path, 'curve_contract');
if ~isfield(loaded_artifact, 'staged') || ...
    ~isfield(loaded_artifact.staged, 'certificate') || ...
    ~isfield(loaded_curve, 'curve_contract')
  error('I51bInput:Schema', ...
    'The frozen artifact or curve contract has the wrong top-level schema.');
end

z = loaded_artifact.staged.certificate;
curve_contract = loaded_curve.curve_contract;
LOCAL_validate_frozen(z);
curve_audit = LOCAL_validate_curve(z, curve_contract);

% --- stage 1: immutable frozen-density transform ---
source_node_count = size(z.eta_unit_256, 1) / 2.0;
density_orders = (-source_node_count / 2.0: ...
  source_node_count / 2.0 - 1.0).';
tau_native = double(z.eta_unit_256(1:source_node_count, :));
eta_second_native = double(z.eta_unit_256(source_node_count + 1.0:end, :));
tau_coeff_map = fftshift(fft(tau_native, [], 1), 1) / source_node_count;
eta_second_coeff_map = ...
  fftshift(fft(eta_second_native, [], 1), 1) / source_node_count;
density_fourier_degree = max(abs(density_orders));

% --- stage 2: independent residual and evaluation cutoffs ---
configuration = struct( ...
  'residual_mode_cutoff', 256.0, ...
  'evaluation_node_count', 1024.0, ...
  'derivative_order', 2.0, ...
  'kernel_series_cutoff', 32.0, ...
  'cell_cutoff', 16.0, ...
  'wall_lift_mode_cutoff', 256.0, ...
  'block_length', 32.0, ...
  'parameter_strip_width', 0.2, ...
  'ewald_split', 2.0, ...
  'reciprocal_cutoff', 5.0, ...
  'image_cutoff', 3.0, ...
  'ewald_local_cutoff', 18.0, ...
  'local_cauchy_radius_factor', 1.5, ...
  'material_tail_tolerance', 1.0e-6, ...
  'lifting_tail_tolerance', 1.0e-6, ...
  'retained_row_radius_tolerance', 1.0e-6);
L = double(configuration.residual_mode_cutoff);
N = double(configuration.evaluation_node_count);
strict_cutoff_pass = isfinite(L) && isfinite(N) && ...
  L == fix(L) && L >= 1.0 && ...
  N == fix(N) && mod(N, 2.0) == 0.0 && ...
  N > 2.0 * max(L, density_fourier_degree);
if ~strict_cutoff_pass
  error('I51bInput:CutoffGate', ...
    'The input must satisfy even N > 2*max(L,M_eta).');
end

% --- stage 3: conservative local real-variable certificate ---
local_certificate = LOCAL_circle_real_certificate( ...
  z, configuration, density_orders, tau_coeff_map, eta_second_coeff_map);
geometry = LOCAL_circle_geometry(z, configuration);
regular_certificate = LOCAL_regular_zero_center_bound( ...
  z, geometry, configuration, density_orders, ...
  tau_coeff_map, eta_second_coeff_map);
off_surface_certificate = LOCAL_off_surface_zero_center_bound( ...
  z, geometry);
propagation_minus = LOCAL_block_certificate( ...
  z.Pminus, configuration.block_length);
propagation_plus = LOCAL_block_certificate( ...
  z.Pplus, configuration.block_length);
cutoff_selection = LOCAL_select_residual_cutoff( ...
  z, configuration, local_certificate.derivative, geometry, ...
  regular_certificate, off_surface_certificate, ...
  propagation_minus, propagation_plus);
if cutoff_selection.pass
  configuration.residual_mode_cutoff = cutoff_selection.selected_L;
  L = cutoff_selection.selected_L;
  configuration.evaluation_node_count = ...
    2.0 * max(L, density_fourier_degree) + 2.0;
  N = configuration.evaluation_node_count;
  geometry = LOCAL_circle_geometry(z, configuration);
  local_certificate = LOCAL_circle_real_certificate( ...
    z, configuration, density_orders, tau_coeff_map, eta_second_coeff_map);
  regular_certificate = LOCAL_regular_zero_center_bound( ...
    z, geometry, configuration, density_orders, ...
    tau_coeff_map, eta_second_coeff_map);
  off_surface_certificate = LOCAL_off_surface_zero_center_bound(z, geometry);
end
strict_cutoff_pass = isfinite(L) && isfinite(N) && ...
  L == fix(L) && L >= 1.0 && ...
  N == fix(N) && mod(N, 2.0) == 0.0 && ...
  N > 2.0 * max(L, density_fourier_degree);
if ~strict_cutoff_pass
  error('I51bInput:SelectedCutoffGate', ...
    'The selected L must still satisfy even N > 2*max(L,M_eta).');
end
weights = LOCAL_material_weights(z, geometry, L);
[retained_assembly, tail_assembly] = LOCAL_material_assemblies( ...
  z, configuration, weights, density_orders, ...
  tau_coeff_map, eta_second_coeff_map, regular_certificate, ...
  off_surface_certificate, propagation_minus, propagation_plus, ...
  cutoff_selection);
[retained_assembly.lifting, wall_lift_tail] = ...
  LOCAL_wall_lift_assembly(z, configuration, geometry, density_orders, ...
  tau_coeff_map, eta_second_coeff_map, retained_assembly.lifting, ...
  propagation_minus, propagation_plus);
tail_assembly.lifting.disjoint_tail_squared = wall_lift_tail.disjoint_squared;
structural_audit = LOCAL_structural_audit( ...
  z, local_certificate, geometry, curve_audit, ...
  tau_coeff_map, eta_second_coeff_map, weights, ...
  retained_assembly, tail_assembly, regular_certificate, ...
  off_surface_certificate, wall_lift_tail, L, N, density_fourier_degree);
wall_module = struct( ...
  'finite_squared', wall_finite_squared, ...
  'tail_squared', wall_tail_squared, ...
  'source_kind', 'explicit_numeric_arguments', ...
  'source_scope', 'B_GAMMA_PM_ONLY', ...
  'provenance_label', wall_provenance_label, ...
  'provenance_authorizes_value', false);

% The complete data-only assembly remains subject to the independent
% pre-run review; every structural condition below is evaluated fail closed.
enclosure_bundle = struct( ...
  'schema', 'EPOST_I5_1B_ENCLOSURE_V1', ...
  'configuration', configuration, ...
  'geometry', geometry, ...
  'local_real_derivative_certificate', local_certificate.derivative, ...
  'local_rows', local_certificate.rows, ...
  'regular_zero_center_certificate', regular_certificate, ...
  'off_surface_zero_center_certificate', off_surface_certificate, ...
  'propagation_minus', propagation_minus, ...
  'propagation_plus', propagation_plus, ...
  'cutoff_selection', cutoff_selection, ...
  'wall_value_lift_certificate', wall_lift_tail, ...
  'retained_assembly', retained_assembly, ...
  'tail_assembly', tail_assembly, ...
  'wall_module', wall_module, ...
  'gates', struct( ...
    'artifact_scalar_match', structural_audit.artifact_scalar_match, ...
    'geometry_certificate', structural_audit.geometry_certificate, ...
    'parameterization_ccw_outward', ...
      curve_audit.parameterization_ccw_outward, ...
    'density_node_phase_match', curve_audit.density_node_phase_match, ...
    'density_sign_and_support', structural_audit.density_sign_and_support, ...
    'kr13_diagonal_safe', structural_audit.kr13_diagonal_safe, ...
    'kr15_full_torus_enclosure', ...
      structural_audit.kr15_full_torus_enclosure, ...
    'kr21_series_delta_enclosure', ...
      structural_audit.kr21_series_delta_enclosure, ...
    'local_operator_center_zero', structural_audit.local_operator_center_zero, ...
    'local_zero_center_full_series_enclosure', ...
      structural_audit.local_zero_center_full_series_enclosure, ...
    'identity_included_once', structural_audit.identity_included_once, ...
    'retained_tail_partition', structural_audit.retained_tail_partition, ...
    'complete_tail_cutoff_selected', cutoff_selection.pass, ...
    'normal_center_sign_local_minus_regular_minus_off_surface', ...
      structural_audit.normal_center_sign, ...
    'outgoing_branch', off_surface_certificate.gate.outgoing_branch, ...
    'nonwood_and_inverse_wavenumber', ...
      off_surface_certificate.gate.nonwood_and_inverse_wavenumber, ...
    'ewald_tail_gates', regular_certificate.gate.pass, ...
    'regular_center_zero_full_finite_enclosure', ...
      regular_certificate.gate.pass, ...
    'off_surface_enclosure', off_surface_certificate.gate.pass, ...
    'wall_module', all(isfinite([wall_module.finite_squared, ...
      wall_module.tail_squared])) && ...
      all([wall_module.finite_squared, wall_module.tail_squared] >= 0.0), ...
    'wall_value_lift', wall_lift_tail.gate.pass, ...
    'propagation_certificate', propagation_minus.pass && propagation_plus.pass, ...
    'tail_ownership_disjoint', structural_audit.tail_ownership_disjoint, ...
    'unqualified_special_functions_used', false, ...
    'sampled_maximum_used', false, ...
    'inter_level_drift_used', false, ...
    'empirical_safety_factor_used', false), ...
  'blocker', struct( ...
    'first', ...
      'NONE', ...
    'detail', ...
      'All structural inputs are generated; numeric gates decide eligibility.'), ...
  'provenance', struct( ...
    'local_adapter', ...
      'circle q-series instance of the shape-general KR theorem', ...
    'curve_contract_path', curve_contract_path, ...
    'curve_audit', curve_audit, ...
    'structural_audit', structural_audit, ...
    'wall_input_kind', 'explicit_numeric_arguments', ...
    'wall_provenance_label', wall_provenance_label, ...
    'eigenpair_solves', 0.0, ...
    'bie_density_solves', 0.0, ...
    'qz_decompositions', 0.0, ...
    'propagation_matrix_solves', 0.0));

% --- stage 4: data-only experiment contract ---
frozen = struct( ...
  'khat', double(z.khat), ...
  'mu_shift', double(z.mu_h), ...
  'beta_bloch', double(z.beta), ...
  'period_y', double(z.d), ...
  'circle_radius', double(z.R), ...
  'material_coefficient_inner', double(z.rho_disk), ...
  'density_coordinate', char(z.density_coordinate), ...
  'source_node_count', source_node_count, ...
  'density_orders', density_orders, ...
  'density_fourier_degree', density_fourier_degree, ...
  'tau_coeff_map', tau_coeff_map, ...
  'eta_second_coeff_map', eta_second_coeff_map);
if isfield(z, 'source_attempt')
  source_attempt = char(z.source_attempt);
else
  source_attempt = 'UNAVAILABLE_IN_FROZEN_SCHEMA';
end

experiment_input = struct( ...
  'schema', 'EPOST_I5_1B_INPUT_V1', ...
  'claim_scope', 'CONTINUOUS_RESIDUAL_NUMERATOR_ONLY', ...
  'certification_label', 'NON_CERTIFIED_ROUNDOFF_EXCLUDED', ...
  'frozen', frozen, ...
  'configuration', configuration, ...
  'strict_cutoff_pass', strict_cutoff_pass, ...
  'enclosure', enclosure_bundle, ...
  'provenance', struct( ...
    'artifact_path', artifact_path, ...
    'curve_contract_path', curve_contract_path, ...
    'wall_input_kind', 'explicit_numeric_arguments', ...
    'wall_provenance_label', wall_provenance_label, ...
    'source_attempt', source_attempt, ...
    'density_transform', ...
      'fftshift(fft(native_density))/N_eta; no midpoint phase', ...
    'eigenpair_solves', 0.0, ...
    'bie_density_solves', 0.0, ...
    'qz_decompositions', 0.0, ...
    'propagation_matrix_solves', 0.0));
save(input_path, 'experiment_input', '-v7.3');
end

