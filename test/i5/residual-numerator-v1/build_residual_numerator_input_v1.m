function [states, labels] = LOCAL_retained_states(z, cell_cutoff)
states = {double(z.q_center)};
labels = {'center'};
sides = {struct('name', 'minus', 'G', double(z.Gminus), ...
  'P', double(z.Pminus), 'c', double(z.cminus)), ...
  struct('name', 'plus', 'G', double(z.Gplus), ...
  'P', double(z.Pplus), 'c', double(z.cplus))};
for side_index = 1:2
  item = sides{side_index};
  state = item.c;
  for cell_index = 0:cell_cutoff - 1.0
    states{end + 1} = item.G * state; %#ok<AGROW>
    labels{end + 1} = sprintf('%s-cell-%d', ...
      item.name, cell_index); %#ok<AGROW>
    state = item.P * state;
  end
end
end

function out = LOCAL_expand_retained( ...
    identity_rows, states, state_labels, weight, ...
    regular_finite_unit, regular_tail_unit, off_surface_unit)
ell_count = size(identity_rows, 1);
state_count = numel(states);
mode_orders = repmat((-(ell_count - 1.0) / 2.0: ...
  (ell_count - 1.0) / 2.0).', state_count, 1);
center = complex(zeros(ell_count * state_count, 5));
self_multiplier = zeros(ell_count * state_count, 1);
regular_finite = zeros(size(self_multiplier));
regular_tail = zeros(size(self_multiplier));
off_surface = zeros(size(self_multiplier));
weight_factor = repmat(weight(:), state_count, 1);
row_labels = cell(ell_count * state_count, 1);
for state_index = 1:state_count
  rows = (state_index - 1.0) * ell_count + (1:ell_count);
  vector = states{state_index};
  vector_norm = norm(vector, 2);
  center(rows, 1) = identity_rows * vector;
  self_multiplier(rows) = vector_norm;
  regular_finite(rows) = regular_finite_unit * vector_norm;
  regular_tail(rows) = regular_tail_unit * vector_norm;
  off_surface(rows) = off_surface_unit * vector_norm;
  row_labels(rows) = repmat(state_labels(state_index), ell_count, 1);
end
out = struct( ...
  'mode_orders', mode_orders, ...
  'center_components', center, ...
  'component_labels', ...
    {{'local_identity', 'regular_zero', 'off_surface_zero', ...
    'flat_wall_finite', 'circle_to_wall_zero'}}, ...
  'state_labels', {row_labels}, ...
  'self_radius_multiplier', self_multiplier, ...
  'regular_finite_enclosure_radius', regular_finite, ...
  'regular_omission_radius', regular_tail, ...
  'off_surface_radius', off_surface, ...
  'other_radius', zeros(size(self_multiplier)), ...
  'weight_factor', weight_factor);
end

function out = LOCAL_low_cell_data( ...
    z, identity_rows, weight, regular_unit, off_surface_unit, pm, pp, J)
sides = {struct('name', 'minus', 'G', double(z.Gminus), ...
  'P', double(z.Pminus), 'c', double(z.cminus), 'cap', pm), ...
  struct('name', 'plus', 'G', double(z.Gplus), ...
  'P', double(z.Pplus), 'c', double(z.cplus), 'cap', pp)};
items = cell(2, 1);
for side_index = 1:2
  item = sides{side_index};
  tail_state = item.c;
  for cell_index = 1:J
    tail_state = item.P * tail_state;
  end
  items{side_index} = struct( ...
    'side', item.name, ...
    'identity_row_map', identity_rows * item.G, ...
    'state_map_norm_upper', norm(item.G, 'fro'), ...
    'regular_unit_radius', regular_unit, ...
    'off_surface_unit_radius', off_surface_unit, ...
    'weight_factor', weight(:), ...
    'tail_state_norm', norm(tail_state, 2), ...
    'sum_power_squared_upper', item.cap.sum_power_squared_upper);
end
out = vertcat(items{:});
end

function [lifting, tail] = LOCAL_wall_lift_assembly( ...
    z, configuration, geometry, density_orders, tau_coeff_map, ...
    eta_second_coeff_map, lifting, pm, pp)
M = double(configuration.wall_lift_mode_cutoff);
orders = (-M:M).';
beta_m = double(z.beta) + 2.0 * pi * orders / double(z.d);
gamma_m = sqrt(complex(double(z.khat)^2 - beta_m.^2));
flip = imag(gamma_m) < 0.0 | ...
  (imag(gamma_m) == 0.0 & real(gamma_m) < 0.0);
gamma_m(flip) = -gamma_m(flip);
if any(gamma_m == 0.0) || ...
    2.0 * pi * (M + 1.0) / double(z.d) - abs(double(z.beta)) <= ...
      double(z.khat)
  error('I51bInput:WallLiftBranch', ...
    'A retained or first omitted wall-lift mode fails the branch gate.');
end
wall_orders = double(z.wall_orders_512(:));
xi_left = LOCAL_embed_wall_rows( ...
  z.xi_left_unit_512, wall_orders, orders);
xi_right = LOCAL_embed_wall_rows( ...
  z.xi_right_unit_512, wall_orders, orders);
wall_input = double(z.wall_input_unit_512);
input_left = LOCAL_embed_wall_rows( ...
  wall_input(1:numel(wall_orders), :), wall_orders, orders);
input_right = LOCAL_embed_wall_rows( ...
  wall_input(numel(wall_orders) + 1.0:end, :), wall_orders, orders);
s0 = 1i ./ (2.0 * gamma_m);
cell_phase = exp(1i * gamma_m * (double(z.X_R) - double(z.X_L)));
base_left = input_left - s0 .* (xi_left + cell_phase .* xi_right);
base_right = input_right - s0 .* (cell_phase .* xi_left + xi_right);
circle_radius = LOCAL_circle_to_wall_radius( ...
  z, geometry, orders, beta_m, gamma_m, ...
  density_orders, tau_coeff_map, eta_second_coeff_map);
wall_weight = 6.0 / (5.0 * double(z.delta_w)) + ...
  13.0 * double(z.delta_w) / 35.0 * ...
  (beta_m.^2 + double(z.mu_h));
center_left = LOCAL_embed_wall_rows( ...
  z.center_left_value_mismatch, wall_orders, orders);
center_right = LOCAL_embed_wall_rows( ...
  z.center_right_value_mismatch, wall_orders, orders);

entries = cell(0, 1);
entries{end + 1} = LOCAL_wall_entry( ...
  center_left, zeros(size(circle_radius)), wall_weight, orders, ...
  'center-left');
entries{end + 1} = LOCAL_wall_entry( ...
  center_right, zeros(size(circle_radius)), wall_weight, orders, ...
  'center-right');
entries{end + 1} = LOCAL_wall_entry( ...
  base_left * (double(z.Gplus) * double(z.cplus)), ...
  circle_radius * norm(double(z.Gplus) * double(z.cplus), 2), ...
  wall_weight, orders, 'singleton-left-plus');
entries{end + 1} = LOCAL_wall_entry( ...
  base_right * (double(z.Gminus) * double(z.cminus)), ...
  circle_radius * norm(double(z.Gminus) * double(z.cminus), 2), ...
  wall_weight, orders, 'singleton-right-minus');
plus_state = double(z.cplus);
minus_state = double(z.cminus);
for cell_index = 0:configuration.cell_cutoff - 1.0
  entries{end + 1} = LOCAL_wall_state_entry( ...
    base_right, circle_radius, double(z.Gplus), plus_state, ...
    wall_weight, orders, sprintf('plus-right-%d', cell_index));
  entries{end + 1} = LOCAL_wall_state_entry( ...
    base_left, circle_radius, double(z.Gplus) * double(z.Pplus), ...
    plus_state, wall_weight, orders, sprintf('plus-left-%d', cell_index));
  entries{end + 1} = LOCAL_wall_state_entry( ...
    base_left, circle_radius, double(z.Gminus), minus_state, ...
    wall_weight, orders, sprintf('minus-left-%d', cell_index));
  entries{end + 1} = LOCAL_wall_state_entry( ...
    base_right, circle_radius, double(z.Gminus) * double(z.Pminus), ...
    minus_state, wall_weight, orders, sprintf('minus-right-%d', cell_index));
  plus_state = double(z.Pplus) * plus_state;
  minus_state = double(z.Pminus) * minus_state;
end
for index = 1:numel(entries)
  lifting = LOCAL_append_retained(lifting, entries{index});
end

omega_plus = LOCAL_wall_omega( ...
  base_right, circle_radius, double(z.Gplus), wall_weight) + ...
  LOCAL_wall_omega(base_left, circle_radius, ...
    double(z.Gplus) * double(z.Pplus), wall_weight);
omega_minus = LOCAL_wall_omega( ...
  base_left, circle_radius, double(z.Gminus), wall_weight) + ...
  LOCAL_wall_omega(base_right, circle_radius, ...
    double(z.Gminus) * double(z.Pminus), wall_weight);
low_squared = omega_plus * pp.sum_power_squared_upper * norm(plus_state, 2)^2 + ...
  omega_minus * pm.sum_power_squared_upper * norm(minus_state, 2)^2;
high_plus = LOCAL_wall_high_squared(z, geometry, tau_coeff_map, ...
  eta_second_coeff_map, double(z.Gplus), 'right', M) + ...
  LOCAL_wall_high_squared(z, geometry, tau_coeff_map, ...
  eta_second_coeff_map, double(z.Gplus) * double(z.Pplus), 'left', M);
high_minus = LOCAL_wall_high_squared(z, geometry, tau_coeff_map, ...
  eta_second_coeff_map, double(z.Gminus), 'left', M) + ...
  LOCAL_wall_high_squared(z, geometry, tau_coeff_map, ...
  eta_second_coeff_map, double(z.Gminus) * double(z.Pminus), 'right', M);
high_singleton = LOCAL_wall_high_squared(z, geometry, tau_coeff_map, ...
  eta_second_coeff_map, double(z.Gplus) * double(z.cplus), 'left', M) + ...
  LOCAL_wall_high_squared(z, geometry, tau_coeff_map, ...
  eta_second_coeff_map, double(z.Gminus) * double(z.cminus), 'right', M);
high_squared = high_plus * pp.sum_power_squared_upper * ...
  norm(double(z.cplus), 2)^2 + ...
  high_minus * pm.sum_power_squared_upper * ...
  norm(double(z.cminus), 2)^2 + high_singleton;
tail = struct( ...
  'low_mode_propagation_squared', low_squared, ...
  'high_mode_squared', high_squared, ...
  'disjoint_squared', [low_squared; high_squared], ...
  'first_omitted_absolute_mode', M + 1.0, ...
  'gate', struct('pass', all(isfinite([low_squared, high_squared]))));
end

function radius = LOCAL_circle_to_wall_radius( ...
    z, geometry, orders, beta_m, gamma_m, density_orders, ...
    tau_coeff_map, eta_second_coeff_map)
P = geometry.boundary_length;
A_tau = P * sum(vecnorm(tau_coeff_map, 2, 2));
A_sigma = P * sum(vecnorm(eta_second_coeff_map, 2, 2));
radius = zeros(size(orders));
clearance = min(geometry.left_clearance_lower, ...
  geometry.right_clearance_lower);
for index = 1:numel(orders)
  decay = exp(-imag(gamma_m(index)) * clearance);
  radius(index) = decay / ...
    (2.0 * abs(gamma_m(index)) * sqrt(double(z.d))) * ...
    ((abs(gamma_m(index)) + abs(beta_m(index))) * A_tau + A_sigma);
end
if numel(density_orders) ~= size(tau_coeff_map, 1) || ...
    any(~isfinite(radius))
  error('I51bInput:WallLiftRadius', ...
    'The circle-to-wall full-action radius is invalid.');
end
end

function entry = LOCAL_wall_state_entry( ...
    rows, radius, state_map, state, weight, orders, label)
mapped_state = state_map * state;
entry = LOCAL_wall_entry(rows * mapped_state, ...
  radius * norm(mapped_state, 2), weight, orders, label);
end

function entry = LOCAL_wall_entry(center, radius, weight, orders, label)
count = numel(orders);
components = complex(zeros(count, 5));
components(:, 4) = center;
entry = struct( ...
  'mode_orders', orders, ...
  'center_components', components, ...
  'state_labels', {repmat({label}, count, 1)}, ...
  'self_radius_multiplier', zeros(count, 1), ...
  'regular_finite_enclosure_radius', zeros(count, 1), ...
  'regular_omission_radius', zeros(count, 1), ...
  'off_surface_radius', zeros(count, 1), ...
  'other_radius', radius(:), ...
  'weight_factor', weight(:));
end

function out = LOCAL_append_retained(out, entry)
fields = {'mode_orders', 'center_components', 'state_labels', ...
  'self_radius_multiplier', 'regular_finite_enclosure_radius', ...
  'regular_omission_radius', 'off_surface_radius', 'other_radius', ...
  'weight_factor'};
for index = 1:numel(fields)
  name = fields{index};
  out.(name) = [out.(name); entry.(name)];
end
end

function omega = LOCAL_wall_omega(rows, radius, state_map, weight)
row_norm = vecnorm(rows * state_map, 2, 2) + ...
  radius * norm(state_map, 'fro');
omega = sum(weight .* row_norm.^2);
end

function squared = LOCAL_wall_high_squared( ...
    z, geometry, tau_coeff_map, eta_second_coeff_map, state_map, side, M)
if strcmp(side, 'left')
  clearance = geometry.left_clearance_lower;
elseif strcmp(side, 'right')
  clearance = geometry.right_clearance_lower;
else
  error('I51bInput:WallLiftSide', 'Wall side must be left or right.');
end
P = geometry.boundary_length;
A_tau = P * sum(vecnorm(tau_coeff_map * state_map, 2, 2));
A_sigma = P * sum(vecnorm(eta_second_coeff_map * state_map, 2, 2));
q0 = 2.0 * pi / double(z.d);
N_first = M + 1.0;
tN = q0 * N_first - abs(double(z.beta));
kappaN = sqrt(tN^2 - double(z.khat)^2);
r = exp(-2.0 * clearance * q0);
S0 = r^N_first / (1.0 - r);
S1 = r^N_first * (N_first / (1.0 - r) + ...
  r / (1.0 - r)^2);
S2 = r^N_first * (N_first^2 / (1.0 - r) + ...
  2.0 * N_first * r / (1.0 - r)^2 + ...
  r * (1.0 + r) / (1.0 - r)^3);
HN = (1.0 + tN / kappaN) * A_tau + A_sigma / kappaN;
C0 = 6.0 / (5.0 * double(z.delta_w)) + ...
  13.0 * double(z.delta_w) * double(z.mu_h) / 35.0;
C2 = 13.0 * double(z.delta_w) / 35.0;
squared = exp(2.0 * clearance * ...
  (double(z.khat) + abs(double(z.beta)))) * HN^2 / ...
  (2.0 * double(z.d)) * (C0 * S0 + C2 * ...
  (q0^2 * S2 + 2.0 * q0 * abs(double(z.beta)) * S1 + ...
  double(z.beta)^2 * S0));
end

function embedded = LOCAL_embed_wall_rows(values, source_orders, target_orders)
[present, indices] = ismember(source_orders, target_orders);
if ~all(present) || size(values, 1) ~= numel(source_orders)
  error('I51bInput:WallEmbedding', ...
    'A finite wall row is absent from the target order set.');
end
embedded = complex(zeros(numel(target_orders), size(values, 2)));
embedded(indices, :) = double(values);
end

function audit = LOCAL_structural_audit( ...
    z, local, geometry, curve_audit, tau_coeff_map, eta_second_coeff_map, ...
    weights, retained, tail, regular, off_surface, wall_lift, L, N, M_eta)
derivative_values = [ ...
  local.derivative.val.source_L1_p, ...
  local.derivative.val.target_diagonal_sup(:).', ...
  local.derivative.val.H_q, local.derivative.val.Q2, ...
  local.derivative.nor.source_L1_p, ...
  local.derivative.nor.target_diagonal_sup(:).', ...
  local.derivative.nor.H_q, local.derivative.nor.Q2, ...
  local.derivative.nor.delta_Ctan2_source_second_upper, ...
  local.derivative.nor.delta_Dstar2_source_second_upper];
density_values = [tau_coeff_map(:); eta_second_coeff_map(:)];
geometry_values = [geometry.boundary_length, geometry.speed_lower, ...
  geometry.speed_upper, geometry.reach_lower, geometry.curvature_upper, ...
  geometry.left_clearance_lower, geometry.right_clearance_lower];
row_values = [local.rows.val.series_delta_log_upper(:); ...
  local.rows.val.series_delta_smooth_upper(:); ...
  local.rows.nor.series_delta_log_upper(:); ...
  local.rows.nor.series_delta_smooth_upper(:)];
material_orders = unique(double(retained.material.mode_orders(:)));
material_expected = (-(L - 1.0):L - 1.0).';
identity_count = sum(strcmp(retained.material.component_labels, ...
  'local_identity')) == 1.0 && ...
  sum(strcmp(retained.lifting.component_labels, 'local_identity')) == 1.0;
tail_values = [tail.material.local_tail_multiplier; ...
  tail.material.regular_tail_norm; tail.material.off_surface_tail_norm; ...
  tail.lifting.local_tail_multiplier; tail.lifting.regular_tail_norm; ...
  tail.lifting.off_surface_tail_norm; ...
  tail.lifting.disjoint_tail_squared(:)];
scalar_scale = max(1.0, max(abs([double(z.mu_h), double(z.khat)^2])));
scalar_tolerance = 4096.0 * eps(scalar_scale);
mu_square_defect = abs(double(z.mu_h) - double(z.khat)^2);
audit = struct( ...
  'artifact_scalar_match', double(z.gamma) == double(z.mu_h) && ...
    mu_square_defect <= scalar_tolerance && double(z.khat) > 0.0 && ...
    double(z.d) > 0.0 && double(z.rho_disk) > 0.0, ...
  'mu_equals_khat_squared_defect', mu_square_defect, ...
  'ordinary_scalar_identity_tolerance', scalar_tolerance, ...
  'geometry_certificate', curve_audit.pass && ...
    all(isfinite(geometry_values)) && ...
    all(geometry_values([1:4, 6:7]) > 0.0) && ...
    double(z.delta_c) < geometry.reach_lower, ...
  'density_sign_and_support', ...
    strcmp(strtrim(char(z.density_coordinate)), ...
      '[tau;zeta], zeta=-sigma') && ...
    all(isfinite(density_values)) && M_eta == 128.0, ...
  'kr13_diagonal_safe', ...
    local.derivative.nor.cotangent_difference_cancelled_before_bound && ...
    local.series.all_ratio_gates_pass && ...
    all(isfinite(derivative_values(end - 1:end))), ...
  'kr15_full_torus_enclosure', all(isfinite(derivative_values)) && ...
    all(derivative_values >= 0.0) && local.series.all_ratio_gates_pass, ...
  'kr21_series_delta_enclosure', ...
    numel(row_values) == 4.0 * N^2 && all(isfinite(row_values)) && ...
    all(row_values >= 0.0), ...
  'local_operator_center_zero', ...
    contains(local.center_policy, 'identity-only'), ...
  'local_zero_center_full_series_enclosure', ...
    local.rows.val.full_operator_enclosed_in_series_radius && ...
    local.rows.nor.full_operator_enclosed_in_series_radius, ...
  'identity_included_once', identity_count, ...
  'retained_tail_partition', ...
    isequal(material_orders, material_expected) && ...
    max(abs(material_orders)) == L - 1.0, ...
  'normal_center_sign', strcmp(regular.center, 'zero') && ...
    strcmp(off_surface.center, 'zero'), ...
  'tail_ownership_disjoint', all(isfinite(tail_values)) && ...
    all(tail_values >= 0.0) && wall_lift.gate.pass, ...
  'strict_evaluation_separation', N > 2.0 * max(L, M_eta));
end
