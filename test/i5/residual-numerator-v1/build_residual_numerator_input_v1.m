density_weight = exp(strip_width * abs(orders));
tau_strip = sum(density_weight .* vecnorm(tau_coeff_map, 2, 2));
eta_second_strip = sum( ...
  density_weight .* vecnorm(eta_second_coeff_map, 2, 2));
path_length = 2.0 * pi * geometry.strip_speed_upper;
value_finite_upper = path_length * ( ...
  kernel_finite(2) * tau_strip + kernel_finite(1) * eta_second_strip);
value_tail_upper = path_length * ( ...
  kernel_tail(2) * tau_strip + kernel_tail(1) * eta_second_strip);
normal_finite_upper = path_length * ( ...
  kernel_finite(4) * tau_strip + kernel_finite(3) * eta_second_strip);
normal_tail_upper = path_length * ( ...
  kernel_tail(4) * tau_strip + kernel_tail(3) * eta_second_strip);
value_strip_upper = path_length * ( ...
  kernel_total(2) * tau_strip + kernel_total(1) * eta_second_strip);
normal_strip_upper = path_length * ( ...
  kernel_total(4) * tau_strip + kernel_total(3) * eta_second_strip);
P = geometry.boundary_length;
out = struct( ...
  'coordinate', coordinate, ...
  'kernel_order', {{'K00', 'K01-source', 'K10-target', 'K11'}}, ...
  'kernel_finite_upper', kernel_finite, ...
  'kernel_tail_upper', kernel_tail, ...
  'kernel_total_upper', kernel_total, ...
  'value_finite_row_radius', sqrt(P) * value_finite_upper, ...
  'value_ewald_tail_row_radius', sqrt(P) * value_tail_upper, ...
  'normal_finite_row_radius', sqrt(P) * normal_finite_upper, ...
  'normal_ewald_tail_row_radius', sqrt(P) * normal_tail_upper, ...
  'value_retained_row_radius', sqrt(P) * value_strip_upper, ...
  'normal_retained_row_radius', sqrt(P) * normal_strip_upper, ...
  'value_strip_upper', value_strip_upper, ...
  'normal_strip_upper', normal_strip_upper, ...
  'center', 'zero', ...
  'finite_special_function_called', false, ...
  'M_T_absorbed_into_retained_full_image_radius', true, ...
  'gate', coordinate.gate);
end

function kernel = LOCAL_contract_coordinate(coordinate, Nt, Ns)
