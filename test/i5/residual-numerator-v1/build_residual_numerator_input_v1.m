  'low_cell', LOCAL_low_cell_data( ...
    z, identity_normal, weights.material_inverse_trace, ...
    regular.normal_finite_row_radius + ...
      regular.normal_ewald_tail_row_radius, ...
    off_surface.normal_retained_row_radius, pm, pp, ...
    configuration.cell_cutoff));
lifting = struct( ...
  'local_tail_multiplier', sqrt(state_sum), ...
  'regular_tail_norm', sqrt(state_sum * ...
    cutoff_selection.regular_lifting_squared(selected)), ...
  'off_surface_tail_norm', sqrt(state_sum * ...
    cutoff_selection.off_surface_lifting_squared(selected)), ...
  'other_tail_norm', zeros(1, 0), ...
  'other_tail_labels', {cell(1, 0)}, ...
  'disjoint_tail_squared', zeros(0, 1), ...
  'low_cell', LOCAL_low_cell_data( ...
    z, identity_value, weights.lifting, ...
    regular.value_finite_row_radius + ...
      regular.value_ewald_tail_row_radius, ...
    off_surface.value_retained_row_radius, pm, pp, ...
    configuration.cell_cutoff));
tail = struct('material', material, 'lifting', lifting);
end

