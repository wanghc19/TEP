result = struct( ...
  'status', 'PRE_RUN_CERTIFICATE_STOP', ...
  'claim_scope', 'CONTINUOUS_RESIDUAL_NUMERATOR_ONLY', ...
  'certification_label', 'NON_CERTIFIED_ROUNDOFF_EXCLUDED', ...
  'roundoff_excluded', true, ...
  'reliability_certified', false, ...
  'configuration', input.configuration, ...
  'numerator_majorant', NaN, ...
  'B_Gamma_pm', NaN, ...
  'B_Upsilon', NaN, ...
  'B_lift', NaN, ...
  'gate_audit', gate_audit, ...
  'theorem_gate', struct( ...
    'structural_pass', false, ...
    'outward_rounding', false, ...
    'ordinary_roundoff_excluded_result_complete', false), ...
  'provenance', input.provenance, ...
  'resource', struct('elapsed_seconds_before_save', elapsed));
end

%% ==================== KR-16--KR-21 local radii ====================
% These helpers compute source, target, and finite-series radii separately.

function [out, constants] = LOCAL_local_radii( ...
    derivative, local_rows, geometry, ell, N)
p = 2.0;
half = N / 2.0;
harmonic = sum(1.0 ./ (1.0:half - 1.0));
C_K = 2.0 * N^(-p) * (2.0 * harmonic + 2.0 / N) * ...
  (2.0^p + 2.0^(p - 1.0) / (p - 1.0)) + ...
  half^(-p - 1.0) + 2.0 / p * half^(-p);
C_T = 2.0 * N^(-p) * (1.0 + 1.0 / (p - 1.0));
source_L1_p = double(derivative.source_L1_p(:).');
target_diagonal_sup = double(derivative.target_diagonal_sup);
identity_derivative = double(derivative.identity_derivative_upper(:).');
provided_H_q = double(derivative.H_q(:).');
if ~isequal(size(source_L1_p), [1, 2]) || ...
    ~isequal(size(target_diagonal_sup), [2, 3]) || ...
    ~isequal(size(identity_derivative), [1, 3]) || ...
    ~isequal(size(provided_H_q), [1, 3]) || ...
    any(~isfinite([source_L1_p, target_diagonal_sup(:).', ...
      identity_derivative, provided_H_q])) || ...
    any([source_L1_p, target_diagonal_sup(:).', ...
      identity_derivative, provided_H_q] < 0.0)
  error('I51b:KR15Shape', 'A KR-15 derivative array is invalid.');
end

derived_H_q = identity_derivative + ...
  8.0 * pi * log(2.0) * target_diagonal_sup(1, :) + ...
  2.0 * pi * target_diagonal_sup(2, :);
if any(provided_H_q < derived_H_q)
  error('I51b:KR18Gate', ...
    'The supplied H_q does not enclose the KR-18 expression.');
end
P = double(geometry.boundary_length);
s_lower = double(geometry.speed_lower);
s_upper = double(geometry.speed_upper);
s_first = double(geometry.speed_first_upper);
s_second = double(geometry.speed_second_upper);
if any(~isfinite([P, s_lower, s_upper, s_first, s_second])) || ...
    P <= 0.0 || s_lower <= 0.0 || s_upper <= 0.0 || ...
    s_first < 0.0 || s_second < 0.0
  error('I51b:GeometryBound', 'A speed or length bound is invalid.');
end

source_radius = 2.0 * pi * s_upper / sqrt(P) * ...
  (source_L1_p(1) * C_K + source_L1_p(2) * C_T);
xi = 2.0 * pi * ell / P;
Psi_second = s_second * provided_H_q(1) + ...
  2.0 * s_first * provided_H_q(2) + ...
  s_upper * provided_H_q(3) + ...
  abs(xi) .* (3.0 * s_upper * s_first * provided_H_q(1) + ...
  2.0 * s_upper^2 * provided_H_q(2)) + ...
  xi.^2 * s_upper^3 * provided_H_q(1);
zeta_two = pi^2 / 6.0;
target_radius = 4.0 * pi * zeta_two / (sqrt(P) * N^2) * ...
  Psi_second;
[series_radius, series_by_target] = LOCAL_series_radius( ...
  local_rows, geometry, N);
total_radius = source_radius + target_radius + series_radius;

out = struct( ...
  'mode_orders', ell, ...
  'source_radius', source_radius * ones(size(ell)), ...
  'target_radius', target_radius, ...
  'series_radius', series_radius * ones(size(ell)), ...
  'series_error_by_target', series_by_target, ...
  'total_radius', total_radius, ...
  'H_q_derived', derived_H_q, ...
  'H_q_used', provided_H_q, ...
  'Q2_provided', double(derivative.Q2), ...
  'identity_in_source_or_series_radius', false);
constants = struct('p', p, 'C_K', C_K, 'C_T', C_T, ...
  'zeta_two', zeta_two);
end

function [radius, error_by_target] = LOCAL_series_radius( ...
    local_rows, geometry, N)
delta_log = double(local_rows.series_delta_log_upper);
delta_smooth = double(local_rows.series_delta_smooth_upper);
if ~isequal(size(delta_log), [N, N]) || ...
    ~isequal(size(delta_smooth), [N, N]) || ...
    any(~isfinite([delta_log(:); delta_smooth(:)])) || ...
    any([delta_log(:); delta_smooth(:)] < 0.0)
  error('I51b:SeriesDelta', ...
    'The two N-by-N finite-series delta arrays are invalid.');
end
rvec = quad.quad_kress_rvec(N);
offset = mod((0:N - 1.0) - (0:N - 1.0).', N) + 1.0;
R = abs(rvec(offset));
dt = 2.0 * pi / N;
error_by_target = sum(R .* delta_log, 2) + ...
  dt * sum(delta_smooth, 2);
speed_nodes = double(geometry.speed_nodes(:));
P = double(geometry.boundary_length);
if numel(speed_nodes) ~= N || any(~isfinite(speed_nodes)) || ...
    any(speed_nodes <= 0.0)
  error('I51b:SpeedNodes', 'The target speed nodes are invalid.');
end
radius = 2.0 * pi / (N * sqrt(P)) * ...
  sum(speed_nodes .* error_by_target);
end

%% ==================== KR-22--KR-25 local tails ====================
% These helpers keep the omitted set exactly |ell| >= L.

function tail = LOCAL_local_tails(certificate, geometry, L)
P = double(geometry.boundary_length);
s_lower = double(geometry.speed_lower);
s_first = double(geometry.speed_first_upper);
normal_Q2_derived = 2.0 * pi * ( ...
  double(certificate.nor.H_q(3)) / s_lower + ...
  s_first * double(certificate.nor.H_q(2)) / s_lower^2);
value_Q2_derived = 2.0 * pi * ( ...
  double(certificate.val.H_q(3)) / s_lower + ...
  s_first * double(certificate.val.H_q(2)) / s_lower^2);
normal_Q2 = double(certificate.nor.Q2);
value_Q2 = double(certificate.val.Q2);
if normal_Q2 < normal_Q2_derived || value_Q2 < value_Q2_derived || ...
    any(~isfinite([normal_Q2, value_Q2]))
  error('I51b:KR22Gate', 'A supplied Q2 does not enclose KR-22.');
end
c_trace = double(geometry.trace_tail_slope_lower);
C0 = double(geometry.tubular_C0);
C1 = double(geometry.tubular_C1);
if any(~isfinite([c_trace, C0, C1])) || ...
    c_trace <= 0.0 || C0 < 0.0 || C1 < 0.0
  error('I51b:TailWeight', 'A trace or tubular tail constant is invalid.');
end
normal_squared = 2.0 * normal_Q2^2 / (P * c_trace) * ...
  (P / (2.0 * pi))^5 * (L^(-5.0) + L^(-4.0) / 4.0);
value_squared = 2.0 * value_Q2^2 / P * ( ...
  C0 * (P / (2.0 * pi))^4 * ...
    (L^(-4.0) + L^(-3.0) / 3.0) + ...
  C1 * (P / (2.0 * pi))^2 * ...
    (L^(-2.0) + L^(-1.0)));
tail = struct( ...
  'first_omitted_absolute_mode', L, ...
  'omitted_index_set', 'abs(ell)>=L', ...
  'normal_Q2_derived', normal_Q2_derived, ...
  'normal_Q2_used', normal_Q2, ...
  'normal_squared', normal_squared, ...
  'value_Q2_derived', value_Q2_derived, ...
  'value_Q2_used', value_Q2, ...
  'value_squared', value_squared);
end

%% ==================== KR-26--KR-32 assembly ====================
% These helpers combine centers before norms and same-defect tails before squares.

function out = LOCAL_retained_module(data, self_radius, ell, module_name)
required = {'mode_orders', 'center_components', 'component_labels', ...
  'self_radius_multiplier', 'regular_finite_enclosure_radius', ...
  'regular_omission_radius', 'off_surface_radius', 'other_radius', ...
  'weight_factor'};
if ~all(isfield(data, required))
  error('I51b:RetainedSchema', ...
    'The %s retained assembly is incomplete.', module_name);
end
mode_orders = double(data.mode_orders(:));
center_components = double(data.center_components);
labels = cellstr(data.component_labels);
count = numel(mode_orders);
arrays = {data.self_radius_multiplier, ...
  data.regular_finite_enclosure_radius, data.regular_omission_radius, ...
  data.off_surface_radius, data.other_radius, data.weight_factor};
if size(center_components, 1) ~= count || ...
    size(center_components, 2) ~= numel(labels) || ...
    numel(unique(labels)) ~= numel(labels) || ...
    any(cellfun(@numel, arrays) ~= count)
  error('I51b:RetainedShape', ...
    'The %s retained rows or labels have inconsistent sizes.', module_name);
end
self_multiplier = double(data.self_radius_multiplier(:));
regular_finite = double(data.regular_finite_enclosure_radius(:));
regular_omission = double(data.regular_omission_radius(:));
off_surface = double(data.off_surface_radius(:));
other = double(data.other_radius(:));
weight = double(data.weight_factor(:));
all_nonnegative = [self_multiplier; regular_finite; regular_omission; ...
  off_surface; other; weight];
if any(~isfinite([center_components(:); all_nonnegative])) || ...
    any(all_nonnegative < 0.0)
  error('I51b:RetainedFinite', ...
    'The %s retained enclosure contains an invalid value.', module_name);
end
[present, indices] = ismember(mode_orders, ell);
if any(~present & self_multiplier ~= 0.0)
  error('I51b:RetainedModeAssociation', ...
    ['A retained row outside the material mode set has a nonzero ', ...
    'local-self radius multiplier.']);
end
local_radius = zeros(size(self_multiplier));
local_radius(present) = self_multiplier(present) .* ...
  self_radius(indices(present));
combined_center = sum(center_components, 2);
total_radius = local_radius + regular_finite + regular_omission + ...
  off_surface + other;
summand = weight .* (abs(combined_center) + total_radius).^2;
out = struct( ...
  'mode_orders', mode_orders, ...
  'component_labels', {labels}, ...
  'combined_center', combined_center, ...
  'local_source_target_series_radius', local_radius, ...
  'regular_finite_center_zero_radius', regular_finite, ...
  'regular_omission_radius', regular_omission, ...
  'off_surface_radius', off_surface, ...
  'other_radius', other, ...
  'total_radius', total_radius, ...
  'weight_factor', weight, ...
  'summand', summand, ...
  'finite_squared', sum(summand), ...
  'centers_combined_before_absolute_value', true);
end

function out = LOCAL_tail_module( ...
    data, local_unit_squared, self_radius, module_name)
required = {'local_tail_multiplier', 'regular_tail_norm', ...
  'off_surface_tail_norm', 'other_tail_norm', ...
  'other_tail_labels', 'disjoint_tail_squared', 'low_cell'};
if ~all(isfield(data, required))
  error('I51b:TailSchema', ...
    'The %s tail assembly is incomplete.', module_name);
end
local_multiplier = double(data.local_tail_multiplier(:));
regular = double(data.regular_tail_norm(:));
off_surface = double(data.off_surface_tail_norm(:));
other = double(data.other_tail_norm);
labels = cellstr(data.other_tail_labels);
disjoint = double(data.disjoint_tail_squared(:));
count = numel(local_multiplier);
if numel(regular) ~= count || numel(off_surface) ~= count || ...
    size(other, 1) ~= count || size(other, 2) ~= numel(labels) || ...
    numel(unique(labels)) ~= numel(labels) || ...
    any(~isfinite([local_multiplier; regular; off_surface; ...
      other(:); disjoint])) || ...
    any([local_multiplier; regular; off_surface; other(:); disjoint] < 0.0)
  error('I51b:TailShape', ...
    'The %s tail groups or labels are invalid.', module_name);
end
local = sqrt(local_unit_squared) * local_multiplier;
same_defect_norm = local + regular + off_surface + sum(other, 2);
same_defect_squared = same_defect_norm.^2;
low_cell_squared = LOCAL_low_cell_tail( ...
  data.low_cell, self_radius, module_name);
out = struct( ...
  'local_fourier_norm', local, ...
  'regular_ewald_norm', regular, ...
  'off_surface_norm', off_surface, ...
  'other_norm', other, ...
  'other_labels', {labels}, ...
  'same_defect_norm', same_defect_norm, ...
  'same_defect_squared', same_defect_squared, ...
  'low_mode_propagation_tail_squared', low_cell_squared, ...
  'disjoint_tail_squared', disjoint, ...
  'tail_squared', sum(same_defect_squared) + ...
    low_cell_squared + sum(disjoint), ...
  'norms_added_before_squaring', true);
end

function squared = LOCAL_low_cell_tail(data, self_radius, module_name)
if ~isstruct(data) || isempty(data)
  error('I51b:LowCellSchema', ...
    'The %s low-cell certificate is absent.', module_name);
end
self_radius = double(self_radius(:));
squared = 0.0;
for side_index = 1:numel(data)
  item = data(side_index);
  required = {'identity_row_map', 'state_map_norm_upper', ...
    'regular_unit_radius', 'off_surface_unit_radius', ...
    'weight_factor', 'tail_state_norm', ...
    'sum_power_squared_upper'};
  if ~all(isfield(item, required))
    error('I51b:LowCellSchema', ...
      'A %s low-cell side is incomplete.', module_name);
  end
  identity_norm = vecnorm(double(item.identity_row_map), 2, 2);
  weight = double(item.weight_factor(:));
  map_norm = double(item.state_map_norm_upper);
  row_norm = identity_norm + map_norm * (self_radius + ...
    double(item.regular_unit_radius) + ...
    double(item.off_surface_unit_radius));
  values = [identity_norm; weight; map_norm; ...
    double(item.regular_unit_radius); ...
    double(item.off_surface_unit_radius); ...
    double(item.tail_state_norm); ...
    double(item.sum_power_squared_upper)];
  if numel(identity_norm) ~= numel(self_radius) || ...
      numel(weight) ~= numel(self_radius) || ...
      any(~isfinite(values)) || any(values < 0.0)
    error('I51b:LowCellFinite', ...
      'A %s low-cell side has invalid values.', module_name);
  end
  omega = sum(weight .* row_norm.^2);
  squared = squared + omega * ...
    double(item.sum_power_squared_upper) * ...
    double(item.tail_state_norm)^2;
end
end
