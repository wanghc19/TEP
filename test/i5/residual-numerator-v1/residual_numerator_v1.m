function result = residual_numerator_v1(input_path, output_path)
%RESIDUAL_NUMERATOR_V1 Assemble the I5.1b residual-numerator enclosure.
% Purpose:
%   Instantiate (KR-16)--(KR-32) from complete real-variable derivative and
%   nonlocal enclosure data, with every missing theorem input failing closed.
% Input:
%   input_path  - Explicit self-contained I5.1b input MAT path.
%   output_path - Explicit create-once result MAT path.
% Output:
%   result      - Three residual modules, their decomposition, and all gates.
% Main algorithm:
%   Compute the Kress source radius, target DFT radius, series radius, and
%   local Fourier tails; combine signed retained centers before absolute
%   values; add same-defect tail norms before squaring; then add the wall,
%   material-normal, and complete lifting modules.
% Based on:
%   (KR-15)--(KR-32) in s-kress-real.md.
% Main changes:
%   The failed complex-strip/P32 gate is absent.  L and N are independent,
%   and finite regular-image enclosures are not misclassified as omissions.
% Numerical goal:
%   Return a drift-free ordinary floating-point upper-bound display when all
%   mathematical gates pass, otherwise persist an explicit fail-closed stop.
% Notes:
%   Floating-point rounding is excluded.  No sampled maximum is a theorem
%   input, and no frozen eigenpair, density, QZ, or propagation solve occurs.

timer = tic;
[input_path, output_path] = LOCAL_paths(input_path, output_path);
loaded = load(input_path, 'experiment_input');
if ~isfield(loaded, 'experiment_input')
  error('I51b:Schema', 'The input MAT file lacks experiment_input.');
end
input = loaded.experiment_input;
LOCAL_validate_top_level(input);

% --- stage 1: fail-closed theorem preflight ---
gate_audit = LOCAL_gate_audit(input);
if ~gate_audit.pass
  result = LOCAL_stopped_result(input, gate_audit, toc(timer));
  save(output_path, 'result', '-v7.3');
  return;
end

% --- stage 2: KR-16--KR-21 retained local-row radii ---
configuration = input.configuration;
geometry = input.enclosure.geometry;
certificate = input.enclosure.local_real_derivative_certificate;
L = double(configuration.residual_mode_cutoff);
N = double(configuration.evaluation_node_count);
ell = (-(L - 1.0):L - 1.0).';
[value_local, kress_constants] = LOCAL_local_radii( ...
  certificate.val, input.enclosure.local_rows.val, geometry, ell, N);
[normal_local, ~] = LOCAL_local_radii( ...
  certificate.nor, input.enclosure.local_rows.nor, geometry, ell, N);

% --- stage 3: KR-22--KR-25 omitted local Fourier tails ---
local_tail = LOCAL_local_tails( ...
  certificate, geometry, L);

% --- stage 4: KR-26--KR-32 disjoint finite-plus-tail assembly ---
material_finite = LOCAL_retained_module( ...
  input.enclosure.retained_assembly.material, normal_local.total_radius, ...
  ell, 'material');
lifting_finite = LOCAL_retained_module( ...
  input.enclosure.retained_assembly.lifting, value_local.total_radius, ...
  ell, 'lifting');
material_tail = LOCAL_tail_module( ...
  input.enclosure.tail_assembly.material, ...
  local_tail.normal_squared, normal_local.total_radius, 'material');
lifting_tail = LOCAL_tail_module( ...
  input.enclosure.tail_assembly.lifting, ...
  local_tail.value_squared, value_local.total_radius, 'lifting');

wall = input.enclosure.wall_module;
B_Gamma_pm = sqrt(double(wall.finite_squared) + ...
  double(wall.tail_squared));
B_Upsilon = sqrt(material_finite.finite_squared + ...
  material_tail.tail_squared);
B_lift = 2.0 * sqrt(lifting_finite.finite_squared + ...
  lifting_tail.tail_squared);
numerator_majorant = B_Gamma_pm + B_Upsilon + B_lift;

material_tail_pass = sqrt(material_tail.tail_squared) <= ...
  double(configuration.material_tail_tolerance);
lifting_tail_pass = 2.0 * sqrt(lifting_tail.tail_squared) <= ...
  double(configuration.lifting_tail_tolerance);
retained_radius_maximum = max([material_finite.total_radius; ...
  lifting_finite.total_radius]);
retained_radius_pass = retained_radius_maximum <= ...
  double(configuration.retained_row_radius_tolerance);
if material_tail_pass && lifting_tail_pass && retained_radius_pass
  status = 'COMPLETE_RESIDUAL_NUMERATOR_ORDINARY';
elseif ~retained_radius_pass
  status = 'RETAINED_RADIUS_TOLERANCE_FAILED_ORDINARY';
else
  status = 'EXPLICIT_REMAINDER_TOLERANCE_FAILED_ORDINARY';
end

workspace = whos;
result = struct( ...
  'status', status, ...
  'claim_scope', 'CONTINUOUS_RESIDUAL_NUMERATOR_ONLY', ...
  'certification_label', 'NON_CERTIFIED_ROUNDOFF_EXCLUDED', ...
  'roundoff_excluded', true, ...
  'reliability_certified', false, ...
  'configuration', configuration, ...
  'kress_constants', kress_constants, ...
  'local_value', value_local, ...
  'local_normal', normal_local, ...
  'local_fourier_tail', local_tail, ...
  'cutoff_selection', input.enclosure.cutoff_selection, ...
  'regular_zero_center_certificate', ...
    input.enclosure.regular_zero_center_certificate, ...
  'off_surface_zero_center_certificate', ...
    input.enclosure.off_surface_zero_center_certificate, ...
  'propagation_minus', input.enclosure.propagation_minus, ...
  'propagation_plus', input.enclosure.propagation_plus, ...
  'wall_value_lift_certificate', ...
    input.enclosure.wall_value_lift_certificate, ...
  'retained_radius_audit', struct( ...
    'local_value_source_maximum', max(value_local.source_radius), ...
    'local_value_target_maximum', max(value_local.target_radius), ...
    'local_value_zero_center_series_maximum', ...
      max(value_local.series_radius), ...
    'local_normal_source_maximum', max(normal_local.source_radius), ...
    'local_normal_target_maximum', max(normal_local.target_radius), ...
    'local_normal_zero_center_series_maximum', ...
      max(normal_local.series_radius), ...
    'material_complete_maximum', max(material_finite.total_radius), ...
    'lifting_complete_maximum', max(lifting_finite.total_radius), ...
    'maximum', retained_radius_maximum, ...
    'tolerance', double(configuration.retained_row_radius_tolerance), ...
    'pass', retained_radius_pass), ...
  'wall', struct( ...
    'finite_squared', double(wall.finite_squared), ...
    'tail_squared', double(wall.tail_squared), ...
    'bound', B_Gamma_pm), ...
  'B_Gamma_pm', B_Gamma_pm, ...
  'material', struct( ...
    'finite', material_finite, ...
    'tail', material_tail, ...
    'bound', B_Upsilon, ...
    'tail_tolerance_pass', material_tail_pass), ...
  'B_Upsilon', B_Upsilon, ...
  'lifting', struct( ...
    'finite', lifting_finite, ...
    'tail', lifting_tail, ...
    'bound', B_lift, ...
    'factor_two_applied_once', true, ...
    'tail_tolerance_pass', lifting_tail_pass), ...
  'B_lift', B_lift, ...
  'numerator_majorant', numerator_majorant, ...
  'component_share', struct( ...
    'B_Gamma_pm', B_Gamma_pm / numerator_majorant, ...
    'B_Upsilon', B_Upsilon / numerator_majorant, ...
    'B_lift', B_lift / numerator_majorant), ...
  'gate_audit', gate_audit, ...
  'theorem_gate', struct( ...
    'structural_pass', true, ...
    'material_tail_tolerance', material_tail_pass, ...
    'lifting_tail_tolerance', lifting_tail_pass, ...
    'retained_row_radius_tolerance', retained_radius_pass, ...
    'outward_rounding', false, ...
    'ordinary_roundoff_excluded_result_complete', ...
      material_tail_pass && lifting_tail_pass && retained_radius_pass), ...
  'provenance', input.provenance, ...
  'resource', struct( ...
    'elapsed_seconds_before_save', toc(timer), ...
    'workspace_proxy_mib_before_save', ...
      sum([workspace.bytes]) / 2.0^20));
save(output_path, 'result', '-v7.3');
end

%% ==================== Explicit paths and schemas ====================
% These helpers enforce portable explicit I/O and immutable output ownership.

function [input_path, output_path] = LOCAL_paths(input_path, output_path)
input_path = LOCAL_char_path(input_path, 'input_path');
output_path = LOCAL_char_path(output_path, 'output_path');
if ~isfile(input_path)
  error('I51b:InputPath', 'input_path must name an existing MAT file.');
end
if isfile(output_path) || isfolder(output_path)
  error('I51b:OutputExists', ...
    'output_path must be a new create-once MAT target.');
end
output_directory = fileparts(output_path);
if ~isempty(output_directory) && ~isfolder(output_directory)
  error('I51b:OutputDirectory', ...
    'The explicit output directory does not exist.');
end
end

function value = LOCAL_char_path(value, name)
if isstring(value) && isscalar(value)
  value = char(value);
end
if ~ischar(value) || isempty(value)
  error('I51b:Path', '%s must be a nonempty path.', name);
end
end

function LOCAL_validate_top_level(input)
required = {'schema', 'claim_scope', 'certification_label', 'frozen', ...
  'configuration', 'strict_cutoff_pass', 'enclosure', 'provenance'};
if ~all(isfield(input, required)) || ...
    ~strcmp(char(input.schema), 'EPOST_I5_1B_INPUT_V1') || ...
    ~strcmp(char(input.certification_label), ...
      'NON_CERTIFIED_ROUNDOFF_EXCLUDED') || ...
    ~input.strict_cutoff_pass
  error('I51b:InputSchema', 'The I5.1b input contract is invalid.');
end
configuration = input.configuration;
required_configuration = {'residual_mode_cutoff', ...
  'evaluation_node_count', 'derivative_order', ...
  'material_tail_tolerance', 'lifting_tail_tolerance', ...
  'retained_row_radius_tolerance'};
if ~all(isfield(configuration, required_configuration)) || ...
    double(configuration.derivative_order) ~= 2.0
  error('I51b:Configuration', 'The I5.1b configuration is incomplete.');
end
L = double(configuration.residual_mode_cutoff);
N = double(configuration.evaluation_node_count);
M_eta = double(input.frozen.density_fourier_degree);
if L ~= fix(L) || L < 1.0 || N ~= fix(N) || mod(N, 2.0) ~= 0.0 || ...
    N <= 2.0 * max(L, M_eta)
  error('I51b:CutoffGate', 'The strict N/L/M_eta gate failed.');
end
end

%% ==================== Fail-closed gates ====================
% These gates separate mathematical eligibility from tail tightness.

function audit = LOCAL_gate_audit(input)
gates = input.enclosure.gates;
required_true = {'artifact_scalar_match', 'geometry_certificate', ...
  'parameterization_ccw_outward', 'density_node_phase_match', ...
  'density_sign_and_support', 'kr13_diagonal_safe', ...
  'kr15_full_torus_enclosure', 'kr21_series_delta_enclosure', ...
  'local_operator_center_zero', ...
  'local_zero_center_full_series_enclosure', ...
  'identity_included_once', 'retained_tail_partition', ...
  'complete_tail_cutoff_selected', ...
  'normal_center_sign_local_minus_regular_minus_off_surface', ...
  'outgoing_branch', 'nonwood_and_inverse_wavenumber', ...
  'ewald_tail_gates', 'regular_center_zero_full_finite_enclosure', ...
  'off_surface_enclosure', 'wall_module', 'wall_value_lift', ...
  'propagation_certificate', ...
  'tail_ownership_disjoint'};
required_false = {'unqualified_special_functions_used', ...
  'sampled_maximum_used', 'inter_level_drift_used', ...
  'empirical_safety_factor_used'};
missing_true = required_true(~isfield(gates, required_true));
missing_false = required_false(~isfield(gates, required_false));
true_values = false(size(required_true));
false_values = true(size(required_false));
for j = 1:numel(required_true)
  if isfield(gates, required_true{j})
    true_values(j) = isequal(gates.(required_true{j}), true);
  end
end
for j = 1:numel(required_false)
  if isfield(gates, required_false{j})
    false_values(j) = isequal(gates.(required_false{j}), false);
  end
end
solve_fields = {'eigenpair_solves', 'bie_density_solves', ...
  'qz_decompositions', 'propagation_matrix_solves'};
solve_pass = all(isfield(input.provenance, solve_fields)) && ...
  all(cellfun(@(name) double(input.provenance.(name)) == 0.0, ...
    solve_fields));
audit = struct( ...
  'required_true', {required_true}, ...
  'required_false', {required_false}, ...
  'missing_true', {missing_true}, ...
  'missing_false', {missing_false}, ...
  'true_gate_values', true_values, ...
  'false_gate_values', false_values, ...
  'zero_solve_counts', solve_pass, ...
  'strict_cutoff', input.strict_cutoff_pass, ...
  'pass', isempty(missing_true) && isempty(missing_false) && ...
    all(true_values) && all(false_values) && solve_pass && ...
    input.strict_cutoff_pass);
end

