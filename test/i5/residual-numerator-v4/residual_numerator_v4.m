%% ==================== Approved upper square root ====================
% Newton iteration retains an upper bound from u0=max(1,x).

function upper = LOCAL_sqrt_upper(x)
if ~(isfinite(x) && x >= 0.0)
  upper = Inf;
  return;
end
if x == 0.0
  upper = 0.0;
  return;
end
upper = max(1.0, x);
for iteration = 1:64
  upper = (upper + x / upper) / 2.0;
end
end
