function result = residual_numerator_v4(input_path, output_path)
%RESIDUAL_NUMERATOR_V4 Assemble the all-zero-center fallback majorant.
% Purpose:
%   Assemble the three continuous residual-numerator modules from one
%   self-contained v4 input without reading source artifacts or old outputs.
% Input:
%   input_path  - Explicit self-contained v4 input MAT path.
%   output_path - Explicit create-once result MAT path.
% Output:
%   result      - Wall, material-normal, lifting, and total scalar bounds.
% Main algorithm:
%   Fail closed on every structural certificate, add disjoint finite and tail
%   squares, apply finite Newton upper roots, and sum the three modules.
% Based on:
%   The I5.1e reliable all-zero-center fallback contract.
% Main changes:
%   No retained center, special function, sampled maximum, or finite-cell
%   propagation is evaluated at runtime.
% Numerical goal:
%   Persist a finite ordinary-arithmetic display with roundoff excluded.

timer = tic;
[input_path, output_path] = LOCAL_paths(input_path, output_path);
loaded = load(input_path, 'experiment_input');
if ~isfield(loaded, 'experiment_input')
  error('I51e:Schema', 'The input MAT file lacks experiment_input.');
end
input = loaded.experiment_input;
LOCAL_validate_input(input);
gate_audit = LOCAL_gate_audit(input);
if ~gate_audit.pass
  result = struct( ...
    'status', 'PRE_RUN_STOP', ...
    'claim_scope', 'CONTINUOUS_RESIDUAL_NUMERATOR_ONLY', ...
    'certification_label', 'NON_CERTIFIED_ROUNDOFF_EXCLUDED', ...
    'gate_audit', gate_audit, ...
    'provenance', input.provenance, ...
    'elapsed_seconds_before_save', toc(timer));
  save(output_path, 'result', '-v7.3');
  return;
end

wall_square = double(input.wall.finite_squared) + ...
  double(input.wall.tail_squared);
material_square = double(input.material.finite_squared) + ...
  double(input.material.tail_squared);
lifting_square = double(input.lifting.finite_squared) + ...
  double(input.lifting.tail_squared);
B_Gamma_pm = LOCAL_sqrt_upper(wall_square);
B_Upsilon = LOCAL_sqrt_upper(material_square);
B_lift = double(input.configuration.global_lift_factor) * ...
  LOCAL_sqrt_upper(lifting_square);
majorant = B_Gamma_pm + B_Upsilon + B_lift;
tightness_pass = logical(input.cutoff_selection.tail_tolerance_pass);
if tightness_pass
  status = 'COMPLETE_RELIABLE_FALLBACK_ORDINARY';
else
  status = 'RELIABLE_FALLBACK_TIGHTNESS_FAILED_ORDINARY';
end
workspace = whos;
result = struct( ...
  'status', status, ...
  'claim_scope', 'CONTINUOUS_RESIDUAL_NUMERATOR_ONLY', ...
  'certification_label', 'NON_CERTIFIED_ROUNDOFF_EXCLUDED', ...
  'roundoff_excluded', true, ...
  'outward_rounding_used', false, ...
  'all_centers_zero', true, ...
  'selected_L', input.selected_L, ...
  'cutoff_selection', input.cutoff_selection, ...
  'wall', struct( ...
    'finite_squared', input.wall.finite_squared, ...
    'tail_squared', input.wall.tail_squared, ...
    'bound', B_Gamma_pm, ...
    'decomposition', input.wall), ...
  'B_Gamma_pm', B_Gamma_pm, ...
  'material', struct( ...
    'finite_squared', input.material.finite_squared, ...
    'tail_squared', input.material.tail_squared, ...
    'bound', B_Upsilon, ...
    'decomposition', input.material), ...
  'B_Upsilon', B_Upsilon, ...
  'lifting', struct( ...
    'finite_squared', input.lifting.finite_squared, ...
    'tail_squared', input.lifting.tail_squared, ...
    'bound', B_lift, ...
    'factor_two_applied_once', ...
      double(input.configuration.global_lift_factor) == 2.0, ...
    'decomposition', input.lifting), ...
  'B_lift', B_lift, ...
  'numerator_majorant', majorant, ...
  'component_share', struct( ...
    'B_Gamma_pm', B_Gamma_pm / majorant, ...
    'B_Upsilon', B_Upsilon / majorant, ...
    'B_lift', B_lift / majorant), ...
  'gate_audit', gate_audit, ...
  'theorem_gate', struct( ...
    'reliable_roundoff_excluded_pass', true, ...
    'tightness_pass', tightness_pass, ...
    'outward_rounding_pass', false), ...
  'provenance', input.provenance, ...
  'resource', struct( ...
    'elapsed_seconds_before_save', toc(timer), ...
    'workspace_proxy_mib_before_save', sum([workspace.bytes]) / 2.0^20));
save(output_path, 'result', '-v7.3');
end

%% ==================== Explicit paths and fail-closed schema ====================
% These helpers protect portable runtime I/O and structural eligibility.

function [input_path, output_path] = LOCAL_paths(input_path, output_path)
input_path = LOCAL_char_path(input_path, 'input_path');
output_path = LOCAL_char_path(output_path, 'output_path');
if ~isfile(input_path)
  error('I51e:InputPath', 'input_path must name an existing MAT file.');
end
if isfile(output_path) || isfolder(output_path)
  error('I51e:OutputExists', 'output_path must be a create-once MAT target.');
end
parent_directory = fileparts(output_path);
if ~isempty(parent_directory) && ~isfolder(parent_directory)
  error('I51e:OutputDirectory', 'The explicit output directory is absent.');
end
end

function value = LOCAL_char_path(value, name)
if isstring(value) && isscalar(value)
  value = char(value);
end
if ~ischar(value) || isempty(value)
  error('I51e:Path', '%s must be an explicit nonempty path.', name);
end
end

function LOCAL_validate_input(input)
required = {'schema', 'claim_scope', 'certification_label', ...
  'configuration', 'selected_L', 'cutoff_selection', 'wall', ...
  'material', 'lifting', 'gates', 'structural_pass', 'provenance'};
if ~all(isfield(input, required)) || ...
    ~strcmp(char(input.schema), 'EPOST_I5_1E_INPUT_V4') || ...
    ~strcmp(char(input.claim_scope), 'CONTINUOUS_RESIDUAL_NUMERATOR_ONLY') || ...
    ~strcmp(char(input.certification_label), ...
      'NON_CERTIFIED_ROUNDOFF_EXCLUDED')
  error('I51e:InputSchema', 'The self-contained v4 input is invalid.');
end
if ~isfield(input.configuration, 'global_lift_factor') || ...
    double(input.configuration.global_lift_factor) ~= 2.0
  error('I51e:LiftFactor', 'The global lifting factor must equal two.');
end
pieces = [double(input.wall.finite_squared), ...
  double(input.wall.tail_squared), ...
  double(input.material.finite_squared), ...
  double(input.material.tail_squared), ...
  double(input.lifting.finite_squared), ...
  double(input.lifting.tail_squared)];
if any(~isfinite(pieces)) || any(pieces < 0.0)
  error('I51e:ComponentSchema', 'A component square is invalid.');
end
end

