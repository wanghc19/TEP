function squared = LOCAL_wall_lift_single_order( ...
    z, clearance, A_tau, A_eta, order)
[a_lower, a_upper] = LOCAL_transverse_interval( ...
  double(z.beta), order, double(z.d));
[q_lower, q_upper, evanescent] = LOCAL_rayleigh_abs_bounds( ...
  double(z.khat), a_lower, a_upper);
if ~evanescent || q_lower <= 0.0
  squared = Inf;
  return;
end
decay = LOCAL_decay_upper(q_lower * clearance);
radius = decay / (2.0 * q_lower * ...
  LOCAL_sqrt_lower(double(z.d))) * ...
  ((q_upper + a_upper) * A_tau + A_eta);
weight = 6.0 / (5.0 * double(z.delta_w)) + ...
  13.0 * double(z.delta_w) / 35.0 * ...
  (a_upper^2 + double(z.mu_h));
