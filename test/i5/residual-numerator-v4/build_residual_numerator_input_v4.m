%% ==================== Artificial-wall normal module ====================
% Direct zero-centered Rayleigh radii cover every frozen wall row.

function out = LOCAL_wall_module( ...
    z, direct_wall, geometry, density, pm, pp)
orders = direct_wall.orders;
retained = true(size(orders));
omitted = false(size(orders));
weights_lower = LOCAL_wall_trace_weights(z, orders);
plus_rows = direct_wall.normal.plus_sequence_radius;
minus_rows = direct_wall.normal.minus_sequence_radius;
plus_omega_retained = sum(plus_rows(retained).^2 ./ weights_lower(retained));
minus_omega_retained = sum(minus_rows(retained).^2 ./ weights_lower(retained));
plus_omega_omitted = sum(plus_rows(omitted).^2 ./ weights_lower(omitted));
minus_omega_omitted = sum(minus_rows(omitted).^2 ./ weights_lower(omitted));
left_singleton = direct_wall.normal.minus_singleton_radius;
right_singleton = direct_wall.normal.plus_singleton_radius;
singleton_retained = sum((left_singleton(retained).^2 + ...
  right_singleton(retained).^2) ./ weights_lower(retained));
singleton_omitted = sum((left_singleton(omitted).^2 + ...
  right_singleton(omitted).^2) ./ weights_lower(omitted));
plus_state = LOCAL_vector_one(z.cplus)^2;
minus_state = LOCAL_vector_one(z.cminus)^2;
finite_squared = singleton_retained + ...
  plus_omega_retained * pp.sum_power_squared_upper * plus_state + ...
  minus_omega_retained * pm.sum_power_squared_upper * minus_state;
frozen_tail = singleton_omitted + ...
  plus_omega_omitted * pp.sum_power_squared_upper * plus_state + ...
  minus_omega_omitted * pm.sum_power_squared_upper * minus_state;
analytic_tail = LOCAL_wall_normal_high( ...
  z, geometry, density, pm, pp);
finite_nonnegative_pass = all(isfinite([finite_squared, frozen_tail, ...
  analytic_tail.total_squared])) && ...
  all([finite_squared, frozen_tail, analytic_tail.total_squared] >= 0.0);
out = struct( ...
  'finite_squared', finite_squared, ...
  'tail_squared', frozen_tail + analytic_tail.total_squared, ...
  'retained_orders', orders(retained), ...
  'omitted_frozen_orders', orders(omitted), ...
  'frozen_tail_squared', frozen_tail, ...
  'analytic_tail', analytic_tail, ...
  'direct_row_certificate', direct_wall.normal, ...
  'direct_reconstruction_pass', ...
    direct_wall.direct_normal_reconstruction_pass, ...
  'stored_J_maps_used', false, ...
  'stored_center_jump_used', false, ...
  'wall_cutoff_independent_of_material_L', ...
    all(retained) && ~any(omitted), ...
  'high_index_sets_disjoint', analytic_tail.index_sets_disjoint && ...
    max(orders) == 255.0 && min(orders) == -256.0 && ...
    analytic_tail.positive_curve_only_order == 256.0 && ...
    analytic_tail.two_sided_high_first_absolute_order == 257.0, ...
  'central_singleton_included_once', ...
    numel(left_singleton) == numel(orders) && ...
    numel(right_singleton) == numel(orders), ...
  'trace_weight_applied_once', all(weights_lower > 0.0), ...
  'finite_nonnegative_pass', finite_nonnegative_pass, ...
  'center_policy', 'zero for singleton and every side row', ...
  'retained_low_cell_split_used', false, ...
  'pass', direct_wall.direct_normal_reconstruction_pass && ...
    finite_nonnegative_pass);
end

function weights = LOCAL_wall_trace_weights(z, orders)
weights = zeros(size(orders));
for j = 1:numel(orders)
  [a_lower, ~] = LOCAL_transverse_interval( ...
    double(z.beta), orders(j), double(z.d));
  lambda = LOCAL_sqrt_lower(a_lower^2 + double(z.mu_h));
  weights(j) = 2.0 * lambda * LOCAL_tanh_lower(0.5 * lambda);
end
end

function out = LOCAL_wall_normal_high(z, geometry, density, pm, pp)
plus_maps = {double(z.Gplus), double(z.Gplus) * double(z.Pplus)};
minus_maps = {double(z.Gminus), double(z.Gminus) * double(z.Pminus)};
plus = LOCAL_wall_normal_high_for_maps( ...
  z, geometry, density, plus_maps);
minus = LOCAL_wall_normal_high_for_maps( ...
  z, geometry, density, minus_maps);
plus_singleton = LOCAL_wall_normal_high_for_maps( ...
  z, geometry, density, {double(z.Gplus) * double(z.cplus)});
minus_singleton = LOCAL_wall_normal_high_for_maps( ...
  z, geometry, density, {double(z.Gminus) * double(z.cminus)});
total = plus.total_squared * pp.sum_power_squared_upper * ...
  LOCAL_vector_one(z.cplus)^2 + ...
  minus.total_squared * pm.sum_power_squared_upper * ...
  LOCAL_vector_one(z.cminus)^2 + ...
  plus_singleton.total_squared + minus_singleton.total_squared;
clearance = min(geometry.left_clearance_lower, ...
  geometry.right_clearance_lower);
ratio = LOCAL_decay_upper( ...
  2.0 * clearance * 2.0 * 3.0 / double(z.d));
positive_power_pass = ...
  LOCAL_positive_power_upper(ratio, 257.0) > 0.0;
out = struct( ...
  'plus_sequence', plus, ...
  'minus_sequence', minus, ...
  'plus_singleton', plus_singleton, ...
  'minus_singleton', minus_singleton, ...
  'positive_curve_only_order', 256.0, ...
  'two_sided_high_first_absolute_order', 257.0, ...
  'index_sets_disjoint', ...
    max(double(z.wall_orders_512(:))) == 255.0 && ...
    min(double(z.wall_orders_512(:))) == -256.0, ...
  'positive_power_pass', positive_power_pass, ...
  'total_squared', total);
end

function out = LOCAL_wall_normal_high_for_maps( ...
    z, geometry, density, maps)
A_tau = 0.0;
A_eta = 0.0;
for j = 1:numel(maps)
  A_tau = A_tau + LOCAL_density_map_L1( ...
    density.tau_native, maps{j}, geometry.boundary_length_upper);
  A_eta = A_eta + LOCAL_density_map_L1( ...
    density.eta_second_native, maps{j}, geometry.boundary_length_upper);
end
clearance = min(geometry.left_clearance_lower, ...
  geometry.right_clearance_lower);
positive_curve_only = LOCAL_wall_normal_single_order( ...
  z, clearance, A_tau, A_eta, 256.0);
two_sided_high = LOCAL_wall_normal_side_tail( ...
  z, clearance, A_tau, A_eta, 257.0);
out = struct( ...
  'positive_curve_only_squared', positive_curve_only, ...
  'two_sided_high_squared', two_sided_high, ...
  'total_squared', positive_curve_only + two_sided_high);
end

function squared = LOCAL_wall_normal_single_order( ...
    z, clearance, A_tau, A_eta, order)
[a_lower, a_upper] = LOCAL_transverse_interval( ...
  double(z.beta), order, double(z.d));
[q_lower, q_upper, evanescent] = LOCAL_rayleigh_abs_bounds( ...
  double(z.khat), a_lower, a_upper);
if ~evanescent || q_lower <= 0.0
  squared = Inf;
  return;
end
decay = LOCAL_decay_upper(q_lower * clearance);
radius = decay / (2.0 * LOCAL_sqrt_lower(double(z.d))) * ...
  ((q_upper + a_upper) * A_tau + A_eta);
weight = LOCAL_wall_trace_weights(z, order);
squared = radius^2 / weight;
end

function squared = LOCAL_wall_normal_side_tail( ...
    z, clearance, A_tau, A_eta, first)
q0_lower = 2.0 * 3.0 / double(z.d);
q0_upper = 2.0 * (22.0 / 7.0) / double(z.d);
a0 = q0_lower * first - abs(double(z.beta));
r = LOCAL_decay_upper(2.0 * clearance * q0_lower);
power = LOCAL_positive_power_upper(r, first);
S0 = power / (1.0 - r);
S1 = power * (first / (1.0 - r) + r / (1.0 - r)^2);
t0 = LOCAL_tanh_lower(0.5 * a0);
bracket = 4.0 * A_tau^2 * (q0_upper * S1 + ...
  abs(double(z.beta)) * S0) + 4.0 * A_tau * A_eta * S0 + ...
  A_eta^2 / a0 * S0;
squared = LOCAL_exp_upper(2.0 * clearance * ...
  (double(z.khat) + abs(double(z.beta)))) * bracket / ...
  (4.0 * double(z.d) * t0);
end

function value = LOCAL_density_map_L1(native, state_map, P_upper)
mapped = double(native) * double(state_map);
coefficient_uniform = sum(LOCAL_row_operator(mapped)) / size(mapped, 1);
value = P_upper * size(mapped, 1) * coefficient_uniform;
end


%% ==================== Wall-value lifting module ====================
% Flat-wall value defects are zero-centered and propagated from cell zero.

function out = LOCAL_wall_lift_module( ...
    z, direct_wall, geometry, density, pm, pp)
orders = direct_wall.orders;
retained = true(size(orders));
omitted = false(size(orders));
row_count = numel(orders);
left_radius = direct_wall.value.left_defect_radius;
right_radius = direct_wall.value.right_defect_radius;
weight_upper = zeros(row_count, 1);
for j = 1:row_count
  [~, a_upper] = LOCAL_transverse_interval( ...
    double(z.beta), orders(j), double(z.d));
  weight_upper(j) = 6.0 / (5.0 * double(z.delta_w)) + ...
    13.0 * double(z.delta_w) / 35.0 * ...
    (a_upper^2 + double(z.mu_h));
end

left_mismatch = direct_wall.value.center_left_mismatch_radius;
right_mismatch = direct_wall.value.center_right_mismatch_radius;
singleton_center = weight_upper .* (left_mismatch.^2 + right_mismatch.^2);

plus_right_retained = LOCAL_wall_lift_omega_mask( ...
  right_radius, z.Gplus, weight_upper, retained);
plus_left_retained = LOCAL_wall_lift_omega_mask( ...
  left_radius, double(z.Gplus) * double(z.Pplus), ...
  weight_upper, retained);
minus_left_retained = LOCAL_wall_lift_omega_mask( ...
  left_radius, z.Gminus, weight_upper, retained);
minus_right_retained = LOCAL_wall_lift_omega_mask( ...
  right_radius, double(z.Gminus) * double(z.Pminus), ...
  weight_upper, retained);
plus_retained = plus_right_retained + plus_left_retained;
minus_retained = minus_left_retained + minus_right_retained;
plus_omitted = LOCAL_wall_lift_omega_mask( ...
  right_radius, z.Gplus, weight_upper, omitted) + ...
  LOCAL_wall_lift_omega_mask( ...
  left_radius, double(z.Gplus) * double(z.Pplus), ...
  weight_upper, omitted);
minus_omitted = LOCAL_wall_lift_omega_mask( ...
  left_radius, z.Gminus, weight_upper, omitted) + ...
  LOCAL_wall_lift_omega_mask( ...
  right_radius, double(z.Gminus) * double(z.Pminus), ...
  weight_upper, omitted);

plus_singleton_retained = LOCAL_wall_lift_singleton_mask( ...
  left_radius, double(z.Gplus) * double(z.cplus), ...
  weight_upper, retained);
minus_singleton_retained = LOCAL_wall_lift_singleton_mask( ...
  right_radius, double(z.Gminus) * double(z.cminus), ...
  weight_upper, retained);
singleton_center_retained = sum(singleton_center(retained));
singleton_center_omitted = sum(singleton_center(omitted));
plus_singleton_omitted = LOCAL_wall_lift_singleton_mask( ...
  left_radius, double(z.Gplus) * double(z.cplus), ...
  weight_upper, omitted);
minus_singleton_omitted = LOCAL_wall_lift_singleton_mask( ...
  right_radius, double(z.Gminus) * double(z.cminus), ...
  weight_upper, omitted);
finite_squared = singleton_center_retained + plus_singleton_retained + ...
  minus_singleton_retained + plus_retained * ...
  pp.sum_power_squared_upper * LOCAL_vector_one(z.cplus)^2 + ...
  minus_retained * pm.sum_power_squared_upper * ...
  LOCAL_vector_one(z.cminus)^2;
frozen_tail = singleton_center_omitted + ...
  plus_singleton_omitted + minus_singleton_omitted + ...
  plus_omitted * pp.sum_power_squared_upper * ...
    LOCAL_vector_one(z.cplus)^2 + ...
  minus_omitted * pm.sum_power_squared_upper * ...
    LOCAL_vector_one(z.cminus)^2;
high = LOCAL_wall_lift_high(z, geometry, density, pm, pp);
center_policy = 'zero; center mismatch rebuilt from q_center and D*c';
finite_nonnegative_pass = all(isfinite([finite_squared, frozen_tail, ...
  high.total_squared])) && ...
  all([finite_squared, frozen_tail, high.total_squared, ...
  plus_omitted, minus_omitted] >= 0.0);
out = struct( ...
  'finite_squared', finite_squared, ...
  'tail_squared', frozen_tail + high.total_squared, ...
  'frozen_tail_squared', frozen_tail, ...
  'analytic_tail', high, ...
  'direct_row_certificate', direct_wall.value, ...
  'wall_input_trace_included', direct_wall.wall_input_exact_map_pass && ...
    all(isfinite([direct_wall.value.shared_left_radius; ...
    direct_wall.value.shared_right_radius])), ...
  'wall_input_support_audited', direct_wall.index_support_pass && ...
    direct_wall.wall_input_exact_map_pass, ...
  'high_direct_input_zero_by_finite_support', ...
    direct_wall.wall_input_exact_map_pass, ...
  'stored_center_mismatch_used', false, ...
  'wall_cutoff_independent_of_material_L', ...
    all(retained) && ~any(omitted), ...
  'high_index_sets_disjoint', high.index_sets_disjoint && ...
    max(orders) == 255.0 && min(orders) == -256.0 && ...
    high.positive_curve_only_order == 256.0 && ...
    high.two_sided_high_first_absolute_order == 257.0, ...
  'value_triangle_combined_before_square', ...
    direct_wall.value_triangle_before_square, ...
  'left_right_collars_squared_separately', ...
    isfinite(plus_right_retained) && isfinite(plus_left_retained) && ...
    isfinite(minus_left_retained) && isfinite(minus_right_retained), ...
  'central_and_lead_singletons_included_once', ...
    numel(singleton_center) == numel(orders) && ...
    isfinite(plus_singleton_retained) && ...
    isfinite(minus_singleton_retained), ...
  'lifting_weight_applied_once', all(weight_upper > 0.0), ...
  'finite_nonnegative_pass', finite_nonnegative_pass, ...
  'center_policy', center_policy, ...
