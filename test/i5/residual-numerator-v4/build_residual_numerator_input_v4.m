end

function audit = LOCAL_validate_frozen(z, input_contract)
required = {'khat', 'gamma', 'mu_h', 'beta', 'd', 'R', 'rho_disk', ...
  'delta_c', 'delta_w', 'X_L', 'X_R', 'L', 'M', 'K', 'q_center', ...
  'Dplus', 'Dminus', 'Gplus', 'Gminus', 'Pplus', 'Pminus', ...
  'cplus', 'cminus', 'branch_port', ...
  'eta_unit_256', 'xi_left_unit_512', 'xi_right_unit_512', ...
  'wall_input_unit_512', 'wall_orders_512', 'density_coordinate'};
contract_required = {'M_role', 'wall_source_orders', 'wall_basis', ...
  'wall_output_ordering', 'no_resolve_required'};
if ~all(isfield(z, required)) || ...
    ~all(isfield(input_contract, contract_required)) || ...
    ~isfield(z.branch_port, 'gamma_m') || ...
    ~strcmp(strtrim(char(z.density_coordinate)), '[tau;zeta], zeta=-sigma')
  error('I51eInput:FrozenSchema', 'The frozen reconstruction schema is invalid.');
end
K = double(z.K);
M = double(z.M);
dimensions_pass = K == 2.0 * M + 1.0 && ...
  isequal(size(z.Dplus), [K, K]) && ...
  isequal(size(z.Dminus), [K, K]) && ...
  isequal(size(z.Gplus), [2.0 * K, K]) && ...
  isequal(size(z.Gminus), [2.0 * K, K]) && ...
  isequal(size(z.Pplus), [K, K]) && ...
  isequal(size(z.Pminus), [K, K]) && ...
  numel(z.cplus) == K && numel(z.cminus) == K && ...
  numel(z.q_center) == 2.0 * K && ...
  numel(z.branch_port.gamma_m) == K && ...
  isequal(size(z.eta_unit_256), [512, 2.0 * K]) && ...
  isequal(size(z.xi_left_unit_512), [512, 2.0 * K]) && ...
  isequal(size(z.xi_right_unit_512), [512, 2.0 * K]) && ...
  isequal(size(z.wall_input_unit_512), [1024, 2.0 * K]);
index_pass = isequal(double(z.wall_orders_512(:)), (-256.0:255.0).');
contract_pass = ...
  strcmp(char(input_contract.M_role), ...
    '97 retained QZ wall-input modes only') && ...
  double(input_contract.wall_source_orders) == 512.0 && ...
  strcmp(char(input_contract.wall_basis), ...
    'd^(-1/2)*exp(i*(beta+2*pi*m/d)*y)') && ...
  strcmp(char(input_contract.wall_output_ordering), ...
    '-N/2:N/2-1 with negative Nyquist retained') && ...
  logical(input_contract.no_resolve_required);
if ~dimensions_pass || ~index_pass || ~contract_pass || ...
    z.khat <= 0.0 || z.d <= 0.0 || z.R <= 0.0 || ...
    z.rho_disk <= 0.0 || z.delta_c <= 0.0 || z.delta_w <= 0.0 || ...
    z.gamma ~= z.mu_h
  error('I51eInput:FrozenGate', 'A frozen dimension or scalar gate failed.');
end
audit = struct( ...
  'dimensions_pass', dimensions_pass, ...
  'wall_order_half_open_pass', index_pass, ...
  'wall_basis_contract_pass', contract_pass, ...
  'state_dimension', K, ...
  'state_order_min', -M, ...
  'state_order_max', M, ...
  'wall_order_min', -256.0, ...
  'wall_order_max', 255.0, ...
  'pass', dimensions_pass && index_pass && contract_pass);
end

function audit = LOCAL_validate_curve(z, contract)
required = {'schema', 'parameter_period', 'source_node_count', ...
  'density_coordinate', 'orientation', 'node_rule', 'adapter_metadata', ...
  'wall_left_x', 'wall_right_x'};
schema_pass = all(isfield(contract, required)) && ...
  strcmp(char(contract.schema), 'TEP_I5_WALL_CURVE_CONTRACT_V1');
source_count_pass = schema_pass && ...
  double(contract.source_node_count) == 256.0;
orientation_pass = schema_pass && strcmp(char(contract.orientation), ...
    'counter-clockwise; outward normal=(dy_dt,-dx_dt)/speed') && ...
  schema_pass;
node_phase_pass = schema_pass && strcmp(char(contract.node_rule), ...
  't_j=2*pi*j/N, j=0,...,N-1; no midpoint shift') && ...
  strcmp(strtrim(char(contract.density_coordinate)), ...
  strtrim(char(z.density_coordinate)));
center_pass = schema_pass && isfield(contract.adapter_metadata, 'center') && ...
  isequal(double(contract.adapter_metadata.center(:).'), [0.0, 0.0]);
radius_pass = schema_pass && isfield(contract.adapter_metadata, 'radius') && ...
  double(contract.adapter_metadata.radius) == double(z.R);
constructor_pass = schema_pass && ...
  isfield(contract.adapter_metadata, 'geometry_constructor') && ...
  strcmp(char(contract.adapter_metadata.geometry_constructor), ...
  'geom.construct_cont');
wall_pass = schema_pass && ...
  double(contract.wall_left_x) == double(z.X_L) && ...
  double(contract.wall_right_x) == double(z.X_R);
pass = schema_pass && source_count_pass && orientation_pass && ...
  node_phase_pass && center_pass && radius_pass && constructor_pass && ...
  wall_pass;
if ~pass
  error('I51eInput:CurveContract', 'The explicit curve adapter contract failed.');
end
audit = struct( ...
  'schema_pass', schema_pass, ...
  'circle_adapter_center_match', center_pass, ...
  'circle_adapter_radius_match', radius_pass, ...
  'counter_clockwise_outward', orientation_pass, ...
  'density_node_phase_match', node_phase_pass, ...
  'geometry_constructor_match', constructor_pass, ...
  'wall_location_match', wall_pass, ...
  'pass', pass);
end

%% ==================== Approved scalar primitives ====================
% These functions are the sole transcendental and vector-size surrogates.

function value = LOCAL_abs_sharp(z)
value = abs(real(z)) + abs(imag(z));
end

function value = LOCAL_vector_one(v)
value = sum(LOCAL_abs_sharp(v(:)));
end

function value = LOCAL_matrix_one(A)
value = max(sum(LOCAL_abs_sharp(A), 1));
end

function value = LOCAL_row_operator(A)
value = max(LOCAL_abs_sharp(A), [], 2);
end

function value = LOCAL_relative_sharp(A, B)
if ~isequal(size(A), size(B)) || any(~isfinite([A(:); B(:)]))
  value = Inf;
  return;
end
scale = max([1.0; LOCAL_abs_sharp(A(:)); LOCAL_abs_sharp(B(:))]);
value = max(LOCAL_abs_sharp(A(:) - B(:))) / scale;
end

function upper = LOCAL_sqrt_upper(x)
if ~(isfinite(x) && x >= 0.0)
  upper = Inf;
  return;
end
if x == 0.0
  upper = 0.0;
  return;
end
upper = max(1.0, x);
for iteration = 1:64
  upper = (upper + x / upper) / 2.0;
end
end

function lower = LOCAL_sqrt_lower(x)
upper = LOCAL_sqrt_upper(x);
if x == 0.0
  lower = 0.0;
else
  lower = x / upper;
end
end

function upper = LOCAL_exp_upper(x)
if ~(isfinite(x) && x >= 0.0)
  upper = Inf;
  return;
end
term = 1.0;
partial = 1.0;
upper = Inf;
for n = 1:256
  term = term * x / n;
  partial = partial + term;
  next_ratio = x / (n + 1.0);
  if next_ratio < 0.5
    next_term = term * next_ratio;
    upper = partial + next_term / (1.0 - x / (n + 2.0));
    break;
  end
end
end

function upper = LOCAL_decay_upper(x)
if ~(isfinite(x) && x >= 0.0)
  upper = Inf;
  return;
end
term = 1.0;
partial = 1.0;
for n = 1:64
  term = term * x / n;
  partial = partial + term;
  if ~isfinite(term) || ~isfinite(partial)
    upper = Inf;
    return;
  end
end
upper = max(1.0 / partial, 1.0e-100);
end

function upper = LOCAL_positive_power_upper(r, n)
if ~(isfinite(r) && r > 0.0 && r < 1.0 && ...
    isfinite(n) && n >= 0.0 && n == fix(n))
  upper = Inf;
  return;
end
upper = 1.0;
for j = 1:n
  upper = max(upper * r, 1.0e-100);
end
end

function upper = LOCAL_logabs_upper(x)
if ~(isfinite(x) && x > 0.0)
  upper = Inf;
else
  upper = x + 1.0 / x;
end
end

function lower = LOCAL_tanh_lower(x)
if ~(isfinite(x) && x >= 0.0)
  lower = 0.0;
else
  lower = x / (1.0 + x);
end
end

function value = LOCAL_factorial(n)
value = 1.0;
for j = 2:n
  value = value * j;
end
end

function value = LOCAL_falling(n, r)
value = 1.0;
for j = 0:r - 1.0
  value = value * (n - j);
end
end

