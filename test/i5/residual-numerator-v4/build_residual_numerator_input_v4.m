function out = LOCAL_root_of_unity_256_ball(configuration)
N = 256.0;
levels = 7.0;
iterations = double(configuration.density_root_newton_iterations);
padding = double(configuration.density_root_bracket_padding);
cosine_lower = zeros(levels + 1.0, 1);
cosine_upper = zeros(levels + 1.0, 1);
sine_lower = zeros(levels, 1);
sine_upper = zeros(levels, 1);
cosine_lower(1) = -1.0;
cosine_upper(1) = -1.0;
ordered_pass = true;
nonperfect_noncollapse_pass = true;
for level = 1:levels
  cosine_argument_lower = (1.0 + cosine_lower(level)) / 2.0;
  cosine_argument_upper = (1.0 + cosine_upper(level)) / 2.0;
  sine_argument_lower = (1.0 - cosine_upper(level)) / 2.0;
  sine_argument_upper = (1.0 - cosine_lower(level)) / 2.0;
  [cosine_lower(level + 1.0), cosine_upper(level + 1.0), ...
    cosine_pass] = LOCAL_sqrt_interval_with_padding( ...
    cosine_argument_lower, cosine_argument_upper, iterations, padding);
  [sine_lower(level), sine_upper(level), sine_pass] = ...
    LOCAL_sqrt_interval_with_padding( ...
    sine_argument_lower, sine_argument_upper, iterations, padding);
  ordered_pass = ordered_pass && cosine_pass && sine_pass;
  cosine_nonperfect = ~LOCAL_perfect_zero_or_one_interval( ...
    cosine_argument_lower, cosine_argument_upper);
  sine_nonperfect = ~LOCAL_perfect_zero_or_one_interval( ...
    sine_argument_lower, sine_argument_upper);
  nonperfect_noncollapse_pass = nonperfect_noncollapse_pass && ...
    (~cosine_nonperfect || ...
    cosine_upper(level + 1.0) > cosine_lower(level + 1.0)) && ...
    (~sine_nonperfect || sine_upper(level) > sine_lower(level));
end
cosine_center = (cosine_lower(end) + cosine_upper(end)) / 2.0;
sine_center = (sine_lower(end) + sine_upper(end)) / 2.0;
omega_center = cosine_center - 1i * sine_center;
omega_radius = (cosine_upper(end) - cosine_lower(end) + ...
  sine_upper(end) - sine_lower(end)) / 2.0;
orientation_pass = real(omega_center) > 0.0 && imag(omega_center) < 0.0;
power_center = zeros(N, 1);
power_radius = zeros(N, 1);
power_center(1) = 1.0;
for order = 1:N - 1.0
  previous_center = power_center(order);
  previous_radius = power_radius(order);
  power_center(order + 1.0) = previous_center * omega_center;
  power_radius(order + 1.0) = ...
    LOCAL_abs_sharp(previous_center) * omega_radius + ...
    LOCAL_abs_sharp(omega_center) * previous_radius + ...
    previous_radius * omega_radius;
end
finite_pass = all(isfinite([cosine_lower; cosine_upper; ...
  sine_lower; sine_upper; real(power_center); imag(power_center); ...
  power_radius])) && all(power_radius >= 0.0) && ...
  isfinite(omega_radius) && omega_radius > 0.0;
out = struct( ...
  'node_count', N, ...
  'half_angle_levels', levels, ...
  'sqrt_newton_iterations', iterations, ...
  'directed_bracket_padding', padding, ...
  'root_sign', 'omega=exp(-2*pi*i/256)', ...
  'cosine_lower', cosine_lower, ...
  'cosine_upper', cosine_upper, ...
  'sine_lower', sine_lower, ...
  'sine_upper', sine_upper, ...
  'omega_center', omega_center, ...
  'omega_radius', omega_radius, ...
  'orientation_pass', orientation_pass, ...
  'power_center', power_center, ...
  'power_radius', power_radius, ...
  'ordered_direction_pass', ordered_pass, ...
  'nonperfect_bracket_noncollapse_pass', ...
    nonperfect_noncollapse_pass, ...
  'finite_power_ball_pass', finite_pass, ...
  'pass', N == 2.0^8 && levels == 7.0 && iterations >= 1.0 && ...
    iterations == fix(iterations) && padding > 0.0 && ...
    ordered_pass && nonperfect_noncollapse_pass && finite_pass && ...
    orientation_pass);
end

function [lower, upper, pass] = LOCAL_sqrt_interval_with_padding( ...
    argument_lower, argument_upper, iterations, padding)
if ~(isfinite(argument_lower) && isfinite(argument_upper) && ...
    0.0 <= argument_lower && argument_lower <= argument_upper && ...
    isfinite(iterations) && iterations >= 1.0 && ...
    iterations == fix(iterations) && isfinite(padding) && padding > 0.0)
  lower = -Inf;
  upper = Inf;
  pass = false;
  return;
end
upper_iteration = max(1.0, argument_upper);
lower_iteration_upper = max(1.0, argument_lower);
for iteration = 1:iterations
  upper_iteration = (upper_iteration + ...
    argument_upper / upper_iteration) / 2.0;
  lower_iteration_upper = (lower_iteration_upper + ...
    argument_lower / lower_iteration_upper) / 2.0;
end
raw_lower = 0.0;
if argument_lower > 0.0
  raw_lower = argument_lower / lower_iteration_upper;
end
raw_upper = upper_iteration;
if LOCAL_perfect_zero_or_one_interval(argument_lower, argument_upper)
  lower = argument_lower;
  upper = argument_upper;
else
  lower = max(0.0, raw_lower - padding);
  upper = raw_upper + padding;
end
pass = isfinite(lower) && isfinite(upper) && ...
  0.0 <= lower && lower <= upper;
end

function pass = LOCAL_perfect_zero_or_one_interval(lower, upper)
pass = lower == upper && (lower == 0.0 || lower == 1.0);
end

function [out, derivative_upper] = LOCAL_density_coefficient_ball( ...
    native, orders, root_ball)
N = size(native, 1);
column_count = size(native, 2);
coefficient_center = zeros(N, column_count);
coefficient_radius = zeros(N, column_count);
native_abs = LOCAL_abs_sharp(native);
modular_index_pass = true;
for row = 1:N
  order = orders(row);
  phase_center = zeros(N, 1);
  phase_radius = zeros(N, 1);
  for node = 0:N - 1.0
    power_index = mod(order * node, N) + 1.0;
    modular_index_pass = modular_index_pass && ...
      power_index >= 1.0 && power_index <= N && ...
      power_index == fix(power_index);
    phase_center(node + 1.0) = root_ball.power_center(power_index);
    phase_radius(node + 1.0) = root_ball.power_radius(power_index);
  end
  coefficient_center(row, :) = phase_center.' * native / N;
  coefficient_radius(row, :) = phase_radius.' * native_abs / N;
end
coefficient_row_upper = max( ...
  LOCAL_abs_sharp(coefficient_center) + coefficient_radius, [], 2);
derivative_upper = zeros(1, 6);
for derivative_order = 0:5
  derivative_upper(derivative_order + 1.0) = sum( ...
    abs(orders).^derivative_order .* coefficient_row_upper);
end
finite_pass = all(isfinite([real(coefficient_center(:)); ...
  imag(coefficient_center(:)); coefficient_radius(:); ...
  coefficient_row_upper; derivative_upper(:)])) && ...
  all(coefficient_radius(:) >= 0.0) && ...
  all(coefficient_row_upper >= 0.0) && all(derivative_upper >= 0.0);
out = struct( ...
  'coefficient_center', coefficient_center, ...
  'coefficient_radius', coefficient_radius, ...
  'coefficient_row_upper', coefficient_row_upper, ...
  'derivative_upper_orders_0_to_5', derivative_upper, ...
  'radius_added_once', true, ...
  'auxiliary_density_center_only', true, ...
  'residual_action_center', false, ...
  'modular_index_pass', modular_index_pass, ...
  'pass', root_ball.pass && N == 256.0 && ...
    isequal(orders, (-128.0:127.0).') && ...
    modular_index_pass && finite_pass);
end

function certificate = LOCAL_block_certificate(P, block_length)
P = double(P);
power = eye(size(P));
prefix = 0.0;
for j = 0:block_length - 1.0
  prefix = prefix + LOCAL_matrix_one(power)^2;
  power = P * power;
end
block_upper = LOCAL_matrix_one(power);
pass = isfinite(prefix) && block_upper < 1.0;
if pass
  sum_power_squared_upper = prefix / (1.0 - block_upper^2);
else
  sum_power_squared_upper = Inf;
end
certificate = struct( ...
  'block_length', block_length, ...
  'matrix_bound', 'entrywise induced one norm', ...
  'prefix_sum_upper', prefix, ...
  'block_norm_upper', block_upper, ...
  'sum_power_squared_upper', sum_power_squared_upper, ...
  'first_cell_index', 0.0, ...
  'pass', pass);
end

function upper = LOCAL_state_sum(z, pm, pp)
upper = LOCAL_vector_one(z.q_center)^2 + ...
  LOCAL_matrix_one(z.Gminus)^2 * pm.sum_power_squared_upper * ...
    LOCAL_vector_one(z.cminus)^2 + ...
  LOCAL_matrix_one(z.Gplus)^2 * pp.sum_power_squared_upper * ...
    LOCAL_vector_one(z.cplus)^2;
end

%% ==================== Local Kress whole-action certificate ====================
% The identity-inclusive H_q constants implement KR-15 and KR-24/KR-25.

function out = LOCAL_circle_KR15_bounds(z, density, geometry, configuration)
PI_LO = 3.0;
PI_UP = 22.0 / 7.0;
R = geometry.radius;
Q = 4.0 * R^2;
outer = LOCAL_entire_bounds(double(z.khat)^2, Q, ...
  configuration.kernel_series_cutoff);
inner = LOCAL_entire_bounds(double(z.rho_disk) * double(z.khat)^2, Q, ...
  configuration.kernel_series_cutoff);
log_c = LOCAL_logabs_upper(R^2);
J_delta = (outer.J + inner.J) / (4.0 * PI_LO);
j_delta = (outer.jshift + inner.jshift) / (2.0 * PI_LO);
R_delta = 2.0 * (outer.c_abs * outer.J + inner.c_abs * inner.J) + ...
  (outer.Y + inner.Y) / PI_LO;
W = 2.0 * log_c * J_delta(2:4) + j_delta + R_delta(2:4);

S1 = LOCAL_h_factor(R * J_delta(1:3), [1.0, 0.0, 0.0], R);
S2 = LOCAL_h_factor(R * (log_c * J_delta(1:3) + ...
  R_delta(1:3)), [1.0, 0.0, 0.0], R);
D1 = LOCAL_h_factor(2.0 * J_delta(2:4), ...
  [2.0 * R^2, R^2, R^2], R);
D2 = LOCAL_h_factor(W, [2.0 * R^2, R^2, R^2], R);
C1 = LOCAL_h_factor(2.0 * J_delta(2:4), ...
  [R^2, R^2, R^2], R);
C2 = LOCAL_h_factor(W, [R^2, R^2, R^2], R);

k2e = double(z.khat)^2;
k2i = double(z.rho_disk) * k2e;
weighted1x = R / (4.0 * PI_LO) * ...
  (k2e * outer.J(1:3) + k2i * inner.J(1:3));
weighted2x = k2e * R * ((log_c / (4.0 * PI_LO) + outer.c_abs) * ...
  outer.J(1:3) + outer.Y(1:3) / (2.0 * PI_LO)) + ...
  k2i * R * ((log_c / (4.0 * PI_LO) + inner.c_abs) * ...
  inner.J(1:3) + inner.Y(1:3) / (2.0 * PI_LO));
A1 = LOCAL_h_factor(weighted1x, [1.0, 1.0, 1.0], R);
A2 = LOCAL_h_factor(weighted2x, [1.0, 1.0, 1.0], R);

val = LOCAL_action_derivatives( ...
  {D1, S1}, {D2, S2}, ...
  {density.tau_derivative_upper, density.eta_second_derivative_upper}, ...
  density.tau_derivative_upper(1:5), R, false);
nor = LOCAL_action_derivatives( ...
  {A1, C1, D1}, {A2, C2, D2}, ...
  {density.tau_derivative_upper, ...
   density.tau_derivative_upper(2:6) / R, ...
   density.eta_second_derivative_upper}, ...
  density.eta_second_derivative_upper(1:5), R, true);
log_two = LOCAL_logabs_upper(2.0);
val.H_q = val.identity + 8.0 * PI_UP * log_two * val.diagonal(1, :) + ...
  2.0 * PI_UP * val.diagonal(2, :);
nor.H_q = nor.identity + 8.0 * PI_UP * log_two * nor.diagonal(1, :) + ...
  2.0 * PI_UP * nor.diagonal(2, :);
val.Q2 = 2.0 * PI_UP * val.H_q(3) / R;
nor.Q2 = 2.0 * PI_UP * nor.H_q(3) / R;
val.Q4 = 2.0 * PI_UP * val.H_q(5) / R^3;
nor.Q4 = 2.0 * PI_UP * nor.H_q(5) / R^3;
p4_C6_certificate = struct( ...
  'curve_parameter_derivative_order', 6.0, ...
  'curve_parameter_derivative_upper', R * ones(1, 6), ...
  'density_parameter_derivative_order', 5.0, ...
  'speed_lower', R, ...
  'speed_upper', R, ...
  'speed_derivative_upper_orders_1_to_3', zeros(1, 3), ...
  'constant_speed', geometry.speed_lower == R && ...
    geometry.speed_upper == R, ...
  'maue_tau_prime_order_five_included', ...
    numel(density.tau_derivative_upper) >= 6, ...
  'pass', R > 0.0 && numel(density.tau_derivative_upper) >= 6 && ...
    numel(density.eta_second_derivative_upper) >= 6);
out = struct( ...
  'schema', 'EPOST_I5_KR15_DERIVATIVE_CERTIFICATE_V2_P4', ...
  'val', val, ...
  'nor', nor, ...
  'C10', struct('val', val.diagonal(1, 1), ...
    'nor', nor.diagonal(1, 1)), ...
  'C20', struct('val', val.diagonal(2, 1), ...
    'nor', nor.diagonal(2, 1)), ...
  'identity_q', struct('val', val.identity, 'nor', nor.identity), ...
  'H_q', struct('val', val.H_q, 'nor', nor.H_q), ...
  'Q2', struct('val', val.Q2, 'nor', nor.Q2), ...
  'Q4', struct('val', val.Q4, 'nor', nor.Q4), ...
  'p4_C6_certificate', p4_C6_certificate, ...
  'series_outer', outer, ...
  'series_inner', inner, ...
  'density_included', val.density_included && nor.density_included, ...
  'special_function_library_used', false, ...
  'instance_adapter', ...
    'circle analytic geometry derivative bounds; no Fourier/Bessel diagonalization', ...
  'pass', outer.pass && inner.pass && p4_C6_certificate.pass && ...
    all(isfinite([val.identity, nor.identity, val.diagonal(:).', ...
      nor.diagonal(:).', val.Q4, nor.Q4])));
end

