  'adapter_certificate', adapter, ...
  'pass', interface_pass && adapter.density_included && ...
    all(isfinite([val.H_q, nor.H_q, val.Q2, nor.Q2, ...
    val.Q4, nor.Q4])));
end

function out = LOCAL_entire_bounds(kappa_squared, Q, cutoff)
alpha = kappa_squared / 4.0;
J = zeros(1, 4);
Y = zeros(1, 4);
jshift = zeros(1, 3);
ratios = zeros(3, 4);
harmonic = zeros(1, cutoff + 1.0);
for n = 1:cutoff + 1.0
  harmonic(n) = harmonic(max(1.0, n - 1.0)) + 1.0 / n;
end
for r = 0:3
  for n = r:cutoff
    term = LOCAL_falling(n, r) * alpha^n * Q^(n - r) / ...
      LOCAL_factorial(n)^2;
    J(r + 1.0) = J(r + 1.0) + term;
    if n >= 1.0
      Y(r + 1.0) = Y(r + 1.0) + harmonic(n) * term;
    end
  end
  n = cutoff + 1.0;
  first = LOCAL_falling(n, r) * alpha^n * Q^(n - r) / ...
    LOCAL_factorial(n)^2;
  ratio_J = alpha * Q / ((n + 1.0) * (n + 1.0 - r));
  ratio_Y = ratio_J * (1.0 + 1.0 / (n + 1.0));
  ratios(1, r + 1.0) = ratio_J;
  ratios(2, r + 1.0) = ratio_Y;
  J(r + 1.0) = J(r + 1.0) + first / (1.0 - ratio_J);
  Y(r + 1.0) = Y(r + 1.0) + ...
    harmonic(n) * first / (1.0 - ratio_Y);
end
for r = 0:2
  for m = r:cutoff - 1.0
    jshift(r + 1.0) = jshift(r + 1.0) + ...
      LOCAL_falling(m, r) * alpha^(m + 1.0) * Q^(m - r) / ...
      LOCAL_factorial(m + 1.0)^2;
  end
  m = cutoff;
  first = LOCAL_falling(m, r) * alpha^(m + 1.0) * Q^(m - r) / ...
    LOCAL_factorial(m + 1.0)^2;
  ratio = alpha * Q * (m + 1.0) / ...
    ((m + 1.0 - r) * (m + 2.0)^2);
  ratios(3, r + 1.0) = ratio;
  jshift(r + 1.0) = jshift(r + 1.0) + first / (1.0 - ratio);
end
kappa_lower = LOCAL_sqrt_lower(kappa_squared);
kappa_upper = LOCAL_sqrt_upper(kappa_squared);
x_lower = kappa_lower / 2.0;
x_upper = kappa_upper / 2.0;
log_kappa_upper = x_upper + 1.0 / x_lower;
c_abs = 0.25 + (log_kappa_upper + 1.0) / ...
  (2.0 * 3.0);
out = struct( ...
  'J', J, 'Y', Y, 'jshift', jshift, 'c_abs', c_abs, ...
  'ratios', ratios, ...
  'pass', x_lower > 0.0 && all(ratios(:) < 1.0) && ...
    all(isfinite([J, Y, jshift, c_abs])));
end

function h = LOCAL_h_factor(x, multiplier, R)
x1 = 2.0 * R^2;
x2 = 2.0 * R^2;
h = [ ...
  multiplier(1) * x(1), ...
  multiplier(2) * x(1) + multiplier(1) * x(2) * x1, ...
  multiplier(3) * x(1) + 2.0 * multiplier(2) * x(2) * x1 + ...
    multiplier(1) * (x(3) * x1^2 + x(2) * x2)];
end

function out = LOCAL_action_derivatives( ...
    split1, split2, densities, identity, R, is_normal)
diagonal = zeros(2, 5);
source_L1 = zeros(1, 2);
groups = {split1, split2};
for split = 1:2
  factors = groups{split};
  for j = 1:numel(factors)
    f = factors{j};
    a = densities{j};
    source_L1(split) = source_L1(split) + 2.0 * (22.0 / 7.0) * ...
      (f(3) * a(1) + 2.0 * f(2) * a(2) + f(1) * a(3));
    for q = 0:4
      diagonal(split, q + 1.0) = diagonal(split, q + 1.0) + ...
        f(1) * a(q + 1.0);
    end
  end
end
out = struct( ...
  'source_L1_second_upper', source_L1, ...
  'diagonal', diagonal, ...
  'identity', identity, ...
  'H_q', NaN(1, 5), ...
  'Q2', NaN, ...
  'Q4', NaN, ...
  'normal_action', is_normal, ...
  'maue_scale', R, ...
  'density_included', true);
end

%% ==================== Regular-image Ewald whole-action certificate ====================
% Every retained Ewald term and omission is enclosed about center zero.

function out = LOCAL_regular_certificate(z, density, geometry, configuration)
real_geometry = struct( ...
  'displacement_abs_upper', [2.0, 2.0] * geometry.radius, ...
  'displacement_imag_upper', [0.0, 0.0], ...
  'displacement_real_upper', [2.0, 2.0] * geometry.radius, ...
  'target_normal_component_upper', [1.0, 1.0], ...
  'source_normal_component_upper', [1.0, 1.0]);
strip_radius = geometry.strip_position_abs_upper;
strip_geometry = struct( ...
  'displacement_abs_upper', [2.0, 2.0] * strip_radius, ...
  'displacement_imag_upper', [2.0, 2.0] * ...
    geometry.strip_position_imag_upper, ...
  'displacement_real_upper', [2.0, 2.0] * strip_radius, ...
  'target_normal_component_upper', [1.0, 1.0] * ...
    LOCAL_exp_upper(geometry.parameter_strip_width), ...
  'source_normal_component_upper', [1.0, 1.0]);
real_coordinate = LOCAL_ewald_coordinate( ...
  z, real_geometry, configuration);
strip_coordinate = LOCAL_ewald_coordinate( ...
  z, strip_geometry, configuration);
real_kernel = LOCAL_contract_coordinate( ...
  real_coordinate.whole, ...
  real_geometry.target_normal_component_upper, ...
  real_geometry.source_normal_component_upper);
strip_kernel = LOCAL_contract_coordinate( ...
  strip_coordinate.whole, ...
  strip_geometry.target_normal_component_upper, ...
  strip_geometry.source_normal_component_upper);
A_tau_L1 = geometry.boundary_length_upper * ...
  density.tau_derivative_upper(1);
A_eta_L1 = geometry.boundary_length_upper * ...
  density.eta_second_derivative_upper(1);
scale = geometry.boundary_length_upper / ...
  LOCAL_sqrt_lower(geometry.boundary_length_lower);
value_real = scale * (real_kernel(2) * A_tau_L1 + ...
  real_kernel(1) * A_eta_L1);
normal_real = scale * (real_kernel(4) * A_tau_L1 + ...
  real_kernel(3) * A_eta_L1);
value_strip = strip_kernel(2) * A_tau_L1 + ...
  strip_kernel(1) * A_eta_L1;
normal_strip = strip_kernel(4) * A_tau_L1 + ...
  strip_kernel(3) * A_eta_L1;
out = struct( ...
  'real_coordinate', real_coordinate, ...
  'strip_coordinate', strip_coordinate, ...
  'value_whole_action_radius', value_real, ...
  'normal_whole_action_radius', normal_real, ...
  'value_strip_upper', value_strip, ...
  'normal_strip_upper', normal_strip, ...
  'center_policy', 'zero; whole Ewald action is a scalar radius', ...
  'M_R', struct('real', real_coordinate.reciprocal_tail, ...
    'strip', strip_coordinate.reciprocal_tail), ...
  'M_I', struct('real', real_coordinate.image_tail, ...
    'strip', strip_coordinate.image_tail), ...
  'M_T', struct('absorbed_into_full_retained_image_bound', true), ...
  'M_L', struct('real', real_coordinate.local_tail, ...
    'strip', strip_coordinate.local_tail), ...
  'special_function_library_used', false, ...
  'pass', real_coordinate.pass && strip_coordinate.pass && ...
    all(isfinite([value_real, normal_real, value_strip, normal_strip])));
end

function kernel = LOCAL_contract_coordinate(coordinate, Nt, Ns)
kernel = [ ...
  coordinate(1), ...
  Ns(1) * coordinate(2) + Ns(2) * coordinate(3), ...
  Nt(1) * coordinate(2) + Nt(2) * coordinate(3), ...
  Nt(1) * Ns(1) * coordinate(4) + ...
    (Nt(1) * Ns(2) + Nt(2) * Ns(1)) * coordinate(5) + ...
    Nt(2) * Ns(2) * coordinate(6)];
end

function out = LOCAL_ewald_coordinate(z, geometry, configuration)
k = double(z.khat);
d = double(z.d);
bloch = double(z.beta);
h = configuration.ewald_split / d;
chi = (k * d / (2.0 * configuration.ewald_split))^2;
RX = geometry.displacement_abs_upper(1);
RY = geometry.displacement_abs_upper(2);
IX = geometry.displacement_imag_upper(1);
IY = geometry.displacement_imag_upper(2);
UX = geometry.displacement_real_upper(1);
UY = geometry.displacement_real_upper(2);
finite = LOCAL_ewald_finite( ...
  k, bloch, d, h, chi, RX, RY, IX, IY, UX, UY, configuration);
[reciprocal_tail, reciprocal_pass] = LOCAL_reciprocal_tail( ...
  k, bloch, d, h, RX, IX, IY, UX, configuration.reciprocal_cutoff);
[image_tail, image_pass] = LOCAL_image_tail( ...
  d, h, chi, RX, RY, IX, IY, UY, configuration.image_cutoff);
[local_finite, local_tail, local_pass] = LOCAL_local_ewald( ...
  h, chi, RX, RY, configuration);
whole = finite + reciprocal_tail + image_tail + local_finite + local_tail;
out = struct( ...
  'coordinate_order', {{'00', '10', '01', '20', '11', '02'}}, ...
  'retained_finite_upper', finite + local_finite, ...
  'reciprocal_tail', reciprocal_tail, ...
  'image_tail', image_tail, ...
  'local_tail', local_tail, ...
  'retained_image_taylor_tail', zeros(1, 6), ...
  'whole', whole, ...
  'pass', reciprocal_pass && image_pass && local_pass && ...
    all(isfinite(whole)));
end

function upper = LOCAL_ewald_finite( ...
    k, bloch, d, h, chi, RX, RY, IX, IY, UX, UY, configuration)
PI_LO = 3.0;
PI_UP = 22.0 / 7.0;
sqrt_pi_lower = LOCAL_sqrt_lower(PI_LO);
sqrt_pi_upper = LOCAL_sqrt_upper(PI_UP);
moments = [sqrt_pi_upper / 2.0, 0.5, sqrt_pi_upper / 4.0];
radial = [moments(1), ...
  2.0 * h^2 * RX * moments(1) + 2.0 * h * moments(2), ...
  (4.0 * h^4 * RX^2 + 2.0 * h^2) * moments(1) + ...
  8.0 * h^3 * RX * moments(2) + 4.0 * h^2 * moments(3)];
orders = [0, 0; 1, 0; 0, 1; 2, 0; 1, 1; 0, 2];
upper = zeros(1, 6);
for mode = -(configuration.reciprocal_cutoff - 1.0): ...
    configuration.reciprocal_cutoff - 1.0
  [a_lower, a_upper] = LOCAL_transverse_interval(bloch, mode, d);
  [q_lower, q_upper, evanescent] = LOCAL_rayleigh_abs_bounds(k, ...
    a_lower, a_upper);
  if q_lower <= 0.0
    upper(:) = Inf;
    return;
  end
  if evanescent && q_lower >= 2.0 * h^2 * UX
    for j = 1:6
      r = orders(j, 1);
      s = orders(j, 2);
      decay = LOCAL_decay_upper(q_lower^2 / (4.0 * h^2));
      upper(j) = upper(j) + radial(r + 1.0) / ...
        (d * sqrt_pi_lower) * a_upper^s / q_lower * decay * ...
        LOCAL_exp_upper(h^2 * IX^2 + a_upper * IY);
    end
  else
    u = q_upper / (2.0 * h) + h * RX;
    exp_u = LOCAL_exp_upper(u^2);
    E0 = 1.0 + 2.0 * u * exp_u / sqrt_pi_lower;
    E1 = 2.0 * exp_u / sqrt_pi_lower;
    E2 = 4.0 * u * exp_u / sqrt_pi_lower;
    base = LOCAL_exp_upper(q_upper * RX + a_upper * IY) / ...
      (2.0 * d * q_lower);
    F0 = base * E0;
    F1 = base * (q_upper * E0 + h * E1);
    F2 = base * (q_upper^2 * E0 + ...
      2.0 * q_upper * h * E1 + h^2 * E2);
    upper = upper + [F0, F1, a_upper * F0, F2, ...
      a_upper * F1, a_upper^2 * F0];
  end
end
for image = [-(configuration.image_cutoff - 1.0):-1.0, ...
    1.0:configuration.image_cutoff - 1.0]
  u = h^2 * ((abs(image) * d - UY)^2 - IX^2 - IY^2);
  if u <= 0.0
    upper(:) = Inf;
    return;
  end
  decay = LOCAL_decay_upper(u);
  H01 = LOCAL_exp_upper(chi) * decay / u;
  H2 = LOCAL_exp_upper(chi) * decay * (1.0 / u + 1.0 / u^2);
  zx = 2.0 * h^2 * RX;
  zy = 2.0 * h^2 * (abs(image) * d + RY);
  upper = upper + [H01, zx * H01, zy * H01, ...
    zx^2 * H2 + 2.0 * h^2 * H01, zx * zy * H2, ...
    zy^2 * H2 + 2.0 * h^2 * H01] / (4.0 * PI_LO);
end
end

function [tail, pass] = LOCAL_reciprocal_tail( ...
    k, bloch, d, h, RX, IX, IY, UX, cutoff)
PI_LO = 3.0;
PI_UP = 22.0 / 7.0;
step_lower = 2.0 * PI_LO / d;
step_upper = 2.0 * PI_UP / d;
sqrt_pi_lower = LOCAL_sqrt_lower(PI_LO);
sqrt_pi_upper = LOCAL_sqrt_upper(PI_UP);
moments = [sqrt_pi_upper / 2.0, 0.5, sqrt_pi_upper / 4.0];
radial = [moments(1), ...
  2.0 * h^2 * RX * moments(1) + 2.0 * h * moments(2), ...
  (4.0 * h^4 * RX^2 + 2.0 * h^2) * moments(1) + ...
  8.0 * h^3 * RX * moments(2) + 4.0 * h^2 * moments(3)];
orders = [0, 0; 1, 0; 0, 1; 2, 0; 1, 1; 0, 2];
tail = zeros(1, 6);
pass = true;
for side = [-1.0, 1.0]
  transverse_lower = step_lower * cutoff - abs(bloch);
  transverse_upper = step_upper * cutoff + abs(bloch);
  q_lower = LOCAL_sqrt_lower(transverse_lower^2 - k^2);
  pass = pass && transverse_lower > k && q_lower >= 2.0 * h^2 * UX;
  for j = 1:6
    r = orders(j, 1);
    s = orders(j, 2);
    ratio = (1.0 + step_upper / transverse_lower)^s * ...
      LOCAL_decay_upper(step_lower * ...
      (2.0 * transverse_lower + step_lower) / (4.0 * h^2)) * ...
      LOCAL_exp_upper(step_upper * IY);
    first = transverse_upper^s / q_lower * ...
      LOCAL_decay_upper(q_lower^2 / (4.0 * h^2)) * ...
      LOCAL_exp_upper(transverse_upper * IY);
    tail(j) = tail(j) + radial(r + 1.0) * ...
      LOCAL_exp_upper(h^2 * IX^2) / (d * sqrt_pi_lower) * ...
      first / (1.0 - ratio);
    pass = pass && ratio < 1.0;
  end
end
end

function [tail, pass] = LOCAL_image_tail( ...
    d, h, chi, RX, RY, IX, IY, UY, cutoff)
PI_LO = 3.0;
u = h^2 * ((cutoff * d - UY)^2 - IX^2 - IY^2);
distance = cutoff * d + RY;
S1 = zeros(1, 3);
S2 = zeros(1, 3);
pass = cutoff * d > UY && u > 0.0;
for a = 0:2
  ratio = (1.0 + d / distance)^a * ...
    LOCAL_decay_upper(h^2 * d * (2.0 * (cutoff * d - UY) + d));
  S1(a + 1.0) = 2.0 * distance^a * LOCAL_decay_upper(u) / ...
    (u * (1.0 - ratio));
  S2(a + 1.0) = 2.0 * distance^a * LOCAL_decay_upper(u) / ...
    (u^2 * (1.0 - ratio));
  pass = pass && ratio < 1.0;
end
scale = LOCAL_exp_upper(chi) / (4.0 * PI_LO);
zx = 2.0 * h^2 * RX;
tail = scale * [S1(1), zx * S1(1), 2.0 * h^2 * S1(2), ...
  zx^2 * (S1(1) + S2(1)) + 2.0 * h^2 * S1(1), ...
  zx * 2.0 * h^2 * (S1(2) + S2(2)), ...
  (2.0 * h^2)^2 * (S1(3) + S2(3)) + 2.0 * h^2 * S1(1)];
end

function [finite, tail, pass] = LOCAL_local_ewald( ...
    h, chi, RX, RY, configuration)
PI_LO = 3.0;
R0 = h^2 * (RX^2 + RY^2);
B = configuration.local_cauchy_radius_factor * R0;
cutoff = configuration.ewald_local_cutoff;
if B <= R0
  finite = Inf(1, 6);
  tail = finite;
  pass = false;
  return;
end
x = chi * B;
xQ = chi * (1.0 + B);
ratios = [x / (cutoff + 2.0)^2, ...
  B * (cutoff + 1.0) / (cutoff + 2.0)^2, ...
  x / (cutoff + 2.0)^2 * (1.0 + 1.0 / (cutoff + 2.0)), ...
  xQ * (cutoff + 1.0) / (cutoff + 2.0)^2];
factorial = LOCAL_factorial(cutoff + 1.0);
harmonic = sum(1.0 ./ (1.0:cutoff + 1.0));
tau_J = x^(cutoff + 1.0) / (factorial^2 * (1.0 - ratios(1)));
tau_S = B^(cutoff + 1.0) / ((cutoff + 1.0) * factorial * ...
  (1.0 - ratios(2)));
tau_D = harmonic * x^(cutoff + 1.0) / ...
  (factorial^2 * (1.0 - ratios(3)));
tau_Q = xQ^(cutoff + 1.0) / ((1.0 + B) * ...
  (cutoff + 1.0) * factorial * (1.0 - ratios(4)));
c_eta = LOCAL_logabs_upper(chi) + 1.0 + 22.0 / 7.0;
tau_C = (tau_J * (LOCAL_exp_upper(B) - 1.0 + c_eta) + ...
  LOCAL_exp_upper(chi * B) * tau_S + LOCAL_exp_upper(B) * tau_Q) / ...
  (4.0 * PI_LO) + tau_D / (2.0 * PI_LO);
tail = LOCAL_radial_to_coordinate( ...
  [tau_C, tau_C / (B - R0), 2.0 * tau_C / (B - R0)^2], ...
  h, RX, RY);

Jfinite = 0.0;
Sfinite = 0.0;
Dfinite = 0.0;
Qfinite = 0.0;
Hn = 0.0;
for n = 0:cutoff
  Jfinite = Jfinite + (chi * B)^n / LOCAL_factorial(n)^2;
  if n >= 1.0
    Hn = Hn + 1.0 / n;
    Sfinite = Sfinite + B^n / (n * LOCAL_factorial(n));
    Dfinite = Dfinite + Hn * (chi * B)^n / LOCAL_factorial(n)^2;
    inner = 0.0;
    for m = 0:n - 1.0
      inner = inner + LOCAL_factorial(n - m - 1.0) * B^m;
    end
    Qfinite = Qfinite + chi^n / LOCAL_factorial(n)^2 * inner;
  end
end
Mfinite = Jfinite * (Sfinite + c_eta) / (4.0 * PI_LO) + ...
  LOCAL_exp_upper(B) * Qfinite / (4.0 * PI_LO) + ...
  Dfinite / (2.0 * PI_LO);
finite = LOCAL_radial_to_coordinate( ...
  [Mfinite, Mfinite / (B - R0), 2.0 * Mfinite / (B - R0)^2], ...
  h, RX, RY);
pass = all(ratios < 1.0) && all(isfinite([finite, tail]));
end

function coordinate = LOCAL_radial_to_coordinate(radial, h, RX, RY)
coordinate = [radial(1), ...
  2.0 * h^2 * RX * radial(2), ...
  2.0 * h^2 * RY * radial(2), ...
  4.0 * h^4 * RX^2 * radial(3) + 2.0 * h^2 * radial(2), ...
  4.0 * h^4 * RX * RY * radial(3), ...
  4.0 * h^4 * RY^2 * radial(3) + 2.0 * h^2 * radial(2)];
end

function [a_lower, a_upper] = LOCAL_transverse_interval(bloch, mode, d)
v1 = bloch + 2.0 * 3.0 * mode / d;
v2 = bloch + 2.0 * (22.0 / 7.0) * mode / d;
lo = min(v1, v2);
hi = max(v1, v2);
if lo <= 0.0 && hi >= 0.0
  a_lower = 0.0;
else
  a_lower = min(abs(lo), abs(hi));
end
a_upper = max(abs(lo), abs(hi));
end

function [q_lower, q_upper, evanescent] = LOCAL_rayleigh_abs_bounds( ...
    k, a_lower, a_upper)
if a_lower > k
  evanescent = true;
  q_lower = LOCAL_sqrt_lower(a_lower^2 - k^2);
  q_upper = LOCAL_sqrt_upper(a_upper^2 - k^2);
elseif a_upper < k
  evanescent = false;
  q_lower = LOCAL_sqrt_lower(k^2 - a_upper^2);
  q_upper = LOCAL_sqrt_upper(k^2 - a_lower^2);
else
  evanescent = false;
  q_lower = 0.0;
  q_upper = LOCAL_sqrt_upper(max(k^2 - a_lower^2, a_upper^2 - k^2));
end
end


%% ==================== Off-surface Rayleigh whole-action certificate ====================
% Frozen finite Rayleigh rows are enclosed directly with outgoing branch bounds.

function out = LOCAL_off_surface_certificate(z, geometry)
orders = (-256.0:255.0).';
value_upper = 0.0;
normal_upper = 0.0;
value_second = 0.0;
normal_strip = 0.0;
value_strip = 0.0;
strip_growth = geometry.strip_position_imag_upper;
clearance = min(geometry.left_clearance_lower, ...
  geometry.right_clearance_lower);
branch_pass = true;
for j = 1:numel(orders)
  [a_lower, a_upper] = LOCAL_transverse_interval( ...
    double(z.beta), orders(j), double(z.d));
  [q_lower, q_upper, evanescent] = LOCAL_rayleigh_abs_bounds( ...
    double(z.khat), a_lower, a_upper);
  if q_lower <= 0.0
    branch_pass = false;
    continue;
  end
  row = LOCAL_row_operator(double(z.xi_left_unit_512(j, :))) + ...
    LOCAL_row_operator(double(z.xi_right_unit_512(j, :)));
  multiplier = row / (2.0 * q_lower * LOCAL_sqrt_lower(double(z.d)));
  if evanescent
    real_factor = LOCAL_decay_upper(q_lower * clearance);
    strip_factor = real_factor * LOCAL_exp_upper(a_upper * strip_growth);
  else
    real_factor = 1.0;
    strip_factor = LOCAL_exp_upper((q_upper + a_upper) * strip_growth);
  end
  parameter_derivative_one = geometry.radius * (q_upper + a_upper);
  unit_normal_one = q_upper + a_upper;
  value_upper = value_upper + multiplier * real_factor;
  normal_upper = normal_upper + multiplier * real_factor * unit_normal_one;
  value_second = value_second + multiplier * real_factor * ...
    (parameter_derivative_one^2 + parameter_derivative_one);
  value_strip = value_strip + multiplier * strip_factor;
  normal_strip = normal_strip + multiplier * strip_factor * ...
    unit_normal_one * LOCAL_exp_upper(geometry.parameter_strip_width);
end
scale = geometry.boundary_length_upper / ...
  LOCAL_sqrt_lower(geometry.boundary_length_lower);
out = struct( ...
  'value_whole_action_radius', scale * value_upper, ...
  'normal_whole_action_radius', scale * normal_upper, ...
  'value_parameter_second_upper', value_second, ...
  'value_strip_upper', value_strip, ...
  'normal_strip_upper', normal_strip, ...
  'minimum_clearance_lower', clearance, ...
  'speed_lower', geometry.speed_lower, ...
  'normal_contraction_speed_pass', geometry.speed_lower > 0.0, ...
  'finite_rayleigh_centers_used', false, ...
  'special_function_library_used', false, ...
  'pass', branch_pass && clearance > 0.0 && geometry.speed_lower > 0.0 && ...
    all(isfinite([value_upper, normal_upper, value_second, ...
      value_strip, normal_strip])));
end

%% ==================== Cutoff and material assemblies ====================
% L is chosen from complete local, regular, and off-surface high-mode tails.

function out = LOCAL_select_cutoff( ...
    z, geometry, local, regular, off_surface, state_sum, configuration)
candidates = configuration.cutoff_schedule;
material_tail = Inf(size(candidates));
lifting_tail = Inf(size(candidates));
pieces = cell(size(candidates));
positive_power_pass = true;
for j = 1:numel(candidates)
  pieces{j} = LOCAL_high_material_pieces( ...
    z, geometry, local, regular, off_surface, candidates(j));
  material_tail(j) = state_sum * ...
    (LOCAL_sqrt_upper(pieces{j}.local_material_squared) + ...
     LOCAL_sqrt_upper(pieces{j}.regular_material_squared) + ...
     LOCAL_sqrt_upper(pieces{j}.off_surface_material_squared))^2;
  lifting_tail(j) = state_sum * ...
    (LOCAL_sqrt_upper(pieces{j}.local_lifting_squared) + ...
     LOCAL_sqrt_upper(pieces{j}.regular_lifting_squared) + ...
     LOCAL_sqrt_upper(pieces{j}.off_surface_lifting_squared))^2;
  positive_power_pass = positive_power_pass && ...
    pieces{j}.positive_power_at_L > 0.0 && ...
    isfinite(pieces{j}.positive_power_at_L);
end
tight = LOCAL_sqrt_upper(max(material_tail)) >= 0.0;
first = [];
for j = 1:numel(candidates)
  if LOCAL_sqrt_upper(material_tail(j)) <= configuration.tail_tolerance && ...
      2.0 * LOCAL_sqrt_upper(lifting_tail(j)) <= ...
      configuration.tail_tolerance
    first = j;
    break;
  end
end
if isempty(first)
  selected = numel(candidates);
  tolerance_pass = false;
else
  selected = first;
  tolerance_pass = true;
end
out = struct( ...
  'candidate_L', candidates, ...
  'material_tail_squared', material_tail, ...
  'lifting_tail_squared', lifting_tail, ...
  'piecewise', {pieces}, ...
  'selected_index', selected, ...
  'selected_L', candidates(selected), ...
  'first_passing_index', first, ...
  'tail_tolerance', configuration.tail_tolerance, ...
  'tail_tolerance_pass', tolerance_pass, ...
  'selection_rule', 'first explicit complete-tail pass; else last finite', ...
  'inter_level_drift_used', false, ...
  'empirical_safety_factor_used', false, ...
  'positive_power_pass', positive_power_pass, ...
  'pass', positive_power_pass && tight && ...
    all(isfinite([material_tail, lifting_tail])));
end

function pieces = LOCAL_high_material_pieces( ...
    z, geometry, local, regular, off_surface, L)
PI_LO = 3.0;
PI_UP = 22.0 / 7.0;
R = geometry.radius;
theta = geometry.theta_lower;
Theta = geometry.Theta_upper;
xi = L / R;
d_scaled_lower = double(z.delta_c) / ...
  LOCAL_sqrt_upper(theta * Theta);
trace_lower = 2.0 * LOCAL_sqrt_lower(theta / Theta) * ...
  LOCAL_tanh_lower(xi * d_scaled_lower);
local_material_p2 = 2.0 * local.nor.Q2^2 / ...
  (geometry.boundary_length_lower * trace_lower) * R^5 * ...
  (L^(-5.0) + L^(-4.0) / 4.0);
local_lifting_p2 = 2.0 * local.val.Q2^2 / ...
  geometry.boundary_length_lower * ...
  (geometry.tubular_C0_upper * R^4 * ...
   (L^(-4.0) + L^(-3.0) / 3.0) + ...
   geometry.tubular_C1_upper * R^2 * ...
   (L^(-2.0) + L^(-1.0)));
two_pi_lower = 2.0 * PI_LO;
local_material_p4 = 2.0 * local.nor.Q4^2 * ...
  geometry.boundary_length_upper^8 / ...
  (trace_lower * two_pi_lower^9) * ...
  (L^(-9.0) + L^(-8.0) / 8.0);
local_lifting_p4 = 2.0 * local.val.Q4^2 * ( ...
  geometry.boundary_length_upper^7 * geometry.tubular_C0_upper / ...
  two_pi_lower^8 * (L^(-8.0) + L^(-7.0) / 7.0) + ...
  geometry.boundary_length_upper^5 * geometry.tubular_C1_upper / ...
  two_pi_lower^6 * (L^(-6.0) + L^(-5.0) / 5.0));
local_material = min(local_material_p2, local_material_p4);
local_lifting = min(local_lifting_p2, local_lifting_p4);
p4_values = [local_material_p2, local_material_p4, local_material, ...
  local_lifting_p2, local_lifting_p4, local_lifting];
p4_forced_pass = all(isfinite(p4_values)) && all(p4_values >= 0.0) && ...
  local_material <= local_material_p2 && ...
  local_material <= local_material_p4 && ...
  local_lifting <= local_lifting_p2 && ...
  local_lifting <= local_lifting_p4;
r = LOCAL_decay_upper(4.0 * PI_LO * ...
  geometry.arclength_strip_lower / geometry.boundary_length_upper);
positive_power = LOCAL_positive_power_upper(r, L);
regular_material = LOCAL_analytic_material_tail( ...
  regular.normal_strip_upper, geometry, trace_lower, r, L);
off_material = LOCAL_analytic_material_tail( ...
  off_surface.normal_strip_upper, geometry, trace_lower, r, L);
regular_lifting = LOCAL_analytic_lifting_tail( ...
  regular.value_strip_upper, geometry, r, L);
off_lifting = LOCAL_analytic_lifting_tail( ...
  off_surface.value_strip_upper, geometry, r, L);
pieces = struct( ...
  'local_material_squared', local_material, ...
  'local_material_p2_squared', local_material_p2, ...
  'local_material_p4_squared', local_material_p4, ...
  'regular_material_squared', regular_material, ...
  'off_surface_material_squared', off_material, ...
  'local_lifting_squared', local_lifting, ...
  'local_lifting_p2_squared', local_lifting_p2, ...
  'local_lifting_p4_squared', local_lifting_p4, ...
  'regular_lifting_squared', regular_lifting, ...
  'off_surface_lifting_squared', off_lifting, ...
  'strip_ratio_upper', r, ...
  'positive_power_at_L', positive_power, ...
  'trace_denominator_lower', trace_lower, ...
  'p4_tail_rule', ...
    'min of complete p2 and p4 local squares before norm assembly', ...
  'p4_forced_pass', p4_forced_pass, ...
  'pi_bounds', [PI_LO, PI_UP]);
end

function squared = LOCAL_analytic_material_tail(A, geometry, denominator, r, L)
power = LOCAL_positive_power_upper(r, L);
squared = geometry.boundary_length_upper^2 * A^2 / ...
  (3.0 * denominator) * power / (L * (1.0 - r));
end

function squared = LOCAL_analytic_lifting_tail(A, geometry, r, L)
power = LOCAL_positive_power_upper(r, L);
S0 = power / (1.0 - r);
S2 = power * (L^2 / (1.0 - r) + ...
  2.0 * L * r / (1.0 - r)^2 + ...
  r * (1.0 + r) / (1.0 - r)^3);
frequency_upper = 2.0 * (22.0 / 7.0) / ...
  geometry.boundary_length_lower;
squared = 2.0 * geometry.boundary_length_upper * A^2 * ...
  (geometry.tubular_C0_upper * S0 + ...
   geometry.tubular_C1_upper * frequency_upper^2 * S2);
end

function out = LOCAL_material_modules( ...
    z, geometry, local, regular, off_surface, state_sum, L)
orders = (-(L - 1.0):L - 1.0).';
absolute_orders = abs(orders);
inverse_trace_weight = zeros(size(orders));
lifting_weight = zeros(size(orders));
for j = 1:numel(orders)
  xi = absolute_orders(j) / geometry.radius;
  lambda_i = LOCAL_sqrt_lower(double(z.mu_h) * double(z.rho_disk) + ...
    xi^2 / (geometry.theta_lower * geometry.Theta_upper));
  lambda_e = LOCAL_sqrt_lower(double(z.mu_h) + ...
    xi^2 / (geometry.theta_lower * geometry.Theta_upper));
  trace_lower = geometry.theta_lower * ( ...
    lambda_i * LOCAL_tanh_lower(double(z.delta_c) * lambda_i) + ...
    lambda_e * LOCAL_tanh_lower(double(z.delta_c) * lambda_e));
  inverse_trace_weight(j) = 1.0 / trace_lower;
  lifting_weight(j) = ...
    geometry.tubular_C0_upper + geometry.tubular_C1_upper * xi^2;
end

% One O(L) recurrence encloses every positive strip factor.
strip_ratio = LOCAL_decay_upper(geometry.target_strip_decay_rate_lower);
strip_power = zeros(L, 1);
strip_power(1) = 1.0;
for order = 1:L - 1.0
  strip_power(order + 1.0) = max( ...
    strip_power(order) * strip_ratio, 1.0e-100);
end
mode_decay = strip_power(absolute_orders + 1.0);
local_scale = geometry.boundary_length_upper^2 / ...
  (4.0 * 3.0^2 * LOCAL_sqrt_lower(geometry.boundary_length_lower));
local_scale_p4 = geometry.boundary_length_upper^4 / ...
  (16.0 * 3.0^4 * LOCAL_sqrt_lower(geometry.boundary_length_lower));
local_value = local.value_whole_action_radius * ones(size(orders));
local_normal = local.normal_whole_action_radius * ones(size(orders));
local_value_p2 = local_value;
local_normal_p2 = local_normal;
local_value_p4 = local_value;
local_normal_p4 = local_normal;
nonzero = absolute_orders > 0.0;
local_value_p2(nonzero) = ...
  local.val.Q2 * local_scale ./ absolute_orders(nonzero).^2;
local_normal_p2(nonzero) = ...
  local.nor.Q2 * local_scale ./ absolute_orders(nonzero).^2;
local_value_p4(nonzero) = ...
  local.val.Q4 * local_scale_p4 ./ absolute_orders(nonzero).^4;
local_normal_p4(nonzero) = ...
  local.nor.Q4 * local_scale_p4 ./ absolute_orders(nonzero).^4;
local_value = min(local_value, min(local_value_p2, local_value_p4));
local_normal = min(local_normal, min(local_normal_p2, local_normal_p4));
regular_value = min( ...
  regular.value_whole_action_radius * ones(size(orders)), ...
  geometry.target_strip_prefactor_upper * ...
    regular.value_strip_upper * mode_decay);
regular_normal = min( ...
  regular.normal_whole_action_radius * ones(size(orders)), ...
  geometry.target_strip_prefactor_upper * ...
    regular.normal_strip_upper * mode_decay);
off_value = min( ...
  off_surface.value_whole_action_radius * ones(size(orders)), ...
  geometry.target_strip_prefactor_upper * ...
    off_surface.value_strip_upper * mode_decay);
off_normal = min( ...
  off_surface.normal_whole_action_radius * ones(size(orders)), ...
  geometry.target_strip_prefactor_upper * ...
    off_surface.normal_strip_upper * mode_decay);
value_radius = local_value + regular_value + off_value;
normal_radius = local_normal + regular_normal + off_normal;
pieces = LOCAL_high_material_pieces( ...
  z, geometry, local, regular, off_surface, L);
material_tail = state_sum * ...
  (LOCAL_sqrt_upper(pieces.local_material_squared) + ...
   LOCAL_sqrt_upper(pieces.regular_material_squared) + ...
   LOCAL_sqrt_upper(pieces.off_surface_material_squared))^2;
lifting_tail = state_sum * ...
  (LOCAL_sqrt_upper(pieces.local_lifting_squared) + ...
   LOCAL_sqrt_upper(pieces.regular_lifting_squared) + ...
   LOCAL_sqrt_upper(pieces.off_surface_lifting_squared))^2;
component_values = [local_value; local_normal; regular_value; ...
  regular_normal; off_value; off_normal; value_radius; normal_radius];
modewise_pass = all(isfinite(component_values(:))) && ...
  isfinite(strip_ratio) && strip_ratio > 0.0 && strip_ratio < 1.0 && ...
  geometry.target_strip_prefactor_upper > 0.0 && ...
  geometry.target_strip_decay_rate_lower > 0.0 && ...
  all(strip_power > 0.0) && all(local_value <= ...
  local.value_whole_action_radius) && all(local_normal <= ...
  local.normal_whole_action_radius) && all(regular_value <= ...
  regular.value_whole_action_radius) && all(regular_normal <= ...
  regular.normal_whole_action_radius) && all(off_value <= ...
  off_surface.value_whole_action_radius) && all(off_normal <= ...
  off_surface.normal_whole_action_radius);
p4_retained_pass = local.p4_C6_certificate.pass && ...
  all(isfinite([local_value_p4; local_normal_p4])) && ...
  all([local_value_p4; local_normal_p4] >= 0.0) && ...
  local_value(~nonzero) == local.value_whole_action_radius && ...
  local_normal(~nonzero) == local.normal_whole_action_radius && ...
  all(local_value(nonzero) <= local_value_p4(nonzero)) && ...
  all(local_normal(nonzero) <= local_normal_p4(nonzero)) && ...
  pieces.p4_forced_pass;
modewise_pass = modewise_pass && p4_retained_pass;
out = struct( ...
  'material', struct( ...
    'finite_squared', state_sum * sum( ...
      normal_radius.^2 .* inverse_trace_weight), ...
    'tail_squared', material_tail, ...
    'retained_radius', normal_radius, ...
    'inverse_trace_weight', inverse_trace_weight, ...
    'high_pieces', pieces), ...
  'lifting', struct( ...
    'finite_squared', state_sum * sum(value_radius.^2 .* lifting_weight), ...
    'tail_squared', lifting_tail, ...
    'retained_radius', value_radius, ...
    'lifting_weight', lifting_weight, ...
    'high_pieces', pieces), ...
  'lifting_finite_squared', state_sum * sum( ...
    value_radius.^2 .* lifting_weight), ...
  'lifting_tail_squared', lifting_tail, ...
  'modewise_component_minima', struct( ...
    'orders', orders, ...
    'strip_ratio_upper', strip_ratio, ...
    'strip_power_upper', strip_power, ...
    'local_value', local_value, ...
    'local_normal', local_normal, ...
    'local_value_p2', local_value_p2, ...
    'local_normal_p2', local_normal_p2, ...
    'local_value_p4', local_value_p4, ...
    'local_normal_p4', local_normal_p4, ...
    'regular_value', regular_value, ...
    'regular_normal', regular_normal, ...
    'off_surface_value', off_value, ...
    'off_surface_normal', off_normal, ...
    'combined_value', value_radius, ...
    'combined_normal', normal_radius, ...
    'local_ell_zero_uses_whole_action', ...
      local_value(orders == 0.0) == local.value_whole_action_radius && ...
      local_normal(orders == 0.0) == local.normal_whole_action_radius, ...
    'weights_applied_once', true, ...
    'p4_retained_rule', ...
      'ell zero whole; nonzero minimum of whole, p2, and p4 radii', ...
    'p4_forced_pass', p4_retained_pass, ...
    'pass', modewise_pass));
end

%% ==================== Direct artificial-wall certificate ====================
% Rebuild wall rows from frozen states and densities without stored residuals.

function out = LOCAL_direct_wall_certificate( ...
    z, input_contract, geometry, density, frozen_audit)
K = double(z.K);
M = double(z.M);
orders = double(z.wall_orders_512(:));
state_orders = (-M:M).';
embed = zeros(numel(orders), K);
index_support_pass = numel(state_orders) == K;
for j = 1:K
  at = find(orders == state_orders(j), 1);
  if isempty(at)
    index_support_pass = false;
  else
    embed(at, j) = 1.0;
  end
end

zero_block = zeros(size(embed));
wall_input_reference = [embed, zero_block; zero_block, embed];
wall_input = double(z.wall_input_unit_512);
wall_input_exact_map_defect = LOCAL_relative_sharp( ...
  wall_input, wall_input_reference);
wall_input_exact_map_pass = isequal(wall_input, wall_input_reference);
input_left = wall_input(1:numel(orders), :);
input_right = wall_input(numel(orders) + 1.0:end, :);

Gplus_reference = [double(z.Dplus); ...
  double(z.Dplus) * double(z.Pplus)];
Gminus_reference = [double(z.Dminus) * double(z.Pminus); ...
  double(z.Dminus)];
Gplus_defect = LOCAL_relative_sharp(double(z.Gplus), Gplus_reference);
Gminus_defect = LOCAL_relative_sharp(double(z.Gminus), Gminus_reference);
G_block_layout_exact_pass = isequal(double(z.Gplus), Gplus_reference) && ...
  isequal(double(z.Gminus), Gminus_reference);
G_block_layout_diagnostic_finite = ...
  all(isfinite([Gplus_defect, Gminus_defect]));
G_block_layout_enters_bound = false;
G_data_used_directly = true;

wall_basis_contract_pass = frozen_audit.wall_basis_contract_pass && ...
  double(input_contract.wall_source_orders) == numel(orders);
xi_left = double(z.xi_left_unit_512);
xi_right = double(z.xi_right_unit_512);
xi_left_radius = LOCAL_row_operator(xi_left);
xi_right_radius = LOCAL_row_operator(xi_right);
shared_left_radius = LOCAL_row_operator(input_left);
shared_right_radius = LOCAL_row_operator(input_right);
flat_normal_left_radius = 0.5 * (xi_left_radius + xi_right_radius);
flat_normal_right_radius = flat_normal_left_radius;
flat_value_left_radius = zeros(size(orders));
flat_value_right_radius = zeros(size(orders));
curve_normal_radius = zeros(size(orders));
curve_value_radius = zeros(size(orders));
q_lower_all = zeros(size(orders));
q_upper_all = zeros(size(orders));

A_tau = geometry.boundary_length_upper * ...
  density.tau_derivative_upper(1);
A_eta = geometry.boundary_length_upper * ...
  density.eta_second_derivative_upper(1);
clearance = min(geometry.left_clearance_lower, ...
  geometry.right_clearance_lower);
for j = 1:numel(orders)
  [a_lower, a_upper] = LOCAL_transverse_interval( ...
    double(z.beta), orders(j), double(z.d));
  [q_lower, q_upper, ~] = LOCAL_rayleigh_abs_bounds( ...
    double(z.khat), a_lower, a_upper);
  q_lower_all(j) = q_lower;
  q_upper_all(j) = q_upper;
  if q_lower <= 0.0
    flat_value_left_radius(j) = Inf;
    flat_value_right_radius(j) = Inf;
    curve_normal_radius(j) = Inf;
    curve_value_radius(j) = Inf;
    continue;
  end
  phase_decay = 1.0;
  if a_lower > double(z.khat)
    phase_decay = LOCAL_decay_upper(q_lower * clearance);
  end
  flat_value_left_radius(j) = ...
    (xi_left_radius(j) + xi_right_radius(j)) / (2.0 * q_lower);
  flat_value_right_radius(j) = flat_value_left_radius(j);
  common_curve = phase_decay / ...
    (2.0 * LOCAL_sqrt_lower(double(z.d))) * ...
    ((q_upper + a_upper) * A_tau + A_eta);
  curve_normal_radius(j) = common_curve;
  curve_value_radius(j) = common_curve / q_lower;
end

Q_left_radius = flat_normal_left_radius + curve_normal_radius;
Q_right_radius = flat_normal_right_radius + curve_normal_radius;
plus_sequence_radius = Q_right_radius * LOCAL_matrix_one(z.Gplus) + ...
  Q_left_radius * LOCAL_matrix_one(double(z.Gplus) * double(z.Pplus));
minus_sequence_radius = Q_left_radius * LOCAL_matrix_one(z.Gminus) + ...
  Q_right_radius * LOCAL_matrix_one(double(z.Gminus) * double(z.Pminus));

q_center = double(z.q_center(:));
q_left = q_center(1:K);
q_right = q_center(K + 1.0:end);
center_dx_left_radius = zeros(size(orders));
center_dx_right_radius = zeros(size(orders));
center_value_left_radius = zeros(size(orders));
center_value_right_radius = zeros(size(orders));
shared_center_left = double(z.Dminus) * double(z.cminus(:));
shared_center_right = double(z.Dplus) * double(z.cplus(:));
for j = 1:K
  at = find(orders == state_orders(j), 1);
  if isempty(at)
    continue;
  end
  q_upper = q_upper_all(at);
  q_pair_radius = LOCAL_abs_sharp(q_left(j)) + ...
    LOCAL_abs_sharp(q_right(j));
  center_dx_left_radius(at) = q_upper * q_pair_radius;
  center_dx_right_radius(at) = q_upper * q_pair_radius;
  center_value_left_radius(at) = ...
    LOCAL_abs_sharp(shared_center_left(j)) + q_pair_radius;
  center_value_right_radius(at) = ...
    LOCAL_abs_sharp(shared_center_right(j)) + q_pair_radius;
end

plus_singleton_radius = center_dx_right_radius + ...
  Q_left_radius * LOCAL_vector_one(double(z.Gplus) * double(z.cplus));
minus_singleton_radius = center_dx_left_radius + ...
  Q_right_radius * LOCAL_vector_one(double(z.Gminus) * double(z.cminus));
value_left_radius = shared_left_radius + flat_value_left_radius + ...
  curve_value_radius;
value_right_radius = shared_right_radius + flat_value_right_radius + ...
  curve_value_radius;

governing_sources = {'certificate.q_center', 'certificate.Dplus', ...
  'certificate.Dminus', 'certificate.Gplus', 'certificate.Gminus', ...
  'certificate.Pplus', 'certificate.Pminus', 'certificate.cplus', ...
  'certificate.cminus', 'certificate.xi_left_unit_512', ...
  'certificate.xi_right_unit_512', 'certificate.wall_input_unit_512', ...
  'certificate.eta_unit_256'};
forbidden_sources = {'raw_maps.Jplus', 'raw_maps.Jminus', ...
  'certificate.center_wall_jumps', ...
  'certificate.center_left_value_mismatch', ...
  'certificate.center_right_value_mismatch'};
stored_residuals_unused = isempty(intersect(governing_sources, ...
  forbidden_sources));
normal_governing_sources = {'certificate.q_center', 'certificate.Gplus', ...
  'certificate.Gminus', 'certificate.Pplus', 'certificate.Pminus', ...
  'certificate.cplus', 'certificate.cminus', ...
  'certificate.xi_left_unit_512', 'certificate.xi_right_unit_512', ...
  'certificate.eta_unit_256'};
normal_direct_shared_trace_used = any(strcmp(normal_governing_sources, ...
  'certificate.wall_input_unit_512'));
all_retained_nonwood = all(q_lower_all > 0.0);
gamma_interval_pass = all(isfinite([q_lower_all; q_upper_all])) && ...
  all(q_lower_all > 0.0) && all(q_upper_all >= q_lower_all);
[positive_high_a_lower, ~] = LOCAL_transverse_interval( ...
  double(z.beta), 256.0, double(z.d));
[negative_high_a_lower, ~] = LOCAL_transverse_interval( ...
  double(z.beta), -257.0, double(z.d));
first_high_evanescent = positive_high_a_lower > double(z.khat) && ...
  negative_high_a_lower > double(z.khat);
value_triangle_pass = isequal(value_left_radius, ...
  shared_left_radius + flat_value_left_radius + curve_value_radius) && ...
  isequal(value_right_radius, shared_right_radius + ...
  flat_value_right_radius + curve_value_radius);
source_speed_ds_pass = geometry.boundary_length_upper > 0.0 && ...
  isfinite(A_tau) && isfinite(A_eta);
wall_basis_normalized_pass = wall_basis_contract_pass && ...
  strcmp(char(input_contract.wall_basis), ...
    'd^(-1/2)*exp(i*(beta+2*pi*m/d)*y)');
eta_sign_pass = strcmp(strtrim(char(z.density_coordinate)), ...
  '[tau;zeta], zeta=-sigma');
collar_disjoint_pass = 2.0 * double(z.delta_w) <= double(z.L);
rho_exterior = 1.0;
rho_exterior_one_pass = rho_exterior == 1.0 && ...
  isequal(double(z.mu_h), double(z.khat)^2 * rho_exterior);
trace_half_width = 0.5;
wall_spacing = double(z.X_R) - double(z.X_L);
trace_half_width_pass = trace_half_width > 0.0 && ...
  2.0 * trace_half_width <= double(z.L) && ...
  2.0 * trace_half_width <= wall_spacing;
direct_normal_pass = index_support_pass && G_data_used_directly && ...
  ~G_block_layout_enters_bound && G_block_layout_diagnostic_finite && ...
  all(isfinite([Q_left_radius; Q_right_radius; plus_sequence_radius; ...
  minus_sequence_radius; plus_singleton_radius; minus_singleton_radius])) && ...
  all_retained_nonwood && gamma_interval_pass && first_high_evanescent && ...
  source_speed_ds_pass && ~normal_direct_shared_trace_used;
