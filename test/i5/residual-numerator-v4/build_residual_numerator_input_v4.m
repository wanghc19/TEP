end

function squared = LOCAL_wall_lift_side_tail( ...
    z, clearance, A_tau, A_eta, first)
q0_lower = 2.0 * 3.0 / double(z.d);
q0_upper = 2.0 * (22.0 / 7.0) / double(z.d);
a0 = q0_lower * first - abs(double(z.beta));
kappa0 = LOCAL_sqrt_lower(a0^2 - double(z.khat)^2);
r = LOCAL_decay_upper(2.0 * clearance * q0_lower);
power = LOCAL_positive_power_upper(r, first);
S0 = power / (1.0 - r);
S1 = power * (first / (1.0 - r) + r / (1.0 - r)^2);
S2 = power * (first^2 / (1.0 - r) + ...
  2.0 * first * r / (1.0 - r)^2 + ...
  r * (1.0 + r) / (1.0 - r)^3);
