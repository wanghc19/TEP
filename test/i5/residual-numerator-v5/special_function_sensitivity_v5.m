function result = special_function_sensitivity_v5( ...
    artifact_path, input_path, output_path)
%SPECIAL_FUNCTION_SENSITIVITY_V5 Bound partial Faddeeva/E1 sensitivity.
% Purpose:
%   Compute the I5.1f restricted phase-2 gains A_F and A_E for the fixed
%   run-02 graph, without changing or re-evaluating its signed centers.
% Input:
%   artifact_path - Explicit frozen I3 certificate MAT path.
%   input_path - Explicit self-contained v5 phase-1 input MAT path.
%   output_path - Explicit create-once sensitivity result MAT target.
% Output:
%   result - Partial ideal-sensitivity gains, oracle thresholds, and gates.
% Main algorithm:
%   Stream every retained target/source pair, propagate unit absolute errors
%   in Faddeeva_erfc and E1 through the exact coordinate formulas, contract
%   density/Jacobian/normal factors, and apply the matched finite/cell S_J.
% Based on:
%   design-5-1f.md, equations (I5.1f-23)--(I5.1f-37).
% Notes:
%   All non-F/E primitives are held at their library values.  Delta_sf,rest
%   and delta_fp remain UNRESOLVED; this is not a reliable residual bound.

timer = tic;
[artifact_path, input_path, output_path] = LOCAL_paths( ...
  artifact_path, input_path, output_path);
artifact_data = load(artifact_path, 'staged');
input_data = load(input_path, 'experiment_input');
if ~isfield(artifact_data, 'staged') || ...
    ~isfield(artifact_data.staged, 'certificate') || ...
    ~isfield(input_data, 'experiment_input')
  error('I5v5Sensitivity:Schema', 'An explicit MAT input has wrong schema.');
end
z = artifact_data.staged.certificate;
input = input_data.experiment_input;
input_audit = LOCAL_validate_input(z, input, artifact_path);

[row_gain, argument_ledger] = LOCAL_streamed_row_gains(z, input);
[matched_state_energy, state_ledger] = LOCAL_matched_state_energy(z, input);
normal_weight_sum = sum(double(input.weights.normal_inverse_trace(:)));
lifting_weight_sum = sum(double(input.weights.lifting(:)));

families = {'Faddeeva_erfc', 'expint_E1'};
value_gain = [row_gain.Faddeeva.val, row_gain.E1.val];
normal_gain = [row_gain.Faddeeva.nor, row_gain.E1.nor];
final_gain = normal_gain * sqrt(matched_state_energy * normal_weight_sum) + ...
  2 * value_gain * sqrt(matched_state_energy * lifting_weight_sum);

family_allocation = [0.00125, 0.00125];
rest_allocation = 0.0025;
required_uniform_absolute_error = family_allocation ./ final_gain;
Faddeeva_imaginary_half_width = max(abs( ...
  argument_ledger.Faddeeva.actual_argument_region(3:4)));
E1_positive_lower = argument_ledger.E1.certified_outer_box(1);
exact_function_magnitude_upper = [ ...
  2 + 2 * Faddeeva_imaginary_half_width / sqrt(pi) * ...
    exp(Faddeeva_imaginary_half_width^2), ...
  exp(-E1_positive_lower) / E1_positive_lower];
required_uniform_exact_relative_error = family_allocation ./ ...
  (final_gain .* exact_function_magnitude_upper);
M_ideal = LOCAL_phase1_scalar(input);
all_values = [value_gain, normal_gain, final_gain, ...
  required_uniform_absolute_error, exact_function_magnitude_upper, ...
  required_uniform_exact_relative_error, matched_state_energy, ...
  normal_weight_sum, lifting_weight_sum, M_ideal];
finite_nonnegative = isreal(all_values) && all(isfinite(all_values)) && ...
  all(all_values >= 0) && all(final_gain > 0);

gates = struct( ...
  'phase1_input', input_audit.pass, ...
  'fixed_run02_L512_N2048_Q18', input_audit.fixed_graph, ...
  'all_actual_arguments_enumerated', argument_ledger.complete, ...
  'Faddeeva_argument_ledger_match', argument_ledger.Faddeeva.match, ...
  'E1_argument_ledger_match', argument_ledger.E1.match, ...
  'outgoing_nonwood_branch', argument_ledger.outgoing_nonwood_branch, ...
  'Faddeeva_E1_only_retained_regular_center', true, ...
  'Faddeeva_E1_not_in_analytic_radii_or_high_tails', true, ...
  'actual_library_phase_magnitudes_used', true, ...
  'density_source_jacobian_normal_target_phase_each_once', true, ...
  'matched_finite_cell_state_energy', state_ledger.pass, ...
  'global_lifting_factor_once', true, ...
  'delta_sf_rest_unresolved', true, ...
  'delta_fp_unresolved', true, ...
  'sampled_continuous_domain_maximum_used', false, ...
  'finite_nonnegative', finite_nonnegative);
required_true = {'phase1_input', 'fixed_run02_L512_N2048_Q18', ...
  'all_actual_arguments_enumerated', 'Faddeeva_argument_ledger_match', ...
  'E1_argument_ledger_match', 'outgoing_nonwood_branch', ...
  'Faddeeva_E1_only_retained_regular_center', ...
  'Faddeeva_E1_not_in_analytic_radii_or_high_tails', ...
  'actual_library_phase_magnitudes_used', ...
  'density_source_jacobian_normal_target_phase_each_once', ...
  'matched_finite_cell_state_energy', 'global_lifting_factor_once', ...
  'delta_sf_rest_unresolved', 'delta_fp_unresolved', 'finite_nonnegative'};
gate_values = cellfun(@(name) isequal(gates.(name), true), required_true);
gates.pass = all(gate_values) && ...
  ~gates.sampled_continuous_domain_maximum_used;
if ~gates.pass
  error('I5v5Sensitivity:Gate', 'A restricted sensitivity gate failed.');
end

workspace = whos;
result = struct( ...
  'status', 'PARTIAL_FADDEEVA_E1_SENSITIVITY_ONLY', ...
  'claim_scope', 'PARTIAL_IDEAL_SENSITIVITY', ...
  'condition_label', 'CONDITIONAL_ON_UNIFORM_ABSOLUTE_FADDEEVA_E1_ERRORS', ...
  'certification_label', 'NON_CERTIFIED_ROUNDOFF_EXCLUDED', ...
  'M_ideal_library', M_ideal, ...
  'families', {families}, ...
  'unit_row_gain', row_gain, ...
  'matched_state_energy', matched_state_energy, ...
  'state_ledger', state_ledger, ...
  'normal_weight_sum', normal_weight_sum, ...
  'lifting_weight_sum', lifting_weight_sum, ...
  'A_F', final_gain(1), ...
  'A_E', final_gain(2), ...
  'family_allocation', family_allocation, ...
  'rest_allocation', rest_allocation, ...
  'total_special_function_allocation', sum(family_allocation) + rest_allocation, ...
  'required_uniform_absolute_error', struct( ...
    'Faddeeva_erfc', required_uniform_absolute_error(1), ...
    'expint_E1', required_uniform_absolute_error(2)), ...
  'exact_function_magnitude_upper', struct( ...
    'Faddeeva_erfc', exact_function_magnitude_upper(1), ...
    'expint_E1', exact_function_magnitude_upper(2), ...
    'relative_denominator', 'exact function magnitude'), ...
  'required_uniform_exact_relative_error', struct( ...
    'Faddeeva_erfc', required_uniform_exact_relative_error(1), ...
    'expint_E1', required_uniform_exact_relative_error(2)), ...
  'partial_implication_if_F_E_contracts_hold', ...
    M_ideal + sum(family_allocation), ...
  'delta_sf_Faddeeva_E1', ...
    'A_F*epsilon_F + A_E*epsilon_E; epsilon values not supplied', ...
  'delta_sf_rest', 'UNRESOLVED', ...
  'delta_sf', 'UNRESOLVED', ...
  'delta_fp', 'UNRESOLVED', ...
  'argument_ledger', argument_ledger, ...
  'gates', gates, ...
  'provenance', struct('artifact_path', artifact_path, ...
    'phase1_input_path', input_path, 'historical_output_read', false, ...
    'phase1_result_read', false, 'eigenpair_solves', 0, ...
    'bie_density_solves', 0, 'qz_decompositions', 0, ...
    'propagation_matrix_solves', 0), ...
  'resource', struct('elapsed_seconds_before_save', toc(timer), ...
    'workspace_proxy_mib_before_save', sum([workspace.bytes]) / 2^20));
save(output_path, 'result', '-v7.3');
end

%% ==================== Portable input and fixed graph ====================
% Only the original artifact and self-contained phase-1 input are consumed.

function [artifact_path, input_path, output_path] = LOCAL_paths( ...
    artifact_path, input_path, output_path)
artifact_path = LOCAL_path(artifact_path, 'artifact_path');
input_path = LOCAL_path(input_path, 'input_path');
output_path = LOCAL_path(output_path, 'output_path');
if ~isfile(artifact_path) || ~isfile(input_path)
  error('I5v5Sensitivity:InputPath', 'Both explicit input MAT files must exist.');
end
if isfile(output_path) || isfolder(output_path)
  error('I5v5Sensitivity:CreateOnce', 'output_path must be a new target.');
end
if ~isfolder(fileparts(output_path))
  error('I5v5Sensitivity:OutputDirectory', 'The output directory does not exist.');
end
end

function value = LOCAL_path(value, name)
if isstring(value) && isscalar(value)
  value = char(value);
end
if ~ischar(value) || isempty(value)
  error('I5v5Sensitivity:Path', '%s must be nonempty text.', name);
end
end

function audit = LOCAL_validate_input(z, input, artifact_path)
required_z = {'khat', 'beta', 'd', 'q_center', 'Gminus', 'Gplus', ...
  'Pminus', 'Pplus', 'cminus', 'cplus', 'eta_unit_256'};
required_input = {'schema', 'condition_label', 'delta_sf', 'delta_fp', ...
  'configuration', 'geometry', 'density', 'weights', 'regular', ...
  'material', 'wall', 'propagation', 'gates', 'structural_pass', 'provenance'};
if ~all(isfield(z, required_z)) || ~all(isfield(input, required_input))
  error('I5v5Sensitivity:Fields', 'The restricted input contract is incomplete.');
end
c = input.configuration;
g = input.geometry;
density = input.density;
fixed_graph = isequal(double(c.residual_mode_cutoff), 512) && ...
  isequal(double(c.evaluation_node_count), 2048) && ...
  isequal(double(c.ewald_local_cutoff), 18) && ...
  isequal(double(c.reciprocal_cutoff), 5) && ...
  isequal(double(c.image_cutoff), 3) && ...
  isequal(double(c.cell_cutoff), 16) && ...
  isequal(double(c.ewald_split), 2) && ...
  isequal(double(c.target_block_size), 32);
mode_orders = (-(double(c.residual_mode_cutoff) - 1): ...
  double(c.residual_mode_cutoff) - 1).';
dimensions = numel(g.parameter_nodes) == double(c.evaluation_node_count) && ...
  isequal(size(g.position), [double(c.evaluation_node_count), 2]) && ...
  isequal(size(g.normal), [double(c.evaluation_node_count), 2]) && ...
  numel(g.speed_nodes) == double(c.evaluation_node_count) && ...
  isequal(double(input.weights.mode_orders(:)), mode_orders) && ...
  size(density.tau_coeff, 1) == numel(density.orders) && ...
  isequal(size(density.tau_coeff), size(density.zeta_coeff));
labels = strcmp(char(input.schema), 'EPOST_I5_1F_INPUT_V5') && ...
  strcmp(char(input.condition_label), ...
    'CONDITIONAL_ON_EXACT_SPECIAL_FUNCTION_EVALUATION') && ...
  strcmp(char(input.delta_sf), 'UNRESOLVED') && ...
  strcmp(char(input.delta_fp), 'UNRESOLVED');
N_eta = size(z.eta_unit_256, 1) / 2;
eta = double(z.eta_unit_256);
tau_coeff = fftshift(fft(eta(1:N_eta, :), [], 1), 1) / N_eta;
zeta_coeff = fftshift(fft(eta(N_eta + 1:end, :), [], 1), 1) / N_eta;
density_match = isequal(double(input.density.orders(:)), ...
    (-N_eta / 2:N_eta / 2 - 1).') && ...
  isequal(input.density.tau_coeff, tau_coeff) && ...
  isequal(input.density.zeta_coeff, zeta_coeff);
artifact_match = isfield(input.provenance, 'artifact_path') && ...
  strcmp(char(input.provenance.artifact_path), artifact_path);
phase1 = isequal(input.structural_pass, true) && ...
  isfield(input.regular, 'sf_ledger') && ...
  isfield(input.regular.sf_ledger, 'calls') && ...
  isfield(input.regular.sf_ledger.calls, 'Faddeeva_erfc') && ...
  isfield(input.regular.sf_ledger.calls, 'expint') && ...
  isfield(input.regular.gates, 'centers_evaluated') && ...
  isequal(input.regular.gates.centers_evaluated, true) && ...
  isequal(input.propagation.minus.pass, true) && ...
  isequal(input.propagation.plus.pass, true);
audit = struct('labels', labels, 'dimensions', dimensions, ...
  'fixed_graph', fixed_graph, 'density_match', density_match, ...
  'artifact_path_match', artifact_match, 'phase1', phase1, ...
  'pass', labels && dimensions && fixed_graph && density_match && ...
    artifact_match && phase1);
if ~audit.pass
  error('I5v5Sensitivity:InputGate', 'The fixed run-02 graph gate failed.');
end
end

%% ==================== Faddeeva and E1 coordinate gains ====================
% Equations (I5.1f-27)--(I5.1f-34) are evaluated for every actual argument.

function [row_gain, ledger] = LOCAL_streamed_row_gains(z, input)
c = input.configuration;
g = input.geometry;
N = double(c.evaluation_node_count);
L = double(c.residual_mode_cutoff);
block_size = double(c.target_block_size);
nodes = double(g.parameter_nodes(:));
position = double(g.position);
normal = double(g.normal);
speed = double(g.speed_nodes(:));
orders = double(input.density.orders(:));
density_phase = exp(1i * nodes * orders.');
tau = density_phase * double(input.density.tau_coeff);
zeta_density = density_phase * double(input.density.zeta_coeff);
tau_norm = vecnorm(tau, 2, 2);
zeta_norm = vecnorm(zeta_density, 2, 2);

source_sum.Faddeeva.val = zeros(N, 1);
source_sum.Faddeeva.nor = zeros(N, 1);
source_sum.E1.val = zeros(N, 1);
source_sum.E1.nor = zeros(N, 1);
faddeeva_region = [Inf, -Inf, Inf, -Inf, Inf, -Inf];
E1_region = [Inf, -Inf];
branch_pass = true;
h_source = 2 * pi / N;

for first_target = 1:block_size:N
  target_ids = first_target:min(first_target + block_size - 1, N);
  target = position(target_ids, :);
  X = target(:, 1) - position(:, 1).';
  Y = target(:, 2) - position(:, 2).';
  [U_F, region_F, reciprocal_branch] = LOCAL_faddeeva_coordinate_gain( ...
    z, c, X, Y);
  [U_E, region_E] = LOCAL_E1_coordinate_gain(z, c, X, Y);
  faddeeva_region = LOCAL_merge_complex_region(faddeeva_region, region_F);
  E1_region = [min(E1_region(1), region_E(1)), ...
    max(E1_region(2), region_E(2))];
  branch_pass = branch_pass && reciprocal_branch;
  [Z_F_val, Z_F_nor] = LOCAL_contract_Z( ...
    U_F, target_ids, normal, speed, tau_norm, zeta_norm);
  [Z_E_val, Z_E_nor] = LOCAL_contract_Z( ...
    U_E, target_ids, normal, speed, tau_norm, zeta_norm);
  source_sum.Faddeeva.val(target_ids) = h_source * sum(Z_F_val, 2);
  source_sum.Faddeeva.nor(target_ids) = h_source * sum(Z_F_nor, 2);
  source_sum.E1.val(target_ids) = h_source * sum(Z_E_val, 2);
  source_sum.E1.nor(target_ids) = h_source * sum(Z_E_nor, 2);
end

ell = (-(L - 1):L - 1).';
P = double(g.boundary_length);
target_phase_abs = abs(exp(-1i * (2 * pi * ell / P) * ...
  double(g.arclength_nodes(:).')));
target_scale = (2 * pi / N) / sqrt(P);
families = {'Faddeeva', 'E1'};
for family_index = 1:numel(families)
  family = families{family_index};
  by_mode_val = target_scale * target_phase_abs * ...
    (speed .* source_sum.(family).val);
  by_mode_nor = target_scale * target_phase_abs * ...
    (speed .* source_sum.(family).nor);
  row_gain.(family) = struct('val', max(by_mode_val), ...
    'nor', max(by_mode_nor), 'by_mode_val', by_mode_val, ...
    'by_mode_nor', by_mode_nor);
end

recorded_F = input.regular.sf_ledger.calls.Faddeeva_erfc;
recorded_E = input.regular.sf_ledger.calls.expint;
F_match = isequal(faddeeva_region, [recorded_F.real_min, recorded_F.real_max, ...
  recorded_F.imag_min, recorded_F.imag_max, ...
  recorded_F.abs_min, recorded_F.abs_max]);
E_match = isequal(E1_region, [recorded_E.real_min, recorded_E.real_max]);
ledger = struct( ...
  'complete', all(isfinite([faddeeva_region, E1_region])) && ...
    E1_region(1) >= 1.44 && E1_region(2) <= 23.68, ...
  'outgoing_nonwood_branch', branch_pass, ...
  'Faddeeva', struct('actual_argument_region', faddeeva_region, ...
    'generated_scalar_argument_count', 2 * N^2 * ...
      (2 * double(c.reciprocal_cutoff) - 1), ...
    'recorded_scalar_argument_count', recorded_F.scalar_arguments, ...
    'match', F_match && isequal(recorded_F.scalar_arguments, ...
      2 * N^2 * (2 * double(c.reciprocal_cutoff) - 1))), ...
  'E1', struct('actual_argument_region', E1_region, ...
    'certified_outer_box', [1.44, 23.68], ...
    'generated_scalar_argument_count', N^2 * ...
      (2 * (double(c.image_cutoff) - 1)), ...
    'recorded_scalar_argument_count', recorded_E.scalar_arguments, ...
    'match', E_match && isequal(recorded_E.scalar_arguments, ...
      N^2 * (2 * (double(c.image_cutoff) - 1)))), ...
  'target_phase_library_magnitude_range', ...
    [min(target_phase_abs(:)), max(target_phase_abs(:))], ...
  'continuous_domain_sampled_maximum_used', false);
end

function [U, region, branch_pass] = LOCAL_faddeeva_coordinate_gain(z, c, X, Y)
U = LOCAL_zero_coordinate(size(X));
kappa = double(z.khat);
beta = double(z.beta);
d = double(z.d);
h = double(c.ewald_split) / d;
region = [Inf, -Inf, Inf, -Inf, Inf, -Inf];
branch_pass = true;
for mode = -(double(c.reciprocal_cutoff) - 1): ...
    double(c.reciprocal_cutoff) - 1
  transverse = beta + 2 * pi * mode / d;
  radicand = transverse^2 - kappa^2;
  q = sqrt(complex(radicand));
  if real(q) < 0 || (real(q) == 0 && imag(q) > 0)
    q = -q;
  end
  branch_pass = branch_pass && q ~= 0 && ...
    ((radicand > 0 && real(q) > 0) || ...
    (radicand < 0 && imag(q) < 0));
  phase_abs = abs(exp(1i * transverse * Y) / (4 * d * q));
  coefficient = zeros(size(X));
  for sign_value = [-1, 1]
    argument = q / (2 * h) + sign_value * h * X;
    exponential_abs = abs(exp(sign_value * q * X));
    coefficient = coefficient + phase_abs .* exponential_abs;
    region = LOCAL_merge_complex_region(region, LOCAL_complex_region(argument));
  end
  U.U00 = U.U00 + coefficient;
  U.U10 = U.U10 + abs(q) * coefficient;
  U.U01 = U.U01 + abs(transverse) * coefficient;
  U.U20 = U.U20 + abs(q)^2 * coefficient;
  U.U11 = U.U11 + abs(transverse) * abs(q) * coefficient;
  U.U02 = U.U02 + abs(transverse)^2 * coefficient;
end
end

function [U, region] = LOCAL_E1_coordinate_gain(z, c, X, Y)
U = LOCAL_zero_coordinate(size(X));
d = double(z.d);
h = double(c.ewald_split) / d;
kappa = double(z.khat);
chi_E = (kappa * d / (2 * double(c.ewald_split)))^2;
Q = double(c.ewald_local_cutoff);
region = [Inf, -Inf];
for image_index = [-(double(c.image_cutoff) - 1):-1, ...
    1:double(c.image_cutoff) - 1]
  shifted_Y = Y - image_index * d;
  argument = h^2 * (X.^2 + shifted_Y.^2);
  region = [min(region(1), min(argument(:))), ...
    max(region(2), max(argument(:)))];
  G0 = zeros(size(argument));
  G1 = zeros(size(argument));
  G2 = zeros(size(argument));
  a_r = 1;
  g_r = ones(size(argument));
  g_previous = [];
  g_previous_two = [];
  for order = 0:Q
    G0 = G0 + abs(a_r) * g_r;
    if order >= 1
      G1 = G1 + abs(a_r) * g_previous;
    end
    if order >= 2
      G2 = G2 + abs(a_r) * g_previous_two;
    end
    g_previous_two = g_previous;
    g_previous = g_r;
    g_r = g_r .* abs(argument) / (order + 1);
    a_r = a_r * chi_E / (order + 1);
  end
  phase_abs = abs(exp(1i * double(z.beta) * image_index * d) / (4 * pi));
  zx = 2 * h^2 * X;
  zy = 2 * h^2 * shifted_Y;
  U.U00 = U.U00 + phase_abs * G0;
  U.U10 = U.U10 + phase_abs * (abs(zx) .* G1);
  U.U01 = U.U01 + phase_abs * (abs(zy) .* G1);
  U.U20 = U.U20 + phase_abs * ...
    (abs(zx).^2 .* G2 + 2 * h^2 * G1);
  U.U11 = U.U11 + phase_abs * (abs(zx .* zy) .* G2);
  U.U02 = U.U02 + phase_abs * ...
    (abs(zy).^2 .* G2 + 2 * h^2 * G1);
end
end

function U = LOCAL_zero_coordinate(matrix_size)
zero = zeros(matrix_size);
U = struct('U00', zero, 'U10', zero, 'U01', zero, ...
  'U20', zero, 'U11', zero, 'U02', zero);
end

function [Z_val, Z_nor] = LOCAL_contract_Z( ...
    U, target_ids, normal, speed, tau_norm, zeta_norm)
source_nx = abs(normal(:, 1).');
source_ny = abs(normal(:, 2).');
target_nx = abs(normal(target_ids, 1));
target_ny = abs(normal(target_ids, 2));
source_speed = speed(:).';
tau_row = tau_norm(:).';
zeta_row = zeta_norm(:).';
source_normal_gain = U.U10 .* source_nx + U.U01 .* source_ny;
target_normal_gain = U.U10 .* target_nx + U.U01 .* target_ny;
mixed_gain = U.U20 .* (target_nx * source_nx) + ...
  U.U11 .* (target_nx * source_ny + target_ny * source_nx) + ...
  U.U02 .* (target_ny * source_ny);
Z_val = source_speed .* ...
  (source_normal_gain .* tau_row + U.U00 .* zeta_row);
Z_nor = source_speed .* ...
  (mixed_gain .* tau_row + target_normal_gain .* zeta_row);
end

function region = LOCAL_complex_region(values)
region = [min(real(values(:))), max(real(values(:))), ...
  min(imag(values(:))), max(imag(values(:))), ...
  min(abs(values(:))), max(abs(values(:)))];
end

function merged = LOCAL_merge_complex_region(first, second)
merged = [min(first(1), second(1)), max(first(2), second(2)), ...
  min(first(3), second(3)), max(first(4), second(4)), ...
  min(first(5), second(5)), max(first(6), second(6))];
end

%% ==================== Matched downstream functional gain ====================
% S_J matches the phase-1 finite-cell plus block-power ownership exactly.

function [energy, ledger] = LOCAL_matched_state_energy(z, input)
J = double(input.configuration.cell_cutoff);
energy = norm(double(z.q_center), 2)^2;
sides = {'minus', 'plus'};
entries = cell(2, 1);
for side_index = 1:2
  side = sides{side_index};
  G = double(z.(['G', side]));
  P = double(z.(['P', side]));
  state = double(z.(['c', side]));
  finite_energy = 0;
  for cell_index = 0:J - 1
    finite_energy = finite_energy + norm(G * state, 2)^2;
    state = P * state;
  end
  cap = double(input.propagation.(side).sum_power_squared_upper);
  tail_energy = cap * norm(G, 'fro')^2 * norm(state, 2)^2;
  energy = energy + finite_energy + tail_energy;
  entries{side_index} = struct('side', side, ...
    'finite_cell_energy', finite_energy, 'tail_energy', tail_energy, ...
    'cell_cutoff', J, 'tail_state_norm', norm(state, 2), ...
    'block_power_sum_upper', cap);
end
entries = vertcat(entries{:});
all_values = [energy; [entries.finite_cell_energy].'; ...
  [entries.tail_energy].'; [entries.tail_state_norm].'; ...
  [entries.block_power_sum_upper].'];
ledger = struct('entries', entries, 'finite_cells_0_through_J_minus_1', true, ...
  'tail_starts_at_P_to_J_c', true, 'center_included_once', true, ...
  'pass', isreal(all_values) && all(isfinite(all_values)) && ...
    all(all_values >= 0));
end

function M_ideal = LOCAL_phase1_scalar(input)
wall_normal = double(input.wall.normal.bound_squared);
material_normal = double(input.material.finite.normal_squared) + ...
  double(input.material.cell_tail.normal_squared) + ...
  double(input.material.high_tail.normal_squared);
material_lifting = double(input.material.finite.lifting_squared) + ...
  double(input.material.cell_tail.lifting_squared) + ...
  double(input.material.high_tail.lifting_squared);
wall_lifting = double(input.wall.lifting.bound_squared);
M_ideal = sqrt(wall_normal) + sqrt(material_normal) + ...
  2 * sqrt(material_lifting + wall_lifting);
end
