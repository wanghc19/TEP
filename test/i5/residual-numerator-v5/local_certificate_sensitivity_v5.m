function result = local_certificate_sensitivity_v5( ...
    artifact_path, input_path, output_path)
%LOCAL_CERTIFICATE_SENSITIVITY_V5 Bound a narrow local certificate subchain.
% Purpose:
%   Compute the I5.1f local log-gamma--exponential sensitivity D_local for
%   the fixed run-02 analytic certificate, without re-evaluating a center.
% Input:
%   artifact_path - Explicit frozen I3 certificate MAT path.
%   input_path - Explicit self-contained v5 phase-1 input MAT path.
%   output_path - Explicit create-once sensitivity result MAT target.
% Output:
%   result - Partial ideal-sensitivity gain, prospective oracle caps, gates.
% Main algorithm:
%   Reuse the complete stored local source/target/series radii and selected
%   p2/p4 high tails, apply the matched and whole-state energy factors, and
%   instantiate (I5.1f-47)--(I5.1f-54).
% Notes:
%   The caps are ordinary floating-point targets, not measured oracle errors.
%   Delta_sf,rest2 and delta_fp remain UNRESOLVED.

timer = tic;
[artifact_path, input_path, output_path] = LOCAL_paths( ...
  artifact_path, input_path, output_path);
artifact_data = load(artifact_path, 'staged');
input_data = load(input_path, 'experiment_input');
if ~isfield(artifact_data, 'staged') || ...
    ~isfield(artifact_data.staged, 'certificate') || ...
    ~isfield(input_data, 'experiment_input')
  error('I5v5LocalSensitivity:Schema', ...
    'An explicit MAT input has the wrong schema.');
end
z = artifact_data.staged.certificate;
input = input_data.experiment_input;
input_audit = LOCAL_validate_input(z, input, artifact_path);

[matched_state_energy, matched_state_ledger] = ...
  LOCAL_matched_state_energy(z, input);
[whole_state_energy, whole_state_ledger] = ...
  LOCAL_whole_state_energy(z, input);

radius_val = double(input.local.radius.val.total(:));
radius_nor = double(input.local.radius.nor.total(:));
weight_val = double(input.weights.lifting(:));
weight_nor = double(input.weights.normal_inverse_trace(:));
high_val_squared = double(input.local.high_tail.val.selected_squared);
high_nor_squared = double(input.local.high_tail.nor.selected_squared);

D_val_squared = matched_state_energy * sum(weight_val .* radius_val.^2) + ...
  whole_state_energy * high_val_squared;
D_nor_squared = matched_state_energy * sum(weight_nor .* radius_nor.^2) + ...
  whole_state_energy * high_nor_squared;
D_val = sqrt(D_val_squared);
D_nor = sqrt(D_nor_squared);
D_local = D_nor + 2 * D_val;

local_allocation = 0.00125;
remaining_rest2_allocation = 0.00125;
target_log_upper_factor = log1p(local_allocation / D_local);
epsilon_logGamma = target_log_upper_factor / 8;
eta_exp = -expm1(-target_log_upper_factor / 2);
bilateral_lower = exp(-4 * epsilon_logGamma) / (1 + eta_exp);
bilateral_upper = exp(4 * epsilon_logGamma) / (1 - eta_exp);
relative_radius = bilateral_upper - 1;
realized_library_allocation = relative_radius * D_local;

exp_return_audit = LOCAL_exp_return_audit(z, input);
all_values = [matched_state_energy; whole_state_energy; radius_val; ...
  radius_nor; weight_val; weight_nor; high_val_squared; high_nor_squared; ...
  D_val_squared; D_nor_squared; D_val; D_nor; D_local; local_allocation; ...
  remaining_rest2_allocation; target_log_upper_factor; epsilon_logGamma; ...
  eta_exp; bilateral_lower; bilateral_upper; relative_radius; ...
  realized_library_allocation];
finite_positive = isreal(all_values) && all(isfinite(all_values)) && ...
  all(all_values >= 0) && D_local > 0 && bilateral_lower > 0 && ...
  bilateral_upper >= 1;

gates = struct( ...
  'phase1_input', input_audit.pass, ...
  'fixed_run02_L512_N2048_Q32', input_audit.fixed_graph, ...
  'local_radius_source_target_series_identity', ...
    input_audit.local_radius_identity, ...
  'local_high_p2_p4_selected_minimum', input_audit.local_high_minimum, ...
  'integer_loggamma_argument_set_1_to_34', ...
    exp_return_audit.integer_argument_set, ...
  'fixed_local_positive_graph_count', exp_return_audit.graph_count_pass, ...
  'positive_nonunderflowing_local_exp_returns', ...
    exp_return_audit.positive_nonunderflowing, ...
  'matched_finite_cell_state_energy', matched_state_ledger.pass, ...
  'whole_state_high_mode_energy', whole_state_ledger.pass, ...
  'epsilon_logGamma_nonnegative', epsilon_logGamma >= 0, ...
  'eta_exp_in_unit_interval', eta_exp >= 0 && eta_exp < 1, ...
  'bilateral_factor_order', bilateral_lower > 0 && ...
    bilateral_lower <= 1 && bilateral_upper >= 1, ...
  'bilateral_enclosure_theorem_not_sampled', true, ...
  'centers_or_operators_reevaluated', false, ...
  'delta_sf_rest2_unresolved', true, ...
  'delta_fp_unresolved', true, ...
  'finite_positive', finite_positive);
required_true = {'phase1_input', 'fixed_run02_L512_N2048_Q32', ...
  'local_radius_source_target_series_identity', ...
  'local_high_p2_p4_selected_minimum', ...
  'integer_loggamma_argument_set_1_to_34', ...
  'fixed_local_positive_graph_count', ...
  'positive_nonunderflowing_local_exp_returns', ...
  'matched_finite_cell_state_energy', 'whole_state_high_mode_energy', ...
  'epsilon_logGamma_nonnegative', 'eta_exp_in_unit_interval', ...
  'bilateral_factor_order', ...
  'bilateral_enclosure_theorem_not_sampled', ...
  'delta_sf_rest2_unresolved', 'delta_fp_unresolved', 'finite_positive'};
gates.pass = all(cellfun(@(name) isequal(gates.(name), true), required_true)) && ...
  ~gates.centers_or_operators_reevaluated;
if ~gates.pass
  error('I5v5LocalSensitivity:Gate', ...
    'A local log-gamma--exponential sensitivity gate failed.');
end

workspace = whos;
result = struct( ...
  'status', 'PARTIAL_LOCAL_LOGGAMMA_EXP_SENSITIVITY', ...
  'claim_scope', 'PARTIAL_IDEAL_SENSITIVITY', ...
  'condition_label', ...
    'CONDITIONAL_ON_UNIFORM_LOCAL_LOGGAMMA_AND_RELATIVE_EXP_ERRORS', ...
  'certification_label', 'NON_CERTIFIED_ROUNDOFF_EXCLUDED', ...
  'D_val_squared', D_val_squared, 'D_nor_squared', D_nor_squared, ...
  'D_val', D_val, 'D_nor', D_nor, 'D_local', D_local, ...
  'matched_state_energy', matched_state_energy, ...
  'matched_state_ledger', matched_state_ledger, ...
  'whole_state_energy', whole_state_energy, ...
  'whole_state_ledger', whole_state_ledger, ...
  'local_radius', struct('val', radius_val, 'nor', radius_nor, ...
    'high_val_squared', high_val_squared, ...
    'high_nor_squared', high_nor_squared), ...
  'local_allocation', local_allocation, ...
  'remaining_rest2_allocation', remaining_rest2_allocation, ...
  'target_log_upper_factor', target_log_upper_factor, ...
  'prospective_error_cap', struct( ...
    'epsilon_logGamma', epsilon_logGamma, 'eta_exp', eta_exp, ...
    'contract', ['|gammaln_lib(n)-logGamma(n)|<=epsilon_logGamma; ', ...
      '|exp_lib(x)-exp(x)|<=eta_exp*exp(x)']), ...
  'bilateral_factor', struct('lower', bilateral_lower, ...
    'upper', bilateral_upper, 'relative_radius', relative_radius), ...
  'realized_library_allocation', realized_library_allocation, ...
  'theoretical_allocation_identity', ...
    'c_Gamma_e*D_local=0.00125 in exact arithmetic by I5.1f-54', ...
  'delta_sf_local_loggamma_exp', ...
    'c_Gamma_e*D_local; oracle contracts not supplied', ...
  'delta_sf_rest2', 'UNRESOLVED', ...
  'delta_sf', 'UNRESOLVED', ...
  'delta_fp', 'UNRESOLVED', ...
  'exp_return_audit', exp_return_audit, ...
  'gates', gates, ...
  'provenance', struct('artifact_path', artifact_path, ...
    'phase1_input_path', input_path, 'historical_output_read', false, ...
    'phase1_result_read', false, 'centers_reevaluated', false, ...
    'true_operators_reevaluated', false, 'eigenpair_solves', 0, ...
    'bie_density_solves', 0, 'qz_decompositions', 0, ...
    'propagation_matrix_solves', 0), ...
  'resource', struct('elapsed_seconds_before_save', toc(timer), ...
    'workspace_proxy_mib_before_save', sum([workspace.bytes]) / 2^20));
save(output_path, 'result', '-v7.3');
end

%% ==================== Portable input and fixed graph ====================
% Only the original artifact and self-contained phase-1 input are consumed.

function [artifact_path, input_path, output_path] = LOCAL_paths( ...
    artifact_path, input_path, output_path)
artifact_path = LOCAL_path(artifact_path, 'artifact_path');
input_path = LOCAL_path(input_path, 'input_path');
output_path = LOCAL_path(output_path, 'output_path');
if ~isfile(artifact_path) || ~isfile(input_path)
  error('I5v5LocalSensitivity:InputPath', ...
    'Both explicit input MAT files must exist.');
end
if isfile(output_path) || isfolder(output_path)
  error('I5v5LocalSensitivity:CreateOnce', ...
    'output_path must be a new target.');
end
if ~isfolder(fileparts(output_path))
  error('I5v5LocalSensitivity:OutputDirectory', ...
    'The output directory does not exist.');
end
end

function value = LOCAL_path(value, name)
if isstring(value) && isscalar(value)
  value = char(value);
end
if ~ischar(value) || isempty(value)
  error('I5v5LocalSensitivity:Path', '%s must be nonempty text.', name);
end
end

function audit = LOCAL_validate_input(z, input, artifact_path)
required_z = {'khat', 'rho_disk', 'R', 'q_center', 'Gminus', 'Gplus', ...
  'Pminus', 'Pplus', 'cminus', 'cplus'};
required_input = {'schema', 'condition_label', 'delta_sf', 'delta_fp', ...
  'configuration', 'local', 'weights', 'material', 'propagation', ...
  'gates', 'structural_pass', 'provenance'};
if ~all(isfield(z, required_z)) || ~all(isfield(input, required_input))
  error('I5v5LocalSensitivity:Fields', ...
    'The local sensitivity input contract is incomplete.');
end
c = input.configuration;
fixed_graph = isequal(double(c.residual_mode_cutoff), 512) && ...
  isequal(double(c.evaluation_node_count), 2048) && ...
  isequal(double(c.kernel_series_cutoff), 32) && ...
  isequal(double(c.alias_cutoff), 64) && ...
  isequal(double(c.cell_cutoff), 16);
labels = strcmp(char(input.schema), 'EPOST_I5_1F_INPUT_V5') && ...
  strcmp(char(input.condition_label), ...
    'CONDITIONAL_ON_EXACT_SPECIAL_FUNCTION_EVALUATION') && ...
  strcmp(char(input.delta_sf), 'UNRESOLVED') && ...
  strcmp(char(input.delta_fp), 'UNRESOLVED');
local = input.local;
required_radius = {'source', 'target', 'series', 'total'};
required_high = {'p2_squared', 'p4_squared', 'selected_squared'};
local_fields = isfield(local, 'radius') && isfield(local.radius, 'val') && ...
  isfield(local.radius, 'nor') && ...
  all(isfield(local.radius.val, required_radius)) && ...
  all(isfield(local.radius.nor, required_radius)) && ...
  isfield(local, 'high_tail') && isfield(local.high_tail, 'val') && ...
  isfield(local.high_tail, 'nor') && ...
  all(isfield(local.high_tail.val, required_high)) && ...
  all(isfield(local.high_tail.nor, required_high));
if ~local_fields
  error('I5v5LocalSensitivity:LocalFields', ...
    'The stored local certificate is incomplete.');
end
radius_val_sum = double(local.radius.val.source(:)) + ...
  double(local.radius.val.target(:)) + double(local.radius.val.series(:));
radius_nor_sum = double(local.radius.nor.source(:)) + ...
  double(local.radius.nor.target(:)) + double(local.radius.nor.series(:));
local_radius_identity = isequal(double(local.radius.val.total(:)), ...
    radius_val_sum) && isequal(double(local.radius.nor.total(:)), radius_nor_sum);
local_high_minimum = isequal(double(local.high_tail.val.selected_squared), ...
    min(double(local.high_tail.val.p2_squared), ...
      double(local.high_tail.val.p4_squared))) && ...
  isequal(double(local.high_tail.nor.selected_squared), ...
    min(double(local.high_tail.nor.p2_squared), ...
      double(local.high_tail.nor.p4_squared)));
mode_count = 2 * double(c.residual_mode_cutoff) - 1;
dimensions = numel(input.weights.normal_inverse_trace) == mode_count && ...
  numel(input.weights.lifting) == mode_count && ...
  numel(local.radius.val.total) == mode_count && ...
  numel(local.radius.nor.total) == mode_count;
artifact_match = isfield(input.provenance, 'artifact_path') && ...
  strcmp(char(input.provenance.artifact_path), artifact_path);
phase1 = isequal(input.structural_pass, true) && ...
  isfield(local, 'gates') && isfield(local.gates, 'pass') && ...
  isequal(local.gates.pass, true) && ...
  isfield(input.propagation, 'minus') && ...
  isfield(input.propagation.minus, 'pass') && ...
  isequal(input.propagation.minus.pass, true) && ...
  isfield(input.propagation, 'plus') && ...
  isfield(input.propagation.plus, 'pass') && ...
  isequal(input.propagation.plus.pass, true);
audit = struct('fixed_graph', fixed_graph, 'labels', labels, ...
  'local_radius_identity', local_radius_identity, ...
  'local_high_minimum', local_high_minimum, 'dimensions', dimensions, ...
  'artifact_match', artifact_match, 'phase1', phase1, ...
  'pass', fixed_graph && labels && local_radius_identity && ...
    local_high_minimum && dimensions && artifact_match && phase1);
end

%% ==================== State-energy ownership ====================
% S_J and S_infinity reproduce I5.1f-35 and I5.1f-50 without any solve.

function [energy, ledger] = LOCAL_matched_state_energy(z, input)
J = double(input.configuration.cell_cutoff);
energy = norm(double(z.q_center), 2)^2;
sides = {'minus', 'plus'};
entries = cell(2, 1);
for side_index = 1:2
  side = sides{side_index};
  G = double(z.(['G', side]));
  P = double(z.(['P', side]));
  state = double(z.(['c', side]));
  finite_energy = 0;
  for cell_index = 0:J - 1
    finite_energy = finite_energy + norm(G * state, 2)^2;
    state = P * state;
  end
  cap = double(input.propagation.(side).sum_power_squared_upper);
  tail_energy = cap * norm(G, 'fro')^2 * norm(state, 2)^2;
  energy = energy + finite_energy + tail_energy;
  entries{side_index} = struct('side', side, ...
    'finite_cell_energy', finite_energy, 'tail_energy', tail_energy, ...
    'cell_cutoff', J, 'tail_state_norm', norm(state, 2), ...
    'block_power_sum_upper', cap);
end
entries = vertcat(entries{:});
values = [energy; [entries.finite_cell_energy].'; ...
  [entries.tail_energy].'; [entries.tail_state_norm].'; ...
  [entries.block_power_sum_upper].'];
ledger = struct('entries', entries, ...
  'finite_cells_0_through_J_minus_1', true, ...
  'tail_starts_at_P_to_J_c', true, ...
  'pass', isreal(values) && all(isfinite(values)) && all(values >= 0));
end

function [energy, ledger] = LOCAL_whole_state_energy(z, input)
minus = LOCAL_whole_side(z, input, 'minus');
plus = LOCAL_whole_side(z, input, 'plus');
center = norm(double(z.q_center), 2)^2;
energy = center + minus.energy + plus.energy;
values = [center; energy; minus.energy; plus.energy; ...
  minus.block_power_sum_upper; plus.block_power_sum_upper];
ledger = struct('center_energy', center, 'minus', minus, 'plus', plus, ...
  'formula', 'I5.1f-50', 'pass', isreal(values) && ...
    all(isfinite(values)) && all(values >= 0));
end

function entry = LOCAL_whole_side(z, input, side)
G = double(z.(['G', side]));
state = double(z.(['c', side]));
cap = double(input.propagation.(side).sum_power_squared_upper);
entry = struct('side', side, ...
  'block_power_sum_upper', cap, ...
  'G_frobenius_norm', norm(G, 'fro'), ...
  'state_norm', norm(state, 2), ...
  'energy', cap * norm(G, 'fro')^2 * norm(state, 2)^2);
end

%% ==================== Fixed local primitive graph ====================
% Replaying the small coefficient-log set verifies positive exp returns.

function audit = LOCAL_exp_return_audit(z, input)
Q = double(input.configuration.kernel_series_cutoff);
R = double(z.R);
x_max = 4 * R^2;
kappas = [double(z.khat), sqrt(double(z.rho_disk)) * double(z.khat)];
log_arguments = [];
integer_arguments = [];
for kappa_index = 1:numel(kappas)
  alpha = kappas(kappa_index)^2 / 4;
  for derivative = 0:5
    [logs, integers] = LOCAL_J_logs( ...
      alpha, x_max, Q, derivative, false);
    log_arguments = [log_arguments; logs]; %#ok<AGROW>
    integer_arguments = [integer_arguments; integers]; %#ok<AGROW>
    [logs, integers] = LOCAL_J_logs( ...
      alpha, x_max, Q, derivative, true);
    log_arguments = [log_arguments; logs]; %#ok<AGROW>
    integer_arguments = [integer_arguments; integers]; %#ok<AGROW>
  end
  for derivative = 0:4
    [logs, integers] = LOCAL_shifted_J_logs( ...
      alpha, x_max, Q, derivative);
    log_arguments = [log_arguments; logs]; %#ok<AGROW>
    integer_arguments = [integer_arguments; integers]; %#ok<AGROW>
  end
end
returns = exp(log_arguments);
integer_set = unique(integer_arguments);
audit = struct('integer_argument_region', [min(integer_set), max(integer_set)], ...
  'integer_argument_set', isequal(integer_set(:), (1:34).'), ...
  'log_argument_region', [min(log_arguments), max(log_arguments)], ...
  'per_local_invocation_exp_return_count', numel(returns), ...
  'phase1_local_invocation_count', 5, ...
  'phase1_exp_return_count', 5 * numel(returns), ...
  'graph_count_pass', numel(returns) == 1064 && ...
    5 * numel(returns) == 5320, ...
  'positive_nonunderflowing', all(isfinite(returns)) && all(returns > 0), ...
  'sampled_continuous_domain_maximum_used', false, ...
  'graph', ['J/Y derivative orders 0:5 and shifted-J orders 0:4; ', ...
    'retained plus first omitted terms']);
end

function [logs, integers] = LOCAL_J_logs( ...
    alpha, x_max, cutoff, derivative, is_Y)
start = derivative;
if is_Y
  start = max(1, derivative);
end
orders = (start:cutoff + 1).';
logs = gammaln(orders + 1) - gammaln(orders - derivative + 1) + ...
  orders * log(alpha) + (orders - derivative) * log(x_max) - ...
  2 * gammaln(orders + 1);
integers = [orders + 1; orders - derivative + 1; orders + 1];
end

function [logs, integers] = LOCAL_shifted_J_logs( ...
    alpha, x_max, cutoff, derivative)
orders = (derivative:cutoff).';
logs = gammaln(orders + 1) - gammaln(orders - derivative + 1) + ...
  (orders + 1) * log(alpha) + (orders - derivative) * log(x_max) - ...
  2 * gammaln(orders + 2);
integers = [orders + 1; orders - derivative + 1; orders + 2];
end
