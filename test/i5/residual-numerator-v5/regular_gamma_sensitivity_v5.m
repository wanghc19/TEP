function result = regular_gamma_sensitivity_v5( ...
    artifact_path, input_path, output_path)
%REGULAR_GAMMA_SENSITIVITY_V5 Bound a regular-certificate primitive subchain.
% Purpose:
%   Compute the reviewed I5.1f regular gamma/downstream-log/exponential
%   partial sensitivity for the fixed run-02 positive certificate graph.
% Input:
%   artifact_path - Explicit frozen I3 certificate MAT path.
%   input_path - Explicit self-contained v5 phase-1 input MAT path.
%   output_path - Explicit create-once sensitivity result MAT target.
% Output:
%   result - Partial ideal-sensitivity gains, prospective caps, and gates.
% Main algorithm:
%   Rebuild only positive coefficient triangles at fixed library values,
%   enumerate the complete real canonical call set and target/source phases,
%   and propagate a common dyadic primitive-error cap through stored radii.
% Based on:
%   The Skeptic-reviewed regular composite following I5.1f-54.
% Notes:
%   No signed center or numerical operator is re-evaluated. Oracle contracts,
%   the remaining special-function subchain, and floating arithmetic remain
%   unresolved.

timer = tic;
[artifact_path, input_path, output_path] = LOCAL_paths( ...
  artifact_path, input_path, output_path);
artifact_data = load(artifact_path, 'staged');
input_data = load(input_path, 'experiment_input');
if ~isfield(artifact_data, 'staged') || ...
    ~isfield(artifact_data.staged, 'certificate') || ...
    ~isfield(input_data, 'experiment_input')
  error('I5v5RegularSensitivity:Schema', ...
    'An explicit MAT input has the wrong schema.');
end
z = artifact_data.staged.certificate;
input = input_data.experiment_input;
input_audit = LOCAL_validate_input(z, input, artifact_path);

[matched_state_energy, matched_state_ledger] = ...
  LOCAL_matched_state_energy(z, input);
[whole_state_energy, whole_state_ledger] = ...
  LOCAL_whole_state_energy(z, input);
[coefficient, coefficient_ledger] = LOCAL_coefficient_triangles(z, input);
[data_gain, call_ledger] = LOCAL_fixed_library_data(z, input, coefficient);
owner_ledger = LOCAL_regular_owner_ledger(input, input_audit.fixed_graph);
positive_owner_audit = LOCAL_positive_owner_audit(z, input);

radius_val = double(input.regular.radius.val.total(:));
radius_nor = double(input.regular.radius.nor.total(:));
weight_val = double(input.weights.lifting(:));
weight_nor = double(input.weights.normal_inverse_trace(:));
high_val = sqrt(double(input.material.high_tail.regular.val));
high_nor = sqrt(double(input.material.high_tail.regular.nor));
dcenter_val = data_gain.target_row_scale .* data_gain.b_val;
dcenter_nor = data_gain.target_row_scale .* data_gain.b_nor;

Dcenter_val_squared = matched_state_energy * ...
  sum(weight_val .* dcenter_val.^2) + whole_state_energy * high_val^2;
Dcenter_nor_squared = matched_state_energy * ...
  sum(weight_nor .* dcenter_nor.^2) + whole_state_energy * high_nor^2;
Dradius_val_squared = matched_state_energy * sum(weight_val .* radius_val.^2);
Dradius_nor_squared = matched_state_energy * sum(weight_nor .* radius_nor.^2);

regular_allocation = 0.000625;
remaining_rest3_allocation = 0.000625;
dyadic_exponents = (4:80).';
dyadic_caps = 2.^(-dyadic_exponents);
increment = NaN(size(dyadic_caps));
factor_ledger = cell(size(dyadic_caps));
for cap_index = 1:numel(dyadic_caps)
  [increment(cap_index), factor_ledger{cap_index}] = LOCAL_increment( ...
    dyadic_caps(cap_index), matched_state_energy, whole_state_energy, ...
    weight_val, weight_nor, dcenter_val, dcenter_nor, ...
    radius_val, radius_nor, high_val, high_nor);
end
selected_index = find(increment <= regular_allocation, 1, 'first');
if isempty(selected_index)
  error('I5v5RegularSensitivity:Dyadic', ...
    'No prospective dyadic primitive-error cap meets the allocation.');
end
selected_cap = dyadic_caps(selected_index);
selected_increment = increment(selected_index);
selected_factor = factor_ledger{selected_index};

all_values = [matched_state_energy; whole_state_energy; radius_val; ...
  radius_nor; weight_val; weight_nor; high_val; high_nor; ...
  dcenter_val; dcenter_nor; Dcenter_val_squared; Dcenter_nor_squared; ...
  Dradius_val_squared; Dradius_nor_squared; dyadic_caps; increment; ...
  selected_cap; selected_increment; regular_allocation; ...
  remaining_rest3_allocation; struct2array(selected_factor).'];
finite_nonnegative = isreal(all_values) && all(isfinite(all_values)) && ...
  all(all_values >= 0) && selected_cap < 1;

gates = struct( ...
  'phase1_input', input_audit.pass, ...
  'fixed_run02_L512_N2048_Q18', input_audit.fixed_graph, ...
  'regular_radius_component_identity', input_audit.radius_identity, ...
  'complete_real_canonical_call_set', call_ledger.canonical_complete, ...
  'complete_source_density_phase_set', call_ledger.source_complete, ...
  'complete_target_phase_set', call_ledger.target_complete, ...
  'actual_library_phase_magnitudes_used', call_ledger.library_magnitudes, ...
  'actual_normal_components_bounded_by_one', ...
    call_ledger.normal_component_pass, ...
  'actual_coordinate_differences_in_real_box', ...
    call_ledger.coordinate_box_pass, ...
  'positive_coefficient_triangles', coefficient_ledger.pass, ...
  'complete_regular_named_owner_map', owner_ledger.pass, ...
  'positive_nonunderflowing_named_owner_returns', ...
    positive_owner_audit.pass, ...
  'matched_finite_cell_state_energy', matched_state_ledger.pass, ...
  'whole_state_high_mode_energy', whole_state_ledger.pass, ...
  'common_dyadic_cap_all_four_errors', true, ...
  'dyadic_first_passing_cap', selected_index == ...
    find(increment <= regular_allocation, 1, 'first'), ...
  'centers_or_operators_reevaluated', false, ...
  'delta_sf_rest3_unresolved', true, ...
  'delta_fp_unresolved', true, ...
  'finite_nonnegative', finite_nonnegative);
required_true = {'phase1_input', 'fixed_run02_L512_N2048_Q18', ...
  'regular_radius_component_identity', 'complete_real_canonical_call_set', ...
  'complete_source_density_phase_set', 'complete_target_phase_set', ...
  'actual_library_phase_magnitudes_used', ...
  'actual_normal_components_bounded_by_one', ...
  'actual_coordinate_differences_in_real_box', ...
  'positive_coefficient_triangles', ...
  'complete_regular_named_owner_map', ...
  'positive_nonunderflowing_named_owner_returns', ...
  'matched_finite_cell_state_energy', 'whole_state_high_mode_energy', ...
  'common_dyadic_cap_all_four_errors', 'dyadic_first_passing_cap', ...
  'delta_sf_rest3_unresolved', 'delta_fp_unresolved', 'finite_nonnegative'};
gates.pass = all(cellfun(@(name) isequal(gates.(name), true), required_true)) && ...
  ~gates.centers_or_operators_reevaluated;
if ~gates.pass
  error('I5v5RegularSensitivity:Gate', ...
    'A regular composite sensitivity gate failed.');
end

workspace = whos;
result = struct( ...
  'status', 'PARTIAL_REGULAR_GAMMA_COMPOSITE_SENSITIVITY', ...
  'claim_scope', 'PARTIAL_IDEAL_SENSITIVITY', ...
  'condition_label', ...
    'CONDITIONAL_ON_UNIFORM_REGULAR_GAMMA_LOG_EXP_ERRORS', ...
  'certification_label', 'NON_CERTIFIED_ROUNDOFF_EXCLUDED', ...
  'matched_state_energy', matched_state_energy, ...
  'matched_state_ledger', matched_state_ledger, ...
  'whole_state_energy', whole_state_energy, ...
  'whole_state_ledger', whole_state_ledger, ...
  'positive_coefficient', coefficient, ...
  'coefficient_ledger', coefficient_ledger, ...
  'fixed_library_data_gain', data_gain, ...
  'call_ledger', call_ledger, ...
  'owner_ledger', owner_ledger, ...
  'positive_owner_audit', positive_owner_audit, ...
  'Dcenter', struct('val_squared', Dcenter_val_squared, ...
    'nor_squared', Dcenter_nor_squared, ...
    'val', sqrt(Dcenter_val_squared), ...
    'nor', sqrt(Dcenter_nor_squared)), ...
  'Dradius', struct('val_squared', Dradius_val_squared, ...
    'nor_squared', Dradius_nor_squared, ...
    'val', sqrt(Dradius_val_squared), ...
    'nor', sqrt(Dradius_nor_squared)), ...
  'regular_allocation', regular_allocation, ...
  'remaining_rest3_allocation', remaining_rest3_allocation, ...
  'dyadic_schedule', struct('exponents', dyadic_exponents, ...
    'caps', dyadic_caps, 'increment', increment, ...
    'selected_index', selected_index), ...
  'prospective_common_cap', struct('value', selected_cap, ...
    'epsilon_logGamma', selected_cap, 'eta_inner_exp', selected_cap, ...
    'epsilon_log', selected_cap, 'eta_outer_exp', selected_cap), ...
  'selected_factor', selected_factor, ...
  'selected_increment', selected_increment, ...
  'delta_sf_regular_composite', ...
    'selected_increment; four oracle contracts not supplied', ...
  'delta_sf_rest3', 'UNRESOLVED', ...
  'delta_sf', 'UNRESOLVED', ...
  'delta_fp', 'UNRESOLVED', ...
  'gates', gates, ...
  'provenance', struct('artifact_path', artifact_path, ...
    'phase1_input_path', input_path, 'historical_output_read', false, ...
    'phase1_result_read', false, 'centers_reevaluated', false, ...
    'true_operators_reevaluated', false, 'eigenpair_solves', 0, ...
    'bie_density_solves', 0, 'qz_decompositions', 0, ...
    'propagation_matrix_solves', 0), ...
  'resource', struct('elapsed_seconds_before_save', toc(timer), ...
    'workspace_proxy_mib_before_save', sum([workspace.bytes]) / 2^20));
save(output_path, 'result', '-v7.3');
end

%% ==================== Portable input and fixed graph ====================
% Only the original artifact and self-contained phase-1 input are consumed.

function [artifact_path, input_path, output_path] = LOCAL_paths( ...
    artifact_path, input_path, output_path)
artifact_path = LOCAL_path(artifact_path, 'artifact_path');
input_path = LOCAL_path(input_path, 'input_path');
output_path = LOCAL_path(output_path, 'output_path');
if ~isfile(artifact_path) || ~isfile(input_path)
  error('I5v5RegularSensitivity:InputPath', ...
    'Both explicit input MAT files must exist.');
end
if isfile(output_path) || isfolder(output_path)
  error('I5v5RegularSensitivity:CreateOnce', ...
    'output_path must be a new target.');
end
if ~isfolder(fileparts(output_path))
  error('I5v5RegularSensitivity:OutputDirectory', ...
    'The output directory does not exist.');
end
end

function value = LOCAL_path(value, name)
if isstring(value) && isscalar(value)
  value = char(value);
end
if ~ischar(value) || isempty(value)
  error('I5v5RegularSensitivity:Path', '%s must be nonempty text.', name);
end
end

function audit = LOCAL_validate_input(z, input, artifact_path)
required_z = {'khat', 'd', 'rho_disk', 'q_center', 'Gminus', 'Gplus', ...
  'Pminus', 'Pplus', 'cminus', 'cplus'};
required_input = {'schema', 'condition_label', 'delta_sf', 'delta_fp', ...
  'configuration', 'geometry', 'density', 'weights', 'regular', ...
  'material', 'propagation', 'structural_pass', 'provenance'};
if ~all(isfield(z, required_z)) || ~all(isfield(input, required_input))
  error('I5v5RegularSensitivity:Fields', ...
    'The regular sensitivity input contract is incomplete.');
end
c = input.configuration;
fixed_graph = isequal(double(c.residual_mode_cutoff), 512) && ...
  isequal(double(c.evaluation_node_count), 2048) && ...
  isequal(double(c.ewald_local_cutoff), 18) && ...
  isequal(double(c.ewald_split), 2) && ...
  isequal(double(c.cell_cutoff), 16);
labels = strcmp(char(input.schema), 'EPOST_I5_1F_INPUT_V5') && ...
  strcmp(char(input.condition_label), ...
    'CONDITIONAL_ON_EXACT_SPECIAL_FUNCTION_EVALUATION') && ...
  strcmp(char(input.delta_sf), 'UNRESOLVED') && ...
  strcmp(char(input.delta_fp), 'UNRESOLVED');
r = input.regular.radius;
radius_fields = {'source', 'target', 'M_R', 'M_I', 'M_T', 'M_L', 'total'};
radius_contract = isfield(r, 'val') && isfield(r, 'nor') && ...
  all(isfield(r.val, radius_fields)) && all(isfield(r.nor, radius_fields));
if ~radius_contract
  error('I5v5RegularSensitivity:RadiusFields', ...
    'The stored regular radius decomposition is incomplete.');
end
val_sum = double(r.val.source(:)) + double(r.val.target(:)) + ...
  double(r.val.M_R(:)) + double(r.val.M_I(:)) + ...
  double(r.val.M_T(:)) + double(r.val.M_L(:));
nor_sum = double(r.nor.source(:)) + double(r.nor.target(:)) + ...
  double(r.nor.M_R(:)) + double(r.nor.M_I(:)) + ...
  double(r.nor.M_T(:)) + double(r.nor.M_L(:));
radius_identity = isequal(double(r.val.total(:)), val_sum) && ...
  isequal(double(r.nor.total(:)), nor_sum);
mode_count = 2 * double(c.residual_mode_cutoff) - 1;
dimensions = numel(r.val.total) == mode_count && ...
  numel(r.nor.total) == mode_count && ...
  numel(input.weights.lifting) == mode_count && ...
  numel(input.weights.normal_inverse_trace) == mode_count;
artifact_match = isfield(input.provenance, 'artifact_path') && ...
  strcmp(char(input.provenance.artifact_path), artifact_path);
phase1 = isequal(input.structural_pass, true) && ...
  isfield(input.regular, 'gates') && isfield(input.regular.gates, 'pass') && ...
  isequal(input.regular.gates.pass, true) && ...
  isequal(input.propagation.minus.pass, true) && ...
  isequal(input.propagation.plus.pass, true);
audit = struct('fixed_graph', fixed_graph, 'labels', labels, ...
  'radius_identity', radius_identity, 'dimensions', dimensions, ...
  'artifact_match', artifact_match, 'phase1', phase1, ...
  'pass', fixed_graph && labels && radius_identity && dimensions && ...
    artifact_match && phase1);
end

%% ==================== Positive regular coefficient graph ====================
% P-sharp and Q-sharp follow the reviewed retained canonical coefficient map.

function [coefficient, ledger] = LOCAL_coefficient_triangles(z, input)
cutoff = double(input.configuration.ewald_local_cutoff);
split = double(input.configuration.ewald_split);
kappa = double(z.khat);
d = double(z.d);
chi_E = (kappa * d / (2 * split))^2;
J = zeros(1, cutoff + 1);
S = J;
D = J;
Q = J;
harmonic = 0;
gamma_arguments = [];
for order = 0:cutoff
  gamma_n = gammaln(order + 1);
  gamma_arguments(end + 1) = order + 1; %#ok<AGROW>
  J(order + 1) = (-chi_E)^order / exp(2 * gamma_n);
  if order >= 1
    harmonic = harmonic + 1 / order;
    S(order + 1) = (-1)^order / (order * exp(gamma_n));
    D(order + 1) = (-1)^order * harmonic * chi_E^order / exp(2 * gamma_n);
    for degree = 0:order - 1
      gamma_difference = gammaln(order - degree);
      gamma_arguments(end + 1) = order - degree; %#ok<AGROW>
      Q(degree + 1) = Q(degree + 1) + chi_E^order / ...
        exp(2 * gamma_n) * exp(gamma_difference) * (-1)^degree;
    end
  end
end

gamma_E = 0.57721566490153286060;
c_chi = log(chi_E) + gamma_E - 1i * pi;
P_sharp = conv(abs(J), abs(S));
P_sharp(1:numel(J)) = P_sharp(1:numel(J)) + ...
  abs(c_chi * J) + 2 * abs(D);
P_sharp = P_sharp / (4 * abs(pi));
Q_sharp = abs(Q);
R0 = double(input.regular.real_certificate.gate.local.local_z_radius);
P_derivative = LOCAL_polynomial_triangle(P_sharp, R0);
Q_derivative = LOCAL_polynomial_triangle(Q_sharp, R0);
coefficient = struct('P_sharp', P_sharp, 'Q_sharp', Q_sharp, ...
  'P_derivative_0_to_2', P_derivative, ...
  'Q_derivative_0_to_2', Q_derivative, ...
  'canonical_radius', R0, 'chi_E', chi_E);
gamma_set = unique(gamma_arguments);
values = [P_sharp(:); Q_sharp(:); P_derivative(:); ...
  Q_derivative(:); R0; chi_E];
ledger = struct('gammaln_integer_argument_region', ...
    [min(gamma_set), max(gamma_set)], ...
  'gammaln_integer_argument_set', isequal(gamma_set(:), (1:19).'), ...
  'P_definition', 'conv(abs(J),abs(S))+abs(c_chi*J)+2abs(D)', ...
  'Q_definition', 'abs(Q)', ...
  'pass', isreal(values) && all(isfinite(values)) && ...
    all(values >= 0) && isequal(gamma_set(:), (1:19).'));
end

function ledger = LOCAL_regular_owner_ledger(input, fixed_graph)
calls = input.regular.sf_ledger.calls;
required = {'gammaln', 'exp', 'log', 'log1p'};
fields = all(isfield(calls, required));
if fields
  gamma = calls.gammaln;
  gamma_match = isequal(double(gamma.vectorized_calls), 25495) && ...
    isequal(double(gamma.scalar_arguments), 25905) && ...
    isequal(double(gamma.real_min), 1) && ...
    isequal(double(gamma.real_max), 20) && ...
    isequal(double(gamma.imag_min), 0) && ...
    isequal(double(gamma.imag_max), 0);
else
  gamma = struct;
  gamma_match = false;
end
ledger = struct( ...
  'scope', 'fixed final governing regular helper invocation', ...
  'gammaln_record', gamma, ...
  'gammaln_vectorized_calls_expected', 25495, ...
  'gammaln_scalar_arguments_expected', 25905, ...
  'gammaln_integer_argument_region_expected', [1, 20], ...
  'gammaln_ledger_match', gamma_match, ...
  'immediate_factorial_exp_sites', {{ ...
    'LOCAL_C_chi_finite:J,S,D,Q', ...
    'LOCAL_local_ewald_bound:retained and first-omitted factorials', ...
    'LOCAL_retained_image_taylor_tail:first omitted factorial'}}, ...
  'downstream_log_outer_exp_sites', {{ ...
    'regular source radius logarithmic assembly', ...
    'regular target radius logarithmic assembly'}}, ...
  'aggregate_unrelated_exp_log_calls_excluded', true, ...
  'fixed_graph_static_site_map', fixed_graph, ...
  'pass', fields && gamma_match && fixed_graph);
end

function audit = LOCAL_positive_owner_audit(z, input)
integer_arguments = (1:20).';
gamma_values = gammaln(integer_arguments);
factorial_exp_one = exp(gamma_values);
factorial_exp_two = exp(2 * gamma_values);
Q = double(input.configuration.ewald_local_cutoff);
split = double(input.configuration.ewald_split);
chi_E = (double(z.khat) * double(z.d) / (2 * split))^2;
taylor_first = exp((Q + 1) * log(chi_E) - gammaln(Q + 2));
source_action = double(input.regular.source_strip_integrand_upper(:));
target_action = double(input.regular.target_strip_action_upper(:));
N = double(input.configuration.evaluation_node_count);
P = double(input.geometry.boundary_length);
source_scale = 4 * pi * ...
  (2 * pi / N * sum(double(input.geometry.speed_nodes(:)))) / sqrt(P);
source_log_return = log(source_scale * source_action);
target_log_return = log(target_action);
stored_outer_returns = [double(input.regular.radius.val.source(:)); ...
  double(input.regular.radius.val.target(:)); ...
  double(input.regular.radius.nor.source(:)); ...
  double(input.regular.radius.nor.target(:))];
positive_values = [factorial_exp_one; factorial_exp_two; taylor_first; ...
  source_action; target_action; source_scale; stored_outer_returns];
log_values = [gamma_values; (Q + 1) * log(chi_E) - gammaln(Q + 2); ...
  source_log_return; target_log_return];
audit = struct( ...
  'factorial_integer_arguments', integer_arguments, ...
  'factorial_exp_one', factorial_exp_one, ...
  'factorial_exp_two', factorial_exp_two, ...
  'retained_image_first_omitted_exp', taylor_first, ...
  'source_action_upper', source_action, ...
  'target_action_upper', target_action, ...
  'source_scale', source_scale, ...
  'source_log_return', source_log_return, ...
  'target_log_return', target_log_return, ...
  'stored_source_target_outer_returns_positive', ...
    all(isfinite(stored_outer_returns)) && all(stored_outer_returns > 0), ...
  'finite_superset_not_aggregate_unrelated_calls', true, ...
  'pass', all(isfinite(positive_values)) && all(positive_values > 0) && ...
    all(isfinite(log_values)));
end

function derivative = LOCAL_polynomial_triangle(coefficient, radius)
degree = (0:numel(coefficient) - 1).';
derivative = zeros(1, 3);
for order = 0:2
  keep = degree >= order;
  falling = ones(sum(keep), 1);
  selected = degree(keep);
  for factor = 0:order - 1
    falling = falling .* (selected - factor);
  end
  derivative(order + 1) = sum(coefficient(keep).' .* falling .* ...
    radius.^(selected - order));
end
end

%% ==================== Complete fixed library data ====================
% Every source/target phase and real canonical exp-factor argument is used.

function [gain, ledger] = LOCAL_fixed_library_data(z, input, coefficient)
g = input.geometry;
c = input.configuration;
density = input.density;
N = double(c.evaluation_node_count);
L = double(c.residual_mode_cutoff);
P = double(g.boundary_length);
dt = 2 * pi / N;
orders = double(density.orders(:));
density_phase = exp(1i * double(g.parameter_nodes(:)) * orders.');
tau_sample = density_phase * double(density.tau_coeff);
zeta_sample = density_phase * double(density.zeta_coeff);
D_tau = dt * sum(double(g.speed_nodes(:)) .* vecnorm(tau_sample, 2, 2));
D_zeta = dt * sum(double(g.speed_nodes(:)) .* vecnorm(zeta_sample, 2, 2));

ell = (-(L - 1):L - 1).';
target_phase = exp(-1i * (2 * pi * ell / P) * ...
  double(g.arclength_nodes(:)).');
target_row_scale = dt / sqrt(P) * ...
  (abs(target_phase) * double(g.speed_nodes(:)));

h = double(c.ewald_split) / double(z.d);
position = double(g.position);
block = double(c.target_block_size);
E_sharp = 0;
canonical_count = 0;
canonical_argument_min = Inf;
canonical_argument_max = -Inf;
RX = double(g.real_displacement_abs_upper(1));
RY = double(g.real_displacement_abs_upper(2));
coordinate_box_pass = true;
for first_target = 1:block:N
  target_ids = first_target:min(first_target + block - 1, N);
  X = position(target_ids, 1) - position(:, 1).';
  Y = position(target_ids, 2) - position(:, 2).';
  canonical_argument = h^2 * (X.^2 + Y.^2);
  coordinate_box_pass = coordinate_box_pass && ...
    all(abs(X(:)) <= RX) && all(abs(Y(:)) <= RY);
  fixed_factor = abs(exp(-canonical_argument) / (4 * pi));
  E_sharp = max(E_sharp, max(fixed_factor(:)));
  canonical_count = canonical_count + numel(canonical_argument);
  canonical_argument_min = min(canonical_argument_min, ...
    min(canonical_argument(:)));
  canonical_argument_max = max(canonical_argument_max, ...
    max(canonical_argument(:)));
end

P_derivative = coefficient.P_derivative_0_to_2;
Q_derivative = coefficient.Q_derivative_0_to_2;
B0 = P_derivative(1) + E_sharp * Q_derivative(1);
B1 = P_derivative(2) + E_sharp * ...
  (Q_derivative(2) + Q_derivative(1));
B2 = P_derivative(3) + E_sharp * ...
  (Q_derivative(3) + 2 * Q_derivative(2) + Q_derivative(1));
zx = 2 * h^2 * RX;
zy = 2 * h^2 * RY;
b00 = B0;
b10 = zx * B1;
b01 = zy * B1;
b20 = zx^2 * B2 + 2 * h^2 * B1;
b11 = zx * zy * B2;
b02 = zy^2 * B2 + 2 * h^2 * B1;
b_val = (b10 + b01) * D_tau + b00 * D_zeta;
b_nor = (b20 + 2 * b11 + b02) * D_tau + ...
  (b10 + b01) * D_zeta;

all_values = [D_tau; D_zeta; target_row_scale; E_sharp; ...
  canonical_argument_min; canonical_argument_max; B0; B1; B2; ...
  b00; b10; b01; b20; b11; b02; b_val; b_nor];
gain = struct('D_tau', D_tau, 'D_zeta', D_zeta, ...
  'target_row_scale', target_row_scale, 'E_sharp', E_sharp, ...
  'B_0_to_2', [B0, B1, B2], ...
  'b_coordinate', [b00, b10, b01, b20, b11, b02], ...
  'b_val', b_val, 'b_nor', b_nor);
ledger = struct( ...
  'canonical_scalar_call_count', canonical_count, ...
  'canonical_argument_region', ...
    [canonical_argument_min, canonical_argument_max], ...
  'canonical_complete', canonical_count == N^2, ...
  'source_phase_scalar_argument_count', N * numel(orders), ...
  'source_complete', isequal(size(density_phase), [N, numel(orders)]), ...
  'target_phase_scalar_argument_count', N * numel(ell), ...
  'target_complete', isequal(size(target_phase), [numel(ell), N]), ...
  'target_normalization', '(2*pi/N)/sqrt(P_library)', ...
  'target_phase_library_magnitude_region', ...
    [min(abs(target_phase(:))), max(abs(target_phase(:)))], ...
  'source_phase_library_magnitude_region', ...
    [min(abs(density_phase(:))), max(abs(density_phase(:)))], ...
  'normal_component_pass', all(isfinite(double(g.normal(:)))) && ...
    all(abs(double(g.normal(:))) <= 1), ...
  'coordinate_box_pass', coordinate_box_pass, ...
  'library_magnitudes', all(isfinite(all_values)) && ...
    all(all_values >= 0));
end

%% ==================== Prospective common dyadic cap ====================
% The four primitive errors share one cap; no oracle error is measured here.

function [increment, factor] = LOCAL_increment( ...
    cap, S_J, S_inf, w_val, w_nor, dcenter_val, dcenter_nor, ...
    radius_val, radius_nor, high_val, high_nor)
c0 = expm1(3 * cap - 2 * log1p(-cap));
u0 = 1 + c0;
l0 = 1 / u0;
cR = expm1(4 * cap - 3 * log1p(-cap));
uR = 1 + cR;
lR = 1 / uR;
error_val = c0 * dcenter_val + cR * radius_val;
error_nor = c0 * dcenter_nor + cR * radius_nor;
D_val = sqrt(S_J * sum(w_val .* error_val.^2) + ...
  S_inf * (c0 * high_val)^2);
D_nor = sqrt(S_J * sum(w_nor .* error_nor.^2) + ...
  S_inf * (c0 * high_nor)^2);
increment = D_nor + 2 * D_val;
factor = struct('u0', u0, 'l0', l0, 'c0', c0, ...
  'uR', uR, 'lR', lR, 'cR', cR, 'D_val', D_val, 'D_nor', D_nor);
end

%% ==================== State-energy ownership ====================
% S_J and S_infinity are the same finite/cell and whole-state owners as v5.

function [energy, ledger] = LOCAL_matched_state_energy(z, input)
J = double(input.configuration.cell_cutoff);
energy = norm(double(z.q_center), 2)^2;
sides = {'minus', 'plus'};
entries = cell(2, 1);
for side_index = 1:2
  side = sides{side_index};
  G = double(z.(['G', side]));
  P = double(z.(['P', side]));
  state = double(z.(['c', side]));
  finite_energy = 0;
  for cell_index = 0:J - 1
    finite_energy = finite_energy + norm(G * state, 2)^2;
    state = P * state;
  end
  cap = double(input.propagation.(side).sum_power_squared_upper);
  tail_energy = cap * norm(G, 'fro')^2 * norm(state, 2)^2;
  energy = energy + finite_energy + tail_energy;
  entries{side_index} = struct('side', side, ...
    'finite_cell_energy', finite_energy, 'tail_energy', tail_energy, ...
    'cell_cutoff', J, 'tail_state_norm', norm(state, 2), ...
    'block_power_sum_upper', cap);
end
entries = vertcat(entries{:});
values = [energy; [entries.finite_cell_energy].'; ...
  [entries.tail_energy].'; [entries.tail_state_norm].'; ...
  [entries.block_power_sum_upper].'];
ledger = struct('entries', entries, ...
  'finite_cells_0_through_J_minus_1', true, ...
  'tail_starts_at_P_to_J_c', true, ...
  'pass', isreal(values) && all(isfinite(values)) && all(values >= 0));
end

function [energy, ledger] = LOCAL_whole_state_energy(z, input)
minus = LOCAL_whole_side(z, input, 'minus');
plus = LOCAL_whole_side(z, input, 'plus');
center = norm(double(z.q_center), 2)^2;
energy = center + minus.energy + plus.energy;
values = [center; energy; minus.energy; plus.energy];
ledger = struct('center_energy', center, 'minus', minus, 'plus', plus, ...
  'formula', 'I5.1f-50', 'pass', isreal(values) && ...
    all(isfinite(values)) && all(values >= 0));
end

function entry = LOCAL_whole_side(z, input, side)
G = double(z.(['G', side]));
state = double(z.(['c', side]));
cap = double(input.propagation.(side).sum_power_squared_upper);
entry = struct('side', side, 'block_power_sum_upper', cap, ...
  'G_frobenius_norm', norm(G, 'fro'), 'state_norm', norm(state, 2), ...
  'energy', cap * norm(G, 'fro')^2 * norm(state, 2)^2);
end
