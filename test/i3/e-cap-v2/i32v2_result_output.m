function i32v2_result_output(result, output_dir)
%I32V2_RESULT_OUTPUT Save the readable v2 artifact and Markdown report.
% Purpose:
%   Publish complete or partial experiment state without changing scientific
%   values, qualification flags, warnings, or blockers.
% Input:
%   result     - serializable v2 result struct.
%   output_dir - already-created exact append-only attempt directory.
% Output:
%   Creates result.mat and report.md in output_dir.

if ~isfolder(output_dir)
  error('I32V2:OutputDirectoryMissing', ...
    'The exact attempt directory must exist before publication.');
end

result_file = fullfile(output_dir, 'result.mat');
report_file = fullfile(output_dir, 'report.md');
save(result_file, 'result', '-v7.3');

fid = fopen(report_file, 'wt');
if fid < 0
  error('I32V2:ReportOpenFailure', 'Unable to create report.md.');
end
cleanup = onCleanup(@() fclose(fid));

fprintf(fid, '# I3.2 empirical epsilon experiment v2\n\n');
fprintf(fid, '- Label: `%s`\n', LOCAL_text(result, {'claim_label'}, ...
  'EMPIRICAL / UNQUALIFIED'));
fprintf(fid, '- Attempt: `%s`\n', LOCAL_text(result, {'attempt'}, 'UNAVAILABLE'));
fprintf(fid, '- Status: `%s`\n', LOCAL_text(result, {'status'}, 'UNAVAILABLE'));
fprintf(fid, '- Elapsed seconds: `%.17g`\n', ...
  LOCAL_number(result, {'resources', 'elapsed_s'}));
fprintf(fid, '- Retained/peak memory proxy MiB: `%.17g` / `%.17g`\n', ...
  LOCAL_number(result, {'resources', 'retained_mib'}), ...
  LOCAL_number(result, {'resources', 'peak_mib'}));
fprintf(fid, '- First blocker: `%s`\n\n', ...
  LOCAL_text(result, {'first_blocker'}, ''));
fprintf(fid, '- Retry ordinal / prior a2 retries: `%.17g / %.17g`\n', ...
  LOCAL_number(result, {'audit', 'retry', 'ordinal'}), ...
  LOCAL_number(result, {'audit', 'retry', 'retries_before'}));
fprintf(fid, '- Replaced existing exact a2 directory: `%s`\n', ...
  LOCAL_bool_text(result, ...
  {'audit', 'retry', 'replaced_existing_exact_a2'}));
fprintf(fid, '- Prior attempt tag / status / blocker: `%s / %s / %s`\n\n', ...
  LOCAL_text(result, {'audit', 'retry', 'prior_attempt', 'tag'}, 'UNAVAILABLE'), ...
  LOCAL_text(result, {'audit', 'retry', 'prior_attempt', 'status'}, 'UNAVAILABLE'), ...
  LOCAL_text(result, {'audit', 'retry', 'prior_attempt', 'first_blocker'}, ...
  'UNAVAILABLE'));

fprintf(fid, '## Frozen trial identity\n\n');
fprintf(fid, '- Trial unchanged at every completed level: `%s`\n', ...
  LOCAL_bool_text(result, {'audit', 'trial_unchanged'}));
fprintf(fid, '- Refinement changes trial: `%s`\n', ...
  LOCAL_bool_text(result, {'audit', 'refinement_changes_trial'}));
fprintf(fid, '- Raw certificate identity digest: `%s`\n', ...
  LOCAL_text(result, {'audit', 'expected_identity_digest'}, 'UNAVAILABLE'));
fprintf(fid, '- Raw identity match before release: `%s`\n', ...
  lower(mat2str(strcmp( ...
  LOCAL_text(result, {'audit', 'initial_identity_digest'}, ''), ...
  LOCAL_text(result, {'audit', 'expected_identity_digest'}, '')))));
fprintf(fid, '- Canonical computation identity digest: `%s`\n', ...
  LOCAL_text(result, {'audit', 'expected_canonical_digest'}, 'UNAVAILABLE'));
for stage = {'initial', 'after_gqp', 'after_circle', 'after_wall', ...
    'pre_release', 'after_lifting', 'after_fullp'}
  key = stage{1};
  actual = LOCAL_text(result, {'audit', 'canonical_digest_ledger', key}, '');
  expected = LOCAL_text(result, {'audit', 'expected_canonical_digest'}, '');
  fprintf(fid, '- Canonical digest match at %s: `%s`\n', key, ...
    lower(mat2str(~isempty(expected) && strcmp(actual, expected))));
end
fprintf(fid, '- Released digest expected / actual: `%s / %s`\n', ...
  LOCAL_text(result, {'audit', 'expected_released_digest'}, 'UNAVAILABLE'), ...
  LOCAL_text(result, ...
  {'audit', 'released_computation_view', 'released_digest'}, 'UNAVAILABLE'));
fprintf(fid, '- Release manifest expected / actual: `%s / %s`\n', ...
  LOCAL_text(result, ...
  {'audit', 'expected_release_manifest_digest'}, 'UNAVAILABLE'), ...
  LOCAL_text(result, ...
  {'audit', 'released_computation_view', 'release_manifest_digest'}, ...
  'UNAVAILABLE'));
fprintf(fid, '- Raw d / canonical d classes: `%s / %s`\n', ...
  LOCAL_text(result, {'audit', 'raw_numeric_types', 'd'}, 'UNAVAILABLE'), ...
  LOCAL_text(result, {'audit', 'canonical_numeric_types', 'd'}, 'UNAVAILABLE'));
fprintf(fid, '- M / role: `%.17g / %s`\n', ...
  LOCAL_number(result, {'audit', 'wall_trace_order_M'}), ...
  LOCAL_text(result, {'audit', 'M_role'}, 'UNAVAILABLE'));
fprintf(fid, '- Density re-solves: `%.17g`\n', ...
  LOCAL_number(result, {'audit', 'density_solves'}));
fprintf(fid, '- Old e-cap evaluator calls: `%.17g`\n', ...
  LOCAL_number(result, {'audit', 'old_ecap_calls'}));
fprintf(fid, '- Image-sum calls: `%.17g`\n', ...
  LOCAL_number(result, {'audit', 'image_sum_calls'}));
fprintf(fid, '- Rayleigh/Fourier field actions: `%.17g`\n\n', ...
  LOCAL_number(result, {'audit', 'rayleigh_field_calls'}));

fprintf(fid, '## MFS GQP and boundary actions\n\n');
fprintf(fid, '- MFS proxy constructions / `lsqminnorm` / `pinv` / outer branch: ');
fprintf(fid, '`%.17g / %.17g / %.17g / %.17g`\n', ...
  LOCAL_number(result, {'gqp', 'counters', 'precomp_proxy'}), ...
  LOCAL_number(result, {'gqp', 'counters', 'lsqminnorm_selected'}), ...
  LOCAL_number(result, {'gqp', 'counters', 'pinv_fallback'}), ...
  LOCAL_number(result, {'gqp', 'counters', 'mfs_outer_plane_wave_evaluator'}));
fprintf(fid, '- MFS production parameters: `%s`\n', ...
  LOCAL_text(result, {'gqp', 'audit', 'production_parameters_text'}, 'UNAVAILABLE'));
fprintf(fid, '- MFS empirical uncertainty basis: `%s`\n', ...
  LOCAL_text(result, {'gqp', 'audit', 'empirical_uncertainty_basis'}, ...
  'UNAVAILABLE'));
fprintf(fid, '- MFS preregistered relative floor: `%.17g`\n', ...
  LOCAL_number(result, {'gqp', 'audit', 'empirical_relative_floor'}));
fprintf(fid, '- MFS interpolation oracle pass / Bloch pass: `%s / %s`\n', ...
  LOCAL_bool_text(result, {'gqp', 'audit', 'oracles', 'interpolation_pass'}), ...
  LOCAL_bool_text(result, {'gqp', 'audit', 'oracles', 'bloch_pass'}));
fprintf(fid, '- MFS interpolation max relative / Bloch defect: `%.17g / %.17g`\n', ...
  LOCAL_max_number(result, ...
  {'gqp', 'audit', 'oracles', 'interpolation_relative_by_field'}), ...
  LOCAL_number(result, {'gqp', 'audit', 'oracles', 'bloch_shift_defect'}));
fprintf(fid, '- Empirical GQP uncertainty: `%.17g`\n', ...
  LOCAL_number(result, {'caps', 'epsilon_GQP_emp'}));
fprintf(fid, '- Image-sum code-path zero (GQP/circle/wall): `%s / %s / %s`\n', ...
  LOCAL_bool_text(result, {'gqp', 'audit', 'image_sum_code_path_zero'}), ...
  LOCAL_bool_text(result, {'circle', 'audit', 'image_sum_code_path_zero'}), ...
  LOCAL_bool_text(result, {'wall', 'audit', 'image_sum_code_path_zero'}));
fprintf(fid, '- Wall self action: `%s`\n', ...
  LOCAL_text(result, {'wall', 'audit', 'self_quadrature'}, 'UNAVAILABLE'));
fprintf(fid, '- Circle self action: `%s`\n\n', ...
  LOCAL_text(result, {'circle', 'audit', 'self_quadrature'}, 'UNAVAILABLE'));

fprintf(fid, '## Empirical numerator caps\n\n');
LOCAL_cap_table(fid, result, 'W', 'wall');
LOCAL_cap_table(fid, result, 'Gamma', 'circle');
LOCAL_cap_table(fid, result, 'V', 'volume');
fprintf(fid, '\n### Diagnostic-only Fourier shells\n\n');
LOCAL_shell_table(fid, result, 'W / wall', ...
  {'caps', 'wall', 'fourier_diagnostic'});
LOCAL_shell_table(fid, result, 'Gamma / circle', ...
  {'caps', 'circle', 'fourier_diagnostic'});
LOCAL_shell_table(fid, result, 'V / circle', ...
  {'caps', 'volume', 'fourier_diagnostic', 'circle'});
LOCAL_shell_table(fid, result, 'V / wall', ...
  {'caps', 'volume', 'fourier_diagnostic', 'wall'});
fprintf(fid, '\n- Total empirical numerator cap: `%.17g`\n', ...
  LOCAL_number(result, {'caps', 'epsilon_M_emp'}));
fprintf(fid, '- Ordinary majorant center: `%.17g`\n\n', ...
  LOCAL_number(result, {'estimator', 'M_h'}));

fprintf(fid, '## Field lower and nominal interval\n\n');
fprintf(fid, '- Field lower center: `%.17g`\n', ...
  LOCAL_number(result, {'estimator', 'field_lower'}));
fprintf(fid, '- Empirical denominator cap: `%.17g`\n', ...
  LOCAL_number(result, {'caps', 'epsilon_N_emp'}));
fprintf(fid, '  - observed one-sided nested term: `%.17g`\n', ...
  LOCAL_number(result, {'field_lower_diagnostic', 'A_N_observed'}));
fprintf(fid, '  - comparison roundoff allowance: `%.17g`\n', ...
  LOCAL_number(result, {'field_lower_diagnostic', 'omega_comparison'}));
fprintf(fid, '  - observed-plus-comparison term: `%.17g`\n', ...
  LOCAL_number(result, {'field_lower_diagnostic', 'A_N'}));
fprintf(fid, '  - three-path spread: `%.17g`\n', ...
  LOCAL_number(result, {'field_lower_diagnostic', 'path_spread'}));
fprintf(fid, '  - three-path roundoff allowance: `%.17g`\n', ...
  LOCAL_number(result, {'field_lower_diagnostic', 'omega_arithmetic'}));
fprintf(fid, '- GQP denominator component: `%.17g`\n', ...
  LOCAL_number(result, {'caps', 'epsilon_N_GQP_emp'}));
fprintf(fid, '- q_emp: `%.17g`\n', LOCAL_number(result, {'estimator', 'q_emp'}));
fprintf(fid, '- Nominal k interval: `[%.17g, %.17g]`\n', ...
  LOCAL_number(result, {'estimator', 'k_interval', 'lower'}), ...
  LOCAL_number(result, {'estimator', 'k_interval', 'upper'}));
fprintf(fid, '- Nominal width: `%.17g`\n', ...
  LOCAL_number(result, {'estimator', 'k_interval', 'width'}));
fprintf(fid, '- Width below 1e-6: `%s`\n\n', ...
  LOCAL_bool_text(result, {'estimator', 'k_interval', 'width_below_1e6'}));

fprintf(fid, '## Module memory proxy\n\n');
for name = {'certificate', 'gqp', 'circle', 'wall', 'lifting', 'fullp'}
  key = name{1};
  fprintf(fid, '- %s entry/local/COW/publication/proxy MiB: ', key);
  fprintf(fid, '`%.17g / %.17g / %.17g / %.17g / %.17g`\n', ...
    LOCAL_number(result, {'resources', 'modules', key, 'entry_mib'}), ...
    LOCAL_number(result, {'resources', 'modules', key, 'local_peak_mib'}), ...
    LOCAL_number(result, {'resources', 'modules', key, 'cow_mib'}), ...
    LOCAL_number(result, {'resources', 'modules', key, 'publication_mib'}), ...
    LOCAL_number(result, {'resources', 'modules', key, 'proxy_mib'}));
end
fprintf(fid, '\n');

fprintf(fid, '## Compact progress checkpoints\n\n');
for name = {'gqp', 'circle', 'wall', 'lifting', 'cap_module'}
  key = name{1};
  checkpoint = LOCAL_value(result, {key, 'data', 'checkpoint'}, struct());
  if ~isstruct(checkpoint) || isempty(fieldnames(checkpoint))
    checkpoint = LOCAL_value(result, ...
      {key, 'audit', 'progress_checkpoint'}, struct());
  end
  fprintf(fid, '- %s stage: `%s`\n', key, ...
    LOCAL_text(checkpoint, {'stage'}, 'UNAVAILABLE'));
  fprintf(fid, '  - tables/variants/target/source/Gauss/components completed: ');
  fprintf(fid, '`%.17g / %.17g / %.17g / %.17g / %.17g / %.17g`\n', ...
    LOCAL_checkpoint_count(checkpoint, 'production_tables_completed', ...
    'completed_production_levels'), ...
    LOCAL_checkpoint_count(checkpoint, 'variants_completed', ...
    'completed_variants'), ...
    LOCAL_checkpoint_count(checkpoint, 'target_actions_completed', ...
    'completed_target_levels'), ...
    LOCAL_checkpoint_count(checkpoint, 'source_actions_completed', ...
    'completed_source_levels'), ...
    LOCAL_number(checkpoint, {'gauss_levels_completed'}), ...
    LOCAL_number(checkpoint, {'components_completed'}));
  fprintf(fid, '  - completed target rows / source panels / local peak MiB: ');
  fprintf(fid, '`%.17g / %.17g / %.17g`\n', ...
    LOCAL_checkpoint_number(checkpoint, 'completed_target_rows', ...
    'completed_rows'), ...
    LOCAL_checkpoint_number(checkpoint, 'completed_source_panels', ...
    'completed_panels'), ...
    LOCAL_number(checkpoint, {'local_peak_mib'}));
end
fprintf(fid, '\n');

fprintf(fid, '## Qualification and claim flags\n\n');
flag_names = {'reliability', 'outward_residual_upper', ...
  'outward_field_lower', 'outward_tail_enclosure', 'certified_tail', ...
  'certified_projected_gap', 'independent_reference', ...
  'reliable_spectral_interval', 'continuous_eigenvalue_exists'};
for k = 1:numel(flag_names)
  fprintf(fid, '- `%s`: `%s`\n', flag_names{k}, ...
    LOCAL_bool_text(result, {'flags', flag_names{k}}));
end

fprintf(fid, '\n## Warnings and unresolved items\n\n');
LOCAL_string_list(fid, LOCAL_value(result, {'warnings'}, {}));
fprintf(fid, '\n### Unresolved\n\n');
LOCAL_string_list(fid, LOCAL_value(result, {'unresolved'}, {}));

fprintf(fid, '\nThis artifact is empirical and unqualified. It is not a reliable or ');
fprintf(fid, 'certified interval, a strict error bound, or a spectral-existence conclusion.\n');
clear cleanup
end

%% ==================== Report formatting ====================
% These helpers tolerate partial artifacts and never invent missing values.

function LOCAL_cap_table(fid, result, label, field_name)
fprintf(fid, '- %s ordinary center: `%.17g`\n', label, ...
  LOCAL_number(result, {'estimator', ['B_', field_name]}));
fprintf(fid, '  - target: `%.17g`\n', ...
  LOCAL_number(result, {'caps', field_name, 'target'}));
fprintf(fid, '  - source: `%.17g`\n', ...
  LOCAL_number(result, {'caps', field_name, 'source'}));
fprintf(fid, '  - Riccati/Gauss: `%.17g`\n', ...
  LOCAL_number(result, {'caps', field_name, 'weight_or_gauss'}));
fprintf(fid, '  - full-P: `%.17g`\n', ...
  LOCAL_number(result, {'caps', field_name, 'fullp'}));
fprintf(fid, '  - GQP: `%.17g`\n', ...
  LOCAL_number(result, {'caps', field_name, 'gqp'}));
fprintf(fid, '    - proxy remainder: `%.17g`\n', ...
  LOCAL_number(result, {'caps', field_name, 'gqp_diagnostic', ...
  'proxy_remainder'}));
fprintf(fid, '    - interpolation remainder: `%.17g`\n', ...
  LOCAL_number(result, {'caps', field_name, 'gqp_diagnostic', ...
  'interp_remainder'}));
fprintf(fid, '  - arithmetic: `%.17g`\n', ...
  LOCAL_number(result, {'caps', field_name, 'arithmetic'}));
fprintf(fid, '  - Fourier shell ledger contribution: `%.17g`\n', ...
  LOCAL_number(result, {'caps', field_name, 'fourier'}));
fprintf(fid, '  - total: `%.17g`\n', ...
  LOCAL_number(result, {'caps', field_name, 'total'}));
end

function LOCAL_shell_table(fid, result, label, path)
fprintf(fid, '- %s S1 / S2 / ratio / omega: ', label);
fprintf(fid, '`%.17g / %.17g / %.17g / %.17g`\n', ...
  LOCAL_number(result, [path, {'S1'}]), ...
  LOCAL_number(result, [path, {'S2'}]), ...
  LOCAL_number(result, [path, {'ratio'}]), ...
  LOCAL_number(result, [path, {'omega'}]));
fprintf(fid, '  - near-zero / contraction pass: `%s / %s`\n', ...
  LOCAL_bool_text(result, [path, {'near_zero'}]), ...
  LOCAL_bool_text(result, [path, {'contraction_pass'}]));
fprintf(fid, '  - R_Fourier / counted in: `%.17g / %s`\n', ...
  LOCAL_number(result, [path, {'R_Fourier'}]), ...
  LOCAL_text(result, [path, {'counted_in'}], 'UNAVAILABLE'));
end

function value = LOCAL_value(root, path, fallback)
value = root;
for k = 1:numel(path)
  if ~isstruct(value) || ~isfield(value, path{k})
    value = fallback;
    return
  end
  value = value.(path{k});
end
end

function value = LOCAL_number(root, path)
value = LOCAL_value(root, path, NaN);
if ~(isnumeric(value) && isscalar(value) && isreal(value))
  value = NaN;
end
end

function value = LOCAL_max_number(root, path)
raw = LOCAL_value(root, path, NaN);
if isnumeric(raw) && ~isempty(raw) && isreal(raw) && all(isfinite(raw(:)))
  value = max(raw(:));
else
  value = NaN;
end
end

function value = LOCAL_checkpoint_count(checkpoint, scalar_name, vector_name)
value = LOCAL_number(checkpoint, {scalar_name});
if isnan(value)
  raw = LOCAL_value(checkpoint, {vector_name}, []);
  if isnumeric(raw) || iscell(raw) || isstruct(raw)
    value = numel(raw);
  end
end
end

function value = LOCAL_checkpoint_number(checkpoint, primary, fallback)
value = LOCAL_number(checkpoint, {primary});
if isnan(value)
  value = LOCAL_number(checkpoint, {fallback});
end
end

function value = LOCAL_text(root, path, fallback)
value = LOCAL_value(root, path, fallback);
if isstring(value) && isscalar(value)
  value = char(value);
elseif ~ischar(value)
  value = fallback;
end
value = strrep(value, '`', '''');
value = strrep(value, newline, ' ');
end

function value = LOCAL_bool_text(root, path)
raw = LOCAL_value(root, path, false);
if islogical(raw) && isscalar(raw)
  value = lower(mat2str(raw));
else
  value = 'false';
end
end

function LOCAL_string_list(fid, values)
if ischar(values) || (isstring(values) && isscalar(values))
  values = {char(values)};
elseif isstring(values)
  values = cellstr(values(:));
end
if ~iscell(values) || isempty(values)
  fprintf(fid, '- None recorded.\n');
  return
end
for k = 1:numel(values)
  if ischar(values{k}) || (isstring(values{k}) && isscalar(values{k}))
    text = strrep(char(values{k}), '`', '''');
    text = strrep(text, newline, ' ');
    fprintf(fid, '- `%s`\n', text);
  end
end
end
