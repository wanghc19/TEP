%% ==================== Finite input ====================
% These checks reproduce only the minimum I2 object and near-null diagnostics.

function LOCAL_seed_gate(seed,frame,c)
  ok = seed.k == c.kstar && seed.pass && all([seed.factors.pass]) && ...
    isequal(size(seed.R),[260,260]) && isequal(size(seed.Aqp),[512,512]) && ...
    isequal(size(seed.AdefD),[194,194]) && ...
    isequal(size(frame.Z0_plus),[194,97]) && ...
    isequal(size(frame.Z0_minus),[194,97]) && frame.proxy_chart.r == 260;
  if ~ok
    error('i31:FiniteInput','The frozen seed/frame health gate failed.');
  end
end

function LOCAL_point_gate(node,frame,c)
  ok = node.k == c.khat && strcmp(node.name,'fine') && ...
    node.spec.ntot == 256 && node.pass && node.plus.pass && ...
    node.minus.pass && node.branch_port.pass && node.branch_proxy.pass && ...
    node.cp.safe && node.cm.safe && all([node.factors.pass]) && ...
    isequal(node.H_plus_rows,frame.rows_plus) && ...
    isequal(node.H_minus_rows,frame.rows_minus) && ...
    isequal(size(node.AdefD),[194,194]) && ...
    isequal(size(node.AdefG),[388,388]) && ...
    all(isfinite(node.beta_m)) && all(isfinite(node.gamma));
  if ~ok
    error('i31:FiniteInput','The saved-candidate point health gate failed.');
  end
end

function out = LOCAL_finite_diagnostics(node,c)
  beta = node.beta_m(:); gamma = node.gamma(:);
  b = sqrt(1+abs(beta).^2);
  wr = repmat(sqrt(1./b),2,1);
  wc = repmat(1./sqrt(b+abs(gamma).^2./b),2,1);
  A = node.AdefD;
  B = wr.*A.*wc.';
  [U,S,V] = svd(B,'econ');
  singular = diag(S);
  u1 = U(:,end); v1 = V(:,end);
  q_raw = wc.*v1;
  q_norm = norm(q_raw);
  if ~isfinite(q_norm) || q_norm == 0 || any(~isfinite(q_raw))
    error('i31:NonzeroField','The physical near-null vector is unavailable.');
  end
  q = q_raw/q_norm;
  ell = wr.*u1;
  anorm = max(realmin,norm(A,2));
  right = norm(A*q_raw);
  left = norm(ell'*A);
  triplet = max(norm(B*v1-singular(end)*u1), ...
    norm(B'*u1-singular(end)*v1))/max(realmin,singular(1));
  physical = LOCAL_physical_summary(node,q,c);
  factor_rcond = [node.factors.rcond];
  factor_residual = [node.factors.residual];
  out = struct('pass',true,'Aphys_score',singular(end)/singular(1), ...
    'near_null_ratio',singular(end)/singular(end-1), ...
    'sigma_min',singular(end),'sigma_next',singular(end-1), ...
    'sigma_max',singular(1),'raw_right_residual',right, ...
    'raw_left_residual',left, ...
    'raw_right_backward',right/max(realmin,anorm*norm(q_raw)), ...
    'raw_left_backward',left/max(realmin,anorm*norm(ell)), ...
    'svd_triplet_residual',triplet,'q_raw_norm',q_norm,'q',q, ...
    'factor_names',{string({node.factors.name})}, ...
    'factor_rcond',factor_rcond,'factor_residual',factor_residual, ...
    'factor_pass',logical([node.factors.pass]), ...
    'minimum_factor_rcond',min(factor_rcond), ...
    'maximum_factor_residual',max(factor_residual), ...
    'physical',physical);
end

function out = LOCAL_physical_summary(node,q,c)
  K = c.K; I = eye(K); E = diag(node.phase(:));
  qL = q(1:K); qR = q(K+1:end);
  cminus = node.Dm\([I,E]*q);
  cplus = node.Dp\([E,I]*q);
  lift = [q;cminus;cplus];
  drow = [1:K,2*K+1:3*K];
  nrow = [K+1:2*K,3*K+1:4*K];
  Gd = node.AdefG(drow,:); Gn = node.AdefG(nrow,:);
  ed = norm(Gd*lift)/max(1,norm(Gd,2)*norm(lift));
  en = norm(Gn*lift-node.AdefD*q)/max(1, ...
    norm(Gn,2)*norm(lift)+norm(node.AdefD,2)*norm(q));
  kernel = norm(node.AdefG*lift)/max(1,norm(node.AdefG,'fro')*norm(lift));
  dL = qL+node.phase(:).*qR;
  dR = node.phase(:).*qL+qR;
  b = sqrt(1+abs(node.beta_m(:)).^2);
  wall = [sqrt(b).*dL;sqrt(b).*dR];
  [px,py] = ndgrid([-0.25,0,0.25],[-0.25,0,0.25]);
  probes = zeros(9,1);
  for j = 1:9
    basis = exp(1i*node.beta_m(:)*py(j))/sqrt(c.d);
    right = exp(1i*node.gamma(:)*(px(j)-c.X_L));
    left = exp(-1i*node.gamma(:)*(px(j)-c.X_R));
    probes(j) = sum((qL.*right+qR.*left).*basis);
  end
  out = struct('center_participation', ...
    min(norm(qL),norm(qR))/max(realmin,norm(q)), ...
    'graph_participation',min(norm(cminus),norm(cplus))/ ...
    max(realmin,norm(lift)),'dirichlet_defect',ed, ...
    'neumann_defect',en,'kernel_defect',kernel, ...
    'wall_participation',norm(wall)/max(realmin,norm(q)), ...
    'probe_participation',norm(probes)/max(realmin,norm(q)), ...
    'probe_field',probes);
end

%% ==================== Continuous strong residual ====================
% These helpers evaluate the fixed compact-support field and all residual terms.

function out = LOCAL_strong_norms(q,beta,gamma,c,N)
  x = linspace(c.X_L,c.X_R,N+1);
  q = q(:); beta = beta(:); gamma = gamma(:);
  qL = q(1:c.K); qR = q(c.K+1:end);
  eL = exp(1i*gamma.*(x-c.X_L));
  eR = exp(-1i*gamma.*(x-c.X_R));
  phi = qL.*eL+qR.*eR;
  phix = 1i*gamma.*qL.*eL-1i*gamma.*qR.*eR;
  chi = cos(pi*x).^2;
  chip = -pi*sin(2*pi*x);
  chipp = -2*pi^2*cos(2*pi*x);
  mu = c.khat^2;
  delta = beta.^2+gamma.^2-mu;
  r_second = -chipp.*phi;
  r_first = -2*chip.*phix;
  r_dispersion = chi.*(delta.*phi);
  residual = r_second+r_first+r_dispersion;

  field_norm = sqrt(max(0,LOCAL_simpson(sum(abs(chi.*phi).^2,1),c,N)));
  residual_norm = sqrt(max(0,LOCAL_simpson(sum(abs(residual).^2,1),c,N)));
  second_norm = sqrt(max(0,LOCAL_simpson(sum(abs(r_second).^2,1),c,N)));
  first_norm = sqrt(max(0,LOCAL_simpson(sum(abs(r_first).^2,1),c,N)));
  dispersion_norm = sqrt(max(0, ...
    LOCAL_simpson(sum(abs(r_dispersion).^2,1),c,N)));
  eta = residual_norm/max(realmin,field_norm);
  delta_scale = max([mu*ones(c.K,1),abs(beta).^2+abs(gamma).^2, ...
    realmin*ones(c.K,1)],[],2);
  info = whos;
  out = struct('N',N,'field_norm',field_norm, ...
    'residual_norm',residual_norm,'eta_lambda',eta, ...
    'cutoff_second_norm',second_norm,'cutoff_first_norm',first_norm, ...
    'dispersion_norm',dispersion_norm, ...
    'dispersion_fraction',dispersion_norm/max(realmin,residual_norm), ...
    'delta_m',delta,'normalized_dispersion_max', ...
    max(abs(delta)./delta_scale),'workspace_mib',sum([info.bytes])/2^20);
end

function value = LOCAL_simpson(samples,c,N)
  h = (c.X_R-c.X_L)/N;
  value = h/3*(samples(1)+samples(end)+ ...
    4*sum(samples(2:2:end-1))+2*sum(samples(3:2:end-2)));
  value = real(value);
end

function result = LOCAL_qualify(result,finite,node,levels,scaled,c)
  finest = levels(end); previous = levels(end-1);
  convergence = abs(finest.eta_lambda-previous.eta_lambda)/ ...
    max(abs(finest.eta_lambda),realmin);
  scale_defect = abs(scaled.eta_lambda-finest.eta_lambda)/ ...
    max(abs(finest.eta_lambda),realmin);
  values = [[levels.field_norm],[levels.residual_norm], ...
    [levels.eta_lambda],convergence,scale_defect];
  field_finite = isfinite(finest.field_norm);
  all_norms_finite = all(isfinite(values));
  nonzero = field_finite && finest.field_norm > c.field_norm_min;
  stable = all_norms_finite && convergence <= c.simpson_relative_max && ...
    scale_defect <= c.scale_relative_max;

  result.execution_pass = true;
  result.finite_input = finite;
  result.field = struct('q',finite.q,'beta_m',node.beta_m(:), ...
    'gamma_m',node.gamma(:),'cutoff','cos(pi*x)^2 on [-1/2,1/2], zero outside', ...
    'operator','A=-rho^{-1}Delta; rho=1 on support', ...
    'conforming_domain','H2 quasi-periodic compact support', ...
    'nonzero',nonzero);
  result.quadrature = struct('method','COMPOSITE_SIMPSON', ...
    'levels',levels,'finest_relative_change',convergence, ...
    'relative_change_max',c.simpson_relative_max, ...
    'scale_factor',c.scale_oracle,'scaled_finest',scaled, ...
    'scale_phase_relative_defect',scale_defect, ...
    'scale_phase_relative_max',c.scale_relative_max, ...
    'stable',stable);
  result.estimator = struct('available',false, ...
    'lambda_scale',finest.eta_lambda, ...
    'field_norm',finest.field_norm,'residual_norm',finest.residual_norm, ...
    'cutoff_second_norm',finest.cutoff_second_norm, ...
    'cutoff_first_norm',finest.cutoff_first_norm, ...
    'dispersion_norm',finest.dispersion_norm, ...
    'dispersion_fraction',finest.dispersion_fraction, ...
    'normalized_dispersion_max',finest.normalized_dispersion_max);

  if ~field_finite || ~all_norms_finite
    result.status = 'I3_1_CONTINUOUS_STRONG_RESIDUAL_UNRESOLVED';
    result.scientific_outcome = 'CONTINUOUS_STRONG_RESIDUAL_UNRESOLVED';
    result.first_failure = LOCAL_failure( ...
      'CONTINUOUS_STRONG_RESIDUAL_UNRESOLVED','QUADRATURE', ...
      'A computed field, residual, ratio, or comparison was nonfinite.','');
  elseif ~nonzero
    result.status = 'I3_1_NONZERO_CONFORMING_FIELD_UNAVAILABLE';
    result.scientific_outcome = 'NONZERO_CONFORMING_FIELD_UNAVAILABLE';
    result.first_failure = LOCAL_failure( ...
      'NONZERO_CONFORMING_FIELD_UNAVAILABLE','FIELD', ...
      'The compact-support field norm was unavailable or too small.','');
  elseif ~stable
    result.status = 'I3_1_CONTINUOUS_STRONG_RESIDUAL_UNRESOLVED';
    result.scientific_outcome = 'CONTINUOUS_STRONG_RESIDUAL_UNRESOLVED';
    result.first_failure = LOCAL_failure( ...
      'CONTINUOUS_STRONG_RESIDUAL_UNRESOLVED','QUADRATURE', ...
      'A Simpson refinement or phase/scale invariance gate failed.','');
  else
    result.status = 'I3_1_CONTINUOUS_STRONG_RESIDUAL_ESTIMATOR_CANDIDATE';
    result.scientific_outcome = ...
      'CONTINUOUS_STRONG_RESIDUAL_ESTIMATOR_CANDIDATE';
    result.indicator_available = true;
    result.estimator.available = true;
    result.first_failure = LOCAL_failure( ...
      'RELIABLE_NUMERICAL_ENCLOSURE_UNAVAILABLE','STRICT_UPGRADE', ...
      'The computed residual ratio has no reliable numerical enclosure.','');
  end
end

