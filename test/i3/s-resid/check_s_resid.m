function result = check_s_resid(attempt)
%CHECK_S_RESID Compute the I3.1 compact-support strong-residual indicator.
% Purpose:
%   Re-evaluate the saved I2 candidate, reconstruct its explicit Fourier
%   field in the homogeneous empty center column, apply a fixed compact
%   cutoff, and compute a continuous strong-residual norm ratio.
% Input:
%   attempt - New append-only output tag. The reviewed tag is 'center-a1'.
% Output:
%   result  - Finite-input diagnostics, three Simpson levels, the computed
%             residual indicator, resource data, and strict claim limits.
% Main algorithm:
%   Use one frozen I2.1 seed and one saved-candidate point, form q=Dc*v1,
%   evaluate the cutoff field mode by mode, and exploit Fourier orthogonality
%   to reduce both continuous norms to one-dimensional Simpson quadrature.
% Based on:
%   research/projects/eig-apost/implementation/i3/design-3-1.md.
% Numerical goal:
%   Produce a computed continuous strong-residual estimator candidate. The
%   result is not a certified enclosure or a discrete-eigenvalue existence
%   claim because rigorous quadrature and the projected gap are unavailable.

  if nargin ~= 1 || ~strcmp(char(attempt),'center-a1')
    error('i31:Attempt','The reviewed attempt name is center-a1.');
  end
  here = fileparts(mfilename('fullpath'));
  output = fullfile(here,'output',char(attempt));
  if exist(output,'dir') || exist(output,'file')
    error('i31:OutputExists','Output already exists: %s.',output);
  end
  if exist('OCTAVE_VERSION','builtin') ~= 0
    error('i31:MATLABRequired','This experiment requires MATLAB.');
  end

  timer = tic;
  c = LOCAL_config();
  result = LOCAL_empty_result(char(attempt),c);
  peak_mib = 0;
  try
    rows = LOCAL_selectors();
    [seed,frame] = eval_i21('seed',c,rows);
    LOCAL_seed_gate(seed,frame,c);
    peak_mib = max(peak_mib,LOCAL_mib({seed,frame}));

    node = eval_i21('point',c.khat,c,frame);
    LOCAL_point_gate(node,frame,c);
    finite = LOCAL_finite_diagnostics(node,c);
    result.finite_input = finite;
    peak_mib = max(peak_mib,LOCAL_mib({seed,frame,node,finite}));
    if toc(timer) > c.soft_seconds
      error('i31:SoftTime','The soft time limit was reached before quadrature.');
    end

    levels = repmat(LOCAL_empty_level(),numel(c.simpson_intervals),1);
    for j = 1:numel(c.simpson_intervals)
      levels(j) = LOCAL_strong_norms(finite.q,node.beta_m,node.gamma,c, ...
        c.simpson_intervals(j));
      peak_mib = max(peak_mib,LOCAL_mib({seed,frame,node,finite})+ ...
        levels(j).workspace_mib);
    end
    if toc(timer) > c.soft_seconds
      error('i31:SoftTime','The soft time limit was reached before the scale check.');
    end
    scaled = LOCAL_strong_norms(c.scale_oracle*finite.q, ...
      node.beta_m,node.gamma,c,c.simpson_intervals(end));
    peak_mib = max(peak_mib,LOCAL_mib({seed,frame,node,finite})+ ...
      scaled.workspace_mib);

    result = LOCAL_qualify(result,finite,node,levels,scaled,c);
  catch ME
    failure = LOCAL_exception_failure(ME);
    result.first_failure = failure;
    if strcmp(failure.code,'FINITE_DISCRETE_INPUT_UNAVAILABLE') || ...
        strcmp(failure.code,'NONZERO_CONFORMING_FIELD_UNAVAILABLE')
      result.execution_pass = true;
      result.status = ['I3_1_',failure.code];
      result.scientific_outcome = failure.code;
    else
      result.execution_pass = false;
      result.status = 'I3_1_EXECUTION_UNAVAILABLE';
      result.scientific_outcome = 'UNAVAILABLE';
    end
  end

  result.elapsed_seconds = toc(timer);
  result.peak_active_mib = peak_mib;
  result.soft_time_exceeded = result.elapsed_seconds > c.soft_seconds;
  if result.elapsed_seconds > c.hard_seconds || peak_mib > c.memory_mib_max
    result.execution_pass = false;
    result.indicator_available = false;
    if isstruct(result.estimator) && isfield(result.estimator,'available')
      result.estimator.available = false;
    end
    result.status = 'I3_1_EXECUTION_UNAVAILABLE';
    result.scientific_outcome = 'UNAVAILABLE';
    result.first_failure = LOCAL_failure('EXECUTION_UNAVAILABLE','RESOURCE', ...
      'The hard time or active-object memory limit was exceeded.','i31:Resource');
  end

  if exist(output,'dir') || exist(output,'file')
    error('i31:OutputExists','Output appeared during the run: %s.',output);
  end
  mkdir(output);
  save(fullfile(output,'result.mat'),'result','-v7');
  LOCAL_report(fullfile(output,'report.md'),result);
end

