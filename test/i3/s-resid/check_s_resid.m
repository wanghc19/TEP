function out = LOCAL_exception_failure(ME)
  if strcmp(ME.identifier,'i31:NonzeroField')
    code = 'NONZERO_CONFORMING_FIELD_UNAVAILABLE'; stage = 'FIELD';
  elseif strcmp(ME.identifier,'i31:FiniteInput') || ...
      startsWith(ME.identifier,'i21:') || startsWith(ME.identifier,'kready')
    code = 'FINITE_DISCRETE_INPUT_UNAVAILABLE'; stage = 'FINITE_INPUT';
  else
    code = 'EXECUTION_UNAVAILABLE'; stage = 'EXECUTION';
  end
  out = LOCAL_failure(code,stage,ME.message,ME.identifier);
end

function out = LOCAL_failure(code,stage,message,identifier)
  out = struct('code',code,'stage',stage,'message',message, ...
    'identifier',identifier);
end

