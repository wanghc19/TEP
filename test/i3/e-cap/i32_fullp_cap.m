end

function center=LOCAL_artifact_wall_center(z,bw)
  left=LOCAL_pad_orders(z.center_wall_jumps.left_coefficients,512,numel(bw));
  right=LOCAL_pad_orders(z.center_wall_jumps.right_coefficients,512,numel(bw));
  center=[left./sqrt(bw);right./sqrt(bw)];
end

function [defL,defR,record]=LOCAL_artifact_wall_defects(s,Nout)
  a=s.raw_maps; y=a.wall_common_y_1024(:); beta=s.certificate.beta;
  values=a.wall_common_value_1024; N=numel(y);
  if size(values,1)~=2*N
    error('i32f:ArtifactWallMap','The artifact common wall map has wrong size.');
  end
  rawL=LOCAL_physical_coeff(values(1:N,:),y,beta,s.certificate.d);
  rawR=LOCAL_physical_coeff(values(N+1:end,:),y,beta,s.certificate.d);
  input=a.wall_input_unit_512;
  gL=LOCAL_pad_orders(input(1:512,:),512,N);
  gR=LOCAL_pad_orders(input(513:end,:),512,N);
  nativeL=gL-rawL; nativeR=gR-rawR;
  defL=LOCAL_pad_orders(nativeL,N,Nout);
  defR=LOCAL_pad_orders(nativeR,N,Nout);
  record=struct('grid_nodes',N,'order_min',-N/2,'order_max',N/2-1, ...
    'defect_left_norm',norm(nativeL,'fro'), ...
    'defect_right_norm',norm(nativeR,'fro'), ...
    'raw_left_norm',norm(rawL,'fro'),'raw_right_norm',norm(rawR,'fro'), ...
    'shared_left_norm',norm(gL,'fro'),'shared_right_norm',norm(gR,'fro'), ...
    'canonical_output_orders',Nout,'Fourier_evaluation_not_nearest_node',true);
end

function coeff=LOCAL_physical_coeff(values,y,beta,d)
  N=numel(y); gauge=bsxfun(@times,values,exp(-1i*beta*y));
  shift=exp(-1i*2*pi*(-N/2:N/2-1).'*y(1)/d);
  coeff=sqrt(d)*fftshift(fft(gauge,[],1),1)/N;
  coeff=bsxfun(@times,coeff,shift);
end

function out=LOCAL_factor_pair(c,a,b,z,Na,Nb)
  if isscalar(Na), Nam=Na; Nap=Na; else, Nam=Na(1); Nap=Na(2); end
  if isscalar(Nb), Nbm=Nb; Nbp=Nb; else, Nbm=Nb(1); Nbp=Nb(2); end
  label=[a.endpoint_id,'->',b.endpoint_id];
  class_name=LOCAL_pair_parity_class(label,false);
  parity_required=~isempty(class_name);
  [dm,bm]=LOCAL_side_factor_pair( ...
    c,a.minus,b.minus,z.Pminus,z.cminus,Nam,Nbm,parity_required);
  [dp,bp]=LOCAL_side_factor_pair( ...
    c,a.plus,b.plus,z.Pplus,z.cplus,Nap,Nbp,parity_required);
  dc=norm(b.center-a.center)^2;
  parity=struct([]);
  if parity_required
    am=LOCAL_tail_slot(z.Pminus,a.minus'*a.minus,z.cminus,Nam,c);
    bm_tail=LOCAL_tail_slot(z.Pminus,b.minus'*b.minus,z.cminus,Nbm,c);
    ap=LOCAL_tail_slot(z.Pplus,a.plus'*a.plus,z.cplus,Nap,c);
    bp_tail=LOCAL_tail_slot(z.Pplus,b.plus'*b.plus,z.cplus,Nbp,c);
    long=norm([b.center(:)-a.center(:);bm; ...
      sqrt(bm_tail.value)-sqrt(am.value);bp; ...
      sqrt(bp_tail.value)-sqrt(ap.value)]);
    reconstructed=sqrt(dc+sum(dm)+ ...
      (sqrt(bm_tail.value)-sqrt(am.value))^2+sum(dp)+ ...
      (sqrt(bp_tail.value)-sqrt(ap.value))^2);
    nops=4*(numel(a.center)+numel(bm)+numel(bp)+2)+24;
    parity=LOCAL_parity_record(label,class_name,long,reconstructed,nops);
    clear am bm_tail ap bp_tail long reconstructed;
  end
  out=struct('left_endpoint_id',a.endpoint_id, ...
    'right_endpoint_id',b.endpoint_id, ...
    'center_difference_squared',dc, ...
    'minus_direct_difference_squared_terms',dm, ...
    'plus_direct_difference_squared_terms',dp, ...
    'left_norm_scale',NaN,'right_norm_scale',NaN, ...
    'finite',all(isfinite([dc,dm,dp])), ...
    'signature_parity',parity);
  clear bm bp;
end

function [terms,block]=LOCAL_side_factor_pair(c,A,B,P,c0,Na,Nb,need_block)
  rows=size(A,1); Nmax=max(c.full_p_levels);
  if size(B,1)~=rows
    error('i32f:SignatureRows','A factor pair has inconsistent row order.');
  end
  terms=zeros(1,Nmax);
  if need_block, block=zeros(rows*Nmax,1,'like',A*c0); else, block=[]; end
  state=c0;
  for n=1:Nmax
    da=zeros(rows,1,'like',A*c0); db=da;
    if n<=Na, da=A*state; end
    if n<=Nb, db=B*state; end
    difference=db-da; terms(n)=norm(difference)^2;
    if need_block, block((n-1)*rows+(1:rows))=difference; end
    state=P*state;
  end
end

function out=LOCAL_combine_pair(a,b)
  out=struct('left_endpoint_id',[a.left_endpoint_id,'+',b.left_endpoint_id], ...
    'right_endpoint_id',[a.right_endpoint_id,'+',b.right_endpoint_id], ...
    'center_difference_squared',a.center_difference_squared+ ...
      b.center_difference_squared, ...
    'minus_direct_difference_squared_terms', ...
      a.minus_direct_difference_squared_terms+ ...
      b.minus_direct_difference_squared_terms, ...
    'plus_direct_difference_squared_terms', ...
      a.plus_direct_difference_squared_terms+ ...
      b.plus_direct_difference_squared_terms, ...
    'left_norm_scale',max(a.left_norm_scale,b.left_norm_scale), ...
    'right_norm_scale',max(a.right_norm_scale,b.right_norm_scale), ...
    'finite',a.finite&&b.finite,'signature_parity',struct([]));
end

function out=LOCAL_combined_factor_pair(c,ac,aw,bc,bw,z,Na,Nb)
  if isscalar(Na), Nam=Na; Nap=Na; else, Nam=Na(1); Nap=Na(2); end
  if isscalar(Nb), Nbm=Nb; Nbp=Nb; else, Nbm=Nb(1); Nbp=Nb(2); end
  if ~strcmp(ac.combined_endpoint_id,aw.combined_endpoint_id)|| ...
      ~strcmp(bc.combined_endpoint_id,bw.combined_endpoint_id)
    error('i32f:CombinedEndpointIdentity', ...
      'Combined-volume factor families do not share an endpoint identity.');
  end
  label=[ac.combined_endpoint_id,'->',bc.combined_endpoint_id];
  class_name=LOCAL_pair_parity_class(label,true);
  parity_required=~isempty(class_name);
  Am=[ac.minus;aw.minus]; Bm=[bc.minus;bw.minus];
  Ap=[ac.plus;aw.plus]; Bp=[bc.plus;bw.plus];
  [dm,bm]=LOCAL_side_factor_pair( ...
    c,Am,Bm,z.Pminus,z.cminus,Nam,Nbm,parity_required);
  [dp,bp]=LOCAL_side_factor_pair( ...
    c,Ap,Bp,z.Pplus,z.cplus,Nap,Nbp,parity_required);
  center_difference=[bc.center(:)-ac.center(:);bw.center(:)-aw.center(:)];
  dc=norm(center_difference)^2; parity=struct([]);
  if parity_required
    old_am=LOCAL_tail_slot(z.Pminus,Am'*Am,z.cminus,Nam,c);
    old_bm=LOCAL_tail_slot(z.Pminus,Bm'*Bm,z.cminus,Nbm,c);
    old_ap=LOCAL_tail_slot(z.Pplus,Ap'*Ap,z.cplus,Nap,c);
    old_bp=LOCAL_tail_slot(z.Pplus,Bp'*Bp,z.cplus,Nbp,c);
    sig_am=LOCAL_tail_slot(z.Pminus, ...
      ac.minus'*ac.minus+aw.minus'*aw.minus,z.cminus,Nam,c);
    sig_bm=LOCAL_tail_slot(z.Pminus, ...
      bc.minus'*bc.minus+bw.minus'*bw.minus,z.cminus,Nbm,c);
    sig_ap=LOCAL_tail_slot(z.Pplus, ...
      ac.plus'*ac.plus+aw.plus'*aw.plus,z.cplus,Nap,c);
    sig_bp=LOCAL_tail_slot(z.Pplus, ...
      bc.plus'*bc.plus+bw.plus'*bw.plus,z.cplus,Nbp,c);
    long=norm([center_difference;bm; ...
      sqrt(old_bm.value)-sqrt(old_am.value);bp; ...
      sqrt(old_bp.value)-sqrt(old_ap.value)]);
    reconstructed=sqrt(dc+sum(dm)+ ...
      (sqrt(sig_bm.value)-sqrt(sig_am.value))^2+sum(dp)+ ...
      (sqrt(sig_bp.value)-sqrt(sig_ap.value))^2);
    nops=4*(numel(center_difference)+numel(bm)+numel(bp)+2)+24;
    parity=LOCAL_parity_record(label,class_name,long,reconstructed,nops);
    clear old_am old_bm old_ap old_bp sig_am sig_bm sig_ap sig_bp;
    clear long reconstructed;
  end
  out=struct('left_endpoint_id',ac.combined_endpoint_id, ...
    'right_endpoint_id',bc.combined_endpoint_id, ...
    'center_difference_squared',dc, ...
    'minus_direct_difference_squared_terms',dm, ...
    'plus_direct_difference_squared_terms',dp, ...
    'left_norm_scale',NaN,'right_norm_scale',NaN, ...
    'finite',all(isfinite([dc,dm,dp])), ...
    'signature_parity',parity);
  clear center_difference bm bp;
end

function out=LOCAL_project_pair(a,b,pair)
  left_match=strcmp(LOCAL_canonical_endpoint_id(pair.left_endpoint_id), ...
    LOCAL_canonical_endpoint_id(a.signature.endpoint_id));
  right_match=strcmp(LOCAL_canonical_endpoint_id(pair.right_endpoint_id), ...
    LOCAL_canonical_endpoint_id(b.signature.endpoint_id));
  if ~left_match||~right_match
    error('i32f:PairEndpointIdentity', ...
      'A pair signature does not name the projected endpoint identities.');
  end
  scalar=abs(b.B-a.B);
  factor=sqrt(pair.center_difference_squared+ ...
    sum(pair.minus_direct_difference_squared_terms)+ ...
    (sqrt(b.tail.minus.value)-sqrt(a.tail.minus.value))^2+ ...
    sum(pair.plus_direct_difference_squared_terms)+ ...
    (sqrt(b.tail.plus.value)-sqrt(a.tail.plus.value))^2);
  numerator=max(scalar,factor); scale=max([realmin,a.B,b.B]);
  out=struct('left_endpoint_id',pair.left_endpoint_id, ...
    'right_endpoint_id',pair.right_endpoint_id, ...
    'endpoint_identity_match',left_match&&right_match, ...
    'scalar_shift',scalar,'factor_shift',factor, ...
    'left_norm',a.B,'right_norm',b.B,'zero_component',a.B==0&&b.B==0, ...
    'value',numerator,'numerator',numerator,'scale',scale, ...
    'ratio',numerator/scale,'threshold',NaN,'absolute_threshold',NaN, ...
    'pass',isfinite(numerator),'signature_parity',pair.signature_parity);
end

function [out,warnings]=LOCAL_anchors(c,s,artifact,final,pair)
  warnings=LOCAL_empty_warnings(); names={'wall','circle','volume'};
  fields={'B_wall','B_circle','B_volume'};
  for j=1:3
    name=names{j}; a=artifact.(name); f=final.(name);
    anchor=s.ordinary_anchor.(fields{j}); metric=LOCAL_project_pair(a,f,pair.(name));
    scale=max([realmin,anchor,f.B,a.B]); nops=2*f.augmented_length+8;
    omega=100*nops*eps*scale; observed=max(abs(f.B-anchor),metric.factor_shift);
    association=abs(f.B-a.B)<=metric.factor_shift+omega;
    out.(name)=struct('artifact_scalar',anchor, ...
      'artifact_common_factor_norm',a.B,'fresh_final',f.B, ...
      'scalar_shift',abs(f.B-anchor),'factor_shift',metric.factor_shift, ...
      'observed_shift',observed,'comparison_operations',nops, ...
      'comparison_omega',omega,'A',observed+omega, ...
      'numerator',abs(f.B-a.B),'scale',max(realmin,metric.factor_shift+omega), ...
      'ratio',abs(f.B-a.B)/max(realmin,metric.factor_shift+omega), ...
      'threshold',1,'pass',association,'reverse_triangle_pass',association, ...
      'available',a.finite&&f.finite&&association&&isfinite(observed+omega), ...
      'factor_metric',metric);
    if ~out.(name).available
      warnings(end+1)=LOCAL_warning('COMPONENT_NORM_ASSOCIATION_UNRESOLVED', ...
        out.(name).ratio); %#ok<AGROW>
    end
  end
end

