    'minus',LOCAL_weight_rows(LOCAL_pad_orders(a.delta_minus,512,Nc),sqrt(cv)), ...
    'plus',LOCAL_weight_rows(LOCAL_pad_orders(a.delta_plus,512,Nc),sqrt(cv)), ...
    'center',zeros(0,1),'endpoint_id','artifact-volume-circle', ...
    'combined_endpoint_id','artifact-volume');
