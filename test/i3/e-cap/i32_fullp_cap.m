function [out,calls,gram]=LOCAL_weight_three_axis( ...
    c,z,lift,wall,circle,axis,component,calls)
  values=cell(1,3); factors=cell(1,3); pairs=cell(1,2); gram=struct([]);
  base_wall=wall.cap_signatures.output{3}.wall;
  base_circle=circle.cap_signatures.angular{3}.circle;
  base_volume_circle=circle.cap_signatures.angular{3}.volume_circle;
  base_volume_wall=wall.cap_signatures.output{3}.volume_wall;
  for j=1:3
    sig.wall=base_wall; sig.circle=base_circle;
    if strcmp(axis,'riccati')
      bc=lift.circle_weights{j};
      factors{j}=struct('minus',LOCAL_weight_rows( ...
        circle.finest_factors.jump_minus,1./sqrt(bc)), ...
        'plus',LOCAL_weight_rows(circle.finest_factors.jump_plus,1./sqrt(bc)), ...
        'center',zeros(0,1),'endpoint_id',sprintf('riccati-circle-%d',j));
      sig.circle=LOCAL_factor_signature(c,sprintf('riccati-circle-%d',j), ...
        'circle',factors{j},z,32);
      sig.volume=LOCAL_existing_combined_volume(c,z, ...
        base_volume_circle,base_volume_wall,32);
    else
      cv=lift.collar_weights{j}/z.gamma;
      wv=lift.wall_lift_weights{j}/z.gamma;
      fc=struct('minus',LOCAL_weight_rows( ...
        circle.finest_factors.delta_minus,sqrt(cv)), ...
        'plus',LOCAL_weight_rows(circle.finest_factors.delta_plus,sqrt(cv)), ...
        'center',zeros(0,1));
      fw=LOCAL_volume_wall_factors(z,wall.finest_factors,wv);
      fc.endpoint_id=sprintf('gauss-volume-circle-%d',j);
      fc.combined_endpoint_id=sprintf('gauss-volume-%d',j);
      fw.endpoint_id=sprintf('gauss-volume-wall-%d',j);
      fw.combined_endpoint_id=sprintf('gauss-volume-%d',j);
      factors{j}=struct('circle',fc,'wall',fw);
      sc=LOCAL_factor_signature(c,sprintf('gauss-volume-circle-%d',j), ...
        'volume-circle',fc,z,32);
      sw=LOCAL_factor_signature(c,sprintf('gauss-volume-wall-%d',j), ...
        'volume-wall',fw,z,32);
      [sig.volume,g]=LOCAL_combine_volume(c,sprintf('gauss-volume-%d',j), ...
        sc,sw,fc,fw,z,32,true,'actual-gauss-axis');
      gram=LOCAL_concat(gram,g);
    end
    [values{j},calls]=LOCAL_project_components( ...
      c,z,sig,calls,'three_axis',true);
  end
  for j=1:2
    if strcmp(axis,'riccati')
      pairs{j}=LOCAL_factor_pair(c,factors{j},factors{j+1},z,32,32);
    else
      pairs{j}=LOCAL_combined_factor_pair(c, ...
        factors{j}.circle,factors{j}.wall, ...
        factors{j+1}.circle,factors{j+1}.wall,z,32,32);
    end
  end
  out=LOCAL_three_axis_metric(c,values,pairs,axis,component);
  clear factors;
end

