    leg_metrics{a}=struct();
    for j=1:numel(affected{a})
      name=affected{a}{j}; metric=LOCAL_project_pair( ...
        legs{a}.(name),final.(name),pairs{a}.(name));
      leg_metrics{a}.(name)=metric; finallegs=finallegs+metric.factor_shift;
    end
  end
  omega=100*(final.wall.augmented_length+final.circle.augmented_length+ ...
    final.volume.augmented_length)*eps*scale;
  out=struct('joint_shift',lhs,'official_final_leg_sum',finallegs, ...
    'omega',omega,'numerator',lhs,'scale',max(realmin,finallegs+omega), ...
    'ratio',lhs/max(realmin,finallegs+omega),'threshold',1, ...
    'pass',isfinite(lhs)&&lhs<=finallegs+omega, ...
    'joint_metrics',joint_metrics,'official_leg_metrics',{leg_metrics}, ...
    'all_projected_endpoint_parity', ...
      LOCAL_component_value_parity([{joint},legs]), ...
    'representative_finest_N16_to_N32_signature_parity', ...
      representative_pair.signature_parity, ...
    'joint_actual_producer_parity',true, ...
    'combined_joint_end_to_end_representative_only',true);
end

