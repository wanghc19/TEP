function out = i32_fullp_cap(c,staged,lift,wall,circle,timer,retained_before_mib)
%I32_FULLP_CAP Project compact signatures and form the frozen empirical cap.
% Purpose:
%   Consume the fixed certificate, finest boundary factors, and compact
%   nested signatures, then reproduce the full-P tail, cap, field, and
%   nominal-transform formulas without retaining augmented vectors.
% Input:
%   c, staged, lift, wall, circle, timer - Frozen REV_F objects.
%   retained_before_mib                 - Caller active-object proxy.
% Output:
%   out                                 - Typed total compact cap result.
% Main algorithm:
%   Reconstruct endpoint and pair norms from orthogonal squared signatures,
%   combine circle and wall volume Grams before one tail per side, preserve
%   all 292 contraction categories, and run the two arithmetic parity gates.
% Based on:
%   i32_cap_tail.m Revision E and design-3-2c.md REV_F.
% Main changes:
%   No endpoint vector or dense nested level leaves its producer.  Full-P
%   powers remain complete matrices and the sole eig allowlist is the small
%   Hermitian Gram diagnostic in LOCAL_psd_root.
% Numerical goal:
%   Produce the same ordinary empirical candidate with bounded retained memory.

  calls=LOCAL_zero_counters(); warnings=LOCAL_empty_warnings(); peak=0;
  first=LOCAL_condition('NONE','All compact cap objects are available.');
  available=false; public=LOCAL_unavailable_public(); signatures=struct();
  input_alias=LOCAL_value_mib(staged)+LOCAL_value_mib(lift)+ ...
    LOCAL_value_mib(wall)+LOCAL_value_mib(circle);
  peak=max(peak,LOCAL_workspace_mib());
  try
    z=staged.certificate;
    [final_factors,final_sig,gram_parity]= ...
      LOCAL_final_objects(c,z,lift,wall.finest_factors, ...
      circle.finest_factors);
    [final,calls]=LOCAL_project_components(c,z,final_sig,calls,'final',true);
    [state,calls]=LOCAL_state_tail(c,z,calls);
    [artifact,artifact_pair,artifact_audit,calls,artifact_gram]= ...
      LOCAL_artifact(c,staged,lift,final_factors,final,calls);
    gram_parity=LOCAL_concat(gram_parity,artifact_gram);
    [anchors,anchor_warnings]=LOCAL_anchors(c,staged,artifact,final,artifact_pair);
    warnings=[warnings,anchor_warnings];
    [axes,axis_warnings,calls,axis_gram]=LOCAL_axes( ...
      c,z,lift,wall,circle,final_factors,final_sig,final,calls,timer);
    warnings=[warnings,axis_warnings]; gram_parity=LOCAL_concat(gram_parity,axis_gram);
    [shells,shell_warnings,calls,shell_gram]=LOCAL_shells( ...
      c,z,lift,wall.finest_factors,circle.finest_factors,calls);
    warnings=[warnings,shell_warnings];
    gram_parity=LOCAL_concat(gram_parity,shell_gram);
    [arithmetic,arith_warnings]=LOCAL_arithmetic(c,final);
    warnings=[warnings,arith_warnings];
    components=LOCAL_component_caps(anchors,axes,shells,arithmetic);
    [field,field_warnings,calls]=LOCAL_field_cap(c,staged,calls);
    warnings=[warnings,field_warnings];
    producer_parity=LOCAL_producer_parity(wall,circle);
    endpoint_parity=LOCAL_collect_endpoint_parity( ...
      final_sig,artifact,artifact_pair,axes,shells);
    signature_parity=LOCAL_join_parity(producer_parity,endpoint_parity);
    combined_gram=LOCAL_gram_parity_summary(gram_parity);
    calls.n_op_signature_parity=endpoint_parity.total_operations;
    calls.n_op_combined_gram_parity=combined_gram.total_operations;
    qualification=LOCAL_qualification(wall,circle,signature_parity,combined_gram);
    numerator_available=components.wall.available&&components.circle.available&& ...
      components.volume.available&&axes.interaction.pass&&state.available&& ...
      qualification.kernel_oracle_available&&qualification.kernel_qualified&& ...
      qualification.conformity_qualified&&qualification.actual_T_qualified&& ...
      qualification.finite_bloch_qualified&&signature_parity.pass&& ...
      combined_gram.pass;
    denominator_available=field.available;
    if ~numerator_available
      first=LOCAL_first_unavailable(components,axes,shells,arithmetic,state, ...
        qualification,signature_parity,combined_gram);
    elseif ~denominator_available
      first=LOCAL_condition('FIELD_PARTIAL_EMPIRICALLY_UNRESOLVED', ...
        'The same finite field partial did not form a one-sided empirical cap.');
    end
    caps=LOCAL_caps(staged,components,field,numerator_available, ...
      denominator_available);
    estimator=LOCAL_estimator(staged,c,caps,numerator_available, ...
      denominator_available);
    warnings=[warnings,LOCAL_tail_warnings(c,final,state)];
    category=LOCAL_category_audit(calls);
    if ~category.pass
      first=LOCAL_condition('FULL_P_CONTRACTION_IDENTITY_UNAVAILABLE', ...
        'The full-P category ledger is not the frozen 292 allocation.');
    end
    eig_audit=LOCAL_eig_audit(calls);
    if ~eig_audit.pass
      first=LOCAL_condition('GRAM_EIG_CALL_IDENTITY_UNAVAILABLE', ...
        'The small-Gram eig ledger is not 274.');
    end
    available=category.pass&&eig_audit.pass;
    public=struct('components',components,'caps',caps,'estimator',estimator, ...
      'tails',struct('components',LOCAL_public_tails(final),'state',state), ...
      'axis_metrics',struct('axes',axes,'shells',shells), ...
      'arithmetic',arithmetic,'field_same_partial',field, ...
      'artifact_association',anchors,'artifact_audit',artifact_audit, ...
      'signature_parity',signature_parity, ...
      'combined_gram_parity',combined_gram, ...
      'qualification',qualification,'numerator_available',numerator_available, ...
      'denominator_available',denominator_available, ...
      'all_modes_included',circle.public_metrics.all_computed_circle_modes_retained, ...
      'first_empirical_unavailable',first, ...
      'unresolved_axes',{LOCAL_unresolved(axes,shells,arithmetic,state, ...
        qualification,signature_parity,combined_gram)}, ...
      'full_p_counter_audit',category,'allowlisted_eig_audit',eig_audit, ...
      'raw_value_enters_volume_only',true, ...
      'raw_wall_normal_enters_wall_only',true, ...
      'raw_circle_normal_enters_circle_only',true, ...
      'uncomputed_tails_outward_enclosed',false);
    signatures=struct('final_norms',LOCAL_public_components(final), ...
      'artifact_norms',LOCAL_public_components(artifact), ...
      'producer_parity',producer_parity,'endpoint_parity',endpoint_parity);
    clear final_factors final_sig artifact_pair artifact gram_parity;
    clear axes shells final state;
  catch ME
    available=false; first=LOCAL_condition(ME.identifier,ME.message);
    signatures=struct();
  end
  peak=max(peak,LOCAL_workspace_mib());
  clear staged lift wall circle timer z final_factors final_sig final state;
  clear artifact artifact_pair artifact_audit gram_parity anchors axes shells;
  clear arithmetic components field producer_parity endpoint_parity;
  clear signature_parity combined_gram qualification caps estimator;
  clear category eig_audit;
  audit=struct('returned_field_inventory',{{}}, ...
    'returned_numeric_shape_inventory',{{}},'prohibited_field_count',NaN, ...
    'prohibited_shape_count',NaN,'last_use_clear_ledger',LOCAL_liveness_ledger(), ...
    'post_clear_local_owner_inventory',{LOCAL_owner_inventory()}, ...
    'finest_factor_whitelist',{{}}, ...
    'compact_signature_whitelist',{{'cap_signatures.final_norms', ...
      'cap_signatures.artifact_norms','cap_signatures.producer_parity', ...
      'cap_signatures.endpoint_parity'}}, ...
    'small_gram_eig_expression','eig((W+W'')/2)', ...
    'small_gram_eig_is_candidate_solve',false, ...
    'dense_augmented_vectors_returned',false, ...
    'full_matrix_P_powers_retained',true);
  payload=struct('available',available,'first_unavailable',first, ...
    'public_metrics',public,'finest_factors',struct(), ...
    'cap_signatures',signatures,'audit_summary',audit,'warnings',warnings, ...
    'call_counters',calls,'resource_record',struct());
  payload.resource_record=LOCAL_resource_record(retained_before_mib, ...
    input_alias,peak,LOCAL_value_mib(payload),c);
  out=payload;
end

%% ==================== Final finest-factor objects ====================
% Final factors remain live only for parity, artifact association, and shells.

function [factors,sig,gram]=LOCAL_final_objects(c,z,lift,wall,circle)
  bw=lift.wall_trace; bc=lift.circle_weights{end};
  cv=lift.collar_weights{end}/z.gamma;
  wv=lift.wall_lift_weights{end}/z.gamma;
  LOCAL_weight_gate(bw,bc,cv,wv);
  factors.wall=struct('minus',LOCAL_weight_rows(wall.normal_minus,1./sqrt(bw)), ...
    'plus',LOCAL_weight_rows(wall.normal_plus,1./sqrt(bw)), ...
    'center',[wall.center_wall.left./sqrt(bw);wall.center_wall.right./sqrt(bw)], ...
    'endpoint_id','final-wall');
  factors.circle=struct( ...
    'minus',LOCAL_weight_rows(circle.jump_minus,1./sqrt(bc)), ...
    'plus',LOCAL_weight_rows(circle.jump_plus,1./sqrt(bc)), ...
    'center',zeros(0,1),'endpoint_id','final-circle');
  factors.volume_circle=struct( ...
    'minus',LOCAL_weight_rows(circle.delta_minus,sqrt(cv)), ...
    'plus',LOCAL_weight_rows(circle.delta_plus,sqrt(cv)), ...
    'center',zeros(0,1),'endpoint_id','final-volume-circle', ...
    'combined_endpoint_id','final-volume');
  factors.volume_wall=LOCAL_volume_wall_factors(z,wall,wv);
  factors.volume_wall.endpoint_id='final-volume-wall';
  factors.volume_wall.combined_endpoint_id='final-volume';
  sig.wall=LOCAL_factor_signature(c,'final-wall','wall',factors.wall,z,32);
  sig.circle=LOCAL_factor_signature(c,'final-circle','circle',factors.circle,z,32);
  sc=LOCAL_factor_signature(c,'final-volume-circle','volume-circle', ...
    factors.volume_circle,z,32);
  sw=LOCAL_factor_signature(c,'final-volume-wall','volume-wall', ...
    factors.volume_wall,z,32);
  [sig.volume,gram]=LOCAL_combine_volume(c,'final-volume',sc,sw, ...
    factors.volume_circle,factors.volume_wall,z,32,true,'actual-final');
end

function out=LOCAL_volume_wall_factors(z,wall,wv)
  DLp=LOCAL_weight_rows(wall.defect_left_plus,sqrt(wv));
  DRp=LOCAL_weight_rows(wall.defect_right_plus,sqrt(wv));
  DLm=LOCAL_weight_rows(wall.defect_left_minus,sqrt(wv));
  DRm=LOCAL_weight_rows(wall.defect_right_minus,sqrt(wv));
  left=LOCAL_pad_orders(z.center_left_value_mismatch,512,numel(wv));
  right=LOCAL_pad_orders(z.center_right_value_mismatch,512,numel(wv));
  out=struct('minus',[DLm;DRm*z.Pminus], ...
    'plus',[DRp;DLp*z.Pplus], ...
    'center',[sqrt(wv).*left;sqrt(wv).*right; ...
      DLp*z.cplus;DRm*z.cminus]);
end

function sig=LOCAL_factor_signature(c,label,component,f,z,N)
  if isfield(f,'endpoint_id')&&~strcmp(label,f.endpoint_id)
    error('i32f:EndpointIdentity', ...
      'The factor endpoint identity differs from its signature identity.');
  end
  if isscalar(N), Nm=N; Np=N; else, Nm=N(1); Np=N(2); end
  class_name=LOCAL_endpoint_parity_class(label,false);
  parity_required=~isempty(class_name);
  [sm,bm]=LOCAL_side_factor_signature( ...
    c,f.minus,z.Pminus,z.cminus,Nm,parity_required);
  [sp,bp]=LOCAL_side_factor_signature( ...
    c,f.plus,z.Pplus,z.cplus,Np,parity_required);
  center_squared=norm(f.center)^2;
  parity=struct([]);
  if parity_required
    tm=LOCAL_tail_slot(z.Pminus,sm.W,z.cminus,Nm,c);
    tp=LOCAL_tail_slot(z.Pplus,sp.W,z.cplus,Np,c);
    long=norm([f.center(:);bm;sqrt(tm.value);bp;sqrt(tp.value)]);
    reconstructed=sqrt(center_squared+sum(sm.direct_squared_terms(1:Nm))+ ...
      tm.value+sum(sp.direct_squared_terms(1:Np))+tp.value);
    nops=4*(numel(f.center)+numel(bm)+numel(bp)+2)+16;
    parity=LOCAL_parity_record(label,class_name,long,reconstructed,nops);
    clear tm tp long reconstructed;
  end
  sig=struct('endpoint_id',label,'component',component, ...
    'row_order','frozen canonical row blocks','Nminus',Nm,'Nplus',Np, ...
    'center_squared',center_squared,'minus',sm,'plus',sp, ...
    'finite',sm.finite&&sp.finite&&isfinite(center_squared), ...
    'signature_parity',parity, ...
    'augmented_length',numel(f.center)+32*size(f.minus,1)+1+ ...
      32*size(f.plus,1)+1);
  clear bm bp;
end

function [out,block]=LOCAL_side_factor_signature(c,H,P,c0,N,need_block)
  Nmax=max(c.full_p_levels); rows=size(H,1); terms=zeros(1,Nmax);
  if need_block, block=zeros(rows*Nmax,1,'like',H*c0); else, block=[]; end
  state=c0;
  for n=1:Nmax
    action=H*state; terms(n)=norm(action)^2;
    if need_block&&n<=N, block((n-1)*rows+(1:rows))=action; end
    state=P*state;
  end
  W=H'*H;
  out=struct('W',W,'direct_squared_terms',terms, ...
    'tail_input_audit',struct('rows',rows,'state_dimension',size(P,1)), ...
    'finite',all(isfinite([W(:);terms(:)])));
end

function [out,records]=LOCAL_combine_volume(c,label,a,b,fa,fb,z,N,actual,class_name)
  if isscalar(N), Nm=N; Np=N; else, Nm=N(1); Np=N(2); end
  records=struct([]);
  if isempty(fa)&&isempty(fb)
    label=[a.endpoint_id,'+',b.endpoint_id];
  end
  if ~isempty(fa)&&~isempty(fb)&& ...
      (~strcmp(fa.combined_endpoint_id,label)|| ...
      ~strcmp(fb.combined_endpoint_id,label))
    error('i32f:CombinedEndpointIdentity', ...
      'A combined-volume endpoint identity is inconsistent.');
  end
  minus=LOCAL_combine_side(a.minus,b.minus); plus=LOCAL_combine_side(a.plus,b.plus);
  center_squared=a.center_squared+b.center_squared;
  parity=LOCAL_combined_direct_parity( ...
    c,label,a,b,fa,fb,z,[Nm,Np],center_squared,actual);
  if nargin>=10&&~isempty(fa)&&~isempty(fb)&&~isempty(class_name)
    records=LOCAL_concat(records,LOCAL_gram_parity(label,'minus', ...
      fa.minus,fb.minus,minus.W,actual,class_name));
    records=LOCAL_concat(records,LOCAL_gram_parity(label,'plus', ...
      fa.plus,fb.plus,plus.W,actual,class_name));
  end
  out=struct('endpoint_id',label,'component','volume', ...
    'row_order','[volume-circle; volume-wall] before single tail', ...
    'Nminus',Nm,'Nplus',Np,'center_squared',center_squared, ...
    'minus',minus,'plus',plus,'finite',a.finite&&b.finite&& ...
      all(isfinite([minus.W(:);plus.W(:);center_squared])), ...
    'signature_parity',parity, ...
    'augmented_length',LOCAL_signature_length(a)+LOCAL_signature_length(b)-2);
end

function out=LOCAL_combine_side(a,b)
  out=struct('W',a.W+b.W, ...
    'direct_squared_terms',a.direct_squared_terms+b.direct_squared_terms, ...
    'tail_input_audit',struct('rows',a.tail_input_audit.rows+ ...
      b.tail_input_audit.rows,'state_dimension',a.tail_input_audit.state_dimension, ...
      'family_grams_added_before_tail',true), ...
    'finite',a.finite&&b.finite);
end

function out=LOCAL_combined_direct_parity(c,label,a,b,fa,fb,z,N,center,actual)
  if isscalar(N), Nm=N; Np=N; else, Nm=N(1); Np=N(2); end
  class_name=LOCAL_endpoint_parity_class(label,true);
  if isempty(class_name)||isempty(fa)||isempty(fb)
    out=struct([]); return;
  end
  Hm=[fa.minus;fb.minus]; Hp=[fa.plus;fb.plus];
  minus=LOCAL_direct_blocks(Hm,z.Pminus,z.cminus,Nm,c);
  plus=LOCAL_direct_blocks(Hp,z.Pplus,z.cplus,Np,c);
  long_tm=LOCAL_tail_slot(z.Pminus,Hm'*Hm,z.cminus,Nm,c);
  long_tp=LOCAL_tail_slot(z.Pplus,Hp'*Hp,z.cplus,Np,c);
  sig_tm=LOCAL_tail_slot(z.Pminus,a.minus.W+b.minus.W,z.cminus,Nm,c);
  sig_tp=LOCAL_tail_slot(z.Pplus,a.plus.W+b.plus.W,z.cplus,Np,c);
  center_block=[fa.center(:);fb.center(:)];
  long=norm([center_block;minus;sqrt(long_tm.value); ...
    plus;sqrt(long_tp.value)]);
  reconstructed=sqrt(center+ ...
    sum(a.minus.direct_squared_terms(1:Nm))+ ...
    sum(b.minus.direct_squared_terms(1:Nm))+sig_tm.value+ ...
    sum(a.plus.direct_squared_terms(1:Np))+ ...
    sum(b.plus.direct_squared_terms(1:Np))+sig_tp.value);
  nops=4*(numel(center_block)+numel(minus)+numel(plus)+2)+32;
  out=LOCAL_parity_record(label,class_name,long,reconstructed,nops);
  out.actual=actual; out.representative=~actual;
  clear center_block minus plus;
end

function block=LOCAL_direct_blocks(H,P,c0,N,c)
  rows=size(H,1); block=zeros(rows*max(c.full_p_levels),1,'like',H*c0);
  state=c0;
  for j=1:N
    block((j-1)*rows+(1:rows))=H*state; state=P*state;
  end
end

function out=LOCAL_gram_parity(label,side,A,B,Wsum,actual,class_name)
  stacked=[A;B]; Wstack=stacked'*stacked;
  nops=4*(numel(A)+numel(B))+2*numel(Wsum);
  stack_norm=norm(Wstack,2); sum_norm=norm(Wsum,2);
  scale=max([realmin,stack_norm,sum_norm]); allowance=100*nops*eps*scale;
  numerator=norm(Wstack-Wsum,2);
  out=struct('label',label,'side',side,'object_class',class_name, ...
    'actual',actual,'representative',~actual,'n_gram',nops, ...
    'stack_norm',stack_norm,'sum_norm',sum_norm,'numerator',numerator, ...
    'scale',scale,'allowance',allowance, ...
    'ratio',numerator/max(realmin,allowance), ...
    'pass',isfinite(numerator)&&numerator<=allowance);
end

function [out,calls]=LOCAL_project_components(c,z,sig,calls,category,diagnostic)
  names={'wall','circle','volume'};
  for j=1:3
    [out.(names{j}),calls]=LOCAL_project_endpoint( ...
      c,z,sig.(names{j}),calls,category,diagnostic);
  end
  out.tail_records=struct('wall',out.wall.tail, ...
    'circle',out.circle.tail,'volume',out.volume.tail);
end

function [out,calls]=LOCAL_project_endpoint(c,z,sig,calls,category,diagnostic)
  if diagnostic
    calls=LOCAL_increment(calls,'small_hermitian_gram_diagnostic_eig_calls',2);
    LOCAL_psd_root(sig.minus.W); LOCAL_psd_root(sig.plus.W);
  end
  tm=LOCAL_tail_slot(z.Pminus,sig.minus.W,z.cminus,sig.Nminus,c);
  tp=LOCAL_tail_slot(z.Pplus,sig.plus.W,z.cplus,sig.Nplus,c);
  calls=LOCAL_category_increment(calls,category,2);
  direct_squared=sig.center_squared+ ...
    sum(sig.minus.direct_squared_terms(1:sig.Nminus))+tm.value+ ...
    sum(sig.plus.direct_squared_terms(1:sig.Nplus))+tp.value;
  if direct_squared<0&&direct_squared>=-100*eps*max(realmin,abs(direct_squared))
    direct_squared=0;
  end
  B=sqrt(direct_squared);
  tail=struct('label',sig.endpoint_id,'Nminus',sig.Nminus, ...
    'Nplus',sig.Nplus,'minus',tm,'plus',tp, ...
    'Nmax',max(c.full_p_levels),'direct_rows_zero_padded',true, ...
    'center_squared',sig.center_squared, ...
    'direct_minus_squares',sig.minus.direct_squared_terms(1:sig.Nminus).', ...
    'direct_plus_squares',sig.plus.direct_squared_terms(1:sig.Nplus).', ...
    'first_four_direct_quadratic_actions',LOCAL_first_four(sig), ...
    'tail_slots_separate',true,'available',tm.available&&tp.available);
  out=struct('B',B,'tail',tail,'finite',isfinite(B)&&tail.available, ...
    'signature',sig,'augmented_length',LOCAL_signature_length(sig));
end

function LOCAL_psd_root(W)
  scale=norm(W,2); herm=norm(W-W','fro')/max(realmin,scale);
  [~,D]=eig((W+W')/2); eigen=real(diag(D));
  tol=100*eps*max(realmin,scale);
  if any(~isfinite(W),'all')||herm>1e-10||min(eigen)<-tol
    error('i32e:ComponentGram','A squared-norm Gram is invalid.');
  end
end

function out=LOCAL_tail_slot(P,W,c0,N,c)
  PN=eye(size(P)); WN=zeros(size(W)); state=c0; direct=0;
  for j=1:N
    direct=direct+real(state'*W*state); WN=WN+PN'*W*PN;
    state=P*state; PN=P*PN;
  end
  alternate=LOCAL_binary_power(P,N); defect=norm(PN-alternate,2);
  [Walternate,Pcheck]=LOCAL_gram_doubling(W,P,N);
  gram_defect=norm(WN-Walternate,2);
  defect=max(defect,norm(PN-Pcheck,2));
  pscale=max([1,norm(PN,2),norm(alternate,2)]);
  ahi=norm(PN,2)+defect+100*numel(c0)*eps*pscale;
  left_scale=norm(WN,2); association_scale=max(left_scale,norm(Walternate,2));
  omega=gram_defect;
  if association_scale>0
    omega=omega+100*numel(c0)*eps*association_scale;
  end
  if ahi<1&&isfinite(ahi)
    tail=ahi^2/(1-ahi^2)*(left_scale+omega)*norm(c0)^2;
  else
    tail=Inf;
  end
  tolerance=100*numel(c0)*eps*norm(W,2)*norm(c0)^2;
  if direct<0&&direct>=-tolerance, direct=0; end
  out=struct('value',tail,'finite_partial',direct,'a_hi',ahi, ...
    'power_association_defect',defect,'roundoff_allowance',omega, ...
    'gram_association_defect',gram_defect,'left_WN_norm',left_scale, ...
    'alternate_WN_norm',norm(Walternate,2), ...
    'tail_share',tail/max(realmin,direct),'available', ...
    isfinite(tail)&&tail>=0&&isfinite(direct)&&direct>=0, ...
    'certified',false);
end

function [WN,PN]=LOCAL_gram_doubling(W,P,N)
  if N<1||N~=2^round(log2(N))
    WN=zeros(size(W)); PN=eye(size(P)); state=eye(size(P));
    for j=1:N, WN=WN+state'*W*state; state=P*state; end
    PN=state; return;
  end
  WN=W; PN=P; count=1;
  while count<N
    WN=WN+PN'*WN*PN; PN=PN*PN; count=2*count;
  end
end

function value=LOCAL_binary_power(P,N)
  if N==0, value=eye(size(P)); return; end
  value=eye(size(P)); base=P; count=N;
  while count>0
    if mod(count,2)==1, value=value*base; end
    count=floor(count/2);
    if count>0, base=base*base; end
  end
end

function out=LOCAL_first_four(sig)
  out=NaN(4,3); out(:,1)=(0:3).';
  out(1:min(4,sig.Nminus),2)= ...
    sig.minus.direct_squared_terms(1:min(4,sig.Nminus)).';
  out(1:min(4,sig.Nplus),3)= ...
    sig.plus.direct_squared_terms(1:min(4,sig.Nplus)).';
end

function n=LOCAL_signature_length(sig)
  if isfield(sig,'augmented_length'), n=sig.augmented_length; return; end
  rowsm=sig.minus.tail_input_audit.rows;
  rowsp=sig.plus.tail_input_audit.rows;
  if strcmp(sig.component,'circle')||strcmp(sig.component,'volume-circle')
    center=0;
  elseif strcmp(sig.component,'wall')
    center=2*rowsm;
  else
    center=2*rowsm;
  end
  n=center+32*rowsm+1+32*rowsp+1;
end

