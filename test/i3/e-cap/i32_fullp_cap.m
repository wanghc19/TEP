  sig=final_sig; sig.circle=LOCAL_factor_signature(c,'riccati-leg-circle', ...
    'circle',rf,z,32);
  [legs{4},calls]=LOCAL_project_components(c,z,sig,calls,'interaction',true);
  ff=LOCAL_circle_final_factor(lift,circle);
  ff.endpoint_id='final-circle';
  pairs{4}=struct('circle',LOCAL_factor_pair(c,rf,ff,z,32,32));
