%% ==================== Fourier shells ====================
% Each masked finest factor is projected and cleared before the next family.

function [out,warnings,calls,gram]= ...
    LOCAL_shells(c,z,lift,wall,circle,calls)
  warnings=LOCAL_empty_warnings(); gram=struct([]);
  [out.circle_circle,calls,g]=LOCAL_shell_family( ...
    c,z,lift,wall,circle,'circle','circle',calls); gram=LOCAL_concat(gram,g);
  [out.circle_volume,calls,g]=LOCAL_shell_family( ...
    c,z,lift,wall,circle,'circle','volume',calls); gram=LOCAL_concat(gram,g);
  [out.wall_wall,calls,g]=LOCAL_shell_family( ...
    c,z,lift,wall,circle,'wall','wall',calls); gram=LOCAL_concat(gram,g);
  [out.wall_volume,calls,g]=LOCAL_shell_family( ...
    c,z,lift,wall,circle,'wall','volume',calls); gram=LOCAL_concat(gram,g);
  names=fieldnames(out);
  for j=1:numel(names)
    if ~out.(names{j}).available
      warnings(end+1)=LOCAL_warning('FOURIER_TAIL_EMPIRICALLY_UNRESOLVED', ...
        out.(names{j}).ratio); %#ok<AGROW>
    end
  end
end

function [out,calls,gram]=LOCAL_shell_family( ...
    c,z,lift,wall,circle,family,component,calls)
  if strcmp(family,'circle'), bands=[512,1024;1024,2048];
  else, bands=[1024,2048;2048,4096]; end
  values=cell(1,2); gram=struct([]);
  for j=1:2
    [f,label]=LOCAL_shell_factor(z,lift,wall,circle,family,component, ...
      bands(j,1),bands(j,2));
    sig=LOCAL_factor_signature(c,label,component,f,z,32);
    if strcmp(component,'volume')
      empty=struct('minus',zeros(0,size(f.minus,2)), ...
        'plus',zeros(0,size(f.plus,2)),'center',zeros(0,1));
      gram=LOCAL_concat(gram,LOCAL_gram_parity(label,'minus', ...
        f.minus,empty.minus,sig.minus.W,true,'actual-shell'));
      gram=LOCAL_concat(gram,LOCAL_gram_parity(label,'plus', ...
        f.plus,empty.plus,sig.plus.W,true,'actual-shell'));
    end
    [values{j},calls]=LOCAL_project_endpoint( ...
      c,z,sig,calls,'shell',true); clear f sig;
  end
  S1=values{1}.B; S2=values{2}.B; scale=max([realmin,S1,S2]);
  omega=100*(values{1}.augmented_length+values{2}.augmented_length)*eps*scale;
  near=S1<=omega&&S2<=omega; pass=near||S2<=max(.5*S1,omega);
  if pass, allowance=2*max(S2,omega); else, allowance=NaN; end
  out=struct('family',family,'component',component,'shell_1',S1, ...
    'shell_2',S2,'omega',omega,'near_zero',near,'contraction_pass',pass, ...
    'shell_1_metric',LOCAL_scalar_metric(S1,realmin,Inf,isfinite(S1)), ...
    'shell_2_metric',LOCAL_scalar_metric(S2,max(realmin,S1),.5,pass), ...
    'numerator',S2,'scale',max(realmin,S1), ...
    'ratio',S2/max(realmin,S1),'threshold',.5,'pass',pass, ...
    'allowance',allowance,'available',pass, ...
