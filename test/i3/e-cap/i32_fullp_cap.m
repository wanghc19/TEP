  [legs{5},calls]=LOCAL_project_components(c,z,sig,calls,'interaction',true);
  fcfinal=LOCAL_volume_circle_final_factor(z,lift,circle);
  fwfinal=LOCAL_volume_wall_factors(z,wall.finest_factors, ...
    lift.wall_lift_weights{end}/z.gamma);
  fcfinal.endpoint_id='final-volume-circle';
  fcfinal.combined_endpoint_id='final-volume';
  fwfinal.endpoint_id='final-volume-wall';
  fwfinal.combined_endpoint_id='final-volume';
  pairs{5}=struct('volume',LOCAL_combined_factor_pair( ...
    c,gc,gw,fcfinal,fwfinal,z,32,32));
  clear gc gw sc sw fcfinal fwfinal;

  sig=fullp_sig{2};
