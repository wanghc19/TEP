  [sig,~]=LOCAL_existing_choice(c,z,wall,circle,6,3,3,32);
  [legs{1},calls]=LOCAL_project_components(c,z,sig,calls,'interaction',true);
  pairs{1}=struct('circle',circle.cap_signatures.image_pairs{5}.circle, ...
    'volume',LOCAL_combine_pair( ...
    circle.cap_signatures.image_pairs{5}.volume_circle, ...
    LOCAL_zero_pair_like(wall.cap_signatures.output_pairs{2}.volume_wall, ...
      wall.cap_signatures.output{3}.volume_wall.endpoint_id)));

  [sig,~]=LOCAL_existing_choice(c,z,wall,circle,0,2,3,32);
