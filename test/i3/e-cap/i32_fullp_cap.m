      wall.public_metrics.repaired_value_qualified, ...
    'actual_T_qualified',cp.actual_T_action_qualified, ...
    'finite_bloch_qualified',cp.finite_image_Bloch_qualified, ...
    'signature_parity_qualified',signature.pass, ...
    'combined_gram_parity_qualified',gram.pass);
end

function out=LOCAL_first_unavailable(components,axes,shells,arithmetic,state, ...
    q,signature,gram)
  if ~q.kernel_oracle_available
    out=LOCAL_condition('KERNEL_ORACLE_UNAVAILABLE', ...
      'A required analytic kernel oracle is numerically unavailable.'); return;
  elseif ~q.kernel_qualified
    out=LOCAL_condition('KERNEL_ORACLE_EMPIRICALLY_UNRESOLVED', ...
      'A preregistered analytic kernel oracle failed qualification.'); return;
  elseif ~q.conformity_qualified
    out=LOCAL_condition('SAME_TRIAL_CONFORMITY_EMPIRICALLY_UNRESOLVED', ...
      'A repaired-trace identity failed qualification.'); return;
  elseif ~q.actual_T_qualified
    out=LOCAL_condition('ACTUAL_DELTA_T_ACTION_EMPIRICALLY_UNRESOLVED', ...
      'The fixed-density Delta-T action ladder failed qualification.'); return;
  elseif ~q.finite_bloch_qualified
    out=LOCAL_condition('FINITE_IMAGE_BLOCH_EMPIRICALLY_UNRESOLVED', ...
      'The finite-image Bloch action failed qualification.'); return;
  elseif ~signature.pass
    out=LOCAL_condition('SIGNATURE_PARITY_UNRESOLVED', ...
      'A required compact-signature arithmetic parity gate failed.'); return;
  elseif ~gram.pass
    out=LOCAL_condition('COMBINED_GRAM_PARITY_UNRESOLVED', ...
      'A required stacked-versus-summed volume Gram parity gate failed.'); return;
  end
  names={'wall','circle','volume'};
  for j=1:3
    if ~components.(names{j}).available
      out=LOCAL_condition('EMPIRICAL_COMPONENT_CAP_UNRESOLVED', ...
        ['The ',names{j},' component cap is unresolved.']); return;
    end
  end
  if ~axes.interaction.pass
    out=LOCAL_condition('AXIS_INTERACTION_EMPIRICALLY_UNRESOLVED', ...
      'The joint holdout exceeds the final-leg ledger.'); return;
  end
  if ~state.available
    out=LOCAL_condition('MANDATORY_STATE_TAIL_UNAVAILABLE', ...
      'The mandatory W=I full-P state tail is unavailable.'); return;
  end
  if any(~structfun(@(x) x.available,shells))
    out=LOCAL_condition('FOURIER_TAIL_EMPIRICALLY_UNRESOLVED', ...
      'A preregistered Fourier shell is unresolved.'); return;
  end
  if any(~structfun(@(x) x.available,arithmetic))
    out=LOCAL_condition('COMPONENT_ARITHMETIC_EMPIRICALLY_UNRESOLVED', ...
      'A component arithmetic path is unresolved.'); return;
  end
  out=LOCAL_condition('EMPIRICAL_CAP_UNRESOLVED', ...
    'A required numerator ledger is unresolved.');
end

function out=LOCAL_unresolved(axes,shells,arithmetic,state,q,signature,gram)
  out={}; names=fieldnames(axes);
  for j=1:numel(names)
    item=axes.(names{j});
    if isfield(item,'available'), pass=item.available; else, pass=item.pass; end
    if ~pass, out{end+1}=names{j}; end %#ok<AGROW>
  end
  names=fieldnames(shells);
  for j=1:numel(names)
    if ~shells.(names{j}).available
      out{end+1}=['shell_',names{j}]; %#ok<AGROW>
    end
  end
  names=fieldnames(arithmetic);
  for j=1:numel(names)
    if ~arithmetic.(names{j}).available
      out{end+1}=['arithmetic_',names{j}]; %#ok<AGROW>
    end
  end
  if ~state.available, out{end+1}='mandatory_state_tail'; end
  if ~q.actual_T_qualified, out{end+1}='actual_DeltaT_action'; end
  if ~q.finite_bloch_qualified, out{end+1}='finite_image_Bloch'; end
  if ~signature.pass, out{end+1}='signature_parity'; end
  if ~gram.pass, out{end+1}='combined_gram_parity'; end
end

function warnings=LOCAL_tail_warnings(c,final,state)
  warnings=LOCAL_empty_warnings(); names={'wall','circle','volume'};
  for j=1:3
    t=final.(names{j}).tail; share=max(t.minus.tail_share,t.plus.tail_share);
    if isfinite(share)&&share>c.tail_share_warning
      warnings(end+1)=LOCAL_warning('FULL_P_TAIL_SHARE_WARNING',share); %#ok<AGROW>
    end
  end
  if state.available
    share=state.levels(state.selected_index).maximum_share;
    if isfinite(share)&&share>c.tail_share_warning
      warnings(end+1)=LOCAL_warning('FULL_P_STATE_TAIL_SHARE_WARNING',share); %#ok<AGROW>
    end
  end
end

