    f.volume_wall,z,selected);
  [sig.volume,gram]=LOCAL_combine_volume(c,'artifact-volume',sc,sw, ...
    f.volume_circle,f.volume_wall,z,selected,true,'actual-artifact');
  [out,calls]=LOCAL_project_components(c,z,sig,calls,'artifact',true);
  pair.wall=LOCAL_factor_pair(c,f.wall,final_factors.wall,z,selected,32);
  pair.circle=LOCAL_factor_pair(c,f.circle,final_factors.circle,z,selected,32);
  pair.volume=LOCAL_combined_factor_pair(c, ...
    f.volume_circle,f.volume_wall,final_factors.volume_circle, ...
    final_factors.volume_wall,z,selected,32);
  audit=struct('wall_common',wall_audit, ...
    'circle_delta_plus_norm',norm(a.delta_plus,'fro'), ...
    'circle_delta_minus_norm',norm(a.delta_minus,'fro'), ...
