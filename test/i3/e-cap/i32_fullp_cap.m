function [out,calls]=LOCAL_state_tail(c,z,calls)
  template=struct('N',0,'minus',struct(),'plus',struct(), ...
    'available',false,'maximum_share',Inf);
  levels=repmat(template,1,numel(c.full_p_levels)); selected=NaN;
  for j=1:numel(c.full_p_levels)
    N=c.full_p_levels(j);
    tm=LOCAL_tail_slot(z.Pminus,eye(size(z.Pminus)),z.cminus,N,c);
    tp=LOCAL_tail_slot(z.Pplus,eye(size(z.Pplus)),z.cplus,N,c);
    calls=LOCAL_category_increment(calls,'state',2);
    share=max(tm.tail_share,tp.tail_share);
    levels(j)=struct('N',N,'minus',tm,'plus',tp, ...
      'available',tm.available&&tp.available,'maximum_share',share);
    if isnan(selected)&&levels(j).available, selected=j; end
  end
  if isnan(selected), selected_N=NaN; else, selected_N=levels(selected).N; end
  out=struct('available',~isnan(selected),'selected_index',selected, ...
    'selected_N',selected_N,'levels',levels, ...
    'ordinary_candidate',true,'certified',false);
end

function [out,pair,audit,calls,gram]= ...
    LOCAL_artifact(c,staged,lift,final_factors,final,calls)
  z=staged.certificate; a=staged.raw_maps; Nw=4096; Nc=2048;
  bw=lift.wall_trace; bc=lift.circle_weights{end};
  cv=lift.collar_weights{end}/z.gamma;
  wv=lift.wall_lift_weights{end}/z.gamma;
  Jp=LOCAL_pad_orders(a.Jplus,512,Nw); Jm=LOCAL_pad_orders(a.Jminus,512,Nw);
  f.wall=struct('minus',LOCAL_weight_rows(Jm,1./sqrt(bw)), ...
    'plus',LOCAL_weight_rows(Jp,1./sqrt(bw)), ...
