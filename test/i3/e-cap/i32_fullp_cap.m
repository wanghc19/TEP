  f.volume_wall.endpoint_id='artifact-volume-wall';
  f.volume_wall.combined_endpoint_id='artifact-volume';
  Nm=round(staged.ordinary_anchor.tail_minus.selected_N);
  Np=round(staged.ordinary_anchor.tail_plus.selected_N); selected=[Nm,Np];
  index=staged.ordinary_anchor.first_level_indices;
  first_level_pass=index.minus_selected_N==Nm&& ...
    index.plus_selected_N==Np&& ...
    isequal(index.minus_physical_start(:).',[0,0,0,1,0])&& ...
    isequal(index.plus_physical_start(:).',[0,0,0,1,0]);
  if ~first_level_pass
