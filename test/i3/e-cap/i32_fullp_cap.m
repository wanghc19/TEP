function out=LOCAL_image_axis(c,values,pairs,component,label)
  map=[3,5;5,7;2,4;4,6;6,7]; labels={ ...
    '64_to_128','128_to_256','48_to_96','96_to_192','192_to_256'};
  metrics=cell(1,5); scale=realmin;
  for j=1:7, scale=max(scale,values{j}.(component).B); end
  for j=1:5
    metrics{j}=LOCAL_project_pair(values{map(j,1)}.(component), ...
      values{map(j,2)}.(component),pairs{j});
    metrics{j}.label=labels{j};
  end
  metrics=[metrics{:}]; omega=100*values{end}.(component).augmented_length*eps*scale;
  for j=[1,3,5], metrics(j).threshold=Inf; metrics(j).absolute_threshold=Inf; end
  metrics(2).threshold=c.image_ratio_max;
  metrics(2).absolute_threshold=max(c.image_ratio_max*metrics(1).numerator,omega);
  metrics(4).threshold=c.image_ratio_max;
  metrics(4).absolute_threshold=max(c.image_ratio_max*metrics(3).numerator,omega);
  for j=1:5
    metrics(j).pass=isfinite(metrics(j).numerator)&& ...
      metrics(j).numerator<=metrics(j).absolute_threshold;
  end
  dyadic_near=metrics(1).value<=omega&&metrics(2).value<=omega;
  staggered_near=metrics(3).value<=omega&&metrics(4).value<=omega;
  dyadic=dyadic_near||metrics(2).value<= ...
    max(c.image_ratio_max*metrics(1).value,omega);
  staggered=staggered_near||metrics(4).value<= ...
    max(c.image_ratio_max*metrics(3).value,omega);
  available=dyadic&&staggered&&all(isfinite([[metrics.value],omega]));
  if available
    remainder=c.image_remainder_factor*max([metrics(2).value, ...
      metrics(4).value,metrics(5).value,omega]);
  else, remainder=NaN; end
  ratio=max(metrics(2).value/max(realmin,metrics(1).value), ...
    metrics(4).value/max(realmin,metrics(3).value));
  out=struct('axis','image','component',label,'differences',metrics, ...
    'omega',omega,'dyadic_pass',dyadic,'staggered_pass',staggered, ...
    'cross_finite',isfinite(metrics(5).value), ...
    'numerator',max(metrics(2).value,metrics(4).value), ...
    'scale',max([realmin,metrics(1).value,metrics(3).value]), ...
    'ratio',ratio,'threshold',c.image_ratio_max,'pass',available, ...
    'maximum_ratio',ratio,'remainder',remainder,'available',available, ...
    'all_projected_endpoint_parity',LOCAL_component_value_parity(values));
end

