function [f,label]=LOCAL_shell_factor(z,lift,wall,circle,family,component,inner,outer)
  if strcmp(family,'circle')
    orders=(-1024:1023).'; mask=LOCAL_shell_mask(orders,inner,outer);
    if strcmp(component,'circle')
      weight=lift.circle_weights{end}(mask);
      f=struct('minus',LOCAL_weight_rows(circle.jump_minus(mask,:),1./sqrt(weight)), ...
        'plus',LOCAL_weight_rows(circle.jump_plus(mask,:),1./sqrt(weight)), ...
        'center',zeros(0,1));
    else
      weight=lift.collar_weights{end}(mask)/z.gamma;
      f=struct('minus',LOCAL_weight_rows(circle.delta_minus(mask,:),sqrt(weight)), ...
        'plus',LOCAL_weight_rows(circle.delta_plus(mask,:),sqrt(weight)), ...
        'center',zeros(0,1));
    end
  else
    orders=(-2048:2047).'; mask=LOCAL_shell_mask(orders,inner,outer);
    if strcmp(component,'wall')
      weight=lift.wall_trace(mask);
      f=struct('minus',LOCAL_weight_rows(wall.normal_minus(mask,:),1./sqrt(weight)), ...
        'plus',LOCAL_weight_rows(wall.normal_plus(mask,:),1./sqrt(weight)), ...
        'center',[wall.center_wall.left(mask)./sqrt(weight); ...
          wall.center_wall.right(mask)./sqrt(weight)]);
    else
      weight=lift.wall_lift_weights{end}(mask)/z.gamma;
      DLp=LOCAL_weight_rows(wall.defect_left_plus(mask,:),sqrt(weight));
      DRp=LOCAL_weight_rows(wall.defect_right_plus(mask,:),sqrt(weight));
      DLm=LOCAL_weight_rows(wall.defect_left_minus(mask,:),sqrt(weight));
      DRm=LOCAL_weight_rows(wall.defect_right_minus(mask,:),sqrt(weight));
      f=struct('minus',[DLm;DRm*z.Pminus], ...
        'plus',[DRp;DLp*z.Pplus], ...
        'center',[DLp*z.cplus;DRm*z.cminus]);
    end
  end
  label=sprintf('shell-%s-%s-%d-%d',family,component,inner,outer);
end

function mask=LOCAL_shell_mask(orders,innerN,outerN)
  outer=orders>=-outerN/2&orders<=outerN/2-1;
  inner=orders>=-innerN/2&orders<=innerN/2-1;
  mask=outer&~inner;
  if ~any(mask), error('i32f:FourierShell','A required Fourier shell is empty.'); end
end

