function [s,ledger,audit]=LOCAL_prune_staged(s)
  certificate_keep={'source_attempt','khat','mu_h','gamma','beta','d','R', ...
    'rho_disk','X_L','X_R','L','M','K','delta_c','delta_w','q_center', ...
    'Pplus','Pminus','cplus','cminus','Gplus','Gminus','branch_port', ...
    'eta_unit_256','xi_left_unit_512','xi_right_unit_512', ...
    'wall_input_unit_512','center_actual_left_trace', ...
    'center_actual_right_trace','center_shared_left_trace', ...
    'center_shared_right_trace','center_left_value_mismatch', ...
    'center_right_value_mismatch','center_wall_jumps'};
  raw_keep={'delta_plus','delta_minus','circle_jump_plus','circle_jump_minus', ...
    'Jplus','Jminus','wall_common_y_1024','wall_common_value_1024', ...
    'wall_input_unit_512'};
  ledger=LOCAL_empty_clear_ledger(); removed_certificate={};
  certificate_names=fieldnames(s.certificate);
  for j=1:numel(certificate_names)
    name=certificate_names{j};
    if ~ismember(name,certificate_keep)
      value=s.certificate.(name);
      removed_certificate{end+1}=LOCAL_removed_summary(name,value); %#ok<AGROW>
      s.certificate=rmfield(s.certificate,name);
      ledger(end+1)=LOCAL_clear_item(['certificate.',name], ...
        {'certificate identity'},'certificate identity','cleared'); %#ok<AGROW>
    end
  end
  gamma_m=s.certificate.branch_port.gamma_m;
  branch_removed=setdiff(fieldnames(s.certificate.branch_port),{'gamma_m'});
  s.certificate.branch_port=struct('gamma_m',gamma_m);
  for j=1:numel(branch_removed)
    ledger(end+1)=LOCAL_clear_item( ...
      ['certificate.branch_port.',branch_removed{j}], ...
      {'certificate identity'},'certificate identity','cleared'); %#ok<AGROW>
  end
  center=s.certificate.center_wall_jumps;
  center_keep={'left_coefficients','right_coefficients', ...
    'field_lower_uses_shared_trace'};
  center_removed=setdiff(fieldnames(center),center_keep);
  reduced_center=struct('left_coefficients',center.left_coefficients, ...
    'right_coefficients',center.right_coefficients);
  if isfield(center,'field_lower_uses_shared_trace')
    reduced_center.field_lower_uses_shared_trace= ...
      center.field_lower_uses_shared_trace;
  end
  s.certificate.center_wall_jumps=reduced_center;
  for j=1:numel(center_removed)
    ledger(end+1)=LOCAL_clear_item( ...
      ['certificate.center_wall_jumps.',center_removed{j}], ...
      {'certificate identity'},'certificate identity','cleared'); %#ok<AGROW>
  end

  raw_names=fieldnames(s.raw_maps);
  removed_raw={};
  for j=1:numel(raw_names)
    name=raw_names{j};
    if ~ismember(name,raw_keep)
      s.raw_maps=rmfield(s.raw_maps,name); removed_raw{end+1}=name; %#ok<AGROW>
      ledger(end+1)=LOCAL_clear_item(['raw_maps.',name], ...
        {'certificate identity'},'certificate identity','cleared'); %#ok<AGROW>
    end
  end
  anchor_keep={'B_wall','B_circle','B_volume','M_tilde','N_tilde', ...
    'lead_field_factor_plus','lead_field_factor_minus','tail_minus','tail_plus', ...
    'first_level_indices'};
  anchor_names=fieldnames(s.ordinary_anchor); removed_anchor={};
  for j=1:numel(anchor_names)
    name=anchor_names{j};
    if ~ismember(name,anchor_keep)
      value=s.ordinary_anchor.(name);
      removed_anchor{end+1}=struct('name',name,'class',class(value), ...
        'size',size(value),'norm',LOCAL_safe_norm(value)); %#ok<AGROW>
      s.ordinary_anchor=rmfield(s.ordinary_anchor,name);
      ledger(end+1)=LOCAL_clear_item(['ordinary_anchor.',name], ...
        {'certificate identity'},'certificate identity','cleared'); %#ok<AGROW>
    end
  end
  audit=struct('retained_certificate_fields',{certificate_keep}, ...
    'removed_certificate_summary',{removed_certificate}, ...
    'removed_branch_identity_fields',{branch_removed}, ...
    'removed_center_duplicate_fields',{center_removed}, ...
    'retained_raw_map_whitelist',{raw_keep}, ...
    'retained_raw_map_count',numel(raw_keep),'removed_raw_maps',{removed_raw}, ...
    'retained_anchor_fields',{anchor_keep}, ...
    'removed_anchor_dense_summary',{removed_anchor}, ...
    'canonical_certificate_prefix', ...
      'finest_factors.staged.certificate', ...
    'canonical_raw_map_prefix','finest_factors.staged.raw_maps', ...
    'certificate_blanket_exception',false, ...
    'raw_map_blanket_exception',false, ...
    'no_unregistered_dense_owner_retained',true);
end

