function out = i32_certificate_input(input_path,c,retained_before_mib)
%I32_CERTIFICATE_INPUT Load and prune the frozen I3.2 certificate.
% Purpose:
%   Validate the explicit staged fbie-a1 certificate, normalize its integer
%   storage exactly, and retain only arrays with a registered REV_F consumer.
% Input:
%   input_path          - Explicit staged certificate MAT file.
%   c                   - Frozen REV_F numerical and resource contract.
%   retained_before_mib - Caller active-object proxy before this call.
% Output:
%   out                 - Typed total module result.  Its private staged
%                         payload is consumed by later science modules only.
% Main algorithm:
%   Load one named variable, normalize preregistered integer fields, verify
%   scalar/branch/center/raw-map/anchor identity, and prune dead dense maps.
% Based on:
%   check_e_cap.m Revision E certificate and identity helpers.
% Main changes:
%   Uses mechanical side dimensions and records an explicit last-use ledger.
% Numerical goal:
%   Preserve the frozen certificate without any solve or reconstruction.

  peak=LOCAL_workspace_mib(); warnings=LOCAL_empty_warnings();
  calls=LOCAL_zero_counters(); identity=struct(); conversion=struct();
  staged=struct(); first=LOCAL_condition('NONE','Certificate input is available.');
  available=false;
  try
    staged_original=LOCAL_load_input(input_path);
    original_mib=LOCAL_value_mib(staged_original);
    peak=max(peak,LOCAL_workspace_mib());
    [staged,conversion]=LOCAL_normalize_integer_storage(staged_original);
    normalized_mib=LOCAL_value_mib(staged);
    normalization_peak=original_mib+normalized_mib+LOCAL_value_mib(conversion);
    peak=max([peak,LOCAL_workspace_mib(),normalization_peak]);
    clear staged_original;

    LOCAL_input_gate(staged,c);
    identity=LOCAL_identity(staged,c);
    if isfield(identity,'branch_and_Wood')&&identity.branch_and_Wood.exact_Wood
      error('i32f:ExactWood','The frozen branch contains an exact Wood point.');
    end
    if isfield(identity,'branch_and_Wood')&&~identity.branch_and_Wood.pass
      error('i32f:BranchUnavailable', ...
        'The frozen branch/Wood identity is unavailable.');
    end
    if ~identity.pass
      error('i32f:CertificateIdentity','The staged certificate identity failed.');
    end

    [staged,clear_ledger,pruning_audit]=LOCAL_prune_staged(staged);
    peak=max(peak,LOCAL_workspace_mib());
    available=true;
  catch ME
    clear_ledger=LOCAL_empty_clear_ledger();
    pruning_audit=struct();
    first=LOCAL_condition(ME.identifier,ME.message);
    staged=struct();
  end

  public=struct('identity',identity,'input_storage_conversion',conversion, ...
    'input_contract',LOCAL_compact_field(staged,'input_contract'), ...
    'historical_diagnostics',LOCAL_compact_field(staged,'historical_diagnostics'), ...
    'ordinary_anchor',LOCAL_anchor_summary(staged), ...
    'M_role','artificial-wall trace order only', ...
    'wall_trace_order_M',48,'wall_trace_coefficient_count',97, ...
    'certificate_trial_redefined',false);
  if available
    staged=rmfield(staged,{'input_contract','historical_diagnostics'});
    clear_ledger(end+1)=LOCAL_clear_item('input_contract', ...
      {'certificate gate','result provenance'},'result provenance','cleared');
    clear_ledger(end+1)=LOCAL_clear_item('historical_diagnostics', ...
      {'result background disclosure'},'result background disclosure','cleared');
    pruning_audit.compact_provenance_removed_from_private_staged=true;
  end
  private=struct('staged',staged);
  audit=struct('storage_normalized',available, ...
    'mechanical_dimensions',LOCAL_dimension_summary(staged), ...
    'pruning',pruning_audit,'last_use_clear_ledger',clear_ledger, ...
    'post_clear_local_owner_inventory',{LOCAL_owner_inventory()}, ...
    'returned_field_inventory',{{}},'returned_numeric_shape_inventory',{{}}, ...
    'prohibited_field_count',NaN,'prohibited_shape_count',NaN, ...
    'finest_factor_whitelist',{LOCAL_return_whitelist()}, ...
    'exact_shape_contract',{LOCAL_exact_shape_contract(staged)}, ...
    'registered_consumer_death',{LOCAL_consumer_death_ledger()}, ...
    'certificate_blanket_exception',false, ...
    'raw_map_blanket_exception',false, ...
    'denominator_factor_whitelist',{{ ...
      'finest_factors.staged.ordinary_anchor.lead_field_factor_minus', ...
      'finest_factors.staged.ordinary_anchor.lead_field_factor_plus'}}, ...
    'compact_signature_whitelist',{{}},'signature_parity_coverage',struct());
  payload=struct('available',available,'first_unavailable',first, ...
    'public_metrics',public,'finest_factors',private,'cap_signatures',struct(), ...
    'audit_summary',audit,'warnings',warnings,'call_counters',calls, ...
    'resource_record',struct());
  payload.resource_record=LOCAL_resource_record( ...
    retained_before_mib,0,peak,LOCAL_value_mib(payload),c);
  out=payload;
end

%% ==================== Load and storage normalization ====================
% These helpers touch only the explicit staged MAT input.

function staged=LOCAL_load_input(path)
  if ~(ischar(path)||isstring(path))||~isfile(char(path))
    error('i32f:InputMissing','The explicit staged input is unavailable.');
  end
  loaded=load(char(path),'staged');
  if ~isfield(loaded,'staged')||~isstruct(loaded.staged)
    error('i32f:InputSchema','The input does not contain staged.');
  end
  staged=loaded.staged;
end

function [staged,ledger]=LOCAL_normalize_integer_storage(staged)
  specs=LOCAL_integer_storage_contract();
  template=struct('path','','original_class','','original_size',[], ...
    'semantic_range',[],'original_scalar_value',NaN,'original_min',NaN, ...
    'original_max',NaN,'maximum_absolute_value',NaN, ...
    'within_flintmax',false,'exact_roundtrip',false, ...
    'converted_class','','downstream_arithmetic','','pass',false);
  ledger=repmat(template,numel(specs),1);
  for j=1:numel(specs)
    spec=specs(j); value=LOCAL_nested_value(staged,spec.path);
    if ~isinteger(value)||~strcmp(class(value),spec.original_class)|| ...
        ~isequal(size(value),spec.expected_size)
      error('i32f:InputStorageClass', ...
        'Integer storage class/size mismatch at %s.',spec.path);
    end
    converted=double(value); maximum=max(abs(converted),[],'all');
    within_flintmax=maximum<=flintmax;
    roundtrip=within_flintmax&&isequal(feval(spec.original_class,converted),value);
    range_pass=all(converted>=spec.minimum&converted<=spec.maximum,'all');
    if ~roundtrip||~range_pass
      error('i32f:InputStorageValue', ...
        'Integer storage value/range mismatch at %s.',spec.path);
    end
    scalar_value=NaN;
    if isscalar(converted), scalar_value=converted; end
    ledger(j)=struct('path',spec.path,'original_class',spec.original_class, ...
      'original_size',size(value),'semantic_range',[spec.minimum,spec.maximum], ...
      'original_scalar_value',scalar_value,'original_min',min(converted,[],'all'), ...
      'original_max',max(converted,[],'all'), ...
      'maximum_absolute_value',maximum,'within_flintmax',within_flintmax, ...
      'exact_roundtrip',roundtrip,'converted_class','double', ...
      'downstream_arithmetic',spec.downstream_arithmetic,'pass',true);
    staged=LOCAL_nested_assign(staged,spec.path,converted);
  end
end

