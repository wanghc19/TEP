%% ==================== Resource, counter, and status gates ====================
% Failure publication preserves all already merged diagnostics and counters.

function [result,dispatch]=LOCAL_resource_gate(result,dispatch,timer,cumulative,c)
  if ~dispatch, return; end
  if toc(timer)>c.hard_seconds||cumulative>c.memory_mib_max
    [result,dispatch]=LOCAL_execution_stop(result,'RESOURCE_LIMIT_EXCEEDED', ...
      'The hard time or 640 MiB active-object proxy was exceeded.');
  elseif toc(timer)>c.soft_seconds
    [result,dispatch]=LOCAL_execution_stop(result,'SOFT_STAGE_START_UNAVAILABLE', ...
      'The 1500-second soft stage-start gate refused another module.');
  end
end

function [result,dispatch]=LOCAL_stop_from_module(result,module,name)
  code=module.first_unavailable.code;
  if strcmp(code,'NONE'), code=[upper(name),'_UNAVAILABLE']; end
  [result,dispatch]=LOCAL_execution_stop(result,code, ...
    module.first_unavailable.message);
end

function [result,cumulative]= ...
    LOCAL_salvage_failed_module(result,module,name,before,cumulative,c)
  snapshot=struct('module',name,'typed_payload_returned',false, ...
    'available',false,'first_unavailable',LOCAL_condition( ...
      'UNRETURNED_MODULE','The module did not return a typed payload.'), ...
    'call_counters_preserved',false,'warnings_preserved',false, ...
    'resource_record_preserved',false,'local_peak_mib',NaN);
  if ~isstruct(module)||~isscalar(module)
    record=LOCAL_unreturned_resource(before,c);
    result.resources.modules.(name)=record;
    cumulative=LOCAL_cumulative_candidate(cumulative, ...
      record.concurrent_peak_candidate_mib);
    result.audit.failed_module=snapshot; return;
  end
  required={'available','first_unavailable','warnings','call_counters', ...
    'resource_record'};
  if ~all(isfield(module,required))
    record=LOCAL_unreturned_resource(before,c);
    result.resources.modules.(name)=record;
    cumulative=LOCAL_cumulative_candidate(cumulative, ...
      record.concurrent_peak_candidate_mib);
    result.audit.failed_module=snapshot; return;
  end
  snapshot.typed_payload_returned=true;
  snapshot.available=logical(module.available);
  snapshot.first_unavailable=module.first_unavailable;
  if isstruct(module.call_counters)
    result.call_counters=LOCAL_add_counters(result.call_counters,module.call_counters);
    result.no_resolve_call_counts=result.call_counters;
    snapshot.call_counters_preserved=true;
  end
  if isstruct(module.warnings)
    result.nonblocking_warnings=[result.nonblocking_warnings,module.warnings];
    snapshot.warnings_preserved=true;
  end
  if isstruct(module.resource_record)
    snapshot.resource_record_preserved=true;
    result.resources.modules.(name)=module.resource_record;
    if isfield(module.resource_record,'local_workspace_peak_mib')
      snapshot.local_peak_mib=module.resource_record.local_workspace_peak_mib;
    end
    if isfield(module.resource_record,'concurrent_peak_candidate_mib')&& ...
        isfinite(module.resource_record.concurrent_peak_candidate_mib)
      cumulative=LOCAL_cumulative_candidate(cumulative, ...
        module.resource_record.concurrent_peak_candidate_mib);
    end
  end
  result.audit.failed_module=snapshot;
end

function value=LOCAL_cumulative_candidate(previous,candidate)
  values=[previous,candidate]; values=values(isfinite(values));
  if isempty(values), value=NaN; else, value=max(values); end
end

function pass=LOCAL_result_private_payload_absent(result)
  pass=isstruct(result.modules)&&isscalar(result.modules);
  names=fieldnames(result.modules);
  expected={'available','first_unavailable','public_metrics', ...
    'audit_summary','resource_record'};
  for j=1:numel(names)
    value=result.modules.(names{j});
    pass=pass&&isstruct(value)&&isscalar(value)&& ...
      isequal(sort(fieldnames(value)),sort(expected(:)))&& ...
      ~isfield(value,'finest_factors')&&~isfield(value,'cap_signatures');
  end
end

function value=LOCAL_unreturned_peak(module,module_merged)
  value=NaN;
  if module_merged||~isstruct(module)||~isscalar(module)|| ...
      ~isfield(module,'resource_record')||~isstruct(module.resource_record)
    return;
  end
  if isfield(module.resource_record,'local_workspace_peak_mib')
    value=module.resource_record.local_workspace_peak_mib;
  end
end

function [result,dispatch]=LOCAL_execution_stop(result,code,message)
  dispatch=false; result.execution_pass=false;
  if strcmp(result.first_execution_blocker.code,'NONE')
    result.first_execution_blocker=LOCAL_condition(code,message);
  end
  if contains(code,'RESOURCE')||contains(code,'HardTime')|| ...
      contains(code,'SOFT_STAGE')
    result.status='I3_2_RESOURCE_BUDGET_UNAVAILABLE';
    result.scientific_outcome='RESOURCE_BUDGET_UNAVAILABLE';
  else
    result.status='I3_2_EXECUTION_UNAVAILABLE';
    result.scientific_outcome='EXECUTION_UNAVAILABLE';
  end
end

function result=LOCAL_finalize_status(result,c)
  if ~result.execution_pass, return; end
  if ~isfield(result.modules,'fullp_cap')
    result.status='I3_2_EXECUTION_UNAVAILABLE';
    result.scientific_outcome='EXECUTION_UNAVAILABLE';
    return;
  end
  cap=result.modules.fullp_cap.public_metrics;
  if ~cap.numerator_available
    result.status='I3_2_EMPIRICAL_CAP_UNRESOLVED';
    result.scientific_outcome='EMPIRICAL_CAP_UNRESOLVED';
    result.cap_status='EMPIRICAL_CAP_UNRESOLVED';
  elseif ~cap.denominator_available
    result.status='I3_2_FIELD_PARTIAL_EMPIRICALLY_UNRESOLVED';
    result.scientific_outcome='FIELD_PARTIAL_EMPIRICALLY_UNRESOLVED';
    result.cap_status='EMPIRICAL_CAP_UNRESOLVED';
  elseif ~cap.estimator.interval_available
    result.status='I3_2_EMPIRICAL_NOMINAL_INTERVAL_UNAVAILABLE';
    result.scientific_outcome='EMPIRICAL_NOMINAL_INTERVAL_UNAVAILABLE';
    result.cap_status='EMPIRICALLY_SUPPORTED_EVALUATION_CAP';
  elseif cap.estimator.width>c.width_target
    result.status='I3_2_EMPIRICAL_RESOLUTION_INSUFFICIENT';
    result.scientific_outcome='EMPIRICAL_RESOLUTION_INSUFFICIENT';
    result.cap_status='EMPIRICALLY_SUPPORTED_EVALUATION_CAP';
  else
    result.status='I3_2_EMPIRICAL_NOMINAL_TRANSFORM';
    result.scientific_outcome='EMPIRICAL_NOMINAL_TRANSFORM';
    result.cap_status='EMPIRICALLY_SUPPORTED_EVALUATION_CAP';
  end
end

function out=LOCAL_add_counters(a,b)
  out=a; names=fieldnames(b);
  for j=1:numel(names)
    name=names{j};
    if isstruct(b.(name))
      if ~isfield(out,name)||~isstruct(out.(name)), out.(name)=struct(); end
      out.(name)=LOCAL_add_counters(out.(name),b.(name));
    elseif isnumeric(b.(name))&&isscalar(b.(name))
      if ~isfield(out,name), out.(name)=0; end
      out.(name)=out.(name)+b.(name);
    end
  end
end

function out=LOCAL_no_resolve_audit(calls)
  names={'candidate_solve_calls','qz_solve_calls','coordinate_solve_calls', ...
    'propagation_solve_calls','wall_density_solve_calls', ...
    'circle_density_solve_calls','schur_solve_calls','proxy_build_calls'};
  values=zeros(1,numel(names));
  for j=1:numel(names), values(j)=calls.(names{j}); end
  out=struct('names',{names},'values',values,'expected',zeros(size(values)), ...
    'pass',all(values==0),'exact_counter_count',numel(names));
end

