%% ==================== Typed module merge and liveness ====================
% Compact diagnostics merge before private owners are cleared and gated.

function [result,cumulative]=LOCAL_merge_module(result,name,module,cumulative)
  result.modules.(name)=struct('available',module.available, ...
    'first_unavailable',module.first_unavailable, ...
    'public_metrics',module.public_metrics, ...
    'audit_summary',module.audit_summary, ...
    'resource_record',module.resource_record);
  result.audit.module_return_audits.(name)=module.audit_summary;
  result.resources.modules.(name)=module.resource_record;
  result.nonblocking_warnings=[result.nonblocking_warnings,module.warnings];
  result.call_counters=LOCAL_add_counters( ...
    result.call_counters,module.call_counters);
  result.no_resolve_call_counts=result.call_counters;
  result.coverage.module_completed.(name)=true;
  result.coverage.module_available.(name)=module.available;
  if strcmp(name,'certificate')
    result.certificate_summary=module.public_metrics;
    result.coverage.fixed_certificate_consumed=module.available;
  end
  cumulative=max(cumulative,module.resource_record.concurrent_peak_candidate_mib);
end

function private=LOCAL_private_science(module)
  private=struct('available',module.available, ...
    'public_metrics',module.public_metrics, ...
    'finest_factors',module.finest_factors, ...
    'cap_signatures',module.cap_signatures);
end

function result=LOCAL_merge_cap(result,cap)
  names={'components','caps','estimator','tails','axis_metrics','arithmetic', ...
    'field_same_partial'};
  for j=1:numel(names), result.(names{j})=cap.(names{j}); end
  result.first_empirical_unavailable=cap.first_empirical_unavailable;
  result.coverage.same_density_actions_computed=true;
  result.coverage.actual_DeltaT_actions_computed= ...
    cap.qualification.actual_T_qualified;
  result.coverage.finite_image_Bloch_actions_computed= ...
    cap.qualification.finite_bloch_qualified;
  result.coverage.all_fresh_computed_modes_included=cap.all_modes_included;
  result.coverage.empirical_numerator_cap_computed=cap.numerator_available;
  result.coverage.empirical_denominator_cap_computed=cap.denominator_available;
  result.coverage.nominal_transform_computed=cap.estimator.interval_available;
end

function [result,cumulative]= ...
    LOCAL_close_resource(result,name,retained_after,cumulative)
  record=result.resources.modules.(name);
  record.retained_after_mib=retained_after;
  candidates=[cumulative,record.concurrent_peak_candidate_mib,retained_after];
  candidates=candidates(isfinite(candidates));
  if isempty(candidates), cumulative=NaN; else, cumulative=max(candidates); end
  record.cumulative_peak_candidate_mib=cumulative;
  result.resources.modules.(name)=record;
  if isfield(result.modules,name)
    result.modules.(name).resource_record=record;
  end
end

function record=LOCAL_unreturned_resource(before,c)
  record=struct( ...
    'retained_before_mib',before,'input_alias_nominal_mib',NaN, ...
    'local_workspace_peak_mib',NaN,'module_exclusive_peak_mib',NaN, ...
    'frozen_streaming_transient_mib',c.worst_transient_mib, ...
    'concurrent_peak_candidate_mib',before+c.worst_transient_mib, ...
    'return_payload_mib',NaN,'retained_after_mib',NaN, ...
    'cumulative_peak_candidate_mib',NaN, ...
    'proxy_semantics',[ ...
      'entry checkpoint with unknown unreturned local peak; deterministic ', ...
      'active-object proxy, not RSS/refcount/allocator accounting']);
end

function [staged,record]=LOCAL_after_wall_prune(staged)
  removed={}; names={'wall_input_unit_512','q_center','branch_port'};
  for j=1:numel(names)
    if isfield(staged.certificate,names{j})
      staged.certificate=rmfield(staged.certificate,names{j});
      removed{end+1}=['finest_factors.staged.certificate.',names{j}]; %#ok<AGROW>
    end
  end
  record=struct('removed_paths',{removed},'unique_last_consumer','wall', ...
    'reachable_owner_after_clear',false);
end

