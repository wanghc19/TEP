function result = check_e_cap_stream(attempt,input_path)
%CHECK_E_CAP_STREAM Run the thin REV_F same-trial evaluation-cap dispatcher.
% Purpose:
%   Dispatch the frozen certificate, lifting, wall, circle, full-P/cap, and
%   publication modules while enforcing resource and append-only contracts.
% Input:
%   attempt    - The sole append-only tag, 'ecap-a3'.
%   input_path - Explicit staged fbie-a1 certificate MAT file.
% Output:
%   result     - Compact diagnostics and empirical candidate; all certified
%                and reliability claims remain false.
% Main algorithm:
%   Merge each typed module result before clearing its private payload and
%   before applying the next resource gate.  The entry contains no boundary
%   action, quadrature, full-P, or cap formula.
% Based on:
%   check_e_cap.m Revision E and design-3-2c.md REV_F.
% Main changes:
%   Replaces the monolithic evaluator with one thin entry and five science
%   modules plus an independently ledgered publication function.
% Numerical goal:
%   Execute one memory-bounded same-trial empirical-cap attempt after review.

  if nargin~=2||~strcmp(char(attempt),'ecap-a3')|| ...
      ~(ischar(input_path)||isstring(input_path))
    error('i32f:Arguments', ...
      'The frozen call is check_e_cap_stream(''ecap-a3'',explicit_input).');
  end
  if exist('OCTAVE_VERSION','builtin')~=0
    error('i32f:MATLABRequired','This experiment requires MATLAB.');
  end
  here=fileparts(mfilename('fullpath')); output=fullfile(here,'output','ecap-a3');
  if exist(output,'file')||exist(output,'dir')
    error('i32f:OutputExists','The whole ecap-a3 directory must be absent.');
  end
  c=LOCAL_config(); timer=tic; result=LOCAL_empty_result(c,char(input_path));
  before=LOCAL_entry_retained_mib();
  consumption=i32_result_output( ...
    'consume',result,c,output,before,0);
  result.resources.attempt_consumption=consumption;
  cumulative=consumption.cumulative_peak_candidate_mib;
  clear consumption;
  dispatch=true; staged=struct(); lift_private=struct();
  wall_private=struct(); circle_private=struct();
  module=struct(); current_module='none'; module_merged=false;
  module_entry_before=NaN;
  try
    % --- stage 1: certificate identity and exact pruning ---
    current_module='certificate'; module_merged=false;
    clear before; before=LOCAL_entry_retained_mib();
    module_entry_before=before;
    module=i32_certificate_input(char(input_path),c,before);
    module=LOCAL_audit_return(module,'certificate');
    [result,cumulative]=LOCAL_merge_module(result,'certificate',module,cumulative);
    module_merged=true;
    if module.available
      staged=module.finest_factors.staged;
    else
      [result,dispatch]=LOCAL_stop_from_module(result,module,'certificate');
    end
    clear module; module=struct(); current_module='none';
    [result,cumulative]=LOCAL_close_resource( ...
      result,'certificate',LOCAL_entry_retained_mib(),cumulative);
    if dispatch&&(c.expected_seconds>c.preflight_seconds_max|| ...
        cumulative>c.preflight_mib_max)
      [result,dispatch]=LOCAL_execution_stop(result,'RESOURCE_PREFLIGHT_UNAVAILABLE', ...
        'The frozen 1500-second/520-MiB preflight refused science dispatch.');
    end
    [result,dispatch]=LOCAL_resource_gate(result,dispatch,timer,cumulative,c);

    % --- stage 2: frozen one-dimensional lift weights ---
    if dispatch
      current_module='lifting'; module_merged=false;
      clear before; before=LOCAL_entry_retained_mib();
      module_entry_before=before;
      module=i32_lifting_quadrature(c,staged,timer,before);
      module=LOCAL_audit_return(module,'lifting');
      [result,cumulative]=LOCAL_merge_module(result,'lifting',module,cumulative);
      module_merged=true;
      if module.available
        lift_private=module.finest_factors;
      else
        [result,dispatch]=LOCAL_stop_from_module(result,module,'lifting');
      end
      clear module; module=struct(); current_module='none';
      [result,cumulative]=LOCAL_close_resource( ...
        result,'lifting',LOCAL_entry_retained_mib(),cumulative);
      [result,dispatch]=LOCAL_resource_gate(result,dispatch,timer,cumulative,c);
    end

    % --- stage 3: artificial-wall action and signatures ---
    if dispatch
      current_module='wall'; module_merged=false;
      clear before; before=LOCAL_entry_retained_mib();
      module_entry_before=before;
      module=i32_wall_module(c,staged,lift_private,timer,before);
      module=LOCAL_audit_return(module,'wall');
      [result,cumulative]=LOCAL_merge_module(result,'wall',module,cumulative);
      module_merged=true;
      if module.available
        wall_private=LOCAL_private_science(module);
      else
        [result,dispatch]=LOCAL_stop_from_module(result,module,'wall');
      end
      clear module; module=struct(); current_module='none';
      if dispatch
        [staged,death]=LOCAL_after_wall_prune(staged);
        result.audit.last_use_death.after_wall=death;
      end
      [result,cumulative]=LOCAL_close_resource(result,'wall', ...
        LOCAL_entry_retained_mib(),cumulative);
      [result,dispatch]=LOCAL_resource_gate(result,dispatch,timer,cumulative,c);
    end

    % --- stage 4: material-circle action, oracles, and signatures ---
    if dispatch
      current_module='circle'; module_merged=false;
      clear before; before=LOCAL_entry_retained_mib();
      module_entry_before=before;
      module=i32_circle_module(c,staged,lift_private, ...
        wall_private.public_metrics,timer,before);
      module=LOCAL_audit_return(module,'circle');
      [result,cumulative]=LOCAL_merge_module(result,'circle',module,cumulative);
      module_merged=true;
      if module.available
        circle_private=LOCAL_private_science(module);
      else
        [result,dispatch]=LOCAL_stop_from_module(result,module,'circle');
      end
      clear module; module=struct(); current_module='none';
      if dispatch
        [staged,death]=LOCAL_after_circle_prune(staged);
        result.audit.last_use_death.after_circle=death;
      end
      [result,cumulative]=LOCAL_close_resource(result,'circle', ...
        LOCAL_entry_retained_mib(),cumulative);
      [result,dispatch]=LOCAL_resource_gate(result,dispatch,timer,cumulative,c);
    end

    % --- stage 5: full-P tails, caps, and empirical nominal transform ---
    if dispatch
      current_module='fullp_cap'; module_merged=false;
      clear before; before=LOCAL_entry_retained_mib();
      module_entry_before=before;
      module=i32_fullp_cap(c,staged,lift_private,wall_private, ...
        circle_private,timer,before);
      module=LOCAL_audit_return(module,'fullp_cap');
      [result,cumulative]=LOCAL_merge_module(result,'fullp_cap',module,cumulative);
      module_merged=true;
      if module.available
        result=LOCAL_merge_cap(result,module.public_metrics);
      else
        [result,dispatch]=LOCAL_stop_from_module(result,module,'fullp_cap');
      end
      clear module; module=struct(); current_module='none';
    end
  catch ME
    if ~module_merged&&~strcmp(current_module,'none')
      [result,cumulative]=LOCAL_salvage_failed_module( ...
        result,module,current_module,module_entry_before,cumulative,c);
    end
    [result,dispatch]=LOCAL_execution_stop(result,ME.identifier,ME.message); %#ok<ASGLU>
  end

  % --- stage 6: finally-style owner cleanup and retained-memory snapshot ---
  result.audit.final_cleanup=struct('trigger_module',current_module, ...
    'unreturned_local_peak_mib',LOCAL_unreturned_peak(module,module_merged), ...
    'preclear_owner_inventory',struct([]),'retained_before_clear_mib',NaN, ...
    'postclear_owner_inventory',struct([]),'retained_after_clear_mib',NaN, ...
    'postclear_private_owner_names',{{}}, ...
    'registered_owner_policy',[ ...
      'All reachable dense/science owners are registered; omitted entry ', ...
      'locals are control scalars, text, timers, or compact ledgers.'], ...
    'result_has_no_private_module_payload',false, ...
    'cumulative_peak_candidate_mib',NaN,'all_private_owners_cleared',false);
  for pass=1:2
    inventory=LOCAL_entry_owner_inventory();
    retained_before_clear=sum([inventory.mib]);
    result.audit.final_cleanup.preclear_owner_inventory=inventory;
    result.audit.final_cleanup.retained_before_clear_mib=retained_before_clear;
  end
  cumulative=max(cumulative,retained_before_clear);
  clear staged lift_private wall_private circle_private module;
  cleanup_death=struct( ...
    'staged_cleared',true,'lifting_factors_cleared',true, ...
    'wall_factors_and_signatures_cleared',true, ...
    'circle_factors_and_signatures_cleared',true, ...
    'current_module_payload_cleared',true);
  result.audit.last_use_death.final_cleanup=cleanup_death;
  if isfield(result.modules,'fullp_cap')
    result.audit.last_use_death.after_fullp_cap=cleanup_death;
  end
  clear cleanup_death;
  resource_names=fieldnames(result.resources.modules);
  for j=1:numel(resource_names)
    name=resource_names{j}; record=result.resources.modules.(name);
    if isfield(record,'retained_after_mib')&& ...
        (~isfinite(record.retained_after_mib)||isnan(record.retained_after_mib))
      [result,cumulative]=LOCAL_close_resource(result,name, ...
        LOCAL_entry_retained_mib(),cumulative);
    end
  end
  clear resource_names name record;
  for pass=1:2
    inventory=LOCAL_entry_owner_inventory();
    retained_after_clear=sum([inventory.mib]);
    result.audit.final_cleanup.postclear_owner_inventory=inventory;
    result.audit.final_cleanup.retained_after_clear_mib=retained_after_clear;
  end
  cumulative=max(cumulative,retained_after_clear);
  private_names={'staged','lift_private','wall_private','circle_private','module'};
  live_names={inventory.name};
  result.audit.final_cleanup.postclear_private_owner_names= ...
    intersect(live_names,private_names,'stable');
  result.audit.final_cleanup.result_has_no_private_module_payload= ...
    LOCAL_result_private_payload_absent(result);
  result.audit.final_cleanup.cumulative_peak_candidate_mib=cumulative;
  result.audit.final_cleanup.all_private_owners_cleared= ...
    isempty(result.audit.final_cleanup.postclear_private_owner_names)&& ...
    result.audit.final_cleanup.result_has_no_private_module_payload;
  if ~result.audit.final_cleanup.all_private_owners_cleared
    [result,dispatch]=LOCAL_execution_stop(result, ...
      'PRIVATE_OWNER_CLEANUP_UNAVAILABLE', ...
      'A registered private science owner remained reachable after cleanup.'); %#ok<ASGLU>
  end
  clear private_names live_names;

  result.elapsed_seconds=toc(timer);
  result.resources.actual.elapsed_seconds=result.elapsed_seconds;
  result.resources.actual.cumulative_peak_candidate_mib=cumulative;
  result.resources.actual.frozen_streaming_transient_mib=c.worst_transient_mib;
  result.resources.actual.sequential_module_peaks_combined_by_max=true;
  result.resources.actual.proxy_is_not_RSS_or_reference_count=true;
  result.peak_active_mib=cumulative;
  if result.elapsed_seconds>c.hard_seconds||cumulative>c.memory_mib_max
    [result,~]=LOCAL_execution_stop(result,'RESOURCE_LIMIT_EXCEEDED', ...
      'The hard time or 640 MiB active-object proxy was exceeded.');
  end
  result=LOCAL_finalize_status(result,c);
  result.audit.no_resolve=LOCAL_no_resolve_audit(result.call_counters);
  result.audit.allowlisted_eig=LOCAL_allowlisted_eig_audit(result.call_counters);
  if ~result.audit.no_resolve.pass
    [result,~]=LOCAL_execution_stop(result,'CERTIFICATE_IDENTITY_MISMATCH', ...
      'At least one of the eight NO_RESOLVE counters is nonzero.');
  elseif ~result.audit.allowlisted_eig.pass&& ...
      isfield(result.modules,'fullp_cap')&&result.modules.fullp_cap.available
    [result,~]=LOCAL_execution_stop(result,'ALLOWLISTED_EIG_IDENTITY_UNAVAILABLE', ...
      'The exact Gauss6/small-Gram274/total280 ledger failed.');
  end
  result=LOCAL_finalize_status(result,c);
  result.first_nonblocking_warning=LOCAL_first_warning(result.nonblocking_warnings);
  result.reliability=LOCAL_reliability_flags();
  result.qualification=LOCAL_result_qualification(result);
  result.resources.actual.hard_limits_respected= ...
    result.elapsed_seconds<=c.hard_seconds&&cumulative<=c.memory_mib_max;

  % Publication is always the last module; directory creation consumes the tag.
  clear before inventory retained_before_clear retained_after_clear;
  before=LOCAL_entry_retained_mib();
  publication=i32_result_output( ...
    'publish',result,c,output,before,cumulative);
  result.resources.modules.result_output=publication;
  result.peak_active_mib=max(result.peak_active_mib, ...
    publication.cumulative_peak_candidate_mib);
  result.resources.actual.cumulative_peak_candidate_mib= ...
    publication.cumulative_peak_candidate_mib;
  if publication.cumulative_peak_candidate_mib>c.memory_mib_max
    [result,~]=LOCAL_execution_stop(result, ...
      'RESOURCE_LIMIT_EXCEEDED_DURING_PUBLICATION', ...
      'The publication active-object proxy exceeded 640 MiB.');
    result.resources.actual.hard_limits_respected=false;
  end
end

