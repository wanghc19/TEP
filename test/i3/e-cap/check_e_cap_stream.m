function pass=LOCAL_public_schema_path(path,module)
  prefix=[module,'.public_metrics.'];
  if ~startsWith(path,prefix), pass=false; return; end
  relative=char(extractAfter(path,strlength(prefix)));
  branch=regexp(relative,'^[^.{]+','match','once');
  top=LOCAL_public_top_fields(module);
  if isempty(branch)||~ismember(branch,top), pass=false; return; end
  if ~contains(relative,'.'), pass=true; return; end
  parts=strsplit(relative,'.');
  child=regexp(parts{2},'^[^\{]+','match','once');
  if isempty(child)|| ...
      ~ismember(child,LOCAL_public_branch_children(module,branch))
    pass=false; return;
  end
  token=regexp(relative,'\.([^.{]+)$','tokens','once');
  if isempty(token), pass=false; return; end
  % Each recursive leaf is scoped by module, top branch, and a literal
  % immediate child.  The terminal vocabulary is therefore not a global
  % leaf-name exception and cannot migrate between public branches.
  pass=ismember(token{1},LOCAL_public_schema_fields(module));
end

