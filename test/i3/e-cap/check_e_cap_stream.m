function value=LOCAL_entry_retained_mib()
  info=evalin('caller','whos'); inventory=LOCAL_registered_inventory(info);
  if isempty(inventory), value=0; else, value=sum([inventory.mib]); end
end

function out=LOCAL_entry_owner_inventory()
  info=evalin('caller','whos'); out=LOCAL_registered_inventory(info);
end

function out=LOCAL_registered_inventory(info)
  owners={'result','staged','lift_private','wall_private','circle_private', ...
    'module','c','output'};
  out=struct('name',{},'class',{},'size',{},'bytes',{},'mib',{});
  for j=1:numel(info)
    if ~ismember(info(j).name,owners), continue; end
    out(end+1)=struct('name',info(j).name,'class',info(j).class, ... %#ok<AGROW>
      'size',info(j).size,'bytes',info(j).bytes, ...
      'mib',info(j).bytes/2^20);
  end
end
