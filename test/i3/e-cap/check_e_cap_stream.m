function out=LOCAL_first_warning(warnings)
  if isempty(warnings), out=LOCAL_condition('NONE','No nonblocking warning.');
  else
    out=LOCAL_condition(warnings(1).code, ...
      sprintf('First nonblocking scientific warning; value %.17g.', ...
      warnings(1).value));
  end
end

function out=LOCAL_condition(code,message)
  out=struct('code',char(code),'message',char(message));
end

