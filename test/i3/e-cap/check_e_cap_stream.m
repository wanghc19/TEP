%% ==================== Recursive returned-payload audit ====================
% Exact dense paths are allowlisted; no module receives a blanket exception.

function module=LOCAL_audit_return(module,name)
  expected_root={'available','first_unavailable','public_metrics', ...
    'finest_factors','cap_signatures','audit_summary','warnings', ...
    'call_counters','resource_record'};
  if ~isstruct(module)||~isscalar(module)|| ...
      ~isequal(sort(fieldnames(module)),sort(expected_root(:)))
    error('i32f:ReturnedPayloadSchema', ...
      'Module %s did not return the exact typed root schema.',name);
  end
  if strcmp(name,'certificate')&&module.available
    shapes=module.audit_summary.exact_shape_contract;
    if isempty(shapes)||~all([shapes.pass])
      error('i32f:CertificateExactShape', ...
        'A canonical certificate return path has the wrong mechanical shape.');
    end
  end
  context=LOCAL_shape_context(module,name);
  [fields,numeric,prohibited_field,prohibited_shape]= ...
    LOCAL_inventory(module,name,name,module,context);
  module.audit_summary.returned_field_inventory=fields;
  module.audit_summary.returned_numeric_shape_inventory=numeric;
  module.audit_summary.prohibited_field_count=numel(prohibited_field);
  module.audit_summary.prohibited_shape_count=numel(prohibited_shape);
  module.audit_summary.prohibited_fields={prohibited_field};
  module.audit_summary.prohibited_shapes={prohibited_shape};
  if ~isempty(prohibited_field)||~isempty(prohibited_shape)
    error('i32f:ReturnedPayloadAudit', ...
      'Module %s returned an unregistered dense or raw field.',name);
  end
  info=whos('module');
  module.resource_record.return_payload_mib=info.bytes/2^20;
end

function [fields,numeric,bad_field,bad_shape]= ...
    LOCAL_inventory(value,module,path,root,context)
  fields=struct('path',{},'class',{}); numeric=struct( ...
    'path',{},'class',{},'size',{},'bytes',{});
  bad_field={}; bad_shape={};
  if isstruct(value)
    for k=1:numel(value)
      names=fieldnames(value(k));
      for j=1:numel(names)
        child=[path,'.',names{j}]; item=value(k).(names{j});
        fields(end+1)=struct('path',child,'class',class(item)); %#ok<AGROW>
        if ~LOCAL_registered_schema_path(child,module)
          bad_field{end+1}=child; %#ok<AGROW>
        end
        [f,n,bf,bs]=LOCAL_inventory(item,module,child,root,context);
        fields=[fields,f]; numeric=[numeric,n]; %#ok<AGROW>
        bad_field=[bad_field,bf]; bad_shape=[bad_shape,bs]; %#ok<AGROW>
      end
    end
  elseif iscell(value)
    for j=1:numel(value)
      [f,n,bf,bs]=LOCAL_inventory(value{j},module, ...
