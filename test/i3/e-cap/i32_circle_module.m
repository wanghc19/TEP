function out=LOCAL_metric_record(a,b,threshold)
  if nargin<3, threshold=NaN; end
  numerator=norm(a-b,'fro'); left=norm(a,'fro'); right=norm(b,'fro');
  scale=max([realmin,left,right]);
  out=struct('label','','numerator',numerator,'left_norm',left, ...
    'right_norm',right,'zero_component',left==0&&right==0, ...
    'scale',scale,'ratio',numerator/scale,'threshold',threshold, ...
    'pass',isfinite(numerator)&&(isnan(threshold)||numerator/scale<=threshold));
end

function out=LOCAL_set_threshold(out,threshold)
  out.threshold=threshold; out.pass=isfinite(out.ratio)&&out.ratio<=threshold;
end

function value=LOCAL_metric(a,b)
