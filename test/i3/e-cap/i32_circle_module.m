function out = i32_circle_module(c,staged,lift_private,wall_public,timer,retained_before_mib)
%I32_CIRCLE_MODULE Evaluate the frozen material-circle action and oracles.
% Purpose:
%   Stream the seven image and three angular levels of the fixed-density
%   circle action, form compact signatures, and run the frozen kernel gates.
% Input:
%   c, staged, lift_private, wall_public, timer - Frozen same-trial inputs.
%   retained_before_mib                         - Caller active-object proxy.
% Output:
%   out                                         - Typed total module result.
% Main algorithm:
%   Accumulate symmetric QP images once, consume every checkpoint in place,
%   retain only pending registered pairs, and project the finest angular
%   action to side factors.  Kernel, Delta-T, Bloch, and conformity gates
%   use the unchanged Revision E formulas.
% Based on:
%   i32_same_eval.m circle, finite-Bloch, oracle, and structural helpers.
% Main changes:
%   Dense image/angular coefficient ladders and raw target samples never
%   enter the module return; nested differences release pending arrays.
% Numerical goal:
%   Preserve the full circle residual bandwidth independently of wall M=48.

  warnings=LOCAL_empty_warnings(); calls=LOCAL_zero_counters(); peak=0;
  first=LOCAL_condition('NONE','The circle action and kernel oracles are available.');
  available=false; public=struct(); finest=struct(); signatures=struct();
  input_alias=LOCAL_value_mib(staged)+LOCAL_value_mib(lift_private)+ ...
    LOCAL_value_mib(wall_public); peak=max(peak,LOCAL_workspace_mib());
  try
    z=staged.certificate; density=LOCAL_density_coefficients(z);
    [science,calls,peak]=LOCAL_stream_circle( ...
      c,z,density,lift_private,calls,peak,timer);
    oracle=LOCAL_oracles(c,z,density,science.angular_action_metric,calls);
    calls=oracle.call_counters;
    structural=LOCAL_structural_metrics(c,z,density,science,wall_public,oracle);
    parity=LOCAL_collect_parity(science.signatures);
    warnings=LOCAL_scientific_warnings( ...
      c,science,oracle,structural,parity);
    core=science.actions_finite;
    available=core&&oracle.available;
    if ~core
      first=LOCAL_condition('CIRCLE_ACTION_UNAVAILABLE', ...
        'A required fixed-density circle action is nonfinite.');
    elseif ~oracle.available
      first=LOCAL_condition('KERNEL_ORACLE_UNAVAILABLE', ...
        'A required analytic kernel oracle is unavailable.');
    end
    finest=science.finest_factors; signatures=science.signatures;
    public=struct('image_levels',science.image_public, ...
      'angular_levels',science.angular_public, ...
      'wronskian',science.wronskian, ...
      'repaired_value_metric',science.repaired_value_metric, ...
      'actual_T_action',science.actual_T_action, ...
      'finite_image_bloch',science.finite_image_bloch, ...
      'angular_action_metric',science.angular_action_metric, ...
      'oracles',oracle.record,'structural_metrics',structural, ...
      'producer_signature_parity',parity, ...
      'core_maps_available',core,'kernel_oracles_available',oracle.available, ...
      'kernel_qualified',oracle.qualified, ...
      'actual_T_action_qualified',science.actual_T_action.qualified, ...
      'finite_image_Bloch_qualified',science.finite_image_bloch.qualified, ...
      'conformity_qualified',structural.pass, ...
      'all_computed_circle_modes_retained',true, ...
      'circle_order_min',-1024,'circle_order_max',1023, ...
      'circle_order_count',2048,'wall_M_role','wall trace order only', ...
      'dense_coefficient_ladders_returned',false, ...
      'raw_target_samples_returned',false);
    calls.n_op_signature_parity=parity.total_operations;
  catch ME
    available=false; first=LOCAL_condition(ME.identifier,ME.message);
    finest=struct(); signatures=struct();
  end
  peak=max(peak,LOCAL_workspace_mib());
  clear staged lift_private wall_public timer z density science oracle;
  clear structural parity core;
  audit=struct('returned_field_inventory',{{}}, ...
    'returned_numeric_shape_inventory',{{}},'prohibited_field_count',NaN, ...
    'prohibited_shape_count',NaN,'last_use_clear_ledger', ...
      LOCAL_liveness_ledger(), ...
    'post_clear_local_owner_inventory',{LOCAL_owner_inventory()}, ...
    'finest_factor_whitelist',{{ ...
      'finest_factors.jump_minus','finest_factors.jump_plus', ...
      'finest_factors.delta_minus','finest_factors.delta_plus'}}, ...
    'compact_signature_whitelist',{{'cap_signatures.image', ...
      'cap_signatures.image_pairs','cap_signatures.angular', ...
      'cap_signatures.angular_pairs','cap_signatures.joint'}}, ...
    'signature_parity_coverage',LOCAL_collect_parity(signatures), ...
    'normal_orientation','circle global +r', ...
    'density_coordinate','[tau;zeta], zeta=-sigma', ...
    'raw_samples_returned',false,'coefficient_ladders_returned',false);
  payload=struct('available',available,'first_unavailable',first, ...
    'public_metrics',public,'finest_factors',finest, ...
    'cap_signatures',signatures,'audit_summary',audit,'warnings',warnings, ...
    'call_counters',calls,'resource_record',struct());
  payload.resource_record=LOCAL_resource_record(retained_before_mib, ...
    input_alias,peak,LOCAL_value_mib(payload),c);
  out=payload;
end

%% ==================== Streamed circle action ====================
% Pending coefficient/factor arrays survive only until their registered pair.

function [out,calls,peak]=LOCAL_stream_circle(c,z,density,lift,calls,peak,timer)
  Nfinal=max(c.circle_levels); theta=(0:Nfinal-1)'*2*pi/Nfinal;
  x=z.R*cos(theta); y=z.R*sin(theta); nx=cos(theta); ny=sin(theta);
  ko=z.khat; ki=sqrt(z.rho_disk)*z.khat;
  [ve0,dve0,vi0,dvi0,wronskian,tout0,tin0,dsout0,dsin0]= ...
    LOCAL_free_self(z,density,theta,ko,ki);
  [vw,dvw]=LOCAL_wall_to_circle(z,density,theta,x,y,nx,ny);
  image_value=zeros(Nfinal,size(density.tau,2)); image_dr=image_value;
  image_T_tau=image_value; image_dS_zeta=image_value;
  pairs=[3,5;5,7;2,4;4,6;6,7];
  pair_labels={'64_to_128','128_to_256','48_to_96', ...
    '96_to_192','192_to_256'};
  image_endpoints=cell(1,7); image_pairs=cell(1,5);
  image_public=cell(1,7); pending_factor=cell(1,7); pending_T=cell(1,7);
  T_metrics=cell(1,5); image_T_scale=realmin; hit=1;
  joint_factors=struct(); joint_endpoint=struct();
  for n=1:max(c.image_levels)
    for signn=[-1,1]
      [dv,ddr,dTtau,dSzeta]=LOCAL_one_image( ...
        z,density,theta,x,y,nx,ny,signn*n);
      image_value=image_value+dv; image_dr=image_dr+ddr;
      image_T_tau=image_T_tau+dTtau;
      image_dS_zeta=image_dS_zeta+dSzeta;
      calls.image_pair_updates=calls.image_pair_updates+1;
    end
    if hit<=numel(c.image_levels)&&n==c.image_levels(hit)
      vp=ve0+vw+image_value; dp=dve0+dvw+image_dr;
      tp=tout0+image_T_tau; sp=dsout0+image_dS_zeta;
      level=LOCAL_circle_level(vp,vi0,dp,dvi0,tp,tin0,sp,dsin0, ...
        dvw,z.R,Nfinal,Nfinal,c.identity_tol);
      level.label=sprintf('image-J-%d',n); level.J=n;
      factor=LOCAL_circle_factors(level,z,lift.circle_weights{end}, ...
        lift.collar_weights{end}/z.gamma);
      factor.circle.endpoint_id=[level.label,'-circle'];
      factor.volume.endpoint_id=[level.label,'-volume-circle'];
      image_endpoints{hit}=struct( ...
        'circle',LOCAL_endpoint_signature(c,[level.label,'-circle'], ...
          'circle',factor.circle_minus,factor.circle_plus,z,zeros(0,1),32), ...
        'volume_circle',LOCAL_endpoint_signature(c, ...
          [level.label,'-volume-circle'],'volume-circle', ...
          factor.volume_minus,factor.volume_plus,z,zeros(0,1),32), ...
        'J',n);
      image_public{hit}=LOCAL_level_summary(level);
      image_T_scale=max(image_T_scale,norm(level.actual_deltaT_coeff,'fro'));
      finish=find(pairs(:,2)==hit).';
      for pair_index=finish
        left=pairs(pair_index,1);
        image_pairs{pair_index}=struct( ...
          'circle',LOCAL_pair_signature(c,pending_factor{left}.circle, ...
            factor.circle,z,32,32), ...
          'volume_circle',LOCAL_pair_signature(c, ...
            pending_factor{left}.volume,factor.volume,z, ...
            32,32), ...
          'label',pair_labels{pair_index});
        T_metrics{pair_index}=LOCAL_metric_record( ...
          pending_T{left},level.actual_deltaT_coeff,NaN);
        pending_factor{left}=[]; pending_T{left}=[];
      end
      if any(pairs(:,1)==hit)
        pending_factor{hit}=factor; pending_T{hit}=level.actual_deltaT_coeff;
      end
      if hit==6
        joint_level=LOCAL_restrict_samples(vp-vi0,dvi0-dp,tp-tin0, ...
          z.R,1024,Nfinal,c.identity_tol,-tp+tin0+sp-dsin0-dvw);
        joint_factors=LOCAL_circle_factors(joint_level,z, ...
          lift.circle_weights{2},lift.collar_weights{2}/z.gamma);
        joint_factors.circle.endpoint_id='joint-circle-circle';
        joint_factors.volume.endpoint_id='joint-circle-volume-circle';
        joint_endpoint=struct( ...
          'circle',LOCAL_endpoint_signature(c,'joint-circle-circle', ...
            'circle',joint_factors.circle_minus,joint_factors.circle_plus, ...
            z,zeros(0,1),16), ...
          'volume_circle',LOCAL_endpoint_signature(c, ...
            'joint-circle-volume-circle','volume-circle', ...
            joint_factors.volume_minus,joint_factors.volume_plus, ...
            z,zeros(0,1),16), ...
          'image_J',n,'angular_nodes',1024, ...
          'riccati_level',c.riccati_levels(2), ...
          'gauss_level',c.gauss_levels(2),'selected_full_p_N',16);
        clear joint_level;
      end
      clear vp dp tp sp level factor finish;
      hit=hit+1;
    end
    if mod(n,16)==0
      LOCAL_hard_time(timer,c,'image action');
      peak=max(peak,LOCAL_workspace_mib());
    end
  end
  calls.harmonic_action_calls=calls.harmonic_action_calls+1;

  final_vp=ve0+vw+image_value; final_dp=dve0+dvw+image_dr;
  final_tp=tout0+image_T_tau; final_sp=dsout0+image_dS_zeta;
  angular_endpoints=cell(1,3); angular_pairs=cell(1,2);
  angular_public=cell(1,3); angular_T_metrics=cell(1,2);
  angular_jump_metrics=cell(1,2);
  angular_T_scale=realmin; previous=struct(); previous_T=[];
  previous_jump=[];
  final_factors=struct(); final_level=struct();
  for j=1:3
    Nt=c.circle_levels(j); stride=Nfinal/Nt; index=1:stride:Nfinal;
    level=LOCAL_circle_level(final_vp(index,:),vi0(index,:), ...
      final_dp(index,:),dvi0(index,:),final_tp(index,:),tin0(index,:), ...
      final_sp(index,:),dsin0(index,:),dvw(index,:), ...
      z.R,Nt,Nfinal,c.identity_tol);
    level.label=sprintf('angular-N-%d',Nt); level.J=max(c.image_levels);
    factor=LOCAL_circle_factors(level,z,lift.circle_weights{end}, ...
      lift.collar_weights{end}/z.gamma);
    factor.circle.endpoint_id=[level.label,'-circle'];
    factor.volume.endpoint_id=[level.label,'-volume-circle'];
    angular_endpoints{j}=struct( ...
      'circle',LOCAL_endpoint_signature(c,[level.label,'-circle'], ...
        'circle',factor.circle_minus,factor.circle_plus,z,zeros(0,1),32), ...
      'volume_circle',LOCAL_endpoint_signature(c, ...
        [level.label,'-volume-circle'],'volume-circle', ...
        factor.volume_minus,factor.volume_plus,z,zeros(0,1),32), ...
      'target_nodes',Nt);
    angular_public{j}=LOCAL_level_summary(level);
    angular_T_scale=max(angular_T_scale,norm(level.actual_deltaT_coeff,'fro'));
    if j>1
      angular_pairs{j-1}=struct( ...
        'circle',LOCAL_pair_signature(c,previous.circle,factor.circle,z, ...
          32,32), ...
        'volume_circle',LOCAL_pair_signature(c,previous.volume,factor.volume,z, ...
          32,32));
      angular_T_metrics{j-1}=LOCAL_metric_record( ...
        previous_T,level.actual_deltaT_coeff,NaN);
      angular_jump_metrics{j-1}=LOCAL_metric_record( ...
        previous_jump,level.jump_coeff,c.action_ratio_max);
      clear previous previous_T previous_jump;
    end
    previous=struct('circle',factor.circle,'volume',factor.volume);
    previous_T=level.actual_deltaT_coeff;
    previous_jump=level.jump_coeff;
    if j==3
      final_factors=factor; final_level=level;
    end
    clear factor level index;
    peak=max(peak,LOCAL_workspace_mib());
  end
  clear previous previous_T previous_jump;
  joint_pair=struct( ...
    'circle',LOCAL_pair_signature(c,joint_factors.circle, ...
      final_factors.circle,z,16,32), ...
    'volume_circle',LOCAL_pair_signature(c,joint_factors.volume, ...
      final_factors.volume,z,16,32));
  joint=joint_endpoint; joint.pair_to_final=joint_pair;
  clear joint_factors joint_pair;

  actual_T=LOCAL_actual_T_qualification(c,[T_metrics{:}],image_T_scale, ...
    [angular_T_metrics{:}],angular_T_scale, ...
    numel(final_level.actual_deltaT_coeff));
  calls.actual_deltaT_action_calls=calls.actual_deltaT_action_calls+ ...
    numel(c.image_levels)+numel(c.circle_levels);
  [finite_bloch,calls]=LOCAL_finite_image_bloch(c,z,density,calls);
  raw_delta=final_vp-vi0;
  repair=LOCAL_metric_record(final_vp-raw_delta/2, ...
    vi0+raw_delta/2,c.identity_tol);
  finest=struct('jump_minus',final_level.jump_coeff*z.Gminus, ...
    'jump_plus',final_level.jump_coeff*z.Gplus, ...
    'delta_minus',final_level.delta_coeff*z.Gminus, ...
    'delta_plus',final_level.delta_coeff*z.Gplus);
  signatures=struct('image',{image_endpoints}, ...
    'image_pairs',{image_pairs},'angular',{angular_endpoints}, ...
    'angular_pairs',{angular_pairs},'joint',joint, ...
    'common_row_order','I_2048 negative Nyquist retained');
  angular_action=angular_jump_metrics{2};
  actions_finite=all(cellfun(@(x) x.finite,image_public))&& ...
    all(cellfun(@(x) x.finite,angular_public));
  out=struct('image_public',[image_public{:}], ...
    'angular_public',[angular_public{:}],'signatures',signatures, ...
    'finest_factors',finest,'wronskian',wronskian, ...
    'repaired_value_metric',repair,'actual_T_action',actual_T, ...
    'finite_image_bloch',finite_bloch,'angular_action_metric',angular_action, ...
    'normal_decomposition_records',{[angular_public{:}]}, ...
    'raw_value_jump_norm',norm(raw_delta,'fro'), ...
    'actions_finite',actions_finite);
  clear image_value image_dr image_T_tau image_dS_zeta;
  clear final_vp final_dp final_tp final_sp vi0 dvi0 tin0 dsin0 dvw;
  clear final_factors final_level raw_delta pending_factor pending_T;
  peak=max(peak,LOCAL_workspace_mib());
end

function out=LOCAL_density_coefficients(z)
  N=256; eta=z.eta_unit_256;
  out=struct('orders',(-N/2:N/2-1).', ...
    'tau',fftshift(fft(eta(1:N,:),[],1),1)/N, ...
    'zeta',fftshift(fft(eta(N+1:end,:),[],1),1)/N, ...
    'xi_left',z.xi_left_unit_512,'xi_right',z.xi_right_unit_512);
  if any(~isfinite([out.tau(:);out.zeta(:)]))
    error('i32f:DensityTransform','The fixed density FFT is nonfinite.');
  end
end

function out=LOCAL_circle_level(vp,vm,dp,dm,tp,tm,sp,sm,wall_dr,R,N,Nfinal,tol)
  delta=vp-vm; jump=dm-dp; deltaT=tp-tm; dSzeta=sp-sm;
  decomposition=-deltaT+dSzeta-wall_dr;
  decomposition_metric=LOCAL_metric_record(jump,decomposition,tol);
  delta_coeff=LOCAL_pad_orders(LOCAL_circle_coeff(delta,R),N,Nfinal);
  jump_coeff=LOCAL_pad_orders(LOCAL_circle_coeff(jump,R),N,Nfinal);
  deltaT_coeff=LOCAL_pad_orders(LOCAL_circle_coeff(deltaT,R),N,Nfinal);
  dSzeta_coeff=LOCAL_pad_orders(LOCAL_circle_coeff(dSzeta,R),N,Nfinal);
  wall_coeff=LOCAL_pad_orders(LOCAL_circle_coeff(wall_dr,R),N,Nfinal);
  out=struct('label','','J',0,'target_nodes',N, ...
    'delta_coeff',delta_coeff,'jump_coeff',jump_coeff, ...
    'actual_deltaT_coeff',deltaT_coeff, ...
    'dS_difference_zeta_norm',norm(dSzeta_coeff,'fro'), ...
    'wall_normal_norm',norm(wall_coeff,'fro'), ...
    'normal_decomposition_metric',decomposition_metric, ...
    'finite',all(isfinite([delta_coeff(:);jump_coeff(:);deltaT_coeff(:); ...
      dSzeta_coeff(:);wall_coeff(:);decomposition_metric.ratio])));
end

function out=LOCAL_restrict_samples(delta,jump,deltaT,R,N,Nfinal,tol,decomposition)
  stride=size(delta,1)/N;
  if stride~=round(stride)
    error('i32f:CircleRestriction','The circle target grids are not nested.');
  end
  index=1:round(stride):size(delta,1);
  dc=LOCAL_pad_orders(LOCAL_circle_coeff(delta(index,:),R),N,Nfinal);
  jc=LOCAL_pad_orders(LOCAL_circle_coeff(jump(index,:),R),N,Nfinal);
  tc=LOCAL_pad_orders(LOCAL_circle_coeff(deltaT(index,:),R),N,Nfinal);
  dm=LOCAL_metric_record(jump(index,:),decomposition(index,:),tol);
  out=struct('label','joint-circle','J',192,'target_nodes',N, ...
    'delta_coeff',dc,'jump_coeff',jc,'actual_deltaT_coeff',tc, ...
    'dS_difference_zeta_norm',NaN,'wall_normal_norm',NaN, ...
    'normal_decomposition_metric',dm, ...
    'finite',all(isfinite([dc(:);jc(:);tc(:);dm.ratio])));
end

function out=LOCAL_level_summary(level)
  out=struct('label',level.label,'J',level.J, ...
    'target_nodes',level.target_nodes, ...
    'order_min',-level.target_nodes/2, ...
    'order_max',level.target_nodes/2-1, ...
    'delta_norm',norm(level.delta_coeff,'fro'), ...
    'jump_norm',norm(level.jump_coeff,'fro'), ...
    'actual_deltaT_norm',norm(level.actual_deltaT_coeff,'fro'), ...
    'dS_difference_zeta_norm',level.dS_difference_zeta_norm, ...
    'wall_normal_norm',level.wall_normal_norm, ...
    'normal_decomposition_metric',level.normal_decomposition_metric, ...
    'finite',level.finite);
end

function out=LOCAL_circle_factors(level,z,circle_weight,collar_weight)
  LOCAL_circle_weight_gate(circle_weight,collar_weight,size(level.jump_coeff,1));
  Jm=level.jump_coeff*z.Gminus; Jp=level.jump_coeff*z.Gplus;
  Dm=level.delta_coeff*z.Gminus; Dp=level.delta_coeff*z.Gplus;
  Hcm=LOCAL_weight_rows(Jm,1./sqrt(circle_weight));
  Hcp=LOCAL_weight_rows(Jp,1./sqrt(circle_weight));
  Hvm=LOCAL_weight_rows(Dm,sqrt(collar_weight));
  Hvp=LOCAL_weight_rows(Dp,sqrt(collar_weight));
  out=struct('circle_minus',Hcm,'circle_plus',Hcp, ...
    'volume_minus',Hvm,'volume_plus',Hvp, ...
    'jump_minus',Jm,'jump_plus',Jp,'delta_minus',Dm,'delta_plus',Dp, ...
    'circle',struct('minus',Hcm,'plus',Hcp,'center',zeros(0,1)), ...
    'volume',struct('minus',Hvm,'plus',Hvp,'center',zeros(0,1)));
end

function LOCAL_circle_weight_gate(circle,collar,N)
  if numel(circle)~=N||numel(collar)~=N|| ...
      any(~isfinite([circle;collar]))||any(circle<=0)||any(collar<0)
    error('i32f:ComponentWeight','A required circle component weight is invalid.');
  end
end

function value=LOCAL_weight_rows(A,w)
  if size(A,1)~=numel(w)
    error('i32f:FactorDimensions','A factor weight dimension is wrong.');
  end
  value=bsxfun(@times,A,w);
end

function [ve,dve,vi,dvi,record,tout,tin,dsout,dsin]= ...
    LOCAL_free_self(z,density,theta,ko,ki)
  ell=density.orders; E=exp(1i*theta*ell.');
  [So,Dpo,~,dSpo,~,To,wo]=LOCAL_free_factors(ell,ko,z.R);
  [Si,~,Dmi,~,dSmi,Ti,wi]=LOCAL_free_factors(ell,ki,z.R);
  ve=E*(bsxfun(@times,Dpo,density.tau)- ...
    bsxfun(@times,So,density.zeta));
  tout=E*bsxfun(@times,To,density.tau);
  dsout=E*bsxfun(@times,dSpo,density.zeta);
  dve=tout-dsout;
  vi=E*(bsxfun(@times,Dmi,density.tau)- ...
    bsxfun(@times,Si,density.zeta));
  tin=E*bsxfun(@times,Ti,density.tau);
  dsin=E*bsxfun(@times,dSmi,density.zeta);
  dvi=tin-dsin;
  record=struct('exterior',wo,'interior',wi, ...
    'minus_S_exterior_minus_interior_jump_is_plus_zeta',true);
end

function [S,Dplus,Dminus,dSplus,dSminus,T,record]= ...
    LOCAL_free_factors(ell,k,R)
  zr=k*R; [lj,pj,ljp,pjp]=LOCAL_bessel_log_j(ell,zr);
  [lh,ph,lhp,php]=LOCAL_hankel_log_orders(ell,zr);
  S=1i*pi*R/2*LOCAL_log_product(lj,pj,lh,ph);
  Dplus=1i*pi*k*R/2*LOCAL_log_product(ljp,pjp,lh,ph);
  Dminus=1i*pi*k*R/2*LOCAL_log_product(lj,pj,lhp,php);
  dSplus=Dminus; dSminus=Dplus;
  T=1i*pi*k^2*R/2*LOCAL_log_product(ljp,pjp,lhp,php);
  jumpD=Dplus-Dminus; jumpS=dSplus-dSminus;
  scaleD=max([realmin*ones(size(ell)),abs(Dplus),abs(Dminus)],[],2);
  record=struct('orders',ell,'D_jump_defect', ...
    max(abs(jumpD-1)./max(realmin,scaleD)), ...
    'dS_jump_defect',max(abs(jumpS+1)./max(realmin,scaleD)), ...
    'finite',all(isfinite([S;Dplus;Dminus;dSplus;dSminus;T])), ...
    'scaled_log_products',true, ...
    'recurrence_oracle_attached_separately',true);
end

function [value,dr,Ttau,dSzeta]= ...
    LOCAL_one_image(z,density,theta,x,y,nx,ny,n)
  k=z.khat; R=z.R; ell=density.orders; center_y=n*z.d;
  dx=x; dy=y-center_y; rn=hypot(dx,dy); angle=atan2(dy,dx);
  erx=dx./rn; ery=dy./rn; etx=-ery; ety=erx;
  radial_dot=nx.*erx+ny.*ery; tangent_dot=nx.*etx+ny.*ety;
  phase=exp(1i*z.beta*n*z.d); N=numel(theta); K=size(density.tau,2);
  value=zeros(N,K); dr=value; Ttau=value; dSzeta=value;
  [lh,ph,lhp,php]=LOCAL_hankel_log_table(ell,k*rn);
  for first=1:16:numel(ell)
    ids=first:min(first+15,numel(ell)); l=ell(ids).';
    A=exp(1i*angle*l);
    [lj,pj,ljp,pjp]=LOCAL_bessel_log_j(l,k*R);
    JH=exp(bsxfun(@plus,lh(:,ids),lj)+ ...
      1i*bsxfun(@plus,ph(:,ids),pj));
    JpH=exp(bsxfun(@plus,lh(:,ids),ljp)+ ...
      1i*bsxfun(@plus,ph(:,ids),pjp));
    JHp=exp(bsxfun(@plus,lhp(:,ids),lj)+ ...
      1i*bsxfun(@plus,php(:,ids),pj));
    JpHp=exp(bsxfun(@plus,lhp(:,ids),ljp)+ ...
      1i*bsxfun(@plus,php(:,ids),pjp));
    Sop=1i*pi*R/2*(JH.*A); Dop=1i*pi*R*k/2*(JpH.*A);
    radialS=1i*pi*R/2*bsxfun(@times,JHp.*A,k*radial_dot);
    radialD=1i*pi*R*k/2*bsxfun(@times,JpHp.*A,k*radial_dot);
    tangentS=bsxfun(@times,Sop,1i*tangent_dot./rn).*l;
    tangentD=bsxfun(@times,Dop,1i*tangent_dot./rn).*l;
    dSop=radialS+tangentS; dDop=radialD+tangentD;
    if any(~isfinite([Sop(:);Dop(:);dSop(:);dDop(:)]))
      error('i32f:CircleHarmonicAction', ...
        'A required scaled harmonic product is nonfinite.');
    end
    value=value+phase*(Dop*density.tau(ids,:)-Sop*density.zeta(ids,:));
    dr=dr+phase*(dDop*density.tau(ids,:)-dSop*density.zeta(ids,:));
    Ttau=Ttau+phase*(dDop*density.tau(ids,:));
    dSzeta=dSzeta+phase*(dSop*density.zeta(ids,:));
  end
end

function [lh,ph,lhp,php]=LOCAL_hankel_log_table(orders,z)
  N=numel(z); K=numel(orders); lh=zeros(N,K); ph=lh; lhp=lh; php=lh;
  for j=1:N
    [lh(j,:),ph(j,:),lhp(j,:),php(j,:)]= ...
      LOCAL_hankel_log_orders(orders.',z(j));
  end
end

function [value,dr]=LOCAL_wall_to_circle(z,density,theta,x,y,nx,ny)
  orders=(-256:255).'; beta=z.beta+2*pi*orders/z.d;
  gamma=LOCAL_outgoing(z.khat,beta); psi=exp(1i*y*beta.')/sqrt(z.d);
  left_phase=exp(1i*(x-z.X_L)*gamma.');
  right_phase=exp(1i*(z.X_R-x)*gamma.');
  s0=1i./(2*gamma);
  SL=bsxfun(@times,psi.*left_phase,s0.');
  SR=bsxfun(@times,psi.*right_phase,s0.');
  dSL=SL.*(nx*(1i*gamma).'+ny*(1i*beta).');
  dSR=SR.*(nx*(-1i*gamma).'+ny*(1i*beta).');
  value=SL*density.xi_left+SR*density.xi_right;
  dr=dSL*density.xi_left+dSR*density.xi_right;
  if any(~isfinite([value(:);dr(:)]))
    error('i32f:WallCircleAction','The wall-to-circle action is nonfinite.');
  end
end

function [logJ,phaseJ,logJp,phaseJp]=LOCAL_bessel_log_j(orders,z)
  nmax=max(abs(orders))+1; logs=zeros(nmax+1,1); phases=zeros(nmax+1,1);
  for n=0:nmax
    term=1; series=1;
    for q=1:200
      term=term*(-z^2/4)/(q*(n+q)); updated=series+term;
      if abs(term)<=eps*max(realmin,abs(updated)), series=updated; break; end
      series=updated;
    end
    logs(n+1)=n*log(abs(z/2))-gammaln(n+1)+log(abs(series));
    phases(n+1)=n*angle(z)+angle(series);
  end
  logJ=zeros(size(orders)); phaseJ=logJ; logJp=logJ; phaseJp=logJ;
  for j=1:numel(orders)
    n=abs(orders(j)); parity=pi*mod(n,2)*(orders(j)<0);
    logJ(j)=logs(n+1); phaseJ(j)=phases(n+1)+parity;
    if n==0
      logJp(j)=logs(2); phaseJp(j)=phases(2)+pi;
    else
      [logJp(j),phaseJp(j)]=LOCAL_log_difference( ...
        logs(n),phases(n),logs(n+2),phases(n+2),log(2));
      phaseJp(j)=phaseJp(j)+parity;
    end
  end
end

function [logH,phaseH,logHp,phaseHp]=LOCAL_hankel_log_orders(orders,z)
  nmax=max(abs(orders))+1; [logs,phases]=LOCAL_hankel_sequence(z,nmax);
  logH=zeros(size(orders)); phaseH=logH; logHp=logH; phaseHp=logH;
  for j=1:numel(orders)
    n=abs(orders(j)); parity=pi*mod(n,2)*(orders(j)<0);
    logH(j)=logs(n+1); phaseH(j)=phases(n+1)+parity;
    if n==0
      logHp(j)=logs(2); phaseHp(j)=phases(2)+pi;
    else
      [logHp(j),phaseHp(j)]=LOCAL_log_difference( ...
        logs(n),phases(n),logs(n+2),phases(n+2),log(2));
      phaseHp(j)=phaseHp(j)+parity;
    end
  end
end

function [logs,phases]=LOCAL_hankel_sequence(z,nmax)
  pair=[besselh(0,1,z),besselh(1,1,z)]; logscale=0;
  logs=zeros(nmax+1,1); phases=logs;
  logs(1)=log(abs(pair(1))); phases(1)=angle(pair(1));
  if nmax==0, return; end
  logs(2)=log(abs(pair(2))); phases(2)=angle(pair(2));
  for n=1:nmax-1
    next=2*n/z*pair(2)-pair(1); magnitude=max(abs([pair,next]));
    if magnitude>1e100||magnitude<1e-100
      pair=pair/magnitude; next=next/magnitude; logscale=logscale+log(magnitude);
    end
    pair=[pair(2),next]; logs(n+2)=log(abs(next))+logscale;
    phases(n+2)=angle(next);
  end
end

function [logvalue,phase]=LOCAL_log_difference(la,pa,lb,pb,subtract_log)
  scale=max(la,lb); value=exp(la-scale+1i*pa)-exp(lb-scale+1i*pb);
  logvalue=scale+log(abs(value))-subtract_log; phase=angle(value);
end

function value=LOCAL_log_product(la,pa,lb,pb)
  value=exp(la+lb+1i*(pa+pb));
end

function gamma=LOCAL_outgoing(k,beta)
  gamma=sqrt(complex(k^2-beta.^2));
  flip=imag(gamma)<0|(imag(gamma)==0&real(gamma)<0);
  gamma(flip)=-gamma(flip);
  if any(~isfinite(gamma))||any(gamma==0)
    error('i32f:BranchUnavailable','A required outgoing branch is unavailable.');
  end
end

%% ==================== Frozen action qualification ====================
% The actual fixed-density Delta-T and finite-image Bloch gates are unchanged.

function out=LOCAL_actual_T_qualification(c,image_metric,image_scale, ...
    angular_metric,angular_scale,final_numel)
  labels={'64_to_128','128_to_256','48_to_96', ...
    '96_to_192','192_to_256'};
  for j=1:5
    image_metric(j).label=labels{j};
  end
  omega_image=100*final_numel*eps*image_scale;
  image_metric(1).threshold=Inf;
  image_metric(2).threshold=max( ...
    c.image_ratio_max*image_metric(1).numerator,omega_image);
  image_metric(3).threshold=Inf;
  image_metric(4).threshold=max( ...
    c.image_ratio_max*image_metric(3).numerator,omega_image);
  image_metric(5).threshold=Inf;
  for j=1:5
    image_metric(j).pass=isfinite(image_metric(j).numerator)&& ...
      image_metric(j).numerator<=image_metric(j).threshold;
  end
  dyadic_near=image_metric(1).numerator<=omega_image&& ...
    image_metric(2).numerator<=omega_image;
  staggered_near=image_metric(3).numerator<=omega_image&& ...
    image_metric(4).numerator<=omega_image;
  dyadic=dyadic_near||image_metric(2).numerator<= ...
    max(c.image_ratio_max*image_metric(1).numerator,omega_image);
  staggered=staggered_near||image_metric(4).numerator<= ...
    max(c.image_ratio_max*image_metric(3).numerator,omega_image);
  image_available=all(isfinite([[image_metric.numerator],omega_image]));

  angular_metric(1).label='512_to_1024';
  angular_metric(2).label='1024_to_2048';
  omega_angular=100*final_numel*eps*angular_scale;
  angular_metric(1).threshold=Inf;
  angular_metric(2).threshold=max( ...
    c.spectral_ratio_max*angular_metric(1).numerator,omega_angular);
  for j=1:2
    angular_metric(j).pass=isfinite(angular_metric(j).numerator)&& ...
      angular_metric(j).numerator<=angular_metric(j).threshold;
  end
  angular_near=all([angular_metric.numerator]<=omega_angular);
  angular_contract=angular_metric(2).numerator<= ...
    max(c.spectral_ratio_max*angular_metric(1).numerator,omega_angular);
  angular_available=all(isfinite([[angular_metric.numerator],omega_angular]));
  ratio_values=[image_metric(2).numerator/ ...
    max(realmin,image_metric(1).numerator), ...
    image_metric(4).numerator/max(realmin,image_metric(3).numerator), ...
    angular_metric(2).numerator/max(realmin,angular_metric(1).numerator)];
  if all(isfinite(ratio_values)), maximum_ratio=max(ratio_values);
  else, maximum_ratio=Inf; end
  available=image_available&&angular_available;
  qualified=available&&dyadic&&staggered&&(angular_near||angular_contract);
  out=struct('available',available,'qualified',qualified, ...
    'orientation','exterior minus interior global +r', ...
    'definition','d_r(D_QP tau)-d_r(D_i tau)', ...
    'image_metrics',image_metric,'angular_metrics',angular_metric, ...
    'image_omega',omega_image,'angular_omega',omega_angular, ...
    'image_ratio_threshold',c.image_ratio_max, ...
    'angular_ratio_threshold',c.spectral_ratio_max, ...
    'dyadic_pass',dyadic,'staggered_pass',staggered, ...
    'cross_finite',isfinite(image_metric(5).numerator), ...
    'angular_pass',angular_near||angular_contract, ...
    'maximum_contraction_ratio',maximum_ratio, ...
    'all_level_maps_stored_separately',false);
end

function [out,calls]=LOCAL_finite_image_bloch(c,z,density,calls)
  try
    [out,calls]=LOCAL_finite_image_bloch_core(c,z,density,calls);
  catch ME
    if ~any(strcmp(ME.identifier, ...
        {'i32f:CircleHarmonicAction','i32f:WallCircleAction'}))
      rethrow(ME);
    end
    out=struct('available',false,'qualified',false,'levels',[], ...
      'safe_target_x',.30,'paired_y',[-z.d/2,z.d/2], ...
      'physical_Bloch_phase',exp(1i*z.beta*z.d), ...
      'derivative','global +y at both paired targets', ...
      'same_fixed_eta_and_xi_consumed',true, ...
      'finite_image_J',c.image_levels,'threshold',c.identity_tol, ...
      'angular_target_grid_dependency', ...
        'none: paired point action consumes fixed eta Fourier coefficients', ...
      'maximum_final_ratio',Inf,'fail_open',true, ...
      'exact_continuous_QP_Bloch_is_structural',true, ...
      'finite_image_action_enclosed',false,'message',ME.message);
  end
end

function [out,calls]=LOCAL_finite_image_bloch_core(c,z,density,calls)
  checkpoints=c.image_levels; x=.30; y=[-z.d/2,z.d/2];
  phase=exp(1i*z.beta*z.d);
  template=struct('J',0,'bottom_value',[],'top_value',[], ...
    'bottom_global_y_derivative',[],'top_global_y_derivative',[], ...
    'value_metric',LOCAL_metric_record(0,0,NaN), ...
    'flux_metric',LOCAL_metric_record(0,0,NaN));
  levels=repmat(template,1,numel(checkpoints));
  value=zeros(2,size(density.tau,2)); derivative=value;
  for side=1:2
    [wall_value,wall_derivative]=LOCAL_wall_to_circle( ...
      z,density,0,x,y(side),0,1);
    [self_value,self_derivative]=LOCAL_one_image( ...
      z,density,0,x,y(side),0,1,0);
    value(side,:)=wall_value+self_value;
    derivative(side,:)=wall_derivative+self_derivative;
  end
  hit=1;
  for n=1:max(checkpoints)
    for signn=[-1,1]
      for side=1:2
        [dv,ddr]=LOCAL_one_image(z,density,0,x,y(side),0,1,signn*n);
        value(side,:)=value(side,:)+dv;
        derivative(side,:)=derivative(side,:)+ddr;
        calls.finite_bloch_image_updates=calls.finite_bloch_image_updates+1;
      end
    end
    if hit<=numel(checkpoints)&&n==checkpoints(hit)
      vm=LOCAL_metric_record(value(2,:),phase*value(1,:),c.identity_tol);
      fm=LOCAL_metric_record( ...
        derivative(2,:),phase*derivative(1,:),c.identity_tol);
      levels(hit)=struct('J',n,'bottom_value',value(1,:), ...
        'top_value',value(2,:), ...
        'bottom_global_y_derivative',derivative(1,:), ...
        'top_global_y_derivative',derivative(2,:), ...
        'value_metric',vm,'flux_metric',fm);
      hit=hit+1;
    end
  end
  value_ratio=arrayfun(@(item) item.value_metric.ratio,levels);
  flux_ratio=arrayfun(@(item) item.flux_metric.ratio,levels);
  available=all(isfinite([value_ratio,flux_ratio]));
  if available, final=max(value_ratio(end),flux_ratio(end)); else, final=Inf; end
  qualified=available&&final<=c.identity_tol;
  out=struct('available',available,'qualified',qualified,'levels',levels, ...
    'safe_target_x',x,'paired_y',y,'physical_Bloch_phase',phase, ...
    'derivative','global +y at both paired targets', ...
    'same_fixed_eta_and_xi_consumed',true, ...
    'finite_image_J',checkpoints,'threshold',c.identity_tol, ...
    'angular_target_grid_dependency', ...
      'none: paired point action consumes fixed eta Fourier coefficients', ...
    'maximum_final_ratio',final,'fail_open',true, ...
    'exact_continuous_QP_Bloch_is_structural',true, ...
    'finite_image_action_enclosed',false);
end

%% ==================== Compact endpoint and pair signatures ====================
% Direct action blocks are transient and die inside these helpers.

function out=LOCAL_endpoint_signature(c,label,component,Hm,Hp,z,center,N)
  [minus,block_m]=LOCAL_side_endpoint(c,Hm,z.Pminus,z.cminus,N);
  [plus,block_p]=LOCAL_side_endpoint(c,Hp,z.Pplus,z.cplus,N);
  center_squared=norm(center)^2;
  long=norm([center(:);block_m;block_p]);
  reconstructed=sqrt(center_squared+sum(minus.direct_squared_terms(1:N))+ ...
    sum(plus.direct_squared_terms(1:N)));
  nops=4*(numel(center)+numel(block_m)+numel(block_p))+16;
  parity=LOCAL_parity_record(label,'producer_endpoint_direct', ...
    long,reconstructed,nops);
  clear block_m block_p long reconstructed;
  out=struct('endpoint_id',label,'component',component, ...
    'row_order','canonical circle I_2048 row blocks', ...
    'Nminus',N,'Nplus',N,'center_squared',center_squared, ...
    'minus',minus,'plus',plus, ...
    'finite',minus.finite&&plus.finite&&isfinite(center_squared), ...
    'signature_parity',parity);
end

function [out,long_block]=LOCAL_side_endpoint(c,H,P,c0,N)
  Nmax=max(c.full_p_levels); terms=zeros(1,Nmax); state=c0;
  rows=size(H,1); long_block=zeros(rows*Nmax,1,'like',H*c0);
  for n=1:Nmax
    action=H*state; terms(n)=norm(action)^2;
    if n<=N, long_block((n-1)*rows+(1:rows))=action; end
    state=P*state;
  end
  W=H'*H;
  out=struct('W',W,'direct_squared_terms',terms, ...
    'tail_input_audit',struct('rows',rows,'state_dimension',size(P,1)), ...
    'finite',all(isfinite([W(:);terms(:)])));
end

function out=LOCAL_pair_signature(c,a,b,z,Na,Nb)
  [dm,block_m]=LOCAL_side_pair(c,a.minus,b.minus,z.Pminus,z.cminus,Na,Nb);
  [dp,block_p]=LOCAL_side_pair(c,a.plus,b.plus,z.Pplus,z.cplus,Na,Nb);
  dc=norm(b.center-a.center)^2;
  long=norm([b.center(:)-a.center(:);block_m;block_p]);
  reconstructed=sqrt(dc+sum(dm)+sum(dp));
  nops=4*(numel(a.center)+numel(block_m)+numel(block_p))+24;
  label=[a.endpoint_id,'->',b.endpoint_id];
  parity=LOCAL_parity_record(label,'producer_pair_direct', ...
    long,reconstructed,nops);
  out=struct('left_endpoint_id',a.endpoint_id, ...
    'right_endpoint_id',b.endpoint_id, ...
    'center_difference_squared',dc, ...
    'minus_direct_difference_squared_terms',dm, ...
    'plus_direct_difference_squared_terms',dp, ...
    'left_norm_scale',LOCAL_direct_scale(a,z,Na), ...
    'right_norm_scale',LOCAL_direct_scale(b,z,Nb), ...
    'finite',all(isfinite([dc,dm,dp])), ...
    'signature_parity',parity);
  clear block_m block_p long reconstructed;
end

function [terms,long_block]=LOCAL_side_pair(c,Ha,Hb,P,c0,Na,Nb)
  Nmax=max(c.full_p_levels); rows=size(Ha,1);
  if size(Hb,1)~=rows
    error('i32f:SignatureRows','A circle pair row order is inconsistent.');
  end
  terms=zeros(1,Nmax); long_block=zeros(rows*Nmax,1,'like',Ha*c0); state=c0;
  for n=1:Nmax
    da=zeros(rows,1,'like',Ha*c0); db=da;
    if n<=Na, da=Ha*state; end
    if n<=Nb, db=Hb*state; end
    difference=db-da; terms(n)=norm(difference)^2;
    long_block((n-1)*rows+(1:rows))=difference; state=P*state;
  end
end

function value=LOCAL_direct_scale(factors,z,N)
  value=norm(factors.center)^2; state=z.cminus;
  for n=1:N, value=value+norm(factors.minus*state)^2; state=z.Pminus*state; end
  state=z.cplus;
  for n=1:N, value=value+norm(factors.plus*state)^2; state=z.Pplus*state; end
  value=sqrt(value);
end

function out=LOCAL_parity_record(label,class_name,long,sig,nops)
  scale=max([realmin,abs(long),abs(sig)]); allowance=100*nops*eps*scale;
  numerator=abs(long-sig);
  out=struct('label',label,'coverage_class',class_name,'actual',true, ...
    'representative',false,'long_value',long,'signature_value',sig, ...
    'n_op',nops,'scale',scale,'allowance',allowance, ...
    'numerator',numerator,'ratio',numerator/max(realmin,allowance), ...
    'pass',isfinite(numerator)&&numerator<=allowance);
end

function out=LOCAL_collect_parity(signatures)
  records=struct([]); names={'image','image_pairs','angular','angular_pairs'};
  for a=1:numel(names)
    name=names{a};
    if ~isstruct(signatures)||~isfield(signatures,name), continue; end
    family=signatures.(name);
    for j=1:numel(family)
      item=family{j};
      records=LOCAL_append(records,item.circle.signature_parity); %#ok<AGROW>
      records=LOCAL_append(records,item.volume_circle.signature_parity); %#ok<AGROW>
    end
  end
  if isstruct(signatures)&&isfield(signatures,'joint')&& ...
      isfield(signatures.joint,'circle')
    records=LOCAL_append(records,signatures.joint.circle.signature_parity); %#ok<AGROW>
    records=LOCAL_append(records, ...
      signatures.joint.volume_circle.signature_parity); %#ok<AGROW>
    records=LOCAL_append(records, ...
      signatures.joint.pair_to_final.circle.signature_parity); %#ok<AGROW>
    records=LOCAL_append(records, ...
      signatures.joint.pair_to_final.volume_circle.signature_parity); %#ok<AGROW>
  end
  coverage=LOCAL_validate_parity_coverage(records,LOCAL_expected_parity());
  if isempty(records)
    out=struct('records',records,'required_count',coverage.required_count, ...
      'pass',false,'total_operations',0,'coverage',coverage); return;
  end
  out=struct('records',records,'required_count',coverage.required_count, ...
    'pass',all([records.pass])&&coverage.pass, ...
    'total_operations',sum([records.n_op]),'coverage',coverage);
end

