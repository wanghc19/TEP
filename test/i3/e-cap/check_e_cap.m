function out=LOCAL_add_counters(out,new)
  names=fieldnames(new);
  for j=1:numel(names)
    if ~isfield(out,names{j}), out.(names{j})=0; end
    out.(names{j})=out.(names{j})+new.(names{j});
  end
end

function pass=LOCAL_all_zero(counters)
  names={'candidate_solve_calls','qz_solve_calls','coordinate_solve_calls', ...
    'propagation_solve_calls','wall_density_solve_calls', ...
    'circle_density_solve_calls','schur_solve_calls','proxy_build_calls'};
  values=zeros(size(names));
  for j=1:numel(names), values(j)=counters.(names{j}); end
  pass=all(values==0);
end

