  dxR=1i*gamma.*(E.*qL-qR); embed=zeros(512,K);
  retained=(-c.M:c.M).'; for j=1:K, embed(wall_orders==retained(j),j)=1; end
  reconstructed_left=a.QRminus*z.cminus-embed*dxL;
  reconstructed_right=embed*dxR+a.QLplus*z.cplus;
  center_jump_defect=max( ...
    LOCAL_relative_difference(reconstructed_left, ...
      z.center_wall_jumps.left_coefficients), ...
    LOCAL_relative_difference(reconstructed_right, ...
      z.center_wall_jumps.right_coefficients));
  finite=all(isfinite([order_defect,circle_order_defect,theta_defect, ...
    y_defect,center_jump_defect]));
  pass=dim_pass&&finite&&max([order_defect,circle_order_defect, ...
    theta_defect,y_defect,center_jump_defect])<=c.identity_tol;
  out=struct('pass',pass,'dimensions',dimensions, ...
    'wall_order_relative_defect',order_defect, ...
    'circle_order_relative_defect',circle_order_defect, ...
    'circle_theta_relative_defect',theta_defect, ...
    'wall_common_grid_relative_defect',y_defect, ...
    'center_wall_jump_association_defect',center_jump_defect);
end

function value=LOCAL_relative_difference(x,y)
  if ~isequal(size(x),size(y))||any(~isfinite([x(:);y(:)]))
    value=Inf;
  else
    value=norm(x-y,'fro')/max([realmin,norm(x,'fro'),norm(y,'fro')]);
  end
end

function out=LOCAL_preflight(c,s,conversion,original_mib,normalization_peak)
  staged_mib=LOCAL_mib({s}); ledger_mib=LOCAL_mib({conversion});
  estimate=max(normalization_peak, ...
    staged_mib+ledger_mib+c.worst_transient_mib);
  out=struct('estimated_seconds',c.expected_seconds, ...
    'estimated_peak_mib',estimate, ...
    'original_integer_storage_staged_mib',original_mib, ...
    'double_expanded_staged_mib',staged_mib, ...
    'conversion_ledger_mib',ledger_mib, ...
    'normalization_peak_mib',normalization_peak, ...
    'staged_input_active_mib',staged_mib, ...
    'worst_streaming_transient_mib',c.worst_transient_mib, ...
    'allocation_combination',[ ...
      'max(original + double-expanded + ledger during normalization, ', ...
      'double-expanded staged input + ledger + worst simultaneous transient)'], ...
    'maximum_seconds',c.preflight_seconds_max, ...
    'maximum_peak_mib',c.preflight_mib_max, ...
    'streamed_target_mode_image_contributions',470e6, ...
    'pass',c.expected_seconds<=c.preflight_seconds_max&& ...
      estimate<=c.preflight_mib_max,'no_fallback_levels',true);
end

