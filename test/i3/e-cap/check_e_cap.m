function result = check_e_cap(attempt,input_path)
%CHECK_E_CAP Evaluate the frozen I3.2 same-trial empirical cap.
% Purpose:
%   Consume one explicit staged fbie-a1 certificate, re-evaluate only its
%   fixed-density boundary actions, and form an empirical evaluation cap.
% Input:
%   attempt    - The sole Revision E tag, 'ecap-a2'.
%   input_path - Explicit staged certificate MAT file.
% Output:
%   result     - Append-only diagnostics, empirical caps, nominal transform,
%                and a complete reliability-false claim ledger.
% Main algorithm:
%   Validate immutable certificate coordinates, evaluate the same trial on
%   preregistered nested levels, assemble canonical full-P factors, and apply
%   the frozen empirical remainder rules without any solve.
% Based on:
%   research/projects/eig-apost/implementation/i3/design-3-2b.md.
% Main changes:
%   Replaces every solve by staged immutable arrays and a direct harmonic-
%   image evaluator for the already-defined continuous QP kernel.
% Numerical goal:
%   Produce an ordinary same-trial evaluation cap, never a rigorous bound.

  if nargin~=2 || ~strcmp(char(attempt),'ecap-a2') || ...
      ~(ischar(input_path)||isstring(input_path))
    error('i32e:Arguments', ...
      'The frozen call is check_e_cap(''ecap-a2'',explicit_input).');
  end
  if exist('OCTAVE_VERSION','builtin')~=0
    error('i32e:MATLABRequired','This experiment requires MATLAB.');
  end
  input_path=char(input_path);
  here=fileparts(mfilename('fullpath'));
  output=fullfile(here,'output',char(attempt));
  if exist(output,'file')||exist(output,'dir')
    error('i32e:OutputExists','Output already exists: %s.',output);
  end
  staged_original=LOCAL_load_input(input_path);
  c=LOCAL_config();
  timer=tic; result=LOCAL_empty_result(char(attempt),c,staged_original);
  original_staged_mib=LOCAL_mib({staged_original});
  peak_mib=original_staged_mib;
  converted_staged_mib=NaN; conversion_ledger_mib=NaN;
  normalization_peak_mib=NaN;
  evaluation_helper_peak_mib=0; cap_helper_peak_mib=0;
  retained_before_evaluation_mib=NaN; retained_after_evaluation_mib=NaN;
  retained_before_cap_mib=NaN; retained_after_cap_mib=NaN;
  try
    % --- stage 1: storage normalization, identity, and resource preflight ---
    [staged,storage_conversion]=LOCAL_normalize_integer_storage(staged_original);
    converted_staged_mib=LOCAL_mib({staged});
    conversion_ledger_mib=LOCAL_mib({storage_conversion});
    normalization_peak_mib=original_staged_mib+converted_staged_mib+ ...
      conversion_ledger_mib;
    peak_mib=max(peak_mib,normalization_peak_mib);
    clear staged_original;
    result.input_storage_conversion=storage_conversion;
    LOCAL_input_gate(staged,c);
    identity=LOCAL_identity(staged,c); result.identity=identity;
    result.certificate_summary=identity;
    result.call_counters=LOCAL_zero_counters();
    preflight=LOCAL_preflight(c,staged,storage_conversion, ...
      original_staged_mib,normalization_peak_mib);
    result.resource_preflight=preflight;
    result.resources.preflight=preflight;
    if isfield(identity,'branch_and_Wood')&& ...
        isfield(identity.branch_and_Wood,'pass')&& ...
        ~identity.branch_and_Wood.pass
      error('i32e:BranchUnavailable', ...
        'The frozen branch/Wood identity is unavailable.');
    end
    if ~identity.pass
      error('i32e:CertificateIdentity','The staged certificate identity failed.');
    end
    if ~preflight.pass
      error('i32e:ResourcePreflight','The frozen resource preflight refused execution.');
    end
    LOCAL_resource_gate(timer,peak_mib,c);

    % --- stage 2: fixed-density harmonic-image and cross actions ---
    evaluation=i32_same_eval(c,staged.certificate,staged.raw_maps,timer);
    result.evaluation=evaluation.public;
    result.audit.evaluation=evaluation.audit;
    result.call_counters=LOCAL_add_counters(result.call_counters, ...
      evaluation.call_counters);
    result.nonblocking_warnings=[result.nonblocking_warnings, ...
      evaluation.warnings];
    retained_before_evaluation_mib=LOCAL_mib({staged})+conversion_ledger_mib;
    retained_after_evaluation_mib=LOCAL_mib({staged,evaluation})+ ...
      conversion_ledger_mib;
    evaluation_helper_peak_mib=evaluation.record.peak_local_workspace_mib;
    evaluation_transient_mib=max( ...
      c.worst_transient_mib,evaluation_helper_peak_mib);
    peak_mib=max([peak_mib,retained_after_evaluation_mib, ...
      retained_before_evaluation_mib+evaluation_transient_mib]);
    LOCAL_resource_gate(timer,peak_mib,c);

    % --- stage 3: canonical factors, empirical caps, and nominal transform ---
    if evaluation.core_available
      LOCAL_soft_gate(timer,c,'cap and full-P contractions');
      cap=i32_cap_tail(c,staged,evaluation,timer);
    else
      cap=LOCAL_unstarted_cap();
    end
    result.components=cap.components;
    result.caps=cap.caps;
    result.estimator=cap.estimator;
    result.tails=cap.tails;
    result.axis_metrics=cap.axis_metrics;
    result.unresolved_axes=cap.unresolved_axes;
    result.arithmetic=cap.arithmetic;
    result.audit.cap=cap.audit;
    result.call_counters=LOCAL_add_counters(result.call_counters, ...
      cap.call_counters);
    result.nonblocking_warnings=[result.nonblocking_warnings,cap.warnings];
    retained_before_cap_mib=LOCAL_mib({staged,evaluation})+conversion_ledger_mib;
    retained_after_cap_mib=LOCAL_mib({staged,evaluation,cap})+ ...
      conversion_ledger_mib;
    cap_helper_peak_mib=cap.peak_local_workspace_mib;
    cap_transient_mib=max(c.worst_transient_mib,cap_helper_peak_mib);
    peak_mib=max([peak_mib,retained_after_cap_mib, ...
      retained_before_cap_mib+cap_transient_mib]);
    LOCAL_resource_gate(timer,peak_mib,c);

    result.coverage.fixed_certificate_consumed=true;
    result.coverage.same_density_actions_computed=evaluation.core_available;
    result.coverage.actual_DeltaT_actions_computed= ...
      isfield(evaluation.circle,'actual_T_action')&& ...
      evaluation.circle.actual_T_action.available;
    result.coverage.finite_image_Bloch_actions_computed= ...
      isfield(evaluation.circle,'finite_image_bloch')&& ...
      evaluation.circle.finite_image_bloch.available;
    result.coverage.all_fresh_computed_modes_included=cap.all_modes_included;
    result.coverage.empirical_numerator_cap_computed=cap.numerator_available;
    result.coverage.empirical_denominator_cap_computed=cap.denominator_available;
    result.coverage.nominal_transform_computed=cap.estimator.interval_available;
    result.coverage.mathematical_trial_redefined=false;
    result.coverage.continuous_error_enclosed=false;
    result.coverage.uncomputed_fourier_tail_enclosed=false;
    result.coverage.uncomputed_image_tail_enclosed=false;
    result.coverage.independent_reference=false;

    if ~LOCAL_all_zero(result.call_counters)
      result.status='I3_2_CERTIFICATE_IDENTITY_MISMATCH';
      result.scientific_outcome='CERTIFICATE_IDENTITY_MISMATCH';
      result.first_empirical_unavailable=LOCAL_condition( ...
        'CERTIFICATE_IDENTITY_MISMATCH', ...
        'At least one forbidden solve/build counter is nonzero.');
    elseif ~evaluation.core_available&&any(strcmp(evaluation.first_unavailable_code, ...
        {'i32e:BranchUnavailable','i32e:ExactWood'}))
      result.status='I3_2_BRANCH_OR_WOOD_UNAVAILABLE';
      result.scientific_outcome='BRANCH_OR_WOOD_UNAVAILABLE';
      result.first_empirical_unavailable=LOCAL_condition( ...
        evaluation.first_unavailable_code,evaluation.first_unavailable_message);
    elseif ~evaluation.core_available
      result.status='I3_2_EVALUATION_UNAVAILABLE';
      result.scientific_outcome='SAME_TRIAL_EVALUATION_UNAVAILABLE';
      result.first_empirical_unavailable=LOCAL_condition( ...
        evaluation.first_unavailable_code,evaluation.first_unavailable_message);
    elseif ~cap.numerator_available
      result.status='I3_2_EMPIRICAL_CAP_UNRESOLVED';
      result.scientific_outcome='EMPIRICAL_CAP_UNRESOLVED';
      result.first_empirical_unavailable=cap.first_unavailable;
    elseif ~cap.denominator_available
      result.status='I3_2_FIELD_PARTIAL_EMPIRICALLY_UNRESOLVED';
      result.scientific_outcome='FIELD_PARTIAL_EMPIRICALLY_UNRESOLVED';
      result.first_empirical_unavailable=cap.first_unavailable;
    elseif cap.estimator.q_emp>=1
      result.status='I3_2_EMPIRICAL_NOMINAL_INTERVAL_UNAVAILABLE';
      result.scientific_outcome='EMPIRICAL_NOMINAL_INTERVAL_UNAVAILABLE';
      result.first_empirical_unavailable=LOCAL_condition('NONE', ...
        'The empirical evaluation cap is available.');
    elseif cap.estimator.width>c.width_target
      result.status='I3_2_EMPIRICAL_RESOLUTION_INSUFFICIENT';
      result.scientific_outcome='EMPIRICAL_RESOLUTION_INSUFFICIENT';
      result.first_empirical_unavailable=LOCAL_condition('NONE', ...
        'The empirical evaluation cap is available.');
    else
      result.status='I3_2_EMPIRICAL_NOMINAL_TRANSFORM';
      result.scientific_outcome='EMPIRICAL_NOMINAL_TRANSFORM';
      result.first_empirical_unavailable=LOCAL_condition('NONE', ...
        'The empirical evaluation cap is available.');
    end
    if cap.numerator_available&&cap.denominator_available
      result.cap_status='EMPIRICALLY_SUPPORTED_EVALUATION_CAP';
    else
      result.cap_status='EMPIRICAL_CAP_UNRESOLVED';
    end
    result.first_nonblocking_warning=LOCAL_first_warning( ...
      result.nonblocking_warnings);
    result.no_resolve_call_counts=result.call_counters;
    result.execution_pass=true;
  catch ME
    result=LOCAL_execution_fail(result,ME);
  end

  result.elapsed_seconds=toc(timer);
  result.peak_active_mib=peak_mib;
  result.soft_time_exceeded=result.elapsed_seconds>c.soft_seconds;
  if result.elapsed_seconds>c.hard_seconds||peak_mib>c.memory_mib_max
    result.execution_pass=false;
    result.status='I3_2_RESOURCE_BUDGET_UNAVAILABLE';
    result.scientific_outcome='RESOURCE_BUDGET_UNAVAILABLE';
    result.first_execution_blocker=LOCAL_condition( ...
      'RESOURCE_LIMIT_EXCEEDED', ...
      'The hard time or active-object memory budget was exceeded.');
  end
  result.reliability=LOCAL_reliability_flags();
  result.qualification=LOCAL_qualification(result);
  result.resources.actual=struct('elapsed_seconds',result.elapsed_seconds, ...
    'peak_active_mib',peak_mib,'soft_time_exceeded', ...
    result.elapsed_seconds>c.soft_seconds,'hard_limits_respected', ...
    result.elapsed_seconds<=c.hard_seconds&&peak_mib<=c.memory_mib_max, ...
    'peak_accounting', ...
      ['max(retained-after-stage, retained-before-stage + ', ...
      'max(frozen transient, measured helper-local peak))'], ...
    'frozen_transient_mib',c.worst_transient_mib, ...
    'original_integer_storage_staged_mib',original_staged_mib, ...
    'double_expanded_staged_mib',converted_staged_mib, ...
    'conversion_ledger_mib',conversion_ledger_mib, ...
    'normalization_peak_mib',normalization_peak_mib, ...
    'evaluation_helper_peak_mib',evaluation_helper_peak_mib, ...
    'cap_helper_peak_mib',cap_helper_peak_mib, ...
    'retained_before_evaluation_mib',retained_before_evaluation_mib, ...
    'retained_after_evaluation_mib',retained_after_evaluation_mib, ...
    'retained_before_cap_mib',retained_before_cap_mib, ...
    'retained_after_cap_mib',retained_after_cap_mib, ...
    'helper_peak_combined_by_max_not_sum_with_frozen_transient',true, ...
    'helper_local_peak_added_to_returned_object',false);
  if exist(output,'file')||exist(output,'dir')
    error('i32e:OutputExists','Output appeared during the run: %s.',output);
  end
  mkdir(output);
  save(fullfile(output,'result.mat'),'result','-v7.3');
  LOCAL_report(fullfile(output,'report.md'),result);
end

