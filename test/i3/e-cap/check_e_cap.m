function result=LOCAL_execution_fail(result,ME)
  result.execution_pass=false;
  switch ME.identifier
    case {'i32e:CertificateIdentity','i32e:InputStorageClass', ...
        'i32e:InputStorageValue','i32e:InputStoragePath'}
      result.status='I3_2_CERTIFICATE_IDENTITY_MISMATCH';
      result.scientific_outcome='CERTIFICATE_IDENTITY_MISMATCH';
    case {'i32e:ExactWood','i32e:BranchUnavailable'}
      result.status='I3_2_BRANCH_OR_WOOD_UNAVAILABLE';
      result.scientific_outcome='BRANCH_OR_WOOD_UNAVAILABLE';
    case {'i32e:ResourcePreflight','i32e:Resource','i32e:HardTime','i32e:SoftTime'}
      result.status='I3_2_RESOURCE_BUDGET_UNAVAILABLE';
      result.scientific_outcome='RESOURCE_BUDGET_UNAVAILABLE';
    otherwise
      result.status='I3_2_EXECUTION_UNAVAILABLE';
      result.scientific_outcome='UNAVAILABLE';
  end
  result.first_execution_blocker=LOCAL_condition(ME.identifier,ME.message);
  result.exception=struct('identifier',ME.identifier,'message',ME.message, ...
    'stack',{ME.stack});
end

function out=LOCAL_condition(code,message)
  out=struct('code',char(code),'message',char(message));
end

function out=LOCAL_first_warning(warnings)
  if isempty(warnings)
    out=LOCAL_condition('NONE','No nonblocking warning was recorded.');
  else
    out=LOCAL_condition(warnings(1).code, ...
      sprintf('Nonblocking metric value %.17g.',warnings(1).value));
  end
end

function LOCAL_soft_gate(timer,c,next_stage)
  if toc(timer)>c.soft_seconds
    error('i32e:SoftTime', ...
      'The soft limit forbids starting %s.',next_stage);
  end
end

function LOCAL_resource_gate(timer,peak,c)
  if toc(timer)>c.hard_seconds||peak>c.memory_mib_max
    error('i32e:Resource','The hard time or memory budget was exceeded.');
  end
end

function value=LOCAL_mib(items)
  value=0;
  for j=1:numel(items)
    item=items{j}; info=whos('item'); value=value+info.bytes/2^20;
  end
end

%% ==================== Append-only report ====================
% The report distinguishes empirical evaluation support from reliability.

function LOCAL_report(path,r)
  if exist(path,'file')||exist(path,'dir')
    error('i32e:ReportExists','Refusing to overwrite an existing report.');
  end
  [fid,message]=fopen(path,'w');
  if fid<0
    error('i32e:ReportOpen','Could not create report: %s.',message);
  end
  cleanup=onCleanup(@() fclose(fid));
  fprintf(fid,'# I3.2 same-trial evaluation-cap report\n\n');
  fprintf(fid,'- Attempt: `%s`\n',r.attempt);
  fprintf(fid,'- Status: `%s`\n',r.status);
  fprintf(fid,'- Scientific outcome: `%s`\n',r.scientific_outcome);
  fprintf(fid,'- Cap status: `%s`\n',r.cap_status);
  fprintf(fid,'- Elapsed: %.17g s\n',r.elapsed_seconds);
  fprintf(fid,'- Peak active memory: %.17g MiB\n',r.peak_active_mib);
  if isfield(r,'resources')&&isfield(r.resources,'preflight')&& ...
      isfield(r.resources.preflight,'estimated_peak_mib')
    fprintf(fid,'- Preflight estimated time / peak: %.17g s / %.17g MiB\n', ...
      r.resources.preflight.estimated_seconds, ...
      r.resources.preflight.estimated_peak_mib);
  end
  if isfield(r,'resources')&&isfield(r.resources,'actual')&& ...
      isfield(r.resources.actual,'evaluation_helper_peak_mib')
    fprintf(fid,'- Measured evaluation / cap helper-local peaks: %.17g / %.17g MiB\n', ...
      r.resources.actual.evaluation_helper_peak_mib, ...
      r.resources.actual.cap_helper_peak_mib);
  end
  fprintf(fid,'- First execution blocker: `%s` -- %s\n', ...
    r.first_execution_blocker.code,r.first_execution_blocker.message);
  fprintf(fid,'- First empirical unavailable: `%s` -- %s\n', ...
    r.first_empirical_unavailable.code,r.first_empirical_unavailable.message);
  fprintf(fid,'- First warning: `%s` -- %s\n\n', ...
    r.first_nonblocking_warning.code,r.first_nonblocking_warning.message);
  if isfield(r,'certificate_summary')&&isfield(r.certificate_summary,'pass')
    fprintf(fid,'- Certificate identity pass: `%d`\n',r.certificate_summary.pass);
  end
  if isfield(r,'historical_diagnostics')&& ...
      isfield(r.historical_diagnostics,'circle_action_metric')
    h=r.historical_diagnostics.circle_action_metric;
    if isstruct(h)&&all(isfield(h,{'ratio','numerator','left_norm','right_norm'}))
      fprintf(fid,['- Historical fbie-a1 circle-action ratio / numerator / ', ...
        'side norms (background only): %.17g / %.17g / %.17g / %.17g\n'], ...
        h.ratio,h.numerator,h.left_norm,h.right_norm);
    else
      fprintf(fid,'- Historical fbie-a1 circle-action background unavailable.\n');
    end
  end
  if isfield(r,'qualification')
    fprintf(fid,['- Kernel / conformity / actual Delta-T / finite-image ', ...
      'Bloch / cap qualified: `%d` / `%d` / `%d` / `%d` / `%d`\n'], ...
      r.qualification.kernel_oracles_qualified, ...
      r.qualification.conformity_qualified, ...
      r.qualification.actual_DeltaT_action_qualified, ...
      r.qualification.finite_image_Bloch_qualified, ...
      r.qualification.empirical_cap_supported);
  end
  if isfield(r.evaluation,'circle')&& ...
      isfield(r.evaluation.circle,'actual_T_action')
    fprintf(fid,'- Actual fixed-density Delta-T maximum contraction ratio: %.17g\n', ...
      r.evaluation.circle.actual_T_action.maximum_contraction_ratio);
  end
  if isfield(r.evaluation,'circle')&& ...
      isfield(r.evaluation.circle,'finite_image_bloch')
    fprintf(fid,'- Finite-image physical Bloch final value/flux ratio: %.17g\n', ...
      r.evaluation.circle.finite_image_bloch.maximum_final_ratio);
  end
  if isfield(r,'unresolved_axes')&&~isempty(r.unresolved_axes)
    fprintf(fid,'- Unresolved axes: `%s`\n',strjoin(r.unresolved_axes,', '));
  else
    fprintf(fid,'- Unresolved axes: `NONE`\n');
  end
  fprintf(fid,'- Forbidden NO_RESOLVE call counters all zero: `%d`\n\n', ...
    LOCAL_all_zero(r.no_resolve_call_counts));
  fprintf(fid,['- Actual Delta-T actions / finite-image Bloch updates / ', ...
    'full-P contraction sequences: %.0f / %.0f / %.0f\n\n'], ...
    r.no_resolve_call_counts.actual_deltaT_action_calls, ...
    r.no_resolve_call_counts.finite_bloch_image_updates, ...
    r.no_resolve_call_counts.full_p_contraction_calls);
  fprintf(fid,'## Nonblocking warnings\n\n');
  if isempty(r.nonblocking_warnings)
    fprintf(fid,'- `NONE`\n\n');
  else
    for j=1:numel(r.nonblocking_warnings)
      fprintf(fid,'- `%s`: %.17g\n',r.nonblocking_warnings(j).code, ...
        r.nonblocking_warnings(j).value);
    end
    fprintf(fid,'\n');
  end
  if isfield(r,'caps')&&isfield(r.caps,'epsilon_M_emp')
    fprintf(fid,'## Ordinary centers and empirical evaluation caps\n\n');
    fprintf(fid,'- M tilde: %.17g\n',r.caps.M_tilde);
    fprintf(fid,'- N tilde: %.17g\n',r.caps.N_tilde);
    fprintf(fid,'- epsilon W/Gamma/V: %.17g / %.17g / %.17g\n', ...
      r.caps.epsilon_W_emp,r.caps.epsilon_Gamma_emp,r.caps.epsilon_V_emp);
    fprintf(fid,'- epsilon M: %.17g\n',r.caps.epsilon_M_emp);
    fprintf(fid,'- epsilon N: %.17g\n',r.caps.epsilon_N_emp);
  end
  if isfield(r,'estimator')&&isfield(r.estimator,'q_emp')
    fprintf(fid,'- q emp: %.17g\n',r.estimator.q_emp);
    fprintf(fid,'- Nominal k interval: [%.17g, %.17g]\n', ...
      r.estimator.k_lower,r.estimator.k_upper);
    fprintf(fid,'- Nominal width: %.17g\n',r.estimator.width);
  end
  fprintf(fid,'\n## Claim boundary\n\n');
  fprintf(fid,['This output is ordinary-double, same-chain, and empirical. ', ...
    'It is not a rigorous cap, reliable residual upper bound, certified ', ...
    'field lower bound, spectral enclosure, gap certificate, existence ', ...
    'result, independent reference, or effectivity validation.\n']);
  clear cleanup;
end
