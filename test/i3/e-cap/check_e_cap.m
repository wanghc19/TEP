  out=struct('components',struct(),'caps',struct(), ...
    'estimator',struct('interval_available',false),'tails',struct(), ...
    'axis_metrics',struct(),'unresolved_axes',{{'EVALUATION_UNAVAILABLE'}}, ...
    'arithmetic',struct(),'audit',struct(),'call_counters',LOCAL_zero_counters(), ...
    'warnings',struct('code',{},'value',{},'blocking',{}), ...
    'peak_local_workspace_mib',0,'all_modes_included',false, ...
    'numerator_available',false,'denominator_available',false, ...
    'first_unavailable',LOCAL_condition('SAME_TRIAL_EVALUATION_UNAVAILABLE', ...
      'Cap construction was not started because evaluation is unavailable.'));
end

%% ==================== Frozen runtime contract ====================
% These helpers validate the explicit input without reading repository state.

function staged=LOCAL_load_input(path)
  if ~isfile(path)
    error('i32e:InputMissing','The explicit staged input is unavailable.');
  end
  loaded=load(path,'staged');
  if ~isfield(loaded,'staged')||~isstruct(loaded.staged)
    error('i32e:InputSchema','The input does not contain staged.');
  end
  staged=loaded.staged;
end

function [staged,ledger]=LOCAL_normalize_integer_storage(staged)
  specs=LOCAL_integer_storage_contract();
  template=struct('path','','original_class','','original_size',[], ...
    'semantic_range',[],'original_scalar_value',NaN,'original_min',NaN, ...
    'original_max',NaN,'maximum_absolute_value',NaN, ...
    'within_flintmax',false,'exact_roundtrip',false, ...
    'converted_class','','downstream_arithmetic','','pass',false);
  ledger=repmat(template,numel(specs),1);
  for j=1:numel(specs)
    spec=specs(j); value=LOCAL_nested_value(staged,spec.path);
    if ~isinteger(value)||~strcmp(class(value),spec.original_class)|| ...
        ~isequal(size(value),spec.expected_size)
      error('i32e:InputStorageClass', ...
        'Integer storage class/size mismatch at %s.',spec.path);
    end
    converted=double(value); maximum=max(abs(converted),[],'all');
    within_flintmax=maximum<=flintmax;
    roundtrip=within_flintmax&& ...
      isequal(feval(spec.original_class,converted),value);
    range_pass=all(converted>=spec.minimum&converted<=spec.maximum,'all');
    if ~roundtrip||~range_pass
      error('i32e:InputStorageValue', ...
        'Integer storage value/range mismatch at %s.',spec.path);
    end
    scalar_value=NaN;
    if isscalar(converted), scalar_value=converted; end
    ledger(j)=struct('path',spec.path, ...
      'original_class',spec.original_class,'original_size',size(value), ...
      'semantic_range',[spec.minimum,spec.maximum], ...
      'original_scalar_value',scalar_value, ...
      'original_min',min(converted,[],'all'), ...
      'original_max',max(converted,[],'all'), ...
      'maximum_absolute_value',maximum, ...
      'within_flintmax',within_flintmax,'exact_roundtrip',roundtrip, ...
      'converted_class','double', ...
      'downstream_arithmetic',spec.downstream_arithmetic,'pass',true);
    staged=LOCAL_nested_assign(staged,spec.path,converted);
  end
end

